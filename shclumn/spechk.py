#!/usr/bin/env python3
"""The corrected form of the formula for H^.(spe(n)) and H^.(pe(n)).

Three checks, all exact, over Q, on the engine of spe.py:

  1) dim H^p(spe(n)) and dim H^p(pe(n))  -- the two are NOT isomorphic;

  2) the Hochschild-Serre relation that replaces the two wrong lines:
        pe(n) = spe(n) +> C.E,   E = diag(1_n, -1_n) the grading operator,
     E acts semisimply, H^.(C.E) = Lambda(xi_1) with xi_1 = the trace, so
        H^.(pe(n)) = Lambda(xi_1) (x) ( H^.(spe(n)) )_0,
     ( )_0 = the part of gl(V)-weight zero.  Numerically this reads
        dim H^p(pe(n)) = dim H^p(spe(n))_0 + dim H^{p-1}(spe(n))_0.
     H^.(spe(n))_0 is computed by running the spe(n) complex on the FULL
     torus of gl(V) (full_torus=True) instead of the torus of sl(V);

  3) spe(2): the printed answer C[x_1,y_2]/(x_1^2-y_2) gives 1,1,1,1,...,
     the computation gives 1,1,2,2,2,2,...  The generators are x_1 = [Pf]
     and y_2 = [det]; we test which products of them are dependent in H^4.

"""
import sys
from fractions import Fraction

import spe as S


def dims(n, special, degmax, full_torus):
    B = S.basis_pe(n, special)
    name = ("spe" if special else "pe") + "(%d)%s" % (n, "_0" if full_torus and special else "")
    return S.cohomology_of(B, name, n, degmax, show=(), full_torus=full_torus)


def cup_test(n, degmax, log):
    """spe(2): are x_1^4, x_1^2 y_2, y_2^2 independent in H^4?"""
    B, f = S.structure_constants(S.basis_pe(n, True), n)
    ce = S.CE(B, f)
    idx = {e["name"]: i for i, e in enumerate(B)}

    def gen(nm):
        return ce.gen_mono(idx[nm])

    # x_1 = [c12*], y_2 = [b11* b22* - b12*^2]  (Pfaffian and determinant, n=2)
    x1 = {gen("c12"): Fraction(1)}
    y2 = {}
    for m, c in ((ce.poly_mul({gen("b11"): Fraction(1)}, {gen("b22"): Fraction(1)}), 1),
                 (ce.poly_mul({gen("b12"): Fraction(1)}, {gen("b12"): Fraction(1)}), -1)):
        for k, v in m.items():
            y2[k] = y2.get(k, 0) + c * v
    y2 = {k: v for k, v in y2.items() if v}

    for nm, p in (("x1", x1), ("y2", y2)):
        assert not ce.Q(p), "%s is not a cocycle" % nm

    prods = {}
    prods["x1^4"] = ce.poly_mul(ce.poly_mul(x1, x1), ce.poly_mul(x1, x1))
    prods["x1^2*y2"] = ce.poly_mul(ce.poly_mul(x1, x1), y2)
    prods["y2^2"] = ce.poly_mul(y2, y2)

    # the degree-4 weight-0 cochains, and the image of d_3 in them
    m3 = ce.monomials(3, n, full_torus=False)
    m4 = ce.monomials(4, n, full_torus=False)
    pos = {m: i for i, m in enumerate(m4)}
    img = []
    for m in m3:
        q = ce.Q({m: Fraction(1)})
        img.append({pos[k]: v for k, v in q.items()})

    def vec(p):
        return {pos[k]: v for k, v in p.items()}

    rows = list(img)
    r0, _ = S.rank_and_kernel(rows, len(m4))
    log("   dim C^4 = %d, rank d_3 = %d" % (len(m4), r0))
    for nm in ("x1^4", "x1^2*y2", "y2^2"):
        assert not ce.Q(prods[nm]), "%s is not a cocycle" % nm
        r, _ = S.rank_and_kernel(rows + [vec(prods[nm])], len(m4))
        log("   %-9s: %s modulo coboundaries" % (nm, "ZERO" if r == r0 else "non-zero"))
    # are the three of them dependent modulo coboundaries?
    for k in (1, 2, 3):
        names = ("x1^4", "x1^2*y2", "y2^2")[:k]
        r, _ = S.rank_and_kernel(rows + [vec(prods[nm]) for nm in names], len(m4))
        log("   {%s}: %d independent classes in H^4" % (", ".join(names), r - r0))


def ring_test(n, degmax, hdims, log):
    """Is H^.(spe(2)) generated by x_1=[Pf] and y_2=[det], with the single
    relation x_1^2 y_2 = 0?  For each degree d we compute the rank of the set
    {x_1^a y_2^b : a+2b=d} modulo coboundaries and compare it with dim H^d."""
    B, f = S.structure_constants(S.basis_pe(n, True), n)
    ce = S.CE(B, f)
    idx = {e["name"]: i for i, e in enumerate(B)}
    x1 = {ce.gen_mono(idx["c12"]): Fraction(1)}
    y2 = {}
    for p, c in ((ce.poly_mul({ce.gen_mono(idx["b11"]): Fraction(1)},
                              {ce.gen_mono(idx["b22"]): Fraction(1)}), 1),
                 (ce.poly_mul({ce.gen_mono(idx["b12"]): Fraction(1)},
                              {ce.gen_mono(idx["b12"]): Fraction(1)}), -1)):
        for k, v in p.items():
            y2[k] = y2.get(k, 0) + c * v
    y2 = {k: v for k, v in y2.items() if v}

    def power(p, k):
        r = {((0,) * len(ce.ncom), ()): Fraction(1)}
        for _ in range(k):
            r = ce.poly_mul(r, p)
        return r

    for d in range(degmax + 1):
        md = ce.monomials(d, n, full_torus=False)
        pos = {m: i for i, m in enumerate(md)}
        img = []
        for m in ce.monomials(d - 1, n, full_torus=False) if d else []:
            q = ce.Q({m: Fraction(1)})
            img.append({pos[k]: v for k, v in q.items()})
        r0, _ = S.rank_and_kernel(img, len(md))
        rows = list(img)
        names = []
        for b in range(d // 2 + 1):
            a = d - 2 * b
            p = ce.poly_mul(power(x1, a), power(y2, b))
            if not p:
                continue
            assert not ce.Q(p), "not a cocycle"
            rows.append({pos[k]: v for k, v in p.items()})
            names.append("x1^%d*y2^%d" % (a, b))
        r, _ = S.rank_and_kernel(rows, len(md))
        log("   d=%d: dim H^d = %d, monomials {%s} span %d of them  %s"
            % (d, hdims[d], ", ".join(names), r - r0,
               "OK" if r - r0 == hdims[d] else "GAP"))


def spe4_top(log):
    """spe(4): do [Pf]^2 and [det] span H^4?  Pf on Lambda^2(V*) is the
    Pfaffian of (c_ij*), det on S^2(V) is the determinant of (b_ij*)."""
    from itertools import permutations
    n = 4
    B, f = S.structure_constants(S.basis_pe(n, True), n)
    ce = S.CE(B, f)
    idx = {e["name"]: i for i, e in enumerate(B)}

    def g(nm):
        return {ce.gen_mono(idx[nm]): Fraction(1)}

    def add(p, q, c=1):
        r = dict(p)
        for k, v in q.items():
            r[k] = r.get(k, 0) + c * v
        return {k: v for k, v in r.items() if v}

    def cname(i, j):
        return "c%d%d" % (i + 1, j + 1) if i < j else "c%d%d" % (j + 1, i + 1)

    pf = {}
    for (a, b, c, d), s in (((0, 1, 2, 3), 1), ((0, 2, 1, 3), -1), ((0, 3, 1, 2), 1)):
        pf = add(pf, ce.poly_mul(g(cname(a, b)), g(cname(c, d))), s)
    det = {}
    for perm in permutations(range(n)):
        sgn = 1
        arr = list(perm)
        for i in range(n):
            for j in range(i + 1, n):
                if arr[i] > arr[j]:
                    sgn = -sgn
        term = {((0,) * len(ce.ncom), ()): Fraction(1)}
        for i in range(n):
            j = perm[i]
            term = ce.poly_mul(term, g("b%d%d" % (min(i, j) + 1, max(i, j) + 1)))
        det = add(det, term, sgn)
    for nm, p in (("Pf", pf), ("det", det)):
        assert not ce.Q(p), "%s is not a cocycle on spe(4)" % nm
    pf2 = ce.poly_mul(pf, pf)
    m4 = ce.monomials(4, n, full_torus=False)
    pos = {m: i for i, m in enumerate(m4)}
    img = []
    for m in ce.monomials(3, n, full_torus=False):
        q = ce.Q({m: Fraction(1)})
        img.append({pos[k]: v for k, v in q.items()})
    r0, _ = S.rank_and_kernel(img, len(m4))
    r, _ = S.rank_and_kernel(img + [{pos[k]: v for k, v in pf2.items()},
                                    {pos[k]: v for k, v in det.items()}], len(m4))
    log("   dim C^4 = %d, rank d_3 = %d; [Pf]^2 and [det] span %d classes in H^4(spe(4))"
        % (len(m4), r0, r - r0))


def main():
    def log(s):
        print(s, flush=True)

    log("Cohomology of spe(n) and pe(n): the corrected form of formula (HofSPE). Exact, over Q.\n")
    table = {}
    for n, degmax in ((2, 6), (3, 5), (4, 4)):
        table[("spe", n)] = dims(n, True, degmax, False)
        print()
        table[("spe0", n)] = dims(n, True, degmax, True)
        print()
        table[("pe", n)] = dims(n, False, degmax, True)
        print()

    log("\n--- 2) Hochschild-Serre: dim H^p(pe) =?= dim H^p(spe)_0 + dim H^{p-1}(spe)_0")
    ok = True
    for n, degmax in ((2, 6), (3, 5), (4, 4)):
        for p in range(degmax + 1):
            lhs = table[("pe", n)][p]
            rhs = table[("spe0", n)][p] + (table[("spe0", n)][p - 1] if p else 0)
            flag = "OK" if lhs == rhs else "MISMATCH"
            if lhs != rhs:
                ok = False
            log("   n=%d p=%d: dim H^p(pe)=%d, predicted %d  %s" % (n, p, lhs, rhs, flag))
    log("   verdict: %s" % ("the relation holds in every degree computed" if ok else "FAILS"))

    log("\n--- 3) the ring H^.(spe(2)): products of x_1=[Pf] and y_2=[det] in H^4")
    cup_test(2, 4, log)

    log("\n--- 3a) do the monomials x_1^a y_2^b span H^d(spe(2)) for d <= 6?")
    ring_test(2, 6, table[("spe", 2)], log)

    log("\n--- 4) spe(4): do [Pf]^2 and [det] span H^4?  (dim H^4(spe(4)) = %d)"
        % table[("spe", 4)][4])
    spe4_top(log)



if __name__ == "__main__":
    main()
