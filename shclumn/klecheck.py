#!/usr/bin/env python3
"""Sanity checks on the kle(9|6;K) model: Jacobi, transitivity, generation,
the sl(5)-structure of g_0 and the congruence deg = 2*(weight sum) mod 5."""
import sys
from fractions import Fraction
import kle

import os, sys; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
from exactlin import rank                                             # noqa: E402

DEG = list(range(-2, 5))
B = {d: kle.comp(d) for d in DEG}
print('dims', {d: len(B[d]) for d in DEG})


def br(x, y):
    return kle.bracket(x, y)


def sub(a, b):
    out = dict(a)
    for k, v in b.items():
        kle._add(out, k, -v)
    return kle._clean(out)


def add(a, b):
    out = dict(a)
    for k, v in b.items():
        kle._add(out, k, v)
    return kle._clean(out)


def smul(c, a):
    return kle._clean({k: c * v for k, v in a.items()})


# --- 1. super Jacobi on all triples of basis vectors of low degree
bad = 0
tot = 0
for d0 in (-2, -1, 0, 1):
    for d1 in (-2, -1, 0, 1):
        for d2 in (-2, -1, 0, 1):
            for x in B[d0]:
                for y in B[d1]:
                    for z in B[d2]:
                        p0, p1 = kle.par(x), kle.par(y)
                        lhs = br(x, br(y, z))
                        r1 = br(br(x, y), z)
                        r2 = smul(Fraction(-1 if (p0 * p1) % 2 else 1), br(y, br(x, z)))
                        tot += 1
                        if sub(lhs, add(r1, r2)):
                            bad += 1
print('Jacobi: %d triples, %d failures' % (tot, bad))

# --- 2. the grading: [g_i,g_j] lands in g_{i+j}
gradok = True
for i in DEG:
    for j in DEG:
        if i + j not in B:
            continue
        for x in B[i]:
            for y in B[j]:
                v = br(x, y)
                if not v:
                    continue
                if kle.comp(i + j) == [] and v:
                    gradok = False
print('grading consistent:', gradok)

# --- 3. transitivity: x in g_k (k >= 0) with [g_{-1},x]=0 implies x=0
for k in (0, 1, 2, 3, 4):
    rows = []
    for x in B[k]:
        row = []
        for t in B[-1]:
            v = br(t, x)
            row.extend(kle_coords(v, k - 1) if False else [])
        rows.append(row)
    # do it properly with coordinates
    import itertools
    tgt = B[k - 1]
    keys = sorted({kk for D in tgt for kk in D}, key=repr)
    pos = {kk: t for t, kk in enumerate(keys)}
    rows = []
    for x in B[k]:
        row = [Fraction(0)] * (len(B[-1]) * len(keys))
        for a, t in enumerate(B[-1]):
            v = br(t, x)
            for kk, c in v.items():
                row[a * len(keys) + pos[kk]] = c
        rows.append(row)
    r = rank(rows)
    print('transitivity in degree %d: rank %d of dim %d -> %s'
          % (k, r, len(B[k]), 'ok' if r == len(B[k]) else 'FAILS'))

# --- 4. g_- generated by g_{-1}
keys = sorted({kk for D in B[-2] for kk in D}, key=repr)
pos = {kk: t for t, kk in enumerate(keys)}
rows = []
for a in B[-1]:
    for b in B[-1]:
        v = br(a, b)
        row = [Fraction(0)] * len(keys)
        for kk, c in v.items():
            row[pos[kk]] = c
        if any(row):
            rows.append(row)
print('[g_-1,g_-1] = g_-2 :', rank(rows), 'of', len(B[-2]))

# --- 5. deg = 2 * (sum of the weight) mod 5
ok = True
for d in DEG + [5, 6]:
    for x in kle.comp(d):
        w = kle.wt(x)
        s = sum(w)
        if (d - 2 * s) % 5:
            ok = False
            print('  FAILS at degree', d, w)
            break
print('deg == 2*sum(weight) (mod 5):', ok)

# --- 6. weight-0 subspaces of each component
for d in DEG + [5, 6]:
    z = sum(1 for x in kle.comp(d) if kle.wt(x) == (0, 0, 0, 0))
    print('  dim (g_%d)_{weight 0} = %d of %d' % (d, z, len(kle.comp(d))))
