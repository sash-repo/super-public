#!/usr/bin/env python3
"""casmax.py, the case of components defined over a number field K only.
A = End_{u_ev}(g/u) is commutative (multiplicity-free); a generic a in A has an
irreducible factor f of degree > 1 in its minimal polynomial.  Pick a prime p at
which f has a simple root r; the eigenspace W_p of a mod p for r has the
dimension of a C-component W (checked), i.e., W_p is the reduction of W at
a prime of K over p.  If the subalgebra generated by u and W_p is everything over
F_p, then the same bracket words span everything over K: maximality follows."""
import sys, os, pickle, random
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(HERE, "..", "lib"), HERE]
import exc3, sympy
from sweep3 import Ech, sdim_of
from exactlin import nullspace

def run(g, ub, PR=(10007, 10009, 10037, 10039, 10061, 10067, 10069, 10079)):
    E = Ech(g.N, ub)
    piv = set(E.piv); comp = [i for i in range(g.N) if i not in piv]; d = len(comp)
    ue = Ech(g.N, [[x if g.PAR[i] == 0 else F(0) for i, x in enumerate(v)] for v in E.basis()]).basis()
    def rho(x):
        M = [[F(0)] * d for _ in range(d)]
        for j, i in enumerate(comp):
            ei = [F(0)] * g.N; ei[i] = F(1)
            r = E.reduce(g.br(x, ei))
            for k, c in enumerate(comp): M[k][j] = r[c]
        return M
    rows = []
    for M in (rho(x) for x in ue):
        for a in range(d):
            for b in range(d):
                row = [F(0)] * (d * d)
                for k in range(d):
                    if M[k][b]: row[a * d + k] += M[k][b]
                    if M[a][k]: row[k * d + b] -= M[a][k]
                if any(row): rows.append(row)
    A = nullspace(rows)
    mats = [sympy.Matrix(d, d, [sympy.Rational(x.numerator, x.denominator) for x in v]) for v in A]
    assert all((X * Y - Y * X).is_zero_matrix for X in mats for Y in mats)
    random.seed(1)
    a = sum((random.randint(1, 97) * X for X in mats), sympy.zeros(d, d))
    t = sympy.Symbol("t")
    mp = sympy.factor_list(a.charpoly(t).as_expr())
    out = []
    for f, mult in mp[1]:
        deg = sympy.degree(f, t)
        dimC = (d - (a - 0 * sympy.eye(d)).rank()) if False else None
        # dimension of one C-component: dim ker f(a) / deg f
        fa = sympy.zeros(d, d); 
        for k, c in enumerate(reversed(sympy.Poly(f, t).all_coeffs())):
            fa += c * a ** k
        kdim = d - fa.rank()
        comp_dim = kdim // deg
        for p in PR:
            fp = sympy.Poly(f, t, modulus=p)
            roots = [r for r in range(p) if fp.eval(r) % p == 0] if deg <= 2 else None
            if roots is None:
                roots = [r for r in range(p) if fp.eval(r) % p == 0]
            if not roots: continue
            r = roots[0]
            Mp = sympy.Matrix(d, d, lambda i, j: (int(sympy.Rational(a[i, j]).p) * pow(int(sympy.Rational(a[i, j]).q), -1, p)) % p)
            Mp = Mp - r * sympy.eye(d)
            ns = nullspace([[int(Mp[i, j]) % p for j in range(d)] for i in range(d)], p)
            if len(ns) != comp_dim: continue
            # closure mod p of u + W_p
            def lift(v):
                w = [0] * g.N
                for kk, c in enumerate(comp): w[c] = int(v[kk]) % p
                return w
            gens = [[int(x.numerator) * pow(int(x.denominator), -1, p) % p for x in v] for v in E.basis()] + [lift(v) for v in ns]
            dimp = closure_modp(g, gens, p)
            out.append((deg, comp_dim, p, dimp))
            break
        else:
            out.append((deg, comp_dim, None, None))
    return out

def closure_modp(g, gens, p):
    piv = {}
    def red(v):
        w = [x % p for x in v]
        for c in sorted(piv):
            if w[c]:
                f = w[c]; r = piv[c]
                w = [(x - f * y) % p for x, y in zip(w, r)]
        return w
    def add(v):
        w = red(v)
        for c in range(g.N):
            if w[c]:
                inv = pow(w[c], -1, p); piv[c] = [x * inv % p for x in w]; return True
        return False
    items = [v for v in gens if add(v)]
    def br(x, y):
        X = [F(c) for c in x]; Y = [F(c) for c in y]
        z = g.br(X, Y)
        return [int(c.numerator) * pow(int(c.denominator), -1, p) % p if c else 0 for c in z]
    i = 0
    while i < len(items):
        for j in range(len(items)):
            v = br(items[i], items[j])
            if any(v) and add(v): items.append(v)
        i += 1
    return len(piv)

