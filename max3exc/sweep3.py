#!/usr/bin/env python3
"""Maximal graded subalgebras of ag(2)=G(3) and ab(3)=F(4): the five cases of
the Leites--Shchepochkina method (plus the sixth one) for every Z-grading of the census.

For a grading given by h (in the coordinates of gradings3exc.py) we run
  4o  u = g_{<=0},   5o  u = g_{>=0},   6o  u_{-1}=0 != u_-  (and u = g_ev),
  2o  u_{-1} = V,  0 != V != g_{-1},  u_0 = st(V),  u_k = prolong,
  3o  u_{-1} = g_{-1},  u_0 = st(V) subsetneq g_0,  u_k = prolong,
V running over (i) all subspaces spanned by weight vectors of g_{-1} -- i.e.
all torus-invariant ones -- (ii) all lines and planes spanned by sums of two
weight vectors (the isotropic/non-isotropic distinction lives here), and
(iii) random subspaces of every dimension.

MAXIMALITY CERTIFICATE.  If u contains a torus t' then u and every subalgebra
w with u subset w subset g are t'-invariant, hence sums of t'-weight spaces.
So if every t'-weight space of g/u is 1-dimensional, it suffices to check, for
one representative x of each such line, that the subalgebra generated by u and
x is g: then u is a maximal subalgebra of g -- not merely a maximal *graded*
one.  When some t'-weight space of g/u has dimension > 1 the check is run on
its basis vectors and on random vectors only, and the answer is flagged (b).
"""
import sys, random
from fractions import Fraction as F
from itertools import combinations, product
from lin import kernel, rref

random.seed(20260803)


# --------------------------------------------------------------- fast echelon
class Ech:
    """row-echelon basis of a subspace of Q^N, with O(dim*N) insert/contains."""

    def __init__(self, N, vecs=()):
        self.N = N
        self.piv = {}          # pivot column -> reduced row
        for v in vecs:
            self.add(v)

    def reduce(self, v):
        w = list(v)
        for c in sorted(self.piv):
            if w[c]:
                f = w[c]
                r = self.piv[c]
                for i in range(c, self.N):
                    if r[i]:
                        w[i] -= f * r[i]
        return w

    def add(self, v):
        w = self.reduce(v)
        for c in range(self.N):
            if w[c]:
                inv = F(1) / w[c]
                self.piv[c] = [x * inv for x in w]
                return True
        return False

    def contains(self, v):
        return not any(self.reduce(v))

    def dim(self):
        return len(self.piv)

    def basis(self):
        return [self.piv[c] for c in sorted(self.piv)]


def ev(g, i):
    return g.e(i)


def sdim_of(g, vecs):
    """superdimension of a span; the span is split by parity first."""
    Nev = [i for i in range(g.N) if g.PAR[i] == 0]
    Nod = [i for i in range(g.N) if g.PAR[i] == 1]
    b = Ech(g.N, vecs)
    # a subalgebra of ours is always parity-homogeneous; project on both parts
    e1 = Ech(g.N, [[x if g.PAR[i] == 0 else F(0) for i, x in enumerate(v)]
                   for v in b.basis()])
    e2 = Ech(g.N, [[x if g.PAR[i] == 1 else F(0) for i, x in enumerate(v)]
                   for v in b.basis()])
    if e1.dim() + e2.dim() != b.dim():
        return None            # not parity-homogeneous
    return (e1.dim(), e2.dim())


def closure(g, gens):
    """subalgebra generated by gens."""
    E = Ech(g.N)
    items = []
    for v in gens:
        if E.add(v):
            items.append(list(v))
    i = 0
    while i < len(items):
        for j in range(len(items)):
            v = g.br(items[i], items[j])
            if any(v) and E.add(v):
                items.append(v)
        i += 1
    return E


def module_closure(g, ub, x):
    """the u-submodule of g generated by x, u = span(ub) (cheaper than the
       subalgebra generated by u and x, and contained in it together with u)."""
    E = Ech(g.N, list(ub) + [x])
    items = [list(x)]
    i = 0
    while i < len(items):
        for y in ub:
            v = g.br(y, items[i])
            if any(v) and E.add(v):
                items.append(v)
        i += 1
    return E


def subspace_stab(g, dom, pieces):
    """{x in span(dom) : [x, W] subset W for every (W) in pieces}."""
    conds = []
    for W in pieces:
        WE = Ech(g.N, W)
        Wb = WE.basis()
        for y in Wb:
            # [x,y] must lie in W: reduce it modulo W and require 0.
            # reduction is linear in x, so one bracket per (x,y) suffices
            red = [WE.reduce(g.br(x, y)) for x in dom]
            for t in range(g.N):
                row = [red[k][t] for k in range(len(dom))]
                if any(row):
                    conds.append(row)
    if not conds:
        return list(dom)
    out = []
    for co in kernel(conds, len(dom)):
        v = [F(0)] * g.N
        for cf, x in zip(co, dom):
            if cf:
                v = [p + cf * q for p, q in zip(v, x)]
        out.append(v)
    return Ech(g.N, out).basis()


# ------------------------------------------------------------------- gradings
class Grading:
    def __init__(self, g, h):
        self.g = g
        self.h = [F(x) for x in h]
        self.deg = []
        for i in range(g.N):
            d = sum(a * b for a, b in zip(g.WT[i], self.h))
            assert d.denominator == 1, ("non-integral grading", i, d)
            self.deg.append(int(d))
        self.comps = {}
        for i, d in enumerate(self.deg):
            self.comps.setdefault(d, []).append(i)
        self.depth = -min(self.comps)
        self.top = max(self.comps)

    def vecs(self, d):
        return [ev(self.g, i) for i in self.comps.get(d, [])]

    def shape(self):
        return "  ".join("g_%+d=%d|%d" % (d, *sdim_of(self.g, self.vecs(d)))
                         for d in sorted(self.comps))


def prolong(g, gr, neg, u0):
    """u_k for k>0 : {x in g_k : [x,u_j] subset u_{j+k} for all j<0}."""
    u = {k: Ech(g.N, v).basis() for k, v in neg.items() if v}
    for k in range(-gr.depth, 0):
        u.setdefault(k, [])
    u[0] = Ech(g.N, u0).basis()
    for k in range(1, gr.top + 1):
        cur = gr.vecs(k)
        if not cur:
            u[k] = []
            continue
        conds = []
        for j in range(-gr.depth, 0):
            tgt = u[0] if j + k == 0 else u.get(j + k, [])
            TE = Ech(g.N, tgt)
            for y in u[j]:
                red = [TE.reduce(g.br(x, y)) for x in cur]
                for t in range(g.N):
                    row = [red[m][t] for m in range(len(cur))]
                    if any(row):
                        conds.append(row)
        if conds:
            out = []
            for co in kernel(conds, len(cur)):
                v = [F(0)] * g.N
                for cf, x in zip(co, cur):
                    if cf:
                        v = [p + cf * q for p, q in zip(v, x)]
                out.append(v)
            u[k] = Ech(g.N, out).basis()
        else:
            u[k] = list(cur)
    return u


def flat(u):
    return [v for k in sorted(u) for v in u[k]]


def is_subalg(g, E):
    b = E.basis()
    return all(E.contains(g.br(x, y)) for x in b for y in b)


# -------------------------------------------------------------- maximality
def cartan(g):
    """the Cartan subalgebra: the weight-0 basis vectors."""
    return [ev(g, i) for i in range(g.N) if all(x == 0 for x in g.WT[i])]


def maximality(g, E, trials=40):
    """(verdict, witness) with verdict in
       'MAX' (rigorous), 'MAX(b)' (weight spaces of dim>1 only sampled),
       'not maximal'."""
    t = cartan(g)
    tin = [x for x in t if E.contains(x)]
    # t'-weights: restrict each weight to the subtorus spanned by tin
    hs = []
    for x in tin:
        # x is a combination of weight-0 basis vectors; the functional it
        # defines on the root lattice is alpha -> alpha(x); compute via ad
        hs.append(x)

    def wt_of(i):
        out = []
        for x in hs:
            v = g.br(x, ev(g, i))
            c = F(0)
            for k, val in enumerate(v):
                if val:
                    assert k == i, "ad(h) not diagonal"
                    c = val
            out.append(c)
        return tuple(out)

    groups = {}
    for i in range(g.N):
        groups.setdefault(wt_of(i), []).append(i)
    rigorous = True
    for wt, idx in sorted(groups.items()):
        outside = [ev(g, i) for i in idx if not E.contains(ev(g, i))]
        if not outside:
            continue
        # dimension of the quotient (weight space)/(weight space cap u)
        Wb = [ev(g, i) for i in idx]
        inside = Ech(g.N, [v for v in Wb if E.contains(v)])
        q = len(Wb) - inside.dim()
        tests = list(Wb)
        if q > 1:
            rigorous = False
            for _ in range(trials):
                v = [F(0)] * g.N
                for b in Wb:
                    cf = F(random.randint(-3, 3))
                    v = [p + cf * x for p, x in zip(v, b)]
                if any(v):
                    tests.append(v)
        for x in tests:
            if E.contains(x):
                continue
            # cheap sufficient test first: the u-MODULE generated by x is
            # contained in the subalgebra generated by u and x
            mod = module_closure(g, E.basis(), x)
            if mod.dim() == g.N:
                continue
            gen = closure(g, E.basis() + [x])
            if gen.dim() != g.N:
                return ("not maximal", gen)
    return ("MAX" if rigorous else "MAX(b)", None)


# --------------------------------------------------------------- descriptions
def derived(g, E):
    out = [E.dim()]
    cur = E.basis()
    for _ in range(5):
        nxt = Ech(g.N, [g.br(x, y) for x in cur for y in cur])
        out.append(nxt.dim())
        if nxt.dim() == len(cur) or nxt.dim() == 0:
            break
        cur = nxt.basis()
    return out


def centre_dim(g, E):
    b = E.basis()
    if not b:
        return 0
    conds = []
    for y in b:
        for t in range(g.N):
            conds.append([g.br(x, y)[t] for x in b])
    return len(kernel(conds, len(b)))


def describe(g, gr, tag, u, seen, results, test=True):
    fl = flat(u)
    E = Ech(g.N, fl)
    if E.dim() == 0 or E.dim() == g.N:
        return None
    if not is_subalg(g, E):
        return None
    key = tuple(tuple(r) for r in E.basis())
    if key in seen:
        seen[key][0].append(tag)
        return None
    sd = sdim_of(g, E.basis())
    if sd is None or any(sdim_of(g, u[k]) is None for k in u if u[k]):
        return None                      # not parity-homogeneous: not a candidate
    pieces = " ".join("%+d:%d|%d" % (k, *sdim_of(g, u[k]))
                      for k in sorted(u) if u[k])
    rec = [[tag], E, sd, pieces, None]
    seen[key] = rec
    results.append(rec)
    return rec


def run_grading(g, h, name, Vmode="full", verbose=True, dump=None):
    gr = Grading(g, h)
    print("\n" + "=" * 100)
    print("%s   h = (%s)   depth %d   %s"
          % (name, ", ".join(str(x) for x in gr.h), gr.depth, gr.shape()))
    print("=" * 100)
    seen, results = {}, []
    g0 = gr.vecs(0)
    negall = {k: gr.vecs(k) for k in range(-gr.depth, 0)}

    # 4o, 5o : the two opposite parabolics
    describe(g, gr, "4o u=g_{<=0}", {k: gr.vecs(k) for k in sorted(gr.comps)
                                     if k <= 0}, seen, results)
    describe(g, gr, "5o u=g_{>=0}", {k: gr.vecs(k) for k in sorted(gr.comps)
                                     if k >= 0}, seen, results)
    # g_even (Lemma 4.2 of the text)
    uev = {k: [ev(g, i) for i in gr.comps[k] if g.PAR[i] == 0]
           for k in sorted(gr.comps)}
    describe(g, gr, "g_ev", uev, seen, results)
    # 6o : u_{-1} = 0 but u_- != 0
    if gr.depth > 1:
        neg = {k: gr.vecs(k) for k in range(-gr.depth, -1)}
        neg[-1] = []
        st = subspace_stab(g, g0, [v for v in neg.values() if v])
        describe(g, gr, "6o u_{-1}=0", prolong(g, gr, neg, st), seen, results)

    # the sweep over V
    m1 = gr.comps[-1]
    wv = [ev(g, i) for i in m1]
    d1 = len(m1)
    Vs = []
    # (i) every torus-invariant V: spanned by a subset of the weight vectors
    for r in range(1, d1):
        for sub in combinations(range(d1), r):
            Vs.append(("hom" + "".join("%x" % s for s in sub),
                       [wv[s] for s in sub]))
    if Vmode != "hom":
        # (ii) all lines spanned by a sum of two weight vectors, and
        # (iii) the planes they span together with one weight vector
        mixed = []
        for a, b in combinations(range(d1), 2):
            if g.PAR[m1[a]] != g.PAR[m1[b]]:
                continue        # V must be a subSUPERspace
            for c in (F(1), F(-1)):
                mixed.append(("mix%x%x%s" % (a, b, "+" if c > 0 else "-"),
                              [p + c * q for p, q in zip(wv[a], wv[b])]))
        for tag, v in mixed:
            Vs.append((tag, [v]))
        for tag, v in mixed:
            for s in range(d1):
                Vs.append((tag + "&%x" % s, [v, wv[s]]))
        # (iv) random sub-superspaces of every superdimension (p|q)
        evs = [wv[s] for s in range(d1) if g.PAR[m1[s]] == 0]
        ods = [wv[s] for s in range(d1) if g.PAR[m1[s]] == 1]

        def rnd(src, r):
            out = []
            for _ in range(r):
                v = [F(0)] * g.N
                for b in src:
                    cf = F(random.randint(-3, 3))
                    v = [p + cf * x for p, x in zip(v, b)]
                out.append(v)
            return out
        for p in range(len(evs) + 1):
            for q in range(len(ods) + 1):
                if p + q == 0 or p + q == d1:
                    continue
                for _ in range(3):
                    vv = rnd(evs, p) + rnd(ods, q)
                    if Ech(g.N, vv).dim() == p + q:
                        Vs.append(("rand%d|%d" % (p, q), vv))

    nV = 0
    for tag, V in Vs:
        Vb = Ech(g.N, V)
        if Vb.dim() == 0 or Vb.dim() == len(m1):
            continue
        nV += 1
        # 2o : u_{-1} = V, u_- generated by V
        neg = {-1: Vb.basis()}
        for k in range(-2, -gr.depth - 1, -1):
            prev = neg[k + 1]
            gen = Ech(g.N, [g.br(x, y) for x in prev for y in neg[-1]])
            gen = [v for v in gen.basis()]
            neg[k] = gen
        st = subspace_stab(g, g0, [v for v in neg.values() if v])
        describe(g, gr, "2o V=%s[%d]" % (tag, Vb.dim()),
                 prolong(g, gr, neg, st), seen, results)
        # 3o : u_{-1} = g_{-1}, u_0 = st(V)
        st0 = subspace_stab(g, g0, [Vb.basis()])
        if len(st0) < len(g0):
            describe(g, gr, "3o V=%s" % tag,
                     prolong(g, gr, negall, st0), seen, results)
    print("   candidate V's swept: %d;  distinct graded subalgebras: %d"
          % (nV, len(results)))

    # keep only the inclusion-maximal candidates.  Pre-filter: u subset w
    # forces dim u < dim w and, component by component, sdim u_k <= sdim w_k.
    def profile(rec):
        out = {}
        for tok in rec[3].split():
            k, sd = tok.split(":")
            a, b = sd.split("|")
            out[int(k)] = (int(a), int(b))
        return out
    prof = [profile(r) for r in results]
    order = sorted(range(len(results)), key=lambda i: -results[i][1].dim())
    survivors = []
    for i in range(len(results)):
        r = results[i]
        big = False
        for j in order:
            if results[j][1].dim() <= r[1].dim():
                break                      # sorted: no larger candidate left
            if any(prof[i].get(k, (0, 0))[0] > prof[j].get(k, (0, 0))[0] or
                   prof[i].get(k, (0, 0))[1] > prof[j].get(k, (0, 0))[1]
                   for k in prof[i]):
                continue
            if all(results[j][1].contains(v) for v in r[1].basis()):
                big = True
                break
        if not big:
            survivors.append(r)
    print("   inclusion-maximal candidates: %d" % len(survivors))
    out = []
    for r in survivors:
        verdict, wit = maximality(g, r[1])
        r[4] = verdict
        if verdict.startswith("MAX"):
            out.append(r)
        elif verbose:
            print("   [not max] %-28s %2d|%-2d  %-30s -> inside %d|%d"
                  % (r[0][0], r[2][0], r[2][1], r[3],
                     *sdim_of(g, wit.basis())))
    # group the answers by their invariants (conjugate copies coincide)
    groups = {}
    for r in out:
        ds = tuple(derived(g, r[1]))
        z = centre_dim(g, r[1])
        key = (r[2], r[3], ds, z, r[4])
        groups.setdefault(key, []).append(r)
    print("\n   MAXIMAL GRADED SUBALGEBRAS (%d up to these invariants)"
          % len(groups))
    print("   %-9s %-32s %-22s %-5s %-7s %s"
          % ("sdim", "graded pieces", "derived series", "centre", "verdict",
             "how many V / a sample tag"))
    for key in sorted(groups, key=lambda k: (-k[0][0] - k[0][1], k[0])):
        sd, pieces, ds, z, verdict = key
        rs = groups[key]
        perfect = "PERFECT" if len(ds) >= 2 and ds[0] == ds[1] else ""
        tags = [t for r in rs for t in r[0]]
        print("   %-9s %-32s %-22s %-5d %-7s %3d  %s   %s"
              % ("%d|%d" % sd, pieces, str(ds), z, verdict, len(tags),
                 tags[0], perfect))
    if dump:
        import pickle
        with open(dump, "wb") as f:
            pickle.dump({"h": [str(x) for x in gr.h], "name": name,
                         "answers": [(r[0], [[str(x) for x in v]
                                             for v in r[1].basis()],
                                      r[2], r[3], r[4]) for r in out]}, f)
    return gr, out
