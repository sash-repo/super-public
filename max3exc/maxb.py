"""The answers marked max(b): settle maximality rigorously.
u is a graded answer from the sweep (pickled bases in runs/, written by run3.py).
Every intermediate w (u < w < g) is a u_ev-submodule, so w/u contains a
u_ev-highest weight vector x and w contains the subalgebra generated by u and x.
Step 1: t' = u cap h, its weights on g/u; positive root vectors of u_ev.
Step 2: HW_lambda = { x in (g/u)_lambda : [e_+, x] in u }.  If dim HW_lambda=1
        test x directly; if >1 the test is run for x = generic combination
        with symbolic parameters is replaced by: the set of x whose u-module
        is proper is the zero set of minors -- we report the dims first."""
