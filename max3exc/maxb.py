def load(which, run, sd, pieces):
    g = exc3.build_G3() if which == "G3" else exc3.build_F4()
    d = pickle.load(open(os.path.join(LM, "runs", run + ".pkl"), "rb"))
    for tags, basis, s, pc, _ in d["answers"]:
        if tuple(s) == sd and pc == pieces:
            return g, [[F(x) for x in v] for v in basis], tags
    raise KeyError

def analyse(g, ub, label):
    E = Ech(g.N, ub)
    print("==", label, "sdim", sdim_of(g, E.basis()))
    hs = [x for x in cartan(g) if E.contains(x)]
    # u cap h (the model's Cartan): span of weight-0 vectors in u
    H0 = [ev(g, i) for i in range(g.N) if all(x == 0 for x in g.WT[i])]
    # intersection of span(H0) with u
    rows = []
    hb = E.basis()
    # solve sum a_i H0_i - sum b_j u_j = 0
    M = [[H0[i][t] for i in range(len(H0))] + [-hb[j][t] for j in range(len(hb))] for t in range(g.N)]
    K = kernel(M, len(H0) + len(hb))
    tor = Ech(g.N, [[sum(k[i] * H0[i][t] for i in range(len(H0))) for t in range(g.N)] for k in K]).basis()
    print("   rank of u cap h:", len(tor))
    return E, tor

