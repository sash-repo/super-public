#!/usr/bin/env python3
"""Conjugation-free maximality test for a graded answer u of g = ag(2), ab(3).
A = End_{u_ev}(g/u) (commutant, exact linear algebra).  u_ev is semisimple, so
g/u is a completely reducible u_ev-module and dim A = sum m_i^2 over its
isotypic components; A is commutative iff all m_i = 1 (multiplicity-free).
Then the components are the eigenspaces of a generic a in A; every u_ev-stable
subspace of g/u is a sum of components, so u is maximal iff for EACH component
W the subalgebra generated by u + W is g.  No torus of the model is used, so
the test applies to every copy the sweep produced, aligned or random."""
import sys, os, pickle, glob, random
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(HERE, "..", "lib"), HERE]
import exc3
from sweep3 import Ech, closure, sdim_of
from exactlin import nullspace, backend
import sympy

def test(g, ub):
    E = Ech(g.N, ub)
    piv = set(E.piv)
    comp = [i for i in range(g.N) if i not in piv]          # complement basis e_i
    d = len(comp)
    ue = Ech(g.N, [[x if g.PAR[i] == 0 else F(0) for i, x in enumerate(v)] for v in E.basis()]).basis()
    if Ech(g.N, [g.br(x, y) for x in ue for y in ue]).dim() != len(ue):
        return "u_ev not perfect", None
    def rho(x):
        M = [[F(0)] * d for _ in range(d)]
        for j, i in enumerate(comp):
            ei = [F(0)] * g.N; ei[i] = F(1)
            r = E.reduce(g.br(x, ei))
            for k, c in enumerate(comp):
                M[k][j] = r[c]
        return M
    R = [rho(x) for x in ue]
    rows = []
    for M in R:
        for a in range(d):
            for b in range(d):
                row = [F(0)] * (d * d)
                # (XM - MX)[a][b] = sum_k X[a][k]M[k][b] - M[a][k]X[k][b]
                for k in range(d):
                    if M[k][b]: row[a * d + k] += M[k][b]
                    if M[a][k]: row[k * d + b] -= M[a][k]
                if any(row): rows.append(row)
    A = nullspace(rows)
    k = len(A)
    mats = [sympy.Matrix(d, d, [sympy.Rational(x.numerator, x.denominator) for x in v]) for v in A]
    comm = all((X * Y - Y * X).is_zero_matrix for X in mats for Y in mats)
    if not comm:
        return "not multiplicity-free (dim A = %d, noncommutative)" % k, None
    random.seed(1)
    a = sum((random.randint(1, 97) * X for X in mats), sympy.zeros(d, d))
    ev = a.eigenvects()
    if any(not val.is_rational for val, _, _ in ev):
        return "irrational components", None
    comps = []
    for val, mult, vecs in ev:
        W = []
        for v in vecs:
            w = [F(0)] * g.N
            for kk, c in enumerate(comp):
                q = sympy.Rational(v[kk]); w[c] = F(int(q.p), int(q.q))
            W.append(w)
        comps.append(W)
    assert len(comps) == k
    gens = [closure(g, E.basis() + W).dim() for W in comps]
    sd = [sdim_of(g, W) for W in comps]
    ok = all(x == g.N for x in gens)
    return ("MAX" if ok else "NOT MAXIMAL"), (k, [len(W) for W in comps], sd, gens)

if __name__ == "__main__":
    print("backend:", backend())
    want = {("G3", (6, 4)), ("G3", (7, 4)), ("G3", (11, 2)), ("F4", (9, 4)), ("F4", (17, 2))}
    summary = {}
    for f in sorted(glob.glob(os.path.join(HERE, "runs", "[GF]*.pkl"))):
        which = "G3" if "G3" in f else "F4"
        g = exc3.build_G3() if which == "G3" else exc3.build_F4()
        d = pickle.load(open(f, "rb"))
        for tags, basis, s, pc, verdict in d["answers"]:
            if (which, tuple(s)) not in want: continue
            ub = [[F(x) for x in v] for v in basis]
            v, info = test(g, ub)
            print(os.path.basename(f), s, pc, tags[0], "->", v, info, flush=True)
            summary.setdefault((which, tuple(s), pc), set()).add(v)
    print("\nSUMMARY")
    for k_, v in sorted(summary.items()): print(k_, v)
