#!/usr/bin/env python3
"""
orb.py -- T_2: THE ORBIT SEPARATOR.

T_1 (stab.py) delivers, for a normal form f, the layer

    Nt_f = m_odd / (m I_f)_odd

and the matrices rho(V), V running over a basis of the stabiliser algebra
s_f, of its action on Nt_f.  T_2 is the step that turns those matrices into a
LIST OF ORBITS with a proof attached to every entry of the list.  Two kinds of
proof are produced, and they are the two directions of the same question.

  (A) SAME ORBIT.  An explicit element of Stab_{Diff_0}(f) carrying v to w,
      written as a product of

          exp(t.M)          M in rho(s_f) nilpotent, t rational -- a finite
                            sum, so an exact matrix over Q;
          diag(t^{w_1},..)  the one-parameter subgroup of a semisimple
                            M in rho(s_f) with integer weights, t rational.

      Every factor lies in the group by construction, so the product is a
      certificate that can be checked by matrix multiplication alone, without
      redoing anything in this file.

  (B) DIFFERENT ORBITS.  One of three certificates, each a proof and not a
      sample:

      (B1) a rho(s_f)-STABLE SUBSPACE W with v in W and w not in W.  Stable
           subspaces are computed exactly, as the submodule generated by a
           vector, so membership is a rank computation;
      (B2) a SEMI-INVARIANT ratio P/Q (P,Q of the same weight) taking
           different values at v and w -- an honest rational invariant of the
           action, hence constant on orbits;
      (B3) different orbit DIMENSIONS, dim rho(s_f).v =/= dim rho(s_f).w.

The reduction behind (A) is the GRADED NORMALISATION of reduce_graded().  The
layer and the stabiliser are both graded, by the degree of the monomial and by
the degree of the vector field, and s_d carries Nt^(e) into Nt^(e+d).  Hence

  -- s_0 preserves each graded piece, so the class of the leading component of
     v under exp(s_0) is an invariant of the orbit;
  -- for s >= 1, exp(M) with M in s_s fixes everything below degree e_0+s and
     translates the component of degree e_0+s by M.v_{e_0}.

So the component of each degree above the leading one is killed modulo a
LINEAR subspace, by one exact reduction, and the sweep upwards is triangular:
no search at all above the leading term, and the leading term itself is a
problem in one graded piece, of small dimension.  When the sweep stalls,
orb.py says UNDECIDED rather than guessing; nothing here reports a conclusion
it has not certified.

Everything is exact arithmetic over Q.  Nothing is randomized except the
SEARCH for the certificates; the certificates themselves are then verified.
"""

from fractions import Fraction as F
from itertools import combinations
import random

import stab


# ------------------------------------------------------------ linear algebra

def mat_mul(A, B):
    n = len(A)
    return [[sum(A[i][l] * B[l][j] for l in range(n)) for j in range(n)]
            for i in range(n)]


def mat_id(n):
    return [[F(1) if i == j else F(0) for j in range(n)] for i in range(n)]


def mat_zero(M):
    return not any(any(x for x in row) for row in M)


def mat_comb(mats, coeffs):
    n = len(mats[0])
    out = [[F(0)] * n for _ in range(n)]
    for M, c in zip(mats, coeffs):
        if not c:
            continue
        for i in range(n):
            for j in range(n):
                if M[i][j]:
                    out[i][j] += c * M[i][j]
    return out


def is_nilpotent(M):
    n = len(M)
    P = [row[:] for row in M]
    for _ in range(n):
        if mat_zero(P):
            return True
        P = mat_mul(P, M)
    return mat_zero(P)


def exp_nilpotent(M, t):
    """exp(t.M) for nilpotent M -- a finite sum, exact over Q"""
    n = len(M)
    E = mat_id(n)
    T = mat_id(n)
    for step in range(1, n + 2):
        T = mat_mul(T, M)
        T = [[x * t / step for x in row] for row in T]
        if mat_zero(T):
            break
        E = [[E[i][j] + T[i][j] for j in range(n)] for i in range(n)]
    return E


def apply_mat(M, v):
    n = len(v)
    return [sum(M[i][j] * v[j] for j in range(n)) for i in range(n)]


def exp_apply(M, t, v):
    """
    exp(t.M).v for nilpotent M, by summing the series on the VECTOR.  Same
    result as apply_mat(exp_nilpotent(M,t), v), at a factor n less work -- and
    the reduction below tries far more steps than it accepts, so this is where
    the time goes.
    """
    out = v[:]
    term = v[:]
    n = len(v)
    for k in range(1, n + 2):
        term = apply_mat(M, term)
        if vec_zero(term):
            break
        term = [x * t / k for x in term]
        out = [out[i] + term[i] for i in range(n)]
    return out


def vec_zero(v):
    return not any(v)


def normalize_scale(v):
    """divide by the first nonzero entry; returns (scaled, scalar)"""
    for c in v:
        if c:
            return [x / c for x in v], c
    return v[:], F(1)


def top_index(v):
    for i in range(len(v) - 1, -1, -1):
        if v[i]:
            return i
    return -1


# --------------------------------------------------------- stable subspaces

class Span:
    """a subspace of Q^n in reduced row echelon form"""

    def __init__(self, n):
        self.n = n
        self.rows = {}                    # pivot column -> row

    def reduce(self, v):
        v = list(v)
        for p, r in sorted(self.rows.items()):
            if v[p]:
                c = v[p] / r[p]
                v = [v[i] - c * r[i] for i in range(self.n)]
        return v

    def add(self, v):
        v = self.reduce(v)
        p = next((i for i in range(self.n) if v[i]), None)
        if p is None:
            return False
        v = [x / v[p] for x in v]
        for q, r in self.rows.items():
            if r[p]:
                c = r[p]
                self.rows[q] = [r[i] - c * v[i] for i in range(self.n)]
        self.rows[p] = v
        return True

    def contains(self, v):
        return vec_zero(self.reduce(v))

    def dim(self):
        return len(self.rows)

    def basis(self):
        return [self.rows[p] for p in sorted(self.rows)]


def submodule(mats, v):
    """the smallest rho(s_f)-stable subspace containing v"""
    n = len(v)
    S = Span(n)
    S.add(v)
    frontier = [v]
    while frontier:
        nxt = []
        for w in frontier:
            for M in mats:
                u = apply_mat(M, w)
                if S.add(u):
                    nxt.append(u)
        frontier = nxt
    return S


def orbit_dim(mats, v):
    return stab.rank_rows([apply_mat(M, v) for M in mats])


# ---------------------------------------------------------- semi-invariants

def weight_of(M, S):
    """
    If the subspace S (a Span) is one-dimensional and M-stable, return the
    eigenvalue; else None.
    """
    if S.dim() != 1:
        return None
    b = S.basis()[0]
    w = apply_mat(M, b)
    lam = None
    for i in range(len(b)):
        if b[i]:
            lam = w[i] / b[i]
            break
    if lam is None:
        return None
    if any(w[i] != lam * b[i] for i in range(len(b))):
        return None
    return lam


def semi_invariants(mats, n, d):
    """
    Homogeneous polynomials P of degree d on the layer that are common
    eigenvectors of all the derivations D_M, i.e. D_M P = chi(M) P.  Returned
    as a list of (P, weights) with weights the tuple (chi(M))_M.

    Implemented by iterated eigenspace splitting: start with the full space of
    degree-d polynomials, and split it under each generator in turn, keeping
    only the eigenspaces with RATIONAL eigenvalue (the ones we can write down).
    When a split does not go through -- an irrational or complex weight, say --
    the answer returned is EMPTY rather than the unsplit space: this routine
    produces certificates, so it must not report a space it has not diagonalised
    as if every vector in it were a semi-invariant.
    """
    mons = stab.deg_monomials(n, d)
    pos = {a: i for i, a in enumerate(mons)}
    N = len(mons)
    if N == 0:
        return []

    # blocks: list of (basis of a subspace, weights so far)
    blocks = [([[F(1) if i == j else F(0) for j in range(N)]
                for i in range(N)], ())]

    certified = True
    for M in mats:
        cols = stab.derivation_matrix(M, mons, pos)
        # matrix of D_M in the monomial basis
        D = [[F(0)] * N for _ in range(N)]
        for j, col in enumerate(cols):
            for a, c in col.items():
                D[pos[a]][j] = c
        newblocks = []
        for basis, wts in blocks:
            if not basis:
                continue
            got, ok = _split(D, basis, wts)
            certified = certified and ok
            newblocks.extend(got)
        blocks = newblocks
        if not blocks:
            return []

    if not certified:
        # the eigenspace split did not go through -- report nothing rather
        # than report the whole space as if it were semi-invariant
        return []
    out = []
    for basis, wts in blocks:
        for b in basis:
            out.append(({mons[i]: c for i, c in enumerate(b) if c}, wts))
    return out


def _split(D, basis, wts):
    """
    Split the subspace spanned by `basis` (rows, coordinates in the ambient)
    into eigenspaces of D with rational eigenvalue.  Only eigenvalues that are
    roots of the characteristic polynomial found among the "obvious" rationals
    are used: we compute the matrix of D on the subspace and look for rational
    eigenvalues by solving (D - lam)v = 0 for lam among the diagonal-derived
    candidates.  For the actions occurring here the weights are integers, so
    the candidate set is the integers in a bounded range together with 0.
    """
    k = len(basis)
    N = len(basis[0])
    # coordinates of D(b) in terms of `basis`: solve by echelon
    S = Span(N)
    pivots = []
    for b in basis:
        S.add(b)
    # build the matrix of D restricted to the subspace, in the basis given
    # (solve D b_j = sum_i c_ij b_i by Gaussian elimination on the basis)
    aug = [row[:] for row in basis]
    piv = []
    used = []
    A = [row[:] for row in aug]
    for r in range(k):
        p = next((i for i in range(N) if A[r][i]), None)
        if p is None:
            continue
        piv.append((r, p))
    # naive coordinate extraction via least-squares-free elimination
    def coords(v):
        v = v[:]
        c = [F(0)] * k
        work = [row[:] for row in basis]
        for idx, (r, p) in enumerate(piv):
            if v[p]:
                f = v[p] / work[r][p]
                c[r] += f
                v = [v[i] - f * work[r][i] for i in range(N)]
        return (c, v)

    Dm = [[F(0)] * k for _ in range(k)]
    for j, b in enumerate(basis):
        img = apply_mat(D, b) if len(D) == N else None
        c, rest = coords(img)
        if not vec_zero(rest):
            return [(basis, wts)], False   # not closed: give up, and SAY so
        for i in range(k):
            Dm[i][j] = c[i]

    # rational eigenvalues: try the diagonal entries and small integers
    cands = set()
    for i in range(k):
        cands.add(Dm[i][i])
    for lam in list(cands):
        cands.add(lam)
    cands |= {F(z) for z in range(-8, 9)}

    out = []
    covered = 0
    for lam in sorted(cands):
        # kernel of (Dm - lam) -- generalized, to catch non-semisimple parts
        Mm = [[Dm[i][j] - (lam if i == j else 0) for j in range(k)]
              for i in range(k)]
        P = [row[:] for row in Mm]
        for _ in range(k):
            P = mat_mul(P, Mm)
        ker = _kernel(P, k)
        if not ker:
            continue
        vecs = []
        for c in ker:
            v = [F(0)] * N
            for i, ci in enumerate(c):
                if ci:
                    v = [v[t] + ci * basis[i][t] for t in range(N)]
            vecs.append(v)
        out.append((vecs, wts + (lam,)))
        covered += len(ker)
        if covered >= k:
            break
    return (out, True) if out else ([], False)


def _kernel(M, k):
    """basis of the kernel of the k x k matrix M, as lists of Fractions"""
    cols = [{i: M[i][j] for i in range(k) if M[i][j]} for j in range(k)]
    return stab.nullspace(cols, set(range(k)))


def eval_poly(P, v):
    tot = F(0)
    for a, c in P.items():
        t = c
        for i, e in enumerate(a):
            for _ in range(e):
                t *= v[i]
        tot += t
    return tot


# ----------------------------------------------------- the group elements

class GroupElt:
    """
    A product of one-parameter subgroups, each verifiably inside the image of
    Stab_{Diff_0}(f) in GL(Nt_f).  Kept as a list of factors so that a reader
    can check the claim factor by factor.
    """

    def __init__(self, n):
        self.n = n
        self.factors = []                  # (kind, data, t)
        self.matrix = mat_id(n)

    def push(self, kind, data, t, M):
        self.factors.append((kind, data, t))
        self.matrix = mat_mul(M, self.matrix)

    def apply(self, v):
        return apply_mat(self.matrix, v)

    def describe(self):
        out = []
        for kind, data, t in self.factors:
            if kind == "exp":
                out.append(f"exp({t}*M_{data})")
            else:
                out.append(f"tau_{data}({t})")
        return " . ".join(reversed(out)) if out else "1"


def nilpotent_pool(mats, extra=24, seed=7, cap=40):
    """
    Nilpotent elements of rho(s_f): the generators that happen to be nilpotent,
    their commutators, and a few random rational combinations.  Only elements
    of rho(s_f) are ever produced, so exp of any of them is in the group.
    """
    pool = [M for M in mats if not mat_zero(M) and is_nilpotent(M)]
    for A, B in combinations(mats[:12], 2):
        C = [[sum(A[i][l] * B[l][j] - B[i][l] * A[l][j]
                  for l in range(len(A))) for j in range(len(A))]
             for i in range(len(A))]
        if not mat_zero(C) and is_nilpotent(C):
            pool.append(C)
    rnd = random.Random(seed)
    for _ in range(extra):
        c = [F(rnd.randint(-2, 2)) for _ in mats]
        M = mat_comb(mats, c)
        if not mat_zero(M) and is_nilpotent(M):
            pool.append(M)
    # de-duplicate, and keep the sparsest first: a step with a sparse M is
    # both cheaper and likelier to leave the coordinates above i alone.
    seen, out = set(), []
    for M in pool:
        key = tuple(tuple(r) for r in M)
        if key not in seen:
            seen.add(key)
            out.append(M)
    out.sort(key=lambda M: sum(1 for row in M for x in row if x))
    return out[:cap]


def torus_pool(mats, n):
    """
    Semisimple elements of rho(s_f) that are DIAGONAL in the layer basis with
    integer entries.  For such an M the one-parameter subgroup is
    diag(t^{w_1},...,t^{w_n}), which is exact over Q for rational t /= 0.
    """
    out = []
    for M in mats:
        if any(M[i][j] for i in range(n) for j in range(n) if i != j):
            continue
        w = [M[i][i] for i in range(n)]
        if all(x == 0 for x in w):
            continue
        if all(x.denominator == 1 for x in w):
            out.append([int(x) for x in w])
    # also diagonal combinations of the generators
    diag = [M for M in mats
            if not any(M[i][j] for i in range(n) for j in range(n) if i != j)]
    for A, B in combinations(diag, 2):
        w = [A[i][i] - B[i][i] for i in range(n)]
        if any(w) and all(x.denominator == 1 for x in w):
            out.append([int(x) for x in w])
    seen, res = set(), []
    for w in out:
        if tuple(w) not in seen:
            seen.add(tuple(w))
            res.append(w)
    return res


def torus_matrix(w, t):
    n = len(w)
    M = [[F(0)] * n for _ in range(n)]
    for i in range(n):
        M[i][i] = F(t) ** w[i] if w[i] >= 0 else F(1) / (F(t) ** (-w[i]))
    return M


# ------------------------------------------------------------ the reduction

def _measure(v, mask=None):
    """what the descent minimises: first the number of nonzero coordinates,
    then the highest nonzero one.  With a mask, only the coordinates in the
    mask are counted -- that is how the graded normalisation below reduces the
    LEADING component while leaving the rest to the triangular sweep."""
    if mask is None:
        return (sum(1 for c in v if c), top_index(v))
    return (sum(1 for i in mask if v[i]),
            max([i for i in mask if v[i]], default=-1))


def _descend(cur, g, pool, tori, max_steps=200, mask=None):
    """
    The monotone half of the reduction.  At each step every pair (generator M,
    coordinate i with v_i /= 0) is tried: the parameter t that kills the i-th
    coordinate is the solution of an affine equation, hence rational, and the
    step is accepted if it strictly lowers the measure.  The measure is a pair
    of non-negative integers decreasing lexicographically, so the loop
    terminates; g is extended by every factor used.
    """
    n = len(cur)
    targets = range(n) if mask is None else mask
    steps = 0
    while steps < max_steps:
        cm = _measure(cur, mask)
        if cm[0] <= 1:
            break
        best = None
        for idx, M in enumerate(pool):
            Mv = apply_mat(M, cur)
            for i in targets:
                if not cur[i] or not Mv[i]:
                    continue
                t = -cur[i] / Mv[i]
                nv = exp_apply(M, t, cur)
                if nv[i]:                       # not affine in t after all
                    continue
                nm = _measure(nv, mask)
                if nm < cm and (best is None or nm < best[0]):
                    best = (nm, idx, t, nv)
            if best is not None and best[0][0] <= cm[0] - 1 and \
                    best[0][1] < cm[1]:
                break                            # good enough, take it
        if best is None:
            break
        _, idx, t, nv = best
        g.push("exp", idx, t, exp_nilpotent(pool[idx], t))
        cur = nv
        steps += 1

    # scale the leading coefficient to 1 if a torus can do it
    scan = range(n) if mask is None else sorted(mask)
    lead = next((j for j in scan if cur[j]), None)
    if lead is not None and cur[lead] != 1:
        for w in tori:
            if abs(w[lead]) != 1:
                continue
            t = (F(1) / cur[lead]) if w[lead] == 1 else cur[lead]
            if t == 0:
                continue
            T = torus_matrix(w, t)
            nv = apply_mat(T, cur)
            if nv[lead] == 1:
                g.push("torus", tuple(w), t, T)
                cur = nv
                break
    return cur


def _key(v, mask=None):
    """the order in which canonical forms are compared: the smaller, the more
    reduced.  First the highest nonzero coordinate, then the number of nonzero
    coordinates, then the coordinates themselves."""
    if mask is None:
        return (top_index(v), sum(1 for c in v if c), tuple(v))
    sub = [v[i] for i in sorted(mask)]
    return (top_index(sub), sum(1 for c in sub if c), tuple(sub))


def reduce_vector(mats, v, pool=None, tori=None, restarts=8, seed=5,
                  mask=None):
    """
    Gauss elimination along the group, with priming.

    Pure descent is not enough: passing from xi_2 to xi_1, say, needs one step
    that RAISES the number of nonzero coordinates before the step that lowers
    the leading index.  So the descent is run repeatedly from v, each run
    preceded by a short word in the group: first the deterministic words of one
    letter exp(+-M), M in the pool -- which is what covers the case just
    described -- and then a few random ones.  Every primer is a genuine group
    element, so priming can only improve the answer, never invalidate one; and
    the certificate returned is checked against the vector it claims to
    produce before it is returned.
    """
    n = len(v)
    if pool is None:
        pool = nilpotent_pool(mats)
    if tori is None:
        tori = torus_pool(mats, n)

    g = GroupElt(n)
    best_v = _descend(v[:], g, pool, tori, mask=mask)
    best_g = g

    def attempt(word):
        nonlocal best_v, best_g
        g1 = GroupElt(n)
        cur = v[:]
        for idx, t in word:
            E = exp_nilpotent(pool[idx], t)
            cur = apply_mat(E, cur)
            g1.push("exp", idx, t, E)
        cur = _descend(cur, g1, pool, tori, mask=mask)
        if _key(cur, mask) < _key(best_v, mask):
            best_v, best_g = cur, g1

    if pool:
        for idx in range(len(pool)):
            for t in (F(1), F(-1)):
                if _key(best_v, mask)[0] <= 0:
                    break
                attempt([(idx, t)])
        rnd = random.Random(seed)
        for _ in range(restarts):
            word = []
            for _ in range(rnd.randint(2, 3)):
                t = F(rnd.randint(-3, 3))
                if t:
                    word.append((rnd.randrange(len(pool)), t))
            if word:
                attempt(word)

    assert best_g.apply(v) == best_v, "certificate does not reproduce the form"
    return best_v, best_g


# ------------------------------------------------- the graded normalisation

def graded_pieces(mats, degs):
    """
    Both the layer and the stabiliser are graded: Nt_f = (+)_e Nt^(e) by the
    degree of the monomial, s_f = (+)_d s_d by the degree of the vector field,
    and s_d.Nt^(e) < Nt^(e+d).  This returns a basis of each homogeneous piece
    g_d of the span of `mats`, as a dict d -> list of matrices.

    A matrix is homogeneous of degree d when M[i][j] = 0 unless
    degs[i] - degs[j] = d, so each piece is the kernel of a linear system in
    the coefficients -- exact, and it never assumes that the span IS graded:
    what is returned is the largest graded subalgebra of it, which is all the
    normalisation below needs to stay sound.
    """
    n = len(degs)
    if not mats:
        return {}
    # a basis of the span
    rows = [sum(M, []) for M in mats]
    keep = []
    cur = []
    for a, r in enumerate(rows):
        if stab.rank_rows(cur + [r]) > len(cur):
            cur.append(r)
            keep.append(mats[a])
    out = {}
    for d in sorted({degs[i] - degs[j] for i in range(n) for j in range(n)}):
        cols = [dict() for _ in keep]
        keys = set()
        for a, M in enumerate(keep):
            for i in range(n):
                for j in range(n):
                    if degs[i] - degs[j] != d and M[i][j]:
                        cols[a][(i, j)] = M[i][j]
                        keys.add((i, j))
        sols = stab.nullspace(cols, keys) if keys else \
            [[F(1) if b == a else F(0) for b in range(len(keep))]
             for a in range(len(keep))]
        piece = []
        for s in sols:
            M = mat_comb(keep, s)
            if not mat_zero(M):
                piece.append(M)
        if piece:
            out[d] = piece
    return out


def reduce_graded(mats, degs, v, cache=None):
    """
    THE NORMALISATION, and the reason T_2 needs no search worth the name.

    Write v = sum_e v_e along the grading and let e_0 be the lowest degree with
    v_{e_0} /= 0.  Then

      -- g_0 preserves each Nt^(e), so the class of v_{e_0} under exp(g_0) is
         an invariant of the orbit of v: the LEADING TERM.  This is a problem
         in one graded piece, of small dimension, and it is the only place
         where anything is searched for;
      -- for s >= 1 and M in g_s, exp(M) leaves the degrees below e_0+s alone
         and sends v_{e_0+s} to v_{e_0+s} + M.v_{e_0}.  So the component of
         degree e_0+s can be killed modulo the LINEAR subspace g_s.v_{e_0}, by
         one exact linear reduction, and the degrees already fixed are never
         disturbed again.

    Sweeping s upwards is therefore a finite triangular loop.  Everything it
    produces is exp of an element of the algebra, hence a group element, so
    the result is a certificate; the loop ignores the stabiliser of the
    leading term inside g_0, so the normal form it reaches is sound but need
    not be optimal -- when two vectors reach different forms the verdict is
    UNDECIDED, never "different orbits".
    """
    n = len(v)
    if cache is None:
        cache = {}
    if "pieces" not in cache:
        cache["pieces"] = graded_pieces(mats, degs)
        p0 = cache["pieces"].get(0, [])
        cache["pool0"] = nilpotent_pool(p0) if p0 else []
        cache["tori0"] = torus_pool(p0, n) if p0 else []
    pieces = cache["pieces"]
    g = GroupElt(n)
    cur = v[:]
    if vec_zero(cur):
        return cur, g

    e0 = min(degs[i] for i in range(n) if cur[i])

    # (1) the leading term, under g_0.  The search runs on the WHOLE layer,
    # with generators taken from g_0 only and the measure masked to the
    # leading graded piece: so every factor used is exp of an element of g_0,
    # an honest group element, and what gets minimised is the leading term.
    if 0 in pieces:
        idxs = [i for i in range(n) if degs[i] == e0]
        cur, g0 = reduce_vector(pieces[0], cur, cache["pool0"],
                                cache["tori0"], mask=idxs)
        for kind, data, t in g0.factors:
            g.factors.append((kind, data, t))
        g.matrix = mat_mul(g0.matrix, g.matrix)

    e0 = min(degs[i] for i in range(n) if cur[i])

    # (2) the higher degrees, one exact linear reduction each
    for s in sorted(d for d in pieces if d >= 1):
        tgt = [i for i in range(n) if degs[i] == e0 + s]
        if not tgt:
            continue
        W = Span(n)
        gens = []
        for M in pieces[s]:
            u = apply_mat(M, cur)
            u = [u[i] if i in tgt else F(0) for i in range(n)]
            if not vec_zero(u):
                if W.add(u):
                    gens.append(M)
        # kill the component of degree e0+s modulo W, tracking the element
        for M in gens:
            u = apply_mat(M, cur)
            piv = next((i for i in tgt if u[i]), None)
            if piv is None or not cur[piv]:
                continue
            t = -cur[piv] / u[piv]
            E = exp_nilpotent(M, t)
            nv = apply_mat(E, cur)
            if any(nv[i] != cur[i] for i in range(n) if degs[i] < e0 + s):
                continue
            g.push("exp", f"g_{s}", t, E)
            cur = nv
    assert g.apply(v) == cur
    return cur, g


def same_orbit(mats, v, w, pool=None, tori=None, degs=None, cache=None):
    """
    Decide whether v and w lie in one orbit, with a certificate either way.
    Returns (verdict, certificate) with verdict in {True, False, None}.
    """
    n = len(v)
    if pool is None:
        pool = nilpotent_pool(mats)
    if tori is None:
        tori = torus_pool(mats, n)

    # (B3) orbit dimension
    dv, dw = orbit_dim(mats, v), orbit_dim(mats, w)
    if dv != dw:
        return False, f"orbit dimensions differ: {dv} vs {dw}"

    # (B1) a stable subspace containing one and not the other
    Sv = submodule(mats, v)
    if not Sv.contains(w):
        return False, (f"the stable subspace generated by v has dimension "
                       f"{Sv.dim()} and does not contain w")
    Sw = submodule(mats, w)
    if not Sw.contains(v):
        return False, (f"the stable subspace generated by w has dimension "
                       f"{Sw.dim()} and does not contain v")

    # (A) try to conjugate
    cv, gv = _reduce(mats, v, pool, tori, degs, cache)
    cw, gw = _reduce(mats, w, pool, tori, degs, cache)
    if cv == cw:
        return True, (gv, gw, cv)
    return None, f"reduction stalled at {cv} and {cw}"


def _reduce(mats, v, pool, tori, degs, cache):
    """the graded normalisation when a grading is supplied, the search
    otherwise"""
    if degs is not None:
        return reduce_graded(mats, degs, v, cache)
    return reduce_vector(mats, v, pool, tori)


# ------------------------------------------------------------- orbit census

def orbit_census(mats, n, samples=60, seed=3, pool=None, tori=None,
                 degs=None, cache=None):
    """
    Sample the layer, reduce every sample, and collect the canonical forms.
    Returns a list of (canonical form, orbit dimension, number of hits).
    This ENUMERATES nothing by itself -- it produces the candidate list that
    the accompanying theorem then has to account for; every sample carries the
    explicit group element that took it to its canonical form.
    """
    if pool is None:
        pool = nilpotent_pool(mats)
    if tori is None:
        tori = torus_pool(mats, n)
    rnd = random.Random(seed)
    found = {}
    for _ in range(samples):
        v = [F(rnd.randint(-4, 4)) for _ in range(n)]
        c, g = _reduce(mats, v, pool, tori, degs, cache)
        assert g.apply(v) == c, "the certificate does not reproduce the form"
        key = tuple(c)
        if key not in found:
            found[key] = [c, orbit_dim(mats, c), 0]
        found[key][2] += 1
    return sorted(found.values(), key=lambda r: -r[1])


def verify_transitive(mats, reps, gen_stratum, samples=40, seed=11,
                      pool=None, tori=None, degs=None, cache=None):
    """
    For each representative r and each of `samples` random points v of the
    stratum described by gen_stratum(r) (a function producing random points of
    the stratum), check that v reduces to r, with the group element exhibited.
    Returns (number of successes, number of samples, first failure or None).
    """
    n = len(reps[0])
    if pool is None:
        pool = nilpotent_pool(mats)
    if tori is None:
        tori = torus_pool(mats, n)
    rnd = random.Random(seed)
    ok = bad = 0
    first = None
    for r in reps:
        for _ in range(samples):
            v = gen_stratum(r, rnd)
            c, g = _reduce(mats, v, pool, tori, degs, cache)
            if c == r and g.apply(v) == c:
                ok += 1
            else:
                bad += 1
                if first is None:
                    first = (r, v, c)
    return ok, ok + bad, first
