#!/usr/bin/env python3
"""
found.py -- checks of the foundations: the layer over a normal form and the
relative local superalgebra over a base with one odd parameter.

Three things are checked, all in exact arithmetic, all with the truncation
validated by recomputing at D and D+1:

 (A) the first layer.  The space
         N_f      = (m^2)_odd / (m I_f)_odd
     is the layer of germs whose differential vanishes at the C-point.
     With "singular" meaning that the reduction is singular, the layer is
         Nt_f     = m_odd / (m I_f)_odd  =  (O_C-germs over f),
     and the two differ by exactly the q classes of xi_1,...,xi_q:
         dim Nt_f = dim N_f + q.
     Checked germ by germ, together with a monomial basis of the quotient.

 (B) the relative local superalgebra.  For C = Lambda[theta] and F = f+theta*g,
         O_F := (O (x) C) / I_F ,   I_F = (dF/dx_i, dF/dxi_j),
     is a C-module.  It is generated by lifts of a k-basis of O_f (nilpotent
     Nakayama), so sdim_k O_F <= sdim_k (C (x) O_f); equality is freeness.
     We measure the defect for g running over
        -- 0                       (the germ itself),
        -- representatives of N_f  (the layer of critical germs),
        -- representatives of Nt_f minus N_f, i.e. g = xi_j  (the new germs).

 (C) the two worked examples II(n,1) and I_1, in the layer Nt_f.

Everything sits on sv.py; theta is carried as the (q+1)-st odd variable, with
no derivative taken along it -- which is exactly what "a parameter" means.
"""

from fractions import Fraction
import sv


# ------------------------------------------------------------------ helpers


def build(R, terms):
    f = {}
    for c, a, S in terms:
        key = (tuple(a), frozenset(S))
        f[key] = f.get(key, Fraction(0)) + Fraction(c)
    return {k: v for k, v in f.items() if v}


def gradient(R, F, p, q):
    """the partials along x_1..x_p and xi_1..xi_q only (never along theta)"""
    gens = []
    for i in range(p):
        g = sv.d_dx(R, F, i)
        if g:
            gens.append(g)
    for j in range(q):
        g = sv.d_dxi(R, F, j)
        if g:
            gens.append(g)
    return gens


def sdim_quotient(p, qtot, terms, p_der, q_der, D):
    """sdim_k of (truncated ring)/(ideal generated by the partials)"""
    R = sv.Ring(p, qtot, D)
    F = build(R, terms)
    gens = gradient(R, F, p_der, q_der)
    allmon = R.basis()
    piv = sv.rref_dims(R, sv.ideal_span(R, gens, allmon))
    tot = {0: 0, 1: 0}
    for m in allmon:
        tot[R.parity(m)] += 1
    return (tot[0] - len(piv[0]), tot[1] - len(piv[1]))


def sdim_quotient_stable(p, qtot, terms, p_der, q_der, D):
    a = sdim_quotient(p, qtot, terms, p_der, q_der, D)
    b = sdim_quotient(p, qtot, terms, p_der, q_der, D + 1)
    return a if a == b else None


def layer_basis(p, q, terms, D, min_mdeg):
    return sv.quotient_basis(p, q, terms, D, min_mdeg=min_mdeg)


# ------------------------------------------------------------------ the germs
# (coefficient, x-exponents, xi-indices), xi indices 0-based

def T(*args):
    return list(args)


GERMS = [
    # name,               p, q, terms,                                      D
    ("I_1  xi1xi2xi3xi4",  0, 4, T((1, (), (0, 1, 2, 3))),                   3),
    ("I_2",                0, 6, T((1, (), (0, 1, 2, 3)), (1, (), (0, 1, 4, 5))), 3),
    ("I_4  6-vector",      0, 6, T((1, (), (0, 1, 2, 3, 4, 5))),             3),
    ("II(3,1) x^3+x.12",   1, 2, T((1, (3,), ()), (1, (1,), (0, 1))),        9),
    ("II(4,1) x^4+x.12",   1, 2, T((1, (4,), ()), (1, (1,), (0, 1))),        9),
    ("II(4,2) x^4+x^2.12", 1, 2, T((1, (4,), ()), (1, (2,), (0, 1))),        9),
    ("III_3 x^3+1234",     1, 4, T((1, (3,), ()), (1, (0,), (0, 1, 2, 3))),  7),
    ("III_4 x^3+x.1234",   1, 4, T((1, (3,), ()), (1, (1,), (0, 1, 2, 3))),  7),
    ("A_2 = x^3 in 1|2",   1, 2, T((1, (3,), ())),                           8),
    ("VII_2",              2, 3, T((1, (3, 0), ()), (1, (0, 4), ()),
                                   (1, (1, 0), (0, 1)), (1, (0, 1), (1, 2))), 6),
]


print("=" * 78)
print("(A)  the corrected layer:  Nt_f = m_odd/(m I_f)_odd  versus  N_f")
print("=" * 78)
print(f"{'germ':22s} {'p|q':>6s} {'sdim O_f':>10s} {'dim N_f':>8s} {'dim Nt_f':>9s}"
      f" {'Nt-N':>5s} {'q':>3s}  new directions")
bad = 0
for name, p, q, terms, D in GERMS:
    r = sv.stable(p, q, terms, D)
    if r["sdim"] is None:
        print(f"{name:22s}  UNSTABLE")
        bad += 1
        continue
    m0, m1 = r["sdim"]
    nt = r["layer"]                      # dim (O/m I_f)_odd = dim m_odd/(m I_f)_odd
    n = nt - q                           # N_f
    b1 = layer_basis(p, q, terms, D, 1)
    b2 = layer_basis(p, q, terms, D, 2)
    new = [m for m in b1 if m not in b2]
    newtxt = ", ".join(sv.show_mon(m, "xy", "xi") for m in new)
    flag = "OK" if nt - n == q else "MISMATCH"
    if flag != "OK":
        bad += 1
    print(f"{name:22s} {str(p)+'|'+str(q):>6s} {str(m0)+'|'+str(m1):>10s}"
          f" {n:8d} {nt:9d} {nt-n:5d} {q:3d}  {newtxt}   {flag}")
print()
print("The new directions are always exactly xi_1,...,xi_q -- i.e. m_odd/(m^2)_odd,")
print("which is the tangent space to the odd coordinate directions at the point.")


print()
print("=" * 78)
print("(B)  freeness of the relative local superalgebra over C = Lambda[theta]")
print("=" * 78)
print("A free C-module of rank m_0|m_1 has sdim_k = (m0+m1)|(m0+m1), C being of")
print("sdim 1|1.  'defect' = that value minus the computed one.")
print()
print(f"{'germ F = f + theta g':38s} {'sdim_k O_F':>12s} {'free rank':>10s} {'defect':>7s}  verdict")

CASES = [
    # name, p, q, f-terms, g-terms (theta = odd index q), D
    ("x^2                       (1|2)", 1, 2, T((1, (2,), ())), None, 7),
    ("x^2 + theta.x.xi1         (1|2)", 1, 2, T((1, (2,), ())),
     T((1, (1,), (0,))), 7),
    ("x^2 + theta.xi1           (1|2)", 1, 2, T((1, (2,), ())),
     T((1, (0,), (0,))), 7),
    ("II(3,1)                   (1|2)", 1, 2, T((1, (3,), ()), (1, (1,), (0, 1))), None, 9),
    ("II(3,1) + theta.x.xi1     (1|2)", 1, 2, T((1, (3,), ()), (1, (1,), (0, 1))),
     T((1, (1,), (0,))), 9),
    ("II(3,1) + theta.xi1       (1|2)", 1, 2, T((1, (3,), ()), (1, (1,), (0, 1))),
     T((1, (0,), (0,))), 9),
    ("I_1                       (0|4)", 0, 4, T((1, (), (0, 1, 2, 3))), None, 3),
    ("I_1 + theta.xi1xi2xi3     (0|4)", 0, 4, T((1, (), (0, 1, 2, 3))),
     T((1, (), (0, 1, 2))), 3),
    ("I_1 + theta.xi1           (0|4)", 0, 4, T((1, (), (0, 1, 2, 3))),
     T((1, (), (0,))), 3),
    ("III_3                     (1|4)", 1, 4, T((1, (3,), ()), (1, (0,), (0, 1, 2, 3))), None, 6),
    ("III_3 + theta.x^2xi1      (1|4)", 1, 4, T((1, (3,), ()), (1, (0,), (0, 1, 2, 3))),
     T((1, (2,), (0,))), 6),
    ("III_3 + theta.xi1         (1|4)", 1, 4, T((1, (3,), ()), (1, (0,), (0, 1, 2, 3))),
     T((1, (0,), (0,))), 6),
]

for name, p, q, fterms, gterms, D in CASES:
    r = sv.stable(p, q, fterms, D)
    m0, m1 = r["sdim"]
    terms = list(fterms)
    if gterms:
        for c, a, S in gterms:
            terms.append((c, a, tuple(sorted(set(S) | {q}))))   # multiply by theta
    got = sdim_quotient_stable(p, q + 1, terms, p, q, D)
    if got is None:
        print(f"{name:38s}  UNSTABLE")
        bad += 1
        continue
    free = (m0 + m1, m0 + m1)
    defect = (free[0] - got[0], free[1] - got[1])
    verdict = "free" if defect == (0, 0) else "NOT free"
    print(f"{name:38s} {str(got[0])+'|'+str(got[1]):>12s}"
          f" {str(free[0])+'|'+str(free[1]):>10s} {str(defect[0])+'|'+str(defect[1]):>7s}  {verdict}")


print()
print("=" * 78)
print("(C)  the two worked examples, corrected layer, monomial bases")
print("=" * 78)
for name, p, q, terms, D in [
        ("II(3,1) = x^3+x xi1xi2", 1, 2, T((1, (3,), ()), (1, (1,), (0, 1))), 9),
        ("II(5,1) = x^5+x xi1xi2", 1, 2, T((1, (5,), ()), (1, (1,), (0, 1))), 9),
        ("I_1     = xi1xi2xi3xi4", 0, 4, T((1, (), (0, 1, 2, 3))), 3)]:
    b1 = layer_basis(p, q, terms, D, 1)
    b2 = layer_basis(p, q, terms, D, 2)
    print(f"{name}:")
    print(f"   Nt_f, dim {len(b1):2d} : " + ", ".join(sv.show_mon(m, "xy", "xi") for m in b1))
    print(f"   N_f , dim {len(b2):2d} : " + ", ".join(sv.show_mon(m, "xy", "xi") for m in b2))

print()
print("=" * 78)
print("SUMMARY:", "all checks passed" if bad == 0 else f"{bad} PROBLEM(S)")
print("=" * 78)
