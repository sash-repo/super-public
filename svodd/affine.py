#!/usr/bin/env python3
"""
affine.py -- the AFFINE certificate: the orbits of an affine action, with a
proof, and without assuming that the translation subspace is invariant.

WHY.  At degree d of the layer the group Stab(v) acts on the piece Nt^(d) by

        u  |-->  A_M u + t_M ,     A_M = proj0(M)|_d ,   t_M = (M v)|_d ,

and this is an honest affine action: M |-> (A_M, t_M) is a homomorphism into
gl(Nt^(d)) semidirect Nt^(d), the bracket giving the cocycle identity

        t_{[M,N]} = A_M t_N - A_N t_M .                                   (*)

The linear shortcut (t3.classify with affine_mode=False) quotients the piece
by T = span{ t_M }, classifies the induced LINEAR action on the quotient,
and takes each fibre of the quotient map for a single orbit.  Two hypotheses hide in that step:

  (i)  T must be invariant under the linear parts, or the quotient does not
       exist -- this is the failure reported as "the translation subspace is
       not stable", which occurs in corank 1|5;
  (ii) even when T is invariant, a fibre need NOT be one orbit.  The tangent
       to the orbit through u is { A_M u + t_M }, which is not T + (linear
       part) but a subspace of it that varies with u.  The smallest example is
       k = 1, one generator A = (1), t = 1: here T fills the space, yet -1 is a
       fixed point and the orbits are {-1} and the complement -- two, not one.

The certificates below replace both by proofs.  Throughout, k = dim U, the
group is the connected group generated by the action, the ground field is
algebraically closed of characteristic 0, and U is irreducible -- so an orbit
whose tangent is everything at every point of U is all of U.

  (A0) k = 0: the space is a point.

  (A1) PURE TRANSLATIONS.  Put h_0 = { M : A_M = 0 } and T_0 = { t_M : M in
       h_0 }.  By (*), A_M t_N = t_{[M,N]} for N in h_0 and [M,N] again in h_0,
       so T_0 is an INVARIANT subspace -- no hypothesis needed.  The group
       translates freely along T_0, hence
         * T_0 = U   ==> one orbit;
         * 0 < dim T_0 < k ==> the orbits are the full preimages of the orbits
           of the induced affine action on U/T_0.  Recurse.

  (A2) A FIXED POINT (the cocycle is a coboundary).  If A_M u_0 + t_M = 0 for
       every M, translating by u_0 turns the affine action into the LINEAR
       action of { A_M }, whose orbits are known to the linear machinery.  The
       classes are u_0 (the origin) together with u_0 + (orbits on U minus 0).
       This needs nothing of T: it is precisely the case that (i) leaves open,
       and it is the case that occurs in corank 1|5.

  (A3) THE SUBMODULE GENERATED BY THE TRANSLATIONS.  Let T^inf be the smallest
       invariant subspace containing every t_M -- always defined, whether or
       not T itself is invariant.  On U/T^inf every translation dies, so the
       induced action is LINEAR.  If T^inf is proper, classify that linear
       action; over a class with representative r the orbits of the fibre
       r + T^inf are the orbits of the stabiliser subalgebra
       h_r = { M : A_M r + t_M in T^inf }, acting on T^inf affinely with
       translations A_M r + t_M.  Recurse; the fibre has smaller dimension, so
       the recursion terminates.

  Otherwise the node is left OPEN and said to be so.

The reduction in (A1) and (A3) is the standard bijection: for an equivariant
map X --> X-bar onto a single orbit, the orbits of X lying over it are the
orbits of the stabiliser of a point on its fibre.
"""

from fractions import Fraction as F

import stab
import orb
import t3

# every family node the guard in (A3) declines is recorded here, so that the
# obstruction can be measured rather than guessed at; see v_fam.py
FAMILY_TRACE = []


# ------------------------------------------------------------ linear algebra

def rref(rows):
    return t3.rref(rows)


def pivots_of(R):
    return t3.pivots_of(R)


def apply(A, v):
    k = len(v)
    return [sum(A[i][j] * v[j] for j in range(k)) for i in range(k)]


def submodule_generated(lins, vecs, k):
    """the smallest subspace containing `vecs` and stable under every A"""
    B = rref([list(v) for v in vecs])
    while B:
        new = list(B)
        for A in lins:
            for r in B:
                new.append(apply(A, r))
        B2 = rref(new)
        if len(B2) == len(B):
            return B
        B = B2
    return B


def coords_in(B, piv, vec):
    """the coordinates of vec in the rref basis B (vec must lie in span B)"""
    return [vec[piv[b]] for b in range(len(B))]


def in_span(B, vec, k):
    return stab.rank_rows([list(r) for r in B] + [list(vec)]) == len(B)


def span_basis(gens, k):
    """a basis of the span of the pairs (A,t), as pairs"""
    keep, rows = [], []
    for A, t in gens:
        r = sum(A, []) + list(t)
        if stab.rank_rows(rows + [r]) > len(rows):
            rows.append(r)
            keep.append((A, t))
    return keep


def comb(gens, c):
    k = len(gens[0][1])
    A = [[sum(c[a] * gens[a][0][i][j] for a in range(len(gens)))
          for j in range(k)] for i in range(k)]
    t = [sum(c[a] * gens[a][1][i] for a in range(len(gens)))
         for i in range(k)]
    return A, t


# --------------------------------------------------------- the certificates

def fixed_point(gens, k):
    """u_0 with A u_0 + t = 0 for every generator, or None"""
    cols = [{} for _ in range(k + 1)]
    eqn = 0
    for A, t in gens:
        for i in range(k):
            for j in range(k):
                if A[i][j]:
                    cols[j][eqn] = A[i][j]
            if t[i]:
                cols[k][eqn] = -t[i]
            eqn += 1
    if eqn == 0:
        return [F(0)] * k
    for s in stab.nullspace(cols, set(range(eqn))):
        if s[k]:
            c = s[k]
            return [-s[j] / c for j in range(k)]
    return None


def pure_translations(gens, k):
    """a basis (in rref) of T_0 = { t_M : A_M = 0 }"""
    cols, keys = [], set()
    for a, (A, t) in enumerate(gens):
        d = {}
        for i in range(k):
            for j in range(k):
                if A[i][j]:
                    d[(i, j)] = A[i][j]
                    keys.add((i, j))
        cols.append(d)
    if not keys:
        return rref([list(t) for A, t in gens])
    sols = stab.nullspace(cols, keys)
    return rref([comb(gens, s)[1] for s in sols])


def stabiliser(gens, k, kbar, red, r):
    """
    { M in span(gens) : A_M r + t_M lies in T^inf } -- the M whose induced
    action on U/T^inf fixes the class of r, since there the translations die
    and the condition reads A_M rbar = 0.  Returned as a list of (A,t) on U.
    """
    cols, keys = [], set(range(kbar))
    for A, t in gens:
        img = red([apply(A, r)[i] + t[i] for i in range(k)])
        cols.append({i: img[i] for i in range(kbar) if img[i]})
    out = []
    for s in stab.nullspace(cols, keys):
        A, t = comb(gens, s)
        if any(any(row) for row in A) or any(t):
            out.append((A, t))
    return out


def parallel(z, r):
    """is z a scalar multiple of r?"""
    i = next((a for a in range(len(r)) if r[a]), None)
    if i is None:
        return not any(z)
    c = z[i] / r[i]
    return all(z[a] == c * r[a] for a in range(len(r)))


def uniform_family(lins, red, r, dirs):
    """
    Over a FAMILY of classes the stabiliser must not move from one member to
    the next, or the fibres below them are different problems.  Two cases in
    which it provably does not, and they are the ones the enumerator produces:

      * the acting algebra kills the whole affine span of the family, so every
        member has the full algebra for its stabiliser;
      * the family is the set of scalar multiples of r.  Then the stabiliser of
        a member is ker(M |-> Abar_M (lambda r)) = ker(M |-> Abar_M r) for every
        lambda different from 0, by linearity -- the same subalgebra.

    Anything else is declined.  It is worth saying why the test cannot simply
    be "the stabiliser has the same dimension at a few sampled members": with
    Phi_mu(M) = Abar_M (r + sum mu_i d_i) = B_0(M) + sum mu_i B_i(M), a constant
    S(mu) = ker Phi_mu forces S(mu) = S* := ker B_0 cap ker B_1 cap ... (subtract
    the conditions at mu and at mu' and let mu - mu' run over a basis), so a node
    with dim S(mu) constant but larger than dim S* has a stabiliser that genuinely
    MOVES while keeping its dimension.  Corank 1|5 has such a node.
    """
    if all(not any(red(apply(A, z))) for A in lins for z in [r] + list(dirs)):
        return True
    return all(parallel(z, r) for z in dirs)


def affine_orbit_reps(gens, k, depth=0):
    """
    Representatives of EVERY orbit of the affine action on U, dim U = k, with a
    proof.  Returns (reps, certificate) or (None, reason).  A rep is a triple
    (vector, family, dirs) exactly as in t3.orbit_reps -- family = t > 0 meaning
    a t-parameter family of orbits along `dirs`.  Unlike t3.orbit_reps, the
    orbit through the origin is included: an affine space has no origin.
    """
    zero = [F(0)] * k
    if k == 0:
        return [([], 0, [])], "the space is a point"
    gens = span_basis([(A, list(t)) for A, t in gens], k) if gens else []
    if not gens:
        ident = [[F(1) if i == j else F(0) for i in range(k)] for j in range(k)]
        return ([(zero, k, ident)],
                f"the algebra acts trivially on a space of dimension {k}: "
                f"every point is its own orbit")
    if depth > 6:
        return None, "the affine recursion did not terminate"

    lins = [A for A, t in gens]

    # (A1) the pure translations
    T0 = pure_translations(gens, k)
    import param
    if param.RECORD:
        # dim T_0, the space of pure translations, against the dimension k of
        # the fibre: T_0 = k is transitivity, i.e. one class, and the fibre of a
        # family splits exactly where this dimension drops.  Intrinsic: T_0 is
        # the image of { M : A_M = 0 }, no pivot enters its definition.
        param.record_rank(("dim_T0", len(T0), k))
    if len(T0) == k:
        return ([(zero, 0, [])],
                "the pure translations (the elements acting with zero linear "
                f"part) already fill the space of dimension {k}: one orbit")
    if T0:
        Q, lift, red = t3.quotient(T0, k)
        kq = len(Q)
        sub = [(t3.induced(A, Q, red), red(t)) for A, t in gens]
        rq, cq = affine_orbit_reps(sub, kq, depth + 1)
        if rq is not None:
            def up(u):
                w = [F(0)] * k
                for b in range(kq):
                    for a in range(k):
                        w[a] = w[a] + u[b] * lift[b][a]
                return w
            out = [(up(r), fam, [up(z) for z in dr]) for r, fam, dr in rq]
            return out, (f"the pure translations span an invariant subspace of "
                         f"dimension {len(T0)} of {k}, along which the group "
                         f"acts simply transitively, so the orbits are its "
                         f"cosets pulled back from the quotient, where {cq}")

    # (A2) a fixed point: the affine action is a linear one in disguise
    u0 = fixed_point(gens, k)
    if u0 is not None:
        lr, cl = t3.orbit_reps(lins, k, depth)
        if lr is not None:
            def sh(u):
                return [u0[i] + u[i] for i in range(k)]
            out = [(list(u0), 0, [])]
            out += [(sh(r), fam, list(dr)) for r, fam, dr in lr]
            return out, ("the affine action has a fixed point, so it is the "
                         "linear action of its linear part translated to that "
                         f"point; there, {cl}")

    # (A3) the submodule generated by the translations
    Tinf = submodule_generated(lins, [t for A, t in gens], k)
    import param
    if param.RECORD:
        # dim T^infty, the module the translations generate: the invariant that
        # decides the fibre.  T^infty = the whole fibre means the action is
        # transitive there and the fibre is one class; a drop is what splits it.
        param.record_rank(("dim_T", len(Tinf), k))
    if len(Tinf) == k:
        return None, ("no pure translations, no fixed point, and the "
                      "translations generate the whole space as a module")
    Q, lift, red = t3.quotient(Tinf, k)
    kq = len(Q)
    bar = [t3.induced(A, Q, red) for A in lins]          # linear on U/T^inf
    if kq == 0:
        return None, "the translations generate the whole space"
    lr, cl = t3.orbit_reps(bar, kq, depth)
    if lr is None:
        return None, f"on the quotient by the module generated by T: {cl}"
    piv = pivots_of(Tinf)
    m = len(Tinf)

    def up_q(u):
        w = [F(0)] * k
        for b in range(kq):
            for a in range(k):
                w[a] = w[a] + u[b] * lift[b][a]
        return w

    def up_f(y):
        return [sum(y[b] * Tinf[b][a] for b in range(m)) for a in range(k)]

    def fibre_body(r, depth_):
        """
        The classes of the fibre r + T^inf, as (y, ff, fd) in the basis Tinf.
        Works over ANY ground field -- over Q for a single class of the
        quotient, over K(mu) for the generic member of a family, which is the
        parametric certificate; see param.py.
        """
        h = stabiliser(gens, k, kq, red, r)
        fg = []
        for A, t in h:
            img = [apply(A, r)[i] + t[i] for i in range(k)]
            if not in_span(Tinf, img, k):
                return None, ("the stabiliser moves a point out of its fibre "
                              "-- the reduction is not valid")
            rows = []
            for b in range(m):
                w = apply(A, up_f([F(1) if c == b else F(0)
                                   for c in range(m)]))
                if not in_span(Tinf, w, k):
                    return None, "the module generated by T is not invariant"
                rows.append(coords_in(Tinf, piv, w))
            AF = [[rows[b][i] for b in range(m)] for i in range(m)]
            fg.append((AF, coords_in(Tinf, piv, img)))
        return affine_orbit_reps(fg, m, depth_ + 1)

    out, notes = [], []
    quo = [(zero, 0, [])] + [(up_q(r), fam, [up_q(z) for z in dr])
                             for r, fam, dr in lr]
    for r, fam, dr in quo:
        # over a FAMILY of quotient classes the stabiliser must not move from
        # one member to the next, or the fibres below them differ; it does not
        # when the induced action kills the whole affine span of the family,
        # which is the case most families come from (a zero action on a
        # residual space).  When it does move, the fibre is classified over the
        # GENERIC member instead, over K(mu) -- the parametric certificate,
        # which proves the answer for every member outside the zero set of the
        # polynomials the elimination inverts.
        rr, param_note, node = r, None, None
        if fam and not uniform_family(lins, red, r, dr):
            FAMILY_TRACE.append({"lins": lins, "red": red, "kq": kq, "k": k,
                                 "r": r, "fam": fam, "dirs": dr})
            import param
            gm = param.generic_member(r, dr) if param.active() else None
            if gm is None:
                return None, ("a family in the quotient along which the "
                              "stabiliser is not constant")
            rr, mus = gm
            node = param.note_node("affine", {
                "k": k, "m": m, "fam": fam, "r": r, "dirs": dr,
                "params": list(param.LAST_PARAMS),
                "run": (lambda vals, _r=r, _dr=dr, _d=depth:
                        fibre_body([_r[i] + sum(v * z[i] for v, z
                                                in zip(vals, _dr))
                                    for i in range(k)], _d))})
            param_note = (f"the fibre is classified over the GENERIC member of "
                          f"the {fam}-parameter family, over K(mu)")
        rf, cf = fibre_body(rr, depth)
        if node is not None:
            import param
            param.close_node(node, (rf, cf))
        if rf is None:
            return None, f"on a fibre of dimension {m}: {cf}"
        notes.append(cf if param_note is None else param_note + "; " + cf)
        for y, ff, fd in rf:
            base = up_f(y)
            out.append(([rr[i] + base[i] for i in range(k)], fam + ff,
                        list(dr) + [up_f(z) for z in fd]))
    return out, (f"the translations generate an invariant subspace of "
                 f"dimension {m} of {k}; on the quotient the action is linear "
                 f"and {cl}; on each fibre, {notes[0] if notes else 'nothing'}")
