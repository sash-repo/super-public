#!/usr/bin/env python3
"""The cotangent retract: H^q(X; Omega^p (x) Theta) on a compact Hermitian
symmetric space X = G/P, exactly, from the Cartan matrix.

Statement 4.4.3 of the text: `cot.py` runs the tests below (items 1)-4) over
every space of the census except E = E_7/P_7, which e7.py runs); `cot.py --census`
prints the table of dim H^1(X; Omega^2 (x) Theta), its invariant part and
dim H^1(X; Omega^3 (x) Theta).

This is the arithmetic behind the claims of Onishchik's paper "Non-split
supermanifolds associated with the cotangent bundle", Comm. Math. 30 (2022)
no. 3, 49--128 (arXiv:2205.12308), which classifies the non-split
supermanifolds with retract (X, Lambda(Omega)); the numbers it produces are
checked against his Propositions 5.17, 5.19, 5.24, 5.25 in tests() below.

Method.  Omega^p (x) Theta is the homogeneous bundle whose fiber is the
l-module Lambda^p(n_-) (x) n_+, generally reducible.  So:

  * the weights of n_+ are the roots of Delta(N_+), each once;
  * the weight multiset of Lambda^p(n_-) (x) n_+ is built from them;
  * it is split into irreducible l-modules by Klimyk's alternation over the
    Weyl group W_l of the Levi (an l-module character is W_l-invariant, so
    mult(lambda) = sum_{w in W_l} (-1)^{l(w)} m(w(lambda+rho)-rho); rho of g
    may be used in place of rho_l, their difference being W_l-invariant);
  * Bott's theorem, as implemented in bott.py, is applied to each constituent.

Everything is integer arithmetic; no root tables are typed in.

Conventions are bott.py's: a weight is given in the basis of fundamental
weights, E_lambda is the bundle of the l-module with highest weight lambda,
Theta_X = E_theta with theta the highest root.  Hence Omega^1 = E_{-alpha_0},
where alpha_0 is the simple root defining P: calibrated by the test
H^1(CP^n; Omega^1) = C below.
"""

from collections import defaultdict
from itertools import combinations

from bott import CHSS, chss_list


# ------------------------------------------------------------------ the Levi

def levi_weyl(X):
    """W_l as a dict {w : l(w)}, w recorded by the images of the basis.

    The Levi is generated by the simple reflections other than the node's.
    An element is determined by its images of the fundamental weights, since
    it acts linearly; BFS depth is the length.
    """
    R = X.R
    gens = [i for i in range(R.rank) if i != X.node - 1]
    basis = tuple(tuple(1 if j == k else 0 for j in range(R.rank))
                  for k in range(R.rank))
    seen = {basis: 0}
    frontier = [basis]
    while frontier:
        new = []
        for w in frontier:
            for i in gens:
                img = tuple(tuple(R.reflect(list(v), i)) for v in w)
                if img not in seen:
                    seen[img] = seen[w] + 1
                    new.append(img)
        frontier = new
    return seen


def apply_w(w, mu):
    """w recorded as images of the basis; mu in omega-coordinates."""
    out = [0] * len(mu)
    for k, c in enumerate(mu):
        if c:
            for j in range(len(out)):
                out[j] += c * w[k][j]
    return tuple(out)


def l_dominant(X, mu):
    return all(mu[i] >= 0 for i in range(X.R.rank) if i != X.node - 1)


# ------------------------------------------------------------- the bundles

def n_plus(X):
    """The weights of n_+, i.e., Delta(N_+), in omega-coordinates."""
    R = X.R
    return [tuple(R.to_omega(r)) for r in R.pos if r[X.node - 1] == 1]


def wedge_times_theta(X, p):
    """Weight multiset of Lambda^p(n_-) (x) n_+."""
    np_ = n_plus(X)
    m = defaultdict(int)
    for combo in combinations(np_, p):
        low = [0] * X.R.rank
        for b in combo:
            for j in range(X.R.rank):
                low[j] -= b[j]                       # n_- = -Delta(N_+)
        for a in np_:
            m[tuple(low[j] + a[j] for j in range(X.R.rank))] += 1
    return m


def decompose(X, m, W=None):
    """Klimyk: the multiset m -> {highest weight : multiplicity}."""
    if W is None:
        W = levi_weyl(X)
    rho = tuple([1] * X.R.rank)
    out = {}
    for mu in m:
        if not l_dominant(X, mu):
            continue
        mur = tuple(mu[j] + 1 for j in range(X.R.rank))
        tot = 0
        for w, ell in W.items():
            nu = apply_w(w, mur)
            c = m.get(tuple(nu[j] - 1 for j in range(X.R.rank)), 0)
            if c:
                tot += (-1) ** ell * c
        if tot:
            out[mu] = tot
    return out


def cohomology(X, p, W=None):
    """H^*(X; Omega^p (x) Theta) as {degree : [(dim, highest weight, mult)]}."""
    parts = decompose(X, wedge_times_theta(X, p), W)
    out = defaultdict(list)
    for lam, mult in parts.items():
        c = X.R.cohomology(list(lam))
        if c is None:
            continue
        ell, hw, dd = c
        out[ell].append((dd, tuple(hw), mult))
    return dict(out)


def dims(X, p, W=None):
    """{degree : dim H^degree(X; Omega^p (x) Theta)}."""
    return {q: sum(dd * mult for dd, _, mult in v)
            for q, v in cohomology(X, p, W).items()}


def invariants(X, p, W=None):
    """{degree : dim of the G-invariant part}, i.e., of the trivial summand."""
    zero = tuple([0] * X.R.rank)
    return {q: sum(mult for dd, hw, mult in v if hw == zero)
            for q, v in cohomology(X, p, W).items()
            if any(hw == zero for _, hw, _ in v)}


# ------------------------------------------------------------- his trichotomy

def case(X):
    """Onishchik's cases I, II, III, see his Subsection 5.11."""
    if X.typ != "A":
        return "I"
    return "III" if X.node in (1, X.rank) else "II"


def small_list(wide=False):
    """The spaces the census runs over; W_l is what costs, so the rank is
    capped.  Nothing is dropped silently: the caps are printed by census()."""
    hi = 7 if wide else 6
    keep = []
    for X in chss_list():
        if X.typ == "A" and X.rank <= hi + 1:
            keep.append(X)
        elif X.typ in ("B", "C", "D") and X.rank <= hi - 1:
            keep.append(X)
        elif X.typ == "E" and X.rank == 6:
            keep.append(X)
    return keep


def census(wide=False):
    """Per space: dim H^1(Omega^2 (x) Theta), its invariant part, and
    dim H^1(Omega^3 (x) Theta) -- the three numbers Onishchik's Theorem 5.32
    rests on."""
    L = small_list(wide)
    print("%-12s %-4s %5s %6s %8s %8s %8s" %
          ("X", "case", "dimX", "dim g", "h1(O2xT)", "inv", "h1(O3xT)"))
    odd = []
    for X in L:
        if X.dimX < 2:
            continue
        W = levi_weyl(X)
        h2 = dims(X, 2, W).get(1, 0)
        inv = invariants(X, 2, W).get(1, 0)
        h3 = dims(X, 3, W).get(1, 0) if X.dimX >= 3 else 0
        flag = ""
        if h2 != inv or h3 != 0:
            flag = "   <-- H^1 is not all invariant"
            odd.append(X.name)
        print("%-12s %-4s %5d %6d %8d %8d %8d%s"
              % (X.name, case(X), X.dimX, X.dimg, h2, inv, h3, flag))
    print("\nranks: A up to %d, B/C/D up to %d, E_6; E_7 not run (|W_l| = "
          "|W(E_6)| = 51840)" % (7 if wide else 6 + 1, 6 if wide else 5))
    print("spaces where H^1(Omega^2 (x) Theta) exceeds its invariant part: %s"
          % (", ".join(odd) if odd else "none"))
    return odd


# ------------------------------------------------------------------- testing

def tests():
    ok = True

    def check(what, got, want):
        nonlocal ok
        good = got == want
        ok = ok and good
        print("  %-58s %s  %s" % (what, "ok " if good else "FAIL", got))

    print("Calibration.")
    for n in (2, 3, 4):
        X = CHSS("CP^%d" % n, "A", n, 1)
        # Omega^1 = E_{-alpha_0}
        a0 = X.R.to_omega(tuple(1 if j == 0 else 0 for j in range(X.R.rank)))
        c = X.R.cohomology([-x for x in a0])
        check("H^*(CP^%d; Omega^1) = C in degree 1" % n, c, (1, [0] * n, 1))

    print("\nOnishchik, Lemma 5.4 and Prop. 5.24:  H^*(X; Omega^1 (x) Theta).")
    for X in small_list():
        W = levi_weyl(X)
        d = dims(X, 1, W)
        want = {0: 1} if case(X) == "III" else {0: 1, 1: X.dimg}
        if d != want:
            check("%-12s case %-3s" % (X.name, case(X)), d, want)
    print("  H^0 = C always, H^1 = g in the cases I, II and 0 in the case III,"
          "\n  H^p = 0 for p >= 2:  verified for all %d spaces of the census"
          % len(small_list()))

    print("\nOnishchik, Prop. 5.17 + 5.25:  dim H^1(X; Omega^2 (x) Theta).")
    for X in small_list():
        if X.dimX < 2:
            continue
        W = levi_weyl(X)
        d = dims(X, 2, W)
        want = 2 if case(X) == "II" else 1
        got = d.get(1, 0)
        if X.name in ("Q_3", "LGr_2"):        # the one exception, see below
            check("%-12s case %-3s  (Q_3 = LGr_2)" % (X.name, case(X)), got, 6)
            continue
        if got != want:
            check("%-12s case %-3s" % (X.name, case(X)), got, want)
    print("  = 1 in the cases I, III and = 2 in the case II:  verified,"
          "\n  except for Q_3 = LGr_2, where it is 6 = 1 + 5:  his Prop. 5.25"
          "\n  (all of H^1 is G-invariant) fails there, and with it the"
          " uniqueness\n  in his Theorem 5.32 for that one space")

    print("\nOnishchik, Prop. 5.15:  H^q(X; Omega^p (x) Theta)^G =/= 0 iff"
          " q = p-1.")
    for X in small_list():
        if X.dimX < 3:
            continue
        W = levi_weyl(X)
        for p in (1, 2, 3):
            inv = invariants(X, p, W)
            got = sorted(q for q, v in inv.items() if v)
            if got != [p - 1]:
                check("%-12s p=%d" % (X.name, p), got, [p - 1])
    print("  verified for p = 1, 2, 3")

    print("\nOnishchik, Prop. 5.19 (he omits the proof):"
          "  k = dim H^2(X; Omega^3 (x) Theta)^G.")
    for X in small_list():
        if X.dimX < 3:
            continue
        W = levi_weyl(X)
        k = invariants(X, 3, W).get(2, 0)
        want = onishchik_k(X)
        if want is None:
            print("  %-12s case %-3s  k = %d   (not covered by his list)"
                  % (X.name, case(X), k))
        elif k != want:
            check("%-12s case %-3s" % (X.name, case(X)), k, want)
        else:
            print("  %-12s case %-3s  k = %d   ok" % (X.name, case(X), k))

    print("\nThe primary obstruction:  H^1(X; T_2), T_2 = Omega^2 (x) Theta"
          " + Omega^3 (x) Theta.")
    for X in small_list():
        if X.dimX < 3:
            continue
        W = levi_weyl(X)
        h3 = dims(X, 3, W).get(1, 0)
        if h3:
            check("H^1(%s; Omega^3 (x) Theta) = 0" % X.name, h3, 0)
    print("  H^1(X; Omega^3 (x) Theta) = 0 throughout, so H^1(X; T_2) is"
          "\n  H^1(X; Omega^2 (x) Theta): 1-dimensional in the cases I, III"
          " and 2-dimensional in the case II")

    print("\n%s" % ("All tests passed." if ok else "SOMETHING FAILED."))
    return ok


def onishchik_k(X):
    """His Prop. 5.19, with his own caveats kept: the quadric rule is stated
    for the types B_l, E_l and for D_l only when l > 4 -- Q_6 = OGr_4 being
    the isotropic Grassmannian in disguise -- and the maximal-isotropic rule
    needs the same guard at the other end, LGr_2 = Q_3 being a quadric."""
    c = case(X)
    if c == "III":                      # M = CP^l
        return 0 if X.dimX == 2 else 1
    if c == "II":                       # M = Gr_s^n, s + t = n, 1 < s <= t
        s, n = (int(x) for x in X.name[3:].split("^"))
        t = n - s
        s, t = min(s, t), max(s, t)
        if s == t == 2:
            return 2
        if s == 2 or t == 2:
            return 3
        return 4
    if X.name == "LGr_2":               # = Q_3, a quadric: the quadric value
        return 1
    if X.name == "OGr_4":               # = Q_6, isotropic: the isotropic one
        return 2
    if X.name.startswith("Q_"):
        return 2 if X.name == "Q_6" else 1
    if X.name.startswith(("LGr", "OGr")):
        return 2
    if X.name == "OP^2":
        return 1                        # E_6, his item (2) for the type E
    return None


if __name__ == "__main__":
    import sys
    if "--census" in sys.argv:
        census("--wide" in sys.argv)
    else:
        tests()
