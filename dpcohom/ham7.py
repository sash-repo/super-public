#!/usr/bin/env python3
"""ham7.py -- the Hamiltonian algebras of [CM] in two indeterminates, p = 2.

g0 = h^(2)(2;n;omega_0) = <x^(i)y^(j) != e> / K.1,   {f,g}_0 = f_y g_x + f_x g_y
g2 = h^(1)(2;n;omega_2) = O(2;n) / K.1,            {f,g}_2 = (1+e){f,g}_0

1) Jacobi, simplicity (Burnside: the associative algebra generated by ad g is
   the full matrix algebra), center, restrictability (Jacobson: (ad_b)^2 inner
   for every basis b), the subspaces P2 = {x | (ad x)^2 inner},
   P4 = {x | (ad x)^4 inner}; ordinary H^1, H^2 with coefficients K and g
   (alternating cochains, blocks by the weight grading).
2) for the restrictable ones: H^n_res via restcx.py (all heights 2), Ext via
   resco.py, the comparison sequence via seq5.py.

All arithmetic exact over F_2 (bitmasks).  Log: ham7.log (single writer, main()).
"""
import sys, os, itertools, time
HERE = os.path.dirname(os.path.abspath(__file__))
