LOG = []


def out(s=""):
    print(s)
    sys.stdout.flush()
    LOG.append(s)


def bits(x):
    i = 0
    while x:
        if x & 1:
            yield i
        x >>= 1
        i += 1


def binom2(a, b):
    """C(a,b) mod 2 (Lucas)"""
    return 1 if (b & ~a) == 0 else 0


# ------------------------------------------------------------- the algebras
def build(n1, n2, which):
    N1, N2 = 2 ** n1, 2 ** n2
    tx, ty = N1 - 1, N2 - 1
    mons = [(i, j) for i in range(N1) for j in range(N2) if (i, j) != (0, 0)]
    if which == 0:
        mons = [m for m in mons if m != (tx, ty)]
    idx = {m: a for a, m in enumerate(mons)}
    d = len(mons)

    def mult(a, b):
        (i, j), (k, l) = a, b
        if i + k > tx or j + l > ty:
            return None
        if binom2(i + k, i) and binom2(j + l, j):
            return (i + k, j + l)
        return None

    def pois(a, b):
        """{a,b}_0 as a set of monomials (constant included)"""
        (i, j), (k, l) = a, b
        res = set()
        # f_y g_x
        if j > 0 and k > 0:
            m = mult((i, j - 1), (k - 1, l))
            if m:
                res ^= {m}
        if i > 0 and l > 0:
            m = mult((i - 1, j), (k, l - 1))
            if m:
                res ^= {m}
        return res

    br = [[0] * d for _ in range(d)]
    bad = []
    for a in range(d):
        for b in range(d):
            r = pois(mons[a], mons[b])
            if which == 2 and (0, 0) in r:
                r ^= {(tx, ty)}
            r.discard((0, 0))
            v = 0
            for m in r:
                if m not in idx:
                    bad.append((mons[a], mons[b], m))
                    continue
                v |= 1 << idx[m]
            br[a][b] = v
    # weights: (i-1, j-1), in Z^2 for g0, mod (tx, ty) for g2
    if which == 0:
        wt = [(i - 1, j - 1) for (i, j) in mons]
        add = lambda u, v: (u[0] + v[0], u[1] + v[1])
    else:
        md = lambda u: (u[0] % tx if tx > 1 else 0, u[1] % ty if ty > 1 else 0)
        wt = [md((i - 1, j - 1)) for (i, j) in mons]
        add = lambda u, v: md((u[0] + v[0], u[1] + v[1]))
    return dict(n=(n1, n2), which=which, mons=mons, d=d, br=br, closure_bad=bad,
                wt=wt, add=add, name="g%d(%d,%d)" % (which, n1, n2))


def vbr(G, u, v):
    br = G["br"]
    o = 0
    for a in bits(u):
        for b in bits(v):
            o ^= br[a][b]
    return o


def jacobi(G):
    d, br = G["d"], G["br"]
    bad = 0
    for i in range(d):
        if br[i][i]:
            bad += 1
        for j in range(i + 1, d):
            if br[i][j] != br[j][i]:
                bad += 1
            for k in range(j + 1, d):
                if vbr(G, 1 << i, br[j][k]) ^ vbr(G, 1 << j, br[k][i]) ^ vbr(G, 1 << k, br[i][j]):
                    bad += 1
    return bad


def grading_ok(G):
    d, br, wt, add = G["d"], G["br"], G["wt"], G["add"]
    for a in range(d):
        for b in range(d):
            w = add(wt[a], wt[b])
            for c in bits(br[a][b]):
                if wt[c] != w:
                    return False
    return True


# matrices: list of d row-bitmasks; ad_a as matrix M with M[i] = row i:
# we store as column images: col[b] = [a, x_b]; then a matrix is "flattened"
def ad_cols(G, a):
    return [G["br"][a][b] for b in range(G["d"])]


def vad_cols(G, v):
    d = G["d"]
    out_ = [0] * d
    for a in bits(v):
        for b in range(d):
            out_[b] ^= G["br"][a][b]
    return out_


def apply_cols(cols, v):
    o = 0
    for b in bits(v):
        o ^= cols[b]
    return o


def compose(A, B):          # A o B, both as column lists
    return [apply_cols(A, c) for c in B]


def flat(cols, d):
    o = 0
    for b, c in enumerate(cols):
        o |= c << (b * d)
    return o


class Span:
    def __init__(self):
        self.piv = {}       # pivot bit -> (vec, comb)

    def add(self, v, comb=0):
        while v:
            h = v.bit_length() - 1
            if h in self.piv:
                pv, pc = self.piv[h]
                v ^= pv
                comb ^= pc
            else:
                self.piv[h] = (v, comb)
                return True
        return False

    def express(self, v):
        comb = 0
        while v:
            h = v.bit_length() - 1
            if h not in self.piv:
                return None
            pv, pc = self.piv[h]
            v ^= pv
            comb ^= pc
        return comb

    def __len__(self):
        return len(self.piv)


def rank(vecs):
    s = Span()
    for v in vecs:
        s.add(v)
    return len(s)


def ad_span(G):
    d = G["d"]
    S = Span()
    for a in range(d):
        S.add(flat(ad_cols(G, a), d), 1 << a)
    return S


def center(G):
    d = G["d"]
    # kernel of v -> ad v (as flattened): rank of ad map
    return d - len(ad_span(G))


def burnside(G):
    """dim of the associative algebra generated by ad g (with 1)"""
    d = G["d"]
    gens = [ad_cols(G, a) for a in range(d)]
    I = [1 << b for b in range(d)]
    S = Span()
    S.add(flat(I, d))
    frontier = [I]
    basis = [I]
    while frontier:
        new = []
        for M in frontier:
            for A in gens:
                P = compose(A, M)
                if S.add(flat(P, d)):
                    new.append(P)
                    basis.append(P)
        frontier = new
        if len(S) == d * d:
            break
    return len(S)


def ideal_dims(G):
    """dims of the ideals generated by each basis vector (sanity)"""
    d = G["d"]
    res = []
    for a in range(d):
        S = Span()
        S.add(1 << a)
        fr = [1 << a]
        while fr:
            nw = []
            for v in fr:
                for b in range(d):
                    w = vbr(G, 1 << b, v)
                    if w and S.add(w):
                        nw.append(w)
            fr = nw
        res.append(len(S))
    return res


def power_inner(G, k):
    """for each basis b: the element z with ad_z = (ad_b)^(2^k), or None.
    Also: the subspace P_{2^k} = {x | (ad x)^{2^k} inner} (as a list of vectors)."""
    d = G["d"]
    A = ad_span(G)
    res = []
    for b in range(d):
        M = ad_cols(G, b)
        P = M
        for _ in range(k):
            P = compose(P, P)
        z = A.express(flat(P, d))
        res.append(z)
    # the subspace P: x |-> (ad x)^{2^k} is semilinear-additive modulo inner
    # (Jacobson), so P = kernel of the F_2-linear map x |-> class of (ad x)^{2^k}
    # in End/ad g.  Compute that linear map on the basis and check additivity
    # on all pairs (cheap sanity).
    imgs = []
    for b in range(d):
        M = ad_cols(G, b)
        P = M
        for _ in range(k):
            P = compose(P, P)
        imgs.append(flat(P, d))
    # reduce imgs modulo ad g
    red = []
    for v in imgs:
        w = v
        while w:
            h = w.bit_length() - 1
            if h in A.piv:
                w ^= A.piv[h][0]
            else:
                break
        # full reduction
        red.append(_reduce_full(A, v))
    # kernel of b -> red[b]
    Sp = Span()
    ker = []
    for b in range(d):
        if not Sp.add(red[b], 1 << b):
            pass
    # kernel vectors: combinations that reduce to 0
    S2 = Span()
    kern = []
    for b in range(d):
        v, comb = red[b], 1 << b
        while v:
            h = v.bit_length() - 1
            if h in S2.piv:
                pv, pc = S2.piv[h]
                v ^= pv
                comb ^= pc
            else:
                S2.piv[h] = (v, comb)
                break
        if v == 0:
            kern.append(comb)
    return res, kern, imgs


def _reduce_full(A, v):
    # reduce v to the normal form modulo span(A) (pivots highest bit)
    changed = True
    w = v
    for h in sorted(A.piv.keys(), reverse=True):
        if (w >> h) & 1:
            w ^= A.piv[h][0]
    return w


def check_additivity(G, k, kern, imgs):
    """(ad (x+y))^{2^k} - (ad x)^{2^k} - (ad y)^{2^k} inner for basis pairs"""
    d = G["d"]
    A = ad_span(G)
    bad = 0
    for a in range(d):
        for b in range(a + 1, d):
            M = vad_cols(G, (1 << a) | (1 << b))
            P = M
            for _ in range(k):
                P = compose(P, P)
            v = flat(P, d) ^ imgs[a] ^ imgs[b]
            if A.express(v) is None:
                bad += 1
    return bad


# ------------------------------------------------- ordinary CE cohomology
def ce_dims(G, coeff, maxdeg=2):
    """dim H^n(g;M), n = 0..maxdeg, M = K or g, alternating cochains,
    by weight blocks."""
    d, br, wt, add = G["d"], G["br"], G["wt"], G["add"]
    zero = (0, 0)
    if coeff == "K":
        Mdim, Mwt = 1, [zero]
        act = lambda i, t: 0
    else:
        Mdim, Mwt = d, wt
        act = lambda i, t: br[i][t]
    neg = lambda u: tuple(-c for c in u) if G["which"] == 0 else \
        G["add"]((0, 0), tuple(-c for c in u))
    pairs_of = {}
    for i in range(d):
        for j in range(i + 1, d):
            for k in bits(br[i][j]):
                pairs_of.setdefault(k, []).append((i, j))

    def swt(S):
        w = zero
        for s in S:
            w = add(w, wt[s])
        return w

    # basis of C^n: (S, t), weight = Mwt[t] - swt(S)
    def basis(n):
        blocks = {}
        for S in itertools.combinations(range(d), n):
            ws = swt(S)
            for t in range(Mdim):
                w = add(Mwt[t], neg(ws))
                blocks.setdefault(w, []).append((S, t))
        return blocks

    bases = [basis(n) for n in range(maxdeg + 2)]

    def dcoch(n, S, t, tidx):
        """image of the cochain (S,t) in C^{n+1}: a bitmask over tidx"""
        o = 0
        Sset = set(S)
        # T = S u {i}: contribution x_i . m_t at T
        for i in range(d):
            if i in Sset:
                continue
            T = tuple(sorted(S + (i,)))
            for t2 in bits(act(i, t) if coeff != "K" else 0):
                key = (T, t2)
                o ^= 1 << tidx[key]
        # T = (S \ {k}) u {i,j}, k in [x_i,x_j]
        for k in S:
            R = Sset - {k}
            for (i, j) in pairs_of.get(k, []):
                if i in R or j in R:
                    continue
                T = tuple(sorted(tuple(R) + (i, j)))
                o ^= 1 << tidx[(T, t)]
        return o

    ranks = []
    for n in range(maxdeg + 1):
        rk = 0
        for w, src in bases[n].items():
            tgt = bases[n + 1].get(w, [])
            tidx = {c: a for a, c in enumerate(tgt)}
            S = Span()
            for (Sx, t) in src:
                S.add(dcoch(n, Sx, t, tidx))
            rk += len(S)
        ranks.append(rk)
    dims = [sum(len(v) for v in bases[n].values()) for n in range(maxdeg + 1)]
    H = []
    for n in range(maxdeg + 1):
        H.append(dims[n] - ranks[n] - (ranks[n - 1] if n else 0))
    return H


# --------------------------------------------- (2,4)-structures, cohomology
def obstruction4(G):
    """basis b with (ad b)^4 NOT in ad g + span{(ad c)^2 | c basis}: such b
    rules out a (2,4)-structure for EVERY Z/2-grading (in u_{2,4}(g) every
    v^4 lies in the restricted closure L = g + g_-^{(2)})"""
    d = G["d"]
    S = Span()
    for a in range(d):
        S.add(flat(ad_cols(G, a), d))
        M = ad_cols(G, a)
        S.add(flat(compose(M, M), d))
    bad = []
    for b in range(d):
        M = ad_cols(G, b)
        P = compose(compose(M, M), compose(M, M))
        if S.express(flat(P, d)) is None:
            bad.append(G["mons"][b])
    return bad


def relabel(G, gp, gm):
    """the bracket in the basis gp + gm (vectors of G), as bitmasks"""
    basis = list(gp) + list(gm)
    n = len(basis)
    E = Span()
    for a, v in enumerate(basis):
        E.add(v, 1 << a)
    br = [[0] * n for _ in range(n)]
    for a in range(n):
        for b in range(n):
            c = E.express(vbr(G, basis[a], basis[b]))
            assert c is not None
            br[a][b] = c
    return br, E


def part24(cases):
    import grade24
    import seq5, runseq
    out()
    out("=" * 78)
    out("(2,4)-STRUCTURES")
    out("=" * 78)
    cand = []
    for (n1, n2) in cases:
        for which in (0, 2):
            G = build(n1, n2, which)
            ob = obstruction4(G)
            line = "%s: (ad b)^4 not in ad g + span (ad c)^2 for b = %s" % (G["name"], ob)
            if not ob and G["d"] <= 15:
                st, res = grade24.structures24(G)
                line += ";  dim Der = %d, idempotent derivations (Z/2-gradings) = %d, " \
                        "with a (2,4)-structure = %d" % (st["dimDer"], st["n_idem"], st["n_ok"])
                if res:
                    cand.append((G, res))
            out(line)
    for (G, res) in cand:
        # prefer a structure spanned by monomials
        mono = [r for r in res if all(bin(v).count("1") == 1 for v in r[0] + r[1])]
        gp, gm, p2, p4 = (mono or res)[0]
        out("-" * 78)
        out("%s with g_+ = %s, g_- = %s" % (G["name"], [[G["mons"][c] for c in bits(v)] for v in gp],
                                            [[G["mons"][c] for c in bits(v)] for v in gm]))
        br, E = relabel(G, gp, gm)
        P2 = [E.express(z) for z in p2]
        P4 = [E.express(z) for z in p4]
        out("   x^[2] (new basis) = %s ;  y^[4] = %s" % (P2, P4))
        dimp, dimm = len(gp), len(gm)
        dim_g = dimp + dimm
        adj = lambda k, v, br=br: runseq.adj(br, k, v)
        seq5.LOG.clear()
        runseq.run("%s  (2,4)-structure" % G["name"], dimp, dimm, br, P2, P4,
                   [("K", 1, lambda k, v: 0), ("g", dim_g, adj)], maxdeg=3)
        for l in seq5.LOG:
            LOG.append(l)
        # independent Ext over u_{2,4}(g) when small
        from restcx import Closure
        if 2 ** dimp * 4 ** dimm <= 64:
            cl = Closure(dimp, dimm, br, P2, P4)
            L = cl.rla()
            for (mn, Mdim, act) in [("K", 1, lambda k, v: 0), ("g", dim_g, adj)]:
                ML = cl.module_L(Mdim, act)
                h = L.cohom(ML, 3)
                e = cl.ext_over_u24(Mdim, act, 4)
                out("   M = %s: H^n of the Gamma(L)-complex, n=0..3 = %s ; Ext^n_{u_{2,4}} = %s ; %s"
                    % (mn, h, e, "AGREE" if list(h) == list(e[:len(h)]) else "MISMATCH"))


# ------------------------------------------------------------------ main
def main():
    t0 = time.time()
    out("ham7.py -- the Hamiltonian algebras in two indeterminates, p = 2")
    cases = [(1, 1), (1, 2), (2, 1), (1, 3), (2, 2), (1, 4), (2, 3)]
    if len(sys.argv) > 1:
        cases = [tuple(int(c) for c in a.split(",")) for a in sys.argv[1:]]
    summary = []
    for (n1, n2) in cases:
        for which in (0, 2):
            G = build(n1, n2, which)
            out("=" * 78)
            out("%s  dim = %d" % (G["name"], G["d"]))
            out("   bracket closes on the basis: %s" %
                ("OK" if not G["closure_bad"] else "NO " + str(G["closure_bad"][:2])))
            out("   Jacobi: %s; weight grading homogeneous: %s"
                % ("OK" if jacobi(G) == 0 else "FAILED", grading_ok(G)))
            z = center(G)
            bd = burnside(G)
            out("   center dim = %d;  dim of assoc. alg. gen. by ad g = %d (d^2 = %d) "
                "=> %s" % (z, bd, G["d"] ** 2,
                           "absolutely simple" if bd == G["d"] ** 2 else "NOT abs. irreducible"))
            if bd != G["d"] ** 2:
                out("   ideal dims generated by basis vectors: %s" % ideal_dims(G))
            r2, P2, im2 = power_inner(G, 1)
            r4, P4, im4 = power_inner(G, 2)
            nb2 = [G["mons"][b] for b in range(G["d"]) if r2[b] is None]
            nb4 = [G["mons"][b] for b in range(G["d"]) if r4[b] is None]
            a2 = check_additivity(G, 1, P2, im2)
            out("   Jacobson additivity of (ad x)^2 mod ad g (pairs failing, must be 0): %d" % a2)
            der = rank([G["br"][a][b] for a in range(G["d"]) for b in range(G["d"])])
            out("   dim [g,g] = %d" % der)
            out("   (ad b)^2 NOT inner for basis b = %s" % nb2)
            out("   dim P2 = {x | (ad x)^2 inner} = %d ;  basis of P2 (as monomial sets): %s"
                % (len(P2), [[G["mons"][c] for c in bits(v)] for v in P2]))
            out("   (ad b)^4 NOT inner for basis b = %s" % nb4)
            out("   (NB (ad x)^4 is NOT additive mod ad g: (ad[x,y])^2 enters)")
            restr = (z == 0 and not nb2)
            out("   RESTRICTABLE (2-structure): %s" % restr)
            if restr:
                out("   [2]: %s" % ["%s^[2] = %s" % (G["mons"][b],
                                                    [G["mons"][c] for c in bits(r2[b])])
                                   for b in range(G["d"])])
            HK = ce_dims(G, "K", 2)
            Hg = ce_dims(G, "g", 2) if G["d"] <= 31 else None
            out("   ordinary H^n(g;K), n=0,1,2: %s" % HK)
            out("   ordinary H^n(g;g), n=0,1,2: %s" % Hg)
            summary.append((G["name"], G["d"], z, bd == G["d"] ** 2, len(P2), sum(1 for z in r4 if z is not None),
                            restr, HK, Hg))
            out("   [%.1fs]" % (time.time() - t0))
    part24(cases)
    out()
    out("SUMMARY: name, dim, center, abs.simple, dim P2, #basis b with (ad b)^4 inner, restrictable, H^*(g;K), H^*(g;g)")
    for s in summary:
        out("   " + str(s))
    with open(os.path.join(HERE, "ham7.log"), "w") as f:
        f.write("\n".join(LOG) + "\n")


if __name__ == "__main__":
    main()
