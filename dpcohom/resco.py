"""resco.py -- restricted enveloping algebras and restricted cohomology as a
derived functor, for the restrictednesses of characteristic 2.

For a restricted Lie algebra Hochschild [Ho] defined H^n_res(g;M) as
Ext^n_{u(g)}(K,M), where u(g) = U(g)/(x^p - x^{[p]}).  Here we do the same for
the two restrictednesses that are peculiar to p = 2, see [BLLS]:

  2-structure:      the classical one,  u_2(g)   = U(g)/(x^2 + x^{[2]});
  (2,4)-structure:  on a Z/2-graded Lie algebra g = g_+ + g_- --- a grading,
                    NOT a superstructure --- a 2-structure on g_+ together with
                    [4]: g_- -> g_+ such that [x^{[4]},y] = (ad_x)^4(y),
                    (ax)^{[4]} = a^4 x^{[4]} and
                    (x+y)^{[4]} = x^{[4]}+y^{[4]}+[x,[x,[x,y]]]+[y,[y,[y,x]]]
                                  +[x,[y,[x,y]]]+[x,y]^{[2]}.
                    We set  u_{2,4}(g) = U(g)/(x^2+x^{[2]} for x in g_+,
                                               y^4+y^{[4]} for y in g_-).

What has to be checked for u_{2,4}(g) to be well defined and of the expected
size (this file does check it):

  (i)   x^2 + x^{[2]} is central in U(g) for x in g_+;
  (ii)  y^4 + y^{[4]} is central in U(g) for y in g_-;
  (iii) the ideal does not depend on the basis: for all y,z in g_-,
        (y+z)^4 + (y+z)^{[4]} lies in the ideal generated by the basis
        elements -- this is exactly the additivity rule above;
  (iv)  dim u_{2,4}(g) = 2^{dim g_+} 4^{dim g_-}.

Then Ext^n_{u}(K,M) is computed from an explicit free resolution over the
finite dimensional algebra u.
"""

import sys
from dpco import bits, span_int, in_span, rank2_int

sys.setrecursionlimit(100000)


class RestAlg:
    """U(g)/(x^{cap_i} + pmap_i) for a Lie algebra g over F_2 with caps."""

    def __init__(self, dim, br, caps, pmap, name="u"):
        self.dim, self.name = dim, name
        self.br = br                      # br[i][j] bitmask, symmetric
        self.caps = caps                  # caps[i] in {2,4}
        self.pmap = pmap                  # pmap[i] = bitmask of x_i^{[cap]}
        self._memo = {}
        self.basis = self._basis()
        self.index = {b: i for i, b in enumerate(self.basis)}

    # -- rewriting ---------------------------------------------------------
    def reduce(self, w):
        w = tuple(w)
        if w in self._memo:
            return self._memo[w]
        pos, kind = -1, None
        for a in range(len(w) - 1):
            if w[a] > w[a + 1]:
                pos, kind = a, "swap"
                break
        if pos < 0:
            # look for a run of length cap
            run, start = 1, 0
            for a in range(1, len(w)):
                if w[a] == w[a - 1]:
                    run += 1
                else:
                    run, start = 1, a
                if run == self.caps[w[a]]:
                    pos, kind = start, "cap"
                    break
        if pos < 0:
            res = frozenset([w])
            self._memo[w] = res
            return res
        out = set()
        if kind == "swap":
            i, j = w[pos], w[pos + 1]
            head, tail = w[:pos], w[pos + 2:]
            out ^= set(self.reduce(head + (j, i) + tail))
            for k in bits(self.br[i][j]):
                out ^= set(self.reduce(head + (k,) + tail))
        else:
            i = w[pos]
            c = self.caps[i]
            head, tail = w[:pos], w[pos + c:]
            for k in bits(self.pmap[i]):
                out ^= set(self.reduce(head + (k,) + tail))
        res = frozenset(out)
        self._memo[w] = res
        return res

    def _basis(self):
        """normal words: nondecreasing, multiplicity of i below caps[i]"""
        out = [()]
        frontier = [()]
        while frontier:
            nxt = []
            for w in frontier:
                start = w[-1] if w else 0
                for k in range(start, self.dim):
                    cand = w + (k,)
                    mult = sum(1 for t in cand if t == k)
                    if mult < self.caps[k]:
                        nxt.append(cand)
            out += nxt
            frontier = nxt
        return out

    def mul(self, x, y):
        """x, y: ints = bitmasks over self.basis"""
        out = 0
        for i in bits(x):
            for j in bits(y):
                for w in self.reduce(self.basis[i] + self.basis[j]):
                    out ^= 1 << self.index[w]
        return out

    def check_associativity(self, sample=None):
        bad = 0
        n = len(self.basis)
        idx = range(n) if sample is None else sample
        for i in idx:
            for j in idx:
                for k in idx:
                    a = self.mul(self.mul(1 << i, 1 << j), 1 << k)
                    b = self.mul(1 << i, self.mul(1 << j, 1 << k))
                    if a != b:
                        bad += 1
        return bad

    def expected_dim(self):
        d = 1
        for c in self.caps:
            d *= c
        return d


# ------------------------------------------------------ Ext over a f.d. algebra

def left_span(A, vecs, width):
    """the A-submodule of A^width generated by vecs (each vec = int over the
    basis of A^width, block j occupying bits [j*n, (j+1)*n) )"""
    n = len(A.basis)
    piv = {}
    queue = list(vecs)
    while queue:
        v = queue.pop()
        w = v
        while w:
            h = w.bit_length() - 1
            if h in piv:
                w ^= piv[h]
            else:
                piv[h] = w
                for a in range(n):        # multiply by every basis element
                    queue.append(act_left(A, a, v, width))
                break
    return piv


def act_left(A, a, v, width):
    """multiply the element v of A^width on the left by the basis element a"""
    n = len(A.basis)
    out = 0
    for j in range(width):
        blk = (v >> (j * n)) & ((1 << n) - 1)
        if blk:
            out ^= A.mul(1 << a, blk) << (j * n)
    return out


def module_gens(A, piv_vectors, width):
    """a generating set of the submodule spanned (as a K-space) by the given
    vectors: greedy"""
    n = len(A.basis)
    gens = []
    cur = {}
    for v in piv_vectors:
        if in_span(cur, v):
            continue
        gens.append(v)
        # extend by A.v
        queue = [v]
        while queue:
            u = queue.pop()
            w = u
            while w:
                h = w.bit_length() - 1
                if h in cur:
                    w ^= cur[h]
                else:
                    cur[h] = w
                    for a in range(n):
                        queue.append(act_left(A, a, u, width))
                    break
    return gens


def kernel_of_map(A, images, width_src, width_dst):
    """kernel of the A-linear map A^{width_src} -> A^{width_dst} sending the
    j-th free generator to images[j]; returned as a K-basis of ints"""
    n = len(A.basis)
    rows = []
    for j in range(width_src):
        for a in range(n):
            src = (1 << a) << (j * n)
            dst = act_left(A, a, images[j], width_dst)
            rows.append((src, dst))
    piv = {}
    ker = []
    for (src, dst) in rows:
        cur, comb = dst, src
        while cur:
            h = cur.bit_length() - 1
            if h in piv:
                cur ^= piv[h][0]
                comb ^= piv[h][1]
            else:
                piv[h] = (cur, comb)
                break
        if cur == 0:
            ker.append(comb)
    return ker


def resolution(A, length):
    """a free resolution ... -> A^{r_1} -> A^{r_0}=A -> K; returns the list of
    lists of images (each image an int over A^{r_{i-1}})"""
    n = len(A.basis)
    eps_kernel = []                        # augmentation ideal
    # the augmentation sends the empty word to 1 and every other word to 0
    empty = A.index[()]
    for i in range(n):
        if i != empty:
            eps_kernel.append(1 << i)
    maps = []
    width_prev = 1
    gens = module_gens(A, eps_kernel, 1)
    maps.append(gens)
    for _ in range(length - 1):
        width = len(gens)
        ker = kernel_of_map(A, gens, width, width_prev)
        newgens = module_gens(A, ker, width)
        maps.append(newgens)
        width_prev = width
        gens = newgens
    return maps


def ext_dims(A, maps, Mact, Mdim, length):
    """dim Ext^i_A(K,M), i = 0..length-1.  Mact(a_basis_index, v) applies the
    basis element a of A to the M-vector v (int)."""
    # Hom_A(A^{r}, M) = M^{r}; the differential Hom(P_{i-1},M) -> Hom(P_i,M)
    # sends (m_1..m_{r_{i-1}}) to ( sum_k images[j][k] . m_k )_j
    n = len(A.basis)
    widths = [1] + [len(g) for g in maps]
    mats = []
    for i, gens in enumerate(maps):
        src_w, dst_w = widths[i], len(gens)
        rows = []
        for k in range(src_w):
            for t in range(Mdim):
                col = 0
                for j, img in enumerate(gens):
                    blk = (img >> (k * n)) & ((1 << n) - 1)
                    val = 0
                    for a in bits(blk):
                        val ^= Mact(a, 1 << t)
                    col |= val << (j * Mdim)
                rows.append(col)
        mats.append((rows, src_w * Mdim, dst_w * Mdim))
    out = []
    for i in range(length):
        if i == 0:
            dim_i = Mdim
            prev_rank = 0
        else:
            dim_i = widths[i] * Mdim
            prev_rank = rank2_int(mats[i - 1][0])
        cur_rank = rank2_int(mats[i][0]) if i < len(mats) else 0
        out.append(dim_i - cur_rank - prev_rank)
    return out


def module_action(A, act_gen, Mdim):
    """extend the action of the generators of g to all of A by multiplication:
    act_gen[k](v) applies the k-th generator.  Returns Mact(a, v) for a a
    basis index of A."""
    cache = {}

    def Mact(a, v):
        w = A.basis[a]
        key = (w, v)
        if key in cache:
            return cache[key]
        out = v
        for k in reversed(w):
            out = act_gen(k, out)
        cache[key] = out
        return out
    return Mact
