"""The Shapovalov determinant of ns(2), and the Boucher--Friedan--Kent formula.

The Verma module over ns(2) is bigraded: by the level n (the eigenvalue of L_0
below the highest weight) and by the charge m relative to that of the highest
weight vector, since the maximal torus is spanned by L_0 and T_0 and hence
sdim t = (2|0).  So the determinant is Sh_{n,m}, a polynomial in h, q and t,
and NOT a polynomial in h and c alone as in the ns(1) case.

Here the determinant is computed from scratch for every (n, m) with n <= NMAX,
factored over Q(t)[h, q], and compared with the vanishing surfaces
   h = h_{r,s},   r in Z_{>0}, s in 2 Z_{>0},
   h = h_k,       k in Z + 1/2,
of Boucher--Friedan--Kent.  The exponents are read off the factorization and
compared with the dimensions of the weight spaces of the Verma module and of
the submodule generated by a charged singular vector.
"""

import sys
import sympy
from verma import NS2, Module, h, q, t

LOG = open("run-ns2.log", "w")


def say(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    LOG.write(s + "\n")
    LOG.flush()


C = 3 - 3 * t


def h_rs(r, s):
    return (sympy.Rational(r ** 2 - 1, 8) * t - sympy.Rational(r * s, 4)
            + sympy.Rational(s ** 2 - 1, 8) / t - (4 * q ** 2 - 1) / (8 * t))


def h_k(k):
    k = sympy.Rational(k)
    return k * q + sympy.Rational(1, 2) * t * (k ** 2 - sympy.Rational(1, 4))


def verma_dims(NMAX):
    """p(n, m) = dim of the (level n, relative charge m) weight space of M."""
    # generating function prod_{j>=1}(1-x^j)^{-2} prod_{r>=1/2}(1+z x^r)(1+z^-1 x^r)
    from collections import defaultdict
    cur = defaultdict(int)
    cur[(sympy.Integer(0), 0)] = 1
    half = sympy.Rational(1, 2)

    def mul_boson(step):
        nonlocal cur
        new = defaultdict(int)
        for (n, m), v in cur.items():
            k = 0
            while n + k * step <= NMAX:
                new[(n + k * step, m)] += v
                k += 1
        cur = new

    def mul_fermion(step, chg):
        nonlocal cur
        new = defaultdict(int)
        for (n, m), v in cur.items():
            new[(n, m)] += v
            if n + step <= NMAX:
                new[(n + step, m + chg)] += v
        cur = new

    j = 1
    while j <= NMAX:
        mul_boson(sympy.Integer(j))   # L_{-j}
        mul_boson(sympy.Integer(j))   # T_{-j}
        j += 1
    r = half
    while r <= NMAX:
        mul_fermion(r, +1)            # G^+_{-r}
        mul_fermion(r, -1)            # G^-_{-r}
        r += 1
    return cur


def run(NMAX=2):
    say("=" * 74)
    say("ns(2): the Shapovalov determinant, c = 3 - 3t, weight (h, q)")
    say("=" * 74)
    alg = NS2(2 * NMAX + 6, C)
    M = Module(alg)
    dims = verma_dims(sympy.Rational(NMAX))

    lev = sympy.Rational(1, 2)
    while lev <= NMAX:
        charges = sorted({m for (n, m) in dims if n == lev})
        for m in charges:
            b, G = M.gram(lev, m)
            if not b:
                continue
            det = sympy.together(sympy.expand(G.det()))
            det = sympy.factor(sympy.simplify(det))
            say("")
            say("level %s, relative charge %+d : dim = %d  (p(n,m) = %s)"
                % (lev, m, len(b), dims.get((lev, m), 0)))
            say("   basis = %s" % (b,))
            say("   det   = %s" % det)
            if det == 0:
                continue
            # which vanishing surfaces divide it, and with which multiplicity
            found = []
            for r in range(1, 4 * NMAX + 3):
                for s in range(2, 4 * NMAX + 3, 2):
                    if r * s > 2 * NMAX + 2:
                        continue
                    fac = sympy.together(h - h_rs(r, s))
                    fac = sympy.numer(sympy.cancel(fac))
                    e = multiplicity(det, fac)
                    if e:
                        found.append(("f", r, s, e))
            kk = sympy.Rational(1, 2)
            while kk <= NMAX + sympy.Rational(1, 2):
                for sgn in (+1, -1):
                    k = sgn * kk
                    fac = sympy.together(h - h_k(k))
                    fac = sympy.numer(sympy.cancel(fac))
                    e = multiplicity(det, fac)
                    if e:
                        found.append(("g", k, None, e))
                kk += 1
            for it in found:
                if it[0] == "f":
                    say("   (h - h_{%d,%d})^%d" % (it[1], it[2], it[3]))
                else:
                    say("   (h - h_{k})^%d   with k = %s" % (it[3], it[1]))
            if not found:
                say("   *** no vanishing surface of the BFK list divides it ***")
        lev += sympy.Rational(1, 2)


def multiplicity(poly, fac):
    """the exact multiplicity of the irreducible ``fac`` in ``poly``."""
    P = sympy.Poly(sympy.numer(sympy.cancel(sympy.together(poly))), h, q)
    F = sympy.Poly(sympy.expand(fac), h, q)
    if F.is_zero:
        return 0
    e = 0
    while True:
        Qq, R = sympy.div(P, F)
        if R.is_zero and not Qq.is_zero:
            P = Qq
            e += 1
            if e > 40:
                break
        else:
            break
    return e


if __name__ == "__main__":
    run(int(sys.argv[1]) if len(sys.argv) > 1 else 2)
