"""Weight 6 over Q[c]: projections modulo dV_5 of the weight-6 elements of the Lie conformal algebra
generated by T and Lambda, from products of length <= 3.  Prints the gcd of the 2x2 minors.
Theorem 11.7.3, heading 1) ("if" part): the gcd is (c+2)(5c+22) up to a constant.  Run:  python3 w6sym.py"""
import sys, itertools
import os; sys.path[:0] = [os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"), os.path.dirname(os.path.abspath(__file__))]
from gensym import conv, C, lin, wt
from va import VA, parts
from fractions import Fraction as Fr
from exactlin import solve, rank
import sympy as sp
V = VA(C, conv)
T = {(2,): conv(1)}; LAM = {(2, 2): conv(1), (4,): conv(Fr(-3, 5))}
def mode(a, j, b):
    r = V.mode(a, j, b); return {k: v for k, v in r.items() if k != ()}
def d(a): return V.L(-1, a)
# all elements of C in weights <= 10 from products of length <= 3 (incl. d)
gens = {2: [T], 4: [LAM]}
def wof(st): return sum(next(iter(st))) if st else None
lvl2 = []
for a, b in itertools.product([T, LAM], repeat=2):
    for j in range(0, 8):
        r = mode(a, j, b)
        if r: lvl2.append(r)
lvl3 = []
for a in [T, LAM]:
    for b in lvl2:
        for j in range(0, 14):
            r = mode(a, j, b)
            if r and wof(r) == 6: lvl3.append(r)
w6 = [r for r in lvl2 if wof(r) == 6] + lvl3
print("weight-6 elements:", len(w6))
V6, V5 = parts(6), parts(5)
dimg = [[d({u: conv(1)}).get(q, conv(0)) for q in V6] for u in V5]
dimgF = [[Fr(int(x.coeffs()[0].p), int(x.coeffs()[0].q)) if x != 0 else Fr(0) for x in r] for r in dimg]
# K_6 coordinates: complement monomials
sel = []
cur = list(dimgF)
for p in V6:
    row = [Fr(1) if q == p else Fr(0) for q in V6]
    if rank(cur + [row]) > rank(cur): cur.append(row); sel.append(p)
M = [list(col) for col in zip(*([[Fr(1) if q == p else Fr(0) for q in V6] for p in sel] + dimgF))]
inv = {q: solve(M, [Fr(1) if q2 == q else Fr(0) for q2 in V6]) for q in V6}
c = sp.Symbol('c')
def topoly(p):
    return sum(sp.Rational(int(q.p), int(q.q)) * c**i for i, q in enumerate(p.coeffs())) if p != 0 else sp.Integer(0)
rows = []
for st in w6:
    a = [sp.Integer(0)] * len(sel)
    for q, v in st.items():
        for i in range(len(sel)):
            a[i] += topoly(v) * inv[q][i]
    rows.append([sp.expand(x) for x in a])
Mx = sp.Matrix(rows)
print("rank over Q(c):", Mx.rank())
g = 0
for i, j in itertools.combinations(range(len(rows)), 2):
    m = sp.expand(Mx[i, 0] * Mx[j, 1] - Mx[i, 1] * Mx[j, 0])
    if m != 0: g = sp.gcd(g, m) if g != 0 else m
print("gcd of 2x2 minors:", sp.factor(g))
