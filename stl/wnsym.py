"""Weight n over Q[c]: quasi-primary projections (mod dV_{n-1}) of elements of the Lie conformal
algebra generated by T and Lambda, from products of length <= L (all j-products, no truncation
other than weight <= Wmax).  Prints the generic rank and the gcd of the maximal minors (sampled: a multiple of the gcd of
all of them, so its roots contain all values of c where the rank drops).
Theorem 11.7.3, headings 2) and 3) ("if" parts): python3 wnsym.py 8 4 8 and python3 wnsym.py 9 4 9.
Problem 11.7.6 (products of length <= 4 reach a 2-dimensional subspace of K_10): wnsym.py 10 4 10."""
import sys, itertools, random
import os; sys.path[:0] = [os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"), os.path.dirname(os.path.abspath(__file__))]
from gensym import conv, C
from va import VA, parts
from fractions import Fraction as Fr
from exactlin import solve, rank
import sympy as sp
n = int(sys.argv[1]); L = int(sys.argv[2]); Wmax = int(sys.argv[3])
V = VA(C, conv)
T = {(2,): conv(1)}; LAM = {(2, 2): conv(1), (4,): conv(Fr(-3, 5))}
def mode(a, j, b):
    r = V.mode(a, j, b); return {k: v for k, v in r.items() if k != ()}
def wof(st): return sum(next(iter(st)))
levels = {1: [T, LAM]}
for l in range(2, L + 1):
    out = []
    for l1 in range(1, l):
        l2 = l - l1
        for a in levels[l1]:
            for b in levels[l2]:
                wa, wb = wof(a), wof(b)
                for j in range(0, wa + wb):
                    w = wa + wb - j - 1
                    if w < 2 or w > Wmax: continue
                    r = mode(a, j, b)
                    if r: out.append(r)
    levels[l] = out
    print("length", l, ":", len(out), flush=True)
wn = [r for l in levels for r in levels[l] if wof(r) == n]
print("weight-%d elements:" % n, len(wn))
Vn, Vm = parts(n), parts(n - 1)
dimgF = []
for u in Vm:
    dd = V.L(-1, {u: conv(1)})
    dimgF.append([Fr(int(dd[q].coeffs()[0].p), int(dd[q].coeffs()[0].q)) if q in dd else Fr(0) for q in Vn])
sel = []; cur = list(dimgF)
for p in Vn:
    row = [Fr(1) if q == p else Fr(0) for q in Vn]
    if rank(cur + [row]) > rank(cur): cur.append(row); sel.append(p)
M = [list(col) for col in zip(*([[Fr(1) if q == p else Fr(0) for q in Vn] for p in sel] + dimgF))]
inv = {q: solve(M, [Fr(1) if q2 == q else Fr(0) for q2 in Vn]) for q in Vn}
c = sp.Symbol('c')
def topoly(p):
    return sum(sp.Rational(int(q.p), int(q.q)) * c**i for i, q in enumerate(p.coeffs())) if p != 0 else sp.Integer(0)
rows = []
for st in wn:
    a = [sp.Integer(0)] * len(sel)
    for q, v in st.items():
        P = topoly(v)
        for i in range(len(sel)):
            if inv[q][i]: a[i] += P * inv[q][i]
    rows.append([sp.expand(x) for x in a])
Mx = sp.Matrix(rows)
k = len(sel)
r = Mx.rank(); print("dim K_%d =" % n, k, " rank over Q(c):", r)
random.seed(0); g = 0; tries = 0
idx = list(range(len(rows)))
while tries < 300:
    rs = random.sample(idx, k); tries += 1
    m = sp.expand(Mx.extract(rs, list(range(k))).det())
    if m != 0: g = sp.gcd(g, m) if g != 0 else m
    if g != 0 and sp.degree(g, c) == 0: break
print("gcd of maximal minors (sampled):", sp.factor(g), flush=True)
