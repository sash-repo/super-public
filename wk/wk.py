#!/usr/bin/env python3
"""wk.py -- the Weisfeiler-Kac bound in characteristic 2, exactly.

The question: what replaces
    max dim of an irrep with a highest weight vector = p^{(dim g - dim t)/2}
when p = 2 and g carries not a 2-structure but a (2,4)-structure, e.g., for
the series o^{(1)}_I(2n+1) (Sect. 3 of the text).

Everything here is exact arithmetic over F_{2^k}; nothing is sampled.

What is built and checked:

  A.  The series g = o^{(1)}_I(2n+1) of [BLLS, Subsec. 2.6.1, Example 1] as
          g = {M in gl(2n+1) | G M is symmetric with zero diagonal},
      G the antidiagonal-with-a-middle-1 Gram matrix.  Verified: closure under
      the bracket; dim = n(2n+1); simplicity (n = 1, 2, 3); the Z-grading by
      the toral element D = diag(d, 0, -d), whose zero part is exactly the
      maximal torus of dim n; and, for each basis vector, whether its square
      lies in g (a 2-element) or not (a 4-element).  The 4-elements are
      exactly the 2n vectors of the X- and Y-blocks -- n of them in n_-.

  B.  The restricted closure L = g + g_-^{(2)} of [LLo, Theorem 4.3] (Subsec. 2.2 of the text) inside
      u_{2,4}(g), realized here by honest matrices: dim L = dim g + dim g_-.
      For n = 1 this is the 5-dimensional algebra whose superization
      ("method 2") is the simple Lie superalgebra oo^{(1)}_{IPi}(1|2), Sect. 4.

  C.  The induced module M(lambda) = u_{2,4}(g) (x)_{u(b)} K_lambda for the
      Borel b = t + n_+, realized as the span of the ordered monomials in n_-
      with a letter of order 2 used at most once and one of order 4 at most
      three times.  The action is computed by straightening in U(g); it is
      then CHECKED to be a representation (rho[x]rho[y] + rho[y]rho[x] =
      rho[[x,y]] on all pairs of basis vectors) and to be a module over the
      reduced enveloping algebra (rho(y)^{order} = 0, rho(h)^2 + rho(h) scalar).

  D.  Irreducibility: M(lambda) is irreducible iff its space of n_+-singular
      vectors is 1-dimensional (every nonzero submodule contains a singular
      vector, and M is generated by the highest weight vector).  This is a
      kernel computation, so the whole census is exact linear algebra.

Usage:  a library; the runs proper are in run.py, crit.py, crit3.py,
        torus.py, index.py, ham.py
"""

import itertools
import sys

# --------------------------------------------------------------------------
# F_{2^k}: elements are ints, the bits being the coefficients of a polynomial
# --------------------------------------------------------------------------

_PRIMPOLY = {1: 0b11, 2: 0b111, 3: 0b1011, 4: 0b10011, 5: 0b100101,
             6: 0b1000011}


class GF:
    """The field F_{2^k}."""

    def __init__(self, k):
        self.k = k
        self.q = 1 << k
        self.poly = _PRIMPOLY[k]
        self.els = list(range(self.q))
        self.name = "F_%d" % self.q
        self._inv = [0] * self.q
        for a in range(1, self.q):
            for b in range(1, self.q):
                if self.mul(a, b) == 1:
                    self._inv[a] = b
                    break

    def add(self, a, b):
        return a ^ b

    sub = add

    def mul(self, a, b):
        r = 0
        while b:
            if b & 1:
                r ^= a
            b >>= 1
            a <<= 1
            if a >> self.k & 1:
                a ^= self.poly
        return r

    def inv(self, a):
        assert a != 0
        return self._inv[a]

    def div(self, a, b):
        return self.mul(a, self.inv(b))

    def pw(self, a, n):
        r = 1
        for _ in range(n):
            r = self.mul(r, a)
        return r


# --------------------------------------------------------------------------
# linear algebra over GF: row reduction with a pivot dictionary
# --------------------------------------------------------------------------

class Space:
    """The row space of the vectors fed to it, kept in reduced echelon form."""

    def __init__(self, F, dim):
        self.F = F
        self.dim = dim
        self.piv = {}          # pivot column -> reduced row

    def reduce(self, v):
        v = list(v)
        F = self.F
        for c in sorted(self.piv):
            if v[c]:
                a, r = v[c], self.piv[c]
                for j in range(self.dim):
                    if r[j]:
                        v[j] = F.add(v[j], F.mul(a, r[j]))
        return v

    def add(self, v):
        """Add v; return True if it enlarged the space."""
        v = self.reduce(v)
        F = self.F
        for c in range(self.dim):
            if v[c]:
                a = F.inv(v[c])
                v = [F.mul(a, x) for x in v]
                for c2 in list(self.piv):
                    r = self.piv[c2]
                    if r[c]:
                        b = r[c]
                        self.piv[c2] = [F.add(r[j], F.mul(b, v[j]))
                                        for j in range(self.dim)]
                self.piv[c] = v
                return True
        return False

    def __contains__(self, v):
        return not any(self.reduce(v))

    def rank(self):
        return len(self.piv)

    def basis(self):
        return [self.piv[c] for c in sorted(self.piv)]

    def coords(self, v, gens):
        """Express v in terms of the list gens (assumed independent)."""
        F = self.F
        n = len(gens)
        rows = [list(gens[i]) + [1 if j == i else 0 for j in range(n)]
                for i in range(n)]
        rhs = list(v) + [0] * n
        S = Space(F, self.dim + n)
        for r in rows:
            S.add(r)
        red = S.reduce(rhs)
        assert not any(red[:self.dim]), "vector not in the span"
        return [F.add(0, red[self.dim + i]) for i in range(n)]


def nullspace(F, rows, ncols):
    """A basis of {v | rows . v = 0}, v of length ncols."""
    S = Space(F, ncols)
    for r in rows:
        S.add(r)
    piv = sorted(S.piv)
    free = [c for c in range(ncols) if c not in S.piv]
    out = []
    for f in free:
        v = [0] * ncols
        v[f] = 1
        for c in piv:
            v[c] = S.piv[c][f]
        out.append(v)
    return out


# --------------------------------------------------------------------------
# matrices over GF
# --------------------------------------------------------------------------

def mat_zero(m):
    return [[0] * m for _ in range(m)]


def mat_mul(F, A, B):
    m = len(A)
    C = mat_zero(m)
    for i in range(m):
        Ai = A[i]
        Ci = C[i]
        for k in range(m):
            a = Ai[k]
            if a:
                Bk = B[k]
                for j in range(m):
                    if Bk[j]:
                        Ci[j] = F.add(Ci[j], F.mul(a, Bk[j]))
    return C


def mat_add(F, A, B):
    return [[F.add(A[i][j], B[i][j]) for j in range(len(A))]
            for i in range(len(A))]


def mat_comm(F, A, B):
    return mat_add(F, mat_mul(F, A, B), mat_mul(F, B, A))   # p = 2


def flat(A):
    return [x for row in A for x in row]


def unflat(v, m):
    return [list(v[i * m:(i + 1) * m]) for i in range(m)]


# --------------------------------------------------------------------------
# a Lie algebra given by a basis of matrices
# --------------------------------------------------------------------------

class MatAlg:
    """A Lie algebra of matrices over F, with structure constants."""

    def __init__(self, F, basis, names=None):
        self.F = F
        self.m = len(basis[0])
        self.basis = basis
        self.n = len(basis)
        self.names = names or ["e%d" % i for i in range(self.n)]
        self._space = Space(F, self.m * self.m)
        for b in basis:
            assert self._space.add(flat(b)), "the basis is dependent"
        self._flat = [flat(b) for b in basis]
        self.struct = None

    # -- coordinates -------------------------------------------------------
    def in_alg(self, A):
        return flat(A) in self._space

    def coords(self, A):
        return self._space.coords(flat(A), self._flat)

    def to_mat(self, v):
        F = self.F
        M = mat_zero(self.m)
        for i, c in enumerate(v):
            if c:
                B = self.basis[i]
                for r in range(self.m):
                    for s in range(self.m):
                        if B[r][s]:
                            M[r][s] = F.add(M[r][s], F.mul(c, B[r][s]))
        return M

    # -- structure constants ----------------------------------------------
    def build_struct(self):
        F = self.F
        self.struct = [[None] * self.n for _ in range(self.n)]
        for i in range(self.n):
            for j in range(self.n):
                C = mat_comm(F, self.basis[i], self.basis[j])
                assert self.in_alg(C), "not closed: [%s,%s]" % (
                    self.names[i], self.names[j])
                self.struct[i][j] = self.coords(C)
        return self.struct

    def bracket(self, u, v):
        F = self.F
        out = [0] * self.n
        for i, a in enumerate(u):
            if not a:
                continue
            for j, b in enumerate(v):
                if not b:
                    continue
                c = F.mul(a, b)
                row = self.struct[i][j]
                for k in range(self.n):
                    if row[k]:
                        out[k] = F.add(out[k], F.mul(c, row[k]))
        return out

    def ad(self, u):
        """The matrix of ad_u in the basis (columns = images)."""
        cols = [self.bracket(u, [1 if j == i else 0 for j in range(self.n)])
                for i in range(self.n)]
        return [[cols[j][i] for j in range(self.n)] for i in range(self.n)]

    # -- simplicity --------------------------------------------------------
    def ideal_generated(self, v):
        S = Space(self.F, self.n)
        S.add(v)
        changed = True
        while changed:
            changed = False
            for w in list(S.basis()):
                for i in range(self.n):
                    e = [1 if j == i else 0 for j in range(self.n)]
                    if S.add(self.bracket(e, w)):
                        changed = True
        return S.rank()

    def is_simple(self):
        """Exhaustive over F_2-points; enough for algebras defined over F_2."""
        for coef in itertools.product([0, 1], repeat=self.n):
            if not any(coef):
                continue
            if self.ideal_generated(list(coef)) != self.n:
                return False, list(coef)
        return True, None


# --------------------------------------------------------------------------
# A. the series o^{(1)}_I(2n+1)
# --------------------------------------------------------------------------

def oI(F, n, weights=None):
    """o^{(1)}_I(2n+1) = {M | GM symmetric with zero diagonal}, with the
    Z-grading by D = diag(d_1..d_n, 0, -d_1..-d_n).

    Returns (alg, deg, sigma) with deg[i] the degree of the i-th basis vector.
    The basis is M_{ij} = G(E_ij + E_ji) for i < j, of degree -(w_i + w_j).
    """
    m = 2 * n + 1
    if weights is None:
        weights = list(range(1, n + 1))
    w = weights + [0] + [-d for d in reversed(weights)]
    # sigma: the involution swapping i and m-1-i (0-based)
    sigma = [m - 1 - i for i in range(m)]
    # careful: index n+1+i of the docstring is m-1-i in 0-based reversed order
    # so the weight of index sigma(i) must be -w[i]:
    assert all(w[sigma[i]] == -w[i] for i in range(m))
    basis, names, deg = [], [], []
    for i in range(m):
        for j in range(i + 1, m):
            A = mat_zero(m)
            # G(E_ij + E_ji) = E_{sigma(i),j} + E_{sigma(j),i}
            A[sigma[i]][j] = F.add(A[sigma[i]][j], 1)
            A[sigma[j]][i] = F.add(A[sigma[j]][i], 1)
            basis.append(A)
            names.append("M%d,%d" % (i, j))
            deg.append(-(w[i] + w[j]))
    alg = MatAlg(F, basis, names)
    return alg, deg


def order_of(alg, i):
    """2 if the i-th basis vector squares inside the algebra, else 4."""
    F = alg.F
    S = mat_mul(F, alg.basis[i], alg.basis[i])
    return 2 if alg.in_alg(S) else 4


# --------------------------------------------------------------------------
# B. the restricted closure L = g + g_-^{(2)}
# --------------------------------------------------------------------------

def restricted_closure(alg):
    """L = Span(g, {y^2 | y a 4-element}), as matrices.  Returns (L, is_odd)
    with is_odd[i] the parity of the i-th basis vector of L for the
    superization by method 2 (the 4-elements become odd)."""
    F = alg.F
    S = Space(F, alg.m * alg.m)
    basis, odd = [], []
    for i in range(alg.n):
        S.add(flat(alg.basis[i]))
        basis.append(alg.basis[i])
        odd.append(order_of(alg, i) == 4)
    for i in range(alg.n):
        if order_of(alg, i) == 4:
            Q = mat_mul(F, alg.basis[i], alg.basis[i])
            if S.add(flat(Q)):
                basis.append(Q)
                odd.append(False)
    return MatAlg(F, basis), odd


# --------------------------------------------------------------------------
# C. the induced module
# --------------------------------------------------------------------------

class Induced:
    """M(lambda) = u_{2,4}(g) (x)_{u(t + n_+)} K_lambda.

    neg  -- the list of indices of the basis vectors spanning n_-, in the
            order in which the monomials are written (leftmost first);
    orders[r] -- 2 or 4, the order of the r-th generator of n_-;
    tor  -- the indices spanning the torus t;
    pos  -- the indices spanning n_+;
    lam[s] -- lambda(t_s) in F.

    The squares/fourth powers of the generators of n_- are assumed to vanish
    (asserted below); this is the character chi that vanishes on n_- + n_+.
    """

    def __init__(self, alg, neg, orders, tor, pos, lam):
        self.g = alg
        self.F = alg.F
        self.neg, self.orders, self.tor, self.pos = neg, orders, tor, pos
        self.lam = lam
        self.k = len(neg)
        # basis of the module: exponent tuples
        self.mons = [tuple(a) for a in
                     itertools.product(*[range(o) for o in orders])]
        self.index = {a: i for i, a in enumerate(self.mons)}
        self.dim = len(self.mons)
        self._lmul = {}
        self._act = {}
        # chi = 0 on n_-: the generators are nilpotent of their own order
        for r, i in enumerate(neg):
            P = alg.basis[i]
            for _ in range(orders[r] - 1):
                P = mat_mul(self.F, P, alg.basis[i])
            assert not any(any(row) for row in P), \
                "generator %d is not nilpotent of order %d" % (i, orders[r])

    # -- vectors of the module are dicts {monomial index: coefficient} ------
    def _addto(self, d, i, c):
        if not c:
            return
        v = self.F.add(d.get(i, 0), c)
        if v:
            d[i] = v
        elif i in d:
            del d[i]

    def _scale(self, d, c):
        if c == 1:
            return dict(d)
        return {i: self.F.mul(c, x) for i, x in d.items() if self.F.mul(c, x)}

    def _combine(self, ds):
        out = {}
        for c, d in ds:
            for i, x in d.items():
                self._addto(out, i, self.F.mul(c, x))
        return out

    # -- left multiplication by the r-th generator of n_- -------------------
    def lmul(self, r, mon):
        key = (r, mon)
        if key in self._lmul:
            return self._lmul[key]
        first = next((s for s in range(self.k) if mon[s] > 0), None)
        if first is None or first >= r:
            a = list(mon)
            a[r] += 1
            res = {} if a[r] >= self.orders[r] else {self.index[tuple(a)]: 1}
        else:
            s = first
            rest = list(mon)
            rest[s] -= 1
            rest = tuple(rest)
            # y_r y_s w = y_s y_r w + [y_r, y_s] w
            part = self.lmul(r, rest)
            res = {}
            for i, c in part.items():
                for j, c2 in self.lmul(s, self.mons[i]).items():
                    self._addto(res, j, self.F.mul(c, c2))
            br = self.g.bracket(self._e(self.neg[r]), self._e(self.neg[s]))
            for j, c in self._neg_coords(br):
                for i, c2 in self.lmul(j, rest).items():
                    self._addto(res, i, self.F.mul(c, c2))
        self._lmul[key] = res
        return res

    def _e(self, i):
        return [1 if j == i else 0 for j in range(self.g.n)]

    def _neg_coords(self, v):
        """v must lie in n_-; return [(r, coeff)]."""
        for i in range(self.g.n):
            if v[i] and i not in self.neg:
                raise AssertionError("bracket left n_-")
        return [(r, v[i]) for r, i in enumerate(self.neg) if v[i]]

    def _lmul_vec(self, v, d):
        """left multiplication by an element v of n_- of a module vector d."""
        out = {}
        for r, c in self._neg_coords(v):
            for i, x in d.items():
                for j, y in self.lmul(r, self.mons[i]).items():
                    self._addto(out, j, self.F.mul(c, self.F.mul(x, y)))
        return out

    # -- the action of a general element of g ------------------------------
    def act(self, v, mon):
        """v a coordinate vector in g, mon a monomial: v . (mon . v_lambda)."""
        key = (tuple(v), mon)
        if key in self._act:
            return self._act[key]
        F = self.F
        first = next((s for s in range(self.k) if mon[s] > 0), None)
        if first is None:
            # act on the highest weight vector
            res = {}
            for r, c in [(r, v[i]) for r, i in enumerate(self.neg) if v[i]]:
                a = [0] * self.k
                a[r] = 1
                self._addto(res, self.index[tuple(a)], c)
            lamv = 0
            for s, i in enumerate(self.tor):
                if v[i]:
                    lamv = F.add(lamv, F.mul(v[i], self.lam[s]))
            if lamv:
                self._addto(res, self.index[tuple([0] * self.k)], lamv)
            # n_+ kills v_lambda: nothing to add
        else:
            s = first
            rest = list(mon)
            rest[s] -= 1
            rest = tuple(rest)
            # x y_s w = y_s (x w) + [x, y_s] w
            inner = self.act(v, rest)
            res = self._lmul_vec(self._e(self.neg[s]), inner)
            br = self.g.bracket(v, self._e(self.neg[s]))
            for i, c in self.act(br, rest).items():
                self._addto(res, i, c)
        self._act[key] = res
        return res

    def matrix(self, v):
        """The matrix of the action of v: columns indexed by monomials."""
        cols = [self.act(list(v), mon) for mon in self.mons]
        M = [[0] * self.dim for _ in range(self.dim)]
        for j, d in enumerate(cols):
            for i, c in d.items():
                M[i][j] = c
        return M

    # -- checks ------------------------------------------------------------
    def check_representation(self):
        F = self.F
        rho = [self.matrix(self._e(i)) for i in range(self.g.n)]
        for i in range(self.g.n):
            for j in range(i, self.g.n):
                lhs = mat_comm(F, rho[i], rho[j])
                rhs = self.matrix(self.g.struct[i][j])
                if lhs != rhs:
                    return False, (i, j)
        return True, None

    def singular(self):
        """A basis of {m | n_+ m = 0}."""
        rows = []
        for i in self.pos:
            M = self.matrix(self._e(i))
            rows.extend(M)
        return nullspace(self.F, rows, self.dim)

    def submodule(self, vec):
        """The dimension of the submodule generated by a module vector."""
        S = Space(self.F, self.dim)
        S.add(vec)
        changed = True
        rho = [self.matrix(self._e(i)) for i in range(self.g.n)]
        while changed:
            changed = False
            for w in list(S.basis()):
                for M in rho:
                    img = [0] * self.dim
                    for i in range(self.dim):
                        acc = 0
                        for j in range(self.dim):
                            if M[i][j] and w[j]:
                                acc = self.F.add(acc, self.F.mul(M[i][j], w[j]))
                        img[i] = acc
                    if S.add(img):
                        changed = True
        return S.rank()


# --------------------------------------------------------------------------
# gradings: split a graded algebra into n_-, t, n_+
# --------------------------------------------------------------------------

def triangular(alg, deg):
    neg = [i for i in range(alg.n) if deg[i] < 0]
    tor = [i for i in range(alg.n) if deg[i] == 0]
    pos = [i for i in range(alg.n) if deg[i] > 0]
    # order n_- so that deg increases (leftmost letters of lowest degree)
    neg.sort(key=lambda i: (deg[i], i))
    return neg, tor, pos


# --------------------------------------------------------------------------
# sl(m) at p = 2 -- the test case with an invertible Cartan matrix
# --------------------------------------------------------------------------

def sl(F, m):
    """sl(m) for m odd (so that it is simple at p = 2), graded by
    D = diag(d_1..d_m) with d generic."""
    d = [3 ** i for i in range(m)]
    basis, deg = [], []
    for i in range(m):
        for j in range(m):
            if i == j:
                continue
            A = mat_zero(m)
            A[i][j] = 1
            basis.append(A)
            deg.append(d[i] - d[j])
    for i in range(m - 1):
        A = mat_zero(m)
        A[i][i] = 1
        A[i + 1][i + 1] = 1
        basis.append(A)
        deg.append(0)
    return MatAlg(F, basis), deg
