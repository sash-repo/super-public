def part_A():
    head("A.  the series o^{(1)}_I(2n+1) at p = 2")
    F = GF(1)
    out("  n | dim g | dim t | dim n_- | 2-elts in n_- | 4-elts in n_- |"
        " dim M(lambda) = 2^(n^2+n)")
    for n in range(1, 6):
        alg, deg = oI(F, n)
        alg.build_struct()
        neg, tor, pos = triangular(alg, deg)
        orders = [order_of(alg, i) for i in neg]
        two, four = orders.count(2), orders.count(4)
        pred = 2 ** two * 4 ** four
        out("  %d | %5d | %5d | %7d | %13d | %13d | %d = 2^%d"
            % (n, alg.n, len(tor), len(neg), two, four, pred,
               pred.bit_length() - 1))
        assert alg.n == n * (2 * n + 1)
        assert len(tor) == n and len(neg) == n * n
        assert two == n * (n - 1) and four == n
        assert pred == 2 ** (n * n + n)
    out()
    out("  So dim g_- = n^2 as over C, but n of the n^2 negative root vectors")
    out("  are 4-elements: their squares are the DIAGONAL of the C-block,")
    out("  which the zero diagonal of a symmetric matrix excludes from g.")
    out()
    out("  simplicity (exhaustive over the F_2-points; for n >= 3 the count")
    out("  2^{n(2n+1)} of those points makes the sweep pointless, and the")
    out("  simplicity of the series is [BLLS, Subsec. 2.6.1] anyway):")
    for n in (1, 2):
        alg, deg = oI(F, n)
        alg.build_struct()
        t0 = time.time()
        ok, bad = alg.is_simple()
        out("    n = %d: simple = %s   (%.1f s)" % (n, ok, time.time() - t0))


def part_B():
    head("B.  the induced modules M(lambda) and their irreducible quotients")
    for k in (2, 3):
        F = GF(k)
        alg, deg = oI(F, 1)
        alg.build_struct()
        neg, tor, pos = triangular(alg, deg)
        orders = [order_of(alg, i) for i in neg]
        out("  n = 1 over %s: dim M = 4 for every lambda" % F.name)
        seen = set()
        for lam in itertools.product(F.els, repeat=len(tor)):
            M = Induced(alg, neg, orders, tor, pos, list(lam))
            ok, bad = M.check_representation()
            assert ok, bad
            rad = max_submodule(M)
            irr = M.dim - rad.rank()
            sing = len(M.singular())
            out("    lambda = %s : dim of the singular space %d,"
                " maximal submodule %d, irreducible quotient %d"
                % (lam[0], sing, rad.rank(), irr))
            seen.add(irr)
            seen.add(rad.rank() if rad.rank() in (1, 3) else irr)
        out("    dimensions met: %s   (Dolotkazin: 1, 3, 4)"
            % sorted(x for x in seen if x))
    out()
    F = GF(3)
    alg, deg = oI(F, 2)
    alg.build_struct()
    neg, tor, pos = triangular(alg, deg)
    orders = [order_of(alg, i) for i in neg]
    out("  n = 2 over %s: dim M = %d for every lambda; orders in n_- = %s"
        % (F.name, 2 ** orders.count(2) * 4 ** orders.count(4), orders))
    irred = 0
    checked = False
    for lam in itertools.product(F.els, repeat=len(tor)):
        M = Induced(alg, neg, orders, tor, pos, list(lam))
        if not checked:
            ok, bad = M.check_representation()
            assert ok, bad
            out("    the action is a representation: verified on all %d pairs"
                % (alg.n * (alg.n + 1) // 2))
            checked = True
        s = len(M.singular())
        if s == 1:
            irred += 1
    out("    M(lambda) is irreducible (a 1-dimensional singular space) for %d"
        " of the %d weights over %s" % (irred, F.q ** len(tor), F.name))
    out("    hence max dim of an irrep with a highest weight vector = 64 ="
        " 2^(2^2+2)")


def part_C():
    head("C.  the same modules read over the superization")
    for n in (1, 2):
        F = GF(3)
        alg, deg = oI(F, n)
        alg.build_struct()
        neg, tor, pos = triangular(alg, deg)
        orders = [order_of(alg, i) for i in neg]
        odd_gens = [r for r in range(len(neg)) if orders[r] == 4]
        out("  n = %d: the odd generators of n_- are %s (the 4-elements)"
            % (n, odd_gens))
        for lam in itertools.product(F.els, repeat=len(tor)):
            M = Induced(alg, neg, orders, tor, pos, list(lam))
            par = parities(M, alg, odd_gens)
            if n == 1:
                rad = max_submodule(M)
                basis = [[1 if j == i else 0 for j in range(M.dim)]
                         for i in range(M.dim)]
                se, so = sdim_of(basis, par, F, M.dim)
                re, ro = sdim_of(rad.basis(), par, F, M.dim) if rad.rank() \
                    else (0, 0)
                out("    lambda = %s : sdim M = (%d|%d), sdim of the maximal"
                    " submodule = (%d|%d), sdim of the irreducible quotient ="
                    " (%d|%d)" % (lam[0], se, so, re, ro, se - re, so - ro))
            else:
                if len(M.singular()) == 1:
                    ev = sum(1 for p in par if p == 0)
                    od = sum(1 for p in par if p == 1)
                    out("    lambda = %s : M irreducible, sdim = (%d|%d)"
                        % (list(lam), ev, od))
                    break


def part_D():
    head('D.  the superization by "method 2"')
    F = GF(1)
    for n in (1, 2, 3):
        S, L, odd, g = method2(F, n)
        out("  n = %d: sdim s(o^{(1)}_I(%d)) = (%d|%d), dim = %d = dim g + %d"
            % (n, 2 * n + 1, S.nev, S.nod, S.n, 2 * n))
        if n <= 2:
            ok, bad = S.check_axioms()
            out("      the axioms of a Lie superalgebra at p = 2: %s" % ok)
            out("      simple: %s" % S.is_simple()[0])
        out("      the span of the squares of the odd elements has rank %d"
            % S.square_image_rank())
        # g is a submodule of the adjoint module, but not an ideal
        Lm = L
        gsp = Space(F, Lm.m * Lm.m)
        for b in g.basis:
            gsp.add(flat(b))
        inv = all(gsp.__contains__(flat(_comm(F, Lm.basis[i], b)))
                  for i in range(Lm.n) for b in g.basis)
        closed = all(gsp.__contains__(flat(mat_mul(F, b, b)))
                     for i, b in enumerate(g.basis) if order_of(g, i) == 4)
        out("      g is ad-invariant in s(g): %s;  closed under the squaring:"
            " %s" % (inv, closed))
        out("      so the adjoint module of the simple superalgebra s(g) has"
            " the proper submodule g, of codimension %d" % (2 * n))
    out()
    out("  identification for n = 1 (exhaustive over the parity-preserving")
    out("  isomorphisms over F_2):")
    S, L, odd, g = method2(F, 1)
    for t in ("Pi", "I"):
        A, _, _ = oo(F, 1, 1, type1=t, derived=True)
        out("    s(o^{(1)}_I(3)) =~ oo^{(1)}_{I%s}(1|2) : %s"
            % (t, iso(S, A)))
    out()
    out("  identification for n = 2:")
    S2, L2, odd2, g2 = method2(F, 2)
    for (a, b) in ((1, 2), (2, 1), (3, 1)):
        try:
            A, _, _ = oo(F, a, b, type1="Pi", derived=True)
        except Exception as e:                       # pragma: no cover
            out("    oo^{(1)}_{IPi}(%d|%d): %s" % (a, 2 * b, e))
            continue
        out("    oo^{(1)}_{IPi}(%d|%d) has sdim (%d|%d)%s"
            % (a, 2 * b, A.nev, A.nod,
               "  <-- same format" if (A.nev, A.nod) == (S2.nev, S2.nod)
               else ""))


def _comm(F, A, B):
    from wk import mat_comm
    return mat_comm(F, A, B)


def part_E():
    head("E.  sl(m) at p = 2, m odd: an invertible Cartan matrix")
    for m in (3, 5):
        F = GF(3)
        alg, deg = sl(F, m)
        alg.build_struct()
        neg, tor, pos = triangular(alg, deg)
        orders = [order_of(alg, i) for i in neg]
        assert set(orders) == {2}, orders
        pred = 2 ** len(neg)
        out("  sl(%d): dim = %d, dim t = %d, dim n_- = %d, all 2-elements,"
            " so dim M = 2^%d = %d = 2^((dim g - dim t)/2)"
            % (m, alg.n, len(tor), len(neg), len(neg), pred))
        best = 0
        nlam = 0
        for lam in itertools.product(F.els, repeat=len(tor)):
            M = Induced(alg, neg, orders, tor, pos, list(lam))
            if nlam == 0:
                ok, bad = M.check_representation()
                assert ok, bad
            nlam += 1
            if len(M.singular()) == 1:
                best = M.dim
                out("    lambda = %s gives an irreducible M(lambda) of"
                    " dimension %d" % (list(lam), M.dim))
                break
        if not best:
            out("    no irreducible induced module over %s" % F.name)


def main():
    LOG[0] = open("run.log", "w")
    t0 = time.time()
    part_A()
    part_B()
    part_C()
    part_D()
    part_E()
    out()
    out("total %.1f s" % (time.time() - t0))
    LOG[0].close()


if __name__ == "__main__":
    main()
