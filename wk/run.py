#!/usr/bin/env python3
"""run.py -- the census behind Sects. 3-6 of the text (Lemma 3.1.1,
Theorem 3.2.1, Statements 3.2.2, 4.2.2, 6.1.1, Propositions 4.1.1, 5.1.1).  Everything exact.

  A  the series o^{(1)}_I(2n+1): dimensions, torus, the Z-grading, and which
     basis vectors are 2- and which are 4-elements;
  B  the induced modules M(lambda) and their irreducible quotients: for n = 1
     this reproduces Dolotkazin's list 1, 3, 4;
  C  the parities: the same modules read over the superization;
  D  the superization s(o^{(1)}_I(2n+1)) by "method 2", its identification for
     n = 1, and the reducibility of its adjoint module;
  E  sl(m) at p = 2, m odd -- a restricted algebra with an invertible Cartan
     matrix, where the classical WK count survives.

Output: run.log
"""

import itertools
import sys
import time

from wk import (GF, Induced, Space, oI, order_of, restricted_closure, sl,
                triangular, mat_mul, flat)
from oo import SuperAlg, method2, oo, iso

LOG = [None]


def out(s=""):
    print(s, flush=True)
    if LOG[0]:
        LOG[0].write(s + "\n")
        LOG[0].flush()


def head(t):
    out()
    out("=" * 78)
    out(t)
    out("=" * 78)


# --------------------------------------------------------------------------
def parities(mod, alg, odd_gens):
    """the parity of each monomial: the number of odd letters, mod 2."""
    return [sum(a[r] for r in odd_gens) % 2 for a in mod.mons]


def max_submodule(mod):
    """the maximal proper submodule = the sum of the proper ones generated by
    the singular vectors."""
    S = Space(mod.F, mod.dim)
    for s in mod.singular():
        if mod.submodule(s) < mod.dim:
            # add the whole submodule generated by s
            T = Space(mod.F, mod.dim)
            T.add(s)
            changed = True
            rho = [mod.matrix(mod._e(i)) for i in range(mod.g.n)]
            while changed:
                changed = False
                for w in list(T.basis()):
                    for M in rho:
                        img = [0] * mod.dim
                        for i in range(mod.dim):
                            acc = 0
                            for j in range(mod.dim):
                                if M[i][j] and w[j]:
                                    acc = mod.F.add(acc,
                                                    mod.F.mul(M[i][j], w[j]))
                            img[i] = acc
                        if T.add(img):
                            changed = True
            for b in T.basis():
                S.add(b)
    return S


def sdim_of(vectors, par, F, dim):
    """(even|odd) dimensions of a subspace given by a basis, the ambient basis
    being parity-homogeneous."""
    ev = [i for i in range(dim) if par[i] == 0]
    od = [i for i in range(dim) if par[i] == 1]
    Se = Space(F, len(ev))
    So = Space(F, len(od))
    for v in vectors:
        Se.add([v[i] for i in ev])
        So.add([v[i] for i in od])
    return Se.rank(), So.rank()


