"""Invariant polydifferential operators on the line: the exact engine.

The category.  For a weight $\\lambda$ let $\\cF_\\lambda=\\{f(dx)^\\lambda\\}$ be the
$\\fvect(1)$-module of weighted densities,
    L_X(f(dx)^lam) = (xi f' + lam xi' f)(dx)^lam   for X = xi(x) d/dx.
An n-linear differential operator
    D(u_1,...,u_n) = sum_z c_z u_1^(z_1)...u_n^(z_n) (dx)^nu,   |z| = k,
from cF_{a_1} (x) ... (x) cF_{a_n} to cF_nu is invariant iff nu = sum a_i + k
(homogeneity, i.e. invariance under x d/dx) and, for every q >= 2 and every
w in N_0^n with |w| = k-q+1,

    sum_i [ C(w_i+q-1, q) + a_i*C(w_i+q-1, q-1) ] * c_{w+(q-1)e_i} = 0.        (INV)

This is derived in the text; it is nothing but the coefficient of xi^{(q)} in
L_X D = sum_i D(...,L_X u_i,...).  Conditions q=2,3 already imply the rest
(fvect(1) is generated by d/dx, x^2 d/dx, x^3 d/dx), but we impose all of them:
they are consequences, so this only costs time, never rigour.

Everything is exact: Fraction arithmetic throughout, ranks via exactlin.py.
"""

import sys
import os
from fractions import Fraction
from functools import lru_cache
from itertools import combinations

from exactlin import rank, nullspace  # noqa: E402


# ---------------------------------------------------------------- multi-indices

@lru_cache(maxsize=None)
def midx(n, k):
    """All z in N_0^n with |z| = k, in a fixed order."""
    if n == 0:
        return ((),) if k == 0 else ()
    out = []
    for first in range(k + 1):
        for rest in midx(n - 1, k - first):
            out.append((first,) + rest)
    return tuple(out)


@lru_cache(maxsize=None)
def binom(n, k):
    if k < 0 or n < 0 or k > n:
        return 0
    r = 1
    for i in range(k):
        r = r * (n - i) // (i + 1)
    return r


# ------------------------------------------------------------ invariant spaces

def _inv_matrix(weights, k):
    """Rows of the system (INV); columns indexed by midx(n,k)."""
    n = len(weights)
    cols = midx(n, k)
    pos = {z: j for j, z in enumerate(cols)}
    rows = []
    for q in range(2, k + 2):
        for w in midx(n, k - q + 1):
            row = [Fraction(0)] * len(cols)
            nonzero = False
            for i in range(n):
                z = list(w)
                z[i] += q - 1
                coeff = (Fraction(binom(w[i] + q - 1, q))
                         + weights[i] * Fraction(binom(w[i] + q - 1, q - 1)))
                if coeff:
                    row[pos[tuple(z)]] += coeff
                    nonzero = True
            if nonzero:
                rows.append(row)
    return cols, rows


@lru_cache(maxsize=None)
def inv_space(weights, k):
    """Basis of the space of invariant n-linear operators of order k.

    weights: tuple of Fractions (or ints).  Returns a tuple of basis vectors,
    each a tuple of Fractions indexed by midx(n,k).
    """
    weights = tuple(Fraction(a) for a in weights)
    if k < 0:
        return ()
    cols, rows = _inv_matrix(weights, k)
    if not rows:
        # no condition at all: the whole space
        return tuple(tuple(Fraction(1) if i == j else Fraction(0)
                           for i in range(len(cols)))
                     for j in range(len(cols)))
    ker = nullspace(rows)
    return tuple(tuple(Fraction(x) for x in v) for v in ker)


def inv_dim(weights, k):
    return len(inv_space(weights, k))


# ---------------------------------------------------------------- compositions

def derivative(vec, n, k, m):
    """d^m/dx^m of the polydifferential expression `vec` (order k, n arguments).

    Returns the coefficient vector of an expression of order k+m, indexed by
    midx(n, k+m).  Leibniz: distribute the m derivatives over the n factors.
    """
    src = midx(n, k)
    dst = midx(n, k + m)
    pos = {z: j for j, z in enumerate(dst)}
    out = [Fraction(0)] * len(dst)
    for z, c in zip(src, vec):
        if not c:
            continue
        for alpha in midx(n, m):
            mult = 1
            rem = m
            for a in alpha:
                mult *= binom(rem, a)
                rem -= a
            tgt = tuple(z[i] + alpha[i] for i in range(n))
            out[pos[tgt]] += c * mult
    return out


def multiply(vecs, blocks, n, orders):
    """Substitute: given r expressions, form their pointwise product.

    vecs[j] is a coefficient vector in the variables of blocks[j] (a tuple of
    argument indices), of order orders[j].  Returns the coefficient vector of
    the product in all n variables, of order sum(orders).
    """
    k = sum(orders)
    dst = midx(n, k)
    pos = {z: j for j, z in enumerate(dst)}
    out = [Fraction(0)] * len(dst)

    def rec(j, acc, coeff):
        if j == len(vecs):
            out[pos[tuple(acc)]] += coeff
            return
        blk = blocks[j]
        for z, c in zip(midx(len(blk), orders[j]), vecs[j]):
            if not c:
                continue
            for t, i in enumerate(blk):
                acc[i] += z[t]
            rec(j + 1, acc, coeff * c)
            for t, i in enumerate(blk):
                acc[i] -= z[t]

    rec(0, [0] * n, Fraction(1))
    return out


def compose(E, Evec_order, Dlist, blocks, orders, n):
    """The composite E(D_1(f_{S_1}), ..., D_r(f_{S_r})) as a coefficient vector.

    E is the coefficient vector of an r-linear operator of order Evec_order.
    Dlist[j] is the coefficient vector of D_j (order orders[j]) in the
    variables blocks[j].  The result has order sum(orders) + Evec_order.
    """
    r = len(Dlist)
    k = sum(orders) + Evec_order
    dst = midx(n, k)
    pos = {z: j for j, z in enumerate(dst)}
    out = [Fraction(0)] * len(dst)
    # cache the derivatives of each D_j
    dcache = [{} for _ in range(r)]
    for m, e in zip(midx(r, Evec_order), E):
        if not e:
            continue
        pieces = []
        ords = []
        for j in range(r):
            if m[j] not in dcache[j]:
                dcache[j][m[j]] = derivative(Dlist[j], len(blocks[j]),
                                             orders[j], m[j])
            pieces.append(dcache[j][m[j]])
            ords.append(orders[j] + m[j])
        prod = multiply(pieces, blocks, n, ords)
        for idx, c in enumerate(prod):
            if c:
                out[idx] += e * c
    return out


# ------------------------------------------------------------- set partitions

def set_partitions(items):
    items = list(items)
    if not items:
        yield []
        return
    first, rest = items[0], items[1:]
    for smaller in set_partitions(rest):
        for i in range(len(smaller)):
            yield smaller[:i] + [[first] + smaller[i]] + smaller[i + 1:]
        yield [[first]] + smaller


# ------------------------------------------------------- decomposable subspace

def decomposable(weights, k, verbose=False):
    """Span of the non-trivial composites inside inv_space(weights, k).

    A composite is  E(D_1(f_{S_1}),...,D_r(f_{S_r}))  with {S_j} a partition of
    the arguments, every D_j and E invariant.  Two factorizations are trivial
    and are excluded, since they reproduce the operator itself:
      * r = n, every block a singleton and every D_j the identity (then E = D);
      * r = 1, S_1 everything and E the identity (then D_1 = D).
    Returns (basis_of_the_span, list_of_witnesses).
    """
    weights = tuple(Fraction(a) for a in weights)
    n = len(weights)
    cols = midx(n, k)
    span = []          # rows, kept in echelon-free form; rank computed at the end
    witness = []
    for part in set_partitions(range(n)):
        blocks = [tuple(sorted(b)) for b in part]
        r = len(blocks)
        allsingle = all(len(b) == 1 for b in blocks)
        # orders k_1..k_r of the inner operators
        for orders in _order_tuples(blocks, weights, k):
            ksum = sum(orders)
            kE = k - ksum
            if kE < 0:
                continue
            if r == 1 and kE == 0:
                continue                      # E = identity
            if allsingle and ksum == 0:
                continue                      # all D_j = identity
            bases = [inv_space(tuple(weights[i] for i in b), o)
                     for b, o in zip(blocks, orders)]
            if any(len(b) == 0 for b in bases):
                continue
            outw = tuple(sum(weights[i] for i in b) + o
                         for b, o in zip(blocks, orders))
            Ebas = inv_space(outw, kE)
            if not Ebas:
                continue
            for E in Ebas:
                for combo in _cartesian(bases):
                    vec = compose(E, kE, list(combo), blocks, list(orders), n)
                    if any(vec):
                        span.append(vec)
                        witness.append((blocks, tuple(orders), kE))
    if not span:
        return [], []
    if not verbose:
        return span, witness
    # which shapes actually contribute: greedy, one rank per vector (slow)
    basis, keep = _independent(span)
    return basis, [witness[i] for i in keep]


def _cartesian(lists):
    if not lists:
        yield ()
        return
    for head in lists[0]:
        for tail in _cartesian(lists[1:]):
            yield (head,) + tail


def _order_tuples(blocks, weights, k):
    """All (k_1,...,k_r) with k_j >= 0 and sum <= k, pruned by emptiness."""
    r = len(blocks)
    ranges = []
    for b in blocks:
        w = tuple(weights[i] for i in b)
        ok = [o for o in range(k + 1) if inv_dim(w, o) > 0]
        ranges.append(ok)
    out = []

    def rec(j, acc, tot):
        if j == r:
            out.append(tuple(acc))
            return
        for o in ranges[j]:
            if tot + o > k:
                break
            acc.append(o)
            rec(j + 1, acc, tot + o)
            acc.pop()

    rec(0, [], 0)
    return out


def _independent(vectors):
    """Greedy: keep the vectors that raise the rank."""
    basis = []
    keep = []
    cur = 0
    for i, v in enumerate(vectors):
        trial = basis + [list(v)]
        rk = rank(trial)
        if rk > cur:
            basis = trial
            cur = rk
            keep.append(i)
    return basis, keep


def atoms(weights, k):
    """(dim inv, dim decomposable, witnesses)."""
    full = inv_space(weights, k)
    if not full:
        return 0, 0, []
    dec, wit = decomposable(weights, k)
    dfull = len(full)
    ddec = rank([list(v) for v in dec]) if dec else 0
    return dfull, ddec, wit


def atom_dim(weights, k):
    d, dd, _ = atoms(weights, k)
    return d - dd


# --------------------------------------------------------------------- pretty

def show(vec, n, k, names=None):
    names = names or [f"u{i+1}" for i in range(n)]
    terms = []
    for z, c in zip(midx(n, k), vec):
        if not c:
            continue
        mon = "".join(names[i] + ("" if z[i] == 0 else f"^({z[i]})")
                      for i in range(n))
        terms.append(f"{c}*{mon}")
    return " + ".join(terms) if terms else "0"
