# (4b) the vacuum:  q ~ 1/(m z-tilde) plus graded corrections
# ---------------------------------------------------------------------------


def ztilde():
    """z-tilde = x-tilde^+ - x-tilde^- = z - (eta rho)/2 summed over all four
    planes: killed by both cD_- and both bD_+."""
    out = mono(1)
    for (e, r) in ((1, 2), (3, 4), (5, 6), (7, 8)):
        out = add(out, mono(0, 0, 0, (e, r), Q(-1, 2)))
    return out


def seed_q():
    """q = 1/(m z-tilde) . 1: satisfies the constraints of (IK4) exactly."""
    inv = inv_scalar(mul(M_MONO, ztilde()), mono(1, 0, 1))
    return [[inv, {}], [{}, inv]]


def graded_entry_monos(zlo, zhi):
    """Grade-0, w-free monomials z^a m^{a+|S|/2} theta_S, S even."""
    out = []
    for r in (0, 2, 4, 6, 8):
        for S in itertools.combinations(MI + PL, r):
            for a in range(zlo, zhi + 1):
                out.append(mono(a, 0, a + r // 2, S))
    return out


def constrained_graded_basis(zlo=-5, zhi=0, verbose=True):
    """A basis of the (C-)constrained 2x2 matrices over the graded window --
    complete over that window, computed sparsely per charge component."""
    ms = graded_entry_monos(zlo, zhi)

    def comps(q):
        L = []
        for g in (0, 1):
            u = (q[g][0], q[g][1])
            L += [cDm(1, u[0]), cDm(2, u[1]),
                  add(cDm(1, u[1]), cDm(2, u[0]))]
        for b in (0, 1):
            v = (q[0][b], q[1][b])
            L += [bDp(1, v[0]), bDp(2, v[1]),
                  add(bDp(1, v[1]), bDp(2, v[0]))]
        return L

    cols = []
    where = []
    for g in (0, 1):
        for b in (0, 1):
            for mo in ms:
                q = mzero()
                q[g][b] = mo
                col = {}
                for i, f in enumerate(comps(q)):
                    for k, c in f.items():
                        col[(i, k)] = c
                cols.append(col)
                where.append((g, b, mo))
    if verbose:
        log("      constrained_graded_basis: %d candidate monomials" %
            len(cols))
    basis = []
    for v in sparse_null(cols):
        q = mzero()
        for j, c in enumerate(v):
            if c:
                g, b, mo = where[j]
                q[g][b] = add(q[g][b], smul(c, mo))
        basis.append(q)
    if verbose:
        log("      constrained_graded_basis: dimension %d (real-doubled)"
            % len(basis))
    return basis


