def x_minus(d=1):
    """(x^-)^d = ((w - z)/2)^d as a ring element, d >= 0."""
    out = mono()
    base = smul(Q(1, 2), sub(mono(0, 1, 0), mono(1, 0, 0)))
    for _ in range(d):
        out = mul(out, base)
    return out


def x_plus(d=1):
    out = mono()
    base = smul(Q(1, 2), add(mono(0, 1, 0), mono(1, 0, 0)))
    for _ in range(d):
        out = mul(out, base)
    return out


def half_solutions(hi, which):
    """A basis of the even doublets satisfying the one-half constraint,
    over the polynomial window of x-degrees 0..hi.

    which = 'minus': cD_-^{(a} psi^{b)} = 0  (row of Qt, upper index);
    which = 'plus' : bD_{+(a} A_{g)} = 0     (column of P, lower index)."""
    if which == "minus":
        D = cDm
        odds = MI
        xpow = x_minus
    else:
        D = bDp
        odds = PL
        xpow = x_plus

    keys = []
    for a in range(0, hi + 1):
        for r in (0, 2, 4):
            for S in itertools.combinations(odds, r):
                keys.append((a, S))
    monos = [mul(xpow(a), mono(S=S)) for (a, S) in keys]

    # the three constraint components, per candidate doublet (u1, u2)
    outkeys = set()
    for g in monos:
        for f in (D(1, g), D(2, g)):
            outkeys |= set(f.keys())
    outkeys = sorted(outkeys)
    oidx = {k: i for i, k in enumerate(outkeys)}
    n = len(outkeys)

    # unknowns: 2 * len(monos)  (coefficients of u1 and of u2)
    # equations: 3 blocks of n
    ncols = 2 * len(monos)
    A = [[C() for _ in range(ncols)] for _ in range(3 * n)]
    for j, g in enumerate(monos):
        d1, d2 = D(1, g), D(2, g)
        for k, c in d1.items():
            A[0 * n + oidx[k]][2 * j] += c          # D1 u1 = 0
            A[1 * n + oidx[k]][2 * j + 1] += c      # D1 u2 + D2 u1 = 0
        for k, c in d2.items():
            A[1 * n + oidx[k]][2 * j] += c
            A[2 * n + oidx[k]][2 * j + 1] += c      # D2 u2 = 0
    sols = []
    for vec in cnull(A):
        u1, u2 = {}, {}
        for j in range(len(monos)):
            if vec[2 * j]:
                u1 = add(u1, smul(vec[2 * j], monos[j]))
            if vec[2 * j + 1]:
                u2 = add(u2, smul(vec[2 * j + 1], monos[j]))
        if u1 or u2:
            sols.append((u1, u2))
    return sols


def half_solutions_full(hi, which):
    """The FULL hypermultiplet shortening on a doublet: the constraint (9)
    of (IK4) together with its consequence (9') of the reality condition
    (12) of [IvKr4] -- without (9'), the m-expansion of the system is
    obstructed at first order (apply cD_+^{(a'} to E2: the left-hand side
    dies, so cD_+^{(a} bar q^{a')} = 0 is forced on solutions).

    which = 'minus' (doublet u^b, upper index):
        cD^{(a} u^{b)} = 0   and   bD_{(a} (eps u)_{b)} = 0,
    i.e.  cD1 u1 = cD2 u2 = cD1 u2 + cD2 u1 = 0  and
          bD1 u2 = bD2 u1 = bD1 u1 - bD2 u2 = 0;
    which = 'plus' (doublet A_g, lower index): the bD/cD mirror."""
    if which == "minus":
        D1 = lambda f: cDm(1, f)
        D2 = lambda f: cDm(2, f)
        E1_ = lambda f: bDm(1, f)
        E2_ = lambda f: bDm(2, f)
        odds = MI
        xpow = x_minus
    else:
        D1 = lambda f: bDp(1, f)
        D2 = lambda f: bDp(2, f)
        E1_ = lambda f: cDp(1, f)
        E2_ = lambda f: cDp(2, f)
        odds = PL
        xpow = x_plus

    keys = []
    for a in range(0, hi + 1):
        for r in (0, 2, 4):
            for S in itertools.combinations(odds, r):
                keys.append((a, S))
    monos = [mul(xpow(a), mono(S=S)) for (a, S) in keys]

    outkeys = set()
    for g in monos:
        for op in (D1, D2, E1_, E2_):
            outkeys |= set(op(g).keys())
    outkeys = sorted(outkeys)
    oidx = {k: i for i, k in enumerate(outkeys)}
    n = len(outkeys)

    ncols = 2 * len(monos)
    A = [[C() for _ in range(ncols)] for _ in range(6 * n)]
    for j, g in enumerate(monos):
        d1, d2, e1, e2 = D1(g), D2(g), E1_(g), E2_(g)
        for k, c in d1.items():
            A[0 * n + oidx[k]][2 * j] += c          # D1 u1 = 0
            A[1 * n + oidx[k]][2 * j + 1] += c      # D1 u2 + D2 u1 = 0
        for k, c in d2.items():
            A[1 * n + oidx[k]][2 * j] += c
            A[2 * n + oidx[k]][2 * j + 1] += c      # D2 u2 = 0
        for k, c in e1.items():
            A[3 * n + oidx[k]][2 * j + 1] += c      # E1 u2 = 0
            A[4 * n + oidx[k]][2 * j] += c          # E1 u1 - E2 u2 = 0
        for k, c in e2.items():
            A[5 * n + oidx[k]][2 * j] += c          # E2 u1 = 0
            A[4 * n + oidx[k]][2 * j + 1] -= c
    sols = []
    for vec in cnull(A):
        u1, u2 = {}, {}
        for j in range(len(monos)):
            if vec[2 * j]:
                u1 = add(u1, smul(vec[2 * j], monos[j]))
            if vec[2 * j + 1]:
                u2 = add(u2, smul(vec[2 * j + 1], monos[j]))
        if u1 or u2:
            sols.append((u1, u2))
    return sols


def qbar_constraints(q):
    """The (9')-families on bar q: cD_+^{(a} bar q_b^{a')} = 0 and
    bD_{-(b} bar q_{b')}^a = 0; returns the number of violated components."""
    bq = qbar(q)
    bad = 0
    for b in (0, 1):                              # upper (plus) index
        v = (bq[b][0], bq[b][1])
        if not eq(cDp(1, v[0]), {}):
            bad += 1
        if not eq(cDp(2, v[1]), {}):
            bad += 1
        if not eq(add(cDp(1, v[1]), cDp(2, v[0])), {}):
            bad += 1
    for a in (0, 1):                              # lower (minus) index
        v = (bq[0][a], bq[1][a])
        if not eq(bDm(1, v[0]), {}):
            bad += 1
        if not eq(bDm(2, v[1]), {}):
            bad += 1
        if not eq(add(bDm(1, v[1]), bDm(2, v[0])), {}):
            bad += 1
    return bad


# --- sparse linear algebra, split by connected components -------------------
#
# Columns are sparse dicts {outkey: C}.  In the eta/rho frame every operator
# is charge-homogeneous, so the column-row incidence graph falls apart into
# many small components; each is solved densely on its own.


def _components(cols, extra_keys=()):
    parent = {}

    def find(x):
        parent.setdefault(x, x)
        root = x
        while parent[root] != root:
            root = parent[root]
        while parent[x] != root:
            parent[x], x = root, parent[x]
        return root

    def union(x, y):
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[rx] = ry

    for j, col in enumerate(cols):
        ks = list(col.keys())
        node = ("c", j)
        parent.setdefault(node, node)
        for k in ks:
            parent.setdefault(("k", k), ("k", k))
            union(node, ("k", k))
    for k in extra_keys:
        parent.setdefault(("k", k), ("k", k))
    comp = {}
    for x in list(parent):
        comp.setdefault(find(x), []).append(x)
    return comp


def sparse_solve(cols, target):
    """Solve sum_j x_j cols[j] = target; cols sparse dicts, target sparse.
    Returns list of C or None."""
    comp = _components(cols, target.keys())
    # target keys must lie in components; keys in no column's component are
    # unmatched unless the target coefficient there is 0
    x = [C() for _ in cols]
    keycomp = {}
    for root, members in comp.items():
        for mm in members:
            if mm[0] == "k":
                keycomp[mm[1]] = root
    groups = {}
    for j, col in enumerate(cols):
        if not col:
            continue
        root = keycomp[next(iter(col.keys()))]
        groups.setdefault(root, []).append(j)
    tgroups = {}
    for k, v in target.items():
        tgroups.setdefault(keycomp[k], {})[k] = v
    for root, tg in tgroups.items():
        js = groups.get(root, [])
        if not js:
            return None
        keys = sorted({k for j in js for k in cols[j]} | set(tg))
        kidx = {k: i for i, k in enumerate(keys)}
        sub_cols = []
        for j in js:
            v = [C() for _ in keys]
            for k, c in cols[j].items():
                v[kidx[k]] = c
            sub_cols.append(v)
        tv = [tg.get(k, C()) for k in keys]
        sol = csolve(sub_cols, tv)
        if sol is None:
            return None
        for j, c in zip(js, sol):
            x[j] = x[j] + c
    return x


def sparse_null(cols):
    """Null space of the sparse column family; vectors as dense C-lists."""
    comp = _components(cols)
    keycomp = {}
    for root, members in comp.items():
        for mm in members:
            if mm[0] == "k":
                keycomp[mm[1]] = root
    groups = {}
    zero_cols = []
    for j, col in enumerate(cols):
        if not col:
            zero_cols.append(j)
            continue
        root = keycomp[next(iter(col.keys()))]
        groups.setdefault(root, []).append(j)
    out = []
    for j in zero_cols:
        v = [C() for _ in cols]
        v[j] = C(1)
        out.append(v)
    for root, js in groups.items():
        keys = sorted({k for j in js for k in cols[j]})
        kidx = {k: i for i, k in enumerate(keys)}
        A = [[C() for _ in js] for _ in keys]
        for jj, j in enumerate(js):
            for k, c in cols[j].items():
                A[kidx[k]][jj] += c
        for vec in cnull(A):
            v = [C() for _ in cols]
            for jj, j in enumerate(js):
                v[j] = vec[jj]
            out.append(v)
    return out


def cnull(A):
    """Null space of a complex matrix (rows of C), via realification."""
    rows = len(A)
    ncols = len(A[0]) if rows else 0
    R = []
    for r in range(rows):
        R.append([A[r][j].re for j in range(ncols)] +
                 [-A[r][j].im for j in range(ncols)])
    for r in range(rows):
        R.append([A[r][j].im for j in range(ncols)] +
                 [A[r][j].re for j in range(ncols)])
    out = []
    for v in exactlin.nullspace(R):
        out.append([C(v[j], v[ncols + j]) for j in range(ncols)])
    return out


def stack_keys(mats):
    ks = set()
    for M in mats:
        for i in (0, 1):
            for j in (0, 1):
                ks |= set(M[i][j].keys())
    return sorted(ks)


def stack_vec(mats, keys):
    kidx = {k: i for i, k in enumerate(keys)}
    n = len(keys)
    v = [C() for _ in range(4 * n * len(mats))]
    for t, M in enumerate(mats):
        for i in (0, 1):
            for j in (0, 1):
                for k, c in M[i][j].items():
                    v[t * 4 * n + (2 * i + j) * n + kidx[k]] = c
    return v


def csolve(cols, target):
    """Solve sum_k x_k cols[k] = target exactly over Q(i) via realification.

    cols and target are lists of C; returns list of C or None."""
    rows = len(target)
    A = []
    for r in range(rows):
        A.append([c[r].re for c in cols] + [-c[r].im for c in cols])
    for r in range(rows):
        A.append([c[r].im for c in cols] + [c[r].re for c in cols])
    b = [target[r].re for r in range(rows)] + \
        [target[r].im for r in range(rows)]
    x = exactlin.solve(A, b)
    if x is None:
        return None
    n = len(cols)
    return [C(x[k], x[n + k]) for k in range(n)]


def residuals(q):
    qi = minv(q)
    R1 = lhs1(q, qi)
    R2 = msub(lhs2(q, qi), rhs2(q))
    return R1, R2


def build_q0(plus, mins, coeffs):
    """q_0 = P . Qt from one-half solutions: coeffs = (pc, mc) with
    pc = [(k, col, c)] adding c * A^(k) to column col of P, likewise mc
    for the rows of Qt."""
    P = mid()
    Qt = mid()
    pc, mc = coeffs
    for (k, col, c) in pc:
        A = plus[k % len(plus)]
        for g in (0, 1):
            P[g][col] = add(P[g][col], smul(c, A[g]))
    for (k, row, c) in mc:
        ps = mins[k % len(mins)]
        for b in (0, 1):
            Qt[row][b] = add(Qt[row][b], smul(c, ps[b]))
    return mmul(P, Qt)


def correction_basis(plus, mins, mpows=(1, 2, 3)):
    """The constrained corrections: m^j A^(k) (x) psi^(l).  Over a polynomial
    window the doubly-constrained space is exactly this tensor product."""
    out = []
    for j in mpows:
        mj = mono(nm=j)
        for A in plus:
            for ps in mins:
                dq = [[mul(mj, mul(A[g], ps[b])) for b in (0, 1)]
                      for g in (0, 1)]
                if any(dq[g][b] for g in (0, 1) for b in (0, 1)):
                    out.append(dq)
    return out


def _sparse_pair(M1, M2, sign=1):
    """Two 2x2 matrices of ring elements as one sparse dict
    {(slot, ringkey): C}, slots 0..3 for M1 and 4..7 for M2."""
    out = {}
    for t, M in ((0, M1), (4, M2)):
        for i in (0, 1):
            for j in (0, 1):
                for k, c in M[i][j].items():
                    out[(t + 2 * i + j, k)] = c * sign
    return out


def newton_m(q0, dqs, max_iter=None, verbose=True, tag="", frozen=True):
    """Chord Newton: Jacobian frozen at q_0 (set frozen=False to relinearize
    at every step).  Terminates exactly when the corrections are nilpotent
    (odd decorations, or powers of m in the ring truncated at m^MTRUNC)."""
    if max_iter is None:
        max_iter = MTRUNC[0] + 4
    q = q0
    varcols = None
    for it in range(max_iter):
        R1, R2 = residuals(q)
        nc = check_constraints(q)
        if nc == 0 and meq(R1, mzero()) and meq(R2, mzero()):
            if verbose:
                log("      %s: exact solution after %d chord steps"
                    % (tag, it))
            return q
        if varcols is None or not frozen:
            qq = q0 if frozen else q
            qqi = minv(qq)
            varcols = [_sparse_pair(var_lhs1(qq, qqi, dq),
                                    msub(var_lhs2(qq, qqi, dq),
                                         var_rhs2(dq)))
                       for dq in dqs]
        target = _sparse_pair(R1, R2, sign=-1)
        x = sparse_solve(varcols, target)
        if x is None:
            log("      %s: linear system inconsistent (widen windows)" % tag)
            return None
        corr = mzero()
        for k, xk in enumerate(x):
            if xk:
                corr = madd(corr, msmul(xk, dqs[k]))
        q = madd(q, corr)
    log("      %s: no convergence" % tag)
    return None


