def check_constraints(q):
    bad = 0
    for g in (0, 1):                              # minus half, upper index
        u = (q[g][0], q[g][1])
        if not eq(cDm(1, u[0]), {}):
            bad += 1
        if not eq(cDm(2, u[1]), {}):
            bad += 1
        if not eq(add(cDm(1, u[1]), cDm(2, u[0])), {}):
            bad += 1
    for b in (0, 1):                              # plus half, lower index
        v = (q[0][b], q[1][b])
        if not eq(bDp(1, v[0]), {}):
            bad += 1
        if not eq(bDp(2, v[1]), {}):
            bad += 1
        if not eq(add(bDp(1, v[1]), bDp(2, v[0])), {}):
            bad += 1
    return bad


def current_minus(q, qi):
    """C_g = q^{-1} bD_{-g} q, g = 1, 2 (matrices, minus-type indices)."""
    return [mmul(qi, mapply(lambda f: bDm(g, f), q)) for g in (1, 2)]


def cvec(q, qi):
    """c_b = sum_g (q^{-1} bD_{-g} q)_b^g -- the current of E2."""
    Cs = current_minus(q, qi)
    return [add(Cs[0][b][0], Cs[1][b][1]) for b in (0, 1)]


def lhs2(q, qi):
    c = cvec(q, qi)
    return [[cDp(a, c[b]) for a in (1, 2)] for b in (0, 1)]


EPSL = {(1, 1): C(), (1, 2): C(1), (2, 1): C(-1), (2, 2): C()}
EPSH = {(1, 1): C(), (1, 2): C(1), (2, 1): C(-1), (2, 2): C()}


def qbar(q):
    out = mzero()
    for b in (1, 2):
        for a in (1, 2):
            v = {}
            for g in (1, 2):
                for d in (1, 2):
                    c = EPSL[(b, g)] * EPSH[(a, d)]
                    if c:
                        v = add(v, smul(-c, q[d - 1][g - 1]))
            out[b - 1][a - 1] = v
    return out


M_MONO = mono(nm=1)          # the mass m, an invertible ring variable


def rhs2(q):
    """RHS of E2: -4 i m (bar q)_b^a."""
    return msmul(C(0, -4), mapply(lambda f: mul(M_MONO, f), qbar(q)))


def jvec(q, qi):
    """j^b = sum_g (q cD_+^g q^{-1})_g^b -- the current of E1."""
    out = [{}, {}]
    for g in (1, 2):
        Jg = mmul(q, mapply(lambda f: cDp(g, f), qi))
        for b in (0, 1):
            out[b] = add(out[b], Jg[g - 1][b])
    return out


def lhs1(q, qi):
    j = jvec(q, qi)
    return [[cDm(a, j[b]) for b in (0, 1)] for a in (1, 2)]


def full_residuals(q):
    """(constraint violations, E1 matrix, E2-defect matrix)."""
    qi = minv(q)
    R1 = lhs1(q, qi)
    R2 = msub(lhs2(q, qi), rhs2(q))
    return check_constraints(q), R1, R2


def is_solution(q, tag=""):
    nc, R1, R2 = full_residuals(q)
    ok = (nc == 0 and meq(R1, mzero()) and meq(R2, mzero()))
    return ok


