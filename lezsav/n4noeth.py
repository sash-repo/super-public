MI = (1, 2, 3, 4)          # minus-half thetas
PL = (5, 6, 7, 8)          # plus-half thetas
EPSODD = (9, 10, 11, 12)   # odd constants

MTRUNC = [99]              # work modulo m^MTRUNC (99 = no truncation)


def _trunc(f):
    K = MTRUNC[0]
    if K >= 99:
        return f
    return {k: v for k, v in f.items() if k[2] < K}


def mono(nz=0, nw=0, nm=0, S=(), c=1):
    S, sgn = sort_odd(tuple(S))
    if sgn == 0:
        return {}
    c = cx(c) * sgn
    return {(nz, nw, nm, S): c} if c else {}


def add(*fs):
    out = {}
    for f in fs:
        for k, v in f.items():
            out[k] = out.get(k, C()) + v
    return {k: v for k, v in out.items() if v}


def smul(c, f):
    c = cx(c)
    return {k: c * v for k, v in f.items() if c * v}


def sub(f, g):
    return add(f, smul(-1, g))


def mul(f, g):
    out = {}
    K = MTRUNC[0]
    for (z1, w1, m1, S1), c1 in f.items():
        for (z2, w2, m2, S2), c2 in g.items():
            if m1 + m2 >= K:
                continue
            S, sgn = sort_odd(S1 + S2)
            if sgn:
                k = (z1 + z2, w1 + w2, m1 + m2, S)
                out[k] = out.get(k, C()) + c1 * c2 * sgn
    return {k: v for k, v in out.items() if v}


def mulmany(*fs):
    out = mono()
    for f in fs:
        out = mul(out, f)
    return out


def d_z(f):
    out = {}
    for (a, b, c, S), v in f.items():
        if a:
            k = (a - 1, b, c, S)
            out[k] = out.get(k, C()) + v * a
    return {k: v for k, v in out.items() if v}


def d_w(f):
    out = {}
    for (a, b, c, S), v in f.items():
        if b:
            k = (a, b - 1, c, S)
            out[k] = out.get(k, C()) + v * b
    return {k: v for k, v in out.items() if v}


def d_xm(f):
    """d/dx^- = d_w - d_z."""
    return sub(d_w(f), d_z(f))


def d_xp(f):
    """d/dx^+ = d_w + d_z."""
    return add(d_w(f), d_z(f))


def d_odd(j, f):
    out = {}
    for (a, b, c, S), v in f.items():
        if j in S:
            p = S.index(j)
            T = S[:p] + S[p + 1:]
            k = (a, b, c, T)
            out[k] = out.get(k, C()) + v * ((-1) ** p)
    return {k: v for k, v in out.items() if v}


def parity(f):
    ps = {len(S) % 2 for (a, b, c, S) in f}
    if len(ps) > 1:
        raise ValueError("inhomogeneous parity")
    return ps.pop() if ps else 0


def eq(f, g):
    return sub(f, g) == {}


def theta_min(f):
    """The least number of odd labels in any term; 99 if f = 0.

    Every odd label is nilpotent -- the thetas and the odd constants alike --
    so a term is nilpotent as soon as S is non-empty."""
    tm = 99
    for (a, b, c, S) in f:
        tm = min(tm, len(S))
    return tm


def show(f, cap=8):
    if not f:
        return "0"
    parts = []
    items = sorted(f.items())
    for (a, b, c, S), v in items[:cap]:
        th = "".join(
            ("tm%d" % j) if j <= 4 else
            (("tp%d" % (j - 4)) if j <= 8 else ("e%d" % (j - 8)))
            for j in S)
        parts.append("%s z^%s w^%s m^%s %s" % (v, a, b, c, th))
    s = " + ".join(parts)
    if len(items) > cap:
        s += " +...(%d)" % (len(items) - cap)
    return s


# --- the odd derivatives ----------------------------------------------------
#
# The odd labels are the COMPLEX frame along the two isotropic planes:
#     1 = eta^1_-,  2 = rho_{-1},  3 = eta^2_-,  4 = rho_{-2}   (minus half)
#     5 = eta^1_+,  6 = rho_{+1},  7 = eta^2_+,  8 = rho_{+2}   (plus half)
# with eta^a = theta_{2a-1} + i theta_{2a}, rho_a = theta_{2a-1} - i theta_{2a}.
# In this frame the four families of odd derivatives are the two-term
# operators below, each homogeneous for the torus charges (#eta - #rho per
# plane), which is what makes every linear solve split into small blocks:
#     cD^a = 2 d_{eta^a} - rho_a d_x,      bD_a = 2 d_{rho_a} - eta^a d_x,
# and {cD^a, bD_b} = -4 delta^a_b d_x per half, all other brackets zero --
# the frame (DN4) of the text.


def cDm(a, f):
    e, r = 2 * a - 1, 2 * a
    return sub(smul(2, d_odd(e, f)), mul(mono(S=(r,)), d_xm(f)))


def bDm(a, f):
    e, r = 2 * a - 1, 2 * a
    return sub(smul(2, d_odd(r, f)), mul(mono(S=(e,)), d_xm(f)))


def cDp(a, f):
    e, r = 2 * a + 3, 2 * a + 4
    return sub(smul(2, d_odd(e, f)), mul(mono(S=(r,)), d_xp(f)))


def bDp(a, f):
    e, r = 2 * a + 3, 2 * a + 4
    return sub(smul(2, d_odd(r, f)), mul(mono(S=(e,)), d_xp(f)))


