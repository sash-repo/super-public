"""
n4noeth.py -- the Noether step: the N=4 stress tensor bold T = -u is a
conserved current of its half, once completed by a composite of the two
currents of (IK4).

Item 2) of Proposition 2.3.4, Theorem 4.2.1, Theorem 5.3.1 says the stress tensor
is a current of its half: d_(other half) T = 0 modulo the system.  At N=4,
for bold T = -u alone this is FALSE (d_+d_- u != 0 is the Liouville
equation); the conserved object is bold T plus a completion, and it is open
which composite of the currents

    c_b = sum_g (q^{-1} bD_{-g} q)_b^g      (the current of E2, minus half)
    j^b = sum_g (q cD_+^g q^{-1})_g^b       (the current of E1, plus half)

the completion is.  This engine settles it, in exact arithmetic over Q(i),
on honest exact solutions of the full system (IK4).

THE RING.  O(2|8) does not contain 1/(x^+ - x^-), which every Liouville-type
solution needs; so the even part here is Laurent in

    z := x^+ - x^-,      w := x^+ + x^-,      m := the mass of (IK4),

with  d_{x^-} = d_w - d_z,  d_{x^+} = d_w + d_z,  and m a central invertible
constant (making m a ring variable lets the m-dependence of the completion be
SOLVED for rather than guessed).  Keys are (nz, nw, nm, S), S a sorted tuple
of odd labels: 1..4 the minus-half thetas, 5..8 the plus-half ones, 9..12
odd constants used to apply odd symmetries and to build even nilpotent
parameters.

THE SOLUTIONS.  A seed solution is found by Newton iteration (the corrections
are nilpotent, so Newton terminates EXACTLY) in the image of the prepotential

    q_g^b = q0 + bD_{+g} cD_-^b (Phi),

which satisfies both constraints of (IK4) for every Phi identically.  The
family is then generated by the transformation law of Proposition 6.2.4,

    delta_f q = K_f(q) - q Lam(f)^T,        f in the acting algebra,

applied through odd constants; every generated q is verified against the
constraints and both dynamical equations EXACTLY -- nothing is trusted.

Usage:  python3 n4noeth.py          (writes n4noeth-out.txt)
"""

