# (4) exact solutions of (IK4), modulo m^K
#
# At m = 0 the system is solved EXACTLY by every factorized
#
#     q_0 = P(x^+, theta^+) . Qt(x^-, theta^-)
#
# whose factors satisfy the one-half constraints (each ROW of Qt is a
# cD_--constrained doublet, each COLUMN of P a bD_+-constrained one): the
# current of E2 is then built from Qt alone and killed by cD_+, the current
# of E1 from P alone and killed by cD_-.  The mass corrections
# q = q_0 + m q_1 + m^2 q_2 + ... are m-adically nilpotent in the ring
# truncated at m^K, so a chord Newton iteration (Jacobian frozen at q_0)
# converges EXACTLY in at most K steps.  Corrections are sought in the span
# of the tensor products A^(k) (x) psi^(l) of one-half constraint solutions,
# which is the whole constrained space over a polynomial window.
# ---------------------------------------------------------------------------


