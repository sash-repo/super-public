# (5) the stress tensor, the currents, and the candidate completions
# ---------------------------------------------------------------------------


def dT(q, qi, dop):
    """The dop-derivative of bold T = -u = 1/2 log det q, computed as
    1/2 tr(q^{-1} dop q) -- exact for every derivation dop of the ring,
    even or odd, so no logarithm is ever needed."""
    return smul(Q(1, 2), mtr(mmul(qi, mapply(dop, q))))


def chi_psi(q):
    """The constraint currents: cD_-^a q_g^b = eps^{ab} chi_g and
    bD_{+a} q_g^b = eps_{ag} psi^b."""
    # eps^{12} = 1: cD^1 q_g^2 = eps^{12} chi_g = chi_g
    chi = [cDm(1, q[g][1]) for g in (0, 1)]
    # eps_{12} = 1: bD_{+1} q_2^b = eps_{12} psi^b = psi^b
    psi = [bDp(1, q[1][b]) for b in (0, 1)]
    return chi, psi


def candidate_shapes(q):
    """Scalar composites of the currents of (IK4), as a dict name -> ring
    element.  j^g and c_b are the currents of E1 and E2; tj, ts their other
    contractions (the traces); chi, psi the constraint currents."""
    qi = minv(q)
    c = cvec(q, qi)                       # lower minus index
    j = jvec(q, qi)                       # upper plus index
    tj = [mtr(mmul(q, mapply(lambda f: cDp(g, f), qi))) for g in (1, 2)]
    ts = [mtr(M) for M in current_minus(q, qi)]
    chi, psi = chi_psi(q)
    jq = [add(mul(j[0], q[0][b]), mul(j[1], q[1][b])) for b in (0, 1)]
    tjq = [add(mul(tj[0], q[0][b]), mul(tj[1], q[1][b])) for b in (0, 1)]
    qc = [add(mul(q[g][0], c[0]), mul(q[g][1], c[1])) for g in (0, 1)]
    shapes = {
        "jq.c": add(mul(jq[0], c[0]), mul(jq[1], c[1])),
        "tjq.c": add(mul(tjq[0], c[0]), mul(tjq[1], c[1])),
        "jq.ts": add(mul(jq[0], ts[0]), mul(jq[1], ts[1])),
        "tjq.ts": add(mul(tjq[0], ts[0]), mul(tjq[1], ts[1])),
        "det": mdet(q),
        "tr(q qbar)": mtr(mmul(q, qbar(q))),
        "bD.(jq)": add(bDm(1, jq[0]), bDm(2, jq[1])),
        "cD.(qc)": add(cDp(1, qc[0]), cDp(2, qc[1])),
        "j.j": mul(j[0], j[1]),
        "c.c": mul(c[0], c[1]),
        "j.chi": add(mul(j[0], chi[0]), mul(j[1], chi[1])),
        "psi.c": add(mul(psi[0], c[0]), mul(psi[1], c[1])),
        "tj.chi": add(mul(tj[0], chi[0]), mul(tj[1], chi[1])),
        "psi.ts": add(mul(psi[0], ts[0]), mul(psi[1], ts[1])),
    }
    return shapes, qi


CAND_MPOWS = (-1, 0, 1)


def conservation_columns(q, dop):
    """For one exact solution q: the target dop(T) and the columns
    dop(m^p * shape) for every candidate, as ring elements."""
    shapes, qi = candidate_shapes(q)
    target = dT(q, qi, dop)
    cols = {}
    for nm, s in shapes.items():
        for p in CAND_MPOWS:
            sp = mul(mono(nm=p), s) if p else s
            cols[(nm, p)] = dop(sp)
    return target, cols


def solve_completion(solutions, dop, names=None):
    """Solve  dop(T) + sum_i x_i dop(m^p shape_i) = 0  across the given
    exact solutions; returns (coeffs dict, residual-check ok)."""
    per_sol = []
    colnames = None
    for q in solutions:
        target, cols = conservation_columns(q, dop)
        if colnames is None:
            colnames = sorted(cols.keys())
        per_sol.append((target, cols))
    stacked_cols = {nm: [] for nm in colnames}
    stacked_target = []
    for target, cols in per_sol:
        keys = sorted(set(target.keys()) |
                      {k for f in cols.values() for k in f})
        for nm in colnames:
            f = cols.get(nm, {})
            stacked_cols[nm].extend([f.get(k, C()) for k in keys])
        stacked_target.extend([-target.get(k, C()) for k in keys])
    cols_list = [stacked_cols[nm] for nm in colnames]
    x = csolve(cols_list, stacked_target)
    if x is None:
        return None, colnames
    return dict(zip(colnames, x)), colnames


def selftest():
    log("=" * 74)
    log("(0)  the ring and the frame")
    log("=" * 74)
    tests = [
        mono(2, 1, 0, (1, 2)),
        mono(-1, 0, 1, (1, 5)),
        mono(0, 2, -1, (3, 6, 7, 8)),
        mono(-2, 0, 0, ()),
        add(mono(1, 0, 0, (2,)), mono(0, 0, 0, (4, 5, 6))),
    ]
    bad = 0
    for f in tests:
        for a in (1, 2):
            for b in (1, 2):
                # {cD^a, bD_b} = -4 delta d_x, per half
                lhsm = add(cDm(a, bDm(b, f)), bDm(b, cDm(a, f)))
                want = smul(-4, d_xm(f)) if a == b else {}
                if not eq(lhsm, want):
                    bad += 1
                lhsp = add(cDp(a, bDp(b, f)), bDp(b, cDp(a, f)))
                want = smul(-4, d_xp(f)) if a == b else {}
                if not eq(lhsp, want):
                    bad += 1
                # cross-half anticommutators vanish
                if not eq(add(cDm(a, cDp(b, f)), cDp(b, cDm(a, f))), {}):
                    bad += 1
                if not eq(add(bDm(a, bDp(b, f)), bDp(b, bDm(a, f))), {}):
                    bad += 1
                if not eq(add(cDm(a, bDp(b, f)), bDp(b, cDm(a, f))), {}):
                    bad += 1
                # squares
                if not eq(add(cDm(a, cDm(b, f)), cDm(b, cDm(a, f))), {}):
                    bad += 1
                if not eq(add(bDp(a, bDp(b, f)), bDp(b, bDp(a, f))), {}):
                    bad += 1
    check(bad == 0, "frame relations (%d failures)" % bad)
    log("    {cD^a,bD_b} = -4 delta d_x per half, all cross and square")
    log("    anticommutators zero: verified on %d monomials.        OK"
        % len(tests))

    # the prepotential satisfies the constraints for arbitrary Phi
    bad = 0
    for Phi in (mono(1, 0, 0, (1, 5)), mono(-1, 1, 0, (2, 3, 6, 8)),
                mono(0, 0, 1, (4, 7)), mono(2, 0, -1, ())):
        if check_constraints(q_of_phi(Phi)):
            bad += 1
    check(bad == 0, "prepotential constraint check")
    log("    q(Phi) = bD_+ cD_- Phi satisfies both constraints for")
    log("    arbitrary Phi: verified on 4 test prepotentials.       OK")


