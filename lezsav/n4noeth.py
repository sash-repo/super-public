def mzero():
    return [[{}, {}], [{}, {}]]


def mid(c=1):
    return [[mono(c=c), {}], [{}, mono(c=c)]]


def madd(*Ms):
    return [[add(*[M[i][j] for M in Ms]) for j in (0, 1)] for i in (0, 1)]


def msub(P, R):
    return [[sub(P[i][j], R[i][j]) for j in (0, 1)] for i in (0, 1)]


def msmul(c, M):
    return [[smul(c, M[i][j]) for j in (0, 1)] for i in (0, 1)]


def mmul(P, R):
    return [[add(mul(P[i][0], R[0][j]), mul(P[i][1], R[1][j]))
             for j in (0, 1)] for i in (0, 1)]


def mtrans(M):
    return [[M[0][0], M[1][0]], [M[0][1], M[1][1]]]


def mtr(M):
    return add(M[0][0], M[1][1])


def mdet(M):
    return sub(mul(M[0][0], M[1][1]), mul(M[0][1], M[1][0]))


def madj(M):
    return [[M[1][1], smul(-1, M[0][1])], [smul(-1, M[1][0]), M[0][0]]]


def mapply(op, M):
    return [[op(M[i][j]) for j in (0, 1)] for i in (0, 1)]


def meq(P, R):
    return all(eq(P[i][j], R[i][j]) for i in (0, 1) for j in (0, 1))


def inv_scalar(u, lead, ord_max=12):
    """1/u for u = lead (1 + n), n with at least one theta in every term.

    lead is a key (nz, nw, nm) with coefficient: pass as a monomial dict."""
    (lk, lc), = lead.items()
    li = {(-lk[0], -lk[1], -lk[2], ()): recip(lc)}
    n = sub(mul(li, u), mono())
    if n and theta_min(n) == 0:
        raise ValueError("non-nilpotent remainder: %s" % show(n))
    out = mono()
    term = mono()
    for _ in range(ord_max):
        term = smul(-1, mul(term, n))
        if not term:
            break
        out = add(out, term)
    return mul(li, out)


def lead_of(u):
    """The theta-free part of u, required to be a single monomial."""
    cand = {k: v for k, v in u.items() if k[3] == ()}
    if len(cand) != 1:
        raise ValueError("leading part not a single monomial: %s" % show(u))
    return cand


def minv(M):
    d = mdet(M)
    di = inv_scalar(d, lead_of(d))
    return [[mul(di, x) for x in row] for row in madj(M)]


