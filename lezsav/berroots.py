"""
berroots.py -- item 8.7 of Appendix D3 of the 2nd edition of Berezin's book
(F. A. Berezin, "Vvedenie v superanaliz", ed. D. Leites, MCCME, Moscow, 2013,
p. 259), machine-checked from scratch.

That item gives, for the Lie superalgebra svect^L_lambda(1|2):

  (D3.70)  a system of simple root vectors X_i^{+-} and the Cartan elements H_i;
           the two systems obtained from it by the odd reflections in the 2nd
           and in the 3rd root;
  (D3.71)  the three resulting Cartan matrices;
  (D3.72)  their normal shapes, whence (item 8.8.3) the isomorphisms
                lambda -> lambda + 1   and   lambda -> 1 - lambda,
           so that one may assume Re lambda in [0, 1/2].

What is verified here, exactly, with lambda a formal parameter:

  1. every one of the nine fields of (D3.70) and of the two reflected systems
     lies in svect^L_lambda(1|2), i.e. div_lambda = 0 -- the divergence being
     the one whose sign rule the machine picked in sv2.py;
  2. each of the three systems satisfies the Chevalley relations
        [H_i,H_j] = 0,  [X_i^+, X_j^-] = delta_ij H_i,
        [H_i, X_j^{+-}] = +- A_ij X_j^{+-},
     and the matrix A is READ OFF from them, not assumed;
  3. the three matrices read off are those of (D3.71);
  4. the reflected systems are what the odd-reflection recipe produces from
     (D3.70): X_2^{+-} are swapped and the other root vectors are the brackets
     with X_2^{-+}, up to the scalars the book puts in square brackets;
  5. the three matrices normalize to the shapes (D3.72), with the parameters
     lambda, 1-lambda, 1+lambda respectively;
  6. the group generated by lambda -> lambda+1 and lambda -> 1-lambda contains
     our own  lambda -> -lambda-2  (the inversion t -> 1/t of Statement 4.2.9),
     and the two sets of generators generate the same group -- so the book's
     answer and ours agree;
  7. the system (D3.70) generates svect^L_lambda(1|2): the Lie superalgebra it
     generates contains the basis fields L_n, J^a_n, G^r_alpha, Gbar^{r alpha}
     of Statement 4.2.7 in a window of modes.

Run:  ../venv/bin/python berroots.py
"""

import os
import sys
import itertools

import os, sys; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]

from sympy import (Matrix, Rational, cancel, expand, simplify, symbols,
                   together, nsimplify)

import sv2 as S

lam = S.lam
SIGN = 'parodd'                  # the unique cocycle sign, decided in sv2.sec0

FAIL = []
CHECKS = [0]


def check(cond, msg):
    CHECKS[0] += 1
    if not cond:
        FAIL.append(msg)
        print("  FAIL: " + msg)


# ------------------------------------------------------------------ helpers

def VF(comps, p):
    return S.VF(comps, p)


def mono(m, Sx=(), c=1):
    return S.mono(m, Sx, c)


def zero(X):
    return X.is_zero()


def eqf(X, Y):
    """X == Y as vector fields, coefficientwise, after simplification."""
    D = X - Y
    for a in S.COMPS:
        for k, v in D.c[a].items():
            if simplify(cancel(together(v))) != 0:
                return False
    return True


def scalar_multiple(X, Y):
    """the c with X = c*Y, or None."""
    c = None
    for a in S.COMPS:
        keys = set(X.c[a]) | set(Y.c[a])
        for k in keys:
            xv, yv = X.c[a].get(k, 0), Y.c[a].get(k, 0)
            if simplify(cancel(together(yv))) == 0:
                if simplify(cancel(together(xv))) != 0:
                    return None
                continue
            cc = cancel(together(xv / yv))
            if c is None:
                c = cc
            elif simplify(cancel(together(c - cc))) != 0:
                return None
    return c


def in_svect(X):
    d = S.div_lam(X, SIGN)
    return all(simplify(cancel(together(v))) == 0 for v in d.values())


# ============================================== the three systems of (D3.70)
#
# Berezin writes xi_1, xi_2 for the odd indeterminates; here they are the
# th1, th2 of sv2.py.  Coefficients stand on the left, as everywhere in sv2.py.

def system_1():
    """(D3.70) itself."""
    Xp = {
        1: VF({2: mono(0, (1,))}, 0),                         # xi1 d_2
        2: VF({1: mono(1)}, 1),                               # t d_1
        3: VF({'t': mono(1, (2,)),                            # xi2 t d_t
               1: mono(0, (1, 2), -(lam + 1))}, 1),           #  - (l+1) xi1 xi2 d_1
    }
    Xm = {
        1: VF({1: mono(0, (2,))}, 0),                         # xi2 d_1
        2: VF({'t': mono(0, (1,)),                            # xi1 d_t
               2: mono(-1, (1, 2), lam)}, 1),                 #  + l xi1 xi2 / t d_2
        3: VF({2: mono(0)}, 1),                               # d_2
    }
    H = {
        1: VF({1: mono(0, (1,)), 2: mono(0, (2,), -1)}, 0),
        2: VF({'t': mono(1), 1: mono(0, (1,)), 2: mono(0, (2,), lam)}, 0),
        3: VF({'t': mono(1), 1: mono(0, (1,), lam + 1)}, 0),
    }
    return Xp, Xm, H


def system_2():
    """(D3.70) reflected in the 2nd root, as printed."""
    Xp = {
        1: VF({2: mono(1)}, 1),                               # t d_2
        2: VF({'t': mono(0, (1,)),                            # xi1 d_t
               2: mono(-1, (1, 2), lam)}, 1),                 #  + l xi1 xi2 / t d_2
        3: VF({1: mono(1, (2,), -lam)}, 0),                   # [-l] t xi2 d_1
    }
    Xm = {
        1: VF({'t': mono(0, (2,), -1),                        # - xi2 d_t
               1: mono(-1, (1, 2), lam)}, 1),                 #  + l xi1 xi2 / t d_1
        2: VF({1: mono(1)}, 1),                               # t d_1
        3: VF({2: mono(-1, (1,), -lam)}, 0),                  # [-l] xi1 / t d_2
    }
    H = {
        1: VF({'t': mono(1, (), -1), 1: mono(0, (1,), -lam),
               2: mono(0, (2,), -1)}, 0),
        2: VF({'t': mono(1), 1: mono(0, (1,)), 2: mono(0, (2,), lam)}, 0),
        3: VF({1: mono(0, (1,), -1), 2: mono(0, (2,))}, 0),
    }
    return Xp, Xm, H


def system_3():
    """(D3.70) reflected in the 3rd root, as printed."""
    Xp = {
        1: VF({2: mono(0)}, 1),                               # d_2
        2: VF({1: mono(1, (2,), lam + 2)}, 0),                # [l+2] t xi2 d_1
        3: VF({'t': mono(0, (1,), -1),                        # - xi1 t d_t / t
               2: mono(0, (1, 2), -(lam + 1))}, 1),
    }
    # careful: (l+1) xi2 xi1 d_2 = -(l+1) xi1 xi2 d_2, and  - xi1 t d_t.
    Xp[3] = VF({'t': mono(1, (1,), -1),
                2: mono(0, (1, 2), -(lam + 1))}, 1)
    Xm = {
        1: VF({'t': mono(1, (2,)),                            # t xi2 d_t
               1: mono(0, (1, 2), -(lam + 1))}, 1),           #  - (l+1) xi1 xi2 d_1
        2: VF({2: mono(-1, (1,), -lam)}, 0),                  # [-l] xi1 / t d_2
        3: VF({1: mono(0)}, 1),                               # d_1
    }
    H = {
        1: VF({'t': mono(1), 1: mono(0, (1,), lam + 1)}, 0),
        2: VF({1: mono(0, (1,), -1), 2: mono(0, (2,))}, 0),
        3: VF({'t': mono(1, (), -1), 2: mono(0, (2,), -(lam + 1))}, 0),
    }
    return Xp, Xm, H


# the matrices printed in (D3.71)
A_PRINTED = [
    Matrix([[2, -1, -1],
            [1 - lam, 0, lam],
            [1 + lam, -lam, 0]]),
    Matrix([[0, 1 - lam, lam - 2],
            [1 - lam, 0, lam],
            [-1, -1, 2]]),
    Matrix([[0, -lam, lam + 1],
            [-1, 2, -1],
            [1 + lam, -lam - 2, 0]]),
]

# the normal shapes printed in (D3.72), as a function of the parameter
def normal_shape(mu):
    return Matrix([[2, -1, -1],
                   [-1 + 1 / mu, 0, 1],
                   [1 + 1 / mu, -1, 0]])


NORMAL_PARAM = [lam, 1 - lam, 1 + lam]


# ========================================================= 1. the three bases

def read_cartan(Xp, Xm, H, tag):
    """Check the Chevalley relations and READ OFF the Cartan matrix."""
    print("\n   %s" % tag)

    for i in (1, 2, 3):
        check(in_svect(Xp[i]), "%s: X_%d^+ not in svect_lambda" % (tag, i))
        check(in_svect(Xm[i]), "%s: X_%d^- not in svect_lambda" % (tag, i))
        check(in_svect(H[i]), "%s: H_%d not in svect_lambda" % (tag, i))
    print("     all 9 fields satisfy div_lambda = 0")

    for i, j in itertools.combinations((1, 2, 3), 2):
        check(zero(S.bracket(H[i], H[j])), "%s: [H_%d,H_%d] != 0" % (tag, i, j))
    print("     the H_i commute")

    # [X_i^+, X_j^-] = delta_ij * (scalar) * H_i.  The book takes the root
    # vectors up to the factors it prints in square brackets, so the scalar
    # need not be 1; it does not affect the Cartan matrix, which is read off
    # from [H_i, X_j^{+-}] below and is invariant under rescaling the X's.
    facs = []
    for i in (1, 2, 3):
        for j in (1, 2, 3):
            B = S.bracket(Xp[i], Xm[j])
            if i == j:
                c = scalar_multiple(B, H[i])
                check(c is not None and simplify(c) != 0,
                      "%s: [X_%d^+,X_%d^-] is not a nonzero multiple of H_%d"
                      % (tag, i, i, i))
                facs.append(simplify(c) if c is not None else None)
            else:
                check(zero(B),
                      "%s: [X_%d^+,X_%d^-] != 0" % (tag, i, j))
    print("     [X_i^+, X_j^-] = delta_ij c_i H_i with (c_1,c_2,c_3) = %s"
          % (tuple(str(c) for c in facs),))

    # [H_i, X_j^{+-}] = +- A_ij X_j^{+-}
    A = [[None] * 3 for _ in range(3)]
    for i in (1, 2, 3):
        for j in (1, 2, 3):
            c = scalar_multiple(S.bracket(H[i], Xp[j]), Xp[j])
            check(c is not None,
                  "%s: [H_%d,X_%d^+] is not a multiple of X_%d^+" % (tag, i, j, j))
            A[i - 1][j - 1] = simplify(cancel(together(c if c is not None else 0)))
            cm = scalar_multiple(S.bracket(H[i], Xm[j]), Xm[j])
            check(cm is not None and
                  simplify(cancel(together(cm + A[i - 1][j - 1]))) == 0,
                  "%s: [H_%d,X_%d^-] != -A_%d%d X_%d^-" % (tag, i, j, i, j, j))
    A = Matrix(A)
    print("     Cartan matrix read off:")
    for r in range(3):
        print("       (%s)" % "  ".join(str(A[r, c]) for c in range(3)))

    # parities of the simple roots: the diagonal must say it
    for j in (1, 2, 3):
        p = Xp[j].p
        check((p == 1) == (simplify(A[j - 1, j - 1]) == 0),
              "%s: parity of root %d clashes with the diagonal" % (tag, j))
    print("     parities agree with the diagonal (2 = even, 0 = odd isotropic)")
    return A


def sec1():
    print("\n1. The three systems of simple root vectors of item 8.7")
    out = []
    for k, (mk, tag) in enumerate([(system_1, "(D3.70) itself"),
                                   (system_2, "reflected in the 2nd root"),
                                   (system_3, "reflected in the 3rd root")]):
        Xp, Xm, H = mk()
        A = read_cartan(Xp, Xm, H, tag)
        P = A_PRINTED[k]
        same = all(simplify(cancel(together(A[i, j] - P[i, j]))) == 0
                   for i in range(3) for j in range(3))
        check(same, "matrix %d differs from the printed (D3.71)" % (k + 1))
        print("     agrees with (D3.71), matrix %d: %s" % (k + 1, same))
        out.append(A)
    return out


# ================================================ 2. the odd reflections used

def sec2():
    print("\n2. The reflections are the odd-reflection recipe applied to (D3.70)")
    Xp, Xm, H = system_1()

    for r, mk, tag in [(2, system_2, "2nd"), (3, system_3, "3rd")]:
        Yp, Ym, _ = mk()
        # the reflected simple root vectors: one new pair is the old r-th pair
        # swapped; the book renumbers, so we look for its place.
        swap = [j for j in (1, 2, 3)
                if scalar_multiple(Yp[j], Xm[r]) is not None
                and scalar_multiple(Ym[j], Xp[r]) is not None]
        check(len(swap) == 1,
              "reflection in the %s root: the swapped pair -alpha_%d is not found"
              % (tag, r))
        if len(swap) != 1:
            continue
        s = swap[0]
        print("     %s root: the new pair no. %d is the old (X_%d^-, X_%d^+): "
              "alpha_%d -> -alpha_%d" % (tag, s, r, r, r, r))
        # the others are the brackets with the reflected root vector
        used = set()
        for j in (1, 2, 3):
            if j == s:
                continue
            found = None
            for i in (1, 2, 3):
                if i == r or i in used:
                    continue
                cp = scalar_multiple(Yp[j], S.bracket(Xp[i], Xp[r]))
                cm = scalar_multiple(Ym[j], S.bracket(Xm[i], Xm[r]))
                if (cp is not None and simplify(cp) != 0
                        and cm is not None and simplify(cm) != 0):
                    found = (i, simplify(cp), simplify(cm))
                    break
            check(found is not None,
                  "reflection in the %s root: the new root vector no. %d is not "
                  "a bracket [X_i^{+-}, X_%d^{+-}]" % (tag, j, r))
            if found is not None:
                i, cp, cm = found
                used.add(i)
                print("       new no. %d = alpha_%d + alpha_%d:  X^+ = [%s]*"
                      "[X_%d^+,X_%d^+],  X^- = [%s]*[X_%d^-,X_%d^-]"
                      % (j, i, r, cp, i, r, cm, i, r))


# ================================================== 3. the normal shapes

def equivalent(A, B):
    """Is B obtained from A by one permutation of rows AND columns, followed
    by a rescaling of the rows?  Returns (perm, scalars) or None."""
    for perm in itertools.permutations(range(3)):
        P = Matrix(3, 3, lambda i, j: A[perm[i], perm[j]])
        cs = []
        ok = True
        for i in range(3):
            c = None
            for j in range(3):
                b, p = B[i, j], P[i, j]
                if simplify(cancel(together(p))) == 0:
                    if simplify(cancel(together(b))) != 0:
                        ok = False
                        break
                    continue
                cc = cancel(together(b / p))
                if c is None:
                    c = cc
                elif simplify(cancel(together(c - cc))) != 0:
                    ok = False
                    break
            if not ok or c is None or simplify(c) == 0:
                ok = False
                break
            cs.append(simplify(c))
        if ok:
            return perm, cs
    return None


def sec3(As):
    print("\n3. The normal shapes (D3.72)")
    for k, A in enumerate(As):
        mu = NORMAL_PARAM[k]
        N = normal_shape(mu)
        r = equivalent(A, N)
        check(r is not None,
              "matrix %d does not normalize to the printed shape with mu=%s"
              % (k + 1, mu))
        if r is not None:
            perm, cs = r
            print("     matrix %d  ->  normal shape with mu = %-9s "
                  "(rows/cols %s, rows scaled by %s)"
                  % (k + 1, mu, tuple(p + 1 for p in perm),
                     tuple(str(c) for c in cs)))
    # and the three normal shapes are the SAME shape at three values of mu
    print("     hence  lambda ~ 1-lambda ~ 1+lambda")


# ============================== 4. the group of isomorphisms, and ours

def sec4():
    print("\n4. The group of the parameter")
    tau = lambda m: m + 1
    sig = lambda m: 1 - m
    orbit = {simplify(lam)}
    for _ in range(6):
        new = set()
        for m in orbit:
            new.add(simplify(tau(m)))
            new.add(simplify(sig(m)))
            new.add(simplify(m - 1))
        orbit |= new
    ours_psi = simplify(-lam - 2)          # Statement 4.2.9, item 3): t -> 1/t
    ours_neg = simplify(-lam)
    check(ours_psi in orbit, "-lambda-2 is not in the book's orbit of lambda")
    check(ours_neg in orbit, "-lambda is not in the book's orbit of lambda")
    print("     -lambda-2 (the inversion t -> 1/t) is in the orbit: %s"
          % (ours_psi in orbit))
    print("     -lambda is in the orbit: %s" % (ours_neg in orbit))
    # conversely: is 1-lambda generated by lambda -> lambda+1 and lambda -> -lambda?
    orbit2 = {simplify(lam)}
    for _ in range(6):
        new = set()
        for m in orbit2:
            new.add(simplify(m + 1))
            new.add(simplify(m - 1))
            new.add(simplify(-m))
            new.add(simplify(-m - 2))
        orbit2 |= new
    check(simplify(1 - lam) in orbit2,
          "1-lambda is not generated by our lambda+1 and -lambda-2")
    print("     conversely, 1-lambda is generated by ours: %s"
          % (simplify(1 - lam) in orbit2))
    # the common normal form of the orbit
    reps = sorted({str(m) for m in orbit})
    print("     the orbit is {lambda+n, n-lambda | n in Z}: %d representatives seen"
          % len(reps))
    print("     a fundamental domain: Re lambda in [0, 1/2]")


# ======================================== 5. (D3.70) generates the algebra

def vectorize(fields):
    """common coordinate system for a list of vector fields."""
    keys = []
    for X in fields:
        for a in S.COMPS:
            for k in X.c[a]:
                if (a, k) not in keys:
                    keys.append((a, k))
    keys.sort(key=lambda z: (str(z[0]), z[1]))
    M = Matrix([[X.c[a].get(k, 0) for (a, k) in keys] for X in fields])
    return M


def sec5():
    print("\n5. Does (D3.70) generate svect^L_lambda(1|2)?")
    Xp, Xm, H = system_1()
    gens = [Xp[i] for i in (1, 2, 3)] + [Xm[i] for i in (1, 2, 3)]

    def tdeg(X):
        d = []
        for a in S.COMPS:
            for (m, Sx) in X.c[a]:
                d.append(m)
        return (min(d), max(d)) if d else (0, 0)

    span = list(gens)
    for _ in range(5):
        new = []
        for A in span:
            for B in gens:
                C = S.bracket(A, B)
                if C.is_zero():
                    continue
                lo, hi = tdeg(C)
                if lo < -3 or hi > 3:
                    continue
                new.append(C)
        cand = span + new
        M = vectorize(cand)
        M = M.applyfunc(lambda z: cancel(together(z)))
        if M.rank() == vectorize(span).applyfunc(
                lambda z: cancel(together(z))).rank():
            break
        span = cand
    M = vectorize(span).applyfunc(lambda z: cancel(together(z)))
    r0 = M.rank()
    print("     the bracket closure inside the window |deg t| <= 3 has rank %d" % r0)

    # the targets: the basis of Statement 4.2.7 in a window
    S.GOOD_SIGN[0] = SIGN
    targets = []
    names = []
    for n in (-1, 0, 1):
        targets.append(S.L(n)); names.append("L_%d" % n)
    for a in ('+', '-', '0'):
        for n in (0, 1):
            targets.append(S.J(a, n)); names.append("J^%s_%d" % (a, n))
    for r in (Rational(-1, 2), Rational(1, 2)):
        for al in (1, 2):
            targets.append(S.G(al, r)); names.append("G_%d^%s" % (al, r))
            targets.append(S.Gbar(al, r)); names.append("Gbar^{%s %d}" % (r, al))
    hit = 0
    for X, nm in zip(targets, names):
        M2 = vectorize(span + [X]).applyfunc(lambda z: cancel(together(z)))
        inside = (M2.rank() == r0)
        check(inside, "%s is not in the algebra generated by (D3.70)" % nm)
        hit += 1 if inside else 0
    print("     %d of %d basis fields of Statement 4.2.7 lie in it"
          % (hit, len(targets)))


# =============================== 6. symmetrizability and degeneracy of A

def sec6(As):
    print("\n6. The matrix A(lambda) itself")
    A = As[0]
    d = simplify(A.det())
    print("     det A = %s  (zero exactly for lambda = %s)"
          % (d, ", ".join(str(r) for r in __import__('sympy').solve(d, lam))))
    # symmetrizable <=> exists D = diag(d_i) with d_i A_ij = d_j A_ji;
    # for a 3x3 with non-zero off-diagonal entries this is the cycle condition
    cyc = simplify(A[0, 1] * A[1, 2] * A[2, 0] - A[1, 0] * A[2, 1] * A[0, 2])
    print("     A_12 A_23 A_31 - A_21 A_32 A_13 = %s" % cyc)
    check(simplify(cyc.subs(lam, 0)) == 0, "the cycle condition fails at lambda=0")
    for l in (Rational(1), Rational(1, 3), Rational(-5, 2)):
        check(simplify(cyc.subs(lam, l)) != 0,
              "A is symmetrizable at lambda=%s" % l)
    print("     so A is symmetrizable only for lambda = 0, and NOT for the")
    print("     values that give a simple Lie superalgebra")


