def main():
    print("=" * 78)
    print("Item 8.7 of Appendix D3 of Berezin's book, 2nd ed. (p. 259), checked")
    print("=" * 78)
    S.GOOD_SIGN[0] = SIGN
    As = sec1()
    sec2()
    sec3(As)
    sec4()
    sec5()
    sec6(As)
