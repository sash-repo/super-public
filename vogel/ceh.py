#!/usr/bin/env python3
"""Chevalley-Eilenberg cohomology H^n(g_-; g) over F_3 for a graded subalgebra
g_- of a graded Lie algebra g, split by the weight of the maximal torus (which
also fixes the Z-degree), together with the g_0-action, the g_0-invariants and
the g_0-submodule generated by a class.

Cross-checked against coh.py (the k^(1)(3;1) engine) by check_k.py.
"""
import numpy as np
from itertools import combinations
from gvect import P, rref, nullspace


def sign_sort(idx):
    idx = list(idx)
    s = 1
    for i in range(len(idx)):
        for j in range(len(idx) - 1 - i):
            if idx[j] > idx[j + 1]:
                idx[j], idx[j + 1] = idx[j + 1], idx[j]
                s = -s
            elif idx[j] == idx[j + 1]:
                return None, 0
    return tuple(idx), s


class CE:
    def __init__(self, g, hidx):
        self.g = g
        self.h = list(hidx)                       # indices of the g_- basis in g
        self.pos = {v: i for i, v in enumerate(self.h)}
        self.hwt = [g.wt[v] for v in self.h]
        self.hdeg = [g.deg[v] for v in self.h]
        self._coch = {}
        self._diff = {}

    # --------------------------------------------------------------- cochains
    def cochains(self, n):
        if n not in self._coch:
            self._coch[n] = [(S, m) for S in combinations(range(len(self.h)), n)
                             for m in range(self.g.n)]
        return self._coch[n]

    def weight(self, S, m):
        w = list(self.g.wt[m])
        for i in S:
            w = [a - b for a, b in zip(w, self.hwt[i])]
        return tuple(w)

    def degree(self, S, m):
        return self.g.deg[m] - sum(self.hdeg[i] for i in S)

    def blocks(self, n):
        out = {}
        for c in self.cochains(n):
            out.setdefault(self.weight(*c), []).append(c)
        return out

    # --------------------------------------------------------------- the differential
    def diff(self, n):
        """dict source-cochain -> {target-cochain: coeff} for d: C^n -> C^{n+1}."""
        if n in self._diff:
            return self._diff[n]
        g, h = self.g, self.h
        cols = {}

        def add(src, tgt, co):
            co %= P
            if co:
                d = cols.setdefault(src, {})
                d[tgt] = (d.get(tgt, 0) + co) % P
                if not d[tgt]:
                    del d[tgt]

        for T in combinations(range(len(h)), n + 1):
            for i in range(n + 1):
                rest = T[:i] + T[i + 1:]
                sgn = (-1) ** i
                row = g.row(h[T[i]])
                for m in range(g.n):
                    for k, c in row[m].items():
                        add((rest, m), (T, k), sgn * c)
            for i in range(n + 1):
                for j in range(i + 1, n + 1):
                    rest = tuple(t for s, t in enumerate(T) if s not in (i, j))
                    sgn = (-1) ** (i + j)
                    for k, c in g.brk(h[T[i]], h[T[j]]).items():
                        if k not in self.pos:
                            raise ValueError("g_- is not a subalgebra")
                        S, s2 = sign_sort((self.pos[k],) + rest)
                        if s2 == 0:
                            continue
                        for m in range(g.n):
                            add((S, m), (T, m), sgn * s2 * c)
        self._diff[n] = cols
        return cols

    # --------------------------------------------------------------- cohomology
    def cohomology(self, n):
        """dict weight -> (dimH, basis of the block, list of representatives,
        rref'd coboundaries)."""
        Bn, Bn1 = self.blocks(n), (self.blocks(n - 1) if n else {})
        dn = self.diff(n)
        dn1 = self.diff(n - 1) if n else {}
        out = {}
        for w, src in sorted(Bn.items()):
            pos = {c: i for i, c in enumerate(src)}
            N = len(src)
            rowmap = {}
            for i, s in enumerate(src):
                for tgt, c in dn.get(s, {}).items():
                    rowmap.setdefault(tgt, np.zeros(N, dtype=np.int64))[i] = c
            rows = np.array(list(rowmap.values()), dtype=np.int64) if rowmap \
                else np.zeros((0, N), dtype=np.int64)
            Z = nullspace(rows, N)
            B = []
            for s0 in Bn1.get(w, []):
                r = np.zeros(N, dtype=np.int64)
                for tgt, c in dn1.get(s0, {}).items():
                    if tgt in pos:
                        r[pos[tgt]] = c
                if r.any():
                    B.append(r)
            Bred = rref(np.array(B, dtype=np.int64))[0] if B else np.zeros((0, N), dtype=np.int64)
            dimH = len(Z) - len(Bred)
            if dimH > 0:
                cur = list(Bred)
                rk = len(Bred)
                reps = []
                for z in Z:
                    test = np.array(cur + [z], dtype=np.int64) if cur else np.array([z])
                    if len(rref(test)[1]) > rk:
                        cur.append(z)
                        rk += 1
                        reps.append(z)
                out[w] = (dimH, src, reps, Bred)
        return out

    # --------------------------------------------------------------- g_0-action
    def act(self, x, phi, n):
        """(x.phi)(a_1..a_n) = [x, phi(a_1..a_n)] - sum_i phi(.., [x,a_i], ..),
        phi a dict tuple -> vector of length g.n."""
        g = self.g
        rowx = g.row(x)
        zero = np.zeros(g.n, dtype=np.int64)
        out = {}
        for T in combinations(range(len(self.h)), n):
            val = np.zeros(g.n, dtype=np.int64)
            cur = phi.get(T)
            if cur is not None:
                for m, c in enumerate(cur):
                    if c:
                        for k, cc in rowx[m].items():
                            val[k] = (val[k] + c * cc) % P
            for i in range(n):
                for k, c in g.brk(x, self.h[T[i]]).items():
                    if k not in self.pos:
                        raise ValueError("x does not normalise g_-")
                    S, s2 = sign_sort(T[:i] + (self.pos[k],) + T[i + 1:])
                    if s2 == 0:
                        continue
                    val = (val - c * s2 * phi.get(S, zero)) % P
            if val.any():
                out[T] = val
        return out

    def to_fun(self, vec, src):
        phi = {}
        for co, (S, m) in zip(vec, src):
            if co:
                phi.setdefault(S, np.zeros(self.g.n, dtype=np.int64))
                phi[S][m] = (phi[S][m] + co) % P
        return phi

    def from_fun(self, phi, src):
        pos = {c: i for i, c in enumerate(src)}
        out = np.zeros(len(src), dtype=np.int64)
        for S, v in phi.items():
            for m, co in enumerate(v):
                if co:
                    if (S, m) not in pos:
                        raise ValueError("action leaves the weight block")
                    out[pos[(S, m)]] = co
        return out


def module_data(ce, H, g0idx, n=2):
    """for each Z-degree: the dimension of H^n, the weights, a basis of the
    g_0-invariants, and the dimensions of the g_0-submodules generated by each
    class.  Returns dict degree -> info."""
    g = ce.g
    # group the weight blocks by Z-degree
    bydeg = {}
    for w, (dimH, src, reps, Bred) in H.items():
        d = ce.degree(*src[0])
        bydeg.setdefault(d, []).append((w, dimH, src, reps, Bred))

    info = {}
    for d in sorted(bydeg):
        entries = bydeg[d]
        # one common cochain space for the whole degree: g_0 moves a class from
        # one weight block into another, so the whole degree must be carried
        allsrc = [c for c in ce.cochains(n) if ce.degree(*c) == d]
        pos = {c: i for i, c in enumerate(allsrc)}
        N = len(allsrc)

        def emb(vec, src):
            out = np.zeros(N, dtype=np.int64)
            for co, c in zip(vec, src):
                out[pos[c]] = co
            return out

        Z, wts = [], []
        for w, dimH, src, reps, Bred in entries:
            for r in reps:
                Z.append(emb(r, src))
                wts.append(w)
        Z = np.array(Z, dtype=np.int64)
        # all coboundaries of this degree
        dprev = ce.diff(n - 1)
        Ball = []
        for s0, col in dprev.items():
            if ce.degree(*s0) != d:
                continue
            r = np.zeros(N, dtype=np.int64)
            ok = False
            for tgt, c in col.items():
                if tgt in pos:
                    r[pos[tgt]] = c
                    ok = True
            if ok and r.any():
                Ball.append(r)
        Bred = rref(np.array(Ball, dtype=np.int64))[0] if Ball else np.zeros((0, N), dtype=np.int64)
        piv = [int(np.nonzero(r)[0][0]) for r in Bred]

        def modB(v):
            v = v.copy() % P
            for i, pc in enumerate(piv):
                if v[pc]:
                    v = (v - v[pc] * Bred[i]) % P
            return v

        # Z together with the coboundaries is an independent system; precompute
        # the rref and the change-of-basis matrix once for the whole degree
        A = np.concatenate([Z, Bred], axis=0) if len(Bred) else Z
        aug = np.concatenate([A, np.eye(len(A), dtype=np.int64)], axis=1)
        Ra, _ = rref(aug)
        Rz, pvz = Ra[:, :N], None
        Rz, pvz = rref(A)
        Tz = Ra[:len(Rz), N:]

        def coords_in_Z(v):
            """coordinates of v mod B in terms of Z (Z is independent mod B)."""
            w = v.copy() % P
            co = np.zeros(len(Rz), dtype=np.int64)
            for i, c in enumerate(pvz):
                if w[c]:
                    co[i] = w[c]
                    w = (w - co[i] * Rz[i]) % P
            if w.any():
                raise ValueError("g_0 does not preserve the space of cocycles")
            return ((co @ Tz) % P)[:len(Z)]

        # matrix of each x in g_0 on H
        acts = {}
        for x in g0idx:
            rows = []
            for z in Z:
                phi = ce.to_fun(z, allsrc)
                img = ce.act(x, phi, n)
                v = np.zeros(N, dtype=np.int64)
                for S, vec in img.items():
                    for m, co in enumerate(vec):
                        if co:
                            v[pos[(S, m)]] = co
                rows.append(coords_in_Z(v))
            acts[x] = np.array(rows, dtype=np.int64)      # rows: image of Z[i]

        # invariants: v with v A = 0 for all x  (A acting on the right)
        M = np.concatenate([acts[x].T for x in g0idx], axis=0) if g0idx \
            else np.zeros((0, len(Z)), dtype=np.int64)
        inv = nullspace(M, len(Z))

        # submodule generated by each basis class
        subdims = []
        for i in range(len(Z)):
            cur = np.zeros((1, len(Z)), dtype=np.int64)
            cur[0, i] = 1
            while True:
                new = [cur]
                for x in g0idx:
                    new.append((cur @ acts[x]) % P)
                A = rref(np.concatenate(new, axis=0))[0]
                if len(A) == len(cur):
                    break
                cur = A
            subdims.append(len(cur))

        info[d] = dict(dim=len(Z), weights=wts, inv=len(inv),
                       subdims=subdims, Z=Z, src=allsrc, acts=acts)
    return info
