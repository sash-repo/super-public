#!/usr/bin/env python3
"""Is m(n;1) simple for p>2?  For a graded transitive algebra with
g_{-2} one-dimensional, every nonzero ideal contains g_{-2} (lower the top
component by g_-), so simplicity <=> transitivity + ideal(M_1) = whole.
Also prints the grading element check: ad M_tau = degree on every M_f."""
import sys
import os
_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
from nisvect import SpEch, lin
from mvect import make, pericontact

def run(p, n):
    S = make(p, n); _, fields = pericontact(S, n)
    F2f = SpEch(p)
    for u, X in fields.items(): F2f.add(X, {u: 1})
    def tofun(X):
        r, pay = F2f.reduce(X, {}); assert not r
        return {u: (-c) % p for u, c in pay.items()}
    def br(f, g): return tofun(S.bracket(lin(S, fields, f), lin(S, fields, g)))
    mons = list(fields)
    def deg(u):
        a, b = u; return sum(a) + sum(b[1:]) + 2 * b[0] - 2
    # identify tau and the constant
    one = [u for u in mons if deg(u) == -2][0]
    tau = [u for u in mons if deg(u) == 0 and u[1][0] == 1 and sum(u[0]) == 0 and sum(u[1][1:]) == 0][0]
    bad = 0
    for u in mons:
        r = br({tau: 1}, {u: 1})
        lam = None
        for w, c in r.items():
            if w != u: bad += 1
        c = r.get(u, 0)
        if c % p != (deg(u) * (1 if True else 1)) % p and (c - (-deg(u))) % p: bad += 1
    # transitivity: ad of degree<0 basis on each u of degree>=-1 not all zero (per homogeneous component, linear check)
    neg = [u for u in mons if deg(u) < 0]
    from collections import defaultdict
    layers = defaultdict(list)
    for u in mons: layers[deg(u)].append(u)
    trans = True
    for d, L in layers.items():
        if d < -1: continue
        # matrix: for each u in L, concatenated vector of [v,u], v in neg
        E = SpEch(p); rk = 0
        rows = []
        for u in L:
            vec = {}
            for k, v in enumerate(neg):
                for w, c in br({v: 1}, {u: 1}).items(): vec[(k, w)] = c
            rows.append(vec)
        idx = {}
        for vec in rows:
            vv = {}
            for key, c in vec.items():
                vv[idx.setdefault(key, len(idx))] = c
            if E.add(vv): rk += 1
        if rk < len(L): trans = False
    # ideal generated by M_1
    I = SpEch(p); I.add({mons.index(one): 1}, {one: 1}); queue = [{one: 1}]
    basis = [{one: 1}]
    while queue:
        f = queue.pop()
        for u in mons:
            g = br({u: 1}, f)
            if not g: continue
            vv = {mons.index(w): c for w, c in g.items()}
            if I.add(vv, g): queue.append(g)
    print(f"p={p} n={n} dim={len(mons)} grading-element defects={bad} transitive={trans} dim ideal(M_1)={I.dim}", flush=True)

for p, n in [(3,1),(5,1),(7,1),(3,2),(5,2),(3,3)]:
    run(p, n)
