"""Identities used in the proofs of Section 6 (n=2):
 [K_f, D_eta] = -(D_eta D_xi f) D_eta,  [K_f, D_xi] = -(D_xi D_eta f) D_xi  (supercommutators), all f;
 normal form of D_xi D_eta; K_f divergence-free; osp(2|2) generated by K_xi,K_eta,K_txi,K_teta;
 [K_xieta, D_xi] = D_xi, [K_xieta, D_eta] = -D_eta.
Usage: python3 ident2.py p N"""
import sys
import os; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
from exactlin import rank
from osp2 import Alg, osp22, br
p, N = int(sys.argv[1]), int(sys.argv[2])
A = Alg(p, N); n = A.n
bad = 0; cnt = 0
for k in range(n):
    f, pf = A.fn(k//4, (k%4)//2, k%2), A.par[k]
    K = A.K(f, pf)
    for D, Dother in ((A.DETA, A.DXI), (A.DXI, A.DETA)):
        lhs = br(A, K, pf, D, 1)
        h = A.apply(A.mul(D, Dother), f)
        rhs = A.mul(A.M(h), D)
        rhs = A.add(A.zero(), rhs, coef=[1, -1])
        cnt += 1; bad += (lhs != rhs)
print(f"[K_f,D] = -(D D' f) D: {cnt} checks, {bad} failures")
# normal form: D_xi D_eta = -xi eta d_t^2 + eta d_eta d_t + d_t - xi d_xi d_t + d_xi d_eta
X = A.add(A.mul(A.mul(A.Mxi, A.Meta), A.mul(A.Dt, A.Dt)), A.mul(A.mul(A.Meta, A.Deta), A.Dt), A.Dt,
          A.mul(A.mul(A.Mxi, A.Dxi), A.Dt), A.mul(A.Dxi, A.Deta), coef=[-1, 1, 1, -1, 1])
print("normal form of D_xi D_eta:", X == A.mul(A.DXI, A.DETA))
g = dict((nm, (A.K(f, pf), pf)) for nm, f, pf in osp22(A))
print("[K_xieta,D_xi]=D_xi:", br(A, g['xieta'][0], 0, A.DXI, 1) == A.DXI,
      " [K_xieta,D_eta]=-D_eta:", br(A, g['xieta'][0], 0, A.DETA, 1) == A.add(A.zero(), A.DETA, coef=[1, -1]))
flat = lambda M: [x for r in M for x in r]
span = [g[x][0] for x in ('xi', 'eta', 'txi', 'teta')]
pars = [1]*4
for _ in range(3):
    new = []
    for i in range(len(span)):
        for j in range(len(span)):
            new.append((br(A, span[i], pars[i], span[j], pars[j]), (pars[i]+pars[j]) % 2))
    for M, pm in new:
        if rank([flat(x) for x in span] + [flat(M)], p) > rank([flat(x) for x in span], p):
            span.append(M); pars.append(pm)
print("dim of the algebra generated by K_xi,K_eta,K_txi,K_teta:", len(span))
