#!/usr/bin/env python3
"""Is the simple core of kas(7;1) that of po_1(6;1)?  Inside kas(7)'s own realization
(kas7.py): the complete prolong P of g_- (the contact algebra), its P_0 = k_0, the three
hyperplanes H of k_0 containing [k_0, k_0], and whether the core J of kas equals the ideal
generated by g_{-1} in the prolong of (g_-, H), for the H = J_0 (which must be one of them,
J_0 being an ideal of codimension 1 of G_0 = k_0)."""
import os, sys
src = open('kas7.py').read()
src = src.replace("    G = prolong(sp, neg, g0, g1=lifted)\n", "    G = prolong(sp, neg, g0, g1=lifted)\n    return sp, neg, g0, G\n")
src = src.replace("if __name__ == '__main__':\n    main()", "")
g = {'__name__': 'kas7mod'}
sys.argv = ['kas7.py', '1']
exec(compile(src, 'kas7mod', 'exec'), g)
sp, neg, g0, G = g['main']()
from prolong import prolong, generators, ad_closure, Graded
J = ad_closure(sp, generators(G), G.basis(-1))
print('kas: dim G', G.dim(), {d: G.dim(d) for d in G.degrees()}, 'dim J', J.dim(), {d: J.dim(d) for d in J.degrees()})
P = prolong(sp, neg, None, verbose=False)
print('complete prolong of g_-: dim', P.dim(), {d: P.dim(d) for d in P.degrees()})
B0 = P.basis(0)
print('G_0 = P_0:', G.dim(0) == P.dim(0) and all(P.contains(v) for v in G.basis(0)))
D = Graded(sp)
for a in B0:
    for b in B0:
        D.add(sp.bracket(a, b))
print('dim [P_0, P_0] =', D.dim())
print('J_0 contains [P_0,P_0]:', all(J.contains(v) for v in D.basis()))
P2 = prolong(sp, neg, J.basis(0), verbose=False)
I = ad_closure(sp, generators(P2), P2.basis(-1))
print('prolong of (g_-, J_0): dim', P2.dim(), {d: P2.dim(d) for d in P2.degrees()},
      '; its ideal generated by g_-1: dim', I.dim(), {d: I.dim(d) for d in I.degrees()})
print('J(kas) contained in it:', all(I.contains(v) for v in J.basis()), '; equal:', I.dim() == J.dim())
z = P.basis(-2)[0]
print('g_-2 central in the prolong of (g_-, J_0):', all(not sp.bracket(z, v) for v in P2.basis()))
