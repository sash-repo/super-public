#!/usr/bin/env python3
r"""
run_row.py NAME [NAME ...] --- the N~ = (1,...,1) computation for rows of rows.py.

For each row two independent routes:
 (A) DIRECT: the paper's own fields, all heights 1; the g_0 generators that need
     a divided power x^(k), k >= 2, do not exist at N~ = 1 and are reported
     as dropped;
 (B) ABSTRACT: the non-positive part read off at the heights the paper's fields
     need (srcH), as an abstract Lie algebra, then realized on O(m;1) by
     blattner.py (which decides whether a realization with N~ = 1 exists at all:
     it does iff g_- has a 2-map compatible with g_0).
For each result: the complete prolong G, the ideal J generated by g_{-1}, its
simplicity (graded criterion), the super-closure (odd squares), the restricted
closure (all squares), the centralizer of J in the restricted closure.
Results are appended to results/NAME.json and printed.
"""
import json
import os
import sys
import time

from f2vf import Space, parse_field, find_weights
from prolong import (prolong, Graded, generators, ad_closure, restricted_closure,
                     simple_test, log)
from rowtools import nonpositive, to_abstract
from absutil import abstract
from blattner import Realization
import rows as R


def space_for(spec, heights, weights=None):
    return Space(heights, spec['degs'], spec['par'], weights)


def names_of(spec):
    nm = {}
    for i, c in enumerate(spec['coords']):
        nm[c] = i
    return nm


def fields(sp, strs, nm):
    return [parse_field(sp, s, nm) for s in strs]


def needs_height(s):
    """max exponent appearing in a field string"""
    mx = 1
    for tok in s.replace('+', ' ').split():
        if '^(' in tok:
            mx = max(mx, int(tok.split('^(')[1].rstrip(')')))
    return mx


def analyse(sp, G, label):
    t0 = time.time()
    out = {'label': label}
    out['components'] = {d: [G.dim(d), list(G.parity_dims(d))] for d in G.degrees()}
    out['dim'] = G.dim()
    out['sdim'] = list(G.parity_dims())
    gens = generators(G)
    J = ad_closure(sp, gens, G.basis(-1))
    out['J'] = [J.dim(), list(J.parity_dims())]
    out['J components'] = {d: J.dim(d) for d in J.degrees()}
    st = simple_test(sp, J)
    out['J simple'] = st

    def oddsq(v):
        if sp.kpar(next(iter(v))) == 1:
            return [sp.square(v)]
        return []
    Js = ad_closure(sp, gens, G.basis(-1), extra=oddsq)
    out['J super-closed'] = [Js.dim(), list(Js.parity_dims())]
    if Js.dim() != J.dim():
        out['Js simple (as Lie algebra)'] = simple_test(sp, Js)
    Rr = restricted_closure(sp, J)
    out['2-closure of J'] = [Rr.dim(), list(Rr.parity_dims())]
    # centralizer of J in its 2-closure (then the closure is the minimal
    # p-envelope iff this is 0)
    C = centralizer(sp, Rr, J)
    out['centralizer of J in 2-closure'] = C
    # 2|4: even part closed under squares of even elements (of Js)
    def evsq(v):
        if sp.kpar(next(iter(v))) == 0:
            return [sp.square(v)]
        return []
    R24 = ad_closure(sp, gens, Js.basis(), extra=lambda v: evsq(v) + oddsq(v))
    out['2|4-closure of super J'] = [R24.dim(), list(R24.parity_dims())]
    RG = restricted_closure(sp, G)
    out['2-closure of G'] = [RG.dim(), list(RG.parity_dims())]
    if Rr.dim() != J.dim():
        # which squares are missing: even vs odd basis elements of J; (2,4)-test
        miss_ev = miss_od = miss4 = 0
        for v in J.basis():
            sq = sp.square(v)
            par = sp.kpar(next(iter(v)))
            if not J.contains(sq):
                if par == 0:
                    miss_ev += 1
                else:
                    miss_od += 1
                    if not J.contains(sp.square(sq)):
                        miss4 += 1
        out['J basis: even squares outside J'] = miss_ev
        out['J basis: odd squares outside J'] = miss_od
        out['J basis: odd 4th powers outside J'] = miss4
        out['(2,4)-structure w.r.t. parity'] = (miss_ev == 0 and miss4 == 0)
        log('   squares outside J: even %d, odd %d; odd 4th powers outside J: %d'
            % (miss_ev, miss_od, miss4))
    log('== %s   (analysis %.1fs)' % (label, time.time() - t0))
    for d in G.degrees():
        log('   deg %3d: dim %6d  sdim %-14s J: %d' % (d, G.dim(d), G.parity_dims(d), J.dim(d)))
    for k in ('dim', 'sdim', 'J', 'J simple', 'J super-closed', '2-closure of J',
              'centralizer of J in 2-closure', '2|4-closure of super J', '2-closure of G'):
        log('   %-30s %s' % (k, out[k]))
    if 'Js simple (as Lie algebra)' in out:
        log('   %-30s %s' % ('Js simple (Lie)', out['Js simple (as Lie algebra)']))
    return out


def centralizer(sp, Rr, J):
    """dim of {r in Rr : [r, J] = 0}"""
    from f2vf import kernel_bits
    JB = J.basis()
    tot = 0
    for d in Rr.degrees():
        B = Rr.basis(d)
        imgs = []
        idx = {}
        for x in B:
            v = 0
            for ci, y in enumerate(JB):
                for kk in sp.bracket(x, y):
                    j = idx.setdefault((ci, kk), len(idx))
                    v ^= 1 << j
            imgs.append(v)
        tot += len(kernel_bits(imgs))
    return tot


def run(name, routes=('A', 'B')):
    spec = R.ROWS[name]
    nm = names_of(spec)
    m = len(spec['coords'])
    res = {'row': name, 'table': spec['table'], 'section': spec['section']}
    log('################ %s  (%s, Sect. %s)' % (name, spec['table'], spec['section']))
    complete = spec['g0'] == 'complete'
    # ---------------------------------------------------------- route A
    if 'A' in routes:
        sp0 = space_for(spec, [1] * m)
        neg = fields(sp0, spec['neg'], nm)
        g0s = [] if complete else [s for s in spec['g0'] if needs_height(s) == 1]
        dropped = [] if complete else [s for s in spec['g0'] if needs_height(s) > 1]
        g0 = fields(sp0, g0s, nm)
        W = find_weights(sp0, neg + g0)
        sp = space_for(spec, [1] * m, W)
        neg = fields(sp, spec['neg'], nm)
        g0 = fields(sp, g0s, nm)
        log('route A: heights 1, weight rank %d, g0 generators dropped (need x^(k)): %d'
            % (len(W[0]), len(dropped)))
        t0 = time.time()
        G = prolong(sp, neg, None if complete else g0)
        log('   prolong %.1fs' % (time.time() - t0))
        outA = analyse(sp, G, name + ' route A (paper coordinates, N~=1)')
        outA['dropped g0 generators'] = dropped
        if spec.get('g0check'):
            chk = fields(sp, spec['g0check'], nm)
            outA['printed g0 elements in G_0'] = sum(1 for x in chk if G.contains(x))
            outA['printed g0 elements'] = len(chk)
            log('   printed g0 elements lying in G_0: %d of %d'
                % (outA['printed g0 elements in G_0'], len(chk)))
        res['A'] = outA
    # ---------------------------------------------------------- route B
    if 'B' in routes:
        H = [1] * m
        for c, h in spec.get('srcH', {}).items():
            H[nm[c]] = h
        if complete and not spec.get('srcH'):
            H = [2] * m            # the complete g_0 at unconstrained (large) heights
        spS0 = space_for(spec, H)
        neg = fields(spS0, spec['neg'], nm)
        g0 = [] if complete else fields(spS0, spec['g0'], nm)
        W = find_weights(spS0, neg + g0)
        spS = space_for(spec, H, W)
        neg = fields(spS, spec['neg'], nm)
        g0 = [] if complete else fields(spS, spec['g0'], nm)
        N0 = nonpositive(spS, neg, g0, complete_neg=complete)
        res['B source g_<=0'] = {d: N0.dim(d) for d in N0.degrees()}
        log('route B: source heights %s, g_<=0 dims %s' % (H, res['B source g_<=0']))
        A = to_abstract(spS, N0)
        try:
            Rz = Realization(A)
            D = Rz.realize()
            res['B full g0 realizable'] = True
        except (ValueError, AssertionError) as e:
            log('   NO realization of the full g_<=0 on O(m;1): %s' % e)
            res['B full g0 realizable'] = False
            res['B reason'] = str(e)
            from blattner import best_core, sub_abstract
            try:
                best, found, total = best_core(A)
            except ValueError as e2:
                log('   no largest compatible g_0\' either: %s (route A is the result)' % e2)
                res['B best_core'] = str(e2)
                save(name, res)
                return res
            n0 = sum(1 for i in range(A.n) if A.deg[i] == 0)
            # distinct g0' subspaces
            spans = {}
            for pm, g0p in found:
                key = tuple(sorted(g0p))
                spans.setdefault(frozenset(_span_ints(g0p)), (pm, g0p))
            log("   best compatible g_0': dim %d of %d; %d of %d p-maps attain it, %d distinct g_0'"
                % (best, n0, len(found), total, len(spans)))
            res["B g0' dim"] = [best, n0]
            res["B distinct g0'"] = len(spans)
            outs = []
            for si, (pm, g0p) in enumerate(spans.values()):
                try:
                    A2 = sub_abstract(A, None, g0p)
                except ValueError as e:
                    log("   g_0' #%d skipped: %s" % (si, e))
                    continue
                Rz = Realization(A2)
                D = Rz.realize()
                fl = [D[i] for i in range(A2.n)]
                W2 = find_weights(Rz.sp, fl)
                sp2 = Space([1] * Rz.m, Rz.sp.degs, Rz.sp.par, W2)
                negB = [D[i] for i in range(A2.n) if A2.deg[i] < 0]
                g0B = [D[i] for i in range(A2.n) if A2.deg[i] == 0]
                G2 = prolong(sp2, negB, g0B, verbose=False)
                outs.append(analyse(sp2, G2, name + " route B (largest N~=1 g_0' #%d)" % si))
            res['B'] = outs
            save(name, res)
            return res
        fl = [D[i] for i in range(A.n)]
        W2 = find_weights(Rz.sp, fl)
        sp2 = Space([1] * Rz.m, Rz.sp.degs, Rz.sp.par, W2)
        negB = [D[i] for i in range(A.n) if A.deg[i] < 0]
        g0B = [D[i] for i in range(A.n) if A.deg[i] == 0]
        log('   realized on O(%d;1), p-map nonzero on %d basis elements, weight rank %d'
            % (Rz.m, sum(1 for b in Rz.pmap if Rz.pmap[b]), len(W2[0])))
        G2 = prolong(sp2, negB, g0B)
        outB = analyse(sp2, G2, name + ' route B (abstract g_<=0, Blattner, N~=1)')
        outB['realizable at N~=1'] = True
        outB['p-map nonzero'] = sum(1 for b in Rz.pmap if Rz.pmap[b])
        res['B'] = outB
    save(name, res)
    return res


def _span_ints(vecs):
    from f2vf import BitEchelon
    E = BitEchelon()
    for v in vecs:
        E.add(v)
    # canonical: reduced echelon
    piv = dict(E.piv)
    for p in sorted(piv):
        for q in list(piv):
            if q != p and (piv[q] >> p) & 1:
                piv[q] ^= piv[p]
    return sorted(piv.values())


def save(name, res):
    os.makedirs('results', exist_ok=True)
    with open('results/%s.json' % name.replace('~', 't'), 'w') as f:
        json.dump(res, f, indent=1, default=str)


if __name__ == '__main__':
    args = sys.argv[1:]
    routes = ('A', 'B')
    if args and args[0] in ('A', 'B', 'AB'):
        routes = tuple(args[0])
        args = args[1:]
    for n in args:
        run(n, routes)
