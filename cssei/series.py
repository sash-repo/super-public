#!/usr/bin/env python3
r"""
series.py --- the serial families of Table 25.2 of BGLLS at N~ = (1,...,1).

Each family is realized in its standard grading by vector fields on O(M;1)
(all heights 1), as the Cartan prolong of (g_-, g_0) inside vect(M;1); then the
analysis of run_row.analyse (G, the ideal J generated by g_{-1}, simplicity by
the graded criterion, restricted closure, 2|4-closure).  Superizations: every
parity assignment of the coordinates for which g_- and g_0 stay parity-graded,
up to the obvious symmetries; for each, sdim J and sdim of the super-closure
(J + odd squares).

Families (M = number of indeterminates):
  vect(M), svect(M)                       lines 1, 2
  hP(2N)  (form Pi, alternate)            lines 3 (m even), 8 = le
  hI(M)   (form Pi_{2n} + 1_m, m >= 1)    line 3 (m odd), non-alternate
  shP(2N) (g_0 = spe(N) = {htr = 0})      line 9 = sle
  k(2N+1)                                 lines 4, 5 = m
  poab(2N; lam), lam in {0, 1, oo}        lines 6, 6_1, 6_oo, 7 (b_{a,b} in m-coordinates)
Usage: series.py FAMILY M [M ...]
"""
import sys, json, os, itertools, time
import run_row as RR
from f2vf import Space, parse_field, find_weights
from prolong import prolong, generators, ad_closure, log, Graded


def names(coords):
    return {c: i for i, c in enumerate(coords)}


def ham(pairs, f_terms, coords):
    """H_f = sum_a d_a(f) d_{a*} over F_2 for quadratic f given as list of
    (a, b) (a == b means a^(2)); pairs: dict a -> a* (a coordinate name)."""
    terms = set()
    for a, b in f_terms:
        if a == b:
            terms ^= {'%s d%s' % (a, pairs[a])}
        else:
            terms ^= {'%s d%s' % (b, pairs[a])}
            terms ^= {'%s d%s' % (a, pairs[b])}
    return ' + '.join(sorted(terms))


def spec_vect(M, special=False):
    X = ['x%d' % i for i in range(1, M + 1)]
    s = dict(coords=X, degs=[1] * M, neg=['d' + x for x in X])
    if not special:
        s['g0'] = 'complete'
    else:
        g0 = ['%s d%s' % (a, b) for a in X for b in X if a != b]
        g0 += ['%s d%s + %s d%s' % (X[0], X[0], x, x) for x in X[1:]]
        s['g0'] = g0
    # superizations: first a coordinates even, the rest odd (a = M..1 for vect; all)
    s['pars'] = {'(%d|%d)' % (M - b, b): [0] * (M - b) + [1] * b for b in range(0, M + 1)}
    return s


def spec_h(M, kind):
    """kind 'P': form Pi on M = 2N coords (pairs u_i,v_i);
       kind 'I': form Pi_{2n} + 1_m on M = 2n + m, m >= 1; we take m = 1 or 2
       for the prolong, the superizations h(2n|m) use their own B."""
    raise NotImplementedError


def spec_ham(npairs, nsingle, sl_half=False):
    """h_B with B = Pi_{2 npairs} + 1_{nsingle}; coords u_i, v_i, w_j.
    g_0 = all linear H_f (f quadratic incl. divided squares) = aut(B);
    sl_half: keep only htr = 0 (the u-block trace), i.e. spe."""
    U = ['u%d' % i for i in range(1, npairs + 1)]
    V = ['v%d' % i for i in range(1, npairs + 1)]
    W = ['w%d' % j for j in range(1, nsingle + 1)]
    X = U + V + W
    star = {}
    for u, v in zip(U, V):
        star[u], star[v] = v, u
    for w in W:
        star[w] = w
    g0 = []
    quad = [(a, b) for i, a in enumerate(X) for b in X[i:]]
    for a, b in quad:
        g0.append((a, b))
    if sl_half:
        # BGLLS Sect. 2.8: the prolong of (id, pe^(2)) is {Le_f | Delta f = 0}, Delta = sum d_{u_i} d_{v_i};
        # on quadratic f: no divided squares (they are not in pe^(1)), and Delta(u_i v_i) = 1
        def dl(ab):
            a, b = ab
            return int(a != b and star[a] == b and a in U + V)
        g0 = [ab for ab in g0 if ab[0] != ab[1]]
        diag = [ab for ab in g0 if dl(ab)]
        rest = [ab for ab in g0 if not dl(ab)]
        g0f = [[ab] for ab in rest] + [[diag[0], d] for d in diag[1:]]
    else:
        g0f = [[ab] for ab in g0]
    g0s = [ham(star, f, X) for f in g0f]
    g0s = [s for s in g0s if s]
    return dict(coords=X, degs=[1] * len(X), neg=['d' + x for x in X], g0=g0s,
                U=U, V=V, W=W)


def spec_k(N, m_coords=False):
    """contact: t (deg 2), pairs (u_i, v_i); g_-1: d_u + v d_t, d_v."""
    U = ['u%d' % i for i in range(1, N + 1)]
    V = ['v%d' % i for i in range(1, N + 1)]
    X = ['t'] + U + V
    neg = ['dt'] + ['d%s + %s dt' % (u, v) for u, v in zip(U, V)] + ['d%s' % v for v in V]
    return dict(coords=X, degs=[2] + [1] * (2 * N), neg=neg, g0='complete', U=U, V=V)


def pair_pars(N, lead, kinds):
    """parities for coords lead + U + V: kinds = per pair 'ee','oo','eo'."""
    pu = [0 if k[0] == 'e' else 1 for k in kinds]
    pv = [0 if k[1] == 'e' else 1 for k in kinds]
    return lead + pu + pv


def superization_parities(fam, n):
    out = {}
    if fam in ('hP', 'shP'):
        N = n
        for k in range(N + 1):
            out['h(%d|%d)' % (2 * (N - k), 2 * k)] = pair_pars(N, [], ['ee'] * (N - k) + ['oo'] * k)
        out['le(%d)' % N if fam == 'hP' else 'sle(%d)' % N] = pair_pars(N, [], ['eo'] * N)
    elif fam == 'k':
        N = n
        for k in range(N + 1):
            out['k(%d|%d)' % (2 * (N - k) + 1, 2 * k)] = pair_pars(N, [0], ['ee'] * (N - k) + ['oo'] * k)
        out['m(%d)' % N] = pair_pars(N, [1], ['eo'] * N)
    elif fam == 'poab':
        N = n
        # m-coordinates tau, q_i, xi_i: b_{a,b}(n) has tau odd, q even, xi odd
        out['b(%d)' % N] = [1] + [0] * N + [1] * N
        for k in range(N + 1):
            out['k-type (%d|%d)' % (2 * (N - k) + 1, 2 * k)] = [0] + [0] * (N - k) + [1] * k + [0] * (N - k) + [1] * k
    return out


def run_spec(label, spec, pars, extra_g0=None):
    X = spec['coords']
    nm = names(X)
    m = len(X)
    complete = spec['g0'] == 'complete'
    sp0 = Space([1] * m, spec['degs'])
    neg = [parse_field(sp0, s, nm) for s in spec['neg']]
    g0 = [] if complete else [parse_field(sp0, s, nm) for s in spec['g0']]
    W = find_weights(sp0, neg + g0)
    sp = Space([1] * m, spec['degs'], None, W)
    neg = [parse_field(sp, s, nm) for s in spec['neg']]
    g0 = None if complete else [parse_field(sp, s, nm) for s in spec['g0']]
    if extra_g0 is not None:
        g0 = extra_g0(sp)
    log('######## %s  (M = %d, weight rank %d)' % (label, m, len(W[0])))
    t0 = time.time()
    G = prolong(sp, neg, g0, verbose=False)
    log('   prolong %.1fs, dims %s' % (time.time() - t0, {d: G.dim(d) for d in G.degrees()}))
    out = RR.analyse(sp, G, label)
    out['superizations'] = superize(sp, G, pars)
    return out


def superize(sp, G, pars):
    res = {}
    gens = generators(G)
    J = ad_closure(sp, gens, G.basis(-1))
    old = sp.par
    for name, p in pars.items():
        sp.par = list(p)
        try:
            sJ = J.parity_dims()
            sG = G.parity_dims()
        except AssertionError:
            res[name] = 'not parity-graded'
            log('   %-16s not parity-graded' % name)
            continue

        def oddsq(v):
            if sp.kpar(next(iter(v))) == 1:
                return [sp.square(v)]
            return []
        Js = ad_closure(sp, gens, G.basis(-1), extra=oddsq)
        try:
            sJs = Js.parity_dims()
        except AssertionError:
            sJs = 'not graded'
        res[name] = {'G': list(sG), 'J': list(sJ), 'J+odd squares': list(sJs) if not isinstance(sJs, str) else sJs}
        log('   %-16s sdim G %-12s sdim J %-12s sdim (J + odd squares) %s' % (name, sG, sJ, sJs))
    sp.par = old
    return res


def poab_g0_choices(sp, G):
    """the three hyperplanes of m_0 containing [m_0, m_0] (they are the kernels
    of the three nonzero functionals a*mu + b*l over F_2)."""
    from f2vf import Echelon
    B0 = G.basis(0)
    Dm = Graded(sp)
    for a in B0:
        for b in B0:
            Dm.add(sp.bracket(a, b))
    comp = [v for v in B0 if not Dm.contains(v)]
    # complete [m0,m0] to m0: pick a complement basis c1, c2
    H = Graded(sp)
    for v in Dm.basis():
        H.add(v)
    cs = []
    for v in B0:
        if H.add(v):
            cs.append(v)
    assert len(cs) == 2, 'codim of [m0,m0] in m0 is %d' % len(cs)
    c1, c2 = cs
    return {'<c1>': Dm.basis() + [c1], '<c2>': Dm.basis() + [c2],
            '<c1+c2>': Dm.basis() + [set(c1) ^ set(c2)]}


def main():
    fam = sys.argv[1]
    sizes = [int(a) for a in sys.argv[2:]]
    os.makedirs('results/series', exist_ok=True)
    for n in sizes:
        if fam in ('vect', 'svect'):
            spec = spec_vect(n, special=(fam == 'svect'))
            res = run_spec('%s(%d;1)' % (fam, n), spec, spec['pars'])
        elif fam == 'hP':
            spec = spec_ham(n, 0)
            res = run_spec('hP(%d;1)' % (2 * n), spec, superization_parities('hP', n))
        elif fam == 'shP':
            spec = spec_ham(n, 0, sl_half=True)
            res = run_spec('shP(%d;1)' % (2 * n), spec, superization_parities('shP', n))
        elif fam == 'hI':
            M = n
            res = {}
            for mm in range(1, M + 1):
                if (M - mm) % 2:
                    continue
                npairs = (M - mm) // 2
                spec = spec_ham(npairs, mm)
                pars = {'h(%d|%d)' % (2 * npairs, mm): [0] * (2 * npairs) + [1] * mm}
                if mm == 1 or mm == 2 or True:
                    res['B = Pi_%d + 1_%d' % (2 * npairs, mm)] = run_spec(
                        'hI(%d;1), B = Pi_%d + 1_%d' % (M, 2 * npairs, mm), spec, pars)
        elif fam == 'k':
            spec = spec_k(n)
            res = run_spec('k(%d;1)' % (2 * n + 1), spec, superization_parities('k', n))
        elif fam == 'poab':
            N = n
            X = ['tau'] + ['q%d' % i for i in range(1, N + 1)] + ['xi%d' % i for i in range(1, N + 1)]
            spec = dict(coords=X, degs=[2] + [1] * (2 * N),
                        neg=['dtau'] + ['dq%d + xi%d dtau' % (i, i) for i in range(1, N + 1)] +
                            ['dxi%d' % i for i in range(1, N + 1)], g0='complete')
            nm = names(X)
            sp0 = Space([1] * len(X), spec['degs'])
            negf = [parse_field(sp0, s, nm) for s in spec['neg']]
            W = find_weights(sp0, negf)
            sp = Space([1] * len(X), spec['degs'], None, W)
            negf = [parse_field(sp, s, nm) for s in spec['neg']]
            Gm = prolong(sp, negf, None, verbose=False, maxdeg=0)
            choices = poab_g0_choices(sp, Gm)
            res = {}
            for lab, g0b in choices.items():
                res[lab] = run_spec('b_{a,b}(%d;1) -> poab(%d;1), g_0 = [m_0,m_0] + %s' % (N, 2 * N, lab),
                                    spec, superization_parities('poab', N),
                                    extra_g0=lambda sp2, g0b=g0b: [set(v) for v in g0b])
        else:
            raise SystemExit('unknown family')
        with open('results/series/%s_%d.json' % (fam, n), 'w') as f:
            json.dump(res, f, indent=1, default=str)


if __name__ == '__main__':
    main()
