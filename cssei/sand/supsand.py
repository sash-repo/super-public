#!/usr/bin/env python3
r"""Sandwiches of the superizations by method 2.

For a Z/2-grading of g given by an idempotent derivation D (g_ev = Ker D, g_od = Im D),
the superization S = s(g, D) is realized inside End g:
   S_ev = ad g_ev + Span{(ad x)^2 | x in g_od},   S_od = ad g_od,
the bracket of any two elements being the commutator (char 2) and the squaring of an odd
element its square in End g.  Sandwiches: homogeneous s with (ad_s)^2 = 0 and
[[S,s],[S,s]] = 0 ; the sandwich subalgebra s(S) = the
subsuperalgebra generated by them (closed under brackets and squares); its normaliser;
maximality among the subsuperalgebras (a homogeneous u outside suffices)."""
import sys, os, json, time, random
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from sand import Span, reduce, kernel
from walk import nil2_rows


def bits(v):
    i = 0
    while v:
        if v & 1:
            yield i
        v >>= 1
        i += 1


class Mat:
    """n x n matrices over F_2 as tuples of column bitmasks."""
    def __init__(self, n):
        self.n = n

    def app(self, A, v):
        r = 0
        for k in bits(v):
            r ^= A[k]
        return r

    def mul(self, A, B):
        return tuple(self.app(A, B[j]) for j in range(self.n))

    def flat(self, A):
        v = 0
        for j, c in enumerate(A):
            v |= c << (j * self.n)
        return v

    def unflat(self, v):
        m = (1 << self.n) - 1
        return tuple((v >> (j * self.n)) & m for j in range(self.n))


def superization(tab, D):
    """D: tuple of columns (D e_j).  Returns (table of S, parity mask, squares of odd basis)."""
    n = len(tab)
    MT = Mat(n)
    ad = [tuple(tab[i][j] for j in range(n)) for i in range(n)]

    def adv(x):
        A = [0] * n
        for i in bits(x):
            A = [A[j] ^ ad[i][j] for j in range(n)]
        return tuple(A)
    g1 = Span(list(D)).basis()                       # Im D
    g0 = kernel(list(D), n)                          # Ker D
    ev = Span()
    evb = []
    for x in g0:
        f = MT.flat(adv(x))
        if ev.add(f):
            evb.append(f)
    for x in g1:
        A = adv(x)
        f = MT.flat(MT.mul(A, A))
        if ev.add(f):
            evb.append(f)
    odb = [MT.flat(adv(x)) for x in g1]
    basis = evb + odb
    par = sum(1 << k for k in range(len(evb), len(basis)))
    Sp = Span()
    # coordinates: keep an echelon with preimage tracking
    piv = []

    def add(v, idx):
        pre = 1 << idx
        for p, r, q in piv:
            if (v >> p) & 1:
                v ^= r
                pre ^= q
        assert v, 'dependent'
        piv.append((v.bit_length() - 1, v, pre))
    for k, v in enumerate(basis):
        add(v, k)

    def coords(v):
        pre = 0
        for p, r, q in sorted(piv, reverse=True):
            if (v >> p) & 1:
                v ^= r
                pre ^= q
        assert v == 0, 'not in S'
        return pre
    mats = [MT.unflat(v) for v in basis]
    N = len(basis)
    T = [[0] * N for _ in range(N)]
    for i in range(N):
        for j in range(i + 1, N):
            c = MT.flat(MT.mul(mats[i], mats[j])) ^ MT.flat(MT.mul(mats[j], mats[i]))
            T[i][j] = T[j][i] = coords(c) if c else 0
    sq = {}
    for i in range(len(evb), N):
        c = MT.flat(MT.mul(mats[i], mats[i]))
        sq[i] = coords(c) if c else 0
    return T, par, sq, len(evb), len(odb)


class SAlg:
    def __init__(self, T, par, sq):
        self.T, self.n, self.par, self.sqb = T, len(T), par, sq

    def br(self, u, v):
        w = 0
        for i in bits(u):
            row = self.T[i]
            for j in bits(v):
                w ^= row[j]
        return w

    def sq(self, x):                  # x odd
        idx = list(bits(x))
        w = 0
        for a in idx:
            w ^= self.sqb[a]
        for s in range(len(idx)):
            for t in range(s + 1, len(idx)):
                w ^= self.T[idx[s]][idx[t]]
        return w

    def is_sandwich2(self, x):
        img = Span([self.br(x, 1 << j) for j in range(self.n)]).basis()
        return all(self.br(a, b) == 0 for a in img for b in img)

    def generated(self, gens, start=()):
        S = Span(start)
        for g in gens:
            S.add(g)
        changed = True
        while changed:
            changed = False
            B = S.basis()
            new = []
            for a in B:
                for b in B:
                    c = self.br(a, b)
                    if c and c not in S:
                        new.append(c)
            # odd part of S: squares of an odd basis
            odd = [v for v in self.homog_basis(S) if v & self.par]
            for v in odd:
                c = self.sq(v)
                if c and c not in S:
                    new.append(c)
            for c in new:
                if S.add(c):
                    changed = True
        return S

    def homog_basis(self, S):
        ev = [v for v in intersect(S, ((1 << self.n) - 1) ^ self.par, self.n)]
        od = [v for v in intersect(S, self.par, self.n)]
        return ev + od

    def normaliser(self, S):
        bs = S.basis()
        imgs = []
        for j in range(self.n):
            v = 0
            sh = 0
            for s in bs:
                v |= reduce(self.br(1 << j, s), S.piv) << sh
                sh += self.n
            imgs.append(v)
        return Span(kernel(imgs, self.n))

    def is_maximal(self, M):
        for mask in (((1 << self.n) - 1) ^ self.par, self.par):
            comp = []
            T = Span(M.basis())
            for j in bits(mask):
                if T.add(1 << j):
                    comp.append(1 << j)
            k = len(comp)
            if k > 16:
                return None
            for c in range(1, 1 << k):
                u = 0
                for i in range(k):
                    if (c >> i) & 1:
                        u ^= comp[i]
                if len(self.generated([u], M.basis())) < self.n:
                    return False
        return True


def intersect(S, mask, n):
    """basis of S n Span{e_j | j in mask} (a coordinate subspace)."""
    # S n W: kernel of the projection of S onto the complementary coordinates
    B = S.basis()
    comp = ((1 << n) - 1) ^ mask
    k = kernel([b & comp for b in B], n)
    out = []
    for c in k:
        v = 0
        for i in bits(c):
            v ^= B[i]
        out.append(v)
    return out


def analyse(tab, D):
    T, par, sq, a, b = superization(tab, D)
    A = SAlg(T, par, sq)
    n = A.n
    evidx = [j for j in range(n) if not (par >> j) & 1]
    odidx = [j for j in range(n) if (par >> j) & 1]
    sw_ev = [x for x in nil2_rows(T, evidx) if A.is_sandwich2(x)]
    sw_od = [x for x in nil2_rows(T, odidx) if A.is_sandwich2(x)]
    S = A.generated(sw_ev + sw_od)
    res = dict(sdim=(a, b), sw=(len(sw_ev), len(sw_od)))
    hb = A.homog_basis(S)
    res['sdim_s'] = (sum(1 for v in hb if not v & par), sum(1 for v in hb if v & par))
    if 0 < len(S) < n:
        Nn = A.normaliser(S)
        hn = A.homog_basis(Nn)
        e = sum(1 for v in hn if not v & par)
        res['codim_n'] = (a - e, b - (len(hn) - e))
        res['n_max'] = A.is_maximal(Nn) if len(Nn) < n else None
    return res


if __name__ == '__main__':
    # usage: supsand.py TABLE.json WORDS.json [sample-per-class]
    tab = json.load(open(sys.argv[1]))['tab']
    W = json.load(open(sys.argv[2]))
    DER, words = W['der'], W['words']
    n = len(tab)
    samp = int(sys.argv[3]) if len(sys.argv) > 3 else 0
    random.seed(1)
    if samp:
        words = random.sample(words, min(samp, len(words)))
    from collections import Counter
    cnt = Counter()
    t0 = time.time()
    for w in words:
        M = [0] * n
        for k in bits(w):
            M = [M[j] ^ DER[k][j] for j in range(n)]
        r = analyse(tab, tuple(M))
        key = json.dumps(r, sort_keys=True)
        cnt[key] += 1
    print(os.path.basename(sys.argv[1]), 'gradings examined', len(words), '(%.0fs)' % (time.time() - t0))
    for k, v in sorted(cnt.items(), key=lambda kv: -kv[1]):
        print('  %6d  %s' % (v, k), flush=True)
