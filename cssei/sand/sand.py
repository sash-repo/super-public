#!/usr/bin/env python3
r"""Sandwiches of the new simple Lie algebras over F_2.

For L given by a table: the F_2-rational sandwiches (ad x)^2 = 0 and
[[L,x],[L,x]] = 0 ; the sandwich subalgebra s(L); its
normaliser n_L(s); codim; is n_L(s) maximal (over F_2: the subalgebra generated by
n_L(s) and u is L for every u outside); the subalgebras of codimension 1."""
import sys, os, json, time
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from walk import nil2, codim1


def reduce(v, piv):
    for p, r in piv:
        if (v >> p) & 1:
            v ^= r
    return v


class Span:
    def __init__(self, vecs=()):
        self.piv = []
        for v in vecs:
            self.add(v)

    def add(self, v):
        v = reduce(v, self.piv)
        if v == 0:
            return False
        p = v.bit_length() - 1
        self.piv = [(q, r ^ v if (r >> p) & 1 else r) for q, r in self.piv]
        self.piv.append((p, v))
        return True

    def __contains__(self, v):
        return reduce(v, self.piv) == 0

    def __len__(self):
        return len(self.piv)

    def basis(self):
        return [r for _, r in self.piv]


class Alg:
    def __init__(self, tab):
        self.tab, self.n = tab, len(tab)

    def br(self, u, v):
        w = 0
        i = 0
        while u:
            if u & 1:
                row = self.tab[i]
                vv, j = v, 0
                while vv:
                    if vv & 1:
                        w ^= row[j]
                    vv >>= 1
                    j += 1
            u >>= 1
            i += 1
        return w

    def ad_cols(self, x):
        return [self.br(x, 1 << j) for j in range(self.n)]

    def is_sandwich2(self, x):
        img = Span(self.ad_cols(x)).basis()
        return all(self.br(a, b) == 0 for a in img for b in img)

    def generated(self, gens, start=()):
        S = Span(start)
        new = [g for g in gens if S.add(g)]
        base = S.basis()
        queue = list(base)
        allv = list(base)
        while queue:
            a = queue.pop()
            for b in list(allv):
                c = self.br(a, b)
                if S.add(c):
                    queue.append(c)
                    allv.append(c)
        return S

    def normaliser(self, S):
        # x with [x, s] in S for all s in basis(S): linear in x
        bs = S.basis()
        rows = []          # for each e_j, the vector of reduced [e_j, s_k] images
        imgs = []
        for j in range(self.n):
            v = 0
            sh = 0
            for s in bs:
                r = reduce(self.br(1 << j, s), S.piv)
                v |= r << sh
                sh += self.n
            imgs.append(v)
        # kernel of x -> sum x_j imgs[j]
        return Span(kernel(imgs, self.n))

    def is_maximal(self, M):
        comp = []
        T = Span(M.basis())
        for j in range(self.n):
            if T.add(1 << j):
                comp.append(1 << j)
        k = len(comp)
        for c in range(1, 1 << k):
            u = 0
            for i in range(k):
                if (c >> i) & 1:
                    u ^= comp[i]
            G = self.generated([u], M.basis())
            if len(G) < self.n:
                return False, len(G)
        return True, None


def kernel(imgs, n):
    """kernel of the map e_j -> imgs[j] (bitmasks), as bitmasks in e_j."""
    piv = []   # (pivot bit, image, preimage)
    ker = []
    for j, v in enumerate(imgs):
        pre = 1 << j
        for p, r, q in piv:
            if (v >> p) & 1:
                v ^= r
                pre ^= q
        if v == 0:
            ker.append(pre)
        else:
            piv.append((v.bit_length() - 1, v, pre))
    return ker


def analyse(name, tab, verbose=True):
    t0 = time.time()
    A = Alg(tab)
    N = nil2(tab)
    sw = [x for x in N if A.is_sandwich2(x)]
    S = A.generated(sw)
    res = dict(name=name, dim=A.n, nil2=len(N) + 1, sandwiches=len(sw) + 1,
               span_sw=len(Span(sw)), dim_s=len(S))
    if len(S) and len(S) < A.n:
        Nn = A.normaliser(S)
        res['codim_n'] = A.n - len(Nn)
        if len(Nn) < A.n:
            mx, _ = A.is_maximal(Nn)
            res['n_maximal'] = mx
        res['s_ideal_in_n'] = True
        # the derived series and the lower central series of s
        res['s_abelian'] = all(A.br(a, b) == 0 for a in S.basis() for b in S.basis())
    C1 = codim1(tab)
    res['codim1_subalgs'] = len(C1)
    res['sec'] = round(time.time() - t0, 1)
    if verbose:
        print(json.dumps(res), flush=True)
    return res, sw, S


if __name__ == '__main__':
    out = []
    for p in sys.argv[1:]:
        d = json.load(open(p))
        r, sw, S = analyse(d.get('name', os.path.basename(p)), d['tab'])
        r['s_basis'] = S.basis()
        out.append(r)
    json.dump(out, open(os.path.join(HERE, 'sand_%d.json' % int(time.time())), 'w'))
