        amb = A.wittN(Ns); m = len(Ns); N = amb.N
        for ad, st in simple_parts(amb, list(amb.basis), rng):
            res[amb.name] = fpr(ad, rng)
        # S(m;N): D_ij(x^a) = d_j x^a d_i + d_i x^a d_j
        gens = []
        for a in range(N):
            for i in range(m):
                for j in range(i + 1, m):
                    v = np.zeros(N * N, np.uint8)
                    b = dmono(Ns, a, j)
                    if b is not None: v ^= amb.basis[b * m + i]
