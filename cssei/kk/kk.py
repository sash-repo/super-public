"""Kondrateva--Kuznetsov (Zh. SVMO 27:1 (2025) 25-33): P1(6), P2(6) inside the
non-alternating Hamiltonian algebra P(6) over F_2, {f,g}=sum d_i f d_i g on divided powers,
brackets modulo constants.  Builds the subalgebras generated by the local parts and checks
dims, grading, simplicity (ideal generated by each basis vector), rank ad_x, restrictedness."""
import itertools, random, sys, json
from math import comb
N = 6
def dmul(a, b):          # divided-power monomials: x^(a) x^(b) = prod C(a_i+b_i,a_i) x^(a+b)
    c = 1
    for ai, bi in zip(a, b):
        if comb(ai+bi, ai) % 2 == 0: return None
    return tuple(ai+bi for ai, bi in zip(a, b))
def pmul(f, g):
    r = {}
    for a in f:
        for b in g:
            m = dmul(a, b)
            if m is not None: r[m] = r.get(m, 0) ^ 1
    return frozenset(m for m, v in r.items() if v)
def der(f, i):
    r = set()
    for a in f:
        if a[i] > 0:
            m = list(a); m[i] -= 1; r ^= {tuple(m)}
    return frozenset(r)
def br(f, g):
    r = set()
    for i in range(N):
        r ^= set(pmul(der(f, i), der(g, i)))
    return frozenset(m for m in r if any(m))       # drop constants
def mono(*ex): return tuple(ex)
def x(i): e = [0]*N; e[i] = 1; return frozenset([tuple(e)])
def X(I):
    e = [0]*N
    for i in I: e[i] = 1
    return frozenset([tuple(e)])
def add(*fs):
    r = set()
    for f in fs: r ^= set(f)
    return frozenset(r)
z = frozenset(tuple(2 if j == i else 0 for j in range(N)) for i in range(N))
Nset = range(N)
def comp(J): return tuple(i for i in Nset if i not in J)
Gm1 = [x(i) for i in Nset]
G0p = [pmul(x(i), x(j)) for i, j in itertools.combinations(Nset, 2)]
M = [add(X(J), X(comp(J))) for J in itertools.combinations(Nset, 3) if 0 in J]
Vt = [pmul(z, x(i)) for i in Nset]

class Span:
    """echelon over F_2 of polynomials (frozensets of monomials)"""
    def __init__(s): s.rows = {}; s.basis = []
    def reduce(s, f):
        f = set(f)
        while f:
            p = max(f)
            if p in s.rows: f ^= s.rows[p]
            else: return f
        return f
    def add(s, f):
        r = s.reduce(f)
        if r:
            s.rows[max(r)] = set(r)
            # keep rows reduced w.r.t. new pivot? not needed for membership via max-pivot reduction
            s.basis.append(frozenset(f)); return True
        return False
def gen(local):
    S = Span()
    for f in local: S.add(f)
    new = list(S.basis)
    while new:
        nxt = []
        for a in new:
            for b in list(S.basis):
                c = br(a, b)
                if c and S.add(c): nxt.append(S.basis[-1])
        new = nxt
    return S.basis
def deg(f):
    d = {sum(m) for m in f}; assert len(d) == 1, f; return d.pop() - 2
def coords(basis):
    """bit coordinates: echelonize basis into matrix form"""
    mons = sorted({m for f in basis for m in f})
    idx = {m: k for k, m in enumerate(mons)}
    vec = [sum(1 << idx[m] for m in f) for f in basis]
    # reduce to solve membership: Gaussian on vec
    piv = {}
    T = []
    for k, v in enumerate(vec):
        w, t = v, 1 << k
        while w:
            p = w.bit_length()-1
            if p in piv: w ^= piv[p][0]; t ^= piv[p][1]
            else: piv[p] = (w, t); break
        assert w
    def express(f):
        w = sum(1 << idx[m] for m in f); t = 0
        while w:
            p = w.bit_length()-1
            w ^= piv[p][0]; t ^= piv[p][1]
        return t
    return express
def table(basis):
    ex = coords(basis); n = len(basis)
    return [[ex(br(basis[i], basis[j])) for j in range(n)] for i in range(n)]
def apply(tab, n, a, b):
    r = 0
    for i in range(n):
        if a >> i & 1:
            for j in range(n):
                if b >> j & 1: r ^= tab[i][j]
    return r
def admat(tab, n, a): return [apply(tab, n, a, 1 << j) for j in range(n)]   # columns
def rank(cols):
    piv = {}; r = 0
    for v in cols:
        while v:
            p = v.bit_length()-1
            if p in piv: v ^= piv[p]
            else: piv[p] = v; r += 1; break
    return r
def ideal_dim(tab, n, v):
    piv = {}; B = []
    def addv(u):
        while u:
            p = u.bit_length()-1
            if p in piv: u ^= piv[p]
            else: piv[p] = u; B.append(u); return True
        return False
    addv(v); k = 0
    while k < len(B):
        for j in range(n):
            addv(apply(tab, n, B[k], 1 << j))
        k += 1
    return len(B)
def matmulcols(A, B, n):   # (A B) columns: A applied to columns of B
    def app(A, v):
        r = 0; i = 0
        while v:
            if v & 1: r ^= A[i]
            v >>= 1; i += 1
        return r
    return [app(A, b) for b in B]
def restricted(tab, n):
    # (ad e_i)^2 must be inner for every basis e_i (Jacobson)
    ads = [admat(tab, n, 1 << i) for i in range(n)]
    # span of ad L as n*n bit-vectors
    def flat(cols): return sum(c << (n*j) for j, c in enumerate(cols))
    piv = {}
    for A in ads:
        v = flat(A)
        while v:
            p = v.bit_length()-1
            if p in piv: v ^= piv[p]
            else: piv[p] = v; break
    bad = 0
    for A in ads:
        v = flat(matmulcols(A, A, n))
        while v:
            p = v.bit_length()-1
            if p in piv: v ^= piv[p]
            else: break
        if v: bad += 1
    return bad == 0, bad
def report(name, local):
    B = gen(local); n = len(B)
    B.sort(key=deg)
    degs = {}
    for f in B: degs[deg(f)] = degs.get(deg(f), 0) + 1
    tab = table(B)
    simple = all(ideal_dim(tab, n, 1 << i) == n for i in range(n))
    random.seed(1)
    rk = max(rank(admat(tab, n, random.getrandbits(n))) for _ in range(300))
    res = restricted(tab, n)
    print(name, 'dim', n, 'grading', dict(sorted(degs.items())), 'simple', simple,
          'max rank ad_x', rk, 'restricted', res, flush=True)
    return B, tab
