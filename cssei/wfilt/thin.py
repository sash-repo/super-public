#!/usr/bin/env python3
"""
The seven simple thin Lie algebras of dimension 15 over F_2 (Cushing--Stagg--Stewart,
arXiv:2207.01094, Theorem 4.1), read from their thin tables:
    [e_a, e_b] = T_{ab} e_{a+b},   a, b in GF(2)^4 \\ 0.

For each we compute, exactly over F_2:
  * Jacobi, simplicity, dim [L,L], dim Der L, Num2Nilps (= CSS Table C.3, which
    includes x = 0, so their number is ours + 1);
  * the sandwich elements (x with (ad_x)^2 = 0 and [[L,x],[L,x]] = 0), the
    sandwich subalgebra s(L) and its normaliser n_L(s);
  * ALL subalgebras invariant under the thin torus T < Der L (an exhaustive
    search over the 2^15 sets of root vectors), hence the T-invariant maximal
    subalgebras of smallest codimension = the candidate Weisfeiler filtrations;
  * for L_0 = n_L(s): the whole W-filtration L = L_{-d} > ... > L_0 > L_1 > ...
    and the dimensions of the components of the associated graded algebra.
"""

import ast
import glob
import os
import sys

from css import LieF2, rref, in_span, all_elements

N = 4
ROOTS = list(range(1, 1 << N))          # GF(2)^4 \ 0, as bit masks 1..15
POS = {a: i for i, a in enumerate(ROOTS)}


def load_table(path):
    s = open(path).read().replace("\n", " ").strip()
    if s.endswith(";"):
        s = s[:-1]
    return ast.literal_eval(s)


def algebra_from_thin_table(T, name):
    n = len(ROOTS)
    tab = [[0] * n for _ in range(n)]
    for i, a in enumerate(ROOTS):
        for j, b in enumerate(ROOTS):
            if i == j or not T[i][j]:
                continue
            tab[i][j] = 1 << POS[a ^ b]
    return LieF2(tab, name)


def toral_subalgebras(L):
    """all subspaces spanned by subsets of the root basis that are subalgebras"""
    n = L.n
    # precompute: for the subset mask S, closure fails if some pair inside brackets out
    out = []
    prod = {}
    for i in range(n):
        for j in range(i + 1, n):
            if L.tab[i][j]:
                k = L.tab[i][j].bit_length() - 1
                prod[(i, j)] = k
    for S in range(1 << n):
        ok = True
        for (i, j), k in prod.items():
            if (S >> i) & 1 and (S >> j) & 1 and not (S >> k) & 1:
                ok = False
                break
        if ok:
            out.append(S)
    return out


def contains_no_ideal(L, rows):
    """L_0 contains no non-zero ideal of L"""
    for u in all_elements(rows):
        if u and len(L.ideal([u])) < L.n:
            # the ideal generated by u is proper; is it inside rows?
            I = L.ideal([u])
            if all(in_span(v, rows) for v in I):
                return False
    return True


def wfiltration(L, L0):
    """The Weisfeiler filtration with the given maximal subalgebra L_0."""
    L0 = rref(L0)
    # L_{-1}: a minimal L_0-invariant subspace strictly containing L_0
    best = None
    for u in range(1, 1 << L.n):
        if in_span(u, L0):
            continue
        M = rref(L0 + [u])
        changed = True
        while changed:
            changed = False
            for a in list(M):
                for b in L0:
                    w = L.mul(a, b)
                    if w and not in_span(w, M):
                        M = rref(M + [w])
                        changed = True
        if best is None or len(M) < len(best):
            best = M
    Lm = [L0, best]                                   # L_0, L_{-1}, ...
    while len(Lm[-1]) < L.n:
        prev = Lm[-1]
        new = rref(prev + [L.mul(a, b) for a in Lm[1] for b in prev])
        if len(new) == len(prev):
            break
        Lm.append(new)
    # positive part
    Lp = [L0]
    while True:
        cur = Lp[-1]
        nxt = [u for u in all_elements(cur)
               if u and all(in_span(L.mul(u, a), cur) for a in Lm[1])]
        nxt = rref(nxt)
        if len(nxt) == len(cur) or not nxt:
            if not nxt:
                Lp.append([])
            break
        Lp.append(nxt)
    neg = [len(x) for x in Lm]
    pos = [len(x) for x in Lp]
    return neg, pos


def main(paths):
    for path in sorted(paths):
        name = os.path.basename(path)[:-4]
        L = algebra_from_thin_table(load_table(path), name)
        ok, msg = L.check_jacobi()
        print("=" * 72)
        print("%-14s dim %d   axioms: %s" % (name, L.n, msg))
        if not ok:
            continue
        print("   simple: %-5s  dim[L,L] = %2d  dim Der L = %2d  Num2Nilps = %d (+1 = %d)"
              % (L.is_simple(), len(L.derived()), L.dim_der(),
                 L.num_2nilps(), L.num_2nilps() + 1))
        S = L.sandwiches()
        Sp = rref(S)
        print("   sandwiches over F_2: %d, spanning dim %d; whole span is sandwiches: %s"
              % (len(S), len(Sp), L.flat_family(Sp)))
        if S:
            sg = L.subalgebra_generated(Sp)
            nn = L.normaliser(sg)
            mx = L.is_maximal_subalgebra(nn)[0] if L.is_subalgebra(nn) else None
            print("   dim s(L) = %d   dim n_L(s) = %d (codim %d)  subalg: %s  maximal: %s"
                  % (len(sg), len(nn), L.n - len(nn), L.is_subalgebra(nn), mx))
        # T-invariant subalgebras
        subs = toral_subalgebras(L)
        cod = {}
        for Sm in subs:
            d = bin(Sm).count("1")
            cod.setdefault(L.n - d, []).append(Sm)
        proper = sorted(c for c in cod if c > 0)
        print("   T-invariant subalgebras by codimension:",
              {c: len(cod[c]) for c in proper[:6]})
        for c in proper:
            # L is simple, so no proper subalgebra contains a non-zero ideal of L
            rowsets = [rref([1 << i for i in range(L.n) if (Sm >> i) & 1])
                       for Sm in cod[c]]
            good = [r for r in rowsets if L.is_maximal_subalgebra(r)[0]]
            if good:
                print("   smallest codim of a T-invariant maximal subalgebra:"
                      " %d  (%d of them, %d T-invariant subalgebras of that codim)"
                      % (c, len(good), len(cod[c])))
                neg, pos = wfiltration(L, good[0])
                print("      W-filtration dims, negative part %s, positive part %s"
                      % (neg, pos))
                gneg = [neg[i + 1] - neg[i] for i in range(len(neg) - 1)]
                gpos = [pos[i] - pos[i + 1] for i in range(len(pos) - 1)]
                print("      dim g_i, i<0 (from -1 down): %s;   dim g_i, i>=0: %s"
                      % (gneg, gpos))
                break


if __name__ == "__main__":
    args = sys.argv[1:] or sorted(glob.glob("css-bases/thin15/*.txt"))
    main(args)
