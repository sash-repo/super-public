def load(name):
    p = os.path.join(BV, ALGS[name])
    if p.endswith('.json'):
        tab = json.load(open(p))['tab']
        if isinstance(tab, str):
            tab = json.loads(tab)
    else:
        import numpy as np
        ad = np.load(p, allow_pickle=True)['ad']
        n = ad.shape[0]
        tab = [[int(sum(int(ad[i, k, j] & 1) << k for k in range(n))) for j in range(n)]
               for i in range(n)]
    L = LieF2(tab, name)
    return L


def g0_type(L, M, pos):
    k0 = len(pos[0]) - (len(pos[1]) if len(pos) > 1 else 0)
    if k0 > 20:                       # skip the 2^k nilpotent count
        save = W.LieF2
        k, der, nil, g0 = None, None, None, None
        L1 = pos[1] if len(pos) > 1 else []
        comp, rows = [], list(L1)
        for v in pos[0]:
            if not in_span(v, rows):
                rows = rref(rows + [v]); comp.append(v)
        der = len(rref([L.mul(a, b) for a in comp for b in comp] + list(L1))) - len(rref(list(L1)))
        return (k0, der, None, None)
    k, der, nil, g0 = W.g0_type(L, M, pos)
    return (k, der, nil, W.solvable(g0))


def wgradings_of(L, M):
    out = []
    for N in minimal_submodules(L, M):
        negdims, posdims, neg, pos = W.filtration(L, M, N)
        if sum(negdims) != L.n - len(M):
            continue
        out.append({'codim': L.n - len(M), 'neg': negdims, 'pos': posdims,
                    'growth': W.growth_vector(negdims), 'g0': g0_type(L, M, pos)})
    return out


def mod_closure(L, M, y):
    """M + the M-submodule generated by y (subspace)"""
    N = rref(M + [y])
    queue = [y]
    while queue:
        a = queue.pop()
        for b in M:
            w = L.mul(a, b)
            if w and not in_span(w, N):
                N = rref(N + [w]); queue.append(w)
    return N


def submods(L, M):
    """the distinct cyclic submodules M+<y>_M, one per coset"""
    seen = {}
    for y in W.cosets(L, M):
        N = mod_closure(L, M, y)
        seen.setdefault(tuple(N), N)
    return list(seen.values())


def minimal_submodules(L, M):
    out = submods(L, M)
    S = [set(N) for N in out]
    mins = []
    for i, N in enumerate(out):
        if not any(len(out[j]) < len(N) and all(in_span(v, N) for v in out[j])
                   for j in range(len(out))):
            mins.append(N)
    return mins


def is_maximal(L, M):
    """M maximal iff each MINIMAL M-submodule generates L (a proper intermediate
    subalgebra contains a minimal submodule)"""
    for N in minimal_submodules(L, M):
        if len(W.closure(L, N)) != L.n:
            return False, N
    return True, None


def walk(L, rng, cap, tries=60):
    M = W.closure(L, [rng.randrange(1, 1 << L.n)])
    if len(M) == L.n:
        return None
    while True:
        grown = False
        for _ in range(tries):
            y = rng.randrange(1, 1 << L.n)
            if in_span(y, M):
                continue
            N = W.closure(L, M + [y])
            if len(N) != L.n:
                M, grown = N, True
                break
        if grown:
            continue
        if L.n - len(M) > cap:
            return ('cap', L.n - len(M))
        ok, N = is_maximal(L, M)
        if ok:
            return M
        M = W.closure(L, N)


def exhaustive(L, cmax, log):
    from walk import lowrank
    from mincodim import restricted_rank
    from sand import Alg
    A = Alg(L.tab)
    t = time.time()
    sup = lowrank(L.tab, 2 * cmax)
    ranks = {f: restricted_rank(A, f) for f in sup}
    log('  lowrank rmax=%d: %d functionals [%.0fs]' % (2 * cmax, len(ranks), time.time() - t))
    W.candidates = lambda L_, r, c: [f for f, v in r.items() if v <= 2 * (c - 1)]
    smaller, maxes = [], []
    for c in range(1, cmax + 1):
        t = time.time()
        subs = W.subalgebras_of_codim(L, ranks, c, budget=None, candmax=None)
        mx = [M for M in subs if not any(all(in_span(v, P) for v in M) for P in smaller)]
        smaller += subs
        maxes += mx
        log('  codim %d: %d subalgebras, %d maximal [%.0fs]' % (c, len(subs), len(mx), time.time() - t))
    return maxes


def main():
    name = sys.argv[1]
    cmax = int(sys.argv[2]) if len(sys.argv) > 2 else 4
    nwalk = int(sys.argv[3]) if len(sys.argv) > 3 else 200
    cap = int(sys.argv[4]) if len(sys.argv) > 4 else 12
    seed = int(sys.argv[5]) if len(sys.argv) > 5 else 1044
    out = os.path.join(HERE, name + '.json')
    logf = open(os.path.join(HERE, name + '.log'), 'a')

    def log(s):
        print(s, flush=True); logf.write(s + '\n'); logf.flush()
    L = load(name)
    ok, msg = L.check_jacobi()
    log('== %s dim %d Jacobi %s cmax %d nwalk %d cap %d seed %d' % (name, L.n, ok, cmax, nwalk, cap, seed))
    maxes = {}
    if cmax > 0:
        for M in exhaustive(L, cmax, log):
            maxes[tuple(M)] = ('exh', M)
    rng = random.Random(seed)
    capped, t = {}, time.time()
    for i in range(nwalk):
        r = walk(L, rng, cap)
        if r is None:
            continue
        if isinstance(r, tuple):
            capped[r[1]] = capped.get(r[1], 0) + 1
            continue
        k = tuple(r)
        if k not in maxes:
            maxes[k] = ('walk', r)
        if (i + 1) % 50 == 0:
            log('  walks %d: %d maximal so far [%.0fs]' % (i + 1, len(maxes), time.time() - t))
    log('  walks: %d, abandoned at codim>cap: %s' % (nwalk, capped))
    found = {}
    for k, (how, M) in maxes.items():
        for w in wgradings_of(L, M):
            key = json.dumps([w['codim'], w['neg'], w['pos'], w['g0']])
            e = found.setdefault(key, {'w': w, 'exh': 0, 'walk': 0})
            e[how] += 1
    rows = sorted(found.values(), key=lambda e: (e['w']['codim'], e['w']['neg'], e['w']['pos']))
    for e in rows:
        w = e['w']
        log('  codim %2d  g_- %s  g_>=0 %s  g0 %s  [#exh %d, #walk-only %d]'
            % (w['codim'], w['neg'], w['pos'], w['g0'], e['exh'], e['walk']))
    json.dump({'name': name, 'dim': L.n, 'cmax': cmax, 'nwalk': nwalk, 'cap': cap,
               'capped': capped, 'nmax': len(maxes),
               'maxcodims': sorted(L.n - len(M) for _, M in maxes.values()),
               'rows': rows}, open(out, 'w'), indent=1)


if __name__ == '__main__':
    main()
