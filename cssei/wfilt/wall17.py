r"""All W-filtrations (= all maximal subalgebras L_0, and for each of them every minimal
L_0-submodule of L/L_0) of the new simple Lie algebras over F_2 found by the random search.

Method = wall.py (in this folder), adapted:
  * EXHAUSTIVE up to codim CMAX: the candidate functionals f (rank(B_f|Ker f) <= 2(c-1))
    come from the numba walk `lowrank` of sand/walk.py instead of a Python loop over 2^n;
    a subalgebra of codim c is maximal iff it lies in no subalgebra of smaller codim
    (the smaller list being exhaustive).
  * RANDOM greedy walks beyond: a line is enlarged (random elements, then the complete
    sweep over the M-submodules generated by the 2^c-1 cosets) until maximal.  A walk
    whose codim exceeds CAP before it stops is abandoned (the sweep would be too long).
For each maximal M and each minimal M-submodule N/M: the W-filtration, dims of g_i,
growth vector, and (dim g_0, dim g_0', #2-nilpotents of g_0 [if dim g_0 <= 20], solvable).
usage: wall17.py NAME [CMAX] [NWALK] [CAP] [SEED]   (NAME in ALGS below)"""
