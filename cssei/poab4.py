#!/usr/bin/env python3
r"""
poab4.py N [lam ...] --- b_{a,b}(N;1), desuperized = po_{a,b}(2N;1) = po_lam(2N+1;1)
(lam = a/b), over F_4, straight from BGLLS (2.31)--(2.33):

  M_f = f d_tau + sum_i [ d_{q_i}(f) (d_{xi_i} + q_i d_tau) + (d_{xi_i} + q_i d_tau)(f) d_{q_i} ],
  b_{a,b} = { M_f | (b + a E_q) d_tau f + a Delta f = 0 },   Delta = sum_i d_{xi_i} d_{q_i},

all coordinates of height 1 (N~ = 1), coefficients in F_4 = {0, 1, w, w^2} (encoded 0,1,2,3).
lam in {0, 1, oo, w}; w = the class of x in GF(2^K) = F_2[x]/(irreducible), K = $GFK (default 2), stands for every lam outside F_2 (the Galois conjugate w^2 gives the
conjugate algebra).  Reports dim b, the ideal J generated by b_{-1}, simplicity (graded criterion),
the 2-closure of J, and sdims of the superizations (b(N): tau, xi odd, q even; the k-type ones).
"""
import sys, itertools, time

# ---------------------------------------------------------------- F_4
import os
_K = int(os.environ.get('GFK', '2'))           # the field GF(2^K); K = 2 is F_4
_POLY = {2: 0b111, 3: 0b1011, 4: 0b10011, 5: 0b100101}[_K]


def _gmul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        b >>= 1
        a <<= 1
        if a >> _K:
            a ^= _POLY
    return r


_Q = 1 << _K
MUL = [[_gmul(a, b) for b in range(_Q)] for a in range(_Q)]
INV = [None] + [next(b for b in range(1, _Q) if MUL[a][b] == 1) for a in range(1, _Q)]


def add(a, b):
    return a ^ b


N = int(sys.argv[1])
LAMS = sys.argv[2:] or ['0', '1', 'oo', 'w']
M = 2 * N + 1
TAU = 0
Q = list(range(1, N + 1))
XI = list(range(N + 1, 2 * N + 1))
DEG = [2] + [1] * (2 * N)


def mdeg(A):
    return sum(DEG[j] for j in range(M) if (A >> j) & 1)


def d(j, f):
    """d_j of a function f = {A: c}"""
    out = {}
    for A, c in f.items():
        if (A >> j) & 1:
            B = A ^ (1 << j)
            out[B] = out.get(B, 0) ^ c
    return {k: v for k, v in out.items() if v}


def fmul(f, g):
    out = {}
    for A, a in f.items():
        for B, b in g.items():
            if A & B:
                continue
            C = A | B
            out[C] = out.get(C, 0) ^ MUL[a][b]
    return {k: v for k, v in out.items() if v}


def fadd(*fs):
    out = {}
    for f in fs:
        for k, v in f.items():
            out[k] = out.get(k, 0) ^ v
    return {k: v for k, v in out.items() if v}


def x(j):
    return {1 << j: 1}


def fld_add(*Xs):
    out = {}
    for X in Xs:
        for k, v in X.items():
            out[k] = out.get(k, 0) ^ v
    return {k: v for k, v in out.items() if v}


def fld(f, j):          # f d_j
    return {(A, j): c for A, c in f.items()}


def Y(i):               # d_{xi_i} + q_i d_tau as a field
    return fld_add({(0, XI[i]): 1}, {(1 << Q[i], TAU): 1})


def Yf(i, f):           # (d_{xi_i} + q_i d_tau)(f)
    return fadd(d(XI[i], f), fmul(x(Q[i]), d(TAU, f)))


def Mf(f):
    out = fld(f, TAU)
    for i in range(N):
        g = d(Q[i], f)
        if g:
            for (A, j), c in Y(i).items():
                for B, b in g.items():
                    if A & B:
                        continue
                    k = (A | B, j)
                    out[k] = out.get(k, 0) ^ MUL[c][b]
        out = fld_add(out, fld(Yf(i, f), Q[i]))
    return {k: v for k, v in out.items() if v}


def apply(X, f):
    out = {}
    for (A, j), c in X.items():
        g = d(j, f)
        for B, b in g.items():
            if A & B:
                continue
            out[A | B] = out.get(A | B, 0) ^ MUL[c][b]
    return {k: v for k, v in out.items() if v}


def bracket(X, Yv):
    out = {}
    for (A, j), c in X.items():
        for (B, k), b in Yv.items():
            if (B >> j) & 1:
                Bd = B ^ (1 << j)
                if not (A & Bd):
                    key = (A | Bd, k)
                    out[key] = out.get(key, 0) ^ MUL[c][b]
            if (A >> k) & 1:
                Ad = A ^ (1 << k)
                if not (B & Ad):
                    key = (B | Ad, j)
                    out[key] = out.get(key, 0) ^ MUL[c][b]
    return {k: v for k, v in out.items() if v}


def square(X):
    out = {}
    for j in range(M):
        f = {A: c for (A, jj), c in X.items() if jj == j}
        g = apply(X, f)
        for A, c in g.items():
            out[(A, j)] = out.get((A, j), 0) ^ c
    return {k: v for k, v in out.items() if v}


def fdeg(X):
    ds = {mdeg(A) - DEG[j] for (A, j) in X}
    assert len(ds) == 1, ds
    return ds.pop()


# ---------------------------------------------------------------- echelon over F_4
class Ech:
    def __init__(self):
        self.rows = {}              # pivot key -> normalized vector (dict), pivot coeff 1

    def reduce(self, v):
        v = dict(v)
        changed = True
        while v:
            p = max(v)
            r = self.rows.get(p)
            if r is None:
                return v
            c = v[p]
            for k, a in r.items():
                nv = v.get(k, 0) ^ MUL[c][a]
                if nv:
                    v[k] = nv
                else:
                    v.pop(k, None)
        return v

    def add(self, v):
        v = self.reduce(v)
        if not v:
            return None
        p = max(v)
        ci = INV[v[p]]
        v = {k: MUL[ci][a] for k, a in v.items()}
        self.rows[p] = v
        return v

    def __len__(self):
        return len(self.rows)

    def basis(self):
        return list(self.rows.values())


def kernel_F4(cols, nrows_keys):
    """nullspace of the linear map sending basis vector t to cols[t] (dict)."""
    E = Ech()
    track = []
    ker = []
    for t, col in enumerate(cols):
        v = dict(col)
        comb = {t: 1}
        # reduce with tracking
        while v:
            p = max(v)
            r = E.rows.get(p)
            if r is None:
                break
            rv, rc = r
            c = v[p]
            for k, a in rv.items():
                nv = v.get(k, 0) ^ MUL[c][a]
                if nv:
                    v[k] = nv
                else:
                    v.pop(k, None)
            for k, a in rc.items():
                nv = comb.get(k, 0) ^ MUL[c][a]
                if nv:
                    comb[k] = nv
                else:
                    comb.pop(k, None)
        if not v:
            ker.append(comb)
        else:
            p = max(v)
            ci = INV[v[p]]
            E.rows[p] = ({k: MUL[ci][a] for k, a in v.items()}, {k: MUL[ci][a] for k, a in comb.items()})
    return ker


# ---------------------------------------------------------------- b_{a,b}
MONOS = list(range(1 << M))


def L_ab(a, b, f):
    dt = d(TAU, f)
    Eq = {}
    for A, c in dt.items():
        cnt = sum(1 for i in range(N) if (A >> Q[i]) & 1) & 1
        if cnt:
            Eq[A] = c
    part1 = fadd({A: MUL[b][c] for A, c in dt.items()}, {A: MUL[a][c] for A, c in Eq.items()})
    Df = {}
    for i in range(N):
        Df = fadd(Df, d(XI[i], d(Q[i], f)))
    return fadd(part1, {A: MUL[a][c] for A, c in Df.items()})


def build(lam):
    a, b = {'0': (0, 1), '1': (1, 1), 'oo': (1, 0), 'w': (2, 1)}[lam]
    cols = [L_ab(a, b, {A: 1}) for A in MONOS]
    ker = kernel_F4(cols, None)
    fs = [{MONOS[t]: c for t, c in comb.items()} for comb in ker]
    # homogeneous in degree: split
    byd = {}
    for f in fs:
        parts = {}
        for A, c in f.items():
            parts.setdefault(mdeg(A), {})[A] = c
        for dg, p in parts.items():
            byd.setdefault(dg, []).append(p)
    fields = {}
    for dg, lst in byd.items():
        E = Ech()
        for p in lst:
            X = Mf(p)
            if X:
                E.add(X)
        fields[dg - 2] = E.basis()
    return fields


def closure_ideal(gens, seed):
    E = {}
    def ech(dg):
        return E.setdefault(dg, Ech())
    queue = []
    for s in seed:
        v = ech(fdeg(s)).add(s)
        if v:
            queue.append(v)
    while queue:
        v = queue.pop()
        for g in gens:
            w = bracket(g, v)
            if w:
                dg = fdeg(w)
                r = ech(dg).add(w)
                if r:
                    queue.append(r)
    return {dg: e.basis() for dg, e in E.items() if len(e)}


def dims(S):
    return {dg: len(v) for dg, v in sorted(S.items())}


def total(S):
    return sum(len(v) for v in S.values())


def rank_F4(vecs):
    E = Ech()
    for v in vecs:
        E.add(v)
    return len(E)


def burnside(J0, Jm1):
    """dim of the associative algebra generated by ad J_0 on J_{-1} (with 1)"""
    Em = Ech()
    basis = []
    for v in Jm1:
        Em.add(v)
    Eb = [Ech() for _ in range(1)]
    # coordinates of J_{-1}
    piv = list(Em.rows.keys())
    def coords(w):
        # express w in the echelon basis of J_{-1}: solve by reduction with tracking
        out = []
        w = dict(w)
        cs = {}
        for p in sorted(Em.rows, reverse=True):
            if p in w:
                c = w[p]
                cs[p] = c
                for k, a in Em.rows[p].items():
                    nv = w.get(k, 0) ^ MUL[c][a]
                    if nv:
                        w[k] = nv
                    else:
                        w.pop(k, None)
        assert not w
        return tuple(cs.get(p, 0) for p in piv)
    Bm = [Em.rows[p] for p in piv]
    n = len(Bm)
    mats = []
    for x in J0:
        cols = [coords(bracket(x, e)) for e in Bm]
        mats.append(tuple(tuple(cols[c][r] for c in range(n)) for r in range(n)))
    def mm(A, B):
        return tuple(tuple(
            __import__('functools').reduce(lambda s, t: s ^ t, (MUL[A[r][k]][B[k][c]] for k in range(n)), 0)
            for c in range(n)) for r in range(n))
    I = tuple(tuple(int(r == c) for c in range(n)) for r in range(n))
    E = Ech()
    def vec(A):
        return {(r, c): A[r][c] for r in range(n) for c in range(n) if A[r][c]}
    E.add(vec(I))
    frontier = [I]
    while frontier:
        nf = []
        for X in frontier:
            for A in mats:
                Yv = mm(A, X)
                if E.add(vec(Yv)):
                    nf.append(Yv)
        frontier = nf
    return len(E), n * n


def simple_test(Jd):
    degs = sorted(Jd)
    gm1 = Jd[-1]
    ok_a = True
    for dg in degs:
        if dg < 0:
            continue
        # kernel of x -> ([x, e])_e
        cols = []
        for xv in Jd[dg]:
            col = {}
            for ci, e in enumerate(gm1):
                for k, c in bracket(xv, e).items():
                    col[(ci, k)] = c
            cols.append(col)
        if kernel_F4(cols, None):
            ok_a = False
    irr, full = burnside(Jd.get(0, []), gm1)
    pos = [v for dg in degs if dg >= 1 for v in Jd[dg]]
    ok_c = True
    for dg in degs:
        if dg > -2:
            continue
        cols = []
        for xv in Jd[dg]:
            col = {}
            for ci, yv in enumerate(pos):
                for k, c in bracket(xv, yv).items():
                    col[(ci, k)] = c
            cols.append(col)
        if kernel_F4(cols, None):
            ok_c = False
    allb = [v for dg in degs for v in Jd[dg]]
    I = closure_ideal(allb, gm1)
    ok_d = total(I) == total(Jd)
    return dict(transitive=ok_a, irreducible=(irr == full), no_low=ok_c, ideal=ok_d,
                simple=ok_a and irr == full and ok_c and ok_d)


def pdims(S, par):
    """sdim; parity-graded check"""
    ev = od = 0
    for dg, B in S.items():
        E0, E1 = Ech(), Ech()
        for v in B:
            v0 = {k: c for k, c in v.items() if (sum((k[0] >> j) & 1 and par[j] for j in range(M)) + par[k[1]]) % 2 == 0}
            v1 = {k: c for k, c in v.items() if k not in v0}
            E0.add(v0); E1.add(v1)
        if len(E0) + len(E1) != len(B):
            return None
        ev += len(E0); od += len(E1)
    return ev, od


def kpar(k, par):
    return (sum(par[j] for j in range(M) if (k[0] >> j) & 1) + par[k[1]]) % 2


def split(v, par):
    out = {}
    for k, c in v.items():
        out.setdefault(kpar(k, par), {})[k] = c
    return out


def superclose(gens, J, par):
    """sdim of the smallest subspace containing J, stable under ad(gens) and under the
    squaring of odd elements (homogeneous in degree and parity)."""
    hg = [w for g in gens for w in split(g, par).values()]
    E = {}
    queue = []
    def put(v):
        for pp, w in split(v, par).items():
            if not w:
                continue
            key = (fdeg(w), pp)
            r = E.setdefault(key, Ech()).add(w)
            if r:
                queue.append((r, pp))
    for dg in J:
        for v in J[dg]:
            put(v)
    while queue:
        v, pp = queue.pop()
        for g in hg:
            w = bracket(g, v)
            if w:
                put(w)
        if pp == 1:
            s2 = square(v)
            if s2:
                put(s2)
    ev = sum(len(e) for (dg, pp), e in E.items() if pp == 0)
    od = sum(len(e) for (dg, pp), e in E.items() if pp == 1)
    return ev, od


PARS = {'b(%d)' % N: [1] + [0] * N + [1] * N}
for k in range(N + 1):
    PARS['k-type (%d|%d)' % (2 * (N - k) + 1, 2 * k)] = [0] + [0] * (N - k) + [1] * k + [0] * (N - k) + [1] * k

for lam in LAMS:
    t0 = time.time()
    B = build(lam)
    allb = [v for dg in sorted(B) for v in B[dg]]
    # sanity: subalgebra
    Eall = {dg: Ech() for dg in B}
    for dg in B:
        for v in B[dg]:
            Eall[dg].add(v)
    closed = True
    for u in allb:
        for v in allb:
            w = bracket(u, v)
            if w and Eall.get(fdeg(w), Ech()).reduce(w):
                closed = False
    J = closure_ideal(allb, B[-1])
    st = simple_test(J)
    Jb = [v for dg in sorted(J) for v in J[dg]]
    # 2-closure of J
    R = {}
    for dg in J:
        R[dg] = Ech()
        for v in J[dg]:
            R[dg].add(v)
    queue = list(Jb)
    while queue:
        v = queue.pop()
        s = square(v)
        if s:
            dg = fdeg(s)
            r = R.setdefault(dg, Ech()).add(s)
            if r:
                queue.append(r)
    Rd = sum(len(e) for e in R.values())
    print('lam = %-3s  dim b = %d %s, closed: %s; J = %d %s; %s; 2-closure of J = %d  (%.0fs)'
          % (lam, total(B), dims(B), closed, total(J), dims(J), 'simple' if st['simple'] else st, Rd, time.time() - t0))
    for nm_, p in PARS.items():
        print('     %-14s sdim b %s   sdim J %s   sdim J^s %s' % (nm_, pdims(B, p), pdims(J, p), superclose(allb, J, p)))
    sys.stdout.flush()
