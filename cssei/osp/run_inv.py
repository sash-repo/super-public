import sys, numpy as np
from sconst import load, NAME
from invariants import *
for t in ('inner', 'outer'):
    tab, sq, par, _ = load(t); d = len(par)
    print('==', NAME[t], 'sdim', (int((par == 0).sum()), int(par.sum())))
    print(' simple:', is_simple(tab, sq, par)[0])
    D = derived(tab, par); print(' [s,s] sdim', homog_basis(D, par))
    print(' [s,s] closed under squaring:', len(ideal(tab, sq, par, list(D))) == len(D), ' ideal generated by [s,s]:', homog_basis(ideal(tab, sq, par, list(D)), par))
    print(' center dim', len(center(tab)))
    print(' assoc(ad) dim', assoc_dim(tab), 'of', d * d)
    der = derivations(tab, sq, par); inn = inner_sdim(tab, par)
    print(' Der sdim (%d|%d), ad s sdim %s, outer (%d|%d)' % (der[0], der[1], inn, der[0] - inn[0], der[1] - inn[1]))
    print(' restricted:', restricted(tab, par))
    f = invariant_forms(tab, sq, par)
    for p in (0, 1): print(' invariant %s forms: dim %d, nondegenerate exists %s, max rank %d' % (('even', 'odd')[p], f[p][0], f[p][1], f[p][2]))
    print(' H^2(s;K) even|odd:', central_ext(tab, sq, par))
    print(' odd x != 0 with x^2 = 0:', odd_null_squares(tab, sq, par), 'of', 2 ** int(par.sum()) - 1)
    sys.stdout.flush()
