"""Matrix (super)algebras over GF(2^K): structure constants, adjoint action, and the dimension of
the associative algebra generated by ad (Burnside: = d^2 iff the adjoint module is absolutely
irreducible, i.e. the Lie algebra is absolutely simple)."""
from galg import Ech, mm, br, flat, unflat

class MSA:
    def __init__(self, F, even, odd):
        self.F = F
        self.N = len((even + odd)[0])
        self.basis = even + odd
        self.par = [0] * len(even) + [1] * len(odd)
        self.d = len(self.basis)
        # coordinate solver: echelon with tracked combinations
        self._rows = []   # (pivot, vec, coeffvec)
        for i, X in enumerate(self.basis):
            c = [0] * self.d; c[i] = 1
            v, c = self._red(flat(X), c)
            p = next(k for k, x in enumerate(v) if x)
            iv = F.inv_(v[p]); v = [F.mul(iv, x) for x in v]; c = [F.mul(iv, x) for x in c]
            self._rows.append((p, v, c))
        self.tab = [[self.coords(br(F, X, Y)) for Y in self.basis] for X in self.basis]
        self.sq = [self.coords(mm(F, X, X)) if p else None for X, p in zip(self.basis, self.par)]
    def _red(self, v, c):
        F = self.F; v = list(v); c = list(c)
        for p, r, rc in self._rows:
            a = v[p]
            if a:
                v = [x ^ F.mul(a, y) for x, y in zip(v, r)]
                c = [x ^ F.mul(a, y) for x, y in zip(c, rc)]
        return v, c
    def coords(self, X):
        v, c = self._red(flat(X), [0] * self.d)
        if any(v):
            raise ValueError('not closed')
        return c    # X = sum c_i basis_i  (char 2: x ^= a*y means v - a*r, fine)
    def admat(self, i):
        """matrix of ad e_i in the basis: column j = coords [e_i, e_j]"""
        d = self.d
        return [[self.tab[i][j][k] for j in range(d)] for k in range(d)]
    def center(self):
        """basis of the center (vectors)"""
        F = self.F; d = self.d
        # solve sum_i c_i [e_i, e_j] = 0 for all j
        eqs = []
        for j in range(d):
            for k in range(d):
                eqs.append([self.tab[i][j][k] for i in range(d)])
        return nullspace(F, eqs, d)

def nullspace(F, rows, ncols):
    E = []   # rref
    piv = []
    R = [list(r) for r in rows if any(r)]
    r = 0; pivcols = []
    for c in range(ncols):
        pr = None
        for i in range(r, len(R)):
            if R[i][c]: pr = i; break
        if pr is None: continue
        R[r], R[pr] = R[pr], R[r]
        iv = F.inv_(R[r][c]); R[r] = [F.mul(iv, x) for x in R[r]]
        for i in range(len(R)):
            if i != r and R[i][c]:
                a = R[i][c]; R[i] = [x ^ F.mul(a, y) for x, y in zip(R[i], R[r])]
        pivcols.append(c); r += 1
    free = [c for c in range(ncols) if c not in pivcols]
    out = []
    for f in free:
        v = [0] * ncols; v[f] = 1
        for i, pc in enumerate(pivcols):
            v[pc] = R[i][f]
        out.append(v)
    return out

def assoc_dim(F, mats):
    """dim of the unital associative algebra generated by the given square matrices"""
    E = Ech(F); N = len(mats[0])
    I = [[1 if i == j else 0 for j in range(N)] for i in range(N)]
    queue = [I]; E.add(flat(I))
    while queue:
        X = queue.pop()
        for M in mats:
            Y = mm(F, M, X)
            if E.add(flat(Y)): queue.append(Y)
    return len(E)
