"""s_ev as a Lie algebra and s_od as an s_ev-module, for s_a and s_b (over F_2, exhaustive)."""
import numpy as np, itertools
from sconst import load, NAME
from invariants import span, bracket, rank
for t in ('inner', 'outer'):
    tab, sq, par, _ = load(t); d = len(par); E = np.eye(d, dtype=np.uint8)
    ev = [i for i in range(d) if par[i] == 0]; od = [i for i in range(d) if par[i] == 1]
    # derived series and center of s_ev
    L = [E[i] for i in ev]; ser = [len(L)]
    while True:
        nb = span([bracket(tab, x, y) for x in L for y in L])
        ser.append(len(nb))
        if len(nb) == len(L) or len(nb) == 0: break
        L = list(nb)
    cen = [c for c in itertools.product([0, 1], repeat=len(ev)) if any(c)
           and all(not bracket(tab, sum(ci * E[i] for ci, i in zip(c, ev)).astype(np.uint8), E[j]).any() for j in ev)]
    cen_dim = rank(np.array([sum(ci * E[i] for ci, i in zip(c, ev)) for c in cen])) if cen else 0
    # submodules of s_od generated by one vector
    subs = set()
    for c in itertools.product([0, 1], repeat=len(od)):
        if not any(c): continue
        v = np.zeros(d, dtype=np.uint8); v[od] = c; B = span([v])
        while True:
            nb = span(list(B) + [bracket(tab, E[i], w) for w in B for i in ev])
            if len(nb) == len(B): break
            B = nb
        subs.add(len(B))
    # squares of odd elements: span
    sqs = span([sq[i] for i in od] + [tab[a, b] for a in od for b in od])
    print(NAME[t], ': s_ev derived series', ser, ', center of s_ev dim', cen_dim,
          '; dims of cyclic s_ev-submodules of s_od', sorted(subs), '; [s_od,s_od]+squares dim', len(sqs))
