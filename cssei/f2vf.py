#!/usr/bin/env python3
r"""
f2vf.py --- vector fields over F_2 with divided-power coefficients, and the
Cartan prolong inside vect(m; N), solved one (degree, weight) block at a time.

O(m; N):  basis x^(a) = prod x_i^(a_i), 0 <= a_i < 2^{N_i}.  The exponent vector
is PACKED into one int, coordinate i occupying N_i bits.  For p = 2,
x^(a) x^(b) = prod binom(a_i+b_i, a_i) x^(a+b), and by Lucas binom(a+b,a) is odd
iff a & b == 0 bitwise; then a + b = a | b.  So the product of two packed
monomials is  A | B  if  A & B == 0,  and 0 otherwise.  The distinguished
derivative is  d_i x^(a) = x^(a - e_i)  (coefficient 1), i.e. subtract 1 from
the i-th field.

A vector field is a set of KEYS, key = (mono << 5) | i  meaning x^mono d_i,
coefficients in F_2 (so a field is a set, sum = symmetric difference).

Grading: deg x_i = degs[i] > 0 (weighted), deg(x^a d_i) = sum a_j degs[j] - degs[i].
Weights: an optional integer vector per coordinate; wt(x^a d_i) = sum a_j w_j - w_i.
The prolong splits into (degree, weight) blocks provided the given fields are
homogeneous; `find_weights` computes the lattice of weight vectors for which they
are.
"""
import itertools
import sys
from fractions import Fraction

import os; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]


class Space:
    def __init__(self, heights, degs, parities=None, weights=None):
        self.m = m = len(heights)
        assert m < 32
        self.h = list(heights)
        self.degs = list(degs)
        self.par = list(parities) if parities is not None else [0] * m
        self.off = []
        o = 0
        for hh in self.h:
            self.off.append(o)
            o += hh
        self.nbits = o
        self.mask = [((1 << hh) - 1) << self.off[i] for i, hh in enumerate(self.h)]
        self.one = [1 << self.off[i] for i in range(m)]
        self.w = [tuple(x) for x in weights] if weights is not None else [()] * m
        self.r = len(self.w[0]) if weights is not None else 0

    # ------------------------------------------------------------ monomials
    def exps(self, A):
        return [(A & self.mask[i]) >> self.off[i] for i in range(self.m)]

    def pack(self, exps):
        A = 0
        for i, a in enumerate(exps):
            assert 0 <= a < (1 << self.h[i]), (i, a)
            A |= a << self.off[i]
        return A

    def mdeg(self, A):
        return sum(a * d for a, d in zip(self.exps(A), self.degs))

    def mwt(self, A):
        e = self.exps(A)
        return tuple(sum(e[j] * self.w[j][t] for j in range(self.m)) for t in range(self.r))

    def mpar(self, A):
        e = self.exps(A)
        return sum(e[j] * self.par[j] for j in range(self.m)) & 1

    def d(self, i, A):
        """d_i x^A, or None"""
        if A & self.mask[i]:
            return A - self.one[i]
        return None

    # ------------------------------------------------------------ fields
    def key(self, A, i):
        return (A << 5) | i

    def kdeg(self, k):
        return self.mdeg(k >> 5) - self.degs[k & 31]

    def kwt(self, k):
        A, i = k >> 5, k & 31
        mw = self.mwt(A)
        return tuple(mw[t] - self.w[i][t] for t in range(self.r))

    def kpar(self, k):
        return (self.mpar(k >> 5) + self.par[k & 31]) & 1

    def bracket(self, X, Y):
        res = set()
        d = self.d
        for kx in X:
            S, i = kx >> 5, kx & 31
            for ky in Y:
                T, j = ky >> 5, ky & 31
                dT = d(i, T)
                if dT is not None and not (S & dT):
                    res ^= {((S | dT) << 5) | j}
                dS = d(j, S)
                if dS is not None and not (T & dS):
                    res ^= {((T | dS) << 5) | i}
        return res

    def apply(self, X, f):
        """X(f) for a function f = set of monomials"""
        res = set()
        for kx in X:
            S, i = kx >> 5, kx & 31
            for T in f:
                dT = self.d(i, T)
                if dT is not None and not (S & dT):
                    res ^= {S | dT}
        return res

    def square(self, X):
        """X^2 as a derivation; valid only if every height is 1 (then O is
        generated by the x_j and a derivation is fixed by its values on them)."""
        assert all(hh == 1 for hh in self.h)
        coef = {}
        for kx in X:
            coef.setdefault(kx & 31, set()).symmetric_difference_update({kx >> 5})
        res = set()
        for j, f in coef.items():
            g = self.apply(X, f)
            for A in g:
                res ^= {(A << 5) | j}
        return res

    # ------------------------------------------------------------ parsing
    def field(self, terms):
        """terms: list of (dict coord->exponent, i) ; returns set of keys"""
        res = set()
        for mono, i in terms:
            e = [0] * self.m
            for c, a in mono.items():
                e[c] = a
            A = self.pack(e)
            res ^= {(A << 5) | i}
        return res

    def all_monos(self):
        """iterate over all packed monomials"""
        ranges = [range(1 << hh) for hh in self.h]
        for e in itertools.product(*ranges):
            yield self.pack(e)


def parse_field(sp, s, names):
    """Parse 'x1 x2 d3 + x4^(2) d5 + d7' -- names: dict name->coord index.
    A monomial is a product of tokens 'xk' or 'xk^(a)'; the derivative 'dk'
    ends the term.  Coefficients are all 1 (F_2)."""
    res = set()
    s = s.replace('∂', 'd')
    for term in s.split('+'):
        toks = term.split()
        if not toks:
            continue
        e = [0] * sp.m
        der = None
        for t in toks:
            if t.startswith('d'):
                assert der is None, term
                der = names[t[1:]]
            else:
                if '^(' in t:
                    nm, a = t.split('^(')
                    a = int(a.rstrip(')'))
                else:
                    nm, a = t, 1
                e[names[nm]] += a
        assert der is not None, term
        A = sp.pack(e)
        res ^= {(A << 5) | der}
    return res


# ------------------------------------------------------------ weights
def find_weights(sp, fields):
    """Integer basis of { w in Z^m : every field in `fields` is homogeneous
    w.r.t. wt(x^a d_i) = <a,w> - w_i }.  Returns list of weight vectors (one
    per coordinate), i.e. transposed: weights[i] = (w^1_i, ..., w^r_i)."""
    rows = []
    for X in fields:
        keys = list(X)
        if len(keys) < 2:
            continue
        v0 = _wrow(sp, keys[0])
        for k in keys[1:]:
            v = _wrow(sp, k)
            rows.append([a - b for a, b in zip(v, v0)])
    m = sp.m
    # nullspace over Q
    from exactlin import nullspace
    if rows:
        ns = nullspace(rows)
    else:
        ns = [[Fraction(int(i == j)) for j in range(m)] for i in range(m)]
    # make integral
    basis = []
    for v in ns:
        den = 1
        for x in v:
            den = den * Fraction(x).denominator // _gcd(den, Fraction(x).denominator)
        basis.append([int(Fraction(x) * den) for x in v])
    return [tuple(basis[t][i] for t in range(len(basis))) for i in range(m)]


def _gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def _wrow(sp, k):
    A, i = k >> 5, k & 31
    e = sp.exps(A)
    v = list(e)
    v[i] -= 1
    return v


# ------------------------------------------------------------ F2 linear algebra
class Echelon:
    """A subspace of F_2^(keys), stored as {pivot_key: vector(set)}, pivot = max key."""

    def __init__(self):
        self.piv = {}

    def reduce(self, v):
        """canonical (hence linear) normal form: no pivot key survives"""
        v = set(v)
        piv = self.piv
        P = v & piv.keys()
        while P:
            p = max(P)
            v ^= piv[p]
            P = v & piv.keys()
        return v

    def add(self, v):
        v = self.reduce(v)
        if v:
            self.piv[max(v)] = v
            return True
        return False

    def __len__(self):
        return len(self.piv)

    def basis(self):
        return list(self.piv.values())

    def contains(self, v):
        return not self.reduce(v)


class BitEchelon:
    """Echelon over local integer indices; vectors are python ints."""

    def __init__(self):
        self.piv = {}

    def reduce(self, v):
        piv = self.piv
        while v:
            p = v.bit_length() - 1
            b = piv.get(p)
            if b is None:
                return v
            v ^= b
        return v

    def reduce_full(self, v):
        for p in sorted(self.piv, reverse=True):
            if (v >> p) & 1:
                v ^= self.piv[p]
        return v

    def add(self, v):
        v = self.reduce(v)
        if v:
            self.piv[v.bit_length() - 1] = v
            return True
        return False

    def __len__(self):
        return len(self.piv)


def kernel_bits(images):
    """images: list of ints (images of unknowns 0..U-1).  Returns list of ints
    over unknown indices spanning the kernel."""
    piv = {}
    ker = []
    for u, v in enumerate(images):
        c = 1 << u
        while v:
            p = v.bit_length() - 1
            b = piv.get(p)
            if b is None:
                piv[p] = (v, c)
                break
            v ^= b[0]
            c ^= b[1]
        else:
            ker.append(c)
    return ker
