#!/usr/bin/env python3
r"""Partial prolongs at N~ = 1 in the directions of the printed lowest/highest
weight vectors of g_1 (BGLLS (6.2)): V = the g_0-submodule generated by the
vector(s), then the prolong of (g_-, g_0, V).  Vectors that need a divided power
x^(k), k >= 2, do not exist at N~ = 1 and are reported as such.

usage: python3 partial.py ROW
"""
import itertools
import json
import os
import sys
from f2vf import Space, parse_field, find_weights
from prolong import prolong, Graded, log
from run_row import analyse, needs_height, names_of
import rows as R


def run(name):
    spec = R.ROWS[name]
    P = R.PARTIAL[name]
    nm = names_of(spec)
    for a, b in P['rename'].items():
        nm[a] = nm[b]
    m = len(spec['coords'])
    complete = spec['g0'] == 'complete'
    sp0 = Space([1] * m, spec['degs'], spec['par'])
    neg = [parse_field(sp0, s, nm) for s in spec['neg']]
    g0s = [] if complete else [s for s in spec['g0'] if needs_height(s) == 1]
    g0 = [parse_field(sp0, s, nm) for s in g0s]
    W = find_weights(sp0, neg + g0)
    sp = Space([1] * m, spec['degs'], spec['par'], W)
    neg = [parse_field(sp, s, nm) for s in spec['neg']]
    g0 = [parse_field(sp, s, nm) for s in g0s]
    G = prolong(sp, neg, None if complete else g0, verbose=False)
    log('%s: complete prolong at N~=1: %d, g_1 = %d %s' % (name, G.dim(), G.dim(1), G.parity_dims(1)))
    G0 = G.basis(0)
    vecs = {}
    for k, s in P['vecs'].items():
        if needs_height(s) > 1:
            log('   %s needs a divided power: absent at N~=1' % k)
            continue
        v = parse_field(sp, s, nm)
        ok = G.contains(v)
        log('   %s lies in G_1: %s' % (k, ok))
        if ok:
            vecs[k] = v
    out = {'row': name, 'G': G.dim(), 'G1': G.dim(1)}
    names = sorted(vecs)
    for r in range(1, len(names) + 1):
        for combo in itertools.combinations(names, r):
            V = Graded(sp)
            queue = []
            for k in combo:
                if V.add(vecs[k]):
                    queue.append(vecs[k])
            while queue:
                v = queue.pop()
                for x in G0:
                    w = V.reduce(sp.bracket(x, v))
                    if w:
                        V.add(w)
                        queue.append(w)
            # [g_-1, V]
            B = Graded(sp)
            for e in G.basis(-1):
                for v in V.basis(1):
                    B.add(sp.bracket(e, v))
            Gp = prolong(sp, neg, G0, g1=V.basis(1), verbose=False)
            lab = '+'.join(combo)
            log('-- direction %s: dim V = %d %s, dim [g_-1,V] = %d (g_0 = %d), prolong dims %s'
                % (lab, V.dim(1), V.parity_dims(1), B.dim(0), G.dim(0),
                   {d: Gp.dim(d) for d in Gp.degrees()}))
            res = analyse(sp, Gp, '%s partial prolong in direction %s' % (name, lab))
            out[lab] = {'V': [V.dim(1), list(V.parity_dims(1))], '[g-1,V]': B.dim(0), 'result': res}
    os.makedirs('results', exist_ok=True)
    json.dump(out, open('results/%s_partial.json' % name.replace('~', 't'), 'w'), indent=1, default=str)


if __name__ == '__main__':
    for n in sys.argv[1:]:
        run(n)
