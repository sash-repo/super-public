#!/usr/bin/env python3
"""Finite-dimensional Lie algebras over F_2 given by structure constants
(br(i,j) -> int bitmask): derived series, ideals, simplicity (brute force over
the ideal generated by each basis element is not a proof; we use the
irreducibility of the adjoint module via Burnside instead), and the minimal
2-envelope inside Der = the 2-closure of ad L in End(L)."""
from f2vf import BitEchelon, kernel_bits


class Lie:
    def __init__(self, n, br):
        self.n = n
        self._br = br
        self.cache = {}

    def br(self, i, j):
        k = (i, j)
        v = self.cache.get(k)
        if v is None:
            v = self.cache[k] = self._br(i, j)
        return v

    def brv(self, a, b):
        out = 0
        i = 0
        while a:
            if a & 1:
                bb, j = b, 0
                while bb:
                    if bb & 1:
                        out ^= self.br(i, j)
                    bb >>= 1
                    j += 1
            a >>= 1
            i += 1
        return out

    def ad(self, v):
        """matrix of ad v as list of columns (ints)"""
        return [self.brv(v, 1 << j) for j in range(self.n)]


def span(vecs):
    E = BitEchelon()
    for v in vecs:
        E.add(v)
    return E


def derived(L, S=None):
    B = list(S.piv.values()) if S is not None else [1 << i for i in range(L.n)]
    return span(L.brv(a, b) for a in B for b in B)


def center(L):
    imgs = []
    for i in range(L.n):
        v = 0
        for j in range(L.n):
            v |= L.br(i, j) << (j * L.n)
        imgs.append(v)
    return kernel_bits(imgs)


def mat_of(cols, n):
    M = 0
    for c, col in enumerate(cols):
        r = 0
        while col:
            if col & 1:
                M |= 1 << (r * n + c)
            col >>= 1
            r += 1
    return M


def matmul(A, B, n):
    C = 0
    mask = (1 << n) - 1
    for r in range(n):
        row = (A >> (r * n)) & mask
        acc = 0
        c = 0
        while row:
            if row & 1:
                acc ^= (B >> (c * n)) & mask
            row >>= 1
            c += 1
        C |= acc << (r * n)
    return C


def two_envelope(L, basis):
    """2-closure of ad(span basis) in End(L): returns its dimension and the
    dimension of ad(span basis) (= dim span if the center is 0)."""
    n = L.n
    E = BitEchelon()
    mats = []
    for v in basis:
        M = mat_of(L.ad(v), n)
        if E.add(M):
            mats.append(M)
    d0 = len(E)
    queue = list(mats)
    while queue:
        M = queue.pop()
        S = matmul(M, M, n)
        if E.add(S):
            queue.append(S)
    return len(E), d0


def is_irreducible_adjoint(L, basis):
    """absolute irreducibility of the adjoint module of S = span(basis) restricted
    to S (Burnside over F_2), i.e. S simple over the algebraic closure; S must be
    an ideal closed under bracket and given in coordinates of L."""
    # coordinates inside S
    piv = {}
    for idx, v in enumerate(basis):
        c = 1 << idx
        while v:
            p = v.bit_length() - 1
            if p in piv:
                v ^= piv[p][0]
                c ^= piv[p][1]
            else:
                piv[p] = (v, c)
                break

    def coords(w):
        c = 0
        while w:
            p = w.bit_length() - 1
            w ^= piv[p][0]
            c ^= piv[p][1]
        return c
    k = len(basis)
    gens = [mat_of([coords(L.brv(x, y)) for y in basis], k) for x in basis]
    I = 0
    for r in range(k):
        I |= 1 << (r * k + r)
    A = BitEchelon()
    A.add(I)
    front = [I]
    while front and len(A) < k * k:
        nf = []
        for X in front:
            for M in gens:
                Y = matmul(M, X, k)
                if A.add(Y):
                    nf.append(Y)
        front = nf
    return len(A) == k * k
