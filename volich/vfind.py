"""Hunting for a lucid form of Baranov's degree-5 identity.

The new identities of degree 5 form the S_5-module

        [5] + [4,1] + [3,2]   +   [2,2,1]
        \______  ______/          \__ __/
               v                     v
        generated by (v)          Baranov's

Since [2,2,1] occurs in Ind_{S_3 x S_2}^{S_5}(sgn (x) sgn), a generator can be
looked for among expressions ALTERNATING in three of the variables and in the
remaining two.  This module builds a fast oracle -- linear functionals that
kill everything already known -- and sweeps the candidates.
"""

