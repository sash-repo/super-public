P = 2147483647


def sgn(perm):
    """Sign of a permutation given as a tuple."""
    p = list(perm)
    s, seen = 1, [False] * len(p)
    for i in range(len(p)):
        if seen[i]:
            continue
        j, ln = i, 0
        while not seen[j]:
            seen[j] = True
            j = p[j]
            ln += 1
        if ln % 2 == 0:
            s = -s
    return s


def alt(f, letters, n=5):
    """Antisymmetrize the expression f over the given variables."""
    out = {}
    ls = list(letters)
    for perm in itertools.permutations(range(len(ls))):
        s = sgn(perm)
        sub = {i: i for i in range(1, n + 1)}          # untouched letters
        sub.update({ls[i]: ls[perm[i]] for i in range(len(ls))})
        for t, c in msubst(f, sub).items():
            out[t] = out.get(t, 0) + s * c
    return {t: c for t, c in out.items() if c}


def sym(f, letters, n=5):
    """Symmetrize the expression f over the given variables."""
    out = {}
    ls = list(letters)
    for perm in itertools.permutations(range(len(ls))):
        sub = {i: i for i in range(1, n + 1)}
        sub.update({ls[i]: ls[perm[i]] for i in range(len(ls))})
        for t, c in msubst(f, sub).items():
            out[t] = out.get(t, 0) + c
    return {t: c for t, c in out.items() if c}


def build_C(n, p=P, cache="C%d.cache"):
    """rref basis of C_n, cached on disk (it costs about a minute)."""
    import json
    import os
    path = cache % n
    ms = MSpace(n)
    if os.path.exists(path):
        with open(path) as fh:
            return ms, json.load(fh)
    lower = {k: identities(k, MSpace(k)) for k in range(3, n)}
    rows, seen = [], set()
    for f in consequences(lower, n):
        v = ms.vec(f)
        if not any(v):
            continue
        key = tuple(v)
        if key in seen:
            continue
        seen.add(key)
        rows.append([int(c) % p for c in v])
        if len(rows) > 4000:
            R, _ = ex_rref(rows, p=p)
            rows = [r for r in R if any(r)]
    R, _ = ex_rref(rows, p=p)
    C = [[int(x) for x in r] for r in R if any(r)]
    with open(path, "w") as fh:
        json.dump(C, fh)
    return ms, C


def build_known(n, p=P, extra=()):
    """rref basis of C_n together with the modules generated by `extra`."""
    ms = MSpace(n)
    lower = {k: identities(k, MSpace(k)) for k in range(3, n)}
    rows, seen = [], set()
    for f in consequences(lower, n):
        v = ms.vec(f)
        if not any(v):
            continue
        key = tuple(v)
        if key in seen:
            continue
        seen.add(key)
        rows.append([int(c) % p for c in v])
        if len(rows) > 4000:
            R, _ = ex_rref(rows, p=p)
            rows = [r for r in R if any(r)]
    R, _ = ex_rref(rows, p=p)
    C = [r for r in R if any(r)]
    U = list(C)
    for f in extra:
        for g in orbit(f, n):
            U.append([int(c) % p for c in ms.vec(g)])
    R, _ = ex_rref(U, p=p)
    U = [r for r in R if any(r)]
    return ms, C, U


def oracle(U, I_rows, p=P, howmany=6):
    """Functionals vanishing on U but not on the identities."""
    phis = ex_null(U, p=p)
    out = []
    for phi in phis:
        if any(sum(a * b for a, b in zip(phi, r)) % p for r in I_rows):
            out.append([int(c) % p for c in phi])
            if len(out) >= howmany:
                break
    return out


def test(v, phis, p=P):
    return any(sum(a * b for a, b in zip(phi, v)) % p for phi in phis)


