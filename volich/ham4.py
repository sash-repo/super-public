#!/usr/bin/env python3
"""
ham4.py --- the n = 4 anomaly of the Hamiltonian Volichenko algebras.

hamvol.py finds that for g = h'(0|4) the algebra h_{ad_x} is NOT absolutely
irreducible over its multiplications: dim <R_a> = dim <L_a> = dim <L,R> = 18
instead of 36.  Since <L_a, R_a> is also deficient, h has proper TWO-sided
ideals -- so h_{ad_x} is not a simple Volichenko algebra at all (heading 2) of
Statement 4.13.3).

This script exhibits the ideals and identifies them.  The reason is structural:
h'(0|4) = psl(2|2), whose even part sl(2) + sl(2) is the one non-simple g_ev in
the list; by R1 a two-sided ideal of h is an ideal of g_ev stable under S.
Under g_ev = so(4) = Lambda^2(C^4) the two summands are the self-dual and the
anti-self-dual bivectors, spanned by  theta_i theta_j +- (Hodge dual).
"""

import sys, os
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hamvol import (HamVol, hyperbolic, add, smul, Echelon, popcount, bits)


def gen_ideal(H, seeds, sides="LR"):
    """the smallest subspace containing `seeds` and stable under the chosen
    multiplications; returns (dim, basis rows)"""
    E = Echelon(H.d)
    frontier = []
    for s in seeds:
        v = H.vec(s)
        if E.add(v):
            frontier.append(s)
    while frontier:
        new = []
        for w in frontier:
            for i in range(H.d):
                b = H.elt(i)
                cand = []
                if "R" in sides:
                    cand.append(H.prod(w, b))
                if "L" in sides:
                    cand.append(H.prod(b, w))
                for c in cand:
                    if E.add(H.vec(c)):
                        new.append(c)
        frontier = new
    return E.dim


def show(f, n):
    "print a Grassmann element readably"
    if not f:
        return "0"
    parts = []
    for m in sorted(f, key=lambda m: (popcount(m), m)):
        c = f[m]
        name = "".join("t%d" % (j + 1) for j in bits(m)) or "1"
        parts.append(("+ " if c > 0 else "- ") + (
            "%s" % name if abs(c) == 1 else "%s*%s" % (abs(c), name)))
    return " ".join(parts).lstrip("+ ")


def hodge_pairs(n=4):
    "theta_i theta_j  and its complement, as bitmasks"
    out = []
    full = (1 << n) - 1
    seen = set()
    for m in range(1 << n):
        if popcount(m) == 2 and m not in seen:
            c = full ^ m
            seen.add(m); seen.add(c)
            out.append((m, c))
    return out


def analyse(tag, B):
    H = HamVol(4, B)
    print("=" * 70)
    print("h'(0|4), %s:  dim h = %d, basis = %s"
          % (tag, H.d, [show({m: 1}, 4) for m in H.evb]))

    # the candidate splitting: self-dual / anti-self-dual bivectors
    for sign in (+1, -1):
        seeds = []
        for m, c in hodge_pairs(4):
            seeds.append({m: 1, c: sign})
        d_two = gen_ideal(H, seeds, "LR")
        d_r = gen_ideal(H, seeds, "R")
        d_l = gen_ideal(H, seeds, "L")
        print("  seeds  theta_i theta_j %s dual  (%d of them):"
              % ("+" if sign > 0 else "-", len(seeds)))
        print("     ", [show(s, 4) for s in seeds])
        print("      generates: two-sided %d, right %d, left %d  (dim h = %d)"
              % (d_two, d_r, d_l, H.d))
        if d_two < H.d:
            print("      ==> a PROPER TWO-SIDED ideal of dimension %d" % d_two)

    # single seeds, for completeness
    dims = set()
    for m, c in hodge_pairs(4):
        for sign in (+1, -1):
            dims.add(gen_ideal(H, [{m: 1, c: sign}], "LR"))
    print("  two-sided ideals generated by a single  t_i t_j +- dual :", sorted(dims))


if __name__ == "__main__":
    analyse("x = theta_1 ANISOTROPIC (the main Hamiltonian algebra)", None)
    analyse("x = theta_1 ISOTROPIC (the other one)", hyperbolic(4))
