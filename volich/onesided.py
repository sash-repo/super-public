#!/usr/bin/env python3
"""
Proposition 2.13 (no one-sided ideals) for the three exceptional Volichenko
algebras of the last row of Table 2.12.1 (proof in Subsec. 4.13).

A left ideal containing v contains A.v, where A is the unital associative
subalgebra of End(h) generated by the left multiplications L_g of the product
    g.h = [g,h] + S(g,h),  S(g,h) = [[g,x],[h,x]].
If A = End(h) then, by Burnside, h is an irreducible A-module, hence A.v = h
for every v != 0 and there is no proper left ideal.  Same on the right.

A is the smallest subspace of End(h) containing 1 and invariant under the
linear operators M |-> M.Q, Q a generator.  Walking that closure over Q in
pure Python is what makes nontriv.py slow for ab(3) (576 insertions into a
576-column rational echelon).  We therefore walk it MODULO A LARGE PRIME.

That costs no rigour, and in the direction we need: reduction mod p can only
LOWER the rank (a minor can vanish mod p, never appear), so

        rank_p(A) = dim End(h)   ==>   rank_Q(A) = dim End(h),

which is the conclusion we want.  The pure-Python rational closure in
nontriv.py confirms the same numbers for osp_a(4|2) and ag(2) independently.

Usage:  python3 onesided.py
"""

import os
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "."))

import nontriv                                # noqa: E402
import exc3                                   # noqa: E402

P = (1 << 61) - 1                             # a Mersenne prime


def to_p(x):
    """image of a Fraction in F_p (denominators here are tiny, never 0 mod p)"""
    x = F(x)
    assert x.denominator % P, "denominator divisible by p"
    return (x.numerator % P) * pow(x.denominator % P, P - 2, P) % P


def closure_mod_p(gens, n):
    """dim of the unital algebra generated by `gens`, computed in F_p."""
    full = n * n
    ech = {}                                   # pivot column -> normalized row

    def insert(v):
        for c in sorted(ech):
            if v[c]:
                f, row = v[c], ech[c]
                v = [(a - f * b) % P for a, b in zip(v, row)]
        c = next((i for i, a in enumerate(v) if a), None)
        if c is None:
            return False
        inv = pow(v[c], P - 2, P)
        ech[c] = [a * inv % P for a in v]
        return True

    def mul(A, B):
        return [[sum(A[i][k] * B[k][j] for k in range(n)) % P
                 for j in range(n)] for i in range(n)]

    ident = [[1 if i == j else 0 for j in range(n)] for i in range(n)]
    frontier = []
    for M in [ident] + gens:
        if insert([M[i][j] for i in range(n) for j in range(n)]):
            frontier.append(M)
    while frontier and len(ech) < full:
        new = []
        for A in frontier:
            for B in gens:
                C = mul(A, B)
                if insert([C[i][j] for i in range(n) for j in range(n)]):
                    new.append(C)
                    if len(ech) == full:
                        return full
        frontier = new
    return len(ech)


def check(g, label):
    rows = nontriv.root_vectors(g, verbose=False)
    x = None
    for (s, wt, iso, wit, dL) in rows:
        if iso and wit:
            x = g.e(s)
            break
    assert x is not None, "no isotropic root vector ensuring nontriviality"
    h = nontriv.Voli(g, x)
    n = h.dim
    full = n * n

    L = [[[to_p(h.prod(h.e(i), h.e(j))[k]) for j in range(n)]
          for k in range(n)] for i in range(n)]
    R = [[[to_p(h.prod(h.e(j), h.e(i))[k]) for j in range(n)]
          for k in range(n)] for i in range(n)]

    out = []
    for name, gens in (("left", L), ("right", R)):
        r = closure_mod_p(gens, n)
        out.append(r)
        print("   %-11s %-5s multiplications generate dim %d of End(h) = %d "
              "  -> %s"
              % (label, name, r, full, "A = End(h)" if r == full else "NOT"))
    return all(r == full for r in out), full


if __name__ == "__main__":
    print("closure computed in F_p, p = 2^61-1 (a lower bound for the rank "
          "over Q, hence conclusive when it is full)\n")
    ok = True
    for (c, lab) in [((1, 1, -2), "osp(4|2)"), ((1, 2, -3), "osp_a, a=2")]:
        good, _ = check(nontriv.from_d21a(c, lab), lab)
        ok &= good
    good, _ = check(nontriv.from_exc3(exc3.build_G3()), "ag(2)")
    ok &= good
    good, _ = check(nontriv.from_exc3(exc3.build_F4()), "ab(3)")
    ok &= good
    print("\nProposition 2.13 holds for all of them: %s" % ok)
    sys.exit(0 if ok else 1)
