"""The NEW multilinear identities of degrees 3, 4, 5, cached.

The T-ideal of all identities of degree < 8 is generated by these: I_4 = C_4 +
new_4 with C_4 inside the T-ideal of I_3, and I_5 = C_5 + new_5 likewise; and
nothing is new in degrees 6 and 7 by [BrP].  So 4 + 9 + 15 = 28 elements
generate every consequence any of the runs below has to divide out.
"""

import pickle
import sys
import time
from pathlib import Path

import numpy as np

from mdeg import Ech, P
from videal import MSpace, identities, consequences

HERE = Path(__file__).resolve().parent
CACHE = HERE / "gens.pkl"


def as_row(f, pos, dim):
    r = np.zeros(dim)
    for t, c in f.items():
        r[pos[t]] = float((int(c.numerator) *
                           pow(int(c.denominator), P - 2, P)) % P
                          if hasattr(c, "numerator") else c % P)
    return r


def new_in_degree(n, lower, verbose=True):
    """A basis of a complement of C_n in I_n, as formal elements of M_n."""
    ms = MSpace(n)
    pos, dim = ms.pos, len(ms.trees)
    t0 = time.time()
    I = identities(n, ms)
    if verbose:
        print("  degree %d: dim I_n = %d  [%.0fs]" % (n, len(I), time.time() - t0),
              flush=True)
    e = Ech(dim)
    if lower:
        buf = []
        for g in consequences(lower, n):
            r = as_row(g, pos, dim)
            if r.any():
                buf.append(r)
            if len(buf) >= 256:
                e.add_block(np.array(buf))
                buf = []
        if buf:
            e.add_block(np.array(buf))
    dC = e.rank()
    if verbose:
        print("  degree %d: dim C_n = %d  [%.0fs]" % (n, dC, time.time() - t0),
              flush=True)
    new = []
    for f in I:
        r = as_row(f, pos, dim)
        if e.add_block(r[None, :]):
            new.append(f)
    if verbose:
        print("  degree %d: new = %d (dim I_n - dim C_n = %d)  [%.0fs]"
              % (n, len(new), len(I) - dC, time.time() - t0), flush=True)
    assert len(new) == len(I) - dC
    return I, new


def build():
    I3, new3 = new_in_degree(3, {})
    I4, new4 = new_in_degree(4, {3: I3})
    I5, new5 = new_in_degree(5, {3: I3, 4: I4})
    gens = {3: new3, 4: new4, 5: new5}
    with open(CACHE, "wb") as fh:
        pickle.dump(gens, fh)
    return gens


def load():
    if CACHE.exists():
        with open(CACHE, "rb") as fh:
            return pickle.load(fh)
    return build()


if __name__ == "__main__":
    g = build()
    print("cached:", {k: len(v) for k, v in g.items()})
