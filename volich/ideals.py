#!/usr/bin/env python3
"""
ideals.py -- Proposition 2.13 of the text (proof in Subsec. 4.13)
("Simple epimorphic Volichenko algebras have no one-sided ideals.")
for the two intriguing examples, vgl_mu(p|q) and vq_mu(n).

The reduction that makes the Proposition finite (remarks R1--R3 of Subsec. 4.13):

  R1.  In h = h_{ad_x} write the product as  a.b = [a,b] + S(a,b), where
       [ , ] is the bracket of g_ev and S(a,b) = [[a,x],[b,x]] is symmetric.
       Then  a.b - b.a = 2[a,b]  and  a.b + b.a = 2S(a,b).  Hence a LEFT ideal
       I is two-sided  <==>  [h,I] subset I  <==>  I is an ideal of g_ev.

  R2.  S(a,-) = 0 for a in h_0 = Ann(x); so L_a = ad_a there, and every
       one-sided ideal is in particular an h_0-submodule of h.

  R3.  (Burnside)  h has no proper one-sided ideal at all  <==>  the unital
       associative algebra generated by the left (resp. right) multiplications
       is the whole of End(h).

R3 is what we verify here, over F_p with p = 2^61-1: reduction mod p can only
lower a rank, so a full rank mod p forces a full rank over Q.

Run:  python3 ideals.py
"""

import os
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from onesided import P, closure_mod_p, to_p       # noqa: E402


# ------------------------------------------------------------------ the algebras

class VGL:
    """vgl_mu(p|q): (p+q)x(p+q) matrices, mu = a:b.

    h_0 = block diagonal, h_1 = block off-diagonal;
    the product is the matrix commutator except on h_1 x h_1, where it is
    a[X,Y]_- + b[X,Y]_+  (Subsec. 1.3.1 of the paper).
    """

    name_fmt = "vgl_(%s:%s)(%d|%d)"

    def __init__(self, p, q, a, b):
        self.p, self.q, self.a, self.b = p, q, F(a), F(b)
        self.d = d = p + q
        self.name = self.name_fmt % (a, b, p, q)
        # basis: all matrix units E_ij
        self.idx = [(i, j) for i in range(d) for j in range(d)]
        self.pos = {ij: k for k, ij in enumerate(self.idx)}
        self.dim = len(self.idx)
        self.deg = [0 if self._same(i, j) else 1 for (i, j) in self.idx]

    def _same(self, i, j):
        return (i < self.p) == (j < self.p)

    def keep(self, i, j):
        return True

    def e(self, k):
        v = [F(0)] * self.dim
        v[k] = F(1)
        return v

    def _mat(self, v):
        M = [[F(0)] * self.d for _ in range(self.d)]
        for k, c in enumerate(v):
            if c:
                i, j = self.idx[k]
                M[i][j] += c
        return M

    def _vec(self, M):
        return [M[i][j] for (i, j) in self.idx]

    def prod(self, u, v):
        """the Volichenko product, bilinear in the h_0/h_1 decomposition."""
        out = [F(0)] * self.dim
        for k, uk in enumerate(u):
            if not uk:
                continue
            for l, vl in enumerate(v):
                if not vl:
                    continue
                A, B = self._mat(self.e(k)), self._mat(self.e(l))
                AB, BA = matmul(A, B), matmul(B, A)
                if self.deg[k] == 1 and self.deg[l] == 1:
                    C = [[self.a * (AB[i][j] - BA[i][j])
                          + self.b * (AB[i][j] + BA[i][j])
                          for j in range(self.d)] for i in range(self.d)]
                else:
                    C = [[AB[i][j] - BA[i][j] for j in range(self.d)]
                         for i in range(self.d)]
                w = self._vec(C)
                for t, c in enumerate(w):
                    if c:
                        out[t] += uk * vl * c
        return out


class VQ(VGL):
    """vq_mu(n) inside vgl_mu(n|n): h_0 = diag(A,A), h_1 = antidiag(B,B)."""

    def __init__(self, n, a, b):
        VGL.__init__(self, n, n, a, b)
        self.n = n
        self.name = "vq_(%s:%s)(%d)" % (a, b, n)
        # a basis of the subalgebra, written in the vgl basis
        self.sub = []
        for i in range(n):
            for j in range(n):
                v = [F(0)] * self.dim
                v[self.pos[(i, j)]] = F(1)
                v[self.pos[(i + n, j + n)]] = F(1)
                self.sub.append(v)
        for i in range(n):
            for j in range(n):
                v = [F(0)] * self.dim
                v[self.pos[(i, j + n)]] = F(1)
                v[self.pos[(i + n, j)]] = F(1)
                self.sub.append(v)


def matmul(A, B):
    d = len(A)
    return [[sum(A[i][k] * B[k][j] for k in range(d)) for j in range(d)]
            for i in range(d)]


# ------------------------------------------------------------------ the checks

def coords(basis, v):
    """coordinates of v in the given (echelonised on the fly) basis; exact."""
    # basis vectors here are 0/1 patterns with disjoint supports up to the
    # doubling in VQ, so a direct read-off is safe; verify it.
    out = []
    rest = list(v)
    for b in basis:
        piv = next(i for i, c in enumerate(b) if c)
        c = rest[piv] / b[piv]
        out.append(c)
        if c:
            rest = [x - c * y for x, y in zip(rest, b)]
    assert not any(rest), "not in the span of the given basis"
    return out


def multiplication_tables(alg, basis):
    n = len(basis)
    L, R = [], []
    prods = [[coords(basis, alg.prod(basis[i], basis[j])) for j in range(n)]
             for i in range(n)]
    for i in range(n):
        L.append([[to_p(prods[i][j][k]) for j in range(n)] for k in range(n)])
        R.append([[to_p(prods[j][i][k]) for j in range(n)] for k in range(n)])
    return L, R, prods


def check_reduction(alg, basis, prods):
    """R2: the symmetric half of the product vanishes as soon as one factor
    lies in h_0 -- which is what makes every one-sided ideal an h_0-submodule.
    (R1 is the tautology  a.b -+ b.a = 2 x (anti)symmetric half, and the
    antisymmetric half is a Lie bracket: on h_1 x h_1 it is a[ , ]_-, i.e. the
    bracket of gl(p+q) rescaled on h_1, an isomorphic copy for a != 0.)
    """
    n = len(basis)
    bad = 0
    for i in range(n):
        for j in range(n):
            sym = [(x + y) / 2 for x, y in zip(prods[i][j], prods[j][i])]
            deg_i = 0 if all(alg.deg[k] == 0 or not c
                             for k, c in enumerate(basis[i])) else 1
            deg_j = 0 if all(alg.deg[k] == 0 or not c
                             for k, c in enumerate(basis[j])) else 1
            if (deg_i == 0 or deg_j == 0) and any(sym):
                bad += 1
    return bad


def unit(alg, basis):
    """coordinates of the identity matrix 1_{p+q} in the given basis."""
    v = [F(0)] * alg.dim
    for i in range(alg.d):
        v[alg.pos[(i, i)]] = F(1)
    return coords(basis, v)


def ideal_generated(alg, basis, prods, v):
    """dimension of the two-sided ideal of h generated by v (exact)."""
    n = len(basis)

    def mul(u, w):
        out = [F(0)] * n
        for i, ui in enumerate(u):
            if not ui:
                continue
            for j, wj in enumerate(w):
                if not wj:
                    continue
                for k in range(n):
                    out[k] += ui * wj * prods[i][j][k]
        return out

    rows, ech = [], {}

    def insert(x):
        x = list(x)
        for c in sorted(ech):
            if x[c]:
                f, r = x[c], ech[c]
                x = [p - f * q for p, q in zip(x, r)]
        c = next((i for i, p in enumerate(x) if p), None)
        if c is None:
            return None
        ech[c] = [p / x[c] for p in x]
        rows.append(x)
        return x

    frontier = [x for x in [insert(v)] if x]
    while frontier:
        new = []
        for u in frontier:
            for k in range(n):
                for w in (mul(alg_e(n, k), u), mul(u, alg_e(n, k))):
                    r = insert(w)
                    if r:
                        new.append(r)
        frontier = new
    return len(ech)


def alg_e(n, k):
    v = [F(0)] * n
    v[k] = F(1)
    return v


def run(alg, basis=None, expect_center=True):
    basis = basis if basis is not None else [alg.e(k) for k in range(alg.dim)]
    n = len(basis)
    full = n * n
    L, R, prods = multiplication_tables(alg, basis)
    bad = check_reduction(alg, basis, prods)
    rl = closure_mod_p(L, n)
    rr = closure_mod_p(R, n)

    one = unit(alg, basis)
    d_one = ideal_generated(alg, basis, prods, one)
    # every other basis vector must generate the whole algebra
    others = min(ideal_generated(alg, basis, prods, alg_e(n, k))
                 for k in range(n))

    # if 1 spans a trivial ideal, the largest the multiplication algebra can
    # possibly be is  K.Id + { M : M(1) = 0 },  of dimension n^2 - n + 1
    cap = n * n - n + 1 if expect_center else full
    if rl == cap == rr:
        verdict = ("L = K.Id + {M : M(1)=0}, the maximum compatible with the "
                   "central ideal")
    elif rl == full == rr:
        verdict = "no one-sided ideals"
    elif others == n - 1:
        verdict = "a second ideal of codimension 1 as well"
    else:
        verdict = "*** INCONCLUSIVE"
    print("  %-20s dim h=%2d  R2 %-6s  L:%4d R:%4d  (End=%d, cap=%d)"
          % (alg.name, n, "OK" if bad == 0 else "%dBAD" % bad,
             rl, rr, full, cap))
    print("       %-15s ideal gen. by 1_%d : %d ;  min over the other "
          "basis vectors : %d   -- %s"
          % ("", alg.d, d_one, others, verdict))
    if expect_center:
        return bad == 0 and rl == cap == rr and d_one == 1 and others == n
    return bad == 0 and rl == full == rr


def subquotient_vq(n, a, b):
    """the simple subquotient  vpsq_mu(n) = {qtr = 0} / K.1_{2n}  of vq_mu(n).

    qtr of  diag(A,A) + antidiag(B,B)  is  tr B, and the B-component of every
    product is a commutator, so {qtr = 0} is an ideal of codimension 1; the
    identity 1_{2n} = diag(1_n,1_n) spans a central ideal inside it.
    """
    alg = VQ(n, a, b)
    # basis of the codimension-1 ideal, with 1_{2n} first
    ii = []
    one = [F(0)] * alg.dim
    for i in range(2 * n):
        one[alg.pos[(i, i)]] = F(1)
    ii.append(one)
    for i in range(n):                                     # diag(A,A), A != 1
        for j in range(n):
            if i == j == 0:
                continue
            v = [F(0)] * alg.dim
            v[alg.pos[(i, j)]] = F(1)
            v[alg.pos[(i + n, j + n)]] = F(1)
            if i == j:
                v[alg.pos[(0, 0)]] = F(-1)
                v[alg.pos[(n, n)]] = F(-1)
            ii.append(v)
    for i in range(n):                                     # antidiag(B,B), tr B = 0
        for j in range(n):
            if i == j == 0:
                continue
            v = [F(0)] * alg.dim
            v[alg.pos[(i, j + n)]] = F(1)
            v[alg.pos[(i + n, j)]] = F(1)
            if i == j:
                v[alg.pos[(0, n)]] = F(-1)
                v[alg.pos[(n, 0)]] = F(-1)
            ii.append(v)
    return alg, ii


def solve_coords(basis, v):
    """exact coordinates of v in `basis` (which must be independent)."""
    from exactlin import solve
    cols = list(zip(*basis))                 # rows of the matrix B (dim x k)
    x = solve([list(r) for r in cols], list(v))
    assert x is not None, "vector not in the span"
    return list(x)


def run_subquotient(n, a, b):
    alg, ii = subquotient_vq(n, a, b)
    k = len(ii)
    prods = [[solve_coords(ii, alg.prod(ii[i], ii[j])) for j in range(k)]
             for i in range(k)]
    # 1_{2n} is central: its whole row and column must vanish
    central = all(not any(prods[0][j]) and not any(prods[j][0])
                  for j in range(k))
    # drop the first coordinate: that is the quotient by K.1
    m = k - 1
    L = [[[to_p(prods[i + 1][j + 1][c + 1]) for j in range(m)]
          for c in range(m)] for i in range(m)]
    R = [[[to_p(prods[j + 1][i + 1][c + 1]) for j in range(m)]
          for c in range(m)] for i in range(m)]
    rl, rr = closure_mod_p(L, m), closure_mod_p(R, m)
    ok = central and rl == m * m == rr
    print("  vpsq_(%s:%s)(%d)      dim = %2d   1_{2n} central: %-3s   "
          "L:%4d R:%4d of %d   -- %s"
          % (a, b, n, m, "yes" if central else "NO", rl, rr, m * m,
             "no one-sided ideals" if rl == m * m == rr else "*** INCONCLUSIVE"))
    return ok


def main():
    print("Proposition 2.13 (Subsec. 4.13), for the two intriguing examples.")
    print("Closure computed in F_p, p = 2^61-1 (a lower bound for the rank "
          "over Q, hence conclusive when full).\n")
    ok = True
    print(" vgl_mu(p|q):")
    for (p, q) in [(1, 1), (2, 1), (1, 2), (2, 2), (3, 1)]:
        for (a, b) in [(1, 1), (2, 3), (1, -1)]:
            ok &= run(VGL(p, q, a, b))
    print("\n vq_mu(n) -- it has a SECOND ideal, {qtr = 0}, of codimension 1:")
    for n in [2, 3]:
        for (a, b) in [(1, 1), (2, 3)]:
            alg = VQ(n, a, b)
            run(alg, alg.sub)
    print("\n ... and the subquotient vpsq_mu(n) = {qtr=0}/K.1 ;")
    print(" n = 2 splits into two 3-dimensional left ideals (18 = 9 + 9), which")
    print(" is the classical exclusion: psq(n) is simple only for n >= 3.")
    for n in [2, 3]:
        for (a, b) in [(1, 1), (2, 3)]:
            good = run_subquotient(n, a, b)
            if n >= 3:
                ok &= good
    print("\nALL CHECKS PASSED" if ok else "\n*** SOMETHING FAILED ***")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
