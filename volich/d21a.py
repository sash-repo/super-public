#!/usr/bin/env python3
"""Explicit model of osp_a(4|2) and the graded subalgebra analysis
for its two Z-gradings (depth 1 and the contact one of depth 2).

Model (classical):  g_ev = sl(2)_1 + sl(2)_2 + sl(2)_3,  g_od = C^2 (x) C^2 (x) C^2,
  [x1(x)x2(x)x3, y1(x)y2(x)y3] = sum_m c_m * prod_{k!=m} w(xk,yk) * gamma_m(xm,ym)
with w = symplectic form on C^2, gamma: S^2(C^2) -> sl(2), and c_1+c_2+c_3 = 0.
The parameter: (c_1 : c_2 : c_3);  a = c_2/c_1  after normalisation, a=1 <-> osp(4|2).
"""
from fractions import Fraction as F
from itertools import product
import random
from lin import span, dim, inspan, kernel, rref, zero

# ------------------------------------------------------------------ basis
# 0,1,2 = E1,H1,F1 ; 3,4,5 = E2,H2,F2 ; 6,7,8 = E3,H3,F3
# 9..16 = x_{ijk}, index 9 + 4i + 2j + k
N = 17
PAR = [0] * 9 + [1] * 8


def xi(i, j, k):
    return 9 + 4 * i + 2 * j + k


def sl2(m, kind):
    return 3 * m + {"E": 0, "H": 1, "F": 2}[kind]


def w(i, j):
    """symplectic form on C^2, w(u0,u1)=1."""
    if i == 0 and j == 1: return F(1)
    if i == 1 and j == 0: return F(-1)
    return F(0)


def gamma(m, i, j):
    """gamma_m(u_i,u_j) in sl(2)_m, as a vector of length N."""
    v = zero(N)
    if i == 0 and j == 0:
        v[sl2(m, "E")] = F(2)
    elif i == 1 and j == 1:
        v[sl2(m, "F")] = F(-2)
    else:
        v[sl2(m, "H")] = F(-1)
    return v


def build(c):
    """structure constants; c = (c1,c2,c3) with c1+c2+c3 = 0."""
    B = [[zero(N) for _ in range(N)] for _ in range(N)]

    def setb(i, j, v):
        B[i][j] = list(v)

    # sl(2) x sl(2)
    for m in range(3):
        E, H, Fm = sl2(m, "E"), sl2(m, "H"), sl2(m, "F")
        v = zero(N); v[H] = F(1); setb(E, Fm, v)
        v = zero(N); v[H] = F(-1); setb(Fm, E, v)
        v = zero(N); v[E] = F(2); setb(H, E, v)
        v = zero(N); v[E] = F(-2); setb(E, H, v)
        v = zero(N); v[Fm] = F(-2); setb(H, Fm, v)
        v = zero(N); v[Fm] = F(2); setb(Fm, H, v)
    # even on odd
    for m in range(3):
        for I in product((0, 1), repeat=3):
            src = xi(*I)
            for kind in "EHF":
                A = sl2(m, kind)
                v = zero(N)
                im = I[m]
                if kind == "E":
                    if im == 1:
                        J = list(I); J[m] = 0
                        v[xi(*J)] = F(1)
                elif kind == "F":
                    if im == 0:
                        J = list(I); J[m] = 1
                        v[xi(*J)] = F(1)
                else:
                    v[src] = F(1) if im == 0 else F(-1)
                setb(A, src, v)
                setb(src, A, [-t for t in v])       # [odd,even] = -[even,odd]
    # odd on odd  (symmetric)
    for I in product((0, 1), repeat=3):
        for J in product((0, 1), repeat=3):
            v = zero(N)
            for m in range(3):
                coef = F(c[m])
                for k in range(3):
                    if k != m:
                        coef *= w(I[k], J[k])
                if coef != 0:
                    g = gamma(m, I[m], J[m])
                    v = [a + coef * b for a, b in zip(v, g)]
            setb(xi(*I), xi(*J), v)
    return B


def bracket(B, x, y):
    out = zero(N)
    for i, xi_ in enumerate(x):
        if xi_ == 0:
            continue
        for j, yj in enumerate(y):
            if yj == 0:
                continue
            cf = xi_ * yj
            row = B[i][j]
            for k, t in enumerate(row):
                if t:
                    out[k] += cf * t
    return out


def check_jacobi(B):
    """super Jacobi: [a,[b,c]] = [[a,b],c] + (-1)^{|a||b|} [b,[a,c]]"""
    e = [[F(1) if i == k else F(0) for i in range(N)] for k in range(N)]
    bad = 0
    for a in range(N):
        for b in range(N):
            for c in range(N):
                lhs = bracket(B, e[a], bracket(B, e[b], e[c]))
                r1 = bracket(B, bracket(B, e[a], e[b]), e[c])
                r2 = bracket(B, e[b], bracket(B, e[a], e[c]))
                sg = F(-1) ** (PAR[a] * PAR[b])
                rhs = [x + sg * y for x, y in zip(r1, r2)]
                if lhs != rhs:
                    bad += 1
    return bad


# ------------------------------------------------------------------ tools

def subalg_generated(B, gens):
    """span of the subalgebra generated by gens."""
    basis = span([list(g) for g in gens])
    changed = True
    while changed:
        changed = False
        for i in range(len(basis)):
            for j in range(len(basis)):
                v = bracket(B, basis[i], basis[j])
                if any(v) and not inspan(v, basis):
                    basis = span(basis + [v])
                    changed = True
    return basis


def stab(B, S, V):
    """{x in span(S) : [x,v] in span(V) for all v in V}."""
    Sb = span([list(s) for s in S])
    Vb = span([list(v) for v in V])
    ann = kernel(Vb, N) if Vb else [[F(1) if i == j else F(0) for i in range(N)]
                                   for j in range(N)]
    rows = []
    for phi in ann:
        for v in Vb:
            # condition: phi([x,v]) = 0, linear in x -> row over the S-basis
            rows.append([sum(phi[k] * bracket(B, s, v)[k] for k in range(N))
                         for s in Sb])
    if not rows:
        return Sb
    ker = kernel(rows, len(Sb))
    out = []
    for co in ker:
        vec = zero(N)
        for cf, s in zip(co, Sb):
            if cf:
                vec = [x + cf * y for x, y in zip(vec, s)]
        out.append(vec)
    return span(out)


def grading(B, D):
    """eigenspaces of ad(D); returns dict deg -> basis (as vectors)."""
    comps = {}
    e = [[F(1) if i == k else F(0) for i in range(N)] for k in range(N)]
    for k in range(N):
        v = bracket(B, D, e[k])
        # our D is diagonal in the chosen basis
        d = None
        for i, t in enumerate(v):
            if t != 0:
                if i != k:
                    raise RuntimeError("D not diagonal on basis vector %d" % k)
                d = t
        if d is None:
            d = F(0)
        comps.setdefault(int(d), []).append(e[k])
    return comps


def sdim(vs):
    """superdimension of a span given as list of basis vectors: only valid
    when the basis is parity-homogeneous (ours are)."""
    b = span([list(v) for v in vs])
    ev = od = 0
    for v in b:
        ps = {PAR[i] for i, t in enumerate(v) if t != 0}
        if ps == {0}:
            ev += 1
        elif ps == {1}:
            od += 1
        else:
            raise RuntimeError("non-homogeneous basis vector")
    return (ev, od)


def graded_pieces(u, comps):
    """intersect the span u with each graded component."""
    out = {}
    ub = span([list(x) for x in u])
    for d, cb in comps.items():
        # intersection of two subspaces: kernel trick
        inter = []
        # solve  sum a_i u_i = sum b_j c_j
        cols = len(ub) + len(cb)
        rows = []
        for k in range(N):
            rows.append([ub[i][k] for i in range(len(ub))] +
                        [-cb[j][k] for j in range(len(cb))])
        for sol in kernel(rows, cols):
            v = zero(N)
            for i in range(len(ub)):
                if sol[i]:
                    v = [x + sol[i] * y for x, y in zip(v, ub[i])]
            if any(v):
                inter.append(v)
        out[d] = span(inter)
    return out


def maximal_graded(B, u, comps, trials=60, verbose=False):
    """test: for every homogeneous x outside u, does <u,x> = g?
    tested on all basis vectors of each component and on random combinations."""
    ub = span([list(x) for x in u])
    if len(ub) == N:
        return None
    for d, cb in comps.items():
        tests = [list(v) for v in cb]
        for _ in range(trials):
            v = zero(N)
            for b in cb:
                cf = F(random.randint(-4, 4))
                v = [x + cf * y for x, y in zip(v, b)]
            if any(v):
                tests.append(v)
        for x in tests:
            if inspan(x, ub):
                continue
            gen = subalg_generated(B, ub + [x])
            if len(gen) != N:
                if verbose:
                    print("      NOT maximal: adding a deg-%d element gives "
                          "sdim %s" % (d, sdim(gen)))
                return (d, x, gen)
    return True
