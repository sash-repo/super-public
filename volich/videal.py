"""The T-ideal of multilinear identities of Volichenko algebras.

Works formally in M_n, the multilinear part of the free nonassociative algebra
on x_1,...,x_n (basis: binary trees with leaves labelled bijectively), and maps
it to the free Lie superalgebra by volid.evaluate.

    I_n  = ker(M_n -> free Volichenko algebra)   = the identities of degree n
    C_n  = the degree-n part of the T-ideal generated by I_2,...,I_{n-1}
           (substitutions of monomials into the variables, and multiplication
            by a monomial on either side)
    I_n / C_n = the NEW identities of degree n.

An identity is called new when it does not follow from the ones of lower degree.
"""

import itertools
import sys
from fractions import Fraction as Fr

import volid
from volid import Space, bracketings, evaluate, tree_str


# ------------------------------------------------- formal elements of M_n ---

def mzero():
    return {}


def madd(*fs):
    out = {}
    for f in fs:
        for t, c in f.items():
            out[t] = out.get(t, 0) + c
    return {t: c for t, c in out.items() if c}


def msmul(c, f):
    return {t: c * d for t, d in f.items()} if c else {}


def mmul(f, g):
    """The product of M: (f g), tree-wise."""
    out = {}
    for tf, cf in f.items():
        for tg, cg in g.items():
            k = (tf, tg)
            out[k] = out.get(k, 0) + cf * cg
    return {t: c for t, c in out.items() if c}


def mcomm(f, g):
    return madd(mmul(f, g), msmul(-1, mmul(g, f)))


def mcirc(f, g):
    return madd(mmul(f, g), mmul(g, f))


def mjac(f, g, h):
    """J(a,b,c) = a(bc) + c(ab) + b(ca)."""
    return madd(mmul(f, mmul(g, h)), mmul(h, mmul(f, g)), mmul(g, mmul(h, f)))


def mjbar(f, g, h):
    """j(a,b,c) = [a, b o c] + [b, c o a] + [c, a o b]."""
    return madd(mcomm(f, mcirc(g, h)), mcomm(g, mcirc(h, f)),
                mcomm(h, mcirc(f, g)))


def var(i):
    return {i: Fr(1)}


def leaves(t):
    if isinstance(t, int):
        return (t,)
    return leaves(t[0]) + leaves(t[1])


def relabel_tree(t, sub):
    """sub: dict  leaf -> tree  (or leaf -> int)."""
    if isinstance(t, int):
        return sub[t]
    return (relabel_tree(t[0], sub), relabel_tree(t[1], sub))


def msubst(f, sub):
    out = {}
    for t, c in f.items():
        k = relabel_tree(t, sub)
        out[k] = out.get(k, 0) + c
    return {t: c for t, c in out.items() if c}


def mevaluate(f):
    """M_n -> free Lie superalgebra."""
    out = {}
    for t, c in f.items():
        for k, v in evaluate(t).items():
            out[k] = out.get(k, 0) + c * v
    return {k: v for k, v in out.items() if v}


# ------------------------------------------------------ linear algebra on M_n ---

class MSpace:
    """Vectors in M_n written on the tree basis."""

    def __init__(self, n):
        self.n = n
        self.trees = bracketings(tuple(range(1, n + 1)))
        self.pos = {t: i for i, t in enumerate(self.trees)}

    def vec(self, f):
        r = [Fr(0)] * len(self.trees)
        for t, c in f.items():
            r[self.pos[t]] += Fr(c)
        return r

    def rank(self, fs):
        from exactlin import rank as ex_rank
        rows = [self.vec(f) for f in fs]
        rows = [r for r in rows if any(r)]
        return ex_rank(rows) if rows else 0


# ---------------------------------------------------------- the identities ---

def identities(n, ms=None):
    """A basis of I_n, as formal elements of M_n."""
    from exactlin import nullspace as ex_null
    ms = ms or MSpace(n)
    vals = [evaluate(t) for t in ms.trees]
    sp = Space(vals)
    rows = sp.rows()                     # one row per tree
    mat = [[rows[j][i] for j in range(len(rows))] for i in range(len(sp.keys))]
    ker = ex_null(mat)                   # combinations of trees that vanish
    out = []
    for v in ker:
        f = {t: c for t, c in zip(ms.trees, v) if c}
        if f:
            out.append(f)
    return out


def consequences(lower, n):
    """Degree-n consequences of the identities `lower` = {k: [I_k basis]}.

    A consequence is: substitute monomials for the variables of an identity of
    degree k (partitioning a subset S of the n letters into k nonempty blocks),
    then plug the result into an arbitrary monomial context built on the
    remaining letters.  That covers substitution and both-sided multiplication,
    iterated -- the T-ideal.
    """
    idx = tuple(range(1, n + 1))
    for k, basis in sorted(lower.items()):
        if not basis:
            continue
        for m in range(k, n + 1):
            for S in itertools.combinations(idx, m):
                rest = tuple(x for x in idx if x not in S)
                ctxs = [None] if not rest else bracketings((0,) + rest)
                for blocks in set_partitions_ordered(S, k):
                    subs = [bracketings(b) for b in blocks]
                    for choice in itertools.product(*subs):
                        sub = {i + 1: choice[i] for i in range(k)}
                        for f in basis:
                            fs = msubst(f, sub)
                            if not rest:
                                yield fs
                                continue
                            for ctx in ctxs:
                                g = {}
                                for t, c in fs.items():
                                    rl = {0: t}
                                    rl.update({r: r for r in rest})
                                    kk = relabel_tree(ctx, rl)
                                    g[kk] = g.get(kk, 0) + c
                                yield g


def set_partitions_ordered(S, k):
    """All ordered partitions of the tuple S into k nonempty blocks."""
    S = tuple(S)
    if k == 1:
        yield (S,)
        return
    n = len(S)
    for size in range(1, n - k + 2):
        for first in itertools.combinations(S, size):
            rest = tuple(x for x in S if x not in first)
            for tail in set_partitions_ordered(rest, k - 1):
                yield (first,) + tail
