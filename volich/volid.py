"""Multilinear identities of Volichenko algebras -- exact rational arithmetic.

The free Volichenko algebra on x_1,...,x_n is the subalgebra generated by
    x_i = a_i + b_i        (a_i even, b_i odd)
of the free Lie superalgebra F on a_1,...,a_n, b_1,...,b_n.  Universality:
given any inhomogeneous subalgebra h of a Lie superalgebra g and h_1..h_n in h,
the assignment a_i -> (h_i)_ev, b_i -> (h_i)_od extends to a homomorphism
F -> g carrying x_i to h_i.  Hence the multilinear identities of THE CLASS of
Volichenko algebras are exactly the kernel of

    Phi_n : M_n  ---->  F,        M_n = multilinear part of the free
                                        nonassociative algebra, dim n! C_{n-1}

We compute inside the free ASSOCIATIVE superalgebra (the tensor algebra), in
which F embeds: its multilinear component in the letters chosen is spanned by
words.  A word is a tuple of letters, a letter being a pair (i, e) with i the
index of the generator x_i and e in {0,1} the parity of the letter picked from
x_i = a_i + b_i.  The product of the tensor algebra is concatenation; the
superbracket is [u,v] = uv - (-1)^{p(u)p(v)} vu with p(w) = sum of parities.

Products used below, in the notation of Volichenko's "Theorem" V:
    ab          the Volichenko product  (= the superbracket of the ambient)
    [a,b]       = ab - ba               (the commutator)
    a o b       = ab + ba               (Jordan element)
    J(a,b,c)    = a(bc) + c(ab) + b(ca) (Jacobi element)
"""

import itertools
import sys
from fractions import Fraction as Fr
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from exactlin import rank as ex_rank, rref as ex_rref, nullspace as ex_null  # noqa: E402


# ---------------------------------------------------------------- algebra ---

def par(word):
    """Parity of a word of the free associative superalgebra."""
    return sum(e for _, e in word) & 1


def add(*elts):
    out = {}
    for u in elts:
        for w, c in u.items():
            out[w] = out.get(w, 0) + c
    return {w: c for w, c in out.items() if c}


def smul(c, u):
    return {w: c * cu for w, cu in u.items()} if c else {}


def mul(u, v):
    """The Volichenko product: the superbracket [u,v] of the ambient."""
    out = {}
    for wu, cu in u.items():
        su = par(wu)
        for wv, cv in v.items():
            sv = par(wv)
            sign = -1 if (su & sv) else 1
            k = wu + wv
            out[k] = out.get(k, 0) + cu * cv
            k = wv + wu
            out[k] = out.get(k, 0) - sign * cu * cv
    return {w: c for w, c in out.items() if c}


def comm(u, v):
    return add(mul(u, v), smul(-1, mul(v, u)))


def circ(u, v):
    return add(mul(u, v), mul(v, u))


def jac(u, v, w):
    """Volichenko's Jacobi element J(a,b,c) = a(bc) + c(ab) + b(ca)."""
    return add(mul(u, mul(v, w)), mul(w, mul(u, v)), mul(v, mul(w, u)))


def jbar(u, v, w):
    """Baranov's j(a,b,c) = [a, b o c] + [b, c o a] + [c, a o b]."""
    return add(comm(u, circ(v, w)), comm(v, circ(w, u)), comm(w, circ(u, v)))


def gen(i):
    """x_i = a_i + b_i."""
    return {((i, 0),): Fr(1), ((i, 1),): Fr(1)}


def even_part(u):
    return {w: c for w, c in u.items() if par(w) == 0}


def odd_part(u):
    return {w: c for w, c in u.items() if par(w) == 1}


# --------------------------------------------------------------- monomials ---

def bracketings(idx):
    """All multilinear bracket monomials on the index tuple idx, as trees.

    A tree is either an int (a leaf) or a pair (L, R).  Their number is
    len(idx)! * Catalan(len(idx)-1) when idx runs over all orders -- here idx
    is a SET, and we produce every tree whose leaf set is idx.
    """
    idx = tuple(idx)
    if len(idx) == 1:
        return [idx[0]]
    out = []
    s = set(idx)
    for k in range(1, len(idx)):
        for a in itertools.combinations(idx, k):
            b = tuple(sorted(s - set(a)))
            for ta in bracketings(a):
                for tb in bracketings(b):
                    out.append((ta, tb))
                    out.append((tb, ta))
    # (ta,tb) and (tb,ta) are both produced, and every unordered split is met
    # once for each k, so each ordered tree is produced exactly twice; halve.
    seen, uniq = set(), []
    for t in out:
        if t not in seen:
            seen.add(t)
            uniq.append(t)
    return uniq


def evaluate(tree):
    if isinstance(tree, int):
        return gen(tree)
    return mul(evaluate(tree[0]), evaluate(tree[1]))


def tree_str(t):
    if isinstance(t, int):
        return "x%d" % t
    return "(%s%s)" % (tree_str(t[0]), tree_str(t[1]))


# ------------------------------------------------------------ linear algebra ---

class Space:
    """A subspace of the multilinear component, given by spanning vectors."""

    def __init__(self, elts):
        self.elts = [e for e in elts if e]
        keys = set()
        for e in self.elts:
            keys.update(e)
        self.keys = sorted(keys)
        self.pos = {k: i for i, k in enumerate(self.keys)}

    def rows(self, elts=None):
        elts = self.elts if elts is None else elts
        n = len(self.keys)
        out = []
        for e in elts:
            r = [Fr(0)] * n
            for k, c in e.items():
                if k not in self.pos:          # outside the ambient we indexed
                    return None
                r[self.pos[k]] = Fr(c)
            out.append(r)
        return out

    def dim(self):
        r = self.rows()
        return ex_rank(r) if r else 0


def span_dim(elts):
    return Space(elts).dim()


def dim_sum(a, b):
    """dim of the span of a+b, both lists of elements."""
    return span_dim(list(a) + list(b))


def in_span(elts, target):
    """Is target in the span of elts?"""
    if not target:
        return True
    d0 = span_dim(elts)
    return span_dim(list(elts) + [target]) == d0


# --------------------------------------------------------------- the report ---

def catalan(n):
    c = 1
    for i in range(n):
        c = c * 2 * (2 * i + 1) // (i + 2)
    return c


def report_degree(n, verbose=True):
    idx = tuple(range(1, n + 1))
    trees = bracketings(idx)
    vals = [evaluate(t) for t in trees]
    exp = 1
    for i in range(1, n + 1):
        exp *= i
    exp *= catalan(n - 1)
    assert len(trees) == exp, (len(trees), exp)

    sp = Space(vals)
    rows = sp.rows()
    dW = ex_rank(rows)
    dM = len(trees)
    if verbose:
        print("degree %d:  dim M_n = %d (n! C_{n-1}),  dim W_n = %d,"
              "  dim I_n = %d" % (n, dM, dW, dM - dW))
    return trees, vals, sp, dW


def even_expressions(trees, vals, sp):
    """Basis of {m in M_n : Phi(m) is even}, as coefficient vectors on trees."""
    # kernel of  m |-> odd part of Phi(m)
    okeys = [k for k in sp.keys if par(k) == 1]
    pos = {k: i for i, k in enumerate(okeys)}
    rows = []
    for e in vals:
        r = [Fr(0)] * len(okeys)
        for k, c in e.items():
            if par(k) == 1:
                r[pos[k]] = Fr(c)
        rows.append(r)
    # nullspace of the transpose: combinations of vals with zero odd part
    mat = [[rows[j][i] for j in range(len(rows))] for i in range(len(okeys))]
    if not mat:
        return [[Fr(1) if i == j else Fr(0) for j in range(len(vals))]
                for i in range(len(vals))]
    return ex_null(mat)


def combine(vals, coeffs):
    out = {}
    for c, e in zip(coeffs, vals):
        if c:
            for k, v in e.items():
                out[k] = out.get(k, 0) + c * v
    return {k: v for k, v in out.items() if v}


