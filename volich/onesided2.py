"""Statement 4.15 of the text: Proposition 2.13 -- "simple
epimorphic Volichenko algebras from Tables 2.12.1 and 2.12.2 have no one-sided
ideals" -- for the SERIES of Table 2.12.1.

Subsec. 4.13 proves it for the two intriguing examples and the three
exceptional ones; onesided.py machine-checks those three.  What was left open
are the series of Table 2.12.1,
    sl(m|n), psl(n|n), osp(2m|2n), osp(2m+1|2n), spe(n), psq(n),
and the whole of Table 2.12.2 (vectorial, infinite-dimensional).  This file
does the finite-dimensional series sl(m|n), psl(n|n) and psq(n) for small
parameters, by the argument of onesided.py:

A left ideal containing v contains A.v, where A is the unital associative
subalgebra of End(h) generated by the left multiplications L_g of the product
    g.h = [g,h] + S(g,h),   S(g,h) = [[g,x],[h,x]] .
If A = End(h), then, by Burnside, h is an irreducible A-module, so A.v = h for
every v /= 0 and there is no proper left ideal; same on the right.

The closure is walked mod p = 2^61-1.  That costs no rigour in the direction
needed: reduction mod p can only LOWER the rank, so rank_p = dim End(h) forces
rank_Q = dim End(h).

The homologic elements x are the ones the Table prescribes; that [x,x] = 0 and
that x ensures nontriviality are asserted, not assumed, for every case run.
"""

