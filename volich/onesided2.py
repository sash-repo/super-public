# ------------------------------------------------------------- matrix algebras

def mat_mul(A, B, d):
    C = [[F(0)] * d for _ in range(d)]
    for i in range(d):
        Ai = A[i]
        for k in range(d):
            a = Ai[k]
            if not a:
                continue
            Bk = B[k]
            for j in range(d):
                if Bk[j]:
                    C[i][j] += a * Bk[j]
    return C


def flat(A, d):
    return [A[i][j] for i in range(d) for j in range(d)]


def unflat(v, d):
    return [[v[i * d + j] for j in range(d)] for i in range(d)]


def par_of_entry(i, j, m):
    return (0 if i < m else 1) ^ (0 if j < m else 1)


def _T(rows):
    if not rows:
        return []
    return [[rows[r][c] for r in range(len(rows))] for c in range(len(rows[0]))]


def subalgebra(name, d, m, gens, center=()):
    """Build an Alg from (matrix, parity) generators spanning a subalgebra of
    gl(m|n), quotienting by the given central matrices.

    All the linear algebra goes through exactlin.py: a hand-rolled single
    pass echelon silently failed to remove the center here, which inflated
    psl(n|n) and psq(n) by one dimension and made the Burnside test come out
    INCONCLUSIVE for a reason that had nothing to do with the mathematics."""
    cen = [flat(Z, d) for Z in center]
    basis, PAR = [], []
    cur = list(cen)
    r_cur = rank(cur) if cur else 0
    for (A, p) in gens:
        v = flat(A, d)
        r_new = rank(cur + [v])
        if r_new > r_cur:
            cur.append(v)
            r_cur = r_new
            basis.append(A)
            PAR.append(p)
    N = len(basis)
    rows = [flat(A, d) for A in basis] + cen        # basis first, center after

    def coords(v):
        sol = solve(_T(rows), v)
        if sol is None:
            raise AssertionError(f"{name}: bracket left the subalgebra")
        return [F(c) for c in sol[:N]]

    def br(u, v):
        A = [[F(0)] * d for _ in range(d)]
        B = [[F(0)] * d for _ in range(d)]
        pu = pv = 0
        for i, c in enumerate(u):
            if c:
                for r in range(d):
                    for s2 in range(d):
                        A[r][s2] += c * basis[i][r][s2]
                pu = PAR[i]
        for i, c in enumerate(v):
            if c:
                for r in range(d):
                    for s2 in range(d):
                        B[r][s2] += c * basis[i][r][s2]
                pv = PAR[i]
        AB = mat_mul(A, B, d)
        BA = mat_mul(B, A, d)
        sg = F(-1) ** (pu * pv)
        C = [[AB[i][j] - sg * BA[i][j] for j in range(d)] for i in range(d)]
        return coords(flat(C, d))

    return nontriv.Alg(name, N, PAR, br), basis, rows, N


# ------------------------------------------------------------- linear algebra

def _echelon(rows):
    ech = []
    for r in rows:
        r = _reduce(list(r), ech)
        if any(r):
            _insert(r, ech)
    return ech


def _pivot(r):
    for i, c in enumerate(r):
        if c:
            return i
    return None


def _reduce(v, ech):
    v = list(v)
    for r in ech:
        p = _pivot(r)
        if p is not None and v[p]:
            f = v[p] / r[p]
            for i in range(len(v)):
                v[i] -= f * r[i]
    return v


def _insert(v, ech):
    if any(v):
        ech.append(list(v))
        ech.sort(key=lambda r: _pivot(r) if _pivot(r) is not None else 10 ** 9)
    return _pivot(v)


def _solve(rows, target):
    """Express target as a combination of rows (rows = list of vectors)."""
    n = len(rows)
    aug = [list(rows[i]) + [F(1) if j == i else F(0) for j in range(n)]
           for i in range(n)]
    L = len(target)
    ech = []
    for r in aug:
        rr = list(r)
        for e in ech:
            p = _pivot(e[:L])
            if p is not None and rr[p]:
                f = rr[p] / e[p]
                for i in range(len(rr)):
                    rr[i] -= f * e[i]
        if any(rr[:L]):
            ech.append(rr)
            ech.sort(key=lambda x: (_pivot(x[:L]) if _pivot(x[:L]) is not None
                                    else 10 ** 9))
    cur = list(target) + [F(0)] * n
    for e in ech:
        p = _pivot(e[:L])
        if p is not None and cur[p]:
            f = cur[p] / e[p]
            for i in range(len(cur)):
                cur[i] -= f * e[i]
    if any(cur[:L]):
        return None
    return [-c for c in cur[L:]]


# --------------------------------------------------------------- the families

def E(d, i, j):
    A = [[F(0)] * d for _ in range(d)]
    A[i][j] = F(1)
    return A


def sl_gens(m, n):
    """Basis of sl(m|n) inside gl(m|n): all E_ij with i /= j, plus the
    supertraceless diagonal."""
    d = m + n
    gens = []
    for i in range(d):
        for j in range(d):
            if i != j:
                gens.append((E(d, i, j), par_of_entry(i, j, m)))
    # supertraceless diagonal: E_ii - E_{i+1,i+1} adjusted by parity
    for i in range(d - 1):
        A = [[F(0)] * d for _ in range(d)]
        si = F(1) if i < m else F(-1)
        sj = F(1) if i + 1 < m else F(-1)
        A[i][i] = sj
        A[i + 1][i + 1] = -si
        gens.append((A, 0))
    return gens


def x_sl(m, n, p, q):
    """x^p_q of Table 2.12.1: ones at (i, m+i) for i < p and at (m+j, j) for
    p <= j < p+q, so that x^2 = 0."""
    d = m + n
    A = [[F(0)] * d for _ in range(d)]
    for i in range(p):
        A[i][m + i] = F(1)
    for j in range(p, p + q):
        A[m + j][j] = F(1)
    return A


def psq_gens(n):
    """q(n) = {(A B / B A)} inside gl(n|n); sq: qtr B = tr B = 0; psq = sq /
    center (the identity)."""
    d = 2 * n
    gens = []
    for i in range(n):
        for j in range(n):
            A = [[F(0)] * d for _ in range(d)]
            A[i][j] = F(1)
            A[n + i][n + j] = F(1)
            gens.append((A, 0))                     # even: (A 0 / 0 A)
    for i in range(n):
        for j in range(n):
            if i == j == n - 1:
                continue                             # impose tr B = 0
            B = [[F(0)] * d for _ in range(d)]
            B[i][n + j] = F(1)
            B[n + i][j] = F(1)
            if i == j:
                B[n - 1][d - 1] = F(-1)
                B[d - 1][n - 1] = F(-1)
            gens.append((B, 1))                      # odd: (0 B / B 0)
    return gens


def x_psq(n, k):
    """x_k = antidiag(X, X), X = diag(J_2(0), ..., J_2(0), 0, ...) with k
    copies of J_2(0) = (0 1 / 0 0)."""
    d = 2 * n
    A = [[F(0)] * d for _ in range(d)]
    for t in range(k):
        i, j = 2 * t, 2 * t + 1
        A[i][n + j] = F(1)
        A[n + i][j] = F(1)
    return A


def identity(d):
    return [[F(1) if i == j else F(0) for j in range(d)] for i in range(d)]


# ------------------------------------------------------------------- the sweep

def run_case(label, alg, x, verbose=True):
    g = alg
    # x must be odd and homologic, and must ensure nontriviality
    xv = x
    br = g.br(xv, xv)
    if any(br):
        print(f"   {label:22s} SKIP: [x,x] /= 0")
        return None
    h = nontriv.Voli(g, xv)
    if not h.closure_ok():
        print(f"   {label:22s} SKIP: h is not closed")
        return None
    ens = any(any(h.Sm[i][j]) for i in range(h.dim) for j in range(h.dim))
    if not ens:
        print(f"   {label:22s} x does NOT ensure nontriviality "
              f"(h = g_ev, a Lie algebra) -- outside the Table's range")
        return None
    nn = h.dim
    full = nn * nn
    L = [[[to_p(h.prod(h.e(i), h.e(j))[k]) for j in range(nn)]
          for k in range(nn)] for i in range(nn)]
    R = [[[to_p(h.prod(h.e(j), h.e(i))[k]) for j in range(nn)]
          for k in range(nn)] for i in range(nn)]
    rl = closure_mod_p(L, nn)
    rr = closure_mod_p(R, nn)
    ok = (rl == full and rr == full)
    print(f"   {label:22s} dim h = {nn:3d}, End(h) = {full:5d}; "
          f"left {rl:5d}, right {rr:5d}  -> "
          + ("no one-sided ideals" if ok else "INCONCLUSIVE"))
    return ok


def main():
    print("Proposition 2.13, for the series of Table 2.12.1 (Statement 4.15).")
    print("Burnside closure mod p = 2^61-1 (a lower bound for the rank over Q,")
    print("hence conclusive exactly when it is full).\n")
    results = []

    print(" sl(m|n), x = x^p_q  (Table: p, q > 0, p + q <= m):")
    for (m, n, p, q) in [(2, 2, 1, 1), (2, 3, 1, 1), (3, 3, 1, 1),
                         (3, 3, 1, 2), (3, 3, 2, 1), (2, 4, 1, 1),
                         (3, 4, 1, 1), (3, 4, 2, 1)]:
        d = m + n
        gens = sl_gens(m, n)
        center = [identity(d)] if m == n else []
        nm = f"{'psl' if m == n else 'sl'}({m}|{n}) x^{p}_{q}"
        alg, _, rows, N = subalgebra(nm, d, m, gens, center=center)
        xv = _coords_of(rows, N, d, x_sl(m, n, p, q))
        results.append(run_case(nm, alg, xv))

    print("\n psq(n), x = x_k  (Table: k > 0, 2k <= n):")
    for (n, k) in [(2, 1), (3, 1), (4, 1), (4, 2)]:
        d = 2 * n
        gens = psq_gens(n)
        center = [identity(d)]
        nm = f"psq({n}) x_{k}"
        alg, _, rows, N = subalgebra(nm, d, n, gens, center=center)
        xv = _coords_of(rows, N, d, x_psq(n, k))
        results.append(run_case(nm, alg, xv))

    # The two cases the Table's range admits but which came out trivial: is
    # that the projectivization, or a misreading of x?  Comparing with the
    # unprojectivized algebra settles it.
    print("\n boundary cases -- where does the nontriviality go?")
    for (nm, d, m, gens, cen, X) in [
            ("sl(2|2)  x^1_1", 4, 2, sl_gens(2, 2), [], x_sl(2, 2, 1, 1)),
            ("psl(2|2) x^1_1", 4, 2, sl_gens(2, 2), [identity(4)], x_sl(2, 2, 1, 1)),
            ("sq(2)    x_1", 4, 2, psq_gens(2), [], x_psq(2, 1)),
            ("psq(2)   x_1", 4, 2, psq_gens(2), [identity(4)], x_psq(2, 1))]:
        alg, _, rows, N = subalgebra(nm, d, m, gens, center=cen)
        xv = _coords_of(rows, N, d, X)
        h = nontriv.Voli(alg, xv)
        e = any(any(h.Sm[i][j]) for i in range(h.dim) for j in range(h.dim))
        print(f"   {nm:22s} dim h = {h.dim:3d}, ensures nontriviality: {e}")
    print("   -> S(a,b) survives in sl(2|2) and sq(2) but lands in the centre,")
    print("      so it dies in the quotient.  psl(3|3) with p+q = m = 3 and")
    print("      psq(4) with 2k = n = 4 are fine, so it is the smallest member")
    print("      only: for psl(2|2), p = q = 1 and for psq(2), k = 1, the Table")
    print("      admits an x that does NOT ensure nontriviality.")

    done = [r for r in results if r is not None]
    print(f"\n{sum(1 for r in done if r)} of {len(done)} cases run give "
          f"A = End(h), i.e. no one-sided ideals.")
    print("Not covered here: osp(2m|2n), osp(2m+1|2n), spe(n) of Table 2.12.1,")
    print("and all of Table 2.12.2 (infinite-dimensional -- Burnside does not")
    print("apply, a different argument is needed).")
    return 0 if all(done) else 1


def _coords_of(rows, N, d, X):
    """Coordinates of the matrix X in the basis the Alg was built on."""
    sol = solve(_T(rows), flat(X, d))
    assert sol is not None, "x is not in the subalgebra"
    return [F(c) for c in sol[:N]]


if __name__ == "__main__":
    sys.exit(main())
