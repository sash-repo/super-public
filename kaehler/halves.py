r"""The two halves of the condition d omega = 0 (Lemma 1.10.1, Example 1.10.2).

On a symplectic manifold M^{2n} the space of 3-forms splits under the Lefschetz
sl(2) generated by  X^+ = omega wedge -,  X^- = convolution with omega^{-1}:

    Omega^3 = P^3 + omega wedge Omega^1,   P^3 = ker X^-.

This module asks what that splitting becomes
  1) on C^{2n|2m} with an even omega,
  2) on C^{n|n} with an odd omega, where X^+- are themselves odd.

Everything is exact over Q.  On C^{a|b} the differentials hat y_a = dz_a have
parity p_a + 1, so Omega^k is finite-dimensional for each k.
Calibration: on C^{2n|0}, dim Omega^3 = C(2n,3), dim omega Omega^1 = 2n,
dim P^3 = C(2n,3) - 2n, and [X^-, X^+] = (n-k) id on Omega^k.

Run (from this folder):  ../venv/bin/python halves.py
"""

import os, sys; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
