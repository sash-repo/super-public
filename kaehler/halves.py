# ---------------------------------------------------------------- algebra ---
class Forms:
    r"""The supercommutative algebra of differential forms on C^{a|b}.

    par[i] = parity of the generator \hat y_i = dz_i, i.e., p(z_i) + 1.
    A monomial is a tuple of generator indices in non-decreasing order; an odd
    generator occurs at most once.
    """

    def __init__(self, coord_parities):
        self.p = list(coord_parities)
        self.N = len(self.p)
        self.par = [(q + 1) % 2 for q in self.p]      # parity of \hat y_i

    # -- basis of \Omega^k ---------------------------------------------
    def monomials(self, k):
        odd = [i for i in range(self.N) if self.par[i] == 1]
        even = [i for i in range(self.N) if self.par[i] == 0]
        out = []
        for r in range(min(k, len(odd)) + 1):
            for sub in combinations(odd, r):
                for tail in self._weak(even, k - r):
                    out.append(tuple(sorted(sub + tail)))
        return sorted(set(out))

    def _weak(self, gens, deg):
        """all multisets of `gens` of size deg, as sorted tuples"""
        if deg == 0:
            return [()]
        if not gens:
            return []
        res = []
        for j, g in enumerate(gens):
            for tail in self._weak(gens[j:], deg - 1):
                res.append((g,) + tail)
        return res

    # -- left multiplication by one generator --------------------------
    def lmul_gen(self, g, mon, coeff):
        r"""coeff * \hat y_g * mon, returned as a dict"""
        if self.par[g] == 1 and g in mon:
            return {}
        sign = 1
        pos = 0
        for h in mon:                     # move \hat y_g into sorted place
            if h < g or (h == g and self.par[g] == 0):
                if self.par[g] == 1 and self.par[h] == 1:
                    sign = -sign
                pos += 1
            else:
                break
        new = mon[:pos] + (g,) + mon[pos:]
        return {new: coeff * sign}

    def lmul(self, elt, mon, coeff):
        """elt (a dict) times the monomial mon"""
        out = {}
        for m2, c2 in elt.items():
            cur = {mon: coeff * c2}
            for g in reversed(m2):        # multiply generator by generator
                nxt = {}
                for m, c in cur.items():
                    for mm, cc in self.lmul_gen(g, m, c).items():
                        nxt[mm] = nxt.get(mm, 0) + cc
                cur = {m: c for m, c in nxt.items() if c}
            for m, c in cur.items():
                out[m] = out.get(m, 0) + c
        return {m: c for m, c in out.items() if c}

    # -- the super derivation \partial_{\hat y_g} ----------------------
    def der_gen(self, g, mon, coeff):
        out = {}
        for j, h in enumerate(mon):
            if h != g:
                continue
            # Koszul sign: \partial_g passes mon[0..j-1]
            sgn = 1
            if self.par[g] == 1:
                for h2 in mon[:j]:
                    if self.par[h2] == 1:
                        sgn = -sgn
            new = mon[:j] + mon[j + 1:]
            out[new] = out.get(new, 0) + coeff * sgn
            if self.par[g] == 0:
                # a commuting generator: all its occurrences give the same
                # monomial, and the loop already counts each of them
                pass
        return {m: c for m, c in out.items() if c}


# ------------------------------------------------------- the two operators ---
def structures(kind, n, m=0):
    r"""Return (Forms, omega, Xminus-pairs, label).

    omega is a dict {monomial: coeff}; Xminus is given as a list of
    (coeff, a, b) meaning coeff * \partial_a \partial_b.
    """
    if kind == "even":
        # C^{2n|2m}: q_1..q_n, p_1..p_n even;  \xi_1..\xi_m, \eta_1..\eta_m odd
        par = [0] * (2 * n) + [1] * (2 * m)
        F = Forms(par)
        om, xm = {}, []
        for i in range(n):                       # antisymmetric on the even part
            om[(i, n + i)] = Fraction(1)
            xm.append((Fraction(1), n + i, i))
        for j in range(m):                       # symmetric on the odd part
            a, b = 2 * n + j, 2 * n + m + j
            om[(a, b)] = Fraction(1)
            # the SUPER inverse of omega carries a minus on the odd part; this
            # is exactly what makes [X^-, X^+] scalar on each Omega^k, namely
            # (n - m - k)*id -- the calibration the code verifies below
            xm.append((Fraction(-1), b, a))
        return F, om, xm, "C^{%d|%d}, omega even" % (2 * n, 2 * m)
    if kind == "odd":
        # C^{n|n}: q_1..q_n even, \xi_1..\xi_n odd; omega = sum dq_i d\xi_i
        par = [0] * n + [1] * n
        F = Forms(par)
        om, xm = {}, []
        for i in range(n):
            om[(i, n + i)] = Fraction(1)
            xm.append((Fraction(1), n + i, i))
        return F, om, xm, "C^{%d|%d}, omega odd" % (n, n)
    raise ValueError(kind)


def matrix_Xplus(F, om, src, dst):
    r"""matrix of X^+ : \Omega^k -> \Omega^{k+2} in the monomial bases"""
    idx = {mon: j for j, mon in enumerate(dst)}
    rows = [[Fraction(0)] * len(src) for _ in dst]
    for c, mon in enumerate(src):
        for mm, cc in F.lmul(om, mon, Fraction(1)).items():
            rows[idx[mm]][c] += cc
    return rows


def matrix_Xminus(F, xm, src, dst):
    r"""matrix of X^- : \Omega^k -> \Omega^{k-2}"""
    idx = {mon: j for j, mon in enumerate(dst)}
    rows = [[Fraction(0)] * len(src) for _ in dst]
    for c, mon in enumerate(src):
        for coeff, a, b in xm:
            cur = F.der_gen(b, mon, coeff)
            for m1, c1 in cur.items():
                for m2, c2 in F.der_gen(a, m1, c1).items():
                    rows[idx[m2]][c] += c2
    return rows


def zero(rows, cols):
    return [[Fraction(0)] * cols for _ in range(rows)]


def mat_mul(A, B, rows, cols):
    """A*B, with the result shape given explicitly (either factor may be empty)"""
    if not A or not B or not A[0] or not B[0]:
        return zero(rows, cols)
    inner = len(B)
    return [[sum(A[i][k] * B[k][j] for k in range(inner))
             for j in range(len(B[0]))] for i in range(len(A))]


def is_scalar(A):
    """if A = c*Id return c, else None"""
    if not A or len(A) != len(A[0]):
        return None
    c = A[0][0]
    for i in range(len(A)):
        for j in range(len(A)):
            if A[i][j] != (c if i == j else 0):
                return None
    return c


# ------------------------------------------------------------------ report ---
def analyse(kind, n, m=0, kmax=4):
    F, om, xm, label = structures(kind, n, m)
    print("=" * 72)
    print(label)
    Om = {k: F.monomials(k) for k in range(kmax + 3)}
    print("  dim Omega^k, k = 0..%d :" % kmax,
          [len(Om[k]) for k in range(kmax + 1)])

    # the "H" of the Lefschetz triple, on each \Omega^k
    print("  [X^-,X^+] (even omega) resp. {X^-,X^+} (odd omega) on Omega^k:")
    for k in range(kmax + 1):
        d = len(Om[k])
        Xp = matrix_Xplus(F, om, Om[k], Om[k + 2])
        Xm_up = matrix_Xminus(F, xm, Om[k + 2], Om[k])
        A = mat_mul(Xm_up, Xp, d, d)
        if k >= 2:
            Xm_dn = matrix_Xminus(F, xm, Om[k], Om[k - 2])
            Xp_dn = matrix_Xplus(F, om, Om[k - 2], Om[k])
            B = mat_mul(Xp_dn, Xm_dn, d, d)
        else:
            B = zero(d, d)
        sgn = -1 if kind == "even" else 1          # commutator vs anticommutator
        C = [[A[i][j] + sgn * B[i][j] for j in range(d)] for i in range(d)]
        s = is_scalar(C)
        if s is not None:
            print("      k=%d: %s * Id" % (k, s))
        else:
            diag = sorted(set(C[i][i] for i in range(d)))
            offdiag = any(C[i][j] != 0 for i in range(d) for j in range(d)
                          if i != j)
            print("      k=%d: not scalar; diagonal values %s%s"
                  % (k, diag, "" if not offdiag else ", and not diagonal"))

    # the splitting of Omega^3
    print("  the splitting of Omega^3:")
    O1, O3 = Om[1], Om[3]
    Xp = matrix_Xplus(F, om, O1, O3)
    Xm = matrix_Xminus(F, xm, O3, O1)
    r_plus = rank(Xp) if Xp and Xp[0] else 0
    ker_dim = len(O3) - (rank(Xm) if Xm and Xm[0] else 0)
    both = mat_mul(Xm, Xp, len(O1), len(O1))
    r_both = rank(both) if both and both[0] else 0
    # dim (P^3 + X^+ Omega^1) = dim P^3 + dim X^+Omega^1 - dim intersection;
    # the intersection is X^+(ker(X^-X^+)) since X^+ is injective here
    inter = r_plus - r_both
    print("      dim Omega^1 = %d,  dim Omega^3 = %d" % (len(O1), len(O3)))
    print("      dim X^+Omega^1 = %d,  dim P^3 = ker X^- = %d" % (r_plus, ker_dim))
    print("      dim (P^3 cap X^+Omega^1) = %d" % inter)
    tot = r_plus + ker_dim - inter
    print("      dim (P^3 + X^+Omega^1) = %d   %s"
          % (tot, "= Omega^3, direct sum" if (tot == len(O3) and inter == 0)
             else ("= Omega^3, NOT direct" if tot == len(O3)
                   else "PROPER SUBSPACE of Omega^3")))
    return dict(O1=len(O1), O3=len(O3), im=r_plus, ker=ker_dim, inter=inter,
                tot=tot, label=label)


if __name__ == "__main__":
    print("### calibration: classical symplectic C^{2n|0}")
    for n in (2, 3, 4):
        analyse("even", n, 0)
    print()
    print("### even omega on a supermanifold C^{2n|2m}")
    #  n - m - 1 = 0  in the pairs (1,0), (2,1), (3,2) -- the degenerate ones
    for n, m in ((2, 1), (3, 2), (1, 1), (2, 2), (3, 1), (2, 3)):
        analyse("even", n, m, kmax=3)
    print()
    print("### odd omega on C^{n|n}")
    for n in (1, 2, 3, 4):
        analyse("odd", n)
