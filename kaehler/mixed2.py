def J_odd_signed(n, signs):
    """J odd with J(\\hat q_i) = s_i \\hat pi_i, J(\\hat pi_i) = s_i^{-1} \\hat q_i."""
    J = {}
    for i, s in enumerate(signs):
        J[i] = [(Fraction(s), n + i)]
        J[n + i] = [(Fraction(1, s), i)]
    return J


