def J_even_theta(n, a, b):
    """J even, J(\\hat q_1)=a \\hat q_2, J(\\hat q_2)=-a^{-1}\\hat q_1, same with b on pi."""
    assert n == 2
    return {0: [(Fraction(a), 1)], 1: [(Fraction(-1, 1) / Fraction(a), 0)],
            2: [(Fraction(b), 3)], 3: [(Fraction(-1, 1) / Fraction(b), 2)]}


