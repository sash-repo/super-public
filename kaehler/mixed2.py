r"""Theorem 1.9.3: the structure of the two 13-dimensional algebras.

In the mixed-parity case p(J) != p(h) the closure of {X^+, X^-, d} is
(3|5) = ba(2) (+) sl(1|1) (Lemma 1.9.1a), but d_c = J d J^{-1} does not lie in it:
the closure of {X^+, X^-, d, d_c} is

    (6|7)  for J odd, h even     (d_c is even here),
    (5|8)  for J even, h odd     (d_c is odd),

both of total dimension 13.  This script

 0) calibrates the same code on the case of both J and h even, where the answer is
    hei(0|4) (+) sl(2) of sdim (4|4);
 1) verifies that each J used is omega-compatible, so that h := omega(J^{-1}.,.)
    is a pseudo-Hermitian form of the parity opposite to p(J);
 2) identifies the two algebras: centre, derived series, lower central series,
    the nilpotent ideal and the quotient by it;
 3) sweeps a family of admissible J.

Run (from this folder):  ../venv/bin/python mixed2.py
"""
