# ------------------------------------------------------------------ 0. calibration
def calibrate():
    """the classical case p1 on C^2: closure{E,F,d,d_c} must be (4|4)."""
    M = Model([0, 0])
    d = d_operator(M)
    dc = dc_from_J(M, {0: [(Fraction(1), 1)], 1: [(Fraction(-1), 0)]})
    E = M.mul(M.gen('c', 0), M.gen('c', 1))
    F = M.mul(M.gen('b', 1), M.gen('b', 0))
    got = closure(M, [E, F, d, dc])[1]
    print('0) calibration, item p1 (both J and h even) on C^2:')
    print('   closure{E,F,d,d_c} = (%d|%d)  %s'
          % (got[0], got[1], 'OK = hei(0|4) (+) sl(2)' if got == (4, 4) else 'MISMATCH'))
    assert got == (4, 4), got
    return got


# ------------------------------------------------- 1. is J compatible with omega?
def J_on_avatar(M, n, J):
    """apply J to each differential in the avatar omega = sum \\hat q_i \\hat pi_i."""
    def image(a):
        return M.add(*[M.smul(co, M.gen('c', b)) for co, b in J[a]])
    return M.add(*[M.mul(image(i), image(n + i)) for i in range(n)])


def compatible(M, n, J):
    """J(omega) = kappa * omega for some scalar kappa; return kappa or None."""
    Xp = Xplus(M, n)
    im = J_on_avatar(M, n, J)
    if not im:
        return None
    # find the scalar
    key = next(iter(Xp))
    if key not in im:
        return None
    kappa = im[key] / Xp[key]
    diff = M.add(im, M.smul(-kappa, Xp))
    return kappa if not diff else None


# ---------------------------------------------------------- 2. structure of a g
def lower_central(M, basis):
    """the lower central series g > [g,g] > [g,[g,g]] > ... , as sdims."""
    base = reduce_basis(M, basis)
    cur = base
    out = [sd(M, cur)]
    while True:
        nxt = reduce_basis(M, [M.br(u, v) for u in base for v in cur])
        s = sd(M, nxt)
        if s == out[-1] or s == (0, 0):
            out.append(s)
            break
        out.append(s)
        cur = nxt
        if len(out) > 12:
            break
    return out


def derived_series(M, basis):
    cur = reduce_basis(M, basis)
    out = [sd(M, cur)]
    while True:
        nxt = reduce_basis(M, [M.br(u, v) for u in cur for v in cur])
        s = sd(M, nxt)
        out.append(s)
        if s == out[-2] or s == (0, 0):
            break
        cur = nxt
        if len(out) > 12:
            break
    return out


def nil_ideal(M, basis):
    """the largest ideal in the lower central series that is nilpotent: take the
    ideal generated by the nilpotent part of the lower central series' tail."""
    lcs = lower_central(M, basis)
    return lcs


def structure(M, basis, name):
    red = reduce_basis(M, basis)
    print('   %s: sdim (%d|%d), dim %d' % (name, sd(M, red)[0], sd(M, red)[1],
                                           sum(sd(M, red))))
    z = centre(M, red)
    print('     centre           (%d|%d)' % z)
    simple, _ = is_simple(M, red)
    print('     simple?          %s' % simple)
    dsr = derived_series(M, red)
    print('     derived series   %s' % ' > '.join('(%d|%d)' % s for s in dsr))
    lcs = lower_central(M, red)
    print('     lower central    %s' % ' > '.join('(%d|%d)' % s for s in lcs))
    # even part as a Lie algebra
    ev = [e for e in red if M.parity(e) == 0]
    ev_der = sd(M, [M.br(u, v) for u in ev for v in ev])
    print('     even part: dim %d, [g_ev,g_ev] dim %d' % (len(ev), sum(ev_der)))
    return red


def minimal_ideals(M, red):
    """the ideal generated by each basis vector; report the smallest proper ones."""
    total = sd(M, red)
    seen = {}
    for u in red:
        s = ideal(M, red, [u])
        if s != total:
            seen.setdefault(s, 0)
            seen[s] += 1
    return sorted(seen.items(), key=lambda kv: sum(kv[0]))


# ------------------------------------------------------------------ the two cases
def run_case(tag, n, J, note):
    M = periplectic(n)
    d = d_operator(M)
    Xp, Xm = Xplus(M, n), Xminus(M, n)
    kappa = compatible(M, n, J)
    dc = dc_from_J(M, J)
    base = closure(M, [Xp, Xm, d])
    full = closure(M, [Xp, Xm, d, dc])
    print('%s  C^{%d|%d}  (%s)' % (tag, n, n, note))
    print('     J(omega) = %s * omega  -->  %s'
          % (kappa, 'omega-compatible, h := omega(J^{-1}.,.) has parity %d'
             % ((1 + (0 if M.parity(dc) == M.parity(d) else 1)) % 2)
             if kappa is not None else 'NOT compatible'))
    print('     p(d_c) = %d (p(d) = %d);  d_c^2 = %s'
          % (M.parity(dc), M.parity(d), 'ZERO' if not M.br(dc, dc) else 'NONZERO'))
    print('     <X^+,X^-,d>       = (%d|%d)' % base[1])
    print('     <X^+,X^-,d,d_c>   = (%d|%d)' % full[1])
    red = structure(M, full[0], 'the Dolbeault answer')
    ids = minimal_ideals(M, red)
    if ids:
        print('     proper ideals generated by one basis vector: %s'
              % ', '.join('(%d|%d)x%d' % (s[0], s[1], c) for s, c in ids[:4]))
    # is the (3|5) of Lemma gl11 an ideal of it?
    gl = reduce_basis(M, base[0])
    ech = span(M, red)
    inside = all(contains(M, ech, e) for e in gl)
    isideal = all(contains(M, span(M, gl), M.br(u, v)) for u in red for v in gl)
    print('     ba(2)(+)sl(1|1) sits inside? %s ; is it an ideal? %s' % (inside, isideal))
    print()
    return full[1]


