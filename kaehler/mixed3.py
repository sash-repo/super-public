NAMES = {'c': 'y', 'b': 'D', 'x': 'z', 't': 't', 'h': 'h'}


def mono(M, n, key):
    """render one normal-ordered monomial key readably."""
    out = []
    for kind, a in key:
        if kind in ('c', 'b'):
            base = 'q%d' % (a + 1) if a < n else 'p%d' % (a - n + 1)
            out.append(('y_' if kind == 'c' else 'D_') + base)
        else:
            base = 'q%d' % (a + 1) if a < n else 'p%d' % (a - n + 1)
            out.append((base if kind == 'x' else 't_' + base))
    return ' '.join(out) if out else '1'


def show(M, n, e, width=64):
    terms = []
    for key in sorted(e, key=lambda k: (len(k), k)):
        co = e[key]
        s = mono(M, n, key)
        terms.append(('%+d ' % co if co.denominator == 1 else '%+s ' % co) + s)
    s = ' '.join(terms)
    return s if len(s) <= width else s[:width - 3] + '...'


def analyse(tag, n, J, note):
    M = periplectic(n)
    d, Xp, Xm = d_operator(M), Xplus(M, n), Xminus(M, n)
    dc = dc_from_J(M, J)
    H = M.br(Xp, Xm)
    g = reduce_basis(M, closure(M, [Xp, Xm, d, dc])[0])
    s = sd(M, g)
    print('%s  C^{%d|%d}  (%s):  g = (%d|%d), dim %d' % (tag, n, n, note, s[0], s[1],
                                                         sum(s)))

    # the reductive-looking part and the ideal generated by the differentials
    sl = reduce_basis(M, closure(M, [Xp, Xm])[0])
    print('     <X^+, X^-> = (%d|%d)  [sl(1|1)]' % sd(M, sl))
    N = ideal(M, g, [d, dc])
    print('     ideal generated by d and d_c: (%d|%d)' % N)
    # its basis, to test the semidirect sum
    Nb = []
    ech = {0: None, 1: None}
    from flatmodel import Echelon
    ech = {0: Echelon(), 1: Echelon()}
    cur = [d, dc]
    for e in cur:
        ech[M.parity(e)].add(e)
        Nb.append(e)
    i = 0
    while i < len(Nb):
        for v in g:
            br = M.br(Nb[i], v)
            if br and ech[M.parity(br)].add(br):
                Nb.append(br)
        i += 1
    print('     N nilpotent?  lower central series of N: %s'
          % ' > '.join('(%d|%d)' % t for t in lcs_of(M, Nb)))
    print('     centre of N = (%d|%d);  centre of g = (%d|%d)'
          % (centre(M, Nb) + centre(M, g)))
    # is g = N (+) sl(1|1)?
    both = reduce_basis(M, Nb + sl)
    print('     N + sl(1|1) spans g?  %s  (sdim of the sum (%d|%d))'
          % (sd(M, both) == s, sd(M, both)[0], sd(M, both)[1]))
    inter = [e for e in sl if contains(M, span(M, Nb), e)]
    print('     N cap sl(1|1) = (%d|%d)' % sd(M, inter))

    # ba(2) = the ideal generated by d inside <X^+,X^-,d>: is it inside N?
    gl = reduce_basis(M, closure(M, [Xp, Xm, d])[0])
    ba2 = [e for e in gl if not contains(M, span(M, sl), e)]
    print('     ba(2) = (%d|%d) sits inside N?  %s'
          % (sd(M, ba2) + (all(contains(M, span(M, Nb), e) for e in ba2),)))
    # N / centre(N)
    z = reduce_basis(M, [b for u in Nb for v in Nb for b in [M.br(u, v)]])
    zz = [e for e in Nb if all(not M.br(e, v) for v in Nb)]
    print('     N/z(N) = (%d|%d)  [z(N) = (%d|%d), so N is 2-step nilpotent'
          ' with %d differentials]'
          % (s[0] - sd(M, sl)[0] - sd(M, zz)[0], s[1] - sd(M, sl)[1] - sd(M, zz)[1],
             sd(M, zz)[0], sd(M, zz)[1],
             sum(s) - sum(sd(M, sl)) - sum(sd(M, zz))))
    print('     the Laplacians spanning z(N):')
    for e in zz:
        print('        p=%d  %s' % (M.parity(e), show(M, n, e)))
    print('     the %d new operators beyond ba(2)(+)sl(1|1):' % (sum(s) - 8))
    old = span(M, closure(M, [Xp, Xm, d])[0])
    for e in g:
        if not contains(M, old, e):
            print('        p=%d  %s' % (M.parity(e), show(M, n, e)))
    print()
    return s


def lcs_of(M, basis):
    base = reduce_basis(M, basis)
    cur = base
    out = [sd(M, cur)]
    while True:
        nxt = reduce_basis(M, [M.br(u, v) for u in base for v in cur])
        t = sd(M, nxt)
        out.append(t)
        if t == out[-2] or t == (0, 0):
            break
        cur = nxt
        if len(out) > 10:
            break
    return out


