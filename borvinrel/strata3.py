"""
Stratification of the symmetric 3x3 family of Section 11 of the paper:

        ( d  a  b )
        ( a  d  c )      a, b, c symbolic,
        ( b  c  d )

for the three cases of the paper:

    odd0   main diagonal 0, all three generators odd   (Subsec. 11.2, eq. (80))
    even0  main diagonal 0, all three generators even  (Subsec. 11.3)
    even2  main diagonal 2, all three generators even  (Subsec. 11.4)

The driver (`driver.analyse`) works multidegree by multidegree: it quotients the free
Lie superalgebra by the ideal generated by the relations already found, forms the Gram
matrix of the contravariant form on the quotient and factors its determinant.  Every
irreducible factor is a wall; with depth >= 1 the driver recurses into each wall and
prints the relations found there.

At the end the script prints the set of all walls met, i.e., the non-constant
irreducible factors of the determinants (a, b, c included).

Usage:  python strata3.py CASE MAXHEIGHT [DEPTH]      (DEPTH defaults to 0)
e.g.    python strata3.py odd0 7          (Statement 11.2.1a: about 3 minutes)
        python strata3.py even0 5         (the walls (92))
        python strata3.py even2 4         (the walls (93))
        python strata3.py odd0 3 1        (Statement 11.5.1; likewise even0, even2)
"""

import sys
import time

import sympy as sp

import driver
from driver import Stratum, analyse
from shapovalov import free_lie_superalgebra

a, b, c = driver.a, driver.b, driver.c

CASES = {
    'odd0': (sp.Integer(0), [1, 1, 1]),
    'even0': (sp.Integer(0), [0, 0, 0]),
    'even2': (sp.Integer(2), [0, 0, 0]),
}


def main():
    case = sys.argv[1]
    maxheight = int(sys.argv[2])
    depth = int(sys.argv[3]) if len(sys.argv) > 3 else 0
    d, par = CASES[case]
    A_sym = [[d, a, b], [a, d, c], [b, c, d]]
    print('case %s: main diagonal %s, parities %s, heights <= %d, depth %d'
          % (case, d, par, maxheight, depth))
    t0 = time.time()
    L = free_lie_superalgebra(3, maxheight, par=par)
    walls = set()

    def log(s):
        print(s, flush=True)
        if 'det=' in s:
            det = sp.sympify(s.split('det=')[1])
            if det != 0:
                for f, _ in sp.factor_list(det)[1]:
                    if f.free_symbols:
                        walls.add(sp.expand(f))

    analyse(A_sym, 3, maxheight, Stratum({}, '', [a, b, c]), L,
            maxdepth=depth, par=par, log=log)
    print()
    print('walls met (non-constant irreducible factors of the determinants):')
    for f in sorted(walls, key=lambda f: (sp.Poly(f, a, b, c).total_degree(), str(f))):
        print('   %s = 0' % f)
    print('elapsed %.1f s' % (time.time() - t0))


if __name__ == '__main__':
    main()
