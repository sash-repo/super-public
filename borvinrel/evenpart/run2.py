def span_rank(vs,p):
    rows=[v[:] for v in vs if any(v)]; r=0; basis=[]
    piv=[]
    for v in rows:
        v=v[:]
        for (c,row) in piv:
            if v[c]: x=v[c]; v=[(a-x*b)%p for a,b in zip(v,row)]
        nz=[t for t,x in enumerate(v) if x]
        if nz:
            iv=inv(v[nz[0]],p); v=[x*iv%p for x in v]; piv.append((nz[0],v)); basis.append(v)
    return basis
def analyse(kind,name,a):
    A=mat(kind,a,p); g=G(A,[1,1,1],p); g.build(H)
    pairs=[(0,1),(1,2),(0,2)]
    U=g.unit
    y=[]
    for (i,j) in pairs:
        deg=g.add(U(i),U(j)); c=g.br(U(i),0,U(j),0); y.append((deg,c))
    # Cartan elements H_i = [y_i^+, [f_a,f_b]]
    def Hof(i,j,c):
        deg=g.add(U(i),U(j)); L=g.low[deg][0]; pu=0
        res=[0]*3
        for (s1,s2) in [(i,j),(j,i)]:
            # term [[u,f_s1],f_s2] (with sign for order): we compute [u,[f_i,f_j]] =[[u,f_i],f_j] + [f_i,[u,f_j]] (p(u)=0)
            pass
        li=L[i][0]; lj=L[j][0]
        # [u,f_i] = -[f_i,u] (p(u)=0) = -li e_j ; [e_j,f_j]=h_j
        res[j]=(res[j]-li)%p
        # [u,f_j] = -lj e_i ; [f_i, e_i] = -(-1)^{p_i} h_i = +h_i (odd)
        res[i]=(res[i]-lj)%p
        return [x*c[0]%p for x in res]
    Hs=[Hof(i,j,c) for (i,j),(d,c) in zip(pairs,y)]
    B=[[sum(Hs[r][k]*g.ev(y[s][0],k) for k in range(3))%p for s in range(3)] for r in range(3)]
    def rat(x):
        for q in range(1,200):
            for u in range(-400,401):
                if (u-x*q)%p==0: return '%d/%d'%(u,q) if q>1 else str(u)
        return '?%d'%x
    Bn=[[rat(B[r][s]*2*inv(B[r][r],p)%p) if B[r][r] else rat(B[r][s]) for s in range(3)] for r in range(3)]
    # subalgebra S generated by y^+
    S={}
    for (d,c) in y: S[d]=[c]
    for k in range(2,H//2+1):
        new={}
        for (dj,cj) in y:
            for d,vs in list(S.items()):
                if sum(d)!=2*(k-1): continue
                D=g.add(d,dj)
                if g.dim.get(D,0)==0: continue
                for v in vs:
                    out=[0]*g.dim[D]
                    for b1,x1 in enumerate(cj):
                        if not x1: continue
                        for b2,x2 in enumerate(v):
                            if x2:
                                r=g.br(dj,b1,d,b2)
                                for t,z in enumerate(r): out[t]=(out[t]+x1*x2*z)%p
                    new.setdefault(D,[]).append(out)
        for D,vs in new.items(): S[D]=span_rank(vs,p)
    tot=g.totals(H)
    ev=[tot[h-1] for h in range(2,H+1,2)]
    sd=[sum(len(v) for d,v in S.items() if sum(d)==h) for h in range(2,H+1,2)]
    print(kind,name,"\n  g_k (k=1..%d):"%H,tot,"\n  g_ev by height 2,4,..:",ev,"\n  <y+> by height 2,4,..:",sd,"\n  B normalized:",Bn,flush=True)
    return g,B,S
