"""
Statement 10.1.1 on its own wall  A_12 + A_13 + A_23 = 0 :
an INDEPENDENT check, and the other two main diagonals.

The stratification run (onwall3.py) reported something strong: on the wall,
with zero main diagonal and all three generators odd, every multidegree of
height >= 4 is already exhausted by the ideal generated by the relations
found in heights 2 and 3.  If true, that means n_+ is FINITE-DIMENSIONAL
there, and "there are no other relations" stops being a conjecture.

That conclusion leans on the ideal machinery, so we re-derive the dimensions
here by a route that does not use it at all:

        dim n_+^alpha  =  rank of the contravariant form on the free L^alpha,

since n_+ = L / r_+ and r_+ = ker of that form.  We do it with a NUMERIC a on
the wall (several values, to make sure the value is not itself special) and
for the three cases of Section 11 ("Relations"):

   (i)   zero main diagonal, all generators odd,
   (ii)  zero main diagonal, all generators even,
   (iii) main diagonal 2, all generators even.
"""

import sys
import time
from collections import defaultdict

import sympy as sp

from shapovalov import free_lie_superalgebra, gram

MAXHEIGHT = int(sys.argv[1]) if len(sys.argv) > 1 else 6
N = 3

CASES = [
    ('zero diagonal, all odd', sp.Integer(0), [1, 1, 1]),
    ('zero diagonal, all even', sp.Integer(0), [0, 0, 0]),
    ('diagonal 2, all even', sp.Integer(2), [0, 0, 0]),
]

# points ON the wall a+b+c = 0, in general position otherwise
WALL_POINTS = [(sp.Integer(2), sp.Integer(1), sp.Integer(-3)),
               (sp.Integer(5), sp.Integer(3), sp.Integer(-8)),
               (sp.Rational(1, 2), sp.Integer(1), sp.Rational(-3, 2))]
# a point OFF the wall, for contrast
OFF_POINTS = [(sp.Integer(2), sp.Integer(1), sp.Integer(1))]


def dims(A, par, maxheight, L):
    """dim n_+ in each height = sum over multidegrees of rank(Gram)."""
    out = {}
    for k in range(1, maxheight + 1):
        tot = 0
        per = {}
        for alpha in sorted(L.get(k, {})):
            basis = L[k][alpha]
            if k == 1:
                r = len(basis)
            else:
                G = gram(basis, A, N, alpha, par)
                r = G.rank()
            per[alpha] = (len(basis), r)
            tot += r
        out[k] = (tot, per)
    return out


def main():
    out = open('log-3x3-onwall-dims.txt', 'w')

    def P(s=''):
        print(s)
        out.write(str(s) + '\n')
        out.flush()

    P('=== dim n_+ ON the wall a+b+c=0, computed as rank of the ===')
    P('=== contravariant form on the FREE component (no ideals)  ===')
    P('maxheight = %d' % MAXHEIGHT)
    P('')

    for name, diag, par in CASES:
        L = free_lie_superalgebra(N, MAXHEIGHT, par=par)
        P('-' * 68)
        P('case: %s' % name)
        P('-' * 68)
        for label, pts in (('ON  wall', WALL_POINTS), ('OFF wall', OFF_POINTS)):
            for (a, b, c) in pts:
                A = [[diag, a, b], [a, diag, c], [b, c, diag]]
                t0 = time.time()
                d = dims(A, par, MAXHEIGHT, L)
                tot = sum(v[0] for v in d.values())
                P('  %s  (a,b,c)=(%s,%s,%s):  dim n_+ by height = %s   total=%d  [%.0fs]'
                  % (label, a, b, c,
                     {k: v[0] for k, v in d.items()}, tot, time.time() - t0))
                # print the per-multidegree detail for the first wall point
                if pts is WALL_POINTS and (a, b, c) == WALL_POINTS[0]:
                    for k in sorted(d):
                        det = ', '.join('%s:%d/%d' % (al, r, dl)
                                        for al, (dl, r) in sorted(d[k][1].items())
                                        if dl)
                        P('        height %d   (dim n_+ / dim free): %s' % (k, det))
        P('')

    out.close()


if __name__ == '__main__':
    main()
