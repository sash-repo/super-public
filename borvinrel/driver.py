"""
Full stratification driver.

At each multidegree alpha, on the current stratum:

  1. I^alpha = component of the ideal generated by the relations already found;
  2. Q = L^alpha / I^alpha  (the form descends: I lies in the radical);
  3. G = Gram matrix of the contravariant form on Q;
  4. det G, factored.  Every non-constant irreducible factor is a WALL: on the
     open stratum where none vanishes we take ker G = the new defining
     relations; for each wall we recurse into the sub-stratum where it does.

The case list is therefore produced as the set of irreducible components of a
determinant, not as the set of cases somebody happened to notice.  That is the
completeness guarantee.
"""

from fractions import Fraction
from collections import defaultdict
import itertools

import sympy as sp

from shapovalov import free_lie_superalgebra, bracket, gram, Span

a, b, c = sp.symbols('a b c')
PARAMS = [a, b, c]


# ------------------------------------------------------------------ util ---


def to_sym(vec):
    return {w: (sp.Rational(cf.numerator, cf.denominator)
                if isinstance(cf, Fraction) else sp.sympify(cf))
            for w, cf in vec.items()}


def sbracket(u, v, par):
    """Super bracket for word-vectors with sympy coefficients."""
    from shapovalov import pw
    out = defaultdict(lambda: sp.Integer(0))
    for wu, cu in u.items():
        for wv, cv in v.items():
            sign = -1 if (pw(wu, par) * pw(wv, par)) % 2 else 1
            out[wu + wv] += cu * cv
            out[wv + wu] -= sign * cu * cv
    return {w: sp.expand(x) for w, x in out.items() if sp.expand(x) != 0}


def matrix_of(vecs, words):
    return sp.Matrix([[v.get(w, sp.Integer(0)) for w in words] for v in vecs])


def ideal_comp(rels, alpha, n, par):
    """Vectors spanning the degree-alpha part of the ideal generated by rels."""
    out = []
    for ral, rv in rels:
        if any(x > y for x, y in zip(ral, alpha)):
            continue
        need = tuple(y - x for x, y in zip(ral, alpha))
        # bracket rv with every word in the missing multidegree, all orders
        letters = []
        for i in range(n):
            letters += [i] * need[i]
        if not letters:
            out.append(rv)
            continue
        for perm in set(itertools.permutations(letters)):
            v = rv
            for i in perm:
                v = sbracket({(i,): sp.Integer(1)}, v, par)
                if not v:
                    break
            if v:
                out.append(v)
    return out


def rank_and_kernel(M):
    return M.rank(), M.nullspace()


# ------------------------------------------------------------- the driver --


class Stratum:
    def __init__(self, subs, name, free):
        self.subs = subs          # dict param -> expression
        self.name = name          # human-readable defining conditions
        self.free = free          # remaining free symbols
        self.rels = []            # list of (alpha, word-vector) new relations
        self.walls = []           # factors declared non-zero (genericity)

    def A(self, A_sym):
        return [[sp.expand(x.subs(self.subs)) for x in row] for row in A_sym]

    def label(self):
        return self.name or 'generic'


def analyse(A_sym, n, maxheight, stratum, L, depth=0, maxdepth=3, log=print, par=None):
    """Returns list of (stratum, findings)."""
    if par is None:
        par = [1] * n
    A = stratum.A(A_sym)
    pad = '  ' * depth
    log('%s== stratum: %s   [generic: %s]' %
        (pad, stratum.label(), ', '.join(str(w) + '!=0' for w in stratum.walls) or '-'))
    results = []
    children = []

    for k in range(2, maxheight + 1):
        for alpha in sorted(L.get(k, {})):
            basis = [to_sym(v) for v in L[k][alpha]]
            words = sorted({w for v in basis for w in v}, key=lambda w: (len(w), w))
            # ideal part
            ivecs = ideal_comp(stratum.rels, alpha, n, par)
            Ispan = matrix_of(ivecs, words) if ivecs else sp.zeros(0, len(words))
            Ispan = Ispan.applyfunc(lambda x: sp.simplify(x.subs(stratum.subs)))
            irank = Ispan.rank() if ivecs else 0
            Lm = matrix_of(basis, words)
            dimL = Lm.rank()
            if irank >= dimL:
                continue                                   # nothing left
            # quotient basis: complete Ispan to a basis of L^alpha
            rows = [Ispan.row(i) for i in range(Ispan.rows)]
            chosen, chosen_idx = list(rows), []
            cur = sp.Matrix(chosen) if chosen else sp.zeros(0, len(words))
            for idx in range(len(basis)):
                cand = Lm.row(idx)
                test = cur.col_join(cand) if cur.rows else cand
                if test.rank() > (cur.rank() if cur.rows else 0):
                    cur = test
                    chosen_idx.append(idx)
            if not chosen_idx:
                continue
            qbasis = [basis[i] for i in chosen_idx]
            # Gram on the quotient
            G = gram_sym(qbasis, A, n, alpha, par)
            det = sp.factor(sp.expand(G.det()))
            if det == 0 and G.rows == 0:
                continue
            log('%s   alpha=%-10s dimL=%-2d dimI=%-2d dimQ=%-2d det=%s'
                % (pad, alpha, dimL, irank, len(qbasis), det))
            # walls
            facs = nonconstant_factors(det, stratum)
            if facs:
                for f in facs:
                    children.append((alpha, f))
            # generic kernel on this stratum
            Ggen = G
            r, ns = rank_and_kernel(Ggen)
            if r < len(qbasis):
                for v in ns:
                    vec = defaultdict(lambda: sp.Integer(0))
                    for i, coeff in enumerate(v):
                        if coeff == 0:
                            continue
                        for w, cf in qbasis[i].items():
                            vec[w] += coeff * cf
                    vec = {w: sp.simplify(x) for w, x in vec.items()
                           if sp.simplify(x) != 0}
                    if vec:
                        stratum.rels.append((alpha, clear_denoms(vec)))
                        log('%s      NEW RELATION in degree %s: %s'
                            % (pad, alpha, pretty(clear_denoms(vec))))
    results.append(stratum)

    if depth < maxdepth:
        seen = set()
        for alpha, f in children:
            key = sp.factor(f)
            if key in seen:
                continue
            seen.add(key)
            sub = branch(stratum, f)
            if sub is None:
                continue
            results += analyse(A_sym, n, maxheight, sub, L, depth + 1, maxdepth, log, par)
    return results


def gram_sym(qbasis, A, n, alpha, par):
    """Gram matrix for basis vectors carrying sympy coefficients."""
    from shapovalov import phi
    d = len(qbasis)
    phis = [phi(u, A, n, alpha, par) for u in qbasis]
    G = sp.zeros(d, d)
    for i in range(d):
        for j in range(d):
            s = sp.Integer(0)
            for w, cf in qbasis[j].items():
                pv = phis[i].get(w)
                if pv is not None and pv != 0:
                    s += cf * pv
            G[i, j] = sp.expand(s)
    return G


def nonconstant_factors(det, stratum):
    if det == 0:
        return []
    out = []
    for f, _ in sp.factor_list(det)[1]:
        f = sp.expand(f)
        if f.free_symbols & set(stratum.free):
            out.append(sp.factor(f))
    return out


def branch(stratum, f):
    """Sub-stratum f = 0, solved for one free parameter if possible."""
    syms = sorted(f.free_symbols & set(stratum.free), key=str)
    if not syms:
        return None
    for s in reversed(syms):
        sol = sp.solve(sp.Eq(f, 0), s, dict=True)
        if len(sol) == 1:
            newsubs = dict(stratum.subs)
            expr = sol[0][s]
            newsubs = {k: sp.simplify(v.subs({s: expr})) for k, v in newsubs.items()}
            newsubs[s] = expr
            free = [x for x in stratum.free if x != s]
            cond = '%s = %s' % (s, sp.simplify(expr))
            name = (stratum.name + ', ' if stratum.name else '') + cond
            st = Stratum(newsubs, name, free)
            st.walls = list(stratum.walls)
            return st
    return None


def clear_denoms(vec):
    dens = [sp.denom(sp.together(x)) for x in vec.values()]
    m = sp.lcm(dens) if dens else 1
    out = {w: sp.simplify(sp.expand(x * m)) for w, x in vec.items()}
    nums = [sp.Poly(x, *[s for s in PARAMS]).coeffs() if x.free_symbols else [x]
            for x in out.values()]
    flat = [q for lst in nums for q in lst]
    try:
        g = sp.gcd([sp.nsimplify(q) for q in flat])
    except Exception:
        g = 1
    if g and g != 0 and not g.free_symbols:
        out = {w: sp.simplify(x / g) for w, x in out.items()}
    return out


GEN = {0: '1', 1: '2', 2: '3'}


def pretty(vec):
    parts = []
    for w, cf in sorted(vec.items(), key=lambda kv: (len(kv[0]), kv[0])):
        parts.append('(%s)*x%s' % (sp.factor(cf), ''.join(GEN[i] for i in w)))
    return ' + '.join(parts)
