"""What these matrices ARE: Gram matrices of bases of root lattices made of roots.

A symmetric integer matrix A with A_ii = 2 is the Gram matrix of a basis
e_1, ..., e_n of a lattice L, and every value x^T A x = 2 sum x_i^2 + 2 sum_{i<j}
A_ij x_i x_j is even, so L is an EVEN lattice; if A is positive definite, L is a
positive definite even lattice generated by the n vectors e_i, each of norm 2.  A
positive definite even lattice generated by its vectors of norm 2 is a root lattice,
i.e. an orthogonal direct sum of lattices of types A, D, E (Witt).  So the census is

    { matrices of size n, up to permutation }
      =  { (root lattice L of rank n, basis of L consisting of roots) } / Isom(L),

which is why the count is finite, and which says how to sort the list: by the type of L.

This module finds all the roots of L (the vectors of norm 2), splits them into
irreducible components and names each component from its rank and its number of roots:
  A_k: k(k+1) roots,  D_k: 2k(k-1),  E_6: 72,  E_7: 126,  E_8: 240.
"""

import collections
import itertools
from fractions import Fraction

from vinb import det_int, is_posdef, is_connected, is_bipartite


def cholesky(A):
    """A = L D L^T with L unit lower triangular; exact rationals.  A positive definite."""
    n = len(A)
    L = [[Fraction(0)] * n for _ in range(n)]
    D = [Fraction(0)] * n
    for j in range(n):
        D[j] = Fraction(A[j][j]) - sum(L[j][k] ** 2 * D[k] for k in range(j))
        L[j][j] = Fraction(1)
        for i in range(j + 1, n):
            L[i][j] = (Fraction(A[i][j])
                       - sum(L[i][k] * L[j][k] * D[k] for k in range(j))) / D[j]
    return L, D


def roots(A):
    """All x in Z^n with x^T A x = 2, one of each +- pair (the first nonzero entry > 0)."""
    n = len(A)
    L, D = cholesky(A)
    out = []
    x = [0] * n

    def rec(i, rem):
        # rem is the norm still available for coordinates 0..i
        if i < 0:
            if rem == 0:
                out.append(tuple(x))
            return
        # x^T A x = sum_j D_j (x_j + sum_{k>j} L_kj x_k)^2 ; process j = n-1 down to 0
        s = sum(L[k][i] * x[k] for k in range(i + 1, n))
        # D_i (x_i + s)^2 <= rem
        bound = rem / D[i]
        lo = -s - _isqrt_frac(bound)
        hi = -s + _isqrt_frac(bound)
        for v in range(_ceil(lo), _floor(hi) + 1):
            x[i] = v
            rec(i - 1, rem - D[i] * (v + s) ** 2)
        x[i] = 0

    rec(n - 1, Fraction(2))
    # keep one of each +- pair
    seen, keep = set(), []
    for r in out:
        if r in seen:
            continue
        seen.add(r)
        seen.add(tuple(-c for c in r))
        keep.append(r)
    return keep


def _isqrt_frac(q):
    """A rational UPPER bound for sqrt(q); only the enclosing interval matters."""
    if q <= 0:
        return Fraction(0)
    import math
    return Fraction(math.isqrt(int(q.numerator * q.denominator)) + 2, q.denominator)


def _ceil(q):
    return -((-q.numerator) // q.denominator)


def _floor(q):
    return q.numerator // q.denominator


def pair(A, u, v):
    return sum(u[i] * A[i][j] * v[j] for i in range(len(A)) for j in range(len(A)))


def root_system_type(A):
    """Name the root system of the lattice with Gram matrix A."""
    R = roots(A)
    m = len(R)
    # components of the "not orthogonal" graph
    adj = {i: [] for i in range(m)}
    for i in range(m):
        for j in range(i + 1, m):
            if pair(A, R[i], R[j]) != 0:
                adj[i].append(j)
                adj[j].append(i)
    seen, comps = [False] * m, []
    for s in range(m):
        if seen[s]:
            continue
        stack, comp = [s], []
        seen[s] = True
        while stack:
            v = stack.pop()
            comp.append(v)
            for w in adj[v]:
                if not seen[w]:
                    seen[w] = True
                    stack.append(w)
        comps.append(comp)
    names = []
    for comp in comps:
        nroots = 2 * len(comp)
        rk = _rank([R[i] for i in comp])
        names.append(_name(rk, nroots))
    return '+'.join(sorted(names, key=_sortkey)), 2 * m


def _rank(vs):
    from fractions import Fraction as F
    M = [[F(c) for c in v] for v in vs]
    r, rows, cols = 0, len(M), len(M[0])
    for c in range(cols):
        piv = next((i for i in range(r, rows) if M[i][c] != 0), None)
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        pv = M[r][c]
        M[r] = [x / pv for x in M[r]]
        for i in range(rows):
            if i != r and M[i][c] != 0:
                f = M[i][c]
                M[i] = [a - f * b for a, b in zip(M[i], M[r])]
        r += 1
    return r


def _name(rk, nroots):
    if nroots == rk * (rk + 1):
        return f'A{rk}'
    if rk >= 4 and nroots == 2 * rk * (rk - 1):
        return f'D{rk}'
    if (rk, nroots) == (6, 72):
        return 'E6'
    if (rk, nroots) == (7, 126):
        return 'E7'
    if (rk, nroots) == (8, 240):
        return 'E8'
    return f'?rk{rk}/{nroots}roots'


def _sortkey(s):
    return (s[0], int(s[1:]) if s[1:].isdigit() else 0)


