#!/usr/bin/env python3
"""Common driver: from fields (in some coordinates, heights H) to the abstract
g_{<=0}, its Blattner realization at N~=1, the prolong and its analysis."""
import time
from f2vf import Space, find_weights, parse_field
from prolong import (prolong, Graded, generators, ad_closure, restricted_closure,
                     simple_test, log)
from absutil import abstract
from blattner import Realization


def close0(sp, G, gens0):
    for x in gens0:
        G.add(x)
    ch = True
    while ch:
        ch = False
        B = G.basis(0)
        for a in B:
            for b in B:
                if G.add(sp.bracket(a, b)):
                    ch = True
    return G


def nonpositive(sp, neg, g0gens=None, complete_neg=False):
    """Graded g_{<=0}: g_- spanned by neg, g_0 generated by g0gens, or (if
    complete_neg) the degree-0 part of the complete prolong of g_- in vect(m;H)."""
    if complete_neg:
        G = prolong(sp, neg, None, maxdeg=0, verbose=False)
        return G
    G = Graded(sp)
    for x in neg:
        G.add(x)
    close0(sp, G, g0gens or [])
    for a in G.basis(0):
        for b in G.basis():
            if sp.kdeg(next(iter(b))) < 0:
                assert G.contains(sp.bracket(a, b)), 'g0 does not preserve g_-'
    return G


def to_abstract(sp, G):
    basis, degs, pars = [], [], []
    for d in sorted(d for d in G.degrees() if d <= 0):
        # split by parity if needed
        for v in G.basis(d):
            ps = {sp.kpar(k) for k in v}
            assert len(ps) == 1, 'basis vector not parity-homogeneous'
            basis.append(v)
            degs.append(d)
            pars.append(ps.pop())
    return abstract(basis, degs, pars, sp.bracket)


def realize_and_prolong(A, g1=None, verbose=True, label=''):
    Rz = Realization(A)
    D = Rz.realize()
    fields = [D[i] for i in range(A.n)]
    W = find_weights(Rz.sp, fields)
    sp = Space([1] * Rz.m, Rz.sp.degs, Rz.sp.par, W)
    if verbose:
        log('%s realized on %d coordinates (N~=1), weight rank %d; p-map nonzero on %d basis elts'
            % (label, Rz.m, len(W[0]), sum(1 for b in Rz.pmap if Rz.pmap[b])))
    neg = [D[i] for i in range(A.n) if A.deg[i] < 0]
    g0 = [D[i] for i in range(A.n) if A.deg[i] == 0]
    G = prolong(sp, neg, g0, verbose=verbose)
    return sp, G, D, Rz


def analyse(sp, G, label=''):
    out = {}
    out['comp'] = {d: (G.dim(d), G.parity_dims(d)) for d in G.degrees()}
    out['dim'] = G.dim()
    out['sdim'] = G.parity_dims()
    gens = generators(G)
    J = ad_closure(sp, gens, G.basis(-1))
    out['J'] = (J.dim(), J.parity_dims())
    out['Jcomp'] = {d: J.dim(d) for d in J.degrees()}
    st = simple_test(sp, J)
    out['J simple'] = st
    # super-closure of J (odd squares); needed for the superization
    def oddsq(v):
        if sp.kpar(next(iter(v))) == 1:
            return [sp.square(v)]
        return []
    Js = ad_closure(sp, gens, G.basis(-1), extra=oddsq)
    out['J super'] = (Js.dim(), Js.parity_dims())
    R = restricted_closure(sp, J)
    out['J restricted closure'] = (R.dim(), R.parity_dims())
    RG = restricted_closure(sp, G)
    out['G restricted closure'] = (RG.dim(), RG.parity_dims())
    out['G/J'] = G.dim() - J.dim()
    log('== %s' % label)
    for d in G.degrees():
        log('   deg %3d: dim %5d  sdim %s   J: %d' % (d, G.dim(d), G.parity_dims(d), J.dim(d)))
    for k in ('dim', 'sdim', 'J', 'J simple', 'J super', 'J restricted closure',
              'G restricted closure'):
        log('   %-22s %s' % (k, out[k]))
    return out, J
