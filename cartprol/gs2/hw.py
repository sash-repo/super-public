#!/usr/bin/env python3
"""Highest weight modules over L wrt the Borel h + N+ for a linear functional phi on the Z^2-grading;
chi|_{N+ + N-} = 0; lambda in K^2 on h = <u1d1, u2d2>."""
import numpy as np, sys, itertools
from gfla import GF
from lalg import *
from induce import Induced, check_rep
H = [NAMES.index('u1d1'), NAMES.index('u2d2')]
def borel(phi):
    pos = [k for k in range(N) if k not in H and phi[0] * WTS[k][0] + phi[1] * WTS[k][1] > 0]
    neg = [k for k in range(N) if k not in H and phi[0] * WTS[k][0] + phi[1] * WTS[k][1] < 0]
    assert len(pos) + len(neg) == N - 2
    return pos, neg
def module(F, phi, lam):
    pos, neg = borel(phi)
    chi = np.zeros(N, dtype=np.int64)
    for i, h in enumerate(H): chi[h] = F.sqrt(F.T[lam[i], lam[i]] ^ lam[i])
    Mod = Induced(F, H + pos, list(lam) + [0] * len(pos), chi)
    return Mod, chi, pos, neg
def singular(F, M, pos):
    A = np.vstack([M[k] for k in pos])
    return F.nullspace(A)
def radical_quotient_dim(F, M, gens):
    """dim of the irreducible quotient of a cyclic module generated by basis vector 0 (hw vector):
    the largest submodule inside ker(coefficient of basis vector 0)."""
    d = M[0].shape[0]
    W = np.eye(d, dtype=np.int64)[1:]          # ker f
    while True:
        # W' = {w in W : x w in W for all x}
        # w = c W ; x w in W  <=>  (x W^T c) has zero component outside W
        # compute a complement test: project to V/W via a matrix Q with ker Q = W
        Q = F.nullspace(W) if len(W) else np.eye(d, dtype=np.int64)   # rows q with q.w=0 for w in W
        cons = [F.dot(Q, F.dot(M[k], W.T)) for k in gens]           # (codim x dimW)
        A = np.vstack(cons)
        C = F.nullspace(A.T.T if False else A, len(W)) if len(W) else np.zeros((0, 0), dtype=np.int64)
        if len(W) == 0: return d
        if len(C) == len(W): return d - len(W)
        W = F.dot(C, W)
        W = F.rref(W)[0]
if __name__ == '__main__':
    F = GF(1)
    for phi in [(1, 10), (1, 1)]:
        pos, neg = borel(phi)
        print('phi', phi, 'N+ =', [NAMES[k] for k in pos], '\n       N- =', [NAMES[k] for k in neg])
        for lam in itertools.product(range(2), repeat=2):
            Mod, chi, pos, neg = module(F, phi, lam)
            M = Mod.mats(); check_rep(F, M, chi)
            S = singular(F, M, pos)
            q = radical_quotient_dim(F, M, range(N))
            print('   lambda', lam, 'dim Z =', Mod.dim, ' singular', len(S), ' dim L(lambda) =', q)
