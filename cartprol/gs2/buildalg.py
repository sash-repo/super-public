#!/usr/bin/env python3
"""The Z-graded Lie (super)algebra g = g_{-1} + g_0 + ... + g_K of a FINITE Cartan prolong, as structure
constants over F_2; Jacobi check; simplicity (Burnside on ad), derived series, center, restrictedness."""
import numpy as np, sys
from f2lin import nullspace, rank, rref, solve

def prolong_data(g0mats, n, odd=(), maxk=20):
    A = np.array([np.asarray(m, dtype=np.uint8).flatten() & 1 for m in g0mats], dtype=np.uint8)
    R, piv = rref(A); g0 = [r.reshape(n, n).astype(np.uint8) for r in R]
    levels = [g0]                    # levels[k] = list of (n x m_{k-1}) coefficient matrices; for k=0 matrices
    ev = [m for m in g0]; p = n
    for k in range(1, maxk + 1):
        m = len(ev)
        rows = []
        for i in range(n):
            for j in range(i + 1, n):
                blk = np.zeros((p, n * m), dtype=np.uint8)
                for b in range(m):
                    blk[:, i * m + b] ^= ev[b][:, j]; blk[:, j * m + b] ^= ev[b][:, i]
                rows.append(blk)
            if i in odd:
                blk = np.zeros((p, n * m), dtype=np.uint8)
                for b in range(m): blk[:, i * m + b] ^= ev[b][:, i]
                rows.append(blk)
        Ns = nullspace(np.vstack(rows), n * m)
        if len(Ns) == 0: break
        ev = [c.reshape(n, m).T.copy() for c in Ns]     # (m x n) : column j = coords of D(e_j) in g_{k-1}
        levels.append(ev); p = m
    else:
        raise ValueError('prolong not finite up to maxk')
    return levels

class Graded:
    def __init__(s, g0mats, n, odd=()):
        s.n = n; s.levels = prolong_data(g0mats, n, odd)
        s.dims = [n] + [len(l) for l in s.levels]          # g_{-1}, g_0, g_1, ...
        s.off = np.cumsum([0] + s.dims)                     # offsets: g_{-1} at 0, g_k at off[k+1]
        s.d = int(s.off[-1])
        s.deg = np.concatenate([[k - 1] * dk for k, dk in enumerate(s.dims)])
        s.C = np.zeros((s.d, s.d, s.d), dtype=np.uint8)
        s.build()
    def lvl(s, k): return range(s.off[k + 1], s.off[k + 2])
    def act(s, k, b, j):
        """[x, e_j] for x = b-th basis element of g_k (k>=0), e_j in g_{-1}: vector in g_{k-1} coords"""
        return s.levels[k][b][:, j] & 1
    def emb(s, k, v):
        out = np.zeros(s.d, dtype=np.uint8); out[s.off[k + 1]: s.off[k + 2]] = v; return out
    def build(s):
        n = s.n; K = len(s.levels) - 1
        # [g_k, g_{-1}]
        for k in range(K + 1):
            for b in range(s.dims[k + 1]):
                x = s.off[k + 1] + b
                for j in range(n):
                    v = s.emb(k - 1, s.act(k, b, j))
                    s.C[x, j] = v; s.C[j, x] = v
        # [g_i, g_j], i,j >= 0 by increasing total degree
        for tot in range(0, K + 1):
            for i in range(0, tot + 1):
                jdeg = tot - i
                for a in range(s.dims[i + 1]):
                    for b in range(s.dims[jdeg + 1]):
                        x = s.off[i + 1] + a; y = s.off[jdeg + 1] + b
                        # z(e_l) = [x,[y,e_l]] + [y,[x,e_l]]  in g_{tot-1}
                        cols = []
                        for l in range(n):
                            yl = s.C[y, l]; xl = s.C[x, l]
                            w = (yl.astype(np.int64) @ s.C[x].astype(np.int64) + xl.astype(np.int64) @ s.C[y].astype(np.int64)) & 1
                            cols.append(w)
                        # express: find z in g_tot with [z, e_l] = cols[l] for all l
                        if tot > K:
                            continue
                        target = np.concatenate(cols)
                        Mz = np.array([np.concatenate([s.C[s.off[tot + 1] + c, l] for l in range(n)])
                                       for c in range(s.dims[tot + 1])], dtype=np.uint8).T if s.dims[tot + 1] else None
                        if Mz is None:
                            assert not target.any(); continue
                        z = solve(Mz, target)
                        assert z is not None, ('bracket not in prolong', i, jdeg)
                        s.C[x, y] = s.emb(tot, z)
    def ad(s, x):
        return s.C[x].T.astype(np.int64)            # column j = [e_x, e_j]
def check_jacobi(C):
    d = C.shape[0]; Ci = C.astype(np.int64)
    for a in range(d):
        for b in range(d):
            ab = Ci[a, b]
            for c in range(d):
                s = (ab @ Ci[:, c] + Ci[b, c] @ Ci[:, a] + Ci[c, a] @ Ci[:, b]) & 1
                if s.any(): return False
    return True
def assoc_dim(C, idx=None):
    """dim of the associative algebra (with 1) generated by ad e_x, x in idx (Burnside: = d^2 iff the
    adjoint module is absolutely irreducible)"""
    from f2vf import BitEchelon
    d = C.shape[0]; idx = range(d) if idx is None else idx
    mats = [C[x].T.astype(np.int64) & 1 for x in idx]
    def key(M): return int(''.join(map(str, M.flatten().astype(int))), 2)
    E = BitEchelon(); Id = np.eye(d, dtype=np.int64)
    E.add(key(Id)); frontier = []
    for M in mats:
        if E.add(key(M)): frontier.append(M)
    gens = frontier[:]
    while frontier:
        new = []
        for M in frontier:
            for G in gens:
                P = (M @ G) & 1
                if E.add(key(P)): new.append(P)
        frontier = new
    return len(E)
def span_derived(C, S=None):
    d = C.shape[0]
    B = np.eye(d, dtype=np.int64) if S is None else S
    vecs = []
    for a in B:
        for b in B:
            vecs.append((np.einsum('i,j,ijk->k', a, b, C.astype(np.int64))) & 1)
    V = np.array(vecs, dtype=np.uint8)
    return rref(V)[0]
def center(C):
    d = C.shape[0]
    M = np.vstack([C[:, j, :].T for j in range(d)])     # rows: for each j, [x, e_j] coords as function of x
    return nullspace(M.astype(np.uint8), d)
