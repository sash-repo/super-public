"""
omirr.py -- the rigorous half of the check of [L3, Subsec. 2.4 b)].

For each degree i it splits Omega^i (constant coefficients, n even and n odd
variables) by the two pe(n)-submodules

        I^i = omega . Omega^{i-2}    and    K^i = Ker(omega. : Omega^i -> Omega^{i+2}),

so that  I^i  <=  K^i  <=  Omega^i,  and proves that each of the three
subquotients is either 0 or an IRREDUCIBLE pe(n)-module, by the two facts

  (1) a nonzero submodule of a finite-dimensional module contains a nonzero
      n_+-invariant vector (take a weight vector of maximal height in it);
  (2) hence M is irreducible  <=>  dim M^{n_+} = 1 and U(pe(n)).v = M for the
      (unique up to scalar) invariant v.

Both are checked exactly over Q.

Usage:  python3 omirr.py [nmax] [imax]
"""

import sys
from fractions import Fraction as F
from omcheck import (basis, omega_mul, gens_pe, to_vec, nullspace, weight, add)


# ------------------------------------------------------------ small lin. alg.

def rref(rows):
    """reduced row echelon form; returns (rows, pivot columns)."""
    rows = [r[:] for r in rows if any(r)]
    if not rows:
        return [], []
    ncol = len(rows[0])
    pivots = []
    r = 0
    for col in range(ncol):
        piv = None
        for i in range(r, len(rows)):
            if rows[i][col] != 0:
                piv = i
                break
        if piv is None:
            continue
        rows[r], rows[piv] = rows[piv], rows[r]
        pv = rows[r][col]
        rows[r] = [t / pv for t in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][col] != 0:
                f = rows[i][col]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
        pivots.append(col)
        r += 1
        if r == len(rows):
            break
    return rows[:r], pivots


def reduce_mod(v, ech, pivots):
    """reduce v modulo the row space given in rref form."""
    v = v[:]
    for row, pc in zip(ech, pivots):
        if v[pc] != 0:
            f = v[pc]
            v = [a - f * b for a, b in zip(v, row)]
    return v


def dim_of(rows):
    return len(rref(rows)[0])


# ------------------------------------------------------------ subquotients

class Sub:
    """the subquotient S/T of Omega^i, both S and T given by spanning sets of
    coordinate vectors in the monomial basis `bas`.

    The basis of S/T used throughout is the rref of {s mod T : s in S}; then the
    coordinates of any v in S are simply the entries of (v mod T) in the pivot
    columns, which makes `act` cheap."""

    def __init__(self, n, bas, S, T, gens):
        self.n, self.bas, self.gens = n, bas, gens
        self.midx = {m: k for k, m in enumerate(bas)}
        self.Tech, self.Tpiv = rref(T)
        red = [reduce_mod(v, self.Tech, self.Tpiv) for v in S]
        self.ech, self.piv = rref([r for r in red if any(r)])
        self.dim = len(self.ech)

    def coords(self, v):
        """coordinates of v mod T in the basis self.ech (v must lie in S)."""
        w = reduce_mod(v, self.Tech, self.Tpiv)
        c = [w[p] for p in self.piv]
        # check that v really lies in S (no component outside the row space)
        for row, cc in zip(self.ech, c):
            if cc:
                w = [a - cc * b for a, b in zip(w, row)]
        assert not any(w), "vector not in S"
        return c

    def vec(self, c):
        """the representative in Omega^i of the element with coordinates c."""
        out = [F(0)] * len(self.bas)
        for cc, row in zip(c, self.ech):
            if cc:
                out = [a + cc * b for a, b in zip(out, row)]
        return out

    def act(self, g, c):
        """apply the generator g to the element with coordinates c."""
        el = {}
        for m, val in zip(self.bas, self.vec(c)):
            if val:
                add(el, m, val)
        img = g.act(el)
        return self.coords(to_vec(img, self.midx))

    def invariants(self, npl):
        """basis of the n_+-invariants of S/T."""
        if self.dim == 0:
            return []
        rows = []
        for g in npl:
            cols = []
            for k in range(self.dim):
                e = [F(0)] * self.dim
                e[k] = F(1)
                cols.append(self.act(g, e))
            for t in range(self.dim):
                rows.append([cols[k][t] for k in range(self.dim)])
        return nullspace(rows, self.dim)

    def generated(self, v, allg):
        """dimension of the pe(n)-submodule of S/T generated by v (BFS with an
        incrementally maintained echelon basis)."""
        ech, piv = [], []
        queue = []

        def insert(w):
            w = reduce_mod(w, ech, piv)
            if not any(w):
                return False
            p = next(k for k in range(len(w)) if w[k] != 0)
            w = [t / w[p] for t in w]
            for j in range(len(ech)):
                if ech[j][p] != 0:
                    f = ech[j][p]
                    ech[j] = [a - f * b for a, b in zip(ech[j], w)]
            ech.append(w)
            piv.append(p)
            queue.append(w)
            return True

        insert(v[:])
        while queue:
            row = queue.pop()
            for g in allg:
                insert(self.act(g, row))
        return len(ech)


def solve(A, b):
    """solve A c = b over Q; A is a list of rows (len = ncol of the ambient)."""
    nrow, ncol = len(A), len(A[0])
    M = [A[r][:] + [b[r]] for r in range(nrow)]
    ech, piv = rref(M)
    sol = [F(0)] * ncol
    for row, pc in zip(ech, piv):
        if pc == ncol:            # 0 = 1
            return None
        sol[pc] = row[ncol]
    # verify
    for r in range(nrow):
        s = sum(A[r][c] * sol[c] for c in range(ncol))
        if s != b[r]:
            return None
    return sol


# ------------------------------------------------------------------- driver

def run(n, imax):
    npl, allg = gens_pe(n)
    bas = {i: basis(n, i) for i in range(0, imax + 3)}
    idx = {i: {m: k for k, m in enumerate(bas[i])} for i in bas}

    print("=" * 74)
    print("n = %d   Omega^i (constant coefficients) as a pe(%d)-module" % (n, n))
    print("=" * 74)
    print("%3s %5s | %-26s | %-26s" % ("i", "dim", "I^i = omega.Omega^{i-2}",
                                       "K^i/I^i (homology)"))

    # images and kernels
    Iim, Ker = {}, {}
    for i in range(imax + 1):
        rows = [to_vec(omega_mul(n, {m: F(1)}), idx[i + 2]) for m in bas[i]]
        # kernel of omega. on Omega^i
        Ker[i] = nullspace([[rows[k][c] for k in range(len(bas[i]))]
                            for c in range(len(bas[i + 2]))], len(bas[i]))
        # image inside Omega^{i+2}
        Iim[i + 2] = [r for r in rref(rows)[0]]
    Iim[0] = []
    Iim[1] = []

    factors = {}
    for i in range(imax + 1):
        d = len(bas[i])
        line = []
        pieces = [("I^i", Iim[i], []),
                  ("K^i/I^i", Ker[i], Iim[i]),
                  ("Om^i/K^i", [e for e in _std(d)], Ker[i])]
        nf = 0
        out = []
        for name, S, T in pieces:
            sq = Sub(n, bas[i], S, T, allg)
            if sq.dim == 0:
                out.append("%s: 0" % name)
                continue
            inv = sq.invariants(npl)
            if len(inv) == 1:
                gen = sq.generated(inv[0], allg)
                ok = "irred" if gen == sq.dim else "NOT irred (gen %d)" % gen
            else:
                ok = "%d invariants!" % len(inv)
            nf += 1
            out.append("%s: dim %d, %d inv, %s" % (name, sq.dim, len(inv), ok))
        factors[i] = nf
        print("%3d %5d | %s" % (i, d, "  |  ".join(out)))
    print("composition factors per degree:",
          {i: factors[i] for i in range(imax + 1)})
    print()


def _std(d):
    out = []
    for k in range(d):
        e = [F(0)] * d
        e[k] = F(1)
        out.append(e)
    return out


if __name__ == "__main__":
    nmax = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    imax = int(sys.argv[2]) if len(sys.argv) > 2 else 6
    for n in range(1, nmax + 1):
        run(n, imax)
