"""
scan.py -- exhaustive search for singular vectors in I(V(lambda)) over le(n).

A singular vector is z in I(V)_m, m > 0, with L_1 z = 0 (hence L_j z = 0 for all j > 0,
since le(n) is generated by L_{-1} + L_0 + L_1) and n_+ z = 0 (Kochetkov normalises
singular vectors to be highest); z is automatically an H-eigenvector because we work
weight space by weight space.

Usage:  python3 scan.py <n> <maxdeg> <box-lo> <box-hi> [height-cutoff]
"""

import sys
from fractions import Fraction as F
from imod import Le, Induced


def weights_of_V(I, ht):
    pe = I.pe
    out, seen, stack = [], set(), [I.lam]
    while stack:
        mu = stack.pop()
        if mu in seen:
            continue
        seen.add(mu)
        nu = tuple(a - b for a, b in zip(I.lam, mu))
        if pe.ht(nu) > ht:
            continue
        if not I.V.wtbasis(mu):
            continue
        out.append(mu)
        for w in pe.nneg_wt:
            stack.append(tuple(a + c for a, c in zip(mu, w)))
    return out


def scan(n, lam, maxdeg=2, ht=6, verbose=False, odd_up=True):
    le = Le(n, odd_up)
    I = Induced(le, lam)
    if not I.V.wtbasis(I.lam):
        return []
    wV = weights_of_V(I, ht)
    found = []
    for m in range(1, maxdeg + 1):
        cand = set()
        for u in I.umonos(m):
            w = I.uwt(u)
            for mu in wV:
                cand.add(tuple(a + b for a, b in zip(mu, w)))
        for nu in sorted(cand, key=lambda t: -I.pe.ht(t)):
            sols = I.singular(m, nu)
            if sols:
                found.append((m, nu, sols))
                if verbose:
                    print('   deg %d weight %s : %d singular vector(s)'
                          % (m, fmtwt(nu), len(sols)))
    return found


def fmtwt(nu):
    return '(' + ','.join(str(x if x.denominator != 1 else x.numerator) for x in nu) + ')'


def fmt(I, sol):
    """render a singular vector in GLS style"""
    n = I.n
    parts = []
    for (u, mu, i), c in sorted(sol.items(), key=lambda kv: (kv[0][0], kv[0][2])):
        a, S = u
        s = ''
        for k in range(n):
            for _ in range(a[k]):
                s += 'd%d' % (k + 1)
        for k in S:
            s += 't%d' % (k + 1)
        parts.append('%s (%s) [%s]#%d' % (fmtc(c), s or '1', fmtwt(mu), i))
    return ' + '.join(parts)


def fmtc(c):
    return str(c.numerator) if c.denominator == 1 else str(c)


def box(n, lo, hi):
    """all dominant integral weights in [lo,hi]^n"""
    out = []

    def rec(i, cur):
        if i == n:
            out.append(tuple(cur))
            return
        top = hi if i == 0 else cur[-1]
        for v in range(lo, top + 1):
            rec(i + 1, cur + [v])

    rec(0, [])
    return out


if __name__ == '__main__':
    n = int(sys.argv[1])
    maxdeg = int(sys.argv[2])
    lo, hi = int(sys.argv[3]), int(sys.argv[4])
    ht = int(sys.argv[5]) if len(sys.argv) > 5 else 6
    odd_up = (len(sys.argv) <= 6 or sys.argv[6] != 'S2')
    print('le(%d): scanning dominant lambda in [%d,%d]^%d, degrees 1..%d, '
          'V-height cutoff %d, Borel %s' % (n, lo, hi, n, maxdeg, ht, 'Lambda2-up' if odd_up else 'S2-up'))
    for lam in box(n, lo, hi):
        res = scan(n, lam, maxdeg, ht, odd_up=odd_up)
        if res:
            le = Le(n, odd_up)
            I = Induced(le, lam)
            for m, nu, sols in res:
                for s in sols:
                    print('lambda=%-14s deg %d  wt %-14s : %s'
                          % (fmtwt(tuple(F(x) for x in lam)), m, fmtwt(nu), fmt(I, s)))
            sys.stdout.flush()
