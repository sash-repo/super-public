# ---------------------------------------------------------------- quaternions

def quaternion_structures(m):
    """J_1, J_2, J_3 on R^{4m} as 4m x 4m integer matrices, acting quadruple by
    quadruple by left multiplication by i, j, k on H = span(1, i, j, k)."""
    N = 4 * m
    #        1     i     j     k        (columns = images of the basis vectors)
    Ji = {   # left multiplication by i:  1->i, i->-1, j->k, k->-j
        0: (1, 1), 1: (0, -1), 2: (3, 1), 3: (2, -1),
    }
    Jj = {   # by j:  1->j, i->-k, j->-1, k->i
        0: (2, 1), 1: (3, -1), 2: (0, -1), 3: (1, 1),
    }
    Jk = {   # by k:  1->k, i->j, j->-i, k->-1
        0: (3, 1), 1: (2, 1), 2: (1, -1), 3: (0, -1),
    }
    out = []
    for tab in (Ji, Jj, Jk):
        M = [[0] * N for _ in range(N)]
        for q in range(m):
            for src, (dst, sgn) in tab.items():
                M[4 * q + dst][4 * q + src] = sgn
        out.append(M)
    return out


def check_quaternion_relations(J):
    """J_a^2 = -1, J_1 J_2 = J_3 = -J_2 J_1."""
    N = len(J[0])

    def mul(A, B):
        return [[sum(A[i][k] * B[k][j] for k in range(N)) for j in range(N)]
                for i in range(N)]

    def minus_id():
        return [[-1 if i == j else 0 for j in range(N)] for i in range(N)]

    ok = all(mul(Ja, Ja) == minus_id() for Ja in J)
    ok = ok and mul(J[0], J[1]) == J[2]
    ok = ok and mul(J[1], J[0]) == [[-v for v in row] for row in J[2]]
    return ok


# ---------------------------------------------------- exterior algebra on R^N

class Ext:
    """Lambda(R^N) with the ONE global order: a basis monomial is a sorted tuple."""

    def __init__(self, N):
        self.N = N
        self.basis = []
        for k in range(N + 1):
            self.basis.extend(combinations(range(N), k))
        self.index = {b: i for i, b in enumerate(self.basis)}
        self.dim = len(self.basis)

    def deg(self, i):
        return len(self.basis[i])

    def wedge_gen(self, i, mono):
        """e_i /\\ mono -> (sign, mono') or None."""
        if i in mono:
            return None
        pos = 0
        for j in mono:
            if j < i:
                pos += 1
            else:
                break
        new = tuple(sorted(mono + (i,)))
        return (-1) ** pos, new

    def contract_gen(self, i, mono):
        """iota_{e_i} mono -> (sign, mono') or None."""
        if i not in mono:
            return None
        pos = mono.index(i)
        new = tuple(x for x in mono if x != i)
        return (-1) ** pos, new


def mat_wedge_form(E, om):
    """Matrix of  omega /\\ .  where omega = sum_{i<j} om[i][j] e_i /\\ e_j."""
    N = E.N
    M = [[0] * E.dim for _ in range(E.dim)]
    for col, mono in enumerate(E.basis):
        for i in range(N):
            for j in range(i + 1, N):
                c = om[i][j]
                if not c:
                    continue
                r = E.wedge_gen(j, mono)
                if r is None:
                    continue
                s1, m1 = r
                r2 = E.wedge_gen(i, m1)
                if r2 is None:
                    continue
                s2, m2 = r2
                M[E.index[m2]][col] += c * s1 * s2
    return M


def transpose(M):
    return [list(row) for row in zip(*M)]


def matmul(A, B):
    n, k, p = len(A), len(B), len(B[0])
    Bt = list(zip(*B))
    return [[sum(A[i][t] * Bt[j][t] for t in range(k)) for j in range(p)]
            for i in range(n)]


def matsub(A, B):
    return [[A[i][j] - B[i][j] for j in range(len(A[0]))] for i in range(len(A))]


def comm(A, B):
    return matsub(matmul(A, B), matmul(B, A))


def is_zero_mat(A):
    return all(not v for row in A for v in row)


def flat(A):
    return [v for row in A for v in row]


# ------------------------------------------------------------ linear algebra

def rank(rows):
    if not rows:
        return 0
    if _rank is not None:
        return _rank([[F(v) for v in r] for r in rows])
    return _rank_pure(rows)


def _rank_pure(rows):
    rows = [[F(v) for v in r] for r in rows]
    piv, r = 0, 0
    ncol = len(rows[0])
    for c in range(ncol):
        p = None
        for i in range(r, len(rows)):
            if rows[i][c]:
                p = i
                break
        if p is None:
            continue
        rows[r], rows[p] = rows[p], rows[r]
        inv = 1 / rows[r][c]
        rows[r] = [v * inv for v in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c]:
                f = rows[i][c]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
        r += 1
        if r == len(rows):
            break
    return r


def span_closure(gens, cap=200):
    """Lie algebra generated by the matrices `gens`, as a list of matrices whose
    flattenings are linearly independent."""
    basis = []
    vecs = []

    def add(M):
        v = [F(x) for x in flat(M)]
        if rank(vecs + [v]) > len(vecs):
            vecs.append(v)
            basis.append(M)
            return True
        return False

    for g in gens:
        add(g)
    changed = True
    while changed and len(basis) < cap:
        changed = False
        cur = list(basis)
        for i in range(len(cur)):
            for j in range(i + 1, len(cur)):
                if add(comm(cur[i], cur[j])):
                    changed = True
    return basis


def killing_rank(basis):
    """Rank of the Killing form of the Lie algebra spanned by `basis`."""
    n = len(basis)
    vecs = [[F(x) for x in flat(B)] for B in basis]

    def coords(M):
        """Write M in the basis: solve  sum c_k vecs[k] = flat(M)."""
        target = [F(x) for x in flat(M)]
        # Gaussian elimination on the augmented transpose
        rows = [list(v) + [F(0)] for v in vecs]
        # build the system  V^T c = target  by elimination over the columns
        A = [[vecs[k][i] for k in range(n)] + [target[i]] for i in range(len(target))]
        r = 0
        piv_col = []
        for c in range(n):
            p = None
            for i in range(r, len(A)):
                if A[i][c]:
                    p = i
                    break
            if p is None:
                continue
            A[r], A[p] = A[p], A[r]
            inv = 1 / A[r][c]
            A[r] = [v * inv for v in A[r]]
            for i in range(len(A)):
                if i != r and A[i][c]:
                    f = A[i][c]
                    A[i] = [a - f * b for a, b in zip(A[i], A[r])]
            piv_col.append(c)
            r += 1
        c = [F(0)] * n
        for i, cc in enumerate(piv_col):
            c[cc] = A[i][n]
        return c

    # structure constants
    ad = []
    for i in range(n):
        Mi = [[F(0)] * n for _ in range(n)]
        for j in range(n):
            cij = coords(comm(basis[i], basis[j]))
            for k in range(n):
                Mi[k][j] = cij[k]
        ad.append(Mi)

    K = [[F(0)] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            P = matmul(ad[i], ad[j])
            K[i][j] = sum(P[t][t] for t in range(n))
    return rank(K)


# ================================================================= part A / B

def part_AB(m, verbose=True):
    N = 4 * m
    J = quaternion_structures(m)
    assert check_quaternion_relations(J), "quaternion relations fail"
    E = Ext(N)

    # h = the Euclidean form (identity Gram matrix), omega_a(u,v) = h(J_a u, v),
    # so the Gram matrix of omega_a is J_a^T = -J_a: antisymmetric, as it must be.
    OM = [[[-J[a][i][j] for j in range(N)] for i in range(N)] for a in range(3)]
    for a in range(3):
        for i in range(N):
            for j in range(N):
                assert OM[a][i][j] == -OM[a][j][i], "omega_a not antisymmetric"

    Xp = [mat_wedge_form(E, OM[a]) for a in range(3)]
    Xm = [transpose(M) for M in Xp]           # adjoint w.r.t. the monomial basis

    gens = Xp + Xm
    alg = span_closure(gens)
    kr = killing_rank(alg)

    if verbose:
        print(f"  [A] m={m}  (R^{N}, dim Lambda = {E.dim})")
        print(f"      dim <X_a^+, X_a^- : a=1,2,3>_Lie = {len(alg)}"
              f"   (sp(4) has dim 10)")
        print(f"      rank of the Killing form         = {kr}"
              f"   ({'nondegenerate: semisimple' if kr == len(alg) else 'degenerate'})")
        # H_a = [X_a^+, X_a^-] should be (deg - 2m) for every a
        okH = True
        for a in range(3):
            Ha = comm(Xp[a], Xm[a])
            for i in range(E.dim):
                for j in range(E.dim):
                    want = (E.deg(i) - 2 * m) if i == j else 0
                    if Ha[i][j] != want:
                        okH = False
        print(f"      [X_a^+, X_a^-] = deg - {2*m} for a=1,2,3: {okH}")

    # ---- B: (D4.16) uses two of the three X_a^-
    if verbose:
        print(f"  [B] ker X_1^- (^) ker X_2^-  versus  (^) ker X_3^-, by degree:")
    same = True
    for d in range(N + 1):
        idx = [i for i in range(E.dim) if E.deg(i) == d]
        if not idx:
            continue

        def ker_dims(ops):
            rows = []
            for M in ops:
                for r in range(E.dim):
                    rows.append([F(M[r][c]) for c in idx])
            rk = rank(rows) if rows else 0
            return len(idx) - rk

        d12 = ker_dims([Xm[0], Xm[1]])
        d123 = ker_dims([Xm[0], Xm[1], Xm[2]])
        if d12 != d123:
            same = False
        if verbose:
            print(f"      i={d:2d}:  dim Omega^i={len(idx):4d}   "
                  f"dim P^i (two) = {d12:4d}   (three) = {d123:4d}"
                  f"   {'=' if d12 == d123 else 'DIFFER'}")
    if verbose:
        print(f"      ker X_1^- (^) ker X_2^- (=) ker X_3^- : {same}")
    return len(alg), kr, same


# ==================================================================== part C/D
#
# Twisted forms: Omega_h = C[x_1..x_N] (x) Lambda(xhat_1..xhat_N), truncated by
# polynomial degree.  A vector is a dict {(xmono, formmono): coeff}, xmono a tuple
# of exponents, formmono a sorted tuple.

class Twisted:
    def __init__(self, N, pdeg):
        self.N, self.pdeg = N, pdeg
        self.E = Ext(N)
        self.xmonos = []
        self._gen_x([0] * N, 0, 0)
        self.basis = [(xm, fm) for xm in self.xmonos for fm in self.E.basis]
        self.index = {b: i for i, b in enumerate(self.basis)}

    def _gen_x(self, cur, pos, tot):
        if pos == self.N:
            self.xmonos.append(tuple(cur))
            return
        for e in range(self.pdeg - tot + 1):
            cur[pos] = e
            self._gen_x(cur, pos + 1, tot + e)
        cur[pos] = 0


def tw_apply_d(T, vec):
    """d = sum xhat_i d/dx_i."""
    out = {}
    for (xm, fm), c in vec.items():
        for i in range(T.N):
            if xm[i] == 0:
                continue
            r = T.E.wedge_gen(i, fm)
            if r is None:
                continue
            s, nf = r
            nx = list(xm)
            nx[i] -= 1
            k = (tuple(nx), nf)
            out[k] = out.get(k, F(0)) + c * xm[i] * s
    return {k: v for k, v in out.items() if v}


def tw_apply_theta(T, om, vec, half=True):
    """multiplication by theta = 1/2 sum_{i,j} om[i][j] x_i xhat_j."""
    out = {}
    fac = F(1, 2) if half else F(1)
    for (xm, fm), c in vec.items():
        for i in range(T.N):
            for j in range(T.N):
                a = om[i][j]
                if not a:
                    continue
                r = T.E.wedge_gen(j, fm)
                if r is None:
                    continue
                s, nf = r
                nx = list(xm)
                nx[i] += 1
                if sum(nx) > T.pdeg:
                    continue
                k = (tuple(nx), nf)
                out[k] = out.get(k, F(0)) + c * fac * a * s
    return {k: v for k, v in out.items() if v}


def tw_apply_mat(T, M, vec):
    """apply a matrix acting on the Lambda factor alone (X^+ or X^-)."""
    out = {}
    for (xm, fm), c in vec.items():
        col = T.E.index[fm]
        for r in range(T.E.dim):
            a = M[r][col]
            if a:
                k = (xm, T.E.basis[r])
                out[k] = out.get(k, F(0)) + c * a
    return {k: v for k, v in out.items() if v}


class TOp:
    """an operator on the truncated twisted forms, stored by its action on the basis"""

    def __init__(self, T, fn=None, cols=None, parity=1):
        self.T, self.parity = T, parity
        if cols is None:
            cols = [fn({b: F(1)}) for b in T.basis]
        self.cols = cols

    def vec(self):
        v = []
        for col in self.cols:
            row = [F(0)] * len(self.T.basis)
            for k, c in col.items():
                if k in self.T.index:
                    row[self.T.index[k]] = c
            v.extend(row)
        return v

    def compose(self, other):
        """self o other"""
        cols = []
        for col in other.cols:
            acc = {}
            for k, c in col.items():
                if k not in self.T.index:
                    continue
                for k2, c2 in self.cols[self.T.index[k]].items():
                    acc[k2] = acc.get(k2, F(0)) + c * c2
            cols.append({k: v for k, v in acc.items() if v})
        return TOp(self.T, cols=cols, parity=(self.parity + other.parity) % 2)

    def bracket(self, other):
        A = self.compose(other)
        B = other.compose(self)
        sgn = -1 if (self.parity and other.parity) else 1
        cols = []
        for ca, cb in zip(A.cols, B.cols):
            acc = dict(ca)
            for k, v in cb.items():
                acc[k] = acc.get(k, F(0)) - sgn * v
            cols.append({k: v for k, v in acc.items() if v})
        return TOp(self.T, cols=cols, parity=(self.parity + other.parity) % 2)


def part_CD(m=1, pdeg=2, hbars=(F(1), F(1)), verbose=True):
    N = 4 * m
    J = quaternion_structures(m)
    E = Ext(N)
    OM = [[[-J[a][i][j] for j in range(N)] for i in range(N)] for a in range(3)]
    Xp = [mat_wedge_form(E, OM[a]) for a in range(3)]
    Xm = [transpose(M) for M in Xp]

    T = Twisted(N, pdeg)
    h1, h2 = hbars

    def mk_D(a, h):
        om = OM[a]
        return TOp(T, fn=lambda v: _add(tw_apply_d(T, v),
                                        tw_apply_theta(T, om, v), h), parity=1)

    def _add(u, w, c):
        out = dict(u)
        for k, val in w.items():
            out[k] = out.get(k, F(0)) + c * val
        return {k: v for k, v in out.items() if v}

    Dp = [mk_D(0, h1), mk_D(1, h2)]
    XP = [TOp(T, fn=lambda v, M=Xp[a]: tw_apply_mat(T, M, v), parity=0)
          for a in range(3)]
    XM = [TOp(T, fn=lambda v, M=Xm[a]: tw_apply_mat(T, M, v), parity=0)
          for a in range(3)]
    Dm = [XM[a].bracket(Dp[a]) for a in range(2)]

    # relation [D_a^+, D_a^+] = 2 h_a X_a^+
    rel = []
    for a, h in ((0, h1), (1, h2)):
        lhs = Dp[a].bracket(Dp[a]).vec()
        rhs = [2 * h * x for x in XP[a].vec()]
        rel.append(lhs == rhs)

    gens = Dp + Dm
    basis, par = _sclosure(gens)
    ev = sum(1 for p in par if p == 0)
    od = sum(1 for p in par if p == 1)

    if verbose:
        print(f"  [C] m={m}, pdeg={pdeg}, hbar=({h1},{h2})")
        print(f"      [D_a^+, D_a^+] = 2 hbar_a X_a^+ for a=1,2: {rel}")
        print(f"      sdim <D_1^+-, D_2^+->_Lie = ({ev}|{od})"
              f"   (osp(1|4) has sdim (10|4))")

    # ---- D: the untwisted limit
    T0 = Twisted(N, pdeg)
    d0 = TOp(T0, fn=lambda v: tw_apply_d(T0, v), parity=1)
    XM0 = [TOp(T0, fn=lambda v, M=Xm[a]: tw_apply_mat(T0, M, v), parity=0)
           for a in range(3)]
    XP0 = [TOp(T0, fn=lambda v, M=Xp[a]: tw_apply_mat(T0, M, v), parity=0)
           for a in range(3)]
    odd0 = [d0] + [XM0[a].bracket(d0) for a in range(3)]
    odd0 += [XP0[a].bracket(o) for a in range(3) for o in [d0]]
    b0, p0 = _sclosure(odd0)
    if verbose:
        e0 = sum(1 for p in p0 if p == 0)
        o0 = sum(1 for p in p0 if p == 1)
        print(f"  [D] hbar = 0: sdim <d, [X_a^-,d], [X_a^+,d]>_Lie = ({e0}|{o0})"
              f"   (hei(0|8) has sdim (1|8))")
    return rel, (ev, od)


def _sclosure(gens, cap=60):
    basis, vecs, par = [], [], []

    def add(op):
        v = op.vec()
        if not any(v):
            return False
        if rank(vecs + [v]) > len(vecs):
            vecs.append(v)
            basis.append(op)
            par.append(op.parity)
            return True
        return False

    for g in gens:
        add(g)
    changed = True
    while changed and len(basis) < cap:
        changed = False
        cur = list(basis)
        for i in range(len(cur)):
            for j in range(i, len(cur)):
                if add(cur[i].bracket(cur[j])):
                    changed = True
    return basis, par


def main():
    m = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    print("hyper-Kaehler flat model: Verbitsky's sp(4) and Berezin (D4.16)/(D4.17)")
    print()
    for mm in range(1, m + 1):
        part_AB(mm)
        print()
    part_CD(m=1, pdeg=2)


