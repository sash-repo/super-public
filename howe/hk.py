#!/usr/bin/env python3
"""Exact engine for the hyper-Kaehler section: the guiding example is
(D4.16) on p.278 of [Ber], where [Ber] is
Berezin, Vvedenie v superanaliz, 2nd ed. (MCCME 2013), Appendix D4 (Leites's own),
Subsec. 4.3.  There

    (D4.16)   P^i     = ker X_1^- (^) ker X_2^- (^) Omega^i,
    (D4.17)   sqrt(P^i_h) = ker D_1^- (^) ker D_2^- (^) Omega^i_h,   D_a^+ = nabla_a,

and the text says: "the operators D_a^- and D_a^+ = [X_a^+, D_a^-] generate the Lie
superalgebra osp(1|4)".

What is checked here, in exact arithmetic over Q, in the flat model H^m = R^{4m}:

  A.  The six operators X_a^+ (multiplication by omega_a) and X_a^- (its adjoint),
      a = 1,2,3, generate a 10-dimensional simple Lie algebra on Lambda(R^{4m}) --
      i.e. sp(4) = o(5), which is Verbitsky's algebra.  Simplicity is decided, not
      assumed: the Killing form is computed and its rank taken.

  B.  (D4.16) uses TWO of the three X_a^-, not three.  The claim implicit in that is
      ker X_1^- (^) ker X_2^- (=) ker X_3^-; it is verified degree by degree.
      (The reason: X_3^- is in the Lie algebra generated by the first two.)

  C.  Twisting.  On Omega_h = C[x] (x) Lambda(xhat) put

          theta_a = 1/2 sum_{i,j} (omega_a)_{ij} x_i xhat_j,      d theta_a = omega_a,
          D_a^+  = d + h_a theta_a . ,     D_a^- = [X_a^-, D_a^+],

      so that [D_a^+, D_a^+] = 2 h_a X_a^+.  The four odd operators D_1^+-, D_2^+-
      close, together with their brackets, into a Lie superalgebra of sdim (10|4)
      whose even part is the sp(4) of A -- i.e. osp(1|4), as (D4.17) says.

  D.  The untwisted limit h = 0: the eight odd operators d, d_a := [X_a^-, d] and
      their adjoints span, with the identity, hei(0|8) -- the algebra [LKae] gives
      for the even hyper-Kaehler case.

Usage:  python3 hk.py [m]           
"""
