#!/usr/bin/env python3
"""
ortho24.py -- how widespread the non-classical restrictedness of [BLLS, Sec. 2] is.

Question: does the non-classical restrictedness occur in one case only?  The
answer is no.  Everything is exact, over F_2 and F_4 (characteristic 2).

Part A.  The series o^(1)(2n+1) of [BLLS, Subsec. 2.6.1, Example 1] in its matrix
         form, for n = 1, 2, 3:
             ( A  X  B )
             ( Y^T 0 X^T ),   A in gl(n);  B, C symmetric with zero diagonal;
             ( C  Y  A^T )    X, Y column vectors.
         Checked: the space is closed under the commutator (so it is a Lie algebra
         of characteristic 2, [u,u] = 0 being automatic in a matrix realization);
         Z/2-grading g_+ = {X = Y = 0}, g_- = {A = B = C = 0};
         g_+ is closed under the matrix square and g_- under the fourth power;
         no 2-structure on g (Jacobson's criterion: some (ad_x)^2 is not inner);
         a (2,4)-structure exists, with [2] = matrix square and [4] = 4th power;
         the additivity rule of Lemma 9.4 holds on all pairs of g_-.

Part B.  Simplicity of o^(1)(2n+1) for n = 1, 2 over F_2 (exhaustive over the
         nonzero elements: the ideal generated by each one is the whole algebra).

Part C.  The (2,-)-example of [BLLS, Subsec. 2.6.1, Example 3]: g = <a_n (n in Z), b>
         with [b,a_n] = a_{n-1}.  Verified in the finite quotient by the ideal
         <a_n | n < -N> (a genuine quotient, hence a genuine example): a (2,-)-structure
         exists, no 2-structure exists, and b has no [4].

Usage:  python ortho24.py
"""

from itertools import product
import sys

LOG = []


def out(s=""):
    print(s)
    LOG.append(s)


def show(title):
    out()
    out("=" * 78)
    out(title)
    out("=" * 78)


# ---------------------------------------------------------------------------
# F_2 and F_4 = F_2[w]/(w^2+w+1); elements 0, 1, 2 = w, 3 = w+1
# ---------------------------------------------------------------------------

class GF:
    def __init__(self, q):
        assert q in (2, 4)
        self.q = q
        self.els = list(range(q))
        if q == 2:
            self._mul = [[0, 0], [0, 1]]
        else:
            self._mul = [[0, 0, 0, 0],
                         [0, 1, 2, 3],
                         [0, 2, 3, 1],
                         [0, 3, 1, 2]]
        self.name = "F_%d" % q

    def add(self, a, b):
        return a ^ b

    def mul(self, a, b):
        return self._mul[a][b]

    def inv(self, a):
        assert a
        for b in self.els:
            if self.mul(a, b) == 1:
                return b


# ---------------------------------------------------------------------------
# matrices over GF, as tuples of tuples
# ---------------------------------------------------------------------------

def mzero(F, m):
    return tuple(tuple(0 for _ in range(m)) for _ in range(m))


def madd(F, a, b):
    return tuple(tuple(F.add(x, y) for x, y in zip(ra, rb)) for ra, rb in zip(a, b))


def mscal(F, c, a):
    return tuple(tuple(F.mul(c, x) for x in r) for r in a)


def mmul(F, a, b):
    m = len(a)
    return tuple(tuple(
        _dot(F, a[i], [b[k][j] for k in range(m)]) for j in range(m))
        for i in range(m))


def _dot(F, u, v):
    s = 0
    for x, y in zip(u, v):
        if x and y:
            s = F.add(s, F.mul(x, y))
    return s


def mcomm(F, a, b):
    """[a,b] = ab + ba (characteristic 2)."""
    return madd(F, mmul(F, a, b), mmul(F, b, a))


def mpow(F, a, k):
    r = a
    for _ in range(k - 1):
        r = mmul(F, r, a)
    return r


def flat(a):
    return tuple(x for r in a for x in r)


# ---------------------------------------------------------------------------
# linear algebra over GF: row reduction on flattened matrices
# ---------------------------------------------------------------------------

def rref(F, rows):
    rows = [list(r) for r in rows if any(r)]
    if not rows:
        return []
    ncol = len(rows[0])
    piv = 0
    for col in range(ncol):
        sel = None
        for r in range(piv, len(rows)):
            if rows[r][col]:
                sel = r
                break
        if sel is None:
            continue
        rows[piv], rows[sel] = rows[sel], rows[piv]
        c = F.inv(rows[piv][col])
        rows[piv] = [F.mul(c, x) for x in rows[piv]]
        for r in range(len(rows)):
            if r != piv and rows[r][col]:
                f = rows[r][col]
                rows[r] = [F.add(x, F.mul(f, y)) for x, y in zip(rows[r], rows[piv])]
        piv += 1
        if piv == len(rows):
            break
    return [tuple(r) for r in rows[:piv] if any(r)]


def rank(F, rows):
    return len(rref(F, rows))


def in_span(F, basis, v):
    if not any(v):
        return True
    return rank(F, list(basis) + [v]) == rank(F, list(basis))


# ---------------------------------------------------------------------------
# Part A: the series o^(1)(2n+1)
# ---------------------------------------------------------------------------

def o_basis(F, n):
    """Basis of o^(1)(2n+1) in the matrix form of [BLLS, 2.6.1], split by degree.

    Returns (plus, minus): lists of matrices of size m = 2n+1.
    """
    m = 2 * n + 1

    def emb(A=None, X=None, B=None, Y=None, C=None):
        M = [[0] * m for _ in range(m)]
        if A is not None:
            for i in range(n):
                for j in range(n):
                    M[i][j] = A[i][j]
                    M[n + 1 + i][n + 1 + j] = A[j][i]        # A^T in the SE block
        if B is not None:
            for i in range(n):
                for j in range(n):
                    M[i][n + 1 + j] = B[i][j]
        if C is not None:
            for i in range(n):
                for j in range(n):
                    M[n + 1 + i][j] = C[i][j]
        if X is not None:
            for i in range(n):
                M[i][n] = X[i]                                # column X
                M[n][n + 1 + i] = X[i]                        # row X^T
        if Y is not None:
            for i in range(n):
                M[n][i] = Y[i]                                # row Y^T
                M[n + 1 + i][n] = Y[i]                        # column Y
        return tuple(tuple(r) for r in M)

    def unit(i, j):
        A = [[0] * n for _ in range(n)]
        A[i][j] = 1
        return A

    plus = []
    for i in range(n):
        for j in range(n):
            plus.append(emb(A=unit(i, j)))
    for i in range(n):
        for j in range(i + 1, n):                              # symmetric, zero diagonal
            S = [[0] * n for _ in range(n)]
            S[i][j] = S[j][i] = 1
            plus.append(emb(B=S))
            plus.append(emb(C=S))
    minus = []
    for i in range(n):
        e = [0] * n
        e[i] = 1
        minus.append(emb(X=e))
        minus.append(emb(Y=e))
    return plus, minus


def span_elements(F, basis):
    """All elements of the span (only used for small dimensions)."""
    els = []
    for coeffs in product(F.els, repeat=len(basis)):
        M = mzero(F, len(basis[0]))
        for c, b in zip(coeffs, basis):
            if c:
                M = madd(F, M, mscal(F, c, b))
        els.append(M)
    return els


def ad_matrix(F, basis, x):
    """The matrix of ad_x in the given basis, as a list of image coordinate rows;
    returns None if some image leaves the span (should not happen)."""
    rows = [flat(b) for b in basis]
    R = rref(F, rows)
    out_rows = []
    for b in basis:
        img = flat(mcomm(F, x, b))
        c = coords(F, rows, img)
        if c is None:
            return None
        out_rows.append(c)
    return out_rows


def coords(F, rows, v):
    """Coordinates of v in terms of the (independent) rows, or None."""
    n = len(rows)
    # solve  sum c_i rows[i] = v
    aug = [list(rows[i]) + [1 if j == i else 0 for j in range(n)] for i in range(n)]
    ncol = len(rows[0])
    piv_cols = []
    piv = 0
    for col in range(ncol):
        sel = None
        for r in range(piv, n):
            if aug[r][col]:
                sel = r
                break
        if sel is None:
            continue
        aug[piv], aug[sel] = aug[sel], aug[piv]
        c = F.inv(aug[piv][col])
        aug[piv] = [F.mul(c, x) for x in aug[piv]]
        for r in range(n):
            if r != piv and aug[r][col]:
                f = aug[r][col]
                aug[r] = [F.add(x, F.mul(f, y)) for x, y in zip(aug[r], aug[piv])]
        piv_cols.append(col)
        piv += 1
        if piv == n:
            break
    w = list(v)
    c = [0] * n
    for i, col in enumerate(piv_cols):
        f = w[col]
        if f:
            for j in range(ncol):
                w[j] = F.add(w[j], F.mul(f, aug[i][j]))
            for j in range(n):
                c[j] = F.add(c[j], F.mul(f, aug[i][ncol + j]))
    if any(w):
        return None
    return tuple(c)


def part_A(F, n):
    plus, minus = o_basis(F, n)
    basis = plus + minus
    m = 2 * n + 1
    dim = len(basis)
    out("o^(1)(%d) over %s: dim = %d  (g_+ %d, g_- %d), matrices %dx%d"
        % (m, F.name, dim, len(plus), len(minus), m, m))
    assert dim == 2 * n * n + n, dim

    rows = [flat(b) for b in basis]
    assert rank(F, rows) == dim, "the listed matrices are not independent"

    # 1) closed under the commutator, and the Z/2-grading
    bad = 0
    grading_ok = True
    for i, u in enumerate(basis):
        for j, v in enumerate(basis):
            c = flat(mcomm(F, u, v))
            if not in_span(F, rows, c):
                bad += 1
            else:
                du = 0 if i < len(plus) else 1
                dv = 0 if j < len(plus) else 1
                tgt = [flat(b) for b in (plus if (du + dv) % 2 == 0 else minus)]
                if not in_span(F, tgt, c):
                    grading_ok = False
    out("  closed under [.,.]:                       %s (%d failures)"
        % ("YES" if bad == 0 else "NO", bad))
    out("  Z/2-grading g_+ + g_- (deg additive):     %s" % ("YES" if grading_ok else "NO"))
    if bad:
        return None

    # 2) squares of g_+ and fourth powers of g_-
    pls = span_elements(F, plus) if len(plus) <= 8 else None
    mns = span_elements(F, minus)
    prows = [flat(b) for b in plus]
    sq_ok = True
    if pls is not None:
        for M in pls:
            if not in_span(F, prows, flat(mmul(F, M, M))):
                sq_ok = False
        out("  M^2 in g_+ for all %d elements of g_+:    %s"
            % (len(pls), "YES" if sq_ok else "NO"))
    else:
        for M in plus:                     # basis + a sample of sums
            if not in_span(F, prows, flat(mmul(F, M, M))):
                sq_ok = False
        for i in range(len(plus)):
            for j in range(i + 1, len(plus)):
                M = madd(F, plus[i], plus[j])
                if not in_span(F, prows, flat(mmul(F, M, M))):
                    sq_ok = False
        out("  M^2 in g_+ (basis and all pairwise sums): %s" % ("YES" if sq_ok else "NO"))

    p4_ok = all(in_span(F, prows, flat(mpow(F, M, 4))) for M in mns)
    out("  M^4 in g_+ for all %d elements of g_-:    %s"
        % (len(mns), "YES" if p4_ok else "NO"))

    # 3) no 2-structure: some (ad_x)^2 is not inner
    ad_of = {}
    for b in basis:
        A = ad_matrix(F, basis, b)
        assert A is not None
        ad_of[flat(b)] = A
    inner_rows = [tuple(x for r in ad_of[flat(b)] for x in r) for b in basis]

    def ad_sq_flat(x):
        A = ad_matrix(F, basis, x)
        # square of the operator: apply twice
        sq = []
        for b in basis:
            img = mcomm(F, x, mcomm(F, x, b))
            sq.append(coords(F, rows, flat(img)))
        return tuple(x for r in sq for x in r)

    non_inner = []
    for b in minus:                                   # the odd-degree part is where it fails
        if not in_span(F, inner_rows, ad_sq_flat(b)):
            non_inner.append(b)
    out("  (ad_x)^2 NOT inner for %d of the %d basis vectors of g_-  ==>  no 2-structure: %s"
        % (len(non_inner), len(minus), "YES" if non_inner else "NO"))

    # also: is the square of an element of g_- even in g?
    outside = sum(1 for M in mns if not in_span(F, rows, flat(mmul(F, M, M))))
    out("  x^2 (matrix square) outside g for %d of the %d elements of g_-" % (outside, len(mns)))

    # 3a) the centralizer of g inside gl(2n+1): if it is K*I, the failure above is
    #     a statement about all of g, not only about the candidate x^2
    unknown = [(i, j) for i in range(m) for j in range(m)]
    eqs = []
    for b in basis:
        for r in range(m):
            for c in range(m):
                row = [0] * len(unknown)
                for t, (i, j) in enumerate(unknown):
                    v = 0
                    if i == r:
                        v = F.add(v, b[j][c])          # (ZB)_{rc} coefficient of Z_{rj}
                    if j == c:
                        v = F.add(v, b[r][i])          # (BZ)_{rc} coefficient of Z_{ic}
                    row[t] = v
                if any(row):
                    eqs.append(tuple(row))
    cent = len(unknown) - rank(F, eqs)
    out("  dim of the centralizer of g in gl(%d):     %d  (the scalars alone would be 1)"
        % (m, cent))

    # 4) the (2,4)-structure: ad-conditions
    c2 = c4 = True
    src = pls if pls is not None else plus
    for M in src:
        S = mmul(F, M, M)
        for b in basis:
            if mcomm(F, S, b) != mcomm(F, M, mcomm(F, M, b)):
                c2 = False
    for M in mns:
        P = mpow(F, M, 4)
        for b in basis:
            t = b
            for _ in range(4):
                t = mcomm(F, M, t)
            if mcomm(F, P, b) != t:
                c4 = False
    out("  ad_{x^[2]} = (ad_x)^2 on g_+:              %s" % ("YES" if c2 else "NO"))
    out("  ad_{x^[4]} = (ad_x)^4 on g_-:              %s" % ("YES" if c4 else "NO"))

    # 5) the additivity rule of Lemma 9.4, on all pairs of g_-
    ok = 0
    fail = 0
    for x in mns:
        for y in mns:
            lhs = mpow(F, madd(F, x, y), 4)
            xy = mcomm(F, x, y)
            s = madd(F, mcomm(F, x, mcomm(F, x, mcomm(F, x, y))),
                     mcomm(F, y, mcomm(F, y, mcomm(F, y, x))))
            s = madd(F, s, mcomm(F, x, mcomm(F, y, xy)))
            s = madd(F, s, mmul(F, xy, xy))
            rhs = madd(F, madd(F, mpow(F, x, 4), mpow(F, y, 4)), s)
            if lhs == rhs:
                ok += 1
            else:
                fail += 1
    out("  additivity rule (Lemma 9.4) on all %d pairs of g_-:  %d hold, %d fail"
        % (ok + fail, ok, fail))

    # semilinearity (ax)^[4] = a^4 x^[4]
    semi = True
    for a in F.els:
        a4 = F.mul(F.mul(a, a), F.mul(a, a))
        for M in mns:
            if mpow(F, mscal(F, a, M), 4) != mscal(F, a4, mpow(F, M, 4)):
                semi = False
    out("  semilinearity (ax)^[4] = a^4 x^[4]:        %s" % ("YES" if semi else "NO"))

    return dict(dim=dim, non_inner=len(non_inner), add_fail=fail)


