# Part B: simplicity
# ---------------------------------------------------------------------------

def ideal_of(F, basis, rows, x):
    """The ideal generated by x, as an rref basis of flattened matrices."""
    cur = rref(F, [flat(x)])
    while True:
        new = list(cur)
        for r in cur:
            M = unflatten(r, len(basis[0]))
            for b in basis:
                new.append(flat(mcomm(F, b, M)))
        nxt = rref(F, new)
        if len(nxt) == len(cur):
            return cur
        cur = nxt


def unflatten(r, m):
    return tuple(tuple(r[i * m:(i + 1) * m]) for i in range(m))


def part_B(F, n):
    plus, minus = o_basis(F, n)
    basis = plus + minus
    rows = [flat(b) for b in basis]
    dim = len(basis)
    els = span_elements(F, basis)
    bad = 0
    for M in els:
        if not any(flat(M)):
            continue
        if len(ideal_of(F, basis, rows, M)) != dim:
            bad += 1
    out("o^(1)(%d) over %s: of the %d nonzero elements, %d generate a PROPER ideal  ==> %s"
        % (2 * n + 1, F.name, len(els) - 1, bad, "SIMPLE" if bad == 0 else "NOT simple"))
    return bad == 0


# ---------------------------------------------------------------------------
# Part C: the (2,-)-example of [BLLS, 2.6.1, Example 3]
# ---------------------------------------------------------------------------

def part_C(F, N=6):
    """g = <a_{-N}, ..., a_N, b>, [b,a_n] = a_{n-1} (a_{-N-1} := 0), [a_m,a_n] = 0.

    This is the quotient of [BLLS]'s g by the ideal <a_n | n < -N>, so anything
    verified here about the non-existence of b^{[2]}, b^{[4]} is a statement about
    a genuine Lie algebra of characteristic 2.
    """
    idx = list(range(-N, N + 1))
    names = ["a%d" % k for k in idx] + ["b"]
    dim = len(names)
    B = len(names) - 1                       # position of b
    pos = {k: i for i, k in enumerate(idx)}

    def br(i, j):
        """[e_i, e_j] as a coordinate tuple."""
        v = [0] * dim
        if i == j:
            return tuple(v)
        if i == B or j == B:
            k = idx[j if i == B else i]
            if k - 1 in pos:
                v[pos[k - 1]] = 1
        return tuple(v)

    def bracket(u, w):
        v = [0] * dim
        for i in range(dim):
            if not u[i]:
                continue
            for j in range(dim):
                if not w[j]:
                    continue
                c = F.mul(u[i], w[j])
                for t, x in enumerate(br(i, j)):
                    if x:
                        v[t] = F.add(v[t], F.mul(c, x))
        return tuple(v)

    e = [tuple(1 if j == i else 0 for j in range(dim)) for i in range(dim)]

    # Jacobi
    jac = True
    for i in range(dim):
        for j in range(dim):
            for k in range(dim):
                s = [0] * dim
                for a, b_, c in ((i, j, k), (j, k, i), (k, i, j)):
                    t = bracket(bracket(e[a], e[b_]), e[c])
                    s = [F.add(x, y) for x, y in zip(s, t)]
                if any(s):
                    jac = False
    out("  Jacobi identity in the quotient (N = %d, dim %d): %s" % (N, dim, "YES" if jac else "NO"))

    gplus = [e[pos[k]] for k in idx if k % 2 == 0]            # deg a_n = n mod 2
    gminus = [e[pos[k]] for k in idx if k % 2 != 0] + [e[B]]  # deg b = 1

    # (2,-)-structure: x^[2] = 0 on g_+ works, since (ad_x)^2 = 0 there
    ok = True
    for x in gplus:
        for y in e:
            if any(bracket(x, bracket(x, y))):
                ok = False
    out("  (ad_x)^2 = 0 for every basis vector of g_+  ==>  [2] = 0 is a (2,-)-structure: %s"
        % ("YES" if ok else "NO"))

    # no 2-structure on the whole g: b^[2] would have to satisfy ad = (ad_b)^2
    adrows = [tuple(x for y in e for x in bracket(u, y)) for u in e]
    sq_b = tuple(x for y in e for x in bracket(e[B], bracket(e[B], y)))
    inner2 = in_span(F, adrows, sq_b)
    out("  (ad_b)^2 inner?  %s   ==>  no 2-structure on g: %s"
        % ("yes" if inner2 else "NO", "NO" if inner2 else "YES"))

    # b has no [4]: (ad_b)^4 is not ad_u for any u in g_+  (nor for any u in g at all)
    q4 = tuple(x for y in e for x in
               bracket(e[B], bracket(e[B], bracket(e[B], bracket(e[B], y)))))
    plusrows = [tuple(x for y in e for x in bracket(u, y)) for u in gplus]
    in_plus = in_span(F, plusrows, q4)
    in_all = in_span(F, adrows, q4)
    out("  (ad_b)^4 = ad_u for some u in g_+?  %s ;  for some u in g at all?  %s"
        % ("yes" if in_plus else "NO", "yes" if in_all else "NO"))
    out("  ==>  b has no [4]: %s  (so g has a (2,-)-structure but no (2,4)-structure)"
        % ("YES" if not in_plus else "no"))
    return (not inner2) and (not in_plus) and ok and jac


# ---------------------------------------------------------------------------

def main():
    show("PART A.  the series o^(1)(2n+1) of [BLLS, 2.6.1, Example 1]")
    res = {}
    for q in (2, 4):
        F = GF(q)
        for n in (1, 2, 3):
            if q == 4 and n == 3:
                continue                      # 4^6 = 4096 elements of g_-: skipped for time
            out()
            res[(q, n)] = part_A(F, n)

    show("PART B.  simplicity (exhaustive over the nonzero elements, F_2)")
    for n in (1, 2):
        part_B(GF(2), n)

    show("PART C.  [BLLS, 2.6.1, Example 3]: a (2,-)-structure with no (2,4)-structure")
    part_C(GF(2), N=6)

    show("SUMMARY")
    out("The non-classical restrictedness is not one case: o^(1)(2n+1) has a")
    out("(2,4)-structure and no 2-structure for every n >= 1, verified for n = 1, 2, 3.")
    with open("ortho24.log", "w") as f:
        f.write("\n".join(LOG) + "\n")


if __name__ == "__main__":
    main()
