class Tensor:
    """T(V) = free associative superalgebra; words are tuples of generator indices."""

    def __init__(self, par, D):
        self.par = list(par)
        self.n = len(par)
        self.D = D
        self.words = {}
        for d in range(1, D + 1):
            for m in mdegs(self.n, d):
                ws = [w for w in product(range(self.n), repeat=d)
                      if all(w.count(i) == m[i] for i in range(self.n))]
                if ws:
                    self.words[m] = ws
        self.index = {m: {w: i for i, w in enumerate(ws)} for m, ws in self.words.items()}

    def parity(self, m):
        return sum(a * b for a, b in zip(m, self.par)) % 2

    def mul(self, x, y):
        """Concatenation product of two vectors (dicts word -> coeff)."""
        out = {}
        for u, a in x.items():
            for v, b in y.items():
                w = u + v
                out[w] = out.get(w, 0) + a * b
        return {w: c for w, c in out.items() if c}

    def bracket(self, x, mx, y, my, p=None):
        s = 1 if (self.parity(mx) * self.parity(my)) % 2 == 0 else -1
        out = self.mul(x, y)
        for w, c in self.mul(y, x).items():
            out[w] = out.get(w, 0) - s * c
        if p:
            out = {w: c % p for w, c in out.items()}
        return {w: c for w, c in out.items() if c}

    # -- the Lie sub-superalgebra generated by V ---------------------------

    def lie(self, p=None):
        """Basis of L_T(V) per multidegree, as row-reduced vectors."""
        L = {}
        for i in range(self.n):
            e = tuple(1 if j == i else 0 for j in range(self.n))
            L[e] = [{(i,): 1}]
        for d in range(2, self.D + 1):
            for m in mdegs(self.n, d):
                if m not in self.words:
                    continue
                gens = []
                for m1, m2 in splits(m):
                    for x in L.get(m1, []):
                        for y in L.get(m2, []):
                            b = self.bracket(x, m1, y, m2, p)
                            if b:
                                gens.append(b)
                L[m] = self._reduce(m, gens, p)
        return L

    def _reduce(self, m, vecs, p):
        idx = self.index[m]
        N = len(idx)
        rows = []
        for v in vecs:
            row = [0] * N
            nz = False
            for w, c in v.items():
                cc = c % p if p else c
                if cc:
                    row[idx[w]] = cc
                    nz = True
            if nz:
                rows.append(row)
        if not rows:
            return []
        R, piv = rref(rows, p=p)
        return [{self.words[m][j]: r[j] for j in range(N) if r[j]} for r in R[:len(piv)]]

    def rank_of(self, m, vecs, p):
        idx = self.index[m]
        rows = []
        for v in vecs:
            row = [0] * len(idx)
            for w, c in v.items():
                cc = c % p if p else c
                if cc:
                    row[idx[w]] = cc
            if any(row):
                rows.append(row)
        return rank(rows, p=p) if rows else 0


