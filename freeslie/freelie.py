def splits(m):
    """All ordered pairs (m1, m2) of nonzero multidegrees with m1 + m2 = m."""
    out = []
    for parts in product(*[range(x + 1) for x in m]):
        m1 = tuple(parts)
        m2 = tuple(a - b for a, b in zip(m, m1))
        if sum(m1) and sum(m2):
            out.append((m1, m2))
    return out


def mdegs(n, d):
    """All multidegrees in n variables of total degree exactly d."""
    if n == 1:
        return [(d,)]
    out = []
    for first in range(d + 1):
        for rest in mdegs(n - 1, d - first):
            out.append((first,) + rest)
    return out


