def variety_vs_tensor(par, D, p, label, cap=None):
    """Compare the variety model and the tensor model over Q and over F_p.

    Also tests the formula suggested by the p = 2 case:

        dim F_A(V)_m  =  dim L(V)_m  +  dim (L(V)_{m/3})_odd    (m divisible by 3)

    i.e. the free object of the variety WITHOUT the identity [x,[x,x]] = 0 is the
    free Lie superalgebra plus one central element for each odd basis element,
    namely its cube [x,[x,x]]."""
    M = Magma(par, D, cap=cap)
    T = Tensor(par, D)
    dQ = M.free_dims(p=None)
    dP = M.free_dims(p=p)
    LQ = T.lie(p=None)
    LP = T.lie(p=p)
    print("  multideg   parity |  variety Q  variety F_%d |  tensor Q  tensor F_%d | predicted"
          % (p, p))
    bad, wrong = [], []
    for d in range(1, D + 1):
        for m in mdegs(len(par), d):
            if m not in M.mon:
                continue
            a, b = dQ[m], dP[m]
            c, e = len(LQ.get(m, [])), len(LP.get(m, []))
            # predicted: dim L_m + dim (L_{m/p})_odd
            extra = 0
            if all(x % p == 0 for x in m):
                mp = tuple(x // p for x in m)
                if T.parity(mp):
                    extra = len(LP.get(mp, []))
            pred = e + extra
            flag = ""
            if a != b:
                flag = "   <-- differs"
                bad.append((m, a, b, c, e))
            if pred != b:
                flag += "  PREDICTION FAILS"
                wrong.append((m, b, pred))
            print("  %-10s %-6s |  %8d  %10d |  %8d  %9d | %8d%s"
                  % (str(m), "odd" if T.parity(m) else "even", a, b, c, e, pred, flag))
    print()
    if bad:
        print("  %s: over F_%d the variety model is BIGGER than over Q in %d multidegrees:"
              % (label, p, len(bad)))
        for m, a, b, c, e in bad:
            print("     %-10s  char 0: %d    char %d: %d    tensor model char %d: %d"
                  % (str(m), a, p, b, p, e))
    else:
        print("  %s: the two models agree in every multidegree, char 0 and char %d." % (label, p))
    print("  formula  dim F_A(V)_m = dim L_m + dim (L_{m/%d})_odd:  %s"
          % (p, "holds in all %d multidegrees" % len(dQ) if not wrong
             else "FAILS at %s" % wrong))
    return dQ, dP, LQ, LP


def char2_model(par, D):
    """The p = 2 free Lie superalgebra: L + squares of odd elements, inside T(V)."""
    T = Tensor(par, D)
    L = T.lie(p=2)
    n = len(par)
    print("  Step 1: dim L_T(V)_m over F_2 against Witt's numbers (total degree).")
    okwitt = True
    for d in range(1, D + 1):
        tot = sum(len(L.get(m, [])) for m in mdegs(n, d))
        w = witt(n, d)
        ok = "ok" if tot == w else "MISMATCH"
        if tot != w:
            okwitt = False
        print("     d = %d:  dim L_d = %-4d  Witt = %-4d  %s" % (d, tot, w, ok))
    print()
    print("  Step 2: squares of a basis of L_odd, independent modulo L?")
    dims = {}
    indep = True
    for d in range(1, D + 1):
        for m in mdegs(n, d):
            dims[m] = len(L.get(m, []))
    for d in range(1, D // 2 + 1):
        for m in mdegs(n, d):
            if not T.parity(m) or not L.get(m):
                continue
            m2 = tuple(2 * x for x in m)
            if m2 not in T.words:
                continue
            sq = [T.mul(b, b) for b in L[m]]
            sq = [{w: c % 2 for w, c in s.items() if c % 2} for s in sq]
            r_sq = T.rank_of(m2, sq, 2)
            r_both = T.rank_of(m2, sq + L.get(m2, []), 2)
            good = (r_sq == len(L[m])) and (r_both == r_sq + len(L.get(m2, [])))
            if not good:
                indep = False
            print("     m = %-8s -> %-8s : dim L_m = %-3d  rk(squares) = %-3d  "
                  "dim L_2m = %-3d  rk(sum) = %-3d  %s"
                  % (str(m), str(m2), len(L[m]), r_sq, len(L.get(m2, [])), r_both,
                     "direct" if good else "NOT DIRECT"))
    print()
    print("  Step 3: closure.  [x^2, y] = [x,[x,y]] in L, and (sum of odds)^2 in L + squares?")
    closure = True
    for d in range(1, D // 2 + 1):
        for m in mdegs(n, d):
            if not T.parity(m) or not L.get(m):
                continue
            m2 = tuple(2 * x for x in m)
            for e in range(1, D - 2 * d + 1):
                for my in mdegs(n, e):
                    if my not in T.words or not L.get(my):
                        continue
                    mt = tuple(a + b for a, b in zip(m2, my))
                    if mt not in T.words:
                        continue
                    for x in L[m]:
                        x2 = {w: c % 2 for w, c in T.mul(x, x).items() if c % 2}
                        for y in L[my]:
                            lhs = T.bracket(x2, m2, y, my, 2)
                            rhs = T.bracket(x, m, T.bracket(x, m, y, my, 2),
                                            tuple(a + b for a, b in zip(m, my)), 2)
                            if lhs != rhs:
                                closure = False
                                print("     FAIL [x^2,y] != [x,[x,y]] at m=%s, my=%s" % (m, my))
                            if T.rank_of(mt, L.get(mt, []) + [lhs], 2) != len(L.get(mt, [])):
                                closure = False
                                print("     FAIL [x^2,y] outside L at m=%s, my=%s" % (m, my))
    print("     [x^2,y] = [x,[x,y]] and lands in L:  %s" % ("ok" if closure else "FAILED"))
    print()
    print("  Step 4: dim F(V)_d = dim L_d + dim (L_{d/2})_odd, and the PBW identity")
    fd = {}
    for d in range(1, D + 1):
        tot = sum(len(L.get(m, [])) for m in mdegs(n, d))
        sq = 0
        if d % 2 == 0:
            sq = sum(len(L.get(m, [])) for m in mdegs(n, d // 2) if T.parity(m))
        fd[d] = tot + sq
        print("     d = %-2d:  dim L_d = %-4d + squares %-4d = dim F_d = %-4d"
              % (d, tot, sq, fd[d]))
    # PBW: prod over even basis elts 1/(1-t^d), over odd (1+t^d)  ==  1/(1-n t)
    ser = [0] * (D + 1)
    ser[0] = 1
    for d in range(1, D + 1):
        ev = sum(len(L.get(m, [])) for m in mdegs(n, d) if not T.parity(m))
        if d % 2 == 0:
            ev += sum(len(L.get(m, [])) for m in mdegs(n, d // 2) if T.parity(m))
        od = sum(len(L.get(m, [])) for m in mdegs(n, d) if T.parity(m))
        for _ in range(ev):                                  # 1/(1-t^d)
            new = list(ser)
            for k in range(d, D + 1):
                new[k] += new[k - d]
            ser = new
        for _ in range(od):                                  # (1+t^d)
            new = list(ser)
            for k in range(D, d - 1, -1):
                new[k] += ser[k - d]
            ser = new
    target = [n ** k for k in range(D + 1)]
    okpbw = ser[:D + 1] == target[:D + 1]
    print("     PBW series  %s" % ser[:D + 1])
    print("     dim T(V)_d  %s" % target[:D + 1])
    print("     PBW identity for U(F(V)) = T(V):  %s" % ("ok" if okpbw else "MISMATCH"))
    return okwitt and indep and closure and okpbw


def cube_map(D=6):
    """p = 3: is x -> [x,[x,x]] additive on the odd part of the free object?"""
    print("  In the free Lie superalgebra of the variety model over F_3 on two odd")
    print("  generators x, y, the element T(x) = [x,[x,x]] is nonzero, and")
    print("  T(x+y) - T(x) - T(y) is checked to vanish identically:")
    M = Magma([1, 1], 3)
    I3 = M.t_ideal(p=3)
    dims = {m: len(M.mon[m]) - len(I3[m]) for m in I3}
    print("     multidegrees of total degree 3:  %s"
          % {m: dims[m] for m in mdegs(2, 3) if m in dims})
    # T(x+y) - T(x) - T(y) expanded in the magma algebra, reduced mod the T-ideal
    x, y = 0, 1
    def T3(a, b):
        # [a+b, [a+b, a+b]] expanded bilinearly over the two letters
        terms = {}
        for u in (a, b):
            for v in (a, b):
                for w in (a, b):
                    key = (u, (v, w))
                    terms[key] = terms.get(key, 0) + 1
        return terms
    full = T3(x, y)
    for key in [(x, (x, x)), (y, (y, y))]:
        full[key] = full.get(key, 0) - 1
    # reduce modulo the T-ideal in multidegrees (2,1) and (1,2)
    ok = True
    for m in [(2, 1), (1, 2)]:
        part = {t: c for t, c in full.items() if M.mdeg(t) == m}
        gens = I3[m]
        r0 = _rank_in(M, m, gens, 3)
        r1 = _rank_in(M, m, gens + [part], 3)
        print("     multidegree %s: T-ideal rank %d, with the cross terms %d -> %s"
              % (str(m), r0, r1, "cross terms lie in the ideal" if r0 == r1 else "NOT in the ideal"))
        if r0 != r1:
            ok = False
    print("     T(x+y) = T(x) + T(y) on the free object:  %s" % ("ok" if ok else "FAILED"))
    # centrality: [T(x), z] = 0 for z a generator, and [T(x), [x,y]] = 0
    print("  and T(x) is central: [T(x), z] lies in the T-ideal for")
    M4 = Magma([1, 1], 4)
    I4 = M4.t_ideal(p=3)
    Tx = (x, (x, x))
    central = True
    for z, mz in [(x, (4, 0)), (y, (3, 1))]:
        for elt in [{(Tx, z): 1}, {(z, Tx): 1}]:
            gens = I4[mz]
            r0 = _rank_in(M4, mz, gens, 3)
            r1 = _rank_in(M4, mz, gens + [elt], 3)
            good = (r0 == r1)
            if not good:
                central = False
            print("     %-22s at multidegree %-7s: %s"
                  % (str(list(elt)[0]), str(mz), "in the ideal" if good else "NOT in the ideal"))
    print("     [T(x), g] = 0:  %s" % ("ok" if central else "FAILED"))
    return ok and central


def _rank_in(M, m, vecs, p):
    idx = M.index[m]
    rows = []
    for v in vecs:
        row = [0] * len(idx)
        for t, c in v.items():
            cc = c % p if p else c
            if cc:
                row[idx[t]] = cc
        if any(row):
            rows.append(row)
    return rank(rows, p=p) if rows else 0


