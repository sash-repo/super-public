#!/usr/bin/env python3
"""freelie.py -- free Lie superalgebras in characteristics 0, 2, 3: exact dimensions.

Question: do free Lie superalgebras exist in characteristics 2 and 3 when Lie
superalgebras are defined as in [BGLL] Section 2, and what are their dimensions?

Two models of "the free Lie superalgebra on V" are built here and compared, per
multidegree, over Q and over F_p:

  (A) THE VARIETY MODEL.  F_A(V) = M(V)/I, where M(V) is the free non-associative
      (magma) superalgebra on V and I is the T-ideal generated by the identities
      that [BGLL] Section 2 imposes:
              [u,u] = 0                     (u even)
              [u,v] + (-1)^{p(u)p(v)}[v,u] = 0
              [u,[v,w]] = [[u,v],w] + (-1)^{p(u)p(v)}[v,[u,w]]
      "T-ideal" = closed under substitution of arbitrary monomials into the
      identities AND under bracketing with arbitrary monomials; that is what the
      recursion  I_m = <instances>_m + [I,M]_m + [M,I]_m  computes.
      This is the object [BGLL] (46) calls free -- "no relations" at a node o or *.

  (B) THE TENSOR MODEL.  L_T(V) = the Lie sub-superalgebra of the free associative
      superalgebra T(V) generated by V, with [a,b] = ab - (-1)^{p(a)p(b)}ba.
      This is the classical construction of the free Lie superalgebra.

Over a field of characteristic 0 the two agree.  The engine measures where they
part company in characteristic 3, and, for p = 2, verifies the model of the free
Lie superalgebra in the sense of [BGLL] Section 2 (squaring, not bracket):

  (C) p = 2:  F(V) = L_T(V) + Span{x^2 | x in L_T(V)_odd} inside T(V).
      Checked: the squares of a basis of L_odd are linearly independent modulo L,
      the sum is closed under the bracket and under the squaring, and the
      resulting dimensions satisfy the PBW identity for U(F(V)) = T(V).

Everything is exact: integer matrices, ranks over Q and over F_p via ../lib/exactlin.py.

Usage:  python freelie.py            (all checks)
        python freelie.py --quick    (smaller degree bound)
"""
