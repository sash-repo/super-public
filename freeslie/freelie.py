def witt(n, d):
    """Witt's number: dim of the degree-d part of the free Lie algebra on n gens."""
    def mu(k):
        r, x = 1, k
        f = 2
        while f * f <= x:
            if x % f == 0:
                x //= f
                if x % f == 0:
                    return 0
                r = -r
            f += 1
        if x > 1:
            r = -r
        return r
    return sum(mu(e) * n ** (d // e) for e in range(1, d + 1) if d % e == 0) // d


