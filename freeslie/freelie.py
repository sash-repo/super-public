class Magma:
    """The free non-associative superalgebra on generators of given parities."""

    def __init__(self, par, D, cap=None):
        self.par = list(par)                # parity of each generator
        self.n = len(par)
        self.D = D
        self.cap = cap                      # optional componentwise bound on multidegrees
        self.mon = {}                       # multidegree -> list of trees
        for i in range(self.n):
            e = tuple(1 if j == i else 0 for j in range(self.n))
            if self._ok(e):
                self.mon[e] = [i]
        for d in range(2, D + 1):
            for m in mdegs(self.n, d):
                if not self._ok(m):
                    continue
                lst = []
                for m1, m2 in splits(m):
                    for u in self.mon.get(m1, []):
                        for v in self.mon.get(m2, []):
                            lst.append((u, v))
                if lst:
                    self.mon[m] = lst
        self.index = {m: {t: i for i, t in enumerate(lst)} for m, lst in self.mon.items()}

    def _ok(self, m):
        return self.cap is None or all(a <= b for a, b in zip(m, self.cap))

    def parity(self, t):
        if isinstance(t, int):
            return self.par[t]
        return (self.parity(t[0]) + self.parity(t[1])) % 2

    def mdeg(self, t):
        if isinstance(t, int):
            return tuple(1 if j == t else 0 for j in range(self.n))
        a, b = self.mdeg(t[0]), self.mdeg(t[1])
        return tuple(x + y for x, y in zip(a, b))

    # -- identity instances -------------------------------------------------

    def instances(self, m):
        """The substitution instances of the defining identities of multidegree m."""
        out = []
        # anti-symmetry (and [u,u] = 0 for u even)
        for m1, m2 in splits(m):
            for u in self.mon.get(m1, []):
                for v in self.mon.get(m2, []):
                    pu, pv = self.parity(u), self.parity(v)
                    vec = {}
                    vec[(u, v)] = vec.get((u, v), 0) + 1
                    s = 1 if (pu * pv) % 2 == 0 else -1
                    vec[(v, u)] = vec.get((v, u), 0) + s
                    out.append(vec)
                    if u == v and pu == 0:
                        out.append({(u, v): 1})
        # Jacobi:  [u,[v,w]] - [[u,v],w] - (-1)^{p(u)p(v)} [v,[u,w]]
        for m1, rest in splits(m):
            for m2, m3 in splits(rest):
                for u in self.mon.get(m1, []):
                    for v in self.mon.get(m2, []):
                        for w in self.mon.get(m3, []):
                            s = 1 if (self.parity(u) * self.parity(v)) % 2 == 0 else -1
                            vec = {}
                            vec[(u, (v, w))] = vec.get((u, (v, w)), 0) + 1
                            vec[((u, v), w)] = vec.get(((u, v), w), 0) - 1
                            vec[(v, (u, w))] = vec.get((v, (u, w)), 0) - s
                            out.append(vec)
        return out

    # -- the T-ideal, multidegree by multidegree ---------------------------

    def t_ideal(self, p=None):
        """Basis of the T-ideal of the defining identities, per multidegree."""
        ideal = {}                          # multidegree -> list of vectors (basis)
        for d in range(1, self.D + 1):
            for m in mdegs(self.n, d):
                if m not in self.mon:
                    continue
                gens = list(self.instances(m))
                # bracket lower-degree ideal elements with arbitrary monomials
                for m1, m2 in splits(m):
                    for x in ideal.get(m1, []):
                        for w in self.mon.get(m2, []):
                            gens.append({(t, w): c for t, c in x.items()})
                            gens.append({(w, t): c for t, c in x.items()})
                ideal[m] = self._reduce(m, gens, p)
        return ideal

    def free_dims(self, p=None):
        """dim of the free Lie superalgebra (variety model) per multidegree."""
        ideal = self.t_ideal(p)
        return {m: len(self.mon[m]) - len(ideal[m]) for m in ideal}

    def _reduce(self, m, vecs, p, batch=4000):
        """Row-reduce a list of vectors of multidegree m; return a basis.

        Reduced in batches: the running basis never exceeds N rows, so the
        memory used is bounded by (N + batch) x N even when the generating set
        has 10^5 elements (which it does in multidegree (3,3))."""
        idx = self.index[m]
        N = len(idx)
        basis = []
        pending = []
        for v in vecs:
            row = [0] * N
            nz = False
            for t, c in v.items():
                cc = c % p if p else c
                if cc:
                    row[idx[t]] = cc
                    nz = True
            if nz:
                pending.append(row)
            if len(pending) >= batch:
                R, piv = rref(basis + pending, p=p)
                basis = [list(r) for r in R[:len(piv)]]
                pending = []
                if len(basis) == N:
                    return [{self.mon[m][j]: r[j] for j in range(N) if r[j]} for r in basis]
        if pending:
            R, piv = rref(basis + pending, p=p)
            basis = [list(r) for r in R[:len(piv)]]
        return [{self.mon[m][j]: r[j] for j in range(N) if r[j]} for r in basis]


