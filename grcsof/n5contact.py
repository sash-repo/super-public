#!/usr/bin/env python3
"""k(1|5): the order-2 bracket is the contact bracket, i.e. it is invariant
under the whole of k(1|5), not merely under i(osp(5|2)) -- the analog, for
n = 5, of the corresponding Statement for n = 4.

k(1|5) is generated by g_{-1} and g_1 = <K_{t y_i}> + <K_{y_i y_j y_k}>, so it
suffices to add the ten cubics to the 23 generating functions of i(osp(5|2))
and to re-run the independent invariance test verify_kn.check.
"""
import sys
from itertools import combinations
from fractions import Fraction as Fr
from sympy import symbols

from superN import mono
from n5 import ALG
from n5bin import Bn, gens_osp
from verify_kn import check, osp_fields
from knclass import label

NM = ALG.names


def all_fields():
    out = dict(osp_fields(ALG))
    for c in combinations(range(5), 3):
        m = 0
        for i in c:
            m |= 1 << i
        out["".join(NM[i] for i in c)] = mono(0, m)
    for c in combinations(range(5), 2):        # t * quadratics, degree 2
        m = 0
        for i in c:
            m |= 1 << i
        out["t" + "".join(NM[i] for i in c)] = mono(1, m)
    return out


if __name__ == '__main__':
    N = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    l1, l2 = Fr(3, 7), Fr(-5, 11)
    C = Bn(gens_osp(), l1, l2)
    ts, ns = C.solve(N, tmax=2)
    fields = all_fields()
    print(f"order {N}: dim = {len(ns)} over i(osp(5|2)); "
          f"testing against {len(fields)} generating functions of k(1|5)")
    for v in ns:
        print("  ", {label(t, NM): str(c) for t, c in zip(ts, v) if c != 0})
        check(ALG, ts, v, l1, l2, N, fields, tmax=3)
        sys.stdout.flush()
