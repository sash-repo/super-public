#!/usr/bin/env python3
"""Is the order-2 bracket J^2 invariant under the whole of k(1|6)?

J^2 = lam2 dt (x) 1 - lam1 1 (x) dt + sum_i (D_xi_i (x) D_eta_i + D_eta_i (x) D_xi_i),
cf. eq. (31) of the paper for n = 4.  k(1|6) is generated by its components of
degree <= 1, i.e. by 1, Lambda^1, Lambda^2, t, Lambda^3 (ALL of it) and t Lambda^1.
"""
from fractions import Fraction as Fr
from itertools import combinations
from kas6 import ALG, NAMES, gens_kas, CUB_ETA
from kasops import binary_terms
from kasbin import build, testmons

F = dict(gens_kas())
for i, f in enumerate(CUB_ETA):          # add the other half of Lambda^3
    F['e%d' % i] = f
names = sorted(F)
l1, l2 = Fr(3, 7), Fr(-5, 11)
ts = binary_terms(2, True)
v = [0] * len(ts)
XI, ETA = [0, 2, 4], [1, 3, 5]
for i, t in enumerate(ts):
    kA, A, kB, B = t
    if (kA, A, kB, B) == (1, (), 0, ()):
        v[i] = l2
    elif (kA, A, kB, B) == (0, (), 1, ()):
        v[i] = -l1
    elif len(A) == len(B) == 1 and {A[0], B[0]} in [{2*j, 2*j+1} for j in range(3)]:
        v[i] = 1
print("J^2 =", [(t, c) for t, c in zip(ts, v) if c])
bad = build([F[k] for k in names], 2, l1, l2, testmons(2, 6), check=[v], names=names)
print("k(1|6)-invariant:" if not bad else "FAILS on:", sorted(set(bad)) or "yes")
