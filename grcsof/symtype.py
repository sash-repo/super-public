#!/usr/bin/env python3
"""The traceless symmetric powers S^m_0 of the vector representation of o(6),
as fibres for the tensor fields of Section 6 of the paper.

The fibres used so far -- F, Lambda^k, S^pm -- are the ones that occur in the
algebra itself.  The families 1a) and 1a^dagger) of [GLS, Sec.10] run through
the fibres of highest weight (m, l, l), and for l = 0 these are exactly the
traceless symmetric powers S^m_0 = S^m_0(V_6), of dimension

    dim S^m_0(V_6) = (m+1)(m+2)(2m+3)/6 - (m-1)m(2m+1)/6,

i.e. 1, 6, 20, 50, 105, ...   S^0_0 = F, S^1_0 = Lambda^1 = V_6, and S^2_0 is
the first new one.  We build S^m(V_6) with the derivation action of c o(6) --
the same convention as lam_type -- and cut out the irreducible S^m_0 as the
submodule generated by the highest weight vector xi_1^m.

Usage:  python3 symtype.py            self-test (dimensions, weights, c_V)
"""
from fractions import Fraction as Fr
from itertools import combinations_with_replacement

from kastypes import Type, CO6, submodule, restrict
from kastens import N6
from kas6 import NAMES


def _sym_mats(m):
    """S^m of the vector representation, c o(6) acting by derivations."""
    bas = [tuple(c) for c in combinations_with_replacement(range(N6), m)]
    idx = {A: p for p, A in enumerate(bas)}
    d = len(bas)
    mats = []
    for M in CO6:
        R = [[Fr(0)] * d for _ in range(d)]
        for p, A in enumerate(bas):
            for pos in range(m):                       # differentiate at pos
                i = A[pos]
                for j in range(N6):
                    if not M[j][i]:
                        continue
                    Bn = list(A)
                    Bn[pos] = j
                    R[idx[tuple(sorted(Bn))]][p] += M[j][i]
        mats.append(R)
    return bas, mats


def sym_type(m, traceless=True):
    """S^m_0(V_6) as a Type; the whole S^m(V_6) if traceless is False."""
    bas, mats = _sym_mats(m)
    lab = ["".join(NAMES[i] for i in A) or "1" for A in bas]
    full = Type(f"S{m}full", len(bas), mats, lab)
    if not traceless or m < 2:
        return Type(f"S{m}" if m > 1 else ('F' if m == 0 else 'L1'),
                    len(bas), mats, lab)
    hw = tuple([0] * m)                                # xi_1^m, weight (m,0,0)
    seed = [Fr(1) if A == hw else Fr(0) for A in bas]
    return restrict(full, submodule(full, seed), f"S{m}")


if __name__ == '__main__':
    import kasV
    from kasV import Rmat, TYPES
    from kas6 import TT

    for m in [2, 3]:
        V = sym_type(m)
        print(f"S^{m}_0: dim = {V.dim}, highest weight = {max(V.wts)}")
        # K_t acts by a scalar c_V on the fibre
        M = Rmat(V, TT, 0)
        cs = {M[b][b].get((0, 0), 0) for b in range(V.dim)}
        off = any(M[b][a] for b in range(V.dim) for a in range(V.dim)
                  if a != b)
        print(f"        c_V = {cs}, off-diagonal: {off}")
        print(f"        weights: {sorted(set(V.wts))[:3]} ... "
              f"{sorted(set(V.wts))[-3:]}")
