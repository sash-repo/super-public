#!/usr/bin/env python3
"""The two other W-regradings of kas: kas(1|6; 3xi) and kas(1|6; 3eta).

[GLS, Sec. 2] gives, for r = 3xi and r = 3eta,

    r = 3xi : deg xi_i = 0, deg eta_i = deg t = 1
    r = 3eta: deg eta_i = 0, deg xi_i = deg t = 1

and the table of nonpositive terms

    kas(4|4) :  g_{-1} = Lambda(3),       g_0 = Lambda(3) + sl(1|3)   (r = 3xi)
    kas(4|3) :  g_{-1} = Vol_0(0|3),      g_0 = c(vect(0|3))          (r = 3eta)

both of depth 1 (no g_{-2}).  This module rebuilds all that from OUR engine:
kas is the same Lie superalgebra of generating functions as in kas6.py -- only
the degree function changes -- so the regradings cost nothing but a re-sorting
of a basis that we compute by brackets.

Conventions of kas6.py: superfunctions are dicts {(a, mask): coeff} for
t^a y^mask with y = (xi1, eta1, xi2, eta2, xi3, eta3); the contact bracket is
ALG.kb; deg K_f = deg f - deg t.

Usage:  python3 regrade.py struct      the graded structure of both regradings
        python3 regrade.py chars       the characters of g_0 (density fibres)
        python3 regrade.py ops [N]     invariant operators between densities
"""
import sys
from fractions import Fraction as Fr
from itertools import combinations

from kas6 import (ALG, NAMES, LAM1, LAM2, CUB_XI, TT, ONE, TLAM1,
                  XI, ETA, msk, fmono)
from superN import parity, popcount

# ------------------------------------------------------------ linear algebra


def _keys(fs):
    return sorted({k for f in fs for k in f})


def _vec(f, ks):
    return [Fr(f.get(k, 0)) for k in ks]


def basis_of(fs):
    """a subset of fs that is a basis of its span (exact)."""
    ks = _keys(fs)
    rows, out = [], []
    for f in fs:
        v = _vec(f, ks)
        for r, p in rows:
            if v[p]:
                c = v[p] / r[p]
                v = [a - c * b for a, b in zip(v, r)]
        p = next((i for i, x in enumerate(v) if x), None)
        if p is not None:
            rows.append((v, p))
            out.append(f)
    return out


def coords(fs, f):
    """coordinates of f in the basis fs, or None if f is not in the span."""
    ks = _keys(list(fs) + [f])
    M = [_vec(g, ks) for g in fs]
    # solve sum_j c_j M[j] = f  by Gaussian elimination on the transpose
    n, m = len(M), len(ks)
    aug = [[M[j][i] for j in range(n)] + [_vec(f, ks)[i]] for i in range(m)]
    piv = []
    r = 0
    for c in range(n):
        pr = next((i for i in range(r, m) if aug[i][c]), None)
        if pr is None:
            continue
        aug[r], aug[pr] = aug[pr], aug[r]
        pv = aug[r][c]
        aug[r] = [x / pv for x in aug[r]]
        for i in range(m):
            if i != r and aug[i][c]:
                k = aug[i][c]
                aug[i] = [a - k * b for a, b in zip(aug[i], aug[r])]
        piv.append(c)
        r += 1
    for i in range(r, m):
        if aug[i][n]:
            return None
    out = [Fr(0)] * n
    for i, c in enumerate(piv):
        out[c] = aug[i][n]
    return out


# --------------------------------------------------- kas, by standard degree

STD = {-2: [ONE],
       -1: list(LAM1),
       0: list(LAM2) + [TT],
       1: list(CUB_XI) + list(TLAM1)}


def build_std(D):
    """kas_d for -2 <= d <= D in the standard grading (deg K_f = deg f - 2);
    kas_+ is generated by kas_1, so brackets with kas_1 suffice."""
    for d in range(2, D + 1):
        cand = [ALG.kb(f, g) for f in STD[1] for g in STD[d - 1]]
        STD[d] = basis_of([h for h in cand if h])
    return STD


# ---------------------------------------------------------- the new gradings

def newdeg_f(f, zero):
    """the r-degree of a superfunction, deg t = 1, deg(zero_i) = 0, other
    odd coordinates of degree 1.  zero is the index list XI or ETA."""
    ds = set()
    for (a, m) in f:
        d = a
        for i in range(6):
            if m >> i & 1 and i not in zero:
                d += 1
        ds.add(d)
    assert len(ds) == 1, ("inhomogeneous in the new grading", f)
    return ds.pop()


def rparts(f, zero):
    """f split into its r-homogeneous parts, {r-degree: superfunction}."""
    out = {}
    for k, c in f.items():
        d = newdeg_f({k: c}, zero)
        out.setdefault(d, {})[k] = c
    return out


def regrade(zero, D=6):
    """{new degree: basis of the component}, from kas_{<=D} (standard).

    kas is r-graded, so the r-homogeneous parts of an element of kas are again
    in kas; splitting each basis element that way (NOT monomial by monomial)
    and taking the span gives the r-components exactly."""
    build_std(D)
    out = {}
    for d in range(-2, D + 1):
        for f in STD[d]:
            for e, g in rparts(f, zero).items():
                out.setdefault(e - 1, []).append(g)
    return {d: basis_of(fs) for d, fs in sorted(out.items())}


def sdim(fs):
    ev = sum(1 for f in fs if parity(f) == 0)
    return ev, len(fs) - ev


# ------------------------------------------------------------ Cartan weights

CARTAN = [TT] + [fmono(2 * i, 2 * i + 1) for i in range(3)]
CARTAN_NAMES = ['K_t', 'K_{xi1eta1}', 'K_{xi2eta2}', 'K_{xi3eta3}']


def weight(f):
    """the weight of a K_t- and K_{xi_i eta_i}-eigenvector, as a 4-tuple."""
    w = []
    for h in CARTAN:
        b = ALG.kb(h, f)
        if not b:
            w.append(Fr(0))
            continue
        c = coords([f], b)
        assert c is not None, ("not a weight vector", f)
        w.append(c[0])
    return tuple(w)


# ------------------------------------------------- characters of the new g_0

def characters(g0, g1, gm1):
    """a basis of (g_0 / [g_0, g_0])^*, i.e. of the 1-dimensional g_0-modules,
    given as linear functionals on the basis g0.  Returns (basis of the space
    of characters, as coefficient vectors on g0)."""
    der = [ALG.kb(f, g) for f in g0 for g in g0]
    der = [h for h in der if h]
    # write [g0,g0] in coordinates of g0
    rows = []
    for h in der:
        c = coords(g0, h)
        assert c is not None, "[g0,g0] not inside g0"
        rows.append(c)
    return nullspace_rows(rows, len(g0))


def nullspace_rows(rows, n):
    """basis of {x : rows . x = 0}."""
    M = [list(map(Fr, r)) for r in rows]
    piv, r = [], 0
    for c in range(n):
        pr = next((i for i in range(r, len(M)) if M[i][c]), None)
        if pr is None:
            continue
        M[r], M[pr] = M[pr], M[r]
        pv = M[r][c]
        M[r] = [x / pv for x in M[r]]
        for i in range(len(M)):
            if i != r and M[i][c]:
                k = M[i][c]
                M[i] = [a - k * b for a, b in zip(M[i], M[r])]
        piv.append(c)
        r += 1
    free = [c for c in range(n) if c not in piv]
    out = []
    for fc in free:
        v = [Fr(0)] * n
        v[fc] = Fr(1)
        for i, c in enumerate(piv):
            v[c] = -M[i][fc]
        out.append(v)
    return out


# ---------------------------------------------------------------------- main

def struct(zero, name, D=6):
    G = regrade(zero, D)
    print(f"=== kas(1|6; {name}) " + "=" * 46)
    lo = min(G)
    print(f"  depth: lowest nonzero component is g_{{{lo}}}"
          f"   {'OK (depth 1)' if lo == -1 else 'NOT depth 1'}")
    for d in sorted(G):
        if d > 2:
            continue
        ev, od = sdim(G[d])
        print(f"  g_{{{d:2d}}}: sdim {ev}|{od}   (dim {ev + od})")
    return G


def show_basis(fs, label):
    print(f"  {label}:")
    for f in fs:
        print("     ", ALG.show(f), "   weight", weight(f))


# ============================================================ the fibre side
#
# Both regradings have depth 1 and g_{-1} abelian (the contact bracket of two
# functions with neither t nor eta -- resp. neither t nor xi -- vanishes), so
#
#     I(V) = U(g_-) (x) V = S(g_{-1}) (x) V,
#
# and x in g_{>0} acts by the standard recursion
#
#     x.(e u (x) m) = [x,e].(u (x) m) + (-1)^{p(x)p(e)} e (x.(u (x) m)),
#     x.(1 (x) m)   = x.m if deg x = 0, and 0 if deg x > 0.
#
# A singular vector of degree N is a v in S^N(g_{-1}) (x) V with g_1.v = 0
# (g_1 generates g_+, so g_1 suffices) that is a g_0-highest weight vector.

class Graded:
    """the r-graded pieces of kas that the recursion needs, with the brackets
    [g_1, g_{-1}] and [g_0, g_{-1}] expressed in the chosen bases."""

    def __init__(self, zero, name, D=6, topbr=1):
        # topbr = the highest r-degree whose brackets with g_{-1} are wanted.
        # g_d is complete only if D is large enough: in the 3xi grading g_d
        # needs t^{d+1} xi1xi2xi3, of standard degree 2d + 3, so D >= 2*topbr+3.
        assert D >= 2 * topbr + 3, "the truncation D is too small for topbr"
        self.name = name
        self.G = regrade(zero, D)
        self.gm1, self.g0, self.g1 = self.G[-1], self.G[0], self.G[1]
        assert not any(ALG.kb(a, b) for a in self.gm1 for b in self.gm1), \
            "g_{-1} is not abelian"
        self.top = topbr
        self.br = {}
        for d in range(0, topbr + 1):
            tgt = self.G[d - 1]
            for i, x in enumerate(self.G[d]):
                for j, e in enumerate(self.gm1):
                    h = ALG.kb(x, e)
                    c = coords(tgt, h) if h else [Fr(0)] * len(tgt)
                    assert c is not None, ("bracket leaves the component", d)
                    self.br[(d, i, j)] = c

    def par_m1(self, j):
        return parity(self.gm1[j])

    def par(self, d, i):
        return parity(self.G[d][i])

    def bracket(self, d, i, e, f):
        """[[...],...]: the coordinates of [x, e] in the basis of g_{d-1},
        for x the i-th basis vector of g_d and e the e-th of g_{-1}."""
        return self.br[(d, i, e)]


def words(gr, N):
    """canonical basis of S^N(g_{-1}): globally sorted index words, repeats
    allowed only for even letters."""
    ev = [j for j in range(len(gr.gm1)) if gr.par_m1(j) == 0]
    od = [j for j in range(len(gr.gm1)) if gr.par_m1(j) == 1]
    out = set()
    for r in range(min(N, len(od)) + 1):
        for sub in combinations(od, r):
            def rec(pos, left, cur):
                if left == 0:
                    out.add(tuple(sorted(cur + list(sub))))
                    return
                for k in range(pos, len(ev)):
                    rec(k, left - 1, cur + [ev[k]])
            rec(0, N - r, [])
    return sorted(out)


def sort_word(w, gr):
    """(sign, canonical word), or None if an odd letter is repeated."""
    w, sign = list(w), 1
    for i in range(1, len(w)):
        j = i
        while j > 0 and w[j - 1] > w[j]:
            if gr.par_m1(w[j - 1]) == 1 and gr.par_m1(w[j]) == 1:
                sign = -sign
            w[j - 1], w[j] = w[j], w[j - 1]
            j -= 1
    for i in range(1, len(w)):
        if w[i] == w[i - 1] and gr.par_m1(w[i]) == 1:
            return None
    return sign, tuple(w)


def act(gr, deg, xi, word, chi):
    """x.(word (x) m) for x the xi-th basis vector of g_deg (deg = 0 or 1) and
    m the generator of the 1-dimensional fibre of character chi (the list of
    its values on the basis g_0).  Returns {word: coefficient}."""
    if not word:
        return ({(): chi[xi]} if chi[xi] else {}) if deg == 0 else {}
    e, rest = word[0], word[1:]
    out = {}
    for k, c in enumerate(gr.br[(deg, xi, e)]):
        if not c:
            continue
        if deg >= 1:                        # [x,e] lies in g_{deg-1}
            sub = act(gr, deg - 1, k, rest, chi)
        else:                               # [x,e] lies in g_{-1}
            s = sort_word((k,) + rest, gr)
            sub = {s[1]: s[0]} if s else {}
        for w, v in sub.items():
            out[w] = out.get(w, 0) + c * v
    sgn = -1 if (gr.par(deg, xi) == 1 and gr.par_m1(e) == 1) else 1
    for w, v in act(gr, deg, xi, rest, chi).items():
        s = sort_word((e,) + w, gr)
        if s:
            out[s[1]] = out.get(s[1], 0) + sgn * s[0] * v
    return {k: v for k, v in out.items() if v}


def wt_word(gr, w, chi_wt):
    """the h-weight of (word (x) m)."""
    out = list(chi_wt)
    for j in w:
        for k, x in enumerate(weight(gr.gm1[j])):
            out[k] += x
    return tuple(out)


# --------------------------------------------------- the characters, and Vol

def char_info(gr):
    """basis of the space of characters of g_0, each returned together with
    its h-weight (its restriction to the Cartan, in GLS's basis)."""
    ch = characters(gr.g0, gr.g1, gr.gm1)
    out = []
    for c in ch:
        w = []
        for h in CARTAN:
            hc = coords(gr.g0, h)
            assert hc is not None, "the Cartan is not inside g_0"
            w.append(sum(a * b for a, b in zip(hc, c)))
        out.append((c, tuple(w)))
    return out


def vol_char(gr):
    """the character of Vol: chi_Vol(X) = -str(ad X on g_{-1}).

    Calibration: in the standard grading of k(1|6), where g_- = <K_1> + Lam^1,
    the same formula gives chi_Vol(K_t) = -(-2 + 6) = -4, which is the weight
    of Vol used throughout Subsection 6.7 of the paper."""
    out = []
    for x in gr.g0:
        s = Fr(0)
        for j, e in enumerate(gr.gm1):
            c = coords(gr.gm1, ALG.kb(x, e))
            assert c is not None
            s += c[j] * (1 if gr.par_m1(j) == 0 else -1)
        out.append(-s)
    return out


# ------------------------------------- singular vectors over a 1-dim(!) fibre
#
# chi enters the action of g_1 on S^N(g_{-1}) (x) chi exactly once (at the
# bottom of the recursion), so every matrix below is AFFINE in the parameter
# lam: M(lam) = A + lam B.  A generic nullspace would therefore miss precisely
# the special values of lam, which are the interesting ones.  We locate them
# exactly: over the reals rank(M) = rank(M^T M), so the rank drops below the
# number d of columns exactly at the roots of the single polynomial
# det(M(lam)^T M(lam)), of degree <= 2d; each root is then confirmed by an
# exact rank computation at that value.


# The Borel of [GLS]: their m_i are obtained from the highest weight vector m1
# by the LOWERING operators eta_1, eta_2, eta_3, xi_1 eta_2, xi_3 eta_1,
# xi_3 eta_2 (Sec. 11) and xi_2, xi_1, xi_3, xi_1 eta_2, xi_3 eta_1 (Sec. 12).
# In our weights xi_1 eta_2 = (0,-1,1,0) and xi_3 eta_1 = (0,1,0,-1), so those
# two being negative forces phi_1 > phi_2 and phi_3 > phi_1; eta_i = (-1,+e_i)
# being negative forces phi_0 > phi_i.  Hence phi_0 >> phi_3 > phi_1 > phi_2,
# and then the top of g_{-1} is xi1xi2xi3 (Sec. 11) resp. eta1eta3 (Sec. 12) --
# exactly the two vectors that carry the entries 1a) of those sections.
PHI = (Fr(10 ** 6), Fr(100), Fr(1), Fr(10 ** 4))


def _pos_part(gr):
    """the indices of the elements of g_0 of positive h-weight for a generic
    functional, i.e. a nilpotent part n^+ of a Borel of g_0, together with the
    zero-weight indices (which should be the Cartan itself)."""
    phi = PHI
    pos, zero = [], []
    for i, x in enumerate(gr.g0):
        v = sum(a * b for a, b in zip(weight(x), phi))
        if v > 0:
            pos.append(i)
        elif v == 0:
            zero.append(i)
    return pos, zero


def sing(gr, N, chi, lam, hw=True):
    """the singular vectors of degree N over the 1-dimensional fibre chi.

    Returns a list of (value of lam, or None meaning 'every lam'; the h-weight
    of the vector; the vector as {word: coefficient}).  With hw=True only the
    g_0-highest weight vectors are kept, which is what [GLS] lists."""
    import sympy as sp
    WN = words(gr, N)
    chw = []
    for h in CARTAN:
        hc = coords(gr.g0, h)
        chw.append(sum(a * b for a, b in zip(hc, chi)))
    byw = {}
    for w in WN:
        byw.setdefault(tuple(sp.simplify(x) for x in wt_word(gr, w, chw)),
                       []).append(w)
    pos, _zero = _pos_part(gr)
    out = []
    for wt, ws in sorted(byw.items(), key=str):
        acts = [(1, i) for i in range(len(gr.g1))]
        if hw:
            acts += [(0, i) for i in pos]
        rows = {}
        for d, i in acts:
            for col, w in enumerate(ws):
                for u, v in act(gr, d, i, w, chi).items():
                    rows.setdefault((d, i, u), [0] * len(ws))[col] += v
        d = len(ws)
        if not rows:
            for k in range(d):
                out.append((None, wt, {ws[k]: sp.Integer(1)}))
            continue
        M = sp.Matrix(list(rows.values()))
        p = sp.expand((M.T * M).det())
        if p == 0:
            cands = [None]
        else:
            cands = [r for r in sp.roots(sp.Poly(p, lam)) if r.is_rational]
        for c in cands:
            Mc = M if c is None else M.subs(lam, c)
            for v in Mc.nullspace():
                vec = {ws[k]: sp.simplify(v[k]) for k in range(d) if v[k] != 0}
                w2 = wt if c is None else \
                    tuple(sp.simplify(sp.sympify(x).subs(lam, c)) for x in wt)
                out.append((c, w2, vec))
    return out


def _nm(gr, j):
    return ALG.show(gr.gm1[j]).replace('(1)*', '').replace('*', '').\
        replace('(1)', '1')


def show_word(gr, w):
    """the word as a product of named basis vectors of g_{-1}, e.g.
    (eta1eta3)^2 or xi1.xi2xi3.xi1xi2xi3."""
    if not w:
        return "1"
    out, i = [], 0
    while i < len(w):
        j = i
        while j < len(w) and w[j] == w[i]:
            j += 1
        nm = _nm(gr, w[i])
        out.append(nm if j - i == 1 else f"({nm})^{j - i}")
        i = j
    return ".".join(out)


def show_sing(gr, N, chi, lam, label, hw=True):
    import sympy as sp
    print(f"  degree {N}, fibre = {label}:")
    res = sing(gr, N, chi, lam, hw)
    if not res:
        print("     NONE, for any value of the parameter")
        return res
    for c, wt, vec in res:
        body = " + ".join(f"({sp.simplify(x)})*{show_word(gr, w)}"
                          for w, x in sorted(vec.items()))
        at = "every lam" if c is None else f"lam = {c}"
        print(f"     [{at}]  weight {tuple(wt)}:  {body}")
    return res


