#!/usr/bin/env python3
"""n = 6: the binary (GRC) operators

    F_{lam1} (x) F_{lam2} --> F_{lam1+lam2+N}

invariant under as, cas = as + <K_t>, kas, i(osp(6|2)); see kas6.py, kasops.py.

Economies (all of them safe, see below):

 * the ansatz is restricted to the torus-weight-0 part (the Cartan subalgebra
   <K_{xi_i eta_i}> lies in all four algebras);
 * the equations are imposed for a small Lie-generating subset of the algebra
   and for a small set of test monomials;
 * EVERY basis vector of the resulting space is then verified, by an
   independent routine, against the FULL list of generating functions of the
   algebra and a~larger set of test monomials.  If one of them fails, the
   failing generator is added to the equation set (and, if it was there
   already, the test set is enlarged) and the whole thing is redone.

Since dropping equations can only enlarge the computed space, and since the
final verification proves that every vector of it is invariant, the answer
printed after a~clean verification is exact.
"""
import sys
from itertools import combinations
from fractions import Fraction as Fr

from superN import add, smul, mul, mono, parity, par_mon
from knclass import nullspace, f_id
from kas6 import (ALG, NAMES, gens_as, gens_cas, gens_kas, gens_osp,
                  gens_asop, zero_weight)
from kasops import binary_terms, blabel, bverify

NM = NAMES
ALGS = {'as': gens_as, 'cas': gens_cas, 'kas': gens_kas, 'osp': gens_osp,
        'asop': gens_asop}

# Lie-generating subsets: g_- is automatic for a constant-coefficient ansatz,
# o(6) is generated by its Cartan and the 6 root vectors below, and one
# highest-weight cubic generates Lambda^3_xi as an o(6)-module.
ROOTS = ['xi1eta1', 'xi2eta2', 'xi3eta3',          # the Cartan
         'xi1eta2', 'eta1xi2', 'xi2eta3', 'eta2xi3', 'xi1xi2', 'eta1eta2']
START = {'as': ROOTS + ['c0'],
         'asop': ROOTS + ['c0'],
         'cas': ROOTS + ['c0', 't'],
         'kas': ROOTS + ['c0', 't', 'txi1', 'teta1'],
         'osp': ROOTS + ['t', 'txi1', 'teta1']}


def key_of(f, F):
    for k, v in F.items():
        if v == f:
            return k
    return '?'


def testmons(tmax, ymax):
    return [m for m in ALG.monos(tmax) if bin(m[1]).count('1') <= ymax]


class Echelon:
    """online row reduction: keeps at most ncols independent rows."""

    def __init__(self, ncols):
        self.n = ncols
        self.rows = {}          # pivot column -> reduced row (list of Fr)

    def add(self, row):
        v = [Fr(x) for x in row]
        for p, r in self.rows.items():
            if v[p]:
                c = v[p]
                v = [a - c * b for a, b in zip(v, r)]
        p = next((i for i, x in enumerate(v) if x), None)
        if p is None:
            return False
        pv = v[p]
        v = [x / pv for x in v]
        for q, r in list(self.rows.items()):
            if r[p]:
                c = r[p]
                self.rows[q] = [a - c * b for a, b in zip(r, v)]
        self.rows[p] = v
        return True

    def rank(self):
        return len(self.rows)

    def nullspace(self):
        piv = sorted(self.rows)
        free = [c for c in range(self.n) if c not in self.rows]
        out = []
        for fc in free:
            v = [0] * self.n
            v[fc] = 1
            for p in piv:
                v[p] = -self.rows[p][fc]
            out.append(v)
        return out


def build(gens, N, lam1, lam2, MS, check=None, names=None):
    """collect the invariance equations for the generators gens.

    check is None  -> return (terms, basis of the solution space);
    check is a list of coefficient vectors -> return the list of names of the
    generators whose equations some of these vectors fails (the independent
    verification: it uses the same rows, but a~larger set of generators and of
    test monomials, and only evaluates them on the given vectors)."""
    ts = binary_terms(N, True)
    if not ts:
        return (ts, []) if check is None else []
    pB = N % 2
    lam = lam1 + lam2 + N
    Ps = [ALG.Dword(A, kA) for (kA, A, kB, Bs) in ts]
    Qs = [ALG.Dword(Bs, kB) for (kA, A, kB, Bs) in ts]
    pQ = [len(Bs) % 2 for (kA, A, kB, Bs) in ts]
    ech = Echelon(len(ts))
    failed = []
    for gi, f in enumerate(gens):
        pf = parity(f)
        sB = -1 if (pf and pB) else 1
        L1, L2, Lt0 = ALG.L(f, lam1), ALG.L(f, lam2), ALG.L(f, lam)
        cache = {}

        def Lt(u, _c=cache, _L=Lt0):
            """L_f is linear: apply it monomial by monomial, with memoization
            (this is what makes the loop below affordable)."""
            out = {}
            for k, c in u.items():
                w = _c.get(k)
                if w is None:
                    w = _c[k] = _L({k: 1})
                for kk, vv in w.items():
                    out[kk] = out.get(kk, 0) + c * vv
            return {k: v for k, v in out.items() if v}

        L1u = {m: L1(mono(*m)) for m in MS}
        L2v = {m: L2(mono(*m)) for m in MS}
        Pu = [{m: Ps[i](mono(*m)) for m in MS} for i in range(len(ts))]
        Qv = [{m: Qs[i](mono(*m)) for m in MS} for i in range(len(ts))]
        PLu = [{m: Ps[i](L1u[m]) for m in MS} for i in range(len(ts))]
        QLv = [{m: Qs[i](L2v[m]) for m in MS} for i in range(len(ts))]
        for m1 in MS:
            pu = par_mon(m1)
            s2 = -1 if (pf and pu) else 1
            pLu = (pu + pf) % 2
            for m2 in MS:
                loc = {}
                for i in range(len(ts)):
                    sgn = -1 if (pQ[i] and pu) else 1
                    sgn1 = -1 if (pQ[i] and pLu) else 1
                    Buv = smul(sgn, mul(Pu[i][m1], Qv[i][m2]))
                    BLuv = smul(sgn1, mul(PLu[i][m1], Qv[i][m2]))
                    BuLv = smul(sgn, mul(Pu[i][m1], QLv[i][m2]))
                    res = add(Lt(Buv), smul(-sB, add(BLuv, smul(s2, BuLv))))
                    for k, val in res.items():
                        loc.setdefault(k, {})[i] = loc.setdefault(k, {}).get(i, 0) + val
                for r in loc.values():
                    row = [r.get(i, 0) for i in range(len(ts))]
                    if not any(row):
                        continue
                    if check is None:
                        ech.add(row)
                    else:
                        for v in check:
                            if sum(a * b for a, b in zip(row, v) if a and b):
                                failed.append(names[gi] if names else str(gi))
                                break
                        if failed and failed[-1] == (names[gi] if names
                                                     else str(gi)):
                            break
                else:
                    continue
                break
            else:
                continue
            break
        if check is None and ech.rank() == len(ts):
            return ts, []
    return failed if check is not None else (ts, ech.nullspace())


def solve(which, N, lam1, lam2, tmax=1, ymax=3, vtmax=2, quiet=False):
    F = ALGS[which]()
    keys = list(START[which])
    MS = testmons(tmax, ymax)
    for attempt in range(6):
        gens = [F[k] for k in keys]
        ts, ns = build(gens, N, lam1, lam2, MS)
        if not quiet:
            print(f"  [{which} N={N}] {len(ts)} terms, {len(keys)} eq.gens, "
                  f"{len(MS)} test monomials -> dim = {len(ns)}", flush=True)
        vnames = sorted(F)
        bad = set(build([F[k] for k in vnames], N, lam1, lam2,
                        testmons(vtmax, 6), check=ns, names=vnames)) if ns \
            else set()
        if not bad:
            return ts, ns, keys, MS
        new = bad - set(keys)
        if new:
            keys += sorted(new)
            if not quiet:
                print(f"      + equations for {sorted(new)}", flush=True)
        else:
            ymax += 1
            tmax += 1
            MS = testmons(tmax, ymax)
            if not quiet:
                print(f"      enlarging the test set to {len(MS)} monomials",
                      flush=True)
    raise RuntimeError("did not stabilize")


if __name__ == '__main__':
    which = sys.argv[1]
    Ns = [int(x) for x in sys.argv[2].split(',')]
    l1 = Fr(sys.argv[3]) if len(sys.argv) > 3 else Fr(3, 7)
    l2 = Fr(sys.argv[4]) if len(sys.argv) > 4 else Fr(-5, 11)
    for N in Ns:
        ts, ns, keys, MS = solve(which, N, l1, l2)
        print(f"{which}: order {N}, lam = ({l1},{l2}): dim = {len(ns)}"
              "   [every vector verified against all generators]")
        for v in ns:
            print("     ", "  ".join(f"{blabel(t)}:{c}"
                                     for t, c in zip(ts, v) if c != 0))
        sys.stdout.flush()
