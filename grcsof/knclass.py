#!/usr/bin/env python3
"""Classification of binary invariant differential operators

     F_{lam1} (x) F_{lam2} --> F_{lam1+lam2+N},      N = -s = the order,

over k(1|n), invariant with respect to a graded subalgebra h with h_- = k(1|n)_-
(for n = 1,2,3 that is h = i(osp(n|2)); for n = 4 also the deformed family, see
k14family.py).

Ansatz (legitimate by [Sh], see Theorem "All invariant differential operators
have constant coefficients in an invariant basis" of the paper): all
combinations, with coefficients constant in t and in the y's, of

     P (x) Q,   P = d_t^{kA} D_A,  Q = d_t^{kB} D_B,   A, B subsets of {1..n},

with 2kA + |A| + 2kB + |B| = N.  The Koszul rule is built in:
     (P (x) Q)(phi, psi) = (-1)^{p(Q) p(phi)} P(phi) Q(psi).

Invariance is imposed for a list of generating functions f (by default the
positive generators t*y_i, since h is generated by h_{-1} and h_1 and the
h_-invariance of the ansatz is automatic -- and is checked separately in
check_neg()):

  L^{lam}_f(B(phi,psi)) = (-1)^{p(f)p(B)} [ B(L_f phi, psi)
                                            + (-1)^{p(f)p(phi)} B(phi, L_f psi) ].
"""
from fractions import Fraction
from itertools import combinations
from superN import (Contact, add, smul, mul, mono, parity, par_mon, d_t,
                    popcount, clean, dtn, compose)


# --------------------------------------------------------------- the ansatz

def terms_of_order(n, N):
    """all (kA, A, kB, B) with 2kA+|A|+2kB+|B| = N."""
    subsets = [()] + [c for r in range(1, n + 1)
                      for c in combinations(range(n), r)]
    out = []
    for A in subsets:
        for B in subsets:
            rest = N - len(A) - len(B)
            if rest < 0 or rest % 2:
                continue
            for kA in range(rest // 2 + 1):
                out.append((kA, A, rest // 2 - kA, B))
    return out


def label(t, names):
    kA, A, kB, B = t
    def one(k, S):
        s = "".join("D" + names[i] for i in S)
        if k:
            s = f"dt^{k}" + s if k > 1 else "dt" + s
        return s or "1"
    return f"{one(kA,A)}(x){one(kB,B)}"


class Classifier:
    def __init__(self, alg, gens, lam1, lam2):
        """alg: Contact;  gens: list of superfunctions (generators of h);
        lam1, lam2: weights (numbers or symbols)."""
        self.alg = alg
        self.gens = gens
        self.lam1, self.lam2 = lam1, lam2

    def build(self, N, tmax=None, zero=None):
        alg, n = self.alg, self.alg.n
        ts = terms_of_order(n, N)
        pB = N % 2
        lam = self.lam1 + self.lam2 + N          # target weight, see below
        if tmax is None:
            tmax = N // 2 + 2
        MS = alg.monos(tmax)

        # precompute the operators of the ansatz
        Ps = [alg.Dword(A, kA) for (kA, A, kB, B) in ts]
        Qs = [alg.Dword(B, kB) for (kA, A, kB, B) in ts]
        pQ = [len(B) % 2 for (kA, A, kB, B) in ts]

        rows = {}
        for f in self.gens:
            pf = parity(f)
            sB = -1 if (pf and pB) else 1
            L1 = alg.L(f, self.lam1)
            L2 = alg.L(f, self.lam2)
            Lt = alg.L(f, lam)
            # cache: action of each P on each monomial and on L1(monomial)
            Pu = [{} for _ in ts]
            Qv = [{} for _ in ts]
            PLu = [{} for _ in ts]
            QLv = [{} for _ in ts]
            L1u = {m: L1(mono(*m)) for m in MS}
            L2v = {m: L2(mono(*m)) for m in MS}
            for i in range(len(ts)):
                for m in MS:
                    Pu[i][m] = Ps[i](mono(*m))
                    Qv[i][m] = Qs[i](mono(*m))
                    PLu[i][m] = Ps[i](L1u[m])
                    QLv[i][m] = Qs[i](L2v[m])
            for m1 in MS:
                pu = par_mon(m1)
                s2 = -1 if (pf and pu) else 1
                pLu = (pu + pf) % 2
                for m2 in MS:
                    for i in range(len(ts)):
                        # B(u,v)
                        sgn = -1 if (pQ[i] and pu) else 1
                        Buv = smul(sgn, mul(Pu[i][m1], Qv[i][m2]))
                        # B(L1 u, v)
                        sgn1 = -1 if (pQ[i] and pLu) else 1
                        BLuv = smul(sgn1, mul(PLu[i][m1], Qv[i][m2]))
                        # B(u, L2 v)
                        BuLv = smul(sgn, mul(Pu[i][m1], QLv[i][m2]))
                        res = add(Lt(Buv),
                                  smul(-sB, add(BLuv, smul(s2, BuLv))))
                        for k, val in res.items():
                            rows.setdefault((f_id(f), m1, m2, k), {})[i] = \
                                rows.setdefault((f_id(f), m1, m2, k), {}).get(i, 0) + val
        return ts, rows

    def solve(self, N, tmax=None, verbose=False):
        ts, rows = self.build(N, tmax)
        mat = [[r.get(i, 0) for i in range(len(ts))] for r in rows.values()]
        mat = [row for row in mat if any(x != 0 for x in row)]
        ns = nullspace(mat, len(ts))
        if verbose:
            print(f"  order {N}: {len(ts)} terms, {len(mat)} equations, "
                  f"dim = {len(ns)}")
        return ts, ns


def f_id(f):
    return tuple(sorted(f.items(), key=str))


# ------------------------------------------------------- exact linear algebra

def nullspace(mat, ncols):
    """Gaussian elimination over the field generated by the entries
    (Fraction, or sympy expressions in the weights -> generic nullspace)."""
    from sympy import simplify, expand, cancel, S
    symbolic = any(not isinstance(x, (int, Fraction)) for row in mat for x in row)
    if symbolic:
        M = [[S(x) for x in row] for row in mat]
        def isz(x):
            return expand(x) == 0
        def red(x):
            return cancel(expand(x))
    else:
        M = [[Fraction(x) for x in row] for row in mat]
        def isz(x):
            return x == 0
        def red(x):
            return x
    pivots = []
    r = 0
    for c in range(ncols):
        piv = None
        for rr in range(r, len(M)):
            if not isz(M[rr][c]):
                piv = rr
                break
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        pv = M[r][c]
        M[r] = [red(x / pv) for x in M[r]]
        for rr in range(len(M)):
            if rr != r and not isz(M[rr][c]):
                fct = M[rr][c]
                M[rr] = [red(a - fct * b) for a, b in zip(M[rr], M[r])]
        pivots.append(c)
        r += 1
        if r == len(M):
            break
    free = [c for c in range(ncols) if c not in pivots]
    basis = []
    for fc in free:
        v = [0] * ncols
        v[fc] = 1
        for i, pc in enumerate(pivots):
            v[pc] = -M[i][fc]
        basis.append(v)
    return basis


# --------------------------------------------------------- standard settings

def osp_gens(alg, positive_only=True):
    """generating functions of i(osp(n|2)) subset k(1|n):
    h_{-1} = <y_i>, h_1 = <t y_i>; h is generated by these."""
    n = alg.n
    pos = [mono(1, 1 << i) for i in range(n)]
    if positive_only:
        return pos
    neg = [mono(0, 0), *[mono(0, 1 << i) for i in range(n)]]
    zero = [mono(1, 0)] + [mono(0, (1 << i) | (1 << j))
                           for i in range(n) for j in range(i + 1, n)]
    top = [mono(2, 0)]
    return neg + zero + pos + top


def check_neg(alg, N, tmax=3):
    """the ansatz is automatically h_-invariant: verify it term by term
    (weights symbolic)."""
    from sympy import symbols, expand
    l1, l2 = symbols('l1 l2')
    gens = [mono(0, 0)] + [mono(0, 1 << i) for i in range(alg.n)]
    C = Classifier(alg, gens, l1, l2)
    ts, rows = C.build(N, tmax)
    bad = set()
    for r in rows.values():
        for i, v in r.items():
            if expand(v) != 0:
                bad.add(i)
    return ts, sorted(bad)


# ------------------------------------------------------------------- unary

class UnaryClassifier:
    """invariant unary operators F_lam --> F_{lam+N}:
         L^{lam+N}_f(P(phi)) = (-1)^{p(f)p(P)} P(L^{lam}_f(phi)).
    Ansatz: P = sum c_{k,A} d_t^k D_A with 2k+|A| = N (constant coefficients)."""

    def __init__(self, alg, gens, lam):
        self.alg, self.gens, self.lam = alg, gens, lam

    def terms(self, N):
        from itertools import combinations
        subs = [()] + [c for r in range(1, self.alg.n + 1)
                       for c in combinations(range(self.alg.n), r)]
        return [(k, A) for A in subs
                for k in [(N - len(A)) // 2]
                if (N - len(A)) >= 0 and (N - len(A)) % 2 == 0]

    def solve(self, N, tmax=None):
        alg = self.alg
        ts = self.terms(N)
        pP = N % 2
        lam2 = self.lam + N
        tmax = tmax if tmax is not None else N // 2 + 2
        MS = alg.monos(tmax)
        Ps = [alg.Dword(A, k) for (k, A) in ts]
        rows = {}
        for f in self.gens:
            pf = parity(f)
            sP = -1 if (pf and pP) else 1
            Ls, Lt = alg.L(f, self.lam), alg.L(f, lam2)
            for m in MS:
                u = mono(*m)
                Lu = Ls(u)
                for i, P in enumerate(Ps):
                    res = add(Lt(P(u)), smul(-sP, P(Lu)))
                    for k, val in res.items():
                        key = (f_id(f), m, k)
                        rows.setdefault(key, {})[i] = \
                            rows.setdefault(key, {}).get(i, 0) + val
        mat = [[r.get(i, 0) for i in range(len(ts))] for r in rows.values()]
        mat = [row for row in mat if any(x != 0 for x in row)]
        return ts, nullspace(mat, len(ts))
