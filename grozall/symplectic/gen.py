# ---------------------------------------------------------------- slot layout


class Layout:
    def __init__(self, a, b, kl, km, kn):
        self.a, self.b, self.kl, self.km, self.kn = a, b, kl, km, kn
        self.dA = list(range(a))
        self.A = list(range(a, a + kl))
        o = a + kl
        self.dB = list(range(o, o + b))
        self.B = list(range(o + b, o + b + km))
        o = o + b + km
        self.O = list(range(o, o + kn))
        self.nslots = o + kn
        kind = {}
        for s in self.dA:
            kind[s] = "dA"
        for s in self.A:
            kind[s] = "A"
        for s in self.dB:
            kind[s] = "dB"
        for s in self.B:
            kind[s] = "B"
        for s in self.O:
            kind[s] = "O"
        self.kind = kind
        self.Apos = {s: i for i, s in enumerate(self.A)}
        self.Bpos = {s: i for i, s in enumerate(self.B)}
        self.Opos = {s: i for i, s in enumerate(self.O)}

    def name(self, s):
        k = self.kind[s]
        if k == "dA":
            return f"d{self.dA.index(s)+1}X"
        if k == "dB":
            return f"d{self.dB.index(s)+1}Y"
        if k == "A":
            return f"X{self.Apos[s]+1}"
        if k == "B":
            return f"Y{self.Bpos[s]+1}"
        return f"o{self.Opos[s]+1}"


def _pairings(items):
    if not items:
        yield ()
        return
    a = items[0]
    for i in range(1, len(items)):
        b = items[i]
        rest = items[1:i] + items[i + 1:]
        for p in _pairings(rest):
            yield ((a, b),) + p


def enumerate_schemes(a, b, kl, km, kn):
    """All admissible matchings, up to permuting derivative slots."""
    L = Layout(a, b, kl, km, kn)
    if L.nslots % 2:
        return L, []
    dAset, dBset = set(L.dA), set(L.dB)
    Aset, Bset = set(L.A), set(L.B)
    seen, out = set(), []
    # the symmetry group: permutations of dA among themselves, dB likewise
    syms = []
    for pa in permutations(L.dA):
        for pb in permutations(L.dB):
            mp = {s: s for s in range(L.nslots)}
            for s, t in zip(L.dA, pa):
                mp[s] = t
            for s, t in zip(L.dB, pb):
                mp[s] = t
            syms.append(mp)
    for pairs in _pairings(list(range(L.nslots))):
        bad = False
        for (s, t) in pairs:
            if (s in dAset and t in dAset) or (s in dBset and t in dBset):
                bad = True
                break
            if (s in Aset and t in Aset) or (s in Bset and t in Bset):
                bad = True
                break
        if bad:
            continue
        best = None
        for mp in syms:
            key = tuple(sorted(tuple(sorted((mp[s], mp[t]))) for (s, t) in pairs))
            if best is None or key < best:
                best = key
        if best in seen:
            continue
        seen.add(best)
        out.append(best)
    return L, out


def scheme_label(L, pairs):
    return " ".join(f"({L.name(s)}-{L.name(t)})" for (s, t) in pairs)


# ------------------------------------------------------------------ evaluation


def deriv_table(S, T, order):
    """{sorted direction tuple -> array of polynomials} for orders 0..order."""
    n = S.n
    tab = {(): T}
    cur = [()]
    for _ in range(order):
        nxt = []
        for al in cur:
            base = tab[al]
            for d in range(n):
                new = tuple(sorted(al + (d,)))
                if new in tab:
                    continue
                tab[new] = [pdiff(p, d) if p else {} for p in base]
                nxt.append(new)
        cur = nxt
    return tab


class Term:
    __slots__ = ("L", "pairs", "inin", "inout", "outout")

    def __init__(self, L, pairs):
        self.L = L
        self.pairs = pairs
        self.inin, self.inout, self.outout = [], [], []
        for (s, t) in pairs:
            ks, kt = L.kind[s], L.kind[t]
            if ks == "O" and kt == "O":
                self.outout.append((L.Opos[s], L.Opos[t]))
            elif ks == "O":
                self.inout.append((t, L.Opos[s]))
            elif kt == "O":
                self.inout.append((s, L.Opos[t]))
            else:
                self.inin.append((s, t))


def eval_term(S, term, dtA, dtB, Omd):
    """The value of one scheme on the pair of fields, as an array over
    {0..n-1}^{k_nu} of polynomials."""
    L = term.L
    n = S.n
    out = [None] * (n ** L.kn)
    Omnz = S.Omnz
    ninin = len(term.inin)
    # enumerate the assignments of the contracted pairs once
    combos = [((), Fraction(1))]
    for _ in range(ninin):
        new = []
        for asg, w in combos:
            for u, v, c in Omnz:
                new.append((asg + ((u, v),), w * c))
        combos = new
    for fj in range(n ** L.kn):
        J = unflat(fj, n, L.kn)
        coef0 = Fraction(1)
        for (o1, o2) in term.outout:
            coef0 *= Omd[J[o1]][J[o2]]
        if coef0 == 0:
            out[fj] = {}
            continue
        acc = {}
        for asg, w in combos:
            idx = [None] * L.nslots
            for (s, o) in term.inout:
                idx[s] = J[o]
            for (s, t), (u, v) in zip(term.inin, asg):
                idx[s] = u
                idx[t] = v
            al = tuple(sorted(idx[s] for s in L.dA))
            be = tuple(sorted(idx[s] for s in L.dB))
            IA = flat(tuple(idx[s] for s in L.A), n)
            IB = flat(tuple(idx[s] for s in L.B), n)
            fa = dtA[al][IA]
            if not fa:
                continue
            fb = dtB[be][IB]
            if not fb:
                continue
            c = w * coef0
            for e1, c1 in fa.items():
                for e2, c2 in fb.items():
                    e = tuple(p + q for p, q in zip(e1, e2))
                    v2 = acc.get(e, 0) + c1 * c2 * c
                    if v2:
                        acc[e] = v2
                    elif e in acc:
                        del acc[e]
        out[fj] = acc
    return out


# ---------------------------------------------------------------- the system


class Problem:
    def __init__(self, S, Fl, Fm, Fn, order):
        self.S, self.Fl, self.Fm, self.Fn = S, Fl, Fm, Fn
        self.order = order
        n = S.n
        self.Omd = [[-S.Om[i][j] for j in range(n)] for i in range(n)]  # omega_{ij}
        self.terms = []
        self.labels = []
        for a in range(order + 1):
            b = order - a
            L, schemes = enumerate_schemes(a, b, Fl.k, Fm.k, Fn.k)
            for pr in schemes:
                self.terms.append(Term(L, pr))
                self.labels.append(f"[{a}|{b}] " + scheme_label(L, pr))

    def eval_all(self, A, B):
        S = self.S
        dtA = deriv_table(S, A, self.order)
        dtB = deriv_table(S, B, self.order)
        return [eval_term(S, t, dtA, dtB, self.Omd) for t in self.terms]

    # ---- equations -------------------------------------------------------
    def membership_rows(self, A, B):
        """rows expressing that the value lies in V_nu."""
        vals = self.eval_all(A, B)
        n, kn = self.S.n, self.Fn.k
        rows = []
        for phi in self.Fn.ann:
            support = [i for i, c in enumerate(phi) if c]
            cols = []
            for V in vals:
                acc = {}
                for i in support:
                    c = phi[i]
                    for e, v in V[i].items():
                        w = acc.get(e, 0) + c * v
                        if w:
                            acc[e] = w
                        elif e in acc:
                            del acc[e]
                cols.append(acc)
            keys = set()
            for acc in cols:
                keys |= set(acc)
            for e in sorted(keys):
                rows.append([acc.get(e, Fraction(0)) for acc in cols])
        return rows

    def defect_rows(self, A, B, f):
        S, kn = self.S, self.Fn.k
        LA = lie_tensor(S, self.Fl.k, f, A)
        LB = lie_tensor(S, self.Fm.k, f, B)
        v0 = self.eval_all(A, B)
        v1 = self.eval_all(LA, B)
        v2 = self.eval_all(A, LB)
        cols = []
        for V0, V1, V2 in zip(v0, v1, v2):
            LV = lie_tensor(S, kn, f, V0)
            d = []
            for i in range(S.n ** kn):
                d.append(padd(LV[i], pscale(padd(V1[i], V2[i]), -1)))
            cols.append(d)
        rows = []
        keys = set()
        for d in cols:
            for i in range(S.n ** kn):
                for e in d[i]:
                    keys.add((i, e))
        for (i, e) in sorted(keys):
            rows.append([d[i].get(e, Fraction(0)) for d in cols])
        return rows

    def operator_rank(self, coeffs, probes):
        """Dimension of the space of OPERATORS spanned by the coefficient
        vectors (kills the relations among the ansatz terms)."""
        S, kn = self.S, self.Fn.k
        fps = []
        cache = [self.eval_all(A, B) for (A, B) in probes]
        for v in coeffs:
            row = []
            for vals in cache:
                acc = [dict() for _ in range(S.n ** kn)]
                for c, V in zip(v, vals):
                    if c == 0:
                        continue
                    for i in range(S.n ** kn):
                        if V[i]:
                            acc[i] = padd(acc[i], pscale(V[i], c))
                row.append(acc)
            fps.append(row)
        keys = []
        for pi in range(len(probes)):
            s = set()
            for row in fps:
                for i in range(S.n ** kn):
                    for e in row[pi][i]:
                        s.add((i, e))
            keys.append(sorted(s))
        M = []
        for row in fps:
            r = []
            for pi in range(len(probes)):
                for (i, e) in keys[pi]:
                    r.append(row[pi][i].get(e, Fraction(0)))
            M.append(r)
        if not M or not M[0]:
            return 0, M
        return rank(M), M
