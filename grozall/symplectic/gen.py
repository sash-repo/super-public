"""Diff^omega-invariant bilinear operators with GENERAL irreducible fibers.

    B : T(lambda) x T(mu) --> T(nu),        lambda, mu, nu partitions with <= m rows.

The ansatz.  Translation invariance makes the symbol constant; Sp(2m)-covariance
plus the first fundamental theorem for Sp make it a linear combination of
complete contraction schemes.  A scheme is a perfect matching of the slot list

    [a derivative slots on chi][k_lambda fiber slots of chi]
    [b derivative slots on theta][k_mu fiber slots of theta][k_nu output slots],

the first four blocks carrying an UP index (they are contracted against a tensor
with down indices) and the last one a DOWN index.  A matched pair contributes

    in-in    omega^{uv}, summed;
    in-out   delta, i.e. the input index is the output index of that slot;
    out-out  omega_{..} inserted into the output.

Schemes matching two derivative slots of one factor, or two fiber slots of one
factor, are dropped: the first vanish because omega is antisymmetric while
partial derivatives commute, the second because the fibers are omega-traceless.

The conditions.  An operator of the ansatz is Diff^omega-invariant if and only if

  (M) its value lies in V_nu at every point, and
  (I) it commutes with the Lie derivative along the cubic Hamiltonians,

because h(2m) is generated by h_{-1} + h_0 + h_1 and the ansatz is by
construction h_{-1}- and h_0-invariant.
"""

