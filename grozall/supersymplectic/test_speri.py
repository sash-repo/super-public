"""Calibration of the PERIPLECTIC (odd symplectic) setup: sdim (k|k), Buttin's
antibracket, the Hamiltonian algebra le(k), aut(omega) = pe(k).

Same discipline as test_ssuper.py: the sign of the antibracket is FOUND by
requiring super-antisymmetry (in the shifted sense, the bracket being odd) and
the odd Jacobi identity; the Lie derivative is then checked to be a
representation of le(k) and to satisfy L_X(df) = d(X f).
"""
import os, random, sys
from fractions import Fraction
from itertools import product
from ssuper import SSetup

def mk(k, oc, hs):
    return SSetup(k, k, "S", odd_coef=oc, ham_sign=hs, form="odd")

def bracket_ok(k, oc, hs):
    S = mk(k, oc, hs); A = S.A
    mons = [p for d in range(1,4) for p in S.monomials(d)]
    rng = random.Random(7)
    if len(mons) > 12: mons = rng.sample(mons, 12)
    for f in mons:
        for g in mons:
            pf, pg = A.parity(f), A.parity(g)
            lhs = S.bracket(f,g)
            rhs = A.scale(S.bracket(g,f), -1 if not ((pf+1)*(pg+1))%2 else 1)
            if lhs != rhs: return False, "antisymmetry"
    for f in mons[:7]:
        for g in mons[:7]:
            for h in mons[:7]:
                pf, pg = A.parity(f), A.parity(g)
                lhs = S.bracket(f, S.bracket(g,h))
                rhs = A.add(S.bracket(S.bracket(f,g), h),
                            A.scale(S.bracket(g, S.bracket(f,h)),
                                    -1 if ((pf+1)*(pg+1))%2 else 1))
                if lhs != rhs: return False, "Jacobi"
    return True, "ok"

print("=== the antibracket: which sign?")
good = []
for k in (1,2,3):
    row = []
    for oc in (1,-1):
        for hs in (1,-1):
            ok, why = bracket_ok(k, oc, hs)
            row.append(((oc,hs), ok, why))
    print(f"  k={k}: " + ", ".join(f"({oc:+d},{hs:+d}):{'OK' if ok else 'no/'+why}"
                                   for (oc,hs),ok,why in row))
    good.append({kk for kk,ok,_ in row if ok})
common = set.intersection(*good)
print("  admissible:", sorted(common))
if not common:
    sys.exit("no admissible antibracket sign")
oc, hs = sorted(common)[0]
print(f">>> using odd_coef={oc}, ham_sign={hs}")

print("\n=== X_f is a derivation and X_f^k reproduces {f,-}")
ok = True
for k in (1,2,3):
    S = mk(k,oc,hs); A=S.A
    mons=[p for d in range(1,4) for p in S.monomials(d)]
    rng=random.Random(3); sel=rng.sample(mons,min(10,len(mons)))
    for f in sel:
        for g in sel:
            if S.act(f,g) != S.bracket(f,g): ok=False
print("  ", "PASS" if ok else "FAIL")

print("\n=== the Lie derivative: 1-forms and the representation property")
for k in (1,2,3):
    S = mk(k,oc,hs); A=S.A
    fs=[p for d in range(1,4) for p in S.monomials(d)]
    gs=[p for d in range(0,4) for p in S.monomials(d)]
    one = all(S.lie(X, S.dform(f)) == S.dform(S.bracket(X,f)) for X in fs for f in gs)
    rng=random.Random(5); T=S.random_field(2,rng,nterms=3)
    rep=True
    for f in fs:
        for g in fs:
            pf,pg=(A.parity(f)+1)%2,(A.parity(g)+1)%2
            lhs=A.add(S.lie(f,S.lie(g,T)),
                      A.scale(S.lie(g,S.lie(f,T)), -1 if not (pf*pg)%2 else 1))
            if lhs != S.lie(S.bracket(f,g),T): rep=False; break
        if not rep: break
    print(f"  k={k}: L_X(df)=d(Xf) {one}, representation of le({k}) {rep}")

print("\n=== is le(k) generated by its part of degree <= 3?")
_HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "..", "lib"), _HERE]
from exactlin import rank
for k in (1,2,3):
    S=mk(k,oc,hs)
    deg3=S.monomials(3); target=S.monomials(4)
    if not target: print(f"  k={k}: no degree-4 part"); continue
    keys={}
    for p in target:
        for kk in p: keys.setdefault(kk,len(keys))
    rows=[]
    for f in deg3:
        for g in deg3:
            b=S.bracket(f,g)
            if not b: continue
            row=[Fraction(0)]*len(keys); bad=False
            for kk,c in b.items():
                if kk not in keys: bad=True; break
                row[keys[kk]]=c
            if not bad: rows.append(row)
    r=rank(rows) if rows else 0
    print(f"  k={k}: image {r} of dim h_2 = {len(target)}  {'OK' if r==len(target) else 'GAP'}")

print("\n=== the fiber")
for k in (1,2,3):
    S=mk(k,oc,hs); ev,od=S.sdim_fiber()
    print(f"  k={k}: sdim S^2(W^*) = ({ev}|{od}) for W of sdim ({k}|{k})")
