"""Does EVERY invariant order-2 operator over an odd form factor through the trace?

soddshapes.py shows the only unary invariants on metrics are the identity, the
periplectic trace ptr(A) = omega^{ij}A_{ij} and -- what looked like a second,
independent first-order operator -- d(ptr A), the differential of that same trace.
So the whole census is generated by ptr, and sodddecomp.py identifies the three
order-2 operators as

        C1(A,B) = L_{X_{ptr A}} B,   C2(A,B) = L_{X_{ptr B}} A,
        C3(A,B) = d(ptr A) . d(ptr B).

The sharp consequence to test here: on the pair of metrics with VANISHING trace
every one of them dies, i.e.

        ptr A = ptr B = 0   ==>   T(A,B) = 0   for every invariant T of order 2.

That is what "there is no analog of Gz over an odd form" means concretely -- and
it is exactly the statement that FAILS over an even form, where ptr is identically
zero and Gz is nevertheless non-zero.

Usage:  python3 soddfactor.py [k]
"""

import random
import os
import sys
from fractions import Fraction

_HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "..", "lib"), _HERE]

from ssuper import SSetup                                  # noqa: E402
from sgen import enumerate_schemes, evaluate               # noqa: E402
from sodd0 import ptr                                      # noqa: E402
from sodddecomp import basis_order2                        # noqa: E402

N = 2


def traceless_fields(S, deg, rng, npool=24, want=2):
    """Metrics with ptr A = 0, built by exact linear algebra.

    Guessing a correction term is what fails here: ptr is ODD, so moving it past
    a coefficient carries a sign, and the naive "subtract ptr(A)/c times the
    metric dual to omega" produces nothing at all.  Instead: draw a pool of random
    fields, compute ptr of each, and take the kernel of that linear map.  Nothing
    is assumed and the fields come out non-zero by construction.
    """
    A = S.A
    # the fiber monomials the trace kills outright: ptr(f * u^i u^j) = +- f ptr(u^i u^j)
    good = [(ij, fib) for (ij, fib) in S.fiber_monomials() if not ptr(S, fib)]
    assert good, "the trace kills no fiber monomial"
    mons = [p for d in range(deg + 1) for p in S.monomials(d)]
    out = []
    for _ in range(want * 8):
        terms = []
        for (ij, fib) in good:
            pf = A.parity(fib)
            pool = [p for p in mons if A.parity(p) == pf]   # keep the field even
            if not pool:
                continue
            for p in rng.sample(pool, min(3, len(pool))):
                c = rng.randint(-4, 4)
                if c:
                    terms.append(A.scale(A.mul(p, fib), c))
        Q = A.summ(terms)
        if Q and not ptr(S, Q):
            out.append(Q)
        if len(out) >= want:
            break
    return out


def main():
    k = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    S = SSetup(k, k, form="odd")
    A = S.A
    schemes = enumerate_schemes(N)
    R, dim = basis_order2(S, k, schemes)
    print(f"PERIPLECTIC k = {k}: the space of order-2 invariants has dimension {dim}")

    G = A.summ([A.scale(A.mul(S.u(i), S.u(j)), w) for (i, j, w) in S.Omnz])
    print(f"  ptr of the metric dual to omega: {ptr(S, G)}")

    rng = random.Random(6180 + k)
    ntested = 0
    allzero = True
    for _ in range(3):
        fields = traceless_fields(S, 4, rng, want=2)
        if len(fields) < 2:
            continue
        P, Q = fields[0], fields[1]
        assert P and Q, "the traceless field came out zero"
        assert not ptr(S, P) and not ptr(S, Q)
        ntested += 1
        for i, v in enumerate(R):
            val = A.summ([A.scale(evaluate(S, sch, P, Q), c)
                          for c, sch in zip(v, schemes) if c])
            if val:
                allzero = False
                print(f"    basis element e{i+1} is NON-ZERO on a traceless pair")
    print(f"  traceless pairs tested: {ntested}  (each field non-zero, "
          f"trace exactly 0)")
    if ntested == 0:
        print("  INCONCLUSIVE: no traceless pair was constructed")
        return
    print(f"  every invariant of order 2 vanishes on them: "
          f"{'YES' if allzero else 'NO'}")
    if allzero:
        print("  ==> every order-2 invariant factors through the periplectic trace;"
              "\n      over an odd form there is no analog of Gz.")

    # the contrast, in one line: over an even form Gz survives a vanishing trace
    print("\n  contrast, even form (m,n) = (2,0): ptr is identically 0 there,")
    print("  so EVERY metric is traceless and Gz is nevertheless non-zero"
          " -- see Section 11 of the text.")


if __name__ == "__main__":
    main()
