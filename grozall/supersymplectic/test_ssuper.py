"""Self-tests and sign calibration for ssuper.py.

Nothing in the engine is taken on faith.  This script

  1) checks the superalgebra (supercommutativity, Leibniz, left derivatives);
  2) finds the sign in the Poisson bracket of po(2m|n) by requiring super-
     antisymmetry and the super Jacobi identity;
  3) checks that a Hamiltonian field is a derivation and that its components
     reproduce the bracket;
  4) (the sign of the Lie derivative is decided separately, in liesign.py);
  5) checks that h(2m|n) is generated by its part of degree <= 3, which is what
     makes the invariance conditions a finite system;
  6) checks the n = 0 case against the old engine symp.py.

Usage:  python3 test_ssuper.py
"""

import random
import os
import sys
from fractions import Fraction
from itertools import product

from ssuper import Super, SSetup


def hdr(s):
    print("\n" + "=" * 70)
    print(s)
    print("=" * 70)


# ------------------------------------------------------------------ 1) algebra

def test_algebra():
    hdr("1) the superalgebra")
    A = Super(2, 3)
    x, y = A.gen_ev(0), A.gen_ev(1)
    t1, t2, t3 = A.gen_od(0), A.gen_od(1), A.gen_od(2)
    ok = True
    ok &= A.mul(t1, t2) == A.scale(A.mul(t2, t1), -1)
    ok &= A.mul(t1, t1) == {}
    ok &= A.mul(x, t1) == A.mul(t1, x)
    # left derivative: d_1 (t1 t2 t3) = -(t1 t3)
    p = A.mul(A.mul(t1, t2), t3)
    ok &= A.d_od(p, 1) == A.scale(A.mul(t1, t3), -1)
    ok &= A.d_od(p, 0) == A.mul(t2, t3)
    ok &= A.d_od(p, 2) == A.mul(t1, t2)
    # Leibniz with signs: d_a(pq) = (d_a p) q + (-1)^{p(p)} p (d_a q)
    rng = random.Random(1)
    for _ in range(20):
        f = A.summ([A.scale(A.mul(A.mul(x, t1), t2), rng.randint(-3, 3)),
                    A.scale(A.mul(y, t3), rng.randint(-3, 3))])
        g = A.summ([A.scale(A.mul(x, t2), rng.randint(-3, 3)),
                    A.scale(t1, rng.randint(-3, 3))])
        for a in range(3):
            for fh in A.parity_parts(f):
                if not fh:
                    continue
                pf = A.parity(fh)
                lhs = A.d_od(A.mul(fh, g), a)
                rhs = A.add(A.mul(A.d_od(fh, a), g),
                            A.scale(A.mul(fh, A.d_od(g, a)), -1 if pf else 1))
                ok &= lhs == rhs
    print("supercommutativity, left derivatives, Leibniz:", "PASS" if ok else "FAIL")
    return ok


# ------------------------------------------------------------------ 2) bracket

def bracket_ok(m, n, odd_coef, ham_sign, ndeg=3):
    S = SSetup(m, n, "S", odd_coef=odd_coef, ham_sign=ham_sign)
    A = S.A
    mons = [p for d in range(1, ndeg + 1) for p in S.monomials(d)]
    rng = random.Random(7)
    if len(mons) > 14:
        mons = rng.sample(mons, 14)
    for f in mons:
        for g in mons:
            pf, pg = A.parity(f), A.parity(g)
            lhs = S.bracket(f, g)
            rhs = A.scale(S.bracket(g, f), -1 if not (pf * pg) % 2 else 1)
            if lhs != rhs:
                return False, "antisymmetry"
    for f in mons[:8]:
        for g in mons[:8]:
            for h in mons[:8]:
                pf, pg = A.parity(f), A.parity(g)
                lhs = S.bracket(f, S.bracket(g, h))
                rhs = A.add(S.bracket(S.bracket(f, g), h),
                            A.scale(S.bracket(g, S.bracket(f, h)),
                                    -1 if (pf * pg) % 2 else 1))
                if lhs != rhs:
                    return False, "Jacobi"
    return True, "ok"


def test_bracket():
    hdr("2) the Poisson bracket of po(2m|n): which sign?")
    good = []
    for m, n in [(1, 1), (1, 2), (2, 2)]:
        row = []
        for oc in (1, -1):
            for hs in (1, -1):
                ok, why = bracket_ok(m, n, oc, hs)
                row.append(((oc, hs), ok, why))
        print(f"  (m,n)=({m},{n}): " +
              ", ".join(f"odd_coef={oc:+d},ham_sign={hs:+d}: "
                        f"{'OK' if ok else 'no ('+why+')'}"
                        for (oc, hs), ok, why in row))
        good.append({k for k, ok, _ in row if ok})
    common = set.intersection(*good)
    print("  admissible for every (m,n) tested:", sorted(common))
    return common


# --------------------------------------------------- 3) Hamiltonian fields

def test_ham(oc, hs):
    hdr("3) Hamiltonian fields are derivations, and X_f^k reproduces {f,-}")
    ok = True
    for m, n in [(1, 1), (1, 2), (2, 2)]:
        S = SSetup(m, n, "S", odd_coef=oc, ham_sign=hs)
        A = S.A
        mons = [p for d in range(1, 4) for p in S.monomials(d)]
        rng = random.Random(3)
        test = rng.sample(mons, min(10, len(mons)))
        for f in test:
            for g in test:
                if S.act(f, g) != S.bracket(f, g):
                    ok = False
                    print(f"  FAIL: X^k d_k g != {{f,g}} at (m,n)=({m},{n})")
                    break
            # derivation property
            for g in test[:5]:
                for h in test[:5]:
                    pf, pg = A.parity(f), A.parity(g)
                    lhs = S.bracket(f, A.mul(g, h))
                    rhs = A.add(A.mul(S.bracket(f, g), h),
                                A.scale(A.mul(g, S.bracket(f, h)),
                                        -1 if (pf * pg) % 2 else 1))
                    if lhs != rhs:
                        ok = False
                        print(f"  FAIL: derivation at (m,n)=({m},{n})")
    print("Hamiltonian fields:", "PASS" if ok else "FAIL")
    return ok


# ------------------------------------------------------------- 5) generation

def test_generation(oc, hs, lie_bits):
    hdr("5) is h(2m|n) generated by its part of degree <= 3?")
    ok = True
    for m, n in [(1, 1), (1, 2), (1, 3), (2, 1), (2, 2), (2, 3)]:
        S = SSetup(m, n, "S", odd_coef=oc, ham_sign=hs)
        A = S.A
        deg3 = S.monomials(3)
        target = S.monomials(4)
        if not target:
            print(f"  (m,n)=({m},{n}): no degree-4 part")
            continue
        keys = {}
        for p in target:
            for k in p:
                keys.setdefault(k, len(keys))
        rows = []
        for f in deg3:
            for g in deg3:
                b = S.bracket(f, g)
                if not b:
                    continue
                row = [Fraction(0)] * len(keys)
                bad = False
                for k, c in b.items():
                    if k not in keys:
                        bad = True
                        break
                    row[keys[k]] = c
                if not bad:
                    rows.append(row)
        _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "..", "lib"), _HERE]
        from exactlin import rank
        r = rank(rows) if rows else 0
        print(f"  (m,n)=({m},{n}): dim h_1*h_1 -> h_2 image = {r}, "
              f"dim h_2 = {len(target)}  {'OK' if r == len(target) else 'GAP'}")
        ok &= (r == len(target))
    print("generation by degree <= 3:", "PASS" if ok else "FAIL")
    return ok


# ---------------------------------------------------- 6) the classical case

def test_classical(oc, hs, lie_bits):
    hdr("6) n = 0: does the super engine reproduce symp.py?")
    import symp
    ok = True
    for m in (1, 2):
        S = SSetup(m, 0, "S", odd_coef=oc, ham_sign=hs)
        S.set_lie_sign(lie_bits)
        C = symp.Symp(m)
        rng = random.Random(19)
        # a random symmetric tensor field in the old format, and its u-encoding
        Aold = symp.random_sym_field(C, 2, rng)
        Anew = S.A.zero()
        for i in range(2 * m):
            for j in range(2 * m):
                p = {}
                for e, c in Aold[i][j].items():
                    p[(e + (0,) * (2 * m), 0)] = c
                if p:
                    Anew = S.A.add(Anew, S.A.mul(p, S.A.mul(S.u(i), S.u(j))))
        for f_old in symp.monomial_polys(C, 3)[:6]:
            fnew = {(e + (0,) * (2 * m), 0): c for e, c in f_old.items()}
            Lold = C.lie_sym2(f_old, Aold)
            Lnew_ref = S.A.zero()
            for i in range(2 * m):
                for j in range(2 * m):
                    p = {(e + (0,) * (2 * m), 0): c for e, c in Lold[i][j].items()}
                    if p:
                        Lnew_ref = S.A.add(Lnew_ref,
                                           S.A.mul(p, S.A.mul(S.u(i), S.u(j))))
            if S.lie(fnew, Anew) != Lnew_ref:
                ok = False
                print(f"  FAIL at m={m}")
                break
        print(f"  m={m}: {'agrees with symp.py' if ok else 'DISAGREES'}")
    print("classical limit:", "PASS" if ok else "FAIL")
    return ok


def main():
    test_algebra()
    common = test_bracket()
    oc, hs = (1, 1) if (1, 1) in common else sorted(common)[0]
    print(f"\n>>> using odd_coef={oc}, ham_sign={hs}")
    test_ham(oc, hs)
    # 4) the sign of the Lie derivative is decided in liesign.py
    lies = {(0,) * 8}
    bits = (0,) * 8
    print(f"\n>>> using LIE_SIGN = {bits}")
    test_generation(oc, hs, bits)
    test_classical(oc, hs, bits)
    hdr("summary")
    print(f"odd_coef = {oc}, ham_sign = {hs}, LIE_SIGN = {bits}")
    print("(the Lie sign is the one liesign.py singles out)")


if __name__ == "__main__":
    main()
