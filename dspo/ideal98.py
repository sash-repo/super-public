"""Statement 3.2.6, m=7, x=xi1xi2xi3eta1theta: s = g_x/r is (9|8) and perfect.
The ideal generated by the kernel of the Killing form of s_0 is computed; it is
proper, so s is not simple.
Usage: python3 ideal98.py
"""
import numpy as np
from radical2 import *
from probe import sub_alg
po = Po(7)
msk = next(mm for mm in range(1 << 7) if po.name(mm) == "xi1xi2xi3eta1theta")
q = Quot(po, {msk: 1})
T = np.array([[[modp(c) for c in v] for v in row] for row in q.table()], dtype=np.int64)
s, _ = radical_quotient(Alg(T, q.par))
I = np.eye(s.d, dtype=np.int64)
ev = [i for i in range(s.d) if s.par[i] == 0]
E = sub_alg(s, I[ev])
A = [E.ad_of(np.eye(E.d, dtype=np.int64)[i]) for i in range(E.d)]
K = np.array([[int(np.trace(matmul(X, Y)) % P) for Y in A] for X in A], dtype=np.int64)
ker = nullspace(K, E.d)                     # coordinates in E's rref basis
Bev = rref(I[ev])[0]
gens = matmul(ker, Bev)                     # back to s coordinates
print("ker Killing(s_0):", len(ker))
J = rref(gens)[0]
while True:
    J2 = rref(np.vstack([J, s.span_br(I, J)]))[0]
    if len(J2) == len(J): break
    J = J2
par = []
for r in J:
    ps = {s.par[i] for i in np.nonzero(r)[0]}; par.append(ps.pop() if len(ps)==1 else None)
print("ideal generated:", len(J), "of", s.d, "parities", par.count(0), par.count(1), par.count(None))
Ja = sub_alg(s, J)
print("ideal: sdim", Ja.sdim(), "dim [J,J]", Ja.derived_dim(), "centroid<=", Ja.centroid_bound())
