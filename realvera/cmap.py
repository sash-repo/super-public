#!/usr/bin/env python3
r"""Exact check of the row-by-row reading of the map c_h of Subsection 11.7.4.

    c_h : Aut h / Aut^o h  -->  Aut g / Aut^o g,      g = h (x) C,

induced by the complexification of a real form h of g.  The target is the group
of Table (185) of the text -- Aut g/Aut^o g -- and NOT the group Out g =
Aut g/Int g of Table (td4.2): the text itself says (Subsec. 13.2.1) that for
loop superalgebras "the group Out g is too big, whereas Out^o g is just right",
and its own reduction 13.3.8 runs over the classes in Aut g/Aut^o g.

What is verified here, exactly, in the matrix realizations, over Q(i):

 (A) (-st)^2 = delta_{-1}  on gl(m|n).
     Hence -st has order 4 as an automorphism but order 2 modulo Aut^o g,
     because delta_{-1} = Add_{(1_m, -1_n)} is inner over C.  Over R it is
     inner only when det(-1_n) = (-1)^n > 0, i.e. n even -- which is exactly
     why Table (t-d4.14) prints Z/4 = <mst> for sl_R(2m+1|2n+1) and Z/2 for
     sl_R(2m|2n) and sl_R(2m+1|2n).  So the Z/4 --> Z/2 of that row is not an
     accident: the kernel is generated by mst^2 = delta_{-1}.

 (B) q^2 = delta_{-1} and q^4 = id on q(n); q = -st . delta_i.
     In Out^o psq(n) = Z/4 = <qbar> the element delta_{-1} is therefore the
     unique element of order 2, i.e. qbar^2.  So every row of Table (t-d4.14)
     whose generator is delta_{-1} lands in <qbar^2> = Z/2, and qbar^{+-1} is
     never reached.

 (C) [Pi, -st] = delta_{-1} on gl(n|n): Pi and -st commute modulo delta_{-1},
     which is inner over C for psl(n|n) (the family {delta_lambda} is
     connected), so their classes commute -- as they must, Out^o psl(n|n)
     being Z/2 x Z/2 -- and the class of Pi.(-st) is the product
     Pibar . mstbar, the third involution.  This is the supe(n) row.

 (D) On osp(k|2n): Ad_{diag(-1_k, 1_{2n})} = Ad_{diag(1_k, -1_{2n})}.
     For k odd this makes the reflection class inner (-1_{2n} lies in the
     connected Sp(2n)), so O(k)/SO(k) dies in Out^o osp(k|2n) = {1}; for k
     even it does not, and the class is AdTbar.  That is the sharp
     non-uniformity of the two osp rows of Table (t-d4.14).

 (E) delta_lambda is an automorphism of gl(m|n) for every lambda, but of q(n)
     only for lambda^2 = 1.  Hence {delta_lambda} is a connected subgroup of
     Aut g -- so delta_{-1} is in Aut^o g -- for g = psl(n|n), spe(n),
     svect(n), h'(n), and is NOT for g = psq(n).  This is what decides every
     delta_{-1} entry of the reading.

 (F) Sanity: each map used is an automorphism of the algebra it is applied to
     (bracket preserved on a basis), and the real-form determinant signs
     quoted in (A) are recomputed rather than asserted.

No floating point anywhere: entries are sympy numbers in Q(i).
"""
import itertools
import sys

import sympy as sp

I = sp.I


# --------------------------------------------------------------- supermatrices
# A supermatrix of format m|n is a sympy Matrix of size (m+n)x(m+n); the parity
# of the basis vector e_i is 0 for i < m and 1 for i >= m.


def parity_vec(m, n):
    return [0] * m + [1] * n


def blocks(X, m, n):
    return (X[:m, :m], X[:m, m:], X[m:, :m], X[m:, m:])


def from_blocks(A, B, C, D):
    return sp.Matrix(sp.BlockMatrix([[A, B], [C, D]]))


def mat_parity(X, m, n):
    """0 if X is even, 1 if X is odd, None if inhomogeneous/zero-ambiguous."""
    A, B, C, D = blocks(X, m, n)
    ev = A.is_zero_matrix and D.is_zero_matrix
    od = B.is_zero_matrix and C.is_zero_matrix
    if od and not ev:
        return 0
    if ev and not od:
        return 1
    if od and ev:
        return 0  # zero matrix
    return None


def sbracket(X, Y, m, n):
    """Supercommutator, for X, Y of definite parity."""
    pX, pY = mat_parity(X, m, n), mat_parity(Y, m, n)
    sign = -1 if (pX == 1 and pY == 1) else 1
    return sp.expand(X * Y - sign * (Y * X))


def basis_gl(m, n):
    """The elementary supermatrices, with their parities."""
    N = m + n
    out = []
    for i in range(N):
        for j in range(N):
            E = sp.zeros(N, N)
            E[i, j] = 1
            p = (0 if i < m else 1) ^ (0 if j < m else 1)
            out.append((E, p))
    return out


def basis_sl(m, n):
    """A basis of sl(m|n) = ker str, str X = tr A - tr D."""
    N = m + n
    out = []
    for E, p in basis_gl(m, n):
        # off-diagonal elementary matrices are already in sl
        nz = [(i, j) for i in range(N) for j in range(N) if E[i, j] != 0]
        (i, j) = nz[0]
        if i != j:
            out.append((E, p))
    # diagonal traceless combinations
    diag = []
    for i in range(N - 1):
        E = sp.zeros(N, N)
        # str(e_ii) = +1 for i<m, -1 for i>=m
        s_i = 1 if i < m else -1
        s_j = 1 if (i + 1) < m else -1
        E[i, i] = s_j
        E[i + 1, i + 1] = -s_i
        diag.append((E, 0))
    return out + diag


def basis_q(n):
    """q(n) = {(A B / B A)} inside gl(n|n)."""
    out = []
    for i in range(n):
        for j in range(n):
            A = sp.zeros(n, n)
            A[i, j] = 1
            out.append((from_blocks(A, sp.zeros(n, n), sp.zeros(n, n), A), 0))
            out.append((from_blocks(sp.zeros(n, n), A, A, sp.zeros(n, n)), 1))
    return out


# ------------------------------------------------------------- automorphisms


def st_minus(X, m, n):
    r"""-st : (A B / C D) |-> (-A^t  C^t / -B^t  -D^t)."""
    A, B, C, D = blocks(X, m, n)
    return from_blocks(-A.T, C.T, -B.T, -D.T)


def Pi(X, n):
    r"""Pi : (A B / C D) |-> (D C / B A),  on gl(n|n)."""
    A, B, C, D = blocks(X, n, n)
    return from_blocks(D, C, B, A)


def delta(lam, X, m, n):
    r"""delta_lambda : (A B / C D) |-> (A  lam B / lam^{-1} C  D)."""
    A, B, C, D = blocks(X, m, n)
    return from_blocks(A, lam * B, sp.Rational(1, 1) / lam * C, D)


def q_aut(X, n):
    r"""q : (A B / B A) |-> (-A^t  i B^t / i B^t  -A^t)."""
    A, B, C, D = blocks(X, n, n)
    return from_blocks(-A.T, I * B.T, I * C.T, -D.T)


def Ad(g, X):
    return sp.expand(g * X * g.inv())


# --------------------------------------------------------------- the checks

FAIL = []


def report(name, ok, detail=""):
    print(("  ok   " if ok else "  FAIL ") + name + ("   " + detail if detail else ""))
    if not ok:
        FAIL.append(name)


def is_aut(f, basis, m, n, name):
    """f preserves the supercommutator on the given basis."""
    bad = 0
    for (X, pX), (Y, pY) in itertools.product(basis, basis):
        lhs = f(sbracket(X, Y, m, n))
        rhs = sbracket(f(X), f(Y), m, n)
        if sp.expand(lhs - rhs) != sp.zeros(m + n, m + n):
            bad += 1
    report("%s is an automorphism" % name, bad == 0,
           "" if bad == 0 else "%d violations" % bad)


def check_A(m, n):
    """(-st)^2 = delta_{-1} on gl(m|n), and the real determinant signs."""
    basis = basis_gl(m, n)
    ok = all(
        sp.expand(st_minus(st_minus(X, m, n), m, n) - delta(-1, X, m, n))
        == sp.zeros(m + n, m + n)
        for X, _ in basis
    )
    report("(A) (-st)^2 = delta_{-1} on gl(%d|%d)" % (m, n), ok)
    # delta_{-1} = Ad of diag(1_m, -1_n)
    g = sp.diag(sp.eye(m), -sp.eye(n))
    ok2 = all(
        sp.expand(Ad(g, X) - delta(-1, X, m, n)) == sp.zeros(m + n, m + n)
        for X, _ in basis
    )
    report("(A) delta_{-1} = Ad diag(1_%d, -1_%d)" % (m, n), ok2)
    return sp.det(-sp.eye(n))


def check_B(n):
    """q^2 = delta_{-1}, q^4 = id, q = -st . delta_i, on q(n)."""
    basis = basis_q(n)
    Z = sp.zeros(2 * n, 2 * n)
    ok1 = all(sp.expand(q_aut(q_aut(X, n), n) - delta(-1, X, n, n)) == Z
              for X, _ in basis)
    report("(B) q^2 = delta_{-1} on q(%d)" % n, ok1)
    ok2 = all(sp.expand(q_aut(q_aut(q_aut(q_aut(X, n), n), n), n) - X) == Z
              for X, _ in basis)
    report("(B) q^4 = id on q(%d)" % n, ok2)
    # a note on the table of the text reads q = -st . delta_{sqrt -1}.
    # On the nose it is delta_{-i}, not delta_{i}: -st . delta_i = q . delta_{-1}
    # = q^3.  The two differ by q^2, so the note is right modulo <q^2> only.
    ok3 = all(sp.expand(q_aut(X, n) - st_minus(delta(-I, X, n, n), n, n)) == Z
              for X, _ in basis)
    report("(B) q = -st . delta_{-i} on q(%d)" % n, ok3)
    ok4 = all(sp.expand(st_minus(delta(I, X, n, n), n, n)
                        - q_aut(delta(-1, X, n, n), n)) == Z
              for X, _ in basis)
    report("(B) -st . delta_{+i} = q . delta_{-1} = q^3 on q(%d)" % n, ok4)
    # q(n) is q-stable, and delta_lambda preserves q(n) only for lambda^2 = 1
    stable = all(_in_span(q_aut(X, n), basis, n) for X, _ in basis)
    report("(B) q preserves q(%d)" % n, stable)
    lam = sp.Symbol("lam")
    bad_lam = [l for l in (2, I, -1, 1)
               if not all(_in_span(delta(l, X, n, n), basis, n) for X, _ in basis)]
    report("(B) delta_lambda preserves q(%d) only for lambda^2=1" % n,
           set(bad_lam) == {2, I}, "offenders: %s" % (bad_lam,))


def _in_span(X, basis, n):
    """Is X in the linear span of `basis` (as 2n x 2n matrices)?"""
    A, B, C, D = blocks(X, n, n)
    return sp.expand(A - D) == sp.zeros(n, n) and sp.expand(B - C) == sp.zeros(n, n)


def check_C(n):
    """[Pi, -st] = delta_{-1} on gl(n|n)."""
    basis = basis_gl(n, n)
    Z = sp.zeros(2 * n, 2 * n)
    # Pi . (-st) . Pi^{-1} . (-st)^{-1} ; note Pi^2 = id and (-st)^4 = id
    def inv_st(X):
        # (-st)^{-1} = (-st)^3 = (-st) . delta_{-1}
        return st_minus(delta(-1, X, n, n), n, n)

    ok = all(
        sp.expand(Pi(st_minus(Pi(inv_st(X), n), n, n), n) - delta(-1, X, n, n)) == Z
        for X, _ in basis
    )
    report("(C) [Pi, -st] = delta_{-1} on gl(%d|%d)" % (n, n), ok)
    # and Pi . (-st) is an involution
    ok2 = all(
        sp.expand(Pi(st_minus(Pi(st_minus(X, n, n), n), n, n), n) - X) == Z
        for X, _ in basis
    )
    report("(C) (Pi . (-st))^2 = id on gl(%d|%d)" % (n, n), ok2)


def check_D(k, n):
    """Ad diag(-1_k, 1_2n) = Ad diag(1_k, -1_2n) on gl(k|2n)."""
    basis = basis_gl(k, 2 * n)
    g1 = sp.diag(-sp.eye(k), sp.eye(2 * n))
    g2 = sp.diag(sp.eye(k), -sp.eye(2 * n))
    Z = sp.zeros(k + 2 * n, k + 2 * n)
    ok = all(sp.expand(Ad(g1, X) - Ad(g2, X)) == Z for X, _ in basis)
    report("(D) Ad diag(-1_%d,1_%d) = Ad diag(1_%d,-1_%d)" % (k, 2 * n, k, 2 * n), ok,
           "det(-1_%d) = %s, det(-1_%d) = %s"
           % (k, sp.det(-sp.eye(k)), 2 * n, sp.det(-sp.eye(2 * n))))


def main():
    print("Backend: sympy exact arithmetic over Q(i); no floating point.\n")

    print("(A) (-st)^2 = delta_{-1}, and why Table (t-d4.14) prints Z/4 once:")
    for (m, n) in ((2, 2), (3, 2), (3, 3), (2, 1)):
        d = check_A(m, n)
        print("       real form sl_R(%d|%d): det(-1_%d) = %s  ==>  delta_{-1} is %s"
              % (m, n, n, d,
                 "in the identity component over R (mst has order 2)" if d > 0
                 else "NOT in it over R (mst has order 4)"))
    print()

    print("(B) q on q(n):")
    for n in (2, 3):
        check_B(n)
    print()

    print("(C) Pi and -st on gl(n|n):")
    for n in (2, 3):
        check_C(n)
    print()

    print("(D) the two osp rows:")
    for (k, n) in ((3, 1), (4, 1), (5, 2), (6, 2)):
        check_D(k, n)
    print()

    print("(F) sanity -- the maps are automorphisms:")
    is_aut(lambda X: st_minus(X, 2, 2), basis_gl(2, 2), 2, 2, "-st on gl(2|2)")
    is_aut(lambda X: Pi(X, 2), basis_gl(2, 2), 2, 2, "Pi on gl(2|2)")
    is_aut(lambda X: delta(-1, X, 2, 2), basis_gl(2, 2), 2, 2,
           "delta_{-1} on gl(2|2)")
    is_aut(lambda X: q_aut(X, 2), basis_q(2), 2, 2, "q on q(2)")
    print()

    if FAIL:
        print("FAILURES: %d" % len(FAIL))
        for f in FAIL:
            print("   " + f)
        return 1
    print("All checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
