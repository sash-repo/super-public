#!/usr/bin/env python3
"""
run_maxgl.py -- is c(pe^a(n)) a maximal subalgebra of gl(n|n)?

A subalgebra U < g is maximal iff the U-module g/U is irreducible, and over an
algebraically closed field a finite-dimensional module is irreducible iff the
associative algebra generated by the action is the whole End (Burnside).  Both
steps are exact here, so the answer is a proof, not a sample.

Output: printed to stdout.  Usage: run_maxgl.py [n ...]
"""

import sys
from fractions import Fraction as F

import os; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
from exactlin import solve                                   # noqa: E402

from wgrad import bracket, Span, to_vec                      # noqa: E402
from run_prolong import deg_k_basis                          # noqa: E402
from run_cartan import preserving, form_odd, euler_field     # noqa: E402


def say(fh, *a):
    s = " ".join(str(x) for x in a)
    print(s, flush=True)
    if fh:
        fh.write(s + "\n")
        fh.flush()


def burnside(n, fh):
    ne = no = n
    gl = deg_k_basis(ne, no, 0)
    keys = sorted({k for X in gl for k in X.t}, key=str)
    idx = {k: i for i, k in enumerate(keys)}
    U = preserving(ne, no, form_odd(ne, no, -1)) + [euler_field(ne, no)]

    S = Span(idx)
    for X in U:
        S.add(to_vec(X, idx))
    comp = [X for X in gl if S.add(to_vec(X, idx))]
    d = len(comp)

    basisvecs = [to_vec(X, idx) for X in U] + [to_vec(X, idx) for X in comp]
    M = [[basisvecs[j][i] for j in range(len(basisvecs))] for i in range(len(keys))]

    def coords_mod_U(v):
        return solve(M, list(v))[len(U):]

    ops = []
    for A in U:
        img = []
        for X in comp:
            C = bracket(A, X)
            img.append(coords_mod_U(to_vec(C, idx) if C else [F(0)] * len(keys)))
        ops.append([[img[j][i] for j in range(d)] for i in range(d)])

    def flat(m):
        return [x for r in m for x in r]

    E = Span({i: i for i in range(d * d)})
    alg = [o for o in ops if E.add(flat(o))]
    i = 0
    while i < len(alg) and E.dim() < d * d:
        for o in ops:
            p = [[sum(alg[i][a][c] * o[c][b] for c in range(d)) for b in range(d)]
                 for a in range(d)]
            if E.add(flat(p)):
                alg.append(p)
            q = [[sum(o[a][c] * alg[i][c][b] for c in range(d)) for b in range(d)]
                 for a in range(d)]
            if E.add(flat(q)):
                alg.append(q)
        i += 1
    ok = E.dim() == d * d
    say(fh, f"  n={n}: dim gl({n}|{n}) = {len(gl)}, dim c(pe^a({n})) = {len(U)}, "
            f"dim of the quotient module = {d}; the associative algebra it "
            f"generates has dim {E.dim()} of {d*d}")
    say(fh, f"        ==> gl/U is {'IRREDUCIBLE: c(pe^a) is MAXIMAL' if ok else 'reducible: NOT maximal'}")
    return ok


def main():
    ns = [int(x) for x in sys.argv[1:]] or [2, 3]
    fh = None
    if True:
        say(fh, "Is c(pe^a(n)) maximal in gl(n|n)?  Burnside test on the quotient module")
        for n in ns:
            burnside(n, fh)


if __name__ == "__main__":
    main()
