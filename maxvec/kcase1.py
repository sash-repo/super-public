"""Case 1o in k(1|2n): u_{-2}+u_{-1}+u_0 = g_{-2}+g_{-1}+g_0, u_1 = W a maximal
g_0-submodule of g_1, u_k = {x in g_k | [g_{-1},x] in u_{k-1}} (the largest such u).
Contact form alpha = dt + sum_j (xi_j d eta_j + eta_j d xi_j); generating functions in
t (even, deg 2) and xi_j, eta_j (odd, deg 1); f of degree d lies in g_{d-2}."""
import sys, itertools, random
