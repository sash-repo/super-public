def setup(n):
    N = 2*n            # odd generators: 0..n-1 = xi, n..2n-1 = eta
    return N

def mul_mono(S, T):
    # product of xi_S * xi_T (sorted tuples); returns (sign, U) or None
    if set(S) & set(T): return None
    L = list(S)+list(T); sign = 1
    # bubble count inversions
    inv = sum(1 for i in range(len(L)) for j in range(i+1, len(L)) if L[i] > L[j])
    return (-1)**inv, tuple(sorted(L))

def mul(f, g):
    r = {}
    for (a, S), c in f.items():
        for (b, T), d in g.items():
            m = mul_mono(S, T)
            if m is None: continue
            s, U = m; k = (a+b, U)
            r[k] = r.get(k, 0) + s*c*d
    return {k: v for k, v in r.items() if v}

def add(*fs):
    r = {}
    for f in fs:
        for k, v in f.items(): r[k] = r.get(k, 0) + v
    return {k: v for k, v in r.items() if v}

def scal(c, f): return {k: c*v for k, v in f.items() if c*v}

def dxi(i, f):  # left derivative
    r = {}
    for (a, S), c in f.items():
        if i in S:
            p = S.index(i); U = S[:p]+S[p+1:]
            r[(a, U)] = r.get((a, U), 0) + (-1)**p * c
    return {k: v for k, v in r.items() if v}

def dt(f):
    return {(a-1, S): a*c for (a, S), c in f.items() if a > 0}

def E(f):  # Euler on odd variables
    return {(a, S): len(S)*c for (a, S), c in f.items() if len(S)}

def parity(f):
    ps = {len(S) % 2 for (a, S) in f}
    assert len(ps) <= 1; return ps.pop() if ps else 0

def br(f, g, n):
    if not f or not g: return {}
    pf = parity(f)
    two_minus_E = lambda h: add(scal(2, h), scal(-1, E(h)))
    s = add(mul(two_minus_E(f), dt(g)), scal(-1, mul(dt(f), two_minus_E(g))))
    t = {}
    for j in range(n):
        t = add(t, mul(dxi(j, f), dxi(n+j, g)), mul(dxi(n+j, f), dxi(j, g)))
    return add(s, scal(-(-1)**pf, t))

def monos(d, n):
    out = []
    for a in range(d//2+1):
        k = d-2*a
        for S in itertools.combinations(range(2*n), k):
            out.append((a, S))
    return out

def vec(f, basis):
    idx = {m: i for i, m in enumerate(basis)}
    v = [0]*len(basis)
    for k, c in f.items(): v[idx[k]] = c
    return v

def span_closure(gens, ops, basis):
    """smallest subspace containing gens, stable under ops (lists of linear maps f->f)."""
    vs = [vec(g, basis) for g in gens]
    cur = []
    queue = list(gens)
    while queue:
        f = queue.pop()
        if not f: continue
        v = vec(f, basis)
        if rank(cur+[v]) > rank(cur) if cur else any(v):
            cur.append(v)
            for op in ops: queue.append(op(f))
    return cur

def tofun(v, basis): return {basis[i]: c for i, c in enumerate(v) if c}

def jacobi_check(n, trials=30):
    rnd = random.Random(1)
    def rnd_hom(d):
        B = monos(d, n); return {m: rnd.randint(-3, 3) for m in rnd.sample(B, min(3, len(B)))}
    for _ in range(trials):
        f, g, h = (rnd_hom(rnd.randint(0, 5)) for _ in range(3))
        f = {k: v for k, v in f.items() if v}; g = {k: v for k, v in g.items() if v}; h = {k: v for k, v in h.items() if v}
        # make homogeneous in parity
        for x in (f, g, h):
            pass
        pf, pg, ph = parity(f), parity(g), parity(h)
        lhs = br(f, br(g, h, n), n)
        rhs = add(br(br(f, g, n), h, n), scal((-1)**(pf*pg), br(g, br(f, h, n), n)))
        assert add(lhs, scal(-1, rhs)) == {}, (f, g, h)
    return trials

def run(n, kmax=6):
    print(f"== k(1|{2*n}), Jacobi checked on {jacobi_check(n)} random triples")
    gm1 = [{(0, (i,)): 1} for i in range(2*n)]
    g0 = [{(1, ()): 1}] + [{(0, S): 1} for S in itertools.combinations(range(2*n), 2)]
    B3 = monos(3, n)
    ops = [lambda f, x=x: br(x, f, n) for x in g0]
    # irreducible pieces of g_1: generated by t*xi_1, xi_1..xi_n (all xi), eta_1..eta_n
    X = (0, 1, 2) if n >= 3 else (0, 1, n)
    Y = (n, n+1, n+2) if n >= 3 else (0, n, n+1)
    seeds = {'tx': {(1, (0,)): 1}, 'X': {(0, X): 1}, 'Y': {(0, Y): 1}}
    pieces = {}
    for k, s in seeds.items():
        p = span_closure([s], ops, B3)
        if any(rank(q+p) == rank(q) for q in pieces.values()): continue
        pieces[k] = p
    for k, p in pieces.items(): print(" g_1 piece", k, "dim", len(p))
    print(" dim g_1 =", len(B3), "sum of pieces =", sum(len(p) for p in pieces.values()))
    keys = list(pieces)
    for drop in keys:
        W = [v for k in keys if k != drop for v in pieces[k]]
        u = {1: W}; dims = [len(W)]
        for k in range(2, kmax+1):
            Bk = monos(k+2, n); Bprev = monos(k+1, n)
            # x in g_k with [g_{-1}, x] in span u_{k-1}: solve linear conditions
            # unknown coefficients c over Bk; condition: for each e in g_{-1}, br(e,x) in U
            U = u[k-1]
            if not U: u[k] = []; dims.append(0); continue
            # complement condition: project onto annihilator of U
            ann = nullspace(U) if U else None  # vectors w with U*w=0 ... want functionals vanishing on U
            # functionals vanishing on U = nullspace of transpose(U) as rows of length len(Bprev)
            UT = [list(r) for r in zip(*U)]
            # rows of U are vectors; annihilator = {phi | phi.u=0 for u in U} = nullspace(U)
            phis = nullspace(U)
            rows = []
            for e in gm1:
                cols = [vec(br(e, {m: 1}, n), Bprev) for m in Bk]
                for phi in phis:
                    rows.append([sum(F(phi[i])*c[i] for i in range(len(Bprev))) for c in cols])
            sol = nullspace(rows) if rows else [[1 if i == j else 0 for i in range(len(Bk))] for j in range(len(Bk))]
            u[k] = sol; dims.append(len(sol))
        print(f" drop {drop:2s}: dims u_1..u_{kmax} =", dims)

if __name__ == "__main__":
    for n in map(int, sys.argv[1:] or ["3"]):
        run(n)
