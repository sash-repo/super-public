#!/usr/bin/env python3
r"""
run_case3b.py -- the case 3^o over the ambients that are NOT vect:
svect(m|n), h(2m|n), le(n), and their relatives.

For an ambient g other than vect the prolong must be taken INSIDE g:

    u_k = { X in g_k | [X, g_{-1}] is contained in u_{k-1} },

which is (g_{-1}, u_0)_* \cap g.  The program builds g layer by layer from its
own definition (kernel of the divergence; the fields H_f; the fields Le_f),
checks that u_0 = g_0 comes out as the matrix algebra eq. (38) claims,
and then runs the same battery as run_case3.py: irreducibility on g_{-1},
maximality of u_0 in g_0, the prolong, and -- for the infinite prolongs --
whether the g_0-module generated by u_1 exhausts g_1.

Output: printed to stdout.
"""

import sys
from fractions import Fraction as F

import os; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
from exactlin import nullspace                                      # noqa: E402

from wgrad import (VF, bracket, Span, to_vec, monomials,            # noqa: E402
                   svect_basis, le_D, ham_H, divergence)
from run_prolong import deg_k_basis, module_generated               # noqa: E402
from run_cartan import (preserving, form_odd,                       # noqa: E402
                        sl_fields, q_fields, euler_field)
from run_case3 import (matrix_of, irreducible_on, is_maximal,       # noqa: E402
                       sdim_of, verdict_of, even_form)

LOG = None


def say(*a):
    s = " ".join(str(x) for x in a)
    print(s, flush=True)
    if LOG:
        LOG.write(s + "\n")
        LOG.flush()


def independent(fields, ne, no):
    keys = sorted({k for X in fields for k in X.t}, key=str)
    S = Span({k: i for i, k in enumerate(keys)})
    out = []
    for X in fields:
        v = to_vec(X, S.index)
        if v is not None and S.add(v):
            out.append(X)
    return out


# ------------------------------------------------------------- ambient layers

def layers_vect(ne, no, kmax):
    return {k: deg_k_basis(ne, no, k) for k in range(-1, kmax + 1)}


def layers_svect(ne, no, kmax):
    B = svect_basis(ne, no, kmax + 1)
    out = {k: [] for k in range(-1, kmax + 1)}
    for X in B:
        (m, j) = next(iter(X.t))
        d = sum(m[0]) + len(m[1]) - 1
        if -1 <= d <= kmax:
            out[d].append(X)
    return {k: independent(v, ne, no) for k, v in out.items()}


def layers_le(n, kmax):
    ne = no = n
    out = {}
    for k in range(-1, kmax + 1):
        fields = []
        for m in monomials(ne, no, k + 2):
            if sum(m[0]) + len(m[1]) != k + 2:
                continue
            X = le_D(m, ne, no, n)
            if X:
                fields.append(X)
        out[k] = independent(fields, ne, no) if fields else []
    return out


def layers_ham(npq, nxi, kmax):
    """h(2*npq | nxi): the fields H_f, deg H_f = deg f - 2."""
    ne, no = 2 * npq, nxi
    out = {}
    for k in range(-1, kmax + 1):
        fields = []
        for m in monomials(ne, no, k + 2):
            if sum(m[0]) + len(m[1]) != k + 2:
                continue
            X = ham_H(m, ne, no, npq, nxi)
            if X:
                fields.append(X)
        out[k] = independent(fields, ne, no) if fields else []
    return out


# -------------------------------------------------------- prolong inside g

def prolong_in(layers, u0, ne, no, kmax):
    """u_k = { X in g_k : [X, g_{-1}] < u_{k-1} }, computed exactly."""
    d_i = [VF({(((0,) * ne, ()), j): F(1)}, ne, no) for j in range(ne + no)]
    out = {0: independent(u0, ne, no)}
    dims = {0: len(out[0])}
    for k in range(1, kmax + 1):
        prev = out[k - 1]
        basis = layers.get(k, [])
        if not basis or not prev:
            out[k] = []
            dims[k] = 0
            continue
        keys_prev = sorted({key for X in layers.get(k - 1, []) for key in X.t},
                           key=str)
        idx_prev = {key: i for i, key in enumerate(keys_prev)}
        # functionals killing u_{k-1}
        rows = []
        for X in prev:
            v = [F(0)] * len(keys_prev)
            for key, c in X.t.items():
                if key in idx_prev:
                    v[idx_prev[key]] = c
            rows.append(v)
        N = nullspace(rows) if rows else \
            [[F(1) if i == j else F(0) for i in range(len(keys_prev))]
             for j in range(len(keys_prev))]
        M = []
        for D in d_i:
            cols = []
            for X in basis:
                B = bracket(X, D)
                v = [F(0)] * len(keys_prev)
                for key, c in B.t.items():
                    if key not in idx_prev:      # left g_{k-1}: impossible, but guard
                        v = None
                        break
                    v[idx_prev[key]] = c
                cols.append(v if v is not None else [F(0)] * len(keys_prev))
            for f in N:
                M.append([sum(f[t] * cols[b][t] for t in range(len(keys_prev)))
                          for b in range(len(basis))])
        lay = []
        if not M:
            lay = list(basis)
        else:
            for vec in nullspace(M):
                X = VF({}, ne, no)
                for j, c in enumerate(vec):
                    if c:
                        X = X.add(basis[j], F(c))
                if X:
                    lay.append(X)
        out[k] = independent(lay, ne, no)
        dims[k] = len(out[k])
    return out, dims


# ------------------------------------------------------------------- reporting

def report(tag, ne, no, u0, layers, kmax):
    N = ne + no
    g0 = layers[0]
    mats = [matrix_of(X, ne, no) for X in u0]
    irr, dA, worst = irreducible_on(mats, N)
    ev, od = sdim_of(u0, ne)
    maxv, dq, dAq = is_maximal(u0, g0, ne, no)
    lay, dims = prolong_in(layers, u0, ne, no, kmax)
    v = verdict_of(dims, kmax)
    say(f"    {tag:<18} sdim u_0 = ({ev}|{od})")
    say(f"        on g_-1 = ({ne}|{no}):  {irr}   [dim A = {dA} of {N*N}]")
    say(f"        maximal in g_0?       {maxv}   [dim g_0/u_0 = {dq}]")
    say(f"        prolong-in-g dims k=0..{kmax}: "
        + ", ".join(str(dims[k]) for k in range(kmax + 1))
        + f"   -> {v}")
    say(f"        for comparison dim g_k      : "
        + ", ".join(str(len(layers.get(k, []))) for k in range(kmax + 1)))
    if v == "infinite" and lay.get(1) and layers.get(1):
        got, _ = module_generated(lay[1], g0, ne, no, layers[1])
        full = len(layers[1])          # dim g_1, not the size of the ambient
                                       # coordinate space, which is bigger here
        if got == full:
            say(f"        the g_0-module generated by u_1 is ALL of g_1 "
                f"({got} of {full}) ==> u is MAXIMAL in the ambient")
        else:
            say(f"        the g_0-module generated by u_1 is PROPER "
                f"({got} of {full}) ==> something sits in between")
    return dims, v


def sec_svect(kmax, spaces):
    for (ne, no) in spaces:
        L = layers_svect(ne, no, kmax)
        say("=" * 78)
        say(f"AMBIENT  svect({ne}|{no}):  g_-1 = ({ne}|{no}), dim g_0 = {len(L[0])} "
            f"(sl({ne}|{no}) has dim {(ne+no)**2 - 1})")
        say("=" * 78)
        cands = []
        if ne % 2 == 0:
            cands.append(("osp^{a}(V)", preserving(ne, no, even_form(ne, no, "a"))))
        if no % 2 == 0:
            cands.append(("osp^{sy}(V)", preserving(ne, no, even_form(ne, no, "sy"))))
        if ne == no and ne > 0:
            pa = preserving(ne, no, form_odd(ne, no, -1))
            ps = preserving(ne, no, form_odd(ne, no, +1))
            cands.append(("pe^{a}(n)", pa))
            cands.append(("spe^{a}(n)", derived(pa, ne, no)))
            cands.append(("pe^{sy}(n)", ps))
            cands.append(("q(n)", q_fields(ne)))
        for tag, u0 in cands:
            u0 = intersect_with(u0, L[0], ne, no)
            if not u0:
                say(f"    {tag:<18} not inside g_0 -- skipped")
                continue
            report(tag + " cap g_0", ne, no, u0, L, kmax)
        say("")


def derived(fields, ne, no):
    out = []
    for i, X in enumerate(fields):
        for Y in fields[i:]:
            C = bracket(X, Y)
            if C:
                out.append(C)
    return independent(out, ne, no)


def str_zero(X, ne):
    return False


def intersect_with(fields, ambient, ne, no):
    """span(fields) cap span(ambient), exactly."""
    keys = sorted({k for X in list(fields) + list(ambient) for k in X.t}, key=str)
    idx = {k: i for i, k in enumerate(keys)}

    def vec(X):
        v = [F(0)] * len(keys)
        for k, c in X.t.items():
            v[idx[k]] = c
        return v
    A = [vec(X) for X in fields]
    B = [vec(X) for X in ambient]
    if not A or not B:
        return []
    # solve  sum a_i A_i = sum b_j B_j
    M = [[A[i][t] for i in range(len(A))] + [-B[j][t] for j in range(len(B))]
         for t in range(len(keys))]
    out = []
    for vv in nullspace(M):
        X = VF({}, ne, no)
        for i in range(len(A)):
            if vv[i]:
                X = X.add(fields[i], F(vv[i]))
        if X:
            out.append(X)
    return independent(out, ne, no)


def sec_le(kmax, ns):
    for n in ns:
        ne = no = n
        L = layers_le(n, kmax)
        say("=" * 78)
        say(f"AMBIENT  le({n}):  g_-1 = ({n}|{n}), dim g_0 = {len(L[0])}")
        say("=" * 78)
        pa = preserving(ne, no, form_odd(ne, no, -1))
        chk = intersect_with(pa, L[0], ne, no)
        say(f"    check: dim(g_0) = {len(L[0])}, dim pe^a({n}) = {len(pa)}, "
            f"dim of the intersection = {len(chk)}"
            + ("   ==> g_0 = pe^a(n), as (38) says"
               if len(chk) == len(L[0]) == len(pa) else "   ==> MISMATCH"))
        cands = [("spe^{a}(n) = [g_0,g_0]", derived(L[0], ne, no))]
        for tag, u0 in cands:
            u0 = intersect_with(u0, L[0], ne, no)
            if not u0:
                say(f"    {tag:<18} empty -- skipped")
                continue
            report(tag, ne, no, u0, L, kmax)
        say("")


def sec_ham(kmax, cases):
    for (npq, nxi) in cases:
        ne, no = 2 * npq, nxi
        L = layers_ham(npq, nxi, kmax)
        say("=" * 78)
        say(f"AMBIENT  h({ne}|{no}):  g_-1 = ({ne}|{no}), dim g_0 = {len(L[0])}")
        say("=" * 78)
        oa = preserving(ne, no, even_form(ne, no, "a"))
        chk = intersect_with(oa, L[0], ne, no)
        say(f"    check: dim g_0 = {len(L[0])}, dim osp^a = {len(oa)}, "
            f"dim of the intersection = {len(chk)}"
            + ("   ==> g_0 = osp^a, as (38) says"
               if len(chk) == len(L[0]) == len(oa) else "   ==> MISMATCH"))
        cands = [("[g_0,g_0]", derived(L[0], ne, no))]
        for tag, u0 in cands:
            u0 = intersect_with(u0, L[0], ne, no)
            if not u0:
                continue
            report(tag, ne, no, u0, L, kmax)
        say("")


def main():
    global LOG
    LOG = None
    kmax = 3
    say("The case 3^o over the ambients svect, le, h (exact over Q)\n")
    sec_le(kmax, [2, 3])
    sec_ham(kmax, [(1, 2), (2, 2), (1, 0), (2, 0)])
    sec_svect(kmax, [(2, 2), (3, 3), (2, 1)])
    say("Done.")


if __name__ == "__main__":
    main()
