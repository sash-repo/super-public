#!/usr/bin/env python3
r"""
run_case3.py -- the run of the case 3^o over the ambients of table (65).

For an ambient g = one of the simple W-graded vectorial Lie superalgebras of
depth 1, taken in its STANDARD grading, so that g_0 is one of the classical
matrix Lie superalgebras of eq. (38):

    vect(m|n) = (id, gl(m|n))_*      svect(m|n) = (id, sl(m|n))_*
    h(2m|n)   = (id, osp^a)_*        le(n)      = (id, pe^a(n))_*

the case 3^o asks for the maximal u_0 < g_0 acting irreducibly on g_{-1} = V,
and for u = (V, u_0)_* \cap g.  The maximal irreducible u_0 are the subject of
[ShM]; what [ShM] does not say is which of the prolongs are infinite, and
whether the prolong is maximal in the ambient.  Both are decided here, exactly.

Per candidate the program reports

  * dim u_0 and sdim u_0;
  * whether u_0 acts irreducibly on V.  The test is a proof, not a sample: the
    basis of V is a weight basis of the torus inside u_0, so every submodule is
    spanned by weight vectors; when all weight spaces are 1-dimensional it
    suffices to generate V from each basis vector in turn.  Independently, the
    associative algebra generated inside End(V) is computed: A = End(V) implies
    irreducibility outright.
  * whether u_0 is maximal in g_0.  Same two tests on the quotient module
    g_0/u_0.  A proper invariant graded subspace, when one is found, is
    exhibited -- that is a proof of NON-maximality.
  * the prolong (V, u_0)_* layer by layer.  A vanishing layer is a proof of
    finiteness (transitivity propagates it upwards); growth is matched against
    the reference series computed by the same engine.
  * for the infinite ones: whether u = (V,u_0)_* is maximal in the ambient,
    i.e. whether the g_0-module generated by u_1 is the whole of g_1.  If it is
    proper, the intermediate algebra is named.

Output: printed to stdout.
Usage:  run_case3.py [--kmax K] [ne no ...]   (default: the nine superdimensions in main)
"""

import sys
from fractions import Fraction as F

import os; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
