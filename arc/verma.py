#!/usr/bin/env python3
"""
verma.py -- the multiplicity in SM_{mu_1} (x) SM_{mu_2} over osp(1|2), proved.

This is the engine behind the proof of Theorem 7.2.11 of the text: namely the EXISTENCE of the second invariant
operator inside the window, and its NON-existence on the rest of the range left
open by Theorem 7.2.10.

THE ROUTE.  Write M(lam) for the lowest-weight Verma module over osp(1|2):

    basis u_k, k >= 0,  p(u_k) = k mod 2,
    Q_+ u_k = u_{k+1},  Q_- u_k = c_k(lam) u_{k-1},  H u_k = -(lam+k) u_k,

where the recursion c_{k+1} = -(lam+k) - c_k with c_0 = 0 (which is nothing but
{Q_-,Q_+} = H) gives

    c_{2j}(lam) = -j,        c_{2j+1}(lam) = -(lam+j).

Two facts, both proved in the text:

 (1)  SM_mu is the DUAL Verma module, SM_mu = M(mu)^vee, because
      Q_-: (SM_mu)_n -> (SM_mu)_{n-1} is bijective for n >= 1, hence Q_+ is
      bijective on every level of the dual, which is therefore generated by its
      level 0; the characters agree.

 (2)  Hence, the duality Hom(X,Y) = Hom(Y^vee, X^vee) and the universal property
      of the Verma module turn the space of invariant operators into a space of
      lowest-weight vectors:

      Hom(SM_{mu_1} (x) SM_{mu_2}, SM_nu) = Hom(M(nu), M(mu_1) (x) M(mu_2))
                                          = Ker Q_- on the level d of M (x) M,

      where d = nu - mu_1 - mu_2.

WHAT IS COMPUTED HERE.  Nothing of the argument is assumed: the level d of
M(mu_1) (x) M(mu_2) is built from the c_k, the matrix of Q_- on it is written
out from the coproduct Q_-(x (x) y) = Q_-x (x) y + (-1)^{p(x)} x (x) Q_-y, and
its kernel is computed exactly.  The result is compared with

  -- multdeg.hom_dim_stable, the independent engine of Subsection 7.2, which
     solves the equivariance system in the SM-picture (this tests fact (2));
  -- the closed formula of Theorem 7.2.11 (this tests the chain argument).

All arithmetic is over Q (fractions.Fraction).
"""

import sys
from fractions import Fraction as F

import os, sys; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "lib"), _HERE]
from exactlin import nullspace  # noqa: E402


# ------------------------------------------------------- the Verma module M(lam)

def c(lam, k):
    """Q_-(u_k) = c_k(lam) u_{k-1} in M(lam)."""
    if k < 0:
        raise ValueError(k)
    j, e = divmod(k, 2)
    return F(-j) if e == 0 else -(F(lam) + j)


def c_by_recursion(lam, kmax):
    """The same numbers from c_{k+1} = -(lam+k) - c_k, c_0 = 0."""
    out = [F(0)]
    for k in range(kmax):
        out.append(-(F(lam) + k) - out[-1])
    return out


# --------------------------------------------- the tensor product of two Vermas

def qminus_matrix(mu1, mu2, d):
    """Matrix of Q_-: level d -> level d-1 of M(mu1) (x) M(mu2).

    Basis of the level n: u_i (x) u'_{n-i}, i = 0..n.
    Rows are indexed by the target basis, columns by the source basis.
    """
    if d == 0:
        return []
    rows = [[F(0)] * (d + 1) for _ in range(d)]
    for i in range(d + 1):
        # Q_-(u_i) (x) u'_{d-i}
        if i >= 1:
            rows[i - 1][i] += c(mu1, i)
        # (-1)^{p(u_i)} u_i (x) Q_-(u'_{d-i})
        if d - i >= 1:
            rows[i][i] += F(-1) ** (i % 2) * c(mu2, d - i)
    return rows


def sing_dim(mu1, mu2, d):
    """dim Ker Q_- on the level d of M(mu1) (x) M(mu2)."""
    if d < 0:
        return 0
    if d == 0:
        return 1
    return len(nullspace(qminus_matrix(mu1, mu2, d)))


# ------------------------------------------------------------- the closed formula

def is_nonpos_int(x):
    return F(x).denominator == 1 and x <= 0


def window_rule(mu1, mu2, d):
    """The answer claimed by Theorem 7.2.11, for d in Z_{>=0}."""
    if d < 0:
        return 0
    if not (is_nonpos_int(mu1) and is_nonpos_int(mu2)):
        return 1
    m1, m2 = -int(mu1), -int(mu2)
    return 2 if 2 * max(m1, m2) + 1 <= d <= 2 * (m1 + m2) + 1 else 1


# ------------------------------------------------------------------- the runs

def line(out, s=""):
    print(s, file=out)


def part0(out):
    """The Verma module itself: the closed form of c_k against the recursion."""
    line(out, "=" * 78)
    line(out, "PART 0.  The structure constants of M(lam): closed form vs the")
    line(out, "         recursion c_{k+1} = -(lam+k) - c_k, i.e., {Q_-,Q_+} = H.")
    line(out, "=" * 78)
    n = 0
    for num in range(-12, 13):
        lam = F(num, 2)
        rec = c_by_recursion(lam, 24)
        for k in range(25):
            assert c(lam, k) == rec[k], (lam, k)
            n += 1
    line(out, f"checked: {n} values of c_k(lam), lam in (1/2)Z cap [-6,6], k <= 24  OK")
    # the zeros of c_k for k >= 1
    line(out, "")
    line(out, "the zeros of c_k(lam) for k >= 1:")
    for num in [-4, -2, 0, 1, 3, -3]:
        lam = F(num, 2)
        z = [k for k in range(1, 30) if c(lam, k) == 0]
        line(out, f"   lam = {str(lam):>5}:  {z}")
    line(out, "   (c_{2j} = -j vanishes only for k = 0; c_{2j+1} = -(lam+j)")
    line(out, "    vanishes iff lam = -j, i.e., at the single k = 1-2lam)")
    return n


def part1(out):
    """The duality: the SM-picture engine against the Verma picture."""
    import multdeg
    line(out, "")
    line(out, "=" * 78)
    line(out, "PART I.  The duality Hom(SM (x) SM, SM_nu) = Ker Q_- on M (x) M.")
    line(out, "         Left: multdeg.hom_dim_stable (equivariance in the SM-picture).")
    line(out, "         Right: sing_dim (lowest-weight vectors in M(mu_1)(x)M(mu_2)).")
    line(out, "=" * 78)
    weights = [F(k, 2) for k in range(-6, 7)]
    weights += [F(1, 3), F(-1, 3), F(2, 3), F(-4, 3), F(1, 5), F(-7, 5)]
    n = 0
    bad = []
    for mu1 in weights:
        for mu2 in weights:
            for d in range(0, 9):
                a = multdeg.hom_dim_stable(mu1, mu2, d)
                b = sing_dim(mu1, mu2, d)
                n += 1
                if a != b:
                    bad.append((mu1, mu2, d, a, b))
    line(out, f"checked: {n} triples (mu_1,mu_2,d), {len(weights)} weights, d <= 8")
    line(out, f"mismatches: {len(bad)}")
    for b in bad[:20]:
        line(out, f"   {b}")
    return n, bad


def part2(out):
    """The chain argument: sing_dim against the closed formula, far out in d."""
    line(out, "")
    line(out, "=" * 78)
    line(out, "PART II.  The window rule against the honest kernel, on a long range")
    line(out, "          of d, where the SM-picture engine is too slow to follow.")
    line(out, "=" * 78)
    weights = [F(k, 2) for k in range(-16, 9)]
    weights += [F(1, 3), F(-1, 3), F(-4, 3), F(1, 5), F(-7, 5), F(-11, 7)]
    n, bad = 0, []
    for mu1 in weights:
        for mu2 in weights:
            for d in range(0, 40):
                a = sing_dim(mu1, mu2, d)
                b = window_rule(mu1, mu2, d)
                n += 1
                if a != b:
                    bad.append((mu1, mu2, d, a, b))
    line(out, f"checked: {n} triples, {len(weights)} weights (halves, thirds,")
    line(out, f"         fifths, sevenths; m_i up to 8), d <= 39")
    line(out, f"mismatches: {len(bad)}")
    for b in bad[:20]:
        line(out, f"   {b}")
    return n, bad


def part3(out):
    """The table (154) of the text, recomputed in the Verma picture."""
    line(out, "")
    line(out, "=" * 78)
    line(out, "PART III.  Eq. (154) of the text, recomputed: the nine pairs")
    line(out, "           of ((1/2)Z cap [-3,3])^2 that fail for d <= 6.")
    line(out, "=" * 78)
    halves = [F(k, 2) for k in range(-6, 7)]
    bad = []
    for mu1 in halves:
        for mu2 in halves:
            dims = [sing_dim(mu1, mu2, d) for d in range(7)]
            if any(x != 1 for x in dims):
                bad.append((mu1, mu2, dims))
    for mu1, mu2, dims in bad:
        line(out, f"   ({str(mu1):>4},{str(mu2):>4})   {dims}")
    line(out, f"pairs failing: {len(bad)} of {len(halves)**2}")
    return bad


def part4(out):
    """The two solutions written out, on one window, to see what they are."""
    line(out, "")
    line(out, "=" * 78)
    line(out, "PART IV.  The kernel written out on a window: the coordinates a_i of")
    line(out, "          the two lowest-weight vectors sum a_i u_i (x) u'_{d-i}.")
    line(out, "=" * 78)
    for (m1, m2) in [(0, 0), (1, 1), (2, 1)]:
        mu1, mu2 = F(-m1), F(-m2)
        lo, hi = 2 * max(m1, m2) + 1, 2 * (m1 + m2) + 1
        line(out, f"  m_1 = {m1}, m_2 = {m2}:  window {lo} <= d <= {hi}")
        for d in range(max(0, lo - 2), hi + 3):
            ker = nullspace(qminus_matrix(mu1, mu2, d)) if d else [[F(1)]]
            line(out, f"    d = {d:>2}  dim = {len(ker)}   {[list(map(str,v)) for v in ker]}")
    line(out)
    line(out, "  The break: Q_-(u_{2m_1+1}) = 0 in M(-m_1) splits the chain of")
    line(out, "  equations c_{p+1} a_{p+1} + (-1)^p c'_{d-p} a_p = 0 into two")
    line(out, "  segments; the lower one survives iff some c'_{d-p} with p <= 2m_1")
    line(out, "  vanishes, i.e., iff 2m_2+1 <= d <= 2(m_1+m_2)+1.")


def main():
    with open("verma.log", "w") as out:
        for f in (out, sys.stdout):
            pass
        n0 = part0(out)
        n1, bad1 = part1(out)
        n2, bad2 = part2(out)
        bad3 = part3(out)
        part4(out)
        line(out, "")
        line(out, "=" * 78)
        ok = not bad1 and not bad2
        line(out, f"TOTAL: {n0 + n1 + n2} checks, "
                  f"{len(bad1) + len(bad2)} mismatches -- "
                  f"{'ALL PASS' if ok else 'FAILURE'}")
        line(out, "=" * 78)
    print(open("verma.log").read())


if __name__ == "__main__":
    main()
