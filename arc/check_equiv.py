r"""
The C-points of SOSp(1|2) used in the proof of Theorem 3.5.3 of the text: the
equivalence of the system (sy) and its solution (sysol)

     (sy)                                   (sysol)
     AD - BC = 1 + al*be                    AD - BC = 1 + al*be
     A*de - C*ga - E*al = 0                 ga = al*B - be*A
     B*de - D*ga - E*be = 0                 de = al*D - be*C
     E^2 + 2*ga*de = 1                      E  = 1 - al*be

The forward direction (sysol) ==> (sy) is a substitution; the converse
(sy) & pr(E)=1 ==> (sysol) needs an argument.

This script verifies BOTH directions.  The converse is proved by the chain

  (1)  D*al*L2 - C*al*L3 = (AD-BC)*al*de + C*E*al*be         <- exact identities,
  (2)  B*al*L2 - A*al*L3 = (AD-BC)*al*ga + A*E*al*be            no assumptions
  (3)  D*be*L2 - C*be*L3 = (AD-BC)*be*de + D*E*al*be
  (4)  B*be*L2 - A*be*L3 = (AD-BC)*be*ga + B*E*al*be

      where L2 := A*de - C*ga - E*al,  L3 := B*de - D*ga - E*be;

  (5)  hence, AD-BC being invertible, al*ga, al*de, be*ga, be*de all lie in the
       ideal generated by al*be, whence every product of three of al, be, ga, de
       vanishes -- in particular ga*de*al = ga*de*be = 0;
  (6)  E = 1 + e with e in the ideal of odd elements and e*(2+e) = -2*ga*de by the
       4th equation, so e*al = e*be = 0, i.e. E*al = al and E*be = be;
  (7)  with E*al = al, E*be = be the 2nd and 3rd equations become
       a linear system for (ga, de) with matrix ((A, C), (B, D)) of determinant
       AD - BC invertible, whose unique solution is ga = al*B - be*A, de = al*D - be*C;
  (8)  then ga*de = al*be*(AD-BC) = al*be, so E^2 = 1 - 2*al*be; writing E = 1 + e
       again, e lies in the ideal of al*be, hence e^2 = 0 and 2e = -2*al*be, i.e.
       E = 1 - al*be.  (Without pr(E) = 1 the second branch is E = -(1 - al*be) with
       all the entries multiplied by -1.)

Steps (1)-(4), (6), (8) and the forward direction are checked below symbolically;
step (5) is checked by evaluating all the triple products; step (7) is a linear
system with invertible matrix -- its solution is checked by substitution.

Ground ring: the free supercommutative algebra on the odd generators al, be, ga, de
over Q[A,B,C,D,E] -- so every identity verified here is an identity of the free
supercommutative algebra, hence holds after any substitution of even/odd elements
of any supercommutative ring.

    ./venv/bin/python3 check_equiv.py
"""

import itertools
import sympy as sp

A, B, C, D, E = sp.symbols('A B C D E')
GENS = ('al', 'be', 'ga', 'de')          # odd generators, in this order


# ------------------------------------------------------------------ Grassmann algebra
# an element is a dict {sorted tuple of odd generators: even (polynomial) coefficient}

def _norm(S):
    S = list(S)
    s = 1
    for i in range(len(S)):
        for j in range(len(S) - 1 - i):
            if GENS.index(S[j]) > GENS.index(S[j + 1]):
                S[j], S[j + 1] = S[j + 1], S[j]
                s = -s
    for i in range(len(S) - 1):
        if S[i] == S[i + 1]:
            return (), 0
    return tuple(S), s


def el(*terms):
    out = {}
    for c, S in terms:
        T, s = _norm(S)
        if s == 0:
            continue
        out[T] = sp.expand(out.get(T, 0) + c * s)
    return {k: v for k, v in out.items() if v != 0}


def add(*xs):
    out = {}
    for e in xs:
        for S, c in e.items():
            out[S] = sp.expand(out.get(S, 0) + c)
    return {k: v for k, v in out.items() if sp.expand(v) != 0}


def neg(e):
    return {S: sp.expand(-c) for S, c in e.items()}


def mul(*xs):
    out = el((1, ()))
    for b in xs:
        new = {}
        for S1, c1 in out.items():
            for S2, c2 in b.items():
                T, s = _norm(S1 + S2)
                if s == 0:
                    continue
                new[T] = sp.expand(new.get(T, 0) + s * c1 * c2)
        out = {k: v for k, v in new.items() if v != 0}
    return out


def scal(c, e):
    return {S: sp.expand(c * v) for S, v in e.items() if sp.expand(c * v) != 0}


def is_zero(e):
    return all(sp.expand(c) == 0 for c in e.values())


def eq(a, b):
    return is_zero(add(a, neg(b)))


def show(e):
    if is_zero(e):
        return "0"
    parts = []
    for S in sorted(e, key=lambda S: (len(S), S)):
        c = sp.factor(sp.expand(e[S]))
        if c == 0:
            continue
        parts.append(f"({c})" + ("" if not S else "*" + "*".join(S)))
    return " + ".join(parts)


ONE = el((1, ()))
al, be, ga, de = (el((1, (g,))) for g in GENS)
eA, eB, eC, eD, eE = (el((s, ())) for s in (A, B, C, D, E))

ok = True


def check(name, lhs, rhs):
    global ok
    good = eq(lhs, rhs)
    ok = ok and good
    print(f"  [{'ok ' if good else 'FAIL'}] {name}")
    if not good:
        print(f"        lhs = {show(lhs)}")
        print(f"        rhs = {show(rhs)}")
        print(f"        lhs - rhs = {show(add(lhs, neg(rhs)))}")


# =====================================================================================
print(__doc__.split('\n')[1].strip())
print()
print("=== 0. the two systems (sy) and (sysol) =============================")

# the four left-hand sides of (sy)
L1 = add(mul(eA, eD), neg(mul(eB, eC)), neg(mul(al, be)), neg(ONE))      # AD-BC-al*be-1
L2 = add(mul(eA, de), neg(mul(eC, ga)), neg(mul(eE, al)))                # A de - C ga - E al
L3 = add(mul(eB, de), neg(mul(eD, ga)), neg(mul(eE, be)))                # B de - D ga - E be
L4 = add(mul(eE, eE), scal(2, mul(ga, de)), neg(ONE))                    # E^2 + 2 ga de - 1
print("  (sy)    : L1 = AD-BC-al*be-1,  L2 = A*de-C*ga-E*al,")
print("            L3 = B*de-D*ga-E*be,  L4 = E^2+2*ga*de-1")
print("  (sysol) : ga = al*B-be*A, de = al*D-be*C, E = 1-al*be, AD-BC = 1+al*be")

# =====================================================================================
print()
print("=== 1. forward: (sysol) ==> (sy) ====================================")
# substitute ga, de, E by their (sysol) values and AD - BC by 1 + al*be.  Working in
# Q[A,B,C,D] with the relation AD-BC = 1+al*be imposed by eliminating D:
#     D = (1 + al*be + BC)/A.
Dsol = el((sp.Rational(1, 1) / A, ()), (sp.Rational(1, 1) * B * C / A, ()))
Dsol = add(el((1 / A, ())), el((B * C / A, ())), scal(1 / A, mul(al, be)))
ga_s = add(mul(al, eB), neg(mul(be, eA)))
de_s = add(mul(al, Dsol), neg(mul(be, eC)))
E_s = add(ONE, neg(mul(al, be)))


def subs_sysol(e):
    """rewrite an expression of the free algebra using (sysol)"""
    out = el()
    for S, c in e.items():
        term = el((c, ()))
        # replace the generators one by one, keeping the order
        factors = []
        for g in S:
            factors.append({'al': al, 'be': be, 'ga': ga_s, 'de': de_s}[g])
        out = add(out, mul(term, *factors))
    # E and D are even symbols: substitute them in the coefficients
    out2 = el()
    for S, c in out.items():
        c2 = c
        out2 = add(out2, {S: c2})
    return out2


def subs_even(e):
    """substitute E -> 1 - al*be and D -> (1+al*be+BC)/A in the even coefficients"""
    out = el()
    for S, c in e.items():
        c = sp.expand(c)
        p = sp.Poly(c, E, D)
        piece = el()
        for (iE, iD), coeff in zip(p.monoms(), p.coeffs()):
            t = el((coeff, ()))
            for _ in range(iE):
                t = mul(t, E_s)
            for _ in range(iD):
                t = mul(t, Dsol)
            piece = add(piece, t)
        out = add(out, mul(piece, el((1, S))))
    return out


def full_subs(e):
    return subs_even(subs_sysol(e))


for nm, L in (("L1", L1), ("L2", L2), ("L3", L3), ("L4", L4)):
    check(f"(sysol) makes {nm} vanish identically", full_subs(L), el())

# =====================================================================================
print()
print("=== 2. converse, steps (1)-(4): exact identities ====================")
AD_BC = add(mul(eA, eD), neg(mul(eB, eC)))
albe = mul(al, be)

check("D*al*L2 - C*al*L3 = (AD-BC)*al*de + C*E*al*be",
      add(mul(eD, al, L2), neg(mul(eC, al, L3))),
      add(mul(AD_BC, al, de), mul(eC, eE, albe)))
check("B*al*L2 - A*al*L3 = (AD-BC)*al*ga + A*E*al*be",
      add(mul(eB, al, L2), neg(mul(eA, al, L3))),
      add(mul(AD_BC, al, ga), mul(eA, eE, albe)))
check("D*be*L2 - C*be*L3 = (AD-BC)*be*de + D*E*al*be",
      add(mul(eD, be, L2), neg(mul(eC, be, L3))),
      add(mul(AD_BC, be, de), mul(eD, eE, albe)))
check("B*be*L2 - A*be*L3 = (AD-BC)*be*ga + B*E*al*be",
      add(mul(eB, be, L2), neg(mul(eA, be, L3))),
      add(mul(AD_BC, be, ga), mul(eB, eE, albe)))

print()
print("=== 3. converse, step (5): all triple products vanish ===============")
# On the solution variety L2 = L3 = 0 and AD-BC invertible, step 2 gives
#     al*ga = -(AD-BC)^{-1} A*E*al*be,   al*de = -(AD-BC)^{-1} C*E*al*be,
#     be*ga = -(AD-BC)^{-1} B*E*al*be,   be*de = -(AD-BC)^{-1} D*E*al*be,
# i.e. each of them equals (even) * al*be.  Substituting these into any product of
# three of al, be, ga, de gives a multiple of al*be*al = 0 or al*be*be = 0.
u = sp.Symbol('u')                      # u stands for (AD-BC)^{-1}
PAIR = {('al', 'ga'): scal(-u * A * E, albe), ('al', 'de'): scal(-u * C * E, albe),
        ('be', 'ga'): scal(-u * B * E, albe), ('be', 'de'): scal(-u * D * E, albe)}
ODD = {'al': al, 'be': be, 'ga': ga, 'de': de}


def reduce_triple(t):
    """Rewrite a product of three of al, be, ga, de by the relations of step 2, applied
    twice: once to the leading pair, once to the pair that this produces."""
    S, s = _norm(t)
    if s == 0:
        return el(), "a generator repeats"
    if S[:2] in PAIR:
        val = mul(scal(s, PAIR[S[:2]]), *[ODD[g] for g in S[2:]])
        why = f"{S[0]}*{S[1]} = (even)*al*be"
    else:                                # S[:2] == ('al','be'): already of that shape
        val = mul(scal(s, albe), *[ODD[g] for g in S[2:]])
        why = "al*be*x"
    out = el()                           # now reduce the surviving (al, be, x) terms
    for T, c in val.items():
        if len(T) == 3 and T[1:] in PAIR:
            out = add(out, mul(scal(c, ODD[T[0]]), PAIR[T[1:]]))
            why += f", then {T[1]}*{T[2]} = (even)*al*be, leaving {T[0]}*al*be = 0"
        else:
            out = add(out, {T: c})
    return out, why


triples_ok = True
for t in itertools.product(GENS, repeat=3):
    if _norm(t)[1] == 0:                 # trivially zero: a generator repeats
        continue
    val, why = reduce_triple(t)
    good = is_zero(val)
    triples_ok = triples_ok and good
    print(f"  [{'ok ' if good else 'FAIL'}] {'*'.join(t)} = 0   [{why}]")
    if not good:
        print(f"        left over: {show(val)}")
ok = ok and triples_ok

print()
print("=== 4. converse, step (6): E*al = al and E*be = be ==================")
# E = 1 + e,  L4 = 0 gives e*(2+e) = -2*ga*de, so e = -2*ga*de*(2+e)^{-1}; by step 3
# ga*de*al = ga*de*be = 0, hence e*al = e*be = 0.
v = sp.Symbol('v')                        # v stands for (2+e)^{-1}
for g in ('al', 'be'):
    val, _ = reduce_triple(('ga', 'de', g))
    good = is_zero(scal(-2 * v, val))
    ok = ok and good
    print(f"  [{'ok ' if good else 'FAIL'}] E*{g} = {g},  since e*{g} = -2v*ga*de*{g} = 0")

print()
print("=== 5. converse, step (7): the linear system ========================")
# With E*al = al, E*be = be the 2nd and 3rd equations read
#     A*de - C*ga = al,   B*de - D*ga = be,
# a linear system with matrix ((A,-C),(B,-D)), determinant -(AD-BC) invertible.
# Check that ga = al*B - be*A, de = al*D - be*C solves it once AD-BC = 1+al*be
# -- i.e. modulo al*be*(anything odd) = 0, which is step 3.
ga_i = add(mul(al, eB), neg(mul(be, eA)))
de_i = add(mul(al, eD), neg(mul(be, eC)))
r1 = add(mul(eA, de_i), neg(mul(eC, ga_i)))       # should be (AD-BC)*al = al*(1+al*be) = al
r2 = add(mul(eB, de_i), neg(mul(eD, ga_i)))       # should be (AD-BC)*be = be*(1+al*be) = be
check("A*de - C*ga = (AD-BC)*al  for the (sysol) values", r1, mul(AD_BC, al))
check("B*de - D*ga = (AD-BC)*be  for the (sysol) values", r2, mul(AD_BC, be))
print("        and (AD-BC)*al = (1+al*be)*al = al,  (AD-BC)*be = (1+al*be)*be = be:")
check("(1+al*be)*al = al", mul(add(ONE, albe), al), al)
check("(1+al*be)*be = be", mul(add(ONE, albe), be), be)
print("        uniqueness: the homogeneous system has only the zero solution because")
print("        det = AD-BC = 1+al*be is invertible.")

print()
print("=== 6. converse, step (8): ga*de = al*be, hence E = 1 - al*be =======")
check("ga*de = (AD-BC)*al*be  for the (sysol) values", mul(ga_i, de_i), mul(AD_BC, albe))
check("(1+al*be)*al*be = al*be", mul(add(ONE, albe), albe), albe)
print("        so L4 becomes E^2 = 1 - 2*al*be; with E = 1+e, e in the odd ideal,")
print("        e*(2+e) = -2*al*be gives e in the ideal of al*be, so e^2 = 0, e = -al*be.")
check("(1-al*be)^2 = 1 - 2*al*be", mul(E_s, E_s), add(ONE, scal(-2, albe)))
check("(-(1-al*be))^2 = 1 - 2*al*be", mul(neg(E_s), neg(E_s)), add(ONE, scal(-2, albe)))
print("        the second root is E = -(1-al*be), all signs reversed.  The condition")
print("        pr(E) = 1 selects the first, i.e. the connected component.")

print()
print("=== 7. the second branch is the first one multiplied by -1 ==========")
# (A,B,C,D,al,be,ga,de,E) -> -(A,B,C,D,al,be,ga,de,E) preserves (sy):
# L1, L4 are quadratic, L2, L3 are quadratic too, so all four are invariant.
def negate_all(e):
    """substitute every generator and every even symbol by its negative"""
    out = el()
    for S, c in e.items():
        c2 = sp.expand(c.subs({A: -A, B: -B, C: -C, D: -D, E: -E}, simultaneous=True)
                       if hasattr(c, 'subs') else c)
        out = add(out, {S: sp.expand(c2 * (-1) ** len(S))})
    return out

for nm, L in (("L1", L1), ("L2", L2), ("L3", L3), ("L4", L4)):
    # L1 and L4 have the constant -1 and are invariant only up to that constant:
    check(f"{nm} is invariant under the global sign change", negate_all(L), L)

print()
print("=====================================================================")
print("ALL CHECKS PASSED" if ok else "SOME CHECKS FAILED")
raise SystemExit(0 if ok else 1)
