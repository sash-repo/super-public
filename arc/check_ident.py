# ============================================================ linear algebra over Q

def rref(rows, n):
    rows = [r[:] for r in rows]
    m, r, piv = len(rows), 0, []
    for j in range(n):
        p = next((i for i in range(r, m) if rows[i][j] != 0), None)
        if p is None:
            continue
        rows[r], rows[p] = rows[p], rows[r]
        iv = F(1) / rows[r][j]
        rows[r] = [v * iv for v in rows[r]]
        for i in range(m):
            if i != r and rows[i][j] != 0:
                c = rows[i][j]
                rows[i] = [a - c * b for a, b in zip(rows[i], rows[r])]
        piv.append(j)
        r += 1
        if r == m:
            break
    return rows[:r], piv


def span_dim(rows, n):
    return len(rref(rows, n)[0])


# ================================================== a Lie superalgebra from a basis

class SuperAlg:
    """finite-dimensional Lie superalgebra given by a basis of generating functions
    inside k^L(1|2n), with the contact bracket L_bracket_h(n, .,.)"""

    def __init__(self, basis, n, tag):
        self.tag, self.n, self.basis = tag, n, basis
        self.keys = sorted({k for f in basis for k in f})
        self.idx = {k: i for i, k in enumerate(self.keys)}
        self.N = len(basis)
        self.par = [parity(f) for f in basis]
        # coordinates of each basis vector, then the change-of-basis matrix
        B = [self._vec(f) for f in basis]
        assert all(v is not None for v in B), "basis leaves the key window"
        self.R, self.piv = rref(B, len(self.keys))
        assert len(self.R) == self.N, "the given 'basis' is not linearly independent"

    def _vec(self, f):
        v = [F(0)] * len(self.keys)
        for k, c in f.items():
            if k not in self.idx:
                return None
            v[self.idx[k]] = F(c)
        return v

    def coords(self, f):
        """express f in the basis; None if f is not in the span"""
        v = self._vec(f)
        if v is None:
            return None
        out = [F(0)] * self.N
        # self.R is the rref of the basis matrix; recover coefficients by back-substitution
        w = v[:]
        for r, (row, j) in enumerate(zip(self.R, self.piv)):
            if w[j] != 0:
                c = w[j]
                out[r] = c
                w = [a - c * b for a, b in zip(w, row)]
        if any(a != 0 for a in w):
            return None
        # out is in terms of the rref rows; convert to the original basis
        return self._rref_to_basis(out)

    def _rref_to_basis(self, out):
        if not hasattr(self, "_T"):
            # matrix expressing the rref rows in terms of the original basis vectors
            M = [self._vec(f) for f in self.basis]
            aug = [M[i][:] + [F(1) if k == i else F(0) for k in range(self.N)]
                   for i in range(self.N)]
            Rr, _ = rref(aug, len(self.keys))
            self._T = [row[len(self.keys):] for row in Rr]
        res = [F(0)] * self.N
        for r, c in enumerate(out):
            if c:
                for i in range(self.N):
                    res[i] += c * self._T[r][i]
        return res

    def closed(self):
        for f in self.basis:
            for g in self.basis:
                if self.coords(L_bracket_h(self.n, f, g)) is None:
                    return False
        return True

    def ad(self, i):
        """matrix of ad(e_i) in the given basis"""
        cols = []
        for j in range(self.N):
            b = L_bracket_h(self.n, self.basis[i], self.basis[j])
            c = self.coords(b) if b else [F(0)] * self.N
            assert c is not None, "not closed under the bracket"
            cols.append(c)
        return [[cols[j][i2] for j in range(self.N)] for i2 in range(self.N)]

    def sdim(self):
        return sum(1 for p in self.par if p == 0), sum(1 for p in self.par if p == 1)

    # ---------------------------------------------------------------- invariants
    def derived_dim(self):
        rows = []
        for f in self.basis:
            for g in self.basis:
                b = L_bracket_h(self.n, f, g)
                if b:
                    v = self._vec(b)
                    if v is not None:
                        rows.append(v)
        return span_dim(rows, len(self.keys))

    def centre_dim(self):
        """dimension of the centre, as the kernel of x -> (ad x)"""
        ads = [self.ad(i) for i in range(self.N)]
        rows = []
        for j in range(self.N):                      # column j of every ad-matrix
            rows.append([ads[i][k][j] for i in range(self.N) for k in range(self.N)])
        # centre = {sum c_i e_i : sum_i c_i ad(e_i) = 0}
        M = [[ads[i][k][j] for i in range(self.N)]
             for k in range(self.N) for j in range(self.N)]
        Rr, piv = rref(M, self.N)
        return self.N - len(piv)

    def even_part(self):
        return [f for f, p in zip(self.basis, self.par) if p == 0]


# ------------------------------------------------------- Burnside irreducibility

def matmul(A, B, n):
    return [[sum(A[i][k] * B[k][j] for k in range(n) if A[i][k]) for j in range(n)]
            for i in range(n)]


def flat(A, n):
    return [A[i][j] for i in range(n) for j in range(n)]


def assoc_envelope_dim(gens, n, cap=None):
    """dimension of the unital associative algebra generated by the matrices `gens`"""
    cap = cap or n * n
    ident = [[F(1) if i == j else F(0) for j in range(n)] for i in range(n)]
    basis_m = [ident]
    rows = [flat(ident, n)]
    dim = 1
    frontier = [ident]
    while frontier and dim < cap:
        new_frontier = []
        for M in frontier:
            for g in gens:
                P = matmul(g, M, n)
                cand = rows + [flat(P, n)]
                d = span_dim(cand, n * n)
                if d > dim:
                    dim = d
                    rows.append(flat(P, n))
                    new_frontier.append(P)
                    if dim >= cap:
                        return dim
        frontier = new_frontier
    return dim


def identify(alg):
    n = alg.N
    ev, od = alg.sdim()
    print(f"  {alg.tag}")
    print(f"     dim = {n}, sdim = ({ev}|{od}), closed under the bracket = {alg.closed()}")
    print(f"     dim [g,g] = {alg.derived_dim()},  dim centre = {alg.centre_dim()}")
    ads = [alg.ad(i) for i in range(n)]
    d = assoc_envelope_dim(ads, n)
    simple = (d == n * n)
    print(f"     dim of the associative algebra generated by the ad's = {d}"
          f"  (= (dim g)^2 = {n * n} ?  {simple})")
    print(f"     ==> adjoint module absolutely irreducible = {simple}"
          f"  ==> g is simple = {simple}")
    if simple and (ev, od) == (4, 4) and n == 8:
        print("     ==> g = sl(1|2) = osp(2|2)")
    elif simple and (ev, od) == (6, 8) and n == 14:
        print("     ==> g = psl(2|2)")
    return simple


def even_structure(alg):
    """structure of g_0: dimension, centre, derived algebra -- to tell
    sl(2) (+) C  (sl(1|2))  from  sl(2) (+) sl(2)  (psl(2|2))"""
    ev = alg.even_part()
    sub = SuperAlg(ev, alg.n, alg.tag + " : even part g_0")
    print(f"     g_0: dim = {sub.N}, dim [g_0,g_0] = {sub.derived_dim()}, "
          f"dim centre(g_0) = {sub.centre_dim()}")


