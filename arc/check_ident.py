r"""
Identification of the annihilators computed in check_bases.py, for the two cases
of Theorem 4.5.1 of the text where the naive candidates are

     svect^L_lambda(1|2) :  Lambda(2) d_t (+) vect(0|2)   (dim 12)
     svect^L'(1|2)       :  vect(0|2)                     (dim  8)

Two things have to be established, and neither is settled by a dimension count:

 (A) window stability -- the annihilator is computed inside a window |m| <= M of
     t-degrees, so we must see that the answer stops growing as M grows.  If the true
     annihilator were infinite-dimensional, the dimension would keep climbing with M.

 (B) the isomorphism type.  We use Burnside's theorem: the adjoint module of a
     finite-dimensional Lie superalgebra g is absolutely irreducible iff the *associative*
     algebra generated by the operators ad(x), x in g, is all of End(g), i.e. has
     dimension (dim g)^2.  Ideals of g are exactly the submodules of the adjoint module,
     so "absolutely irreducible adjoint" == "g simple" (g of dim > 1).  Together with the
     superdimension this pins the algebra down via the classification:

        simple, sdim (4|4), dim  8  ==>  sl(1|2) = osp(2|2) = A(0,1)
        simple, sdim (6|8), dim 14  ==>  psl(2|2) = A(1,1)

     (the only other classical simple superalgebras of these dimensions have the wrong
     sdim: psq(2) is (3|3), osp(4|2) = D(2,1) is (9|8) of dim 17, G(3) has dim 31).

We also print the structure of the even part, as an independent cross-check: sl(1|2)
has g_0 = sl(2) (+) C (a 1-dimensional centre), psl(2|2) has g_0 = sl(2) (+) sl(2)
(semisimple, centreless).
"""

