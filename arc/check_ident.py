def annihilator_alg(lam, derived, M, tag):
    """the annihilator computed by check_bases, as a Lie superalgebra"""
    import io, contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ns, cols = radical_svect(lam, M, derived)
    i_dx, i_dth = make_i(2)

    def img_el(el):
        f = {}
        for c, tok in el[2]:
            kind, m, j, T = tok
            f = add(f, smul(c, i_dx(m, T) if kind == 'dx' else i_dth(m, j, T)))
        return f

    vecs = []
    for v in ns:
        f = {}
        for j, xx in enumerate(v):
            if xx:
                f = add(f, smul(xx, img_el(cols[j])))
        vecs.append(f)
    return SuperAlg(vecs, 2, tag)


