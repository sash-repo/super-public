#!/usr/bin/env python3
"""THE STRUCTURAL STEP of Section 7 of the text (Subsec. 7.2).

Lemmas 7.2.2 and 7.2.3 of the text
produce exactly one candidate constituent SM_{mu1+mu2+n} for each n >= 0 (one
lowest-weight vector v_n per level, characters matching), but do NOT say that
the submodule U(g).v_n generated by v_n IS SM_{mu1+mu2+n}, nor that the sum of
these submodules is direct.  This engine checks, with the weights kept as
SYMBOLS (sympy, exact), every ingredient of the proof written into the text:

(A) SM_mu.  Q_- = d_theta - theta d_t,  Q_+ = t d_theta - t theta d_t - mu theta.
    * Ker Q_- = C.1 (one line, in level 0 only) -- so every nonzero submodule
      of SM_mu contains 1.
    * Q_+^k(1) = c_k(mu) . (monomial), and c_k(mu) is computed: SM_mu is
      generated by 1, equivalently is irreducible, iff mu is not in Zee_{<=0}.
    * The Scasimir  S := (Q_-Q_+ - Q_+Q_-)/2  satisfies S.1 = -(mu/2).1 and
      S^2 = (mu^2/4).id  on every level.

(B) The tensor product W = SM_{mu1} (x) SM_{mu2}, with the Koszul sign.
    * S^tot anticommutes with Q_-^tot and with Q_+^tot; hence (S^tot)^2 is
      central, i.e. commutes with the whole osp(1|2).
    * S^tot v_n = -((mu1+mu2+n)/2) v_n  for the lowest-weight vectors v_n of Lemma 7.2.2.
    * (S^tot)^2 acts on the level-j space W_j with the j+1 eigenvalues
      ((mu1+mu2+n)/2)^2, n = 0..j, each of multiplicity one -- so the
      candidates are separated by a central element as soon as those numbers
      are pairwise distinct, i.e. as soon as 2(mu1+mu2) is not in Zee_{<0}.
    * dim (U.v_n)_j = 1 for every j >= n: the vectors (Q_+^tot)^{j-n} v_n are
      nonzero, and together, for n = 0..j, they form a BASIS of W_j.  The
      determinant of the transition matrix is computed and FACTORED: its zero
      locus is exactly the set of weights where the decomposition degenerates.

Run:  ../venv/bin/python structure.py [NMAX]      (default 8)
"""
import sys

import sympy as sp

mu, mu1, mu2 = sp.symbols("mu mu1 mu2")

# ---------------------------------------------------------------- one factor
# element of SM_mu = C[t,theta]: dict {(a, e): coeff}, monomial t^a theta^e


def clean(d):
    return {k: sp.expand(v) for k, v in d.items() if sp.expand(v) != 0}


def addto(dst, key, c):
    dst[key] = dst.get(key, sp.Integer(0)) + c


def Qm1(u):
    """Q_- = d_theta - theta d_t on SM_mu."""
    out = {}
    for (a, e), c in u.items():
        if e:
            addto(out, (a, 0), c)
        elif a:
            addto(out, (a - 1, 1), -a * c)
    return clean(out)


def Qp1(u, w=mu):
    """Q_+ = t d_theta - t theta d_t - w theta on SM_w."""
    out = {}
    for (a, e), c in u.items():
        if e:
            addto(out, (a + 1, 0), c)          # t d_theta
        else:
            if a:
                addto(out, (a, 1), -a * c)     # -t theta d_t
            addto(out, (a, 1), -w * c)         # -w theta
    return clean(out)


def basis1(n):
    """basis of the level-n space of SM_mu; level = 2a + e."""
    return [(n // 2, 0)] if n % 2 == 0 else [((n - 1) // 2, 1)]


# ------------------------------------------------------- the tensor product
# element of W: dict {(a1, e1, a2, e2): coeff}; theta_1 written left of theta_2


def levelW(m):
    a1, e1, a2, e2 = m
    return 2 * (a1 + a2) + e1 + e2


def basisW(n):
    out = []
    for e1 in (0, 1):
        for e2 in (0, 1):
            r = n - e1 - e2
            if r < 0 or r % 2:
                continue
            for a1 in range(r // 2 + 1):
                out.append((a1, e1, r // 2 - a1, e2))
    return out


def Qm(u):
    """Q_-^tot = Q_- (x) 1 + (-1)^p (x) Q_-."""
    out = {}
    for (a1, e1, a2, e2), c in u.items():
        if e1:
            addto(out, (a1, 0, a2, e2), c)
        elif a1:
            addto(out, (a1 - 1, 1, a2, e2), -a1 * c)
        sg = -1 if e1 else 1
        if e2:
            addto(out, (a1, e1, a2, 0), sg * c)
        elif a2:
            addto(out, (a1, e1, a2, e2), 0)    # placeholder, keeps keys tidy
            addto(out, (a1, e1, a2 - 1, 1), -sg * a2 * c)
    return clean(out)


def Qp(u):
    """Q_+^tot = Q_+ (x) 1 + (-1)^p (x) Q_+, weights mu1 (first), mu2 (second)."""
    out = {}
    for (a1, e1, a2, e2), c in u.items():
        # first factor
        if e1:
            addto(out, (a1 + 1, 0, a2, e2), c)
        else:
            if a1:
                addto(out, (a1, 1, a2, e2), -a1 * c)
            addto(out, (a1, 1, a2, e2), -mu1 * c)
        # second factor, with the Koszul sign of the first
        sg = -1 if e1 else 1
        if e2:
            addto(out, (a1, e1, a2 + 1, 0), sg * c)
        else:
            if a2:
                addto(out, (a1, e1, a2, 1), -sg * a2 * c)
            addto(out, (a1, e1, a2, 1), -sg * mu2 * c)
    return clean(out)


def comp(f, g, u):
    return f(g(u))


def Scas(u, qm, qp):
    """The Scasimir S = (Q_- Q_+ - Q_+ Q_-)/2 + 1/4.

    The shift by 1/4 is what makes S anticommute with the odd generators:
    without it, {S, Q_-} = -(1/2) Q_-.  With it, S^2 is central."""
    out = {}
    for k, v in comp(qm, qp, u).items():
        addto(out, k, sp.Rational(1, 2) * v)
    for k, v in comp(qp, qm, u).items():
        addto(out, k, -sp.Rational(1, 2) * v)
    for k, v in u.items():
        addto(out, k, sp.Rational(1, 4) * v)
    return clean(out)


# ------------------------------------------------- the vectors v_n
def poly_S(m):
    """S^m = (t_1 - t_2)^m."""
    out = {}
    b = 1
    for i in range(m + 1):
        out[(m - i, 0, i, 0)] = sp.Integer(b * (-1) ** i)
        b = b * (m - i) // (i + 1)
    return clean(out)


def vn(n):
    """v_{2m} = S^m + (m/2) Theta Xi S^{m-1},   v_{2m+1} = Xi S^m."""
    if n % 2 == 0:
        m = n // 2
        v = poly_S(m)
        if m:
            # Theta.Xi.u = -2 theta_1 theta_2 u; (m/2) Theta Xi S^{m-1}
            for (a1, e1, a2, e2), c in poly_S(m - 1).items():
                addto(v, (a1, 1, a2, 1), -2 * sp.Rational(m, 2) * c)
        return clean(v)
    out = {}
    for (a1, e1, a2, e2), c in poly_S((n - 1) // 2).items():
        addto(out, (a1, 1, a2, 0), c)          # theta_1 . u
        addto(out, (a1, 0, a2, 1), -c)         # - theta_2 . u
    return clean(out)


# ----------------------------------------------------------------- utilities
def vec(u, bas):
    idx = {m: i for i, m in enumerate(bas)}
    out = [sp.Integer(0)] * len(bas)
    for m, c in u.items():
        out[idx[m]] += c
    return [sp.expand(x) for x in out]


def opmatrix(op, src, tgt):
    """matrix of op: span(src) -> span(tgt), columns = images of src."""
    cols = []
    for m in src:
        cols.append(vec(op({m: sp.Integer(1)}), tgt))
    return sp.Matrix([[cols[j][i] for j in range(len(src))] for i in range(len(tgt))])


def ok(flag):
    return "OK" if flag else "*** FAILED ***"


# ---------------------------------------------------------------------- main
def main():
    N = int(sys.argv[1]) if len(sys.argv) > 1 else 8
    print("=" * 74)
    print("the structural step, weights kept symbolic")
    print("levels checked: n <= %d" % N)
    print("=" * 74)
    bad = 0

    # ---------------------------------------------------------------- (A)
    print("\n(A) THE FACTOR SM_mu\n" + "-" * 74)

    # A1: Ker Q_- = C.1
    kerlv = []
    for n in range(1, N + 1):
        src, tgt = basis1(n), basis1(n - 1)
        M = opmatrix(Qm1, src, tgt)
        if M.rank() != len(src):
            kerlv.append(n)
    print("A1  Ker Q_- meets no level n with 1<=n<=%d : %s" % (N, ok(not kerlv)))
    bad += bool(kerlv)

    # A2: Q_+^k(1); the coefficient as a polynomial in mu
    u = {(0, 0): sp.Integer(1)}
    coeffs = []
    for k in range(1, 2 * N + 1):
        u = Qp1(u)
        if not u:
            coeffs.append((k, sp.Integer(0)))
            break
        assert len(u) == 1, u
        (m, c), = u.items()
        coeffs.append((k, sp.factor(c)))
    print("A2  Q_+^k(1) = c_k(mu) . t^a theta^e :")
    for k, c in coeffs[:8]:
        print("      k=%d   c_k = %s" % (k, c))
    roots = set()
    for k, c in coeffs:
        for r in sp.Poly(c, mu).all_roots():
            roots.add(sp.nsimplify(r))
    exp = set(sp.Integer(-i) for i in range(0, 2 * N))
    good = roots.issubset(exp) and set(sp.Integer(-i) for i in range(0, N)) <= roots
    print("      zeros of the c_k, k<=%d : %s" % (2 * N, sorted(roots, key=lambda x: -x)))
    print("      => SM_mu is generated by 1 (equivalently, is irreducible)")
    print("         iff mu is not in Zee_{<=0} : %s" % ok(good))
    bad += (not good)

    # A3: the Scasimir on SM_mu
    s0 = sp.Rational(1, 4) - mu / 2                       # the value of S on 1
    S1 = Scas({(0, 0): sp.Integer(1)}, Qm1, Qp1)
    v0 = sp.expand(S1.get((0, 0), 0) - s0)
    print("A3  S := (Q_-Q_+ - Q_+Q_-)/2 + 1/4 ;  S.1 = (1/4 - mu/2).1 : %s"
          % ok(v0 == 0 and len(S1) <= 1))
    bad += (v0 != 0)
    sq_ok = True
    for n in range(0, N + 1):
        for m in basis1(n):
            w = Scas(Scas({m: sp.Integer(1)}, Qm1, Qp1), Qm1, Qp1)
            if clean(w) != clean({m: sp.expand(s0 ** 2)}):
                sq_ok = False
    print("    S^2 = ((1-2mu)/4)^2 . id on every level n<=%d : %s" % (N, ok(sq_ok)))
    bad += (not sq_ok)

    # ---------------------------------------------------------------- (B)
    print("\n(B) THE TENSOR PRODUCT W = SM_mu1 (x) SM_mu2\n" + "-" * 74)

    def S(u):
        return Scas(u, Qm, Qp)

    # B1: S anticommutes with the odd generators
    anti = True
    for n in range(0, N + 1):
        for m in basisW(n):
            e = {m: sp.Integer(1)}
            for X in (Qm, Qp):
                lhs = S(X(e))
                rhs = {k: -v for k, v in X(S(e)).items()}
                if clean(lhs) != clean(rhs):
                    anti = False
    print("B1  S Q_pm = - Q_pm S  on all levels n<=%d : %s" % (N, ok(anti)))
    print("      hence S^2 commutes with osp(1|2): it is a central element")
    bad += (not anti)

    # B2: S v_n = (1/4 - (mu1+mu2+n)/2) v_n
    b2 = True
    for n in range(0, N + 1):
        v = vn(n)
        s = sp.Rational(1, 4) - (mu1 + mu2 + n) / 2
        if clean(S(v)) != clean({k: s * c for k, c in v.items()}):
            b2 = False
            print("      n=%d MISMATCH" % n)
    print("B2  S v_n = (1/4 - (mu1+mu2+n)/2) v_n for n<=%d : %s" % (N, ok(b2)))
    print("      i.e. v_n behaves as the lowest-weight vector of SM_{mu1+mu2+n}")
    bad += (not b2)

    # B3: the spectrum of S^2 on each level, and the transition determinant
    print("B3  level j: basis {(Q_+)^(j-n) v_n : 0<=n<=j}, det of the transition")
    dets = {}
    for j in range(0, N + 1):
        bas = basisW(j)
        cols = []
        for n in range(0, j + 1):
            w = vn(n)
            for _ in range(j - n):
                w = Qp(w)
            cols.append(vec(w, bas))
        M = sp.Matrix([[cols[n][i] for n in range(j + 1)] for i in range(len(bas))])
        if M.rows != M.cols:
            print("      j=%d : NOT SQUARE (%dx%d) ***" % (j, M.rows, M.cols))
            bad += 1
            continue
        d = sp.factor(sp.expand(M.det()))
        dets[j] = d
        print("      j=%2d  dim W_j = %d   det = %s" % (j, len(bas), d))
    # the eigenvalues of S^2 on W_j
    print("    the spectrum of S^2 on W_j (should be ((1-2(mu1+mu2+n))/4)^2, n=0..j):")
    spec_ok = True
    x = sp.Symbol("x")
    for j in range(0, min(N, 5) + 1):
        bas = basisW(j)
        M = opmatrix(lambda u: S(S(u)), bas, bas)
        cp = M.charpoly(x).as_expr()
        want = sp.prod([x - (sp.Rational(1, 4) - (mu1 + mu2 + n) / 2) ** 2
                        for n in range(j + 1)])
        same = sp.expand(cp - sp.expand(want)) == 0
        spec_ok &= same
        print("      j=%d : %s" % (j, ok(same)))
    bad += (not spec_ok)

    # ---------------------------------------------------------------- (C)
    print("\n(C) WHERE IT DEGENERATES\n" + "-" * 74)
    # C1: no constituent ever collapses -- (Q_+)^k v_n is never identically zero
    c1 = True
    for n in range(0, min(N, 4) + 1):
        w = vn(n)
        for k in range(1, N - n + 1):
            w = Qp(w)
            if not clean(w):
                c1 = False
                print("      (Q_+)^%d v_%d vanishes identically ***" % (k, n))
    print("C1  (Q_+)^k v_n is never identically zero: no constituent collapses : %s"
          % ok(c1))
    bad += (not c1)

    # C2: on mu1+mu2+n = 0 the constituents OVERLAP: Q_+ v_n becomes a multiple
    #     of v_{n+1}, so U.v_{n+1} sits inside U.v_n and the sum is not direct
    c2 = True
    for n in range(0, min(N, 4)):
        sub = {mu2: -mu1 - n}                       # i.e. mu1 + mu2 + n = 0
        w = clean({k: sp.expand(c.subs(sub)) for k, c in Qp(vn(n)).items()})
        u = clean({k: sp.expand(c.subs(sub)) for k, c in vn(n + 1).items()})
        # is w a scalar multiple of u?
        bas = basisW(n + 1)
        A, B = vec(w, bas), vec(u, bas)
        lam = None
        for a, b in zip(A, B):
            if b != 0:
                lam = sp.simplify(a / b)
                break
        prop = lam is not None and all(sp.simplify(a - lam * b) == 0 for a, b in zip(A, B))
        print("      mu1+mu2+n = 0, n=%d : Q_+ v_%d = (%s) v_%d : %s"
              % (n, n, lam, n + 1, ok(prop and lam != 0)))
        c2 &= bool(prop and lam != 0)
    print("C2  on mu1+mu2+n = 0 the constituent n+1 sits INSIDE the constituent n : %s"
          % ok(c2))
    bad += (not c2)

    # ------------------------------------------------------------ conclusion
    print("\n" + "=" * 74)
    print("the transition determinants, factored (the degeneracy locus):")
    for j, d in dets.items():
        print("   j=%2d : %s" % (j, d))
    print("=" * 74)
    print("FAILURES: %d" % bad)
    return bad


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
