#!/usr/bin/env python3
"""What Q_- and Q_+ generate on SM_mu.

The two fields of eq. (138),

    Q_- = d_theta - theta d_t,      Q_+ = t d_theta - t theta d_t - mu theta,

act on SM_mu = C[t, theta].  They are ODD.  Their pairwise anticommutators are
even, so the three operators Q_-^2, {Q_-,Q_+}, Q_+^2 span an even subalgebra and
nothing else: they give osp(1|2)_ev = sl(2) alone, and the odd part
comes from Q_\\pm themselves.  What the computation checks:

  1)  Q_\\pm are odd operators on C[t,theta];
  2)  Q_-^2 = -d_t                        (eq. (142) of the text);
  3)  {Q_-,Q_+} = -(2t d_t + theta d_theta + mu) = H   (eq. (142));
  4)  Q_+^2 = -(t^2 d_t + t theta d_theta + mu t)      -- the raising operator;
  5)  those three are linearly independent and close under the bracket: an
      sl(2), of sdim = (3|0);
  6)  the subalgebra generated by the three of them is that sl(2) and contains
      NEITHER Q_- NOR Q_+;
  7)  the Lie SUPERalgebra generated by Q_- and Q_+ alone is of sdim = (3|2),
      i.e., the whole of osp(1|2) -- which is why imposing invariance with
      respect to Q_\\pm alone is imposing it with respect to osp(1|2).

An operator is represented by its matrix on the monomials t^a, theta t^a with
a <= N; every operator in sight is of order <= 2 with coefficients of degree
<= 2, so agreement on that range is agreement.  Coefficients are exact:
sympy over Q(mu).
"""

import sympy as sp

N = 10                     # monomials t^a, theta t^a with a <= N
mu = sp.Symbol('mu')

# A superpolynomial f_0(t) + theta f_1(t) is a pair of sympy polynomials in t.
t = sp.Symbol('t')


def basis():
    """(parity, exponent) of each basis monomial, in a fixed order."""
    out = []
    for a in range(N + 1):
        out.append((0, a))          # t^a
    for a in range(N + 1):
        out.append((1, a))          # theta t^a
    return out


BAS = basis()
IDX = {b: i for i, b in enumerate(BAS)}


def as_pair(par, a):
    """monomial -> (f0, f1)"""
    return (t**a, sp.Integer(0)) if par == 0 else (sp.Integer(0), t**a)


def to_vector(pair, where):
    """(f0,f1) -> coordinate column; raise if it leaves the truncation."""
    vec = [sp.Integer(0)] * len(BAS)
    for par, f in enumerate(pair):
        f = sp.expand(f)
        if f == 0:
            continue
        p = sp.Poly(f, t)
        for (a,), c in p.terms():
            if a > N:
                raise RuntimeError(f"{where}: degree {a} leaves the truncation")
            vec[IDX[(par, a)]] += c
    return vec


# --- the operators, written on pairs -----------------------------------------
# d_theta (f0 + theta f1) = f1 ;  theta*(f0 + theta f1) = theta f0
# d_t acts on each component; multiplication by t likewise.

def op_Qminus(f0, f1):
    # (d_theta - theta d_t)(f0 + theta f1) = f1 - theta f0'
    return (f1, -sp.diff(f0, t))


def op_Qplus(f0, f1):
    # (t d_theta - t theta d_t - mu theta)(f0 + theta f1)
    #   = t f1 + theta(-t f0' - mu f0)
    return (t * f1, -t * sp.diff(f0, t) - mu * f0)


def op_dt(f0, f1):
    return (sp.diff(f0, t), sp.diff(f1, t))


def op_H(f0, f1):
    # -(2t d_t + theta d_theta + mu)
    return (-(2 * t * sp.diff(f0, t) + mu * f0),
            -(2 * t * sp.diff(f1, t) + f1 + mu * f1))


def op_raise(f0, f1):
    # -(t^2 d_t + t theta d_theta + mu t)
    return (-(t**2 * sp.diff(f0, t) + mu * t * f0),
            -(t**2 * sp.diff(f1, t) + t * f1 + mu * t * f1))


# --- turn a callable into a matrix; compose matrices --------------------------
def matrix_of(fn, name, margin=3):
    """Columns for a <= N-margin only; the rest is padding for compositions."""
    cols = []
    for (par, a) in BAS:
        if a > N - margin:
            cols.append([sp.Integer(0)] * len(BAS))
            continue
        cols.append(to_vector(fn(*as_pair(par, a)), name))
    return sp.Matrix([[cols[j][i] for j in range(len(BAS))]
                      for i in range(len(BAS))])


def parity_of(M):
    """0 if even (preserves parity of the monomial), 1 if odd, None if mixed."""
    half = N + 1
    ee = any(M[i, j] != 0 for i in range(half) for j in range(half))
    oo = any(M[i, j] != 0 for i in range(half, 2 * half)
             for j in range(half, 2 * half))
    eo = any(M[i, j] != 0 for i in range(half) for j in range(half, 2 * half))
    oe = any(M[i, j] != 0 for i in range(half, 2 * half) for j in range(half))
    if (ee or oo) and not (eo or oe):
        return 0
    if (eo or oe) and not (ee or oo):
        return 1
    return None


def trunc(M, keep):
    """The block on the monomials with a <= keep -- where compositions are honest."""
    rows = [IDX[(p, a)] for p in (0, 1) for a in range(keep + 1)]
    return M[rows, rows]


CHECKS = []


def check(label, ok):
    CHECKS.append((label, bool(ok)))
    print(("  ok   " if ok else "  FAIL ") + label)


def main():
    print(__doc__.strip().splitlines()[0])
    print()

    Qm = matrix_of(op_Qminus, 'Q_-')
    Qp = matrix_of(op_Qplus, 'Q_+')
    DT = matrix_of(op_dt, 'd_t')
    H = matrix_of(op_H, 'H')
    RA = matrix_of(op_raise, 'raise')

    print("1) parities")
    check("Q_- is odd", parity_of(Qm) == 1)
    check("Q_+ is odd", parity_of(Qp) == 1)
    check("d_t, H and the raising operator are even",
          all(parity_of(M) == 0 for M in (DT, H, RA)))

    K = N - 4                      # range on which two compositions are honest
    print("\n2) the squares and the anticommutator, eq. (142)")
    QmQm = sp.expand(Qm * Qm)
    QpQp = sp.expand(Qp * Qp)
    anti = sp.expand(Qm * Qp + Qp * Qm)
    check("Q_-^2 = -d_t", trunc(QmQm, K) == trunc(-DT, K))
    check("{Q_-,Q_+} = H = -(2t d_t + theta d_theta + mu)",
          trunc(anti, K) == trunc(H, K))
    check("Q_+^2 = -(t^2 d_t + t theta d_theta + mu t)",
          trunc(QpQp, K) == trunc(RA, K))

    def flatten(mats, keep):
        """columns = the truncated matrices, entry by entry"""
        T = [trunc(M, keep) for M in mats]
        return sp.Matrix([[sp.expand(S[i, j]) for S in T]
                          for i in range(T[0].rows) for j in range(T[0].cols)])

    def in_span(M, mats, keep):
        cols = flatten(mats, keep)
        v = flatten([M], keep)
        return cols.rank() == cols.row_join(v).rank()

    print("\n3) the three even ones span an sl(2)")
    EVEN = [QmQm, anti, QpQp]             # full matrices; truncate at each use
    check("linearly independent over Q(mu): rank 3", flatten(EVEN, K).rank() == 3)

    def br(A, B):                         # both even here: the commutator
        return sp.expand(A * B - B * A)

    # the honest range shrinks by one composition at each bracket
    K2 = K - 2
    closed = all(in_span(br(A, B), EVEN, K2) for A in EVEN for B in EVEN)
    check("closed under the bracket", closed)

    print("\n4) the even ones do NOT give Q_\\pm")
    check("Q_- is not in the span of Q_-^2, {Q_-,Q_+}, Q_+^2",
          not in_span(Qm, EVEN, K2))
    check("Q_+ is not in that span", not in_span(Qp, EVEN, K2))
    check("every bracket of two even operators is even -- so the subalgebra "
          "they generate is even, of sdim (3|0)",
          closed and all(parity_of(br(A, B)) in (0, None) and
                         parity_of(br(A, B)) != 1 for A in EVEN for B in EVEN))

    print("\n5) Q_\\pm alone generate the whole of osp(1|2), of sdim (3|2)")
    ODD = [Qm, Qp]
    check("the three even generators ARE the anticommutators of Q_\\pm",
          True)                           # established in 2) above, restated
    stays = all(in_span(br(A, X), ODD, K2 - 2) for A in EVEN for X in ODD)
    check("[even, Q_\\pm] stays in the span of Q_- and Q_+", stays)
    check("Q_- and Q_+ are linearly independent: the odd part is 2-dimensional",
          flatten(ODD, K2).rank() == 2)
    check("sdim of the generated Lie superalgebra = (3|2) = sdim osp(1|2)",
          flatten(EVEN, K).rank() == 3 and flatten(ODD, K2).rank() == 2
          and closed and stays)

    bad = [c for c, ok in CHECKS if not ok]
    print(f"\n{len(CHECKS)} checks, {len(bad)} failed")
    for c in bad:
        print("  FAILED:", c)
    return 1 if bad else 0


if __name__ == '__main__':
    raise SystemExit(main())
