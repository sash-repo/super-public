def check_embedding(n, M=4):
    """i(D) for D in vect^L(1|n) -> k^L(1|2n), eq. (28); check it is a
    homomorphism, and that the factor 2^{-m} is what makes it one."""
    print("=" * 72)
    print("(F)  the embedding i: vect^L(1|%d) -> k^L(1|%d), eq. (28)" % (n, 2 * n))
    # coordinates of k^L(1|2n): xi_i = 2i-1, eta_i = 2i  (i = 1..n)
    xi = [2 * i - 1 for i in range(1, n + 1)]
    eta = [2 * i for i in range(1, n + 1)]
    Phi = {}
    for i in range(n):
        Phi = add(Phi, mono(0, (xi[i], eta[i])))
    def tPhi(m):
        """(t - Phi)^m for m >= 0 ; for m < 0 expand as a Laurent polynomial"""
        out = mono(0, (), 1)
        if m >= 0:
            base = add(mono(1), smul(-1, Phi))
            for _ in range(m):
                out = mul(out, base)
            return out
        # (t - Phi)^m = t^m (1 - Phi/t)^m = t^m sum_k binom(m,k) (-Phi/t)^k
        out = {}
        from math import comb
        for k in range(0, n + 1):
            cbin = F(1)
            for j in range(k):
                cbin *= F(m - j, j + 1)
            term = mono(m - k, (), cbin * (-1) ** k)
            P = mono(0, (), 1)
            for _ in range(k):
                P = mul(P, Phi)
            out = add(out, mul(term, P))
        return out
    # vect^L(1|n) in coordinates (x | theta_1..theta_n): use x^m d_x and x^m d_theta
    def i_of(kind, m, j=None, coeff=F(1), scale=True):
        s = F(1, 2 ** m) if scale else F(1)
        if kind == 'dx':
            return smul(coeff * s, tPhi(m))
        return smul(coeff * s, mul(mono(0, (eta[j],)), tPhi(m)))
    # vect^L(1|1): brackets [x^m d_x, x^k d_x] = (k-m) x^{m+k-1} d_x etc.
    for scale in (True, False):
        bad = 0
        for m in range(0, M):
            for k in range(0, M):
                lhs = L_bracket(2 * n, i_of('dx', m, scale=scale), i_of('dx', k, scale=scale))
                rhs = i_of('dx', m + k - 1, coeff=F(k - m), scale=scale) if m + k - 1 >= 0 else {}
                if not eq(lhs, rhs):
                    bad += 1
        print("   with%s the factor 2^{-m}: [i(x^m d_x), i(x^k d_x)] = i([x^m d_x, x^k d_x]) : %s"
              % ("" if scale else "OUT", "OK" if bad == 0 else "%d failures" % bad))

