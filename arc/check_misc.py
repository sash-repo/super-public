def ops_as_VF(n):
    """D^M_zeta, D^M_{theta_i}, D, K^M_{theta_i}, X  as vector fields."""
    odd = tuple(range(0, n))
    half = F(1, 2)
    Dz = VF({'t': mono(0, (0,)), 0: mono(-1)}, odd)
    Dcal = VF({'t': mono(0), 0: smul(-half, mono(-1, (0,)))}, odd)
    Dth = [VF({'t': mono(0, (i,)), i: mono(0),
               0: smul(-half, mono(-1, (i, 0)))}, odd) for i in range(1, n)]
    Kth = [VF({'t': mono(0, (i,)), i: mono(0, (), -1),
               0: smul(-half, mono(-1, (i, 0)))}, odd) for i in range(1, n)]
    X = VF({0: mono(0), 't': mono(1, (0,))}, odd)
    return Dz, Dcal, Dth, Kth, X

def report_h_f(n):
    Dz, Dcal, Dth, Kth, X = ops_as_VF(n)
    print("-" * 72)
    print("n = %d" % n)
    print("  D^M_zeta            =", Dz)
    print("  [D^M_z, D^M_z]      =", Dz.bracket(Dz))
    print("  X = d_z + t z d_t   =", X)
    print("  (1/t) X             =", VF({c: mul(mono(-1), f) for c, f in X.c.items()}, X.odd),
          "   equals D^M_zeta:", VF({c: mul(mono(-1), f) for c, f in X.c.items()}, X.odd) == Dz)
    gens_h = [Dz, Dcal] + Dth
    B = closure(gens_h, maxdim=120, depth=10)
    print("  h_%d: %d basis elements found (search truncated at 120)" % (n, len(B)))
    bydeg = {}
    for Y in B:
        for d in degVF(Y, n, 'M'):
            bydeg.setdefault(d, []).append(Y)
    for d in sorted(bydeg, reverse=True)[:14]:
        print("     degree %3d : dim %d   %s" % (d, len(bydeg[d]),
              "; ".join(str(Y) for Y in bydeg[d][:3]) + (" ..." if len(bydeg[d]) > 3 else "")))
    gens_f = [X] + Kth
    Bf = closure(gens_f, maxdim=120, depth=10)
    print("  f_%d: dim = %d" % (n, len(Bf)))
    bydeg = {}
    for Y in Bf:
        for d in degVF(Y, n, 'M'):
            bydeg.setdefault(d, []).append(Y)
    for d in sorted(bydeg, reverse=True):
        print("     degree %3d : dim %d   %s" % (d, len(bydeg[d]),
              "; ".join(str(Y) for Y in bydeg[d])))

# --------------------------------------------------------------------- (D)

def kernels_L(n):
    """Ker s_n on k^L(1|n) in the window of t-powers 0..4 (the kernel is
    concentrated in low degrees; we search a wide window and check)."""
    sn = L_sn(n)
    keys = monomials(n, range(-4, 6), tuple(range(1, n + 1)))
    ker = [k for k in keys if not sn(mono(*k))]
    return ker

def kernels_M(n):
    sn = M_sn(n)
    keys = monomials(n, range(-4, 6), tuple(range(0, n)))
    ker = [k for k in keys if not sn(mono(*k))]
    return ker

def pr_keys(ks, kind='L'):
    def nm(k):
        a, S = k
        s = "".join(("z" if j == 0 else "th%d" % j) for j in S)
        base = ("" if a == 0 else ("t" if a == 1 else "t^%d" % a))
        return (base + s) if (base or s) else "1"
    return ", ".join(nm(k) for k in ks)

# --------------------------------------------------------------------- (E)

def div(X, n):
    """Div(A d_t + sum B_i d_i) = d_t A + sum (-1)^{p(B_i)} d_i B_i"""
    out = d_t(X.c.get('t', {}))
    for i in X.odd:
        Bi = X.c.get(i, {})
        if Bi:
            out = add(out, smul((-1) ** parity(Bi), d_odd(i, Bi)))
    return out

def check_div():
    print("=" * 72)
    print("(E)  Div K_f  for k^L(1|n)")
    for n in (1, 2, 3, 4):
        ok = True
        for k in monomials(n, range(-3, 4), tuple(range(1, n + 1))):
            f = mono(*k)
            lhs = div(K_L(n, f), n)
            rhs = smul(2 - n, d_t(f))
            if not eq(lhs, rhs):
                ok = False
                print("     n=%d  f=%s : Div K_f = %s , (2-n) d_t f = %s" % (n, k, show(lhs), show(rhs)))
                break
        print("   n=%d : Div K_f = (2-n) d_t(f) : %s" % (n, "OK" if ok else "FAILS"))

