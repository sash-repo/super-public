# ---------------------------------------------------------------- gradings

def degf(key, n, kind):
    """degree of the monomial t^a theta_S: deg t = 2, deg theta_i = 1, deg zeta = 0"""
    a, S = key
    if kind == 'M':
        return 2 * a + len([j for j in S if j != 0])
    return 2 * a + len(S)

def degVF(X, n, kind):
    """degree of a homogeneous vector field"""
    degs = set()
    for c, f in X.c.items():
        dc = -2 if c == 't' else (0 if (kind == 'M' and c == 0) else -1)
        for k in f:
            degs.add(degf(k, n, kind) + dc)
    return degs

# --------------------------------------------------- closure of a Lie algebra

def flatten(X):
    """a hashable canonical form of a vector field"""
    return tuple(sorted(((c, tuple(sorted(f.items()))) for c, f in X.c.items() if f), key=str))

def closure(gens, maxdim=400, depth=12):
    """Lie superalgebra generated by gens (spanning set, not a basis)."""
    basis = []
    seen = set()
    def addvec(X):
        if X.is_zero():
            return False
        k = flatten(X)
        if k in seen:
            return False
        # linear independence over the existing basis (naive: use dict of monomials)
        seen.add(k)
        basis.append(X)
        return True
    frontier = []
    for g in gens:
        if addvec(g):
            frontier.append(g)
    for _ in range(depth):
        new = []
        for X in list(basis):
            for Y in frontier:
                Z = X.bracket(Y)
                Z = reduce_mod(Z, basis)
                if Z is not None and addvec(Z):
                    new.append(Z)
        if not new or len(basis) > maxdim:
            break
        frontier = new
    return basis

def reduce_mod(Z, basis):
    """Gaussian reduction of Z against basis (as vectors in the monomial space)."""
    Z = VF({c: dict(f) for c, f in Z.c.items() if f}, Z.odd)
    for B in basis:
        lead = leading(B)
        if lead is None:
            continue
        cz = Z.c.get(lead[0], {}).get(lead[1])
        if cz:
            lam = F(cz) / F(leading_coeff(B))
            Z = Z.plus(B.scal(-lam))
    return None if Z.is_zero() else Z

def leading(X):
    ks = []
    for c, f in X.c.items():
        for k in f:
            ks.append((c, k))
    if not ks:
        return None
    return sorted(ks, key=str)[0]

def leading_coeff(X):
    c, k = leading(X)
    return X.c[c][k]

