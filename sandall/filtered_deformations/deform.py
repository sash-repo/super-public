def as_map(vec, src):
    """cochain coordinates -> dict (i<j) -> vector in g."""
    c = {}
    for co, (S, m) in zip(vec, src):
        if co:
            c.setdefault(S, [0] * g.n)
            c[S][m] = (c[S][m] + co) % P
    return c


def cval(c, i, j):
    if i == j:
        return [0] * g.n
    if i < j:
        return c.get((i, j), [0] * g.n)
    v = c.get((j, i), [0] * g.n)
    return [(-x) % P for x in v]


def cbil(c, x, y):
    """extend the cochain bilinearly to arbitrary vectors."""
    out = [0] * g.n
    for i, xi in enumerate(x):
        if not xi:
            continue
        for j, yj in enumerate(y):
            if not yj:
                continue
            v = cval(c, i, j)
            f = xi * yj % P
            for k, vk in enumerate(v):
                if vk:
                    out[k] = (out[k] + f * vk) % P
    return out


def nr_square(c1, c2):
    """the Nijenhuis-Richardson bracket [c1,c2] (symmetric); zero <=> integrable."""
    bad = []
    for i, j, k in combinations(range(g.n), 3):
        e = lambda t: [1 if s == t else 0 for s in range(g.n)]
        tot = [0] * g.n
        for a, b, d in ((i, j, k), (j, k, i), (k, i, j)):
            for (u, v) in ((c1, c2), (c2, c1)):
                t = cbil(v, cval(u, a, b), e(d))
                tot = [(x + y) % P for x, y in zip(tot, t)]
        if any(tot):
            bad.append((i, j, k))
    return bad


