_SUBSP = {}


def subspaces(dim, codim):
    """all subspaces of F_3^dim of the given codimension, in rref form."""
    key = (dim, codim)
    if key in _SUBSP:
        return _SUBSP[key]
    k = dim - codim                      # dimension of the subspace
    out = []
    if k < 0:
        _SUBSP[key] = out
        return out
    for piv in combinations(range(dim), k):
        free = [(i, c) for i in range(k) for c in range(dim)
                if c > piv[i] and c not in piv]
        for vals in product(range(P), repeat=len(free)):
            M = [[0] * dim for _ in range(k)]
            for i in range(k):
                M[i][piv[i]] = 1
            for (pos, val) in zip(free, vals):
                M[pos[0]][pos[1]] = val
            out.append(M)
    _SUBSP[key] = out
    return out


def span_add(basis, v):
    """add v to a list of rref rows; True if the span grew."""
    v = v[:]
    for r in basis:
        pc = next(i for i, x in enumerate(r) if x)
        if v[pc]:
            f = v[pc]
            v = [(a - f * b) % P for a, b in zip(v, r)]
    if not any(v):
        return False
    pc = next(i for i, x in enumerate(v) if x)
    inv = pow(v[pc], P - 2, P)
    v = [x * inv % P for x in v]
    for i, r in enumerate(basis):
        if r[pc]:
            f = r[pc]
            basis[i] = [(a - f * b) % P for a, b in zip(r, v)]
    basis.append(v)
    basis.sort(key=lambda r: next(i for i, x in enumerate(r) if x))
    return True


def contains(basis, v):
    v = v[:]
    for r in basis:
        pc = next(i for i, x in enumerate(r) if x)
        if v[pc]:
            f = v[pc]
            v = [(a - f * b) % P for a, b in zip(v, r)]
    return not any(v)


def unit(n, i):
    return [1 if s == i else 0 for s in range(n)]


def weisfeiler(alg, maxcodim=3):
    """all torus-graded subalgebras of codimension <= maxcodim (the torus is the
    weight class (0,0), so it lies in every such subalgebra automatically)."""
    n = alg.n
    keys = sorted(cls)
    found = []
    for ncut in range(1, maxcodim + 1):
        for cut in combinations(keys, ncut):
            for codims in product(range(1, maxcodim + 1), repeat=ncut):
                if sum(codims) > maxcodim:
                    continue
                if any(c > len(cls[k]) for k, c in zip(cut, codims)):
                    continue
                uncut = [k for k in keys if k not in cut]
                # vectors forced into the cut classes by brackets of uncut ones
                forced = {k: [] for k in cut}
                dead = False
                for a in uncut:
                    for b in uncut:
                        for i in cls[a]:
                            for j in cls[b]:
                                br = alg.bracket(unit(n, i), unit(n, j))
                                if not any(br):
                                    continue
                                for k in cut:
                                    proj = [0] * n
                                    for t in cls[k]:
                                        proj[t] = br[t]
                                    if any(proj):
                                        span_add(forced[k], proj)
                        if dead:
                            break
                for k, c in zip(cut, codims):
                    if len(forced[k]) > len(cls[k]) - c:
                        dead = True
                if dead:
                    continue
                # enumerate subspaces of the cut classes containing `forced`
                opts = []
                for k, c in zip(cut, codims):
                    good = []
                    for S in subspaces(len(cls[k]), c):
                        rows = []
                        for b in S:
                            v = [0] * n
                            for i, co in zip(cls[k], b):
                                v[i] = co
                            rows.append(v)
                        red = rref(rows, n)[0]
                        if all(contains(red, f) for f in forced[k]):
                            good.append(red)
                    opts.append(good)
                base = []
                for k in uncut:
                    for i in cls[k]:
                        span_add(base, unit(n, i))
                for choice in product(*opts):
                    red = [r[:] for r in base]
                    for part in choice:
                        for r in part:
                            span_add(red, r)
                    if len(red) != n - sum(codims):
                        continue
                    closed = True
                    for a in range(len(red)):
                        for b in range(a + 1, len(red)):
                            br = alg.bracket(red[a], red[b])
                            if any(br) and not contains(red, br):
                                closed = False
                                break
                        if not closed:
                            break
                    if closed:
                        found.append((sum(codims), red))
    return found


def module_gen(alg, L0, seed):
    """the L_0-submodule generated by L_0 and the vector `seed`."""
    n = alg.n
    span = []
    for r in L0:
        span_add(span, r)
    span_add(span, seed)
    frontier = [seed]
    while frontier:
        new = []
        for u in frontier:
            for r0 in L0:
                b = alg.bracket(r0, u)
                if any(b) and span_add(span, b):
                    new.append(b)
        frontier = new
    return span


def filtration(alg, L0):
    """the Weisfeiler filtration: L_{-1} = a minimal L_0-invariant subspace
    strictly containing L_0 (torus-graded, so a weight vector generates it),
    then L_{-i-1} = [L_{-1}, L_{-i}] + L_{-i}.  Returns the list of dims
    (L_0, L_{-1}, L_{-2}, ...)."""
    n = alg.n
    L0 = rref([r[:] for r in L0], n)[0]
    best = None
    for k, idxs in cls.items():                      # torus weight classes
        for coeffs in product(range(P), repeat=len(idxs)):
            if not any(coeffs):
                continue
            v = [0] * n
            for i, co in zip(idxs, coeffs):
                v[i] = co
            if contains(L0, v):
                continue
            span = module_gen(alg, L0, v)
            if best is None or len(span) < len(best):
                best = span
    dims = [len(L0), len(best)]
    cur = best
    while len(cur) < n:
        new = [r[:] for r in cur]
        grew = False
        for a in best:
            for b in cur:
                br = alg.bracket(a, b)
                if any(br) and span_add(new, br):
                    grew = True
        if not grew:
            break
        cur = new
        dims.append(len(cur))
    return dims


