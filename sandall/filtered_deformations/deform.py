def is_simple(alg):
    """an ideal contains, with any vector, the ideal it generates; it suffices to
    test the ideals generated by the vectors of a basis (a nonzero ideal contains
    a nonzero vector, and -- the algebra being weight-graded -- a weight vector;
    here we test all basis vectors, which are weight vectors)."""
    n = alg.n
    for i in range(n):
        span = []
        span_add(span, unit(n, i))
        frontier = [unit(n, i)]
        while frontier:
            new = []
            for u in frontier:
                for j in range(n):
                    b = alg.bracket(unit(n, j), u)
                    if any(b) and span_add(span, b):
                        new.append(b)
            frontier = new
        if len(span) < n:
            return False, i, len(span)
    return True, None, n


