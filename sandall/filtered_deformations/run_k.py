#!/usr/bin/env python3
"""H^2(g;g), H^2(g_-;g) and (H^2(g_-;g))^{g_0} for g = k^(1)(3;1) and for
fr(3;1), both over F_3."""
from k3 import (P, MONS, IDX, build_k3, LieAlg, degK, wpq, rref, rank, nullspace)
from coh import Complex, invariants


def monomial_subalgebra(k, keep):
    pos = {m: i for i, m in enumerate(keep)}

    def brk(i, j):
        out = {}
        for gi, c in k.c[IDX[keep[i]]][IDX[keep[j]]].items():
            m = MONS[gi]
            if m not in pos:
                raise ValueError(f"not closed: {m}")
            out[pos[m]] = c
        return out

    names = [k.names[IDX[m]] for m in keep]
    wt = [(degK(m), wpq(m)) for m in keep]
    return LieAlg(list(keep), brk, wt, names)


def span_subalgebra(k, rows):
    """LieAlg on the span of rref rows of k (rows must be weight vectors)."""
    piv = [next(i for i, x in enumerate(r) if x) for r in rows]

    def coords(v):
        v = v[:]
        out = [0] * len(rows)
        for i, pc in enumerate(piv):
            if v[pc]:
                co = v[pc]
                out[i] = co
                v = [(a - co * b) % P for a, b in zip(v, rows[i])]
        assert not any(v), "not closed"
        return out

    def brk(i, j):
        return {a: c for a, c in enumerate(coords(k.bracket(rows[i], rows[j]))) if c}

    wt, names = [], []
    for r in rows:
        ws = {k.wt[i] for i, x in enumerate(r) if x}
        assert len(ws) == 1
        wt.append(ws.pop())
        names.append(" + ".join(("" if x == 1 else str(x)) + k.names[i]
                                for i, x in enumerate(r) if x))
    a = LieAlg(list(range(len(rows))), brk, wt, names)
    a.rows = rows
    return a


def gname(cx, i):
    return cx.g.names[cx.h[i]]


def show(cx, vec, src):
    terms = []
    for co, (S, m) in zip(vec, src):
        if co:
            hats = "\\wedge".join("\\widehat{%s}" % gname(cx, i) for i in S)
            c = "" if co == 1 else f"{co}"
            terms.append(f"{c}{cx.g.names[m]}\\otimes {hats}")
    return " + ".join(terms) if terms else "0"


def analyse(g, name):
    deg = [w[0] for w in g.wt]
    gm = [i for i in range(g.n) if deg[i] < 0]
    g0 = [i for i in range(g.n) if deg[i] == 0]
    print(f"\n################ {name}: dim {g.n} ################")
    print("  graded dims:", {d: deg.count(d) for d in sorted(set(deg))})
    print("  g_- =", [g.names[i] for i in gm])
    print("  g_0 =", [g.names[i] for i in g0])
    cx = Complex(g, gm)
    H = cx.cohomology(2)
    tot = sum(d for d, *_ in H.values())
    print(f"\n  --- H^2(g_-;g), total dim {tot} ---")
    for w, (d, src, reps, B) in sorted(H.items()):
        print(f"   (deg;pq) = {w}: dim {d}")
        for r in reps:
            print("      ", show(cx, r, src))
    inv, Z, B = invariants(cx, H, g0)
    print(f"\n  --- (H^2(g_-;g))^(g_0): dim {len(inv)} ---")
    for v in inv:
        print("      ", show(cx, v, cx.cochains(2)))
    return cx, H, inv


k27 = build_k3()
keep = [m for m in MONS if m != (2, 2, 2)]
g = monomial_subalgebra(k27, keep)
gm = [i for i, m in enumerate(keep) if degK(m) < 0]
g0 = [i for i, m in enumerate(keep) if degK(m) == 0]

if __name__ == "__main__":
    analyse(g, "g = k^(1)(3;1)")

    # ---------------------------------------------------------------- H^2(g;g)
    print("\n  --- H^2(g;g) ---")
    cx = Complex(g, list(range(g.n)))
    H2 = cx.cohomology(2)
    for w, (d, src, reps, B) in sorted(H2.items()):
        print(f"   (deg;pq) = {w}: dim {d}")
    print("   total dim H^2(g;g) =", sum(d for d, *_ in H2.values()))

    # ------------------------------------------------------------- fr(3;1)
    # the partial prolong (k_{<=0}, Span(tp - p^(2)q, tq + pq^(2)))_{*,1}
    def vec(d):
        v = [0] * g.n
        for m, c in d.items():
            v[keep.index(m)] = c % P
        return v

    gens = [vec({m: 1}) for m in keep if degK(m) <= 0]
    gens += [vec({(1, 1, 0): 1, (0, 2, 1): -1}),      # tp - p^(2)q
             vec({(1, 0, 1): 1, (0, 1, 2): 1})]       # tq + pq^(2)
    span = rref(gens, g.n)[0]
    while True:
        new = [r[:] for r in span]
        grew = False
        for a in span:
            for b in span:
                br = g.bracket(a, b)
                if any(br):
                    cand = rref(new + [br], g.n)[0]
                    if len(cand) > len(new):
                        new, grew = cand, True
        span = new
        if not grew:
            break
    print(f"\n  fr(3;1) = subalgebra generated by k_(<=0) and the two vectors:"
          f" dim {len(span)}")
    fr = span_subalgebra(g, span)
    print("   Jacobi:", fr.check_jacobi()[0])
    analyse(fr, "fr(3;1)")
