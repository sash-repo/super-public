#!/usr/bin/env python3
"""The g_0-module structure of H^2(g_-;g) for k^(1)(3;1) and fr(3;1):
the submodule generated by each weight vector."""
from itertools import product
from k3 import P, rref, nullspace, degK
from coh import Complex, act, invariants
from run_k import g, keep, analyse
from fr3 import build_fr


def structure(alg, label):
    deg = [w[0] for w in alg.wt]
    gm = [i for i in range(alg.n) if deg[i] < 0]
    g0 = [i for i in range(alg.n) if deg[i] == 0]
    cx = Complex(alg, gm)
    H = cx.cohomology(2)
    src = cx.cochains(2)
    pos = {c: i for i, c in enumerate(src)}
    N = len(src)

    def embed(vec, s):
        o = [0] * N
        for co, c in zip(vec, s):
            o[pos[c]] = co
        return o

    Z, W = [], []
    for w, (d, s, reps, B) in sorted(H.items()):
        for r in reps:
            Z.append(embed(r, s))
            W.append(w)
    # coboundaries
    d1 = cx.diff(1)
    Ball = []
    for s0, col in d1.items():
        r = [0] * N
        for tgt, c in col.items():
            r[pos[tgt]] = c
        if any(r):
            Ball.append(r)
    Bred = rref(Ball, N)[0]
    piv = [next(i for i, x in enumerate(r) if x) for r in Bred]

    def modB(v):
        v = v[:]
        for i, pc in enumerate(piv):
            if v[pc]:
                f = v[pc]
                v = [(a - f * b) % P for a, b in zip(v, Bred[i])]
        return v

    # express a cocycle in terms of the classes Z modulo B
    basis = [r[:] for r in Bred]
    coords_of = {}
    full = [r[:] for r in Bred]
    for z in Z:
        full = rref(full + [z], N)[0]

    def coords(v):
        """coordinates of [v] in the basis [Z] of H^2 (v must be a cocycle)."""
        M = [[z[c] for z in Z] + [b[c] for b in Bred] for c in range(N)]
        rhs = [v[c] for c in range(N)]
        # solve M x = rhs
        aug = [M[c] + [rhs[c]] for c in range(N)]
        red, pv = rref(aug, len(Z) + len(Bred) + 1)
        if (len(Z) + len(Bred)) in pv:
            return None
        sol = [0] * (len(Z) + len(Bred))
        for i, pc in enumerate(pv):
            sol[pc] = red[i][-1]
        return sol[:len(Z)]

    print(f"\n### {label}: dim H^2(g_-;g) = {len(Z)}; weights {W}")
    # action matrices
    for r in sorted({w[0] for w in W}):
        idx = [i for i, w in enumerate(W) if w[0] == r]
        if len(idx) < 2:
            continue
        print(f"  degree {r}: {len(idx)} classes of pq-weights "
              f"{[W[i][1] for i in idx]}")
        for i in idx:
            # submodule generated by the class of Z[i]
            gen = [[1 if k == i else 0 for k in range(len(Z))]]
            frontier = [Z[i]]
            span = [gen[0][:]]
            span = rref(span, len(Z))[0]
            while frontier:
                new = []
                for u in frontier:
                    for x in g0:
                        im = act(cx, x, u, 2)
                        c = coords(im)
                        if c is None:
                            print("      (image not a cocycle -- bug)")
                            continue
                        if any(c) and len(rref(span + [c], len(Z))[0]) > len(span):
                            span = rref(span + [c], len(Z))[0]
                            new.append(im)
                frontier = new
            print(f"      submodule generated by the class of pq-weight "
                  f"{W[i][1]}: dim {len(span)}")


structure(g, "k^(1)(3;1)")
structure(build_fr(), "fr(3;1)")
