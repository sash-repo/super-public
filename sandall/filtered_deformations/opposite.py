#!/usr/bin/env python3
"""The "opposite" gradings h_i := g_{-i} of the Weisfeiler graded algebras, N = 1, F_3.

Which structures do the algebras g = (+) h_i preserve? (Subsection "The opposite
gradings" of the text.)

For each algebra g with its Weisfeiler grading g = (+) g_i we compute, for the opposite
grading (h_- = g_{>0}, h_0 = g_0):

 (a) the subalgebra of h_- generated by h_{-1} = g_1, degree by degree, and the depth;
 (b) transitivity: the x in g_{<=0} with [x, g_1] = 0, and with [x, g_{>0}] = 0;
 (c) the Tanaka (formal, untruncated) prolong of (h_-, h_0), degree by degree, the
     embedding of h_{>0} = g_{<0} in it, and der_0(h_-) against the image of g_0;
 and, for calibration, the same for the ORIGINAL grading (g_-, g_0).

Everything is split by the torus weight (an honest Z^r-grading of g), and every linear
system is solved over F_3 by ../../lib/exactlin.py (FLINT if installed).
"""
import sys
import time
import os, sys; _HERE = os.path.dirname(os.path.abspath(__file__)); sys.path[:0] = [os.path.join(_HERE, "..", "..", "lib"), _HERE]
from exactlin import nullspace as xnull, rank as xrank, backend

P = 3
KMAX = 14
import os
FULL0 = os.environ.get('FULL0') == '1'   # h_0 := all of der_0(h_-) instead of g_0


class Alg:
    def __init__(self, name, n, c, deg, wt):
        self.name, self.n, self.c, self.deg, self.wt = name, n, c, deg, wt

    def br(self, i, j):
        return self.c[i][j]


def from_lie(name, L, degfun=None):
    deg = [degfun(w) if degfun else w[0] for w in L.wt]
    return Alg(name, L.n, L.c, deg, [tuple(w) for w in L.wt])


def nullsp(rows, ncols):
    rows = [r for r in rows if any(r)]
    if ncols == 0:
        return []
    if not rows:                                   # no equation: everything is free
        return [[1 if a == b else 0 for a in range(ncols)] for b in range(ncols)]
    return [[int(x) % P for x in v] for v in xnull(rows, P)]


def rk(rows, ncols):
    rows = [r for r in rows if any(r)]
    return xrank(rows, P) if rows and ncols else 0


def vadd(d, k, v):
    v %= P
    if v:
        d[k] = (d.get(k, 0) + v) % P
        if not d[k]:
            del d[k]


def wadd(a, b, s=1):
    return tuple(x + s * y for x, y in zip(a, b))


# ------------------------------------------------------------------ (a), (b)
def generation(g, sign):
    """sign=+1: the part g_{>0} and its generation by g_1; sign=-1: g_{<0} by g_{-1}."""
    pos = [i for i in range(g.n) if sign * g.deg[i] > 0]
    one = [i for i in pos if sign * g.deg[i] == 1]
    depth = max(sign * g.deg[i] for i in pos)
    bydeg = {d: [i for i in pos if sign * g.deg[i] == d] for d in range(1, depth + 1)}
    # generated piece in each degree: span of brackets [g_1, gen_{d-1}]
    gen = {1: [[1 if j == i else 0 for j in range(g.n)] for i in one]}
    for d in range(2, depth + 1):
        vecs = []
        for x in one:
            for v in gen[d - 1]:
                out = {}
                for j, co in enumerate(v):
                    if co:
                        for k, cc in g.br(x, j).items():
                            vadd(out, k, co * cc)
                row = [0] * g.n
                for k, cc in out.items():
                    row[k] = cc
                vecs.append(row)
        r = rk(vecs, g.n)
        # keep a basis
        from exactlin import rref
        red, piv = rref([v for v in vecs if any(v)], P) if any(any(v) for v in vecs) else ([], [])
        gen[d] = [[int(x) % P for x in v] for v in red[:len(piv)]]
    return {d: (len(bydeg[d]), len(gen[d])) for d in range(1, depth + 1)}, depth


def centralizer(g, sign):
    """x in g_{sign*deg <= 0} commuting with g_{sign*1}, resp. with all of g_{sign*deg>0}."""
    res = {}
    for which in ("one", "all"):
        tgt = [i for i in range(g.n) if sign * g.deg[i] > 0 and (which == "all" or sign * g.deg[i] == 1)]
        out = {}
        for d in sorted({g.deg[i] for i in range(g.n) if sign * g.deg[i] <= 0}):
            src = [i for i in range(g.n) if g.deg[i] == d]
            rows = []
            for y in tgt:
                for k in range(g.n):
                    rows.append([g.br(x, y).get(k, 0) for x in src])
            ker = nullsp(rows, len(src))
            if ker:
                out[d] = len(ker)
        res[which] = out
    return res


# ---------------------------------------------------------------------- (c)
def prolong(g, sign, log):
    """Tanaka prolong of (m, m_0) where m = g_{sign*deg>0} regraded negatively
    (sign=+1: the opposite grading, m = g_{>0}; sign=-1: the original, m = g_{<0})."""
    hd = [-sign * g.deg[i] for i in range(g.n)]          # degree in the grading at hand
    M = [i for i in range(g.n) if hd[i] < 0]
    Mset = set(M)
    # H: global basis of the prolong. entries: dict(deg, wt, g=index | act={a: {H: c}})
    H = []
    gH = {}
    for i in M:
        gH[i] = len(H)
        H.append({"deg": hd[i], "wt": g.wt[i], "g": i})
    byDW = {}
    for t, e in enumerate(H):
        byDW.setdefault((e["deg"], e["wt"]), []).append(t)

    def act(t, b):
        """[H_t, b] for b in M, as dict over H."""
        e = H[t]
        if "g" in e:
            out = {}
            for k, c in g.br(e["g"], b).items():
                vadd(out, gH[k], c)       # [m, m] lands in m
            return out
        return e["act"].get(b, {})

    actcache = {}

    def actc(t, b):
        key = (t, b)
        if key not in actcache:
            actcache[key] = act(t, b)
        return actcache[key]

    def solve_block(k, w):
        """all phi: M -> H of degree k, weight w, that are derivations."""
        unk = []                               # (a, t)
        T = {}
        for a in M:
            ts = byDW.get((k + hd[a], wadd(g.wt[a], w)), [])
            T[a] = ts
            for t in ts:
                unk.append((a, t))
        if not unk:
            return [], unk
        col = {u: j for j, u in enumerate(unk)}
        active = [a for a in M if T[a]]
        rows = []
        # pairs (a,b): at least one of phi(a), phi(b), phi([a,b]) must involve unknowns
        for ia, a in enumerate(M):
            for b in M[ia + 1:]:
                ab = g.br(a, b)
                if not T[a] and not T[b] and not any(T[e] for e in ab):
                    continue
                eq = {}                      # outcoord -> {col: coef}
                for e, c in ab.items():
                    for t in T[e]:
                        eq.setdefault(t, {})
                        vadd(eq[t], col[(e, t)], c)
                for t in T[a]:
                    for o, c in actc(t, b).items():
                        eq.setdefault(o, {})
                        vadd(eq[o], col[(a, t)], -c)
                for t in T[b]:
                    for o, c in actc(t, a).items():
                        eq.setdefault(o, {})
                        vadd(eq[o], col[(b, t)], c)
                for o, d in eq.items():
                    if d:
                        r = [0] * len(unk)
                        for j, c in d.items():
                            r[j] = c
                        rows.append(r)
        return nullsp(rows, len(unk)), unk

    def weights_of_degree(k):
        ws = set()
        for a in M:
            for (d, wy) in byDW:
                if d == k + hd[a]:
                    ws.add(wadd(wy, g.wt[a], -1))
        return ws

    def phi_of_g(x, k):
        """ad x restricted to M, x in g of degree k (>= 0), as dict a -> {H: c};
        needs the coordinates gcoord of lower-degree g-elements in H."""
        out = {}
        for a in M:
            d = {}
            for kk, c in g.br(x, a).items():
                for t, cc in gcoord[kk].items():
                    vadd(d, t, c * cc)
            if d:
                out[a] = d
        return out

    gcoord = {i: {gH[i]: 1} for i in M}
    results = {}
    zeros = 0
    depth = -min(hd[i] for i in M)
    for k in range(0, KMAX + 1):
        t0 = time.time()
        ws = weights_of_degree(k)
        gk = [i for i in range(g.n) if hd[i] == k]
        new = []
        ncoords_ok = True
        kernel_g = 0
        for w in sorted(ws):
            sol, unk = solve_block(k, w)
            if not sol:
                sol = []
            gx = [i for i in gk if g.wt[i] == w]
            if k == 0:
                full = len(sol)                    # der_0(m) in this weight
                # h_0 := image of g_0 only (not all of der_0)
                imgs = []
                for x in gx:
                    ph = phi_of_g(x, 0)
                    v = [0] * len(unk)
                    for j, (a, t) in enumerate(unk):
                        v[j] = ph.get(a, {}).get(t, 0)
                    imgs.append(v)
                from exactlin import rref
                nz = [v for v in imgs if any(v)]
                if nz:
                    rr, pv = rref(nz, P)
                    basis = [[int(x) % P for x in r] for r in rr[:len(pv)]]
                else:
                    basis = []
                kernel_g += len(gx) - len(basis)
                results.setdefault("der0", 0)
                results["der0"] += full
                if not FULL0:
                    sol = basis
            else:
                # express ad(g_{-k}) (resp. g_k) in the basis sol
                for x in gx:
                    ph = phi_of_g(x, k)
                    v = [0] * len(unk)
                    for j, (a, t) in enumerate(unk):
                        v[j] = ph.get(a, {}).get(t, 0)
                    if not any(v):
                        kernel_g += 1
                    elif rk(sol + [v], len(unk)) != rk(sol, len(unk)):
                        ncoords_ok = False
            start = len(H)
            for s in sol:
                actd = {}
                for co, (a, t) in zip(s, unk):
                    if co:
                        actd.setdefault(a, {})
                        vadd(actd[a], t, co)
                H.append({"deg": k, "wt": w, "act": actd})
                new.append(len(H) - 1)
            if sol:
                byDW[(k, w)] = list(range(start, len(H)))
            # coordinates of the g-elements of this degree/weight in H
            for x in gx:
                ph = phi_of_g(x, k)
                v = [0] * len(unk)
                for j, (a, t) in enumerate(unk):
                    v[j] = ph.get(a, {}).get(t, 0)
                if not sol or not any(v):
                    gcoord[x] = {}
                    continue
                # solve sum c_s sol_s = v
                ns = len(sol)
                A = [[sol[s][j] for s in range(ns)] + [(-v[j]) % P] for j in range(len(unk))]
                z = nullsp(A, ns + 1)
                c = None
                for vec in z:
                    if vec[-1]:
                        inv = pow(vec[-1], P - 2, P)
                        c = [x_ * inv % P for x_ in vec[:-1]]
                        break
                if c is None:
                    gcoord[x] = {}
                    ncoords_ok = False
                    continue
                gcoord[x] = {start + s: c[s] for s in range(ns) if c[s]}
        results[k] = (len(new), len(gk), kernel_g, ncoords_ok)
        log(f"    prolong degree {k:2d}: dim {len(new):4d}   dim g in it {len(gk):3d}"
            f"   killed {kernel_g}   embedded {ncoords_ok}   ({time.time()-t0:.1f}s)")
        if k > 0 and not new:
            zeros += 1
            if zeros >= depth:
                break
        else:
            zeros = 0
    return results


