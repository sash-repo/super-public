def build_psl3(grading):
    """psl(3) over F_3: basis E_ij (i != j), H1 = E11 - E22 (H2 = H1 mod the center)."""
    import itertools
    roots = {(0, 1): (1, 0), (1, 2): (0, 1), (0, 2): (1, 1)}
    basis = []
    for (i, j), r in roots.items():
        basis.append(("E", i, j, r))
        basis.append(("E", j, i, (-r[0], -r[1])))
    basis.append(("H", None, None, (0, 0)))
    n = len(basis)

    def mat(b):
        m = [[0] * 3 for _ in range(3)]
        if b[0] == "E":
            m[b[1]][b[2]] = 1
        else:
            m[0][0], m[1][1] = 1, -1
        return m

    def coords(m):
        out = {}
        for t, b in enumerate(basis):
            if b[0] == "E":
                vadd(out, t, m[b[1]][b[2]])
        a = (m[0][0] - m[2][2]) % P       # diag mod the center = a*H1
        vadd(out, n - 1, a)
        return out

    def mm(a, b):
        return [[sum(a[i][k] * b[k][j] for k in range(3)) % P for j in range(3)] for i in range(3)]

    c = [[None] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            A, B = mat(basis[i]), mat(basis[j])
            x, y = mm(A, B), mm(B, A)
            c[i][j] = coords([[(x[r][s] - y[r][s]) % P for s in range(3)] for r in range(3)])
    wt = [b[3] for b in basis]
    deg = [grading[0] * w[0] + grading[1] * w[1] for w in wt]
    return Alg(f"psl(3) grading {grading}", n, c, deg, wt)


def build_pgl3(grading):
    """pgl(3) = gl(3)/scalars over F_3: basis E_ij (i != j), D1 = E11, D2 = E22 (mod I)."""
    roots = {(0, 1): (1, 0), (1, 2): (0, 1), (0, 2): (1, 1)}
    basis = []
    for (i, j), r in roots.items():
        basis.append(("E", i, j, r))
        basis.append(("E", j, i, (-r[0], -r[1])))
    basis.append(("D", 0, 0, (0, 0)))
    basis.append(("D", 1, 1, (0, 0)))
    n = len(basis)

    def mat(b):
        m = [[0] * 3 for _ in range(3)]
        m[b[1]][b[2]] = 1
        return m

    def coords(m):
        out = {}
        for t, b in enumerate(basis):
            if b[0] == "E":
                vadd(out, t, m[b[1]][b[2]])
        vadd(out, n - 2, m[0][0] - m[2][2])
        vadd(out, n - 1, m[1][1] - m[2][2])
        return out

    def mm(a, b):
        return [[sum(a[i][k] * b[k][j] for k in range(3)) % P for j in range(3)] for i in range(3)]

    c = [[None] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            A, B = mat(basis[i]), mat(basis[j])
            x, y = mm(A, B), mm(B, A)
            c[i][j] = coords([[(x[r][s] - y[r][s]) % P for s in range(3)] for r in range(3)])
    wt = [b[3] for b in basis]
    deg = [grading[0] * w[0] + grading[1] * w[1] for w in wt]
    return Alg(f"pgl(3) grading {grading}", n, c, deg, wt)


def build_all():
    from k3 import build_k3
    from run_k import g as k1
    from fr3 import build_fr
    from vect3 import build_vect, build_svect, subalg_from_rows
    from k3 import derived, rref as krref
    algs = []
    algs.append(build_psl3((1, 1)))
    algs.append(build_psl3((1, 0)))
    algs.append(build_pgl3((1, 1)))
    algs.append(build_pgl3((1, 0)))
    algs.append(from_lie("k^(1)(3;1)", k1))
    algs.append(from_lie("fr(3;1)", build_fr()))
    vect, ker = build_svect()
    algs.append(from_lie("vect(3;1)", vect, degfun=sum))
    sv = subalg_from_rows(vect, ker)
    algs.append(from_lie("svect(3;1)", sv, degfun=sum))
    d1 = krref(derived(sv), sv.n)[0]
    sv1 = subalg_from_rows(sv, d1)
    algs.append(from_lie("svect^(1)(3;1)", sv1, degfun=sum))
    return algs


def main():
    logf = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "opposite.log"), "a" if sys.argv[1:] else "w")

    def log(s):
        print(s, flush=True)
        logf.write(s + "\n")
        logf.flush()

    log(f"opposite.py  backend={backend()}  p={P}  KMAX={KMAX}  FULL0={FULL0}")
    only = sys.argv[1:]
    for g in build_all():
        if only and not any(o in g.name for o in only):
            continue
        dims = {}
        for i in range(g.n):
            dims[g.deg[i]] = dims.get(g.deg[i], 0) + 1
        log(f"\n######## {g.name}: dim {g.n}, graded dims {dict(sorted(dims.items()))}")
        for sign, lab in ((-1, "ORIGINAL (g_-, g_0)"), (1, "OPPOSITE (h_- = g_{>0}, h_0 = g_0)")):
            log(f"  --- {lab}")
            gen, depth = generation(g, sign)
            log(f"    depth {depth};  (dim piece, dim generated by the degree-1 piece) by |degree|: {gen}")
            ce = centralizer(g, sign)
            log(f"    x in the non-negative part killing the degree -1 piece: {ce['one'] or 'none'}")
            log(f"    x in the non-negative part killing the whole negative part: {ce['all'] or 'none'}")
            r = prolong(g, sign, log)
            log(f"    dim der_0(negative part) = {r['der0']}  vs dim g_0 = {dims.get(0, 0)}")
    logf.close()


if __name__ == "__main__":
    main()
