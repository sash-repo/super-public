#!/usr/bin/env python3
r"""
fvle.py --- all the W-gradings of the desuperized exceptional algebra

        F(vle(4|3; 1)) = vle(7; 1)' subset vect(7; 1)        (dim 94)

i.e., the two rows F vle of table (grVexF) of the text, by the method of irw.py:
a W-grading of a vectorial algebra is a regrading of the indeterminates, so
one runs over degree vectors d in Z^7 and tests the Weisfeiler conditions.

The algebra is built by the F_2 prolong engine
(vle7.py: the prolong of g_{-1} = Pi(O(3;1)/K1), g_0 = c(vect(3;1)), and its
ideal generated by g_{-1}, 94-dimensional, simple).  The vector fields are
converted to the bit-vector format of ir.py with NVAR = 7, and the Weisfeiler
test is irw.w_test verbatim.

The set of degree vectors d grading the algebra is a LATTICE (the cocharacters
of the diagonal torus normalizing it); Step 1 finds it in a box and checks
that it is a lattice, Step 2 runs the W-test over the lattice points of a box.

Usage:  python3 fvle.py [--box B]
"""
import os as _os_runs; _os_runs.makedirs('runs', exist_ok=True)  # logs go to ./runs
import itertools
import sys
from math import gcd


import ir                     # noqa: E402
import irw                    # noqa: E402

NV = 7
ir.NVAR = NV
irw.NVAR = NV

from irw import graded_pieces, normalize, w_test, growth, is_contact, signature  # noqa: E402
from ir import echelon, bracket, compose_square, in_span, burnside_irreducible   # noqa: E402
from irw import span_br   # noqa: E402
from absirr import abs_irreducible   # noqa: E402


def cyclic_ok(g0, gm1):
    """cheap necessary condition for irreducibility: every basis vector of
    g_{-1} generates the whole of g_{-1} as a g_0-module"""
    n = len(gm1)
    for u in gm1:
        sub = echelon([u])
        front = [u]
        while front:
            new = []
            for a in g0:
                for v in front:
                    w = bracket(a, v)
                    if w and not in_span(w, sub):
                        sub = echelon([b for _, b in sub] + [w])
                        new.append(w)
            front = new
        if len(sub) < n:
            return False
    return True


def module_mats(g0, gm1):
    rec = []
    for j, u in enumerate(gm1):
        v, cm = u, 1 << j
        for p, b, c in rec:
            if v >> p & 1:
                v ^= b
                cm ^= c
        rec.append((v.bit_length() - 1, v, cm))
        rec.sort(key=lambda t: -t[0])

    def coords(v):
        cm = 0
        for p, b, c in rec:
            if v >> p & 1:
                v ^= b
                cm ^= c
        return None if v else cm
    mats = []
    for g in g0:
        m = [coords(bracket(g, u)) for u in gm1]
        if any(x is None for x in m):
            return None
        mats.append(m)
    return mats


XCHECK = {'agree': 0, 'fallback': 0}


def wtest(pieces):
    """irw.w_test, with the Burnside step replaced by Norton's test + the
    commutant (absirr.py) and cross-checked against Burnside for n <= 12"""
    degs = sorted(pieces)
    if degs[0] >= 0 or not pieces.get(-1) or not pieces.get(0):
        return False, 'no g_-1 or g_0'
    gm1, g0 = pieces[-1], pieces[0]
    if not cyclic_ok(g0, gm1):
        return False, 'g_{-1} reducible'
    cur = gm1
    for c in range(-2, degs[0] - 1, -1):
        cur = span_br(cur, gm1)
        want = pieces.get(c, [])
        if len(cur) != len(want):
            return False, 'g_- not generated by g_{-1}'
    for c in degs:
        if c < 0:
            continue
        for v in pieces[c]:
            if all(bracket(v, w) == 0 for w in gm1):
                return False, 'not transitive'
    mats = module_mats(g0, gm1)
    if mats is None:
        return False, 'g_0 does not preserve g_{-1}'
    n = len(gm1)
    r = abs_irreducible(mats, n)
    if r is None or n <= 12:
        b, _ = burnside_irreducible(g0, gm1)
        if r is None:
            XCHECK['fallback'] += 1
            r = b
        else:
            assert r == b, 'Norton/commutant disagrees with Burnside'
            XCHECK['agree'] += 1
    if not r:
        return False, 'g_{-1} not absolutely irreducible'
    return True, 'W'


LOG = open("runs/fvle.log", "a")


def say(*a):
    s = ' '.join(str(x) for x in a)
    print(s, flush=True)
    LOG.write(s + '\n')
    LOG.flush()


def build():
    import vle7
    from f2vf import Space, find_weights
    from prolong import prolong, generators, ad_closure
    sp, neg, g0 = vle7.build()
    W = find_weights(sp, neg + g0)
    sp = Space([1] * NV, [1] * NV, vle7.par, W)
    _, neg, g0 = vle7.build()
    G = prolong(sp, neg, g0, verbose=False)
    gens = generators(G)
    J = ad_closure(sp, gens, G.basis(-1))
    out = []
    for X in J.basis():
        v = 0
        for k in X:
            A, i = k >> 5, k & 31
            v ^= 1 << (A * NV + i)
        out.append(v)
    return out


def main():
    B = 3
    if '--box' in sys.argv:
        B = int(sys.argv[sys.argv.index('--box') + 1])
    basis = build()
    say('F vle: dim', len(basis), ', rank', len(echelon(basis)))
    # sanity: closed under the bracket, and the squares of the standard grading
    eb = echelon(basis)
    assert all(in_span(bracket(a, b), eb) for a in basis for b in basis)
    say('closed under the bracket: yes')
    tms = [irw.terms(v) for v in basis]
    # Step 1: the grading lattice
    good = []
    for d in itertools.product(range(-B, B + 1), repeat=NV):
        if graded_pieces(basis, tms, d) is not None:
            good.append(d)
    say('box', B, ': degree vectors grading F vle:', len(good))
    # Hermite basis of the span over Z (small: do it by sympy)
    from sympy import Matrix
    M = Matrix(good)
    H = M.T.rref()[0] if False else None
    rk = M.rank()
    say('rank of the grading lattice:', rk)
    # lattice closure test: sums/differences of good vectors stay good
    gs = set(good)
    bad = 0
    for a in good[:200]:
        for b in good[:200]:
            c = tuple(x + y for x, y in zip(a, b))
            if max(abs(x) for x in c) <= B and c not in gs:
                bad += 1
    say('lattice closure violations (sample):', bad)
    # Step 2: W-test
    found = {}
    nonw = {}
    for d in good:
        if all(x == 0 for x in d):
            continue
        g = 0
        for x in d:
            g = gcd(g, abs(x))
        if g != 1:
            continue
        pieces = normalize(graded_pieces(basis, tms, d))
        ok, msg = wtest(pieces)
        if not ok:
            nonw[msg.split(' (')[0]] = nonw.get(msg.split(' (')[0], 0) + 1
            continue
        sig = signature(pieces)
        if sig not in found:
            dims = tuple((c, len(pieces[c])) for c in sorted(pieces))
            found[sig] = (d, dims, growth(pieces), is_contact(pieces))
    say('non-W reasons:', nonw)
    say('Norton/commutant vs Burnside:', XCHECK)
    say('distinct W-gradings:', len(found))
    for sig, (d, dims, gv, ct) in sorted(found.items(), key=lambda t: t[1][2]):
        cod = sum(n for c, n in dims if c < 0)
        say('  d =', d, ' dims', dims, ' growth', gv, 'C' if ct else '', ' codim', cod)


if __name__ == '__main__':
    main()
