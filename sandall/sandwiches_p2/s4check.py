import itertools, os
os.environ.setdefault('KAS_NT','2')
import kas2 as K, kastau as TAU
NVAR, XI, ETA, T = K.NVAR, K.XI, K.ETA, K.T
MONS, IDX, DIMO = K.MONS, K.IDX, K.DIMO

comp = K.build_kas(); kas = K.echelon([v for j in sorted(comp) for v in comp[j]])
pv = K.pivots(kas)

def perm_table(p):
    tab=[]
    for m in MONS:
        e=[0]*NVAR; e[T]=m[T]
        for i in range(3):
            e[XI[p[i]]]=m[XI[i]]; e[ETA[p[i]]]=m[ETA[i]]
        tab.append(1<<IDX[tuple(e)])
    return tab

def compose(t1,t2):   # t1 after t2
    return tuple(TAU.apply_tab(t1,t2[k]) for k in range(DIMO))

gens=[]
for p in [(1,0,2),(1,2,0)]:
    t=perm_table(p)
    ok_br = all(TAU.apply_tab(t,K.kb(1<<i,1<<j))==K.kb(t[i],t[j]) for i in range(DIMO) for j in range(DIMO))
    ok_kas = all(K.in_span(TAU.apply_tab(t,v),pv) for v in kas)
    print('permutation %s: bracket %s, preserves kas %s' % (p, ok_br, ok_kas))
    gens.append(tuple(t))
gens.append(tuple(TAU.tau_table({0,2})))
gens.append(tuple(TAU.tau_table({0,1})))

G={tuple(1<<i for i in range(DIMO))}
frontier=list(G)
while frontier:
    new=[]
    for a in frontier:
        for g in gens:
            c=compose(g,a)
            if c not in G:
                G.add(c); new.append(c)
    frontier=new
print('order of the group generated by S_3 and the even tau_S: %d' % len(G))
print('all of it preserves kas: %s' % all(all(K.in_span(TAU.apply_tab(list(t),v),pv) for v in kas) for t in G))
