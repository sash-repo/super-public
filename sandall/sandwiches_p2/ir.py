# ------------------------------------------------------------------ (2) prolongs

def component(deg):
    return [1 << i for i in range(DIMV) if FDEG[i] == deg]


def prolong(g0_basis, maxdeg=14):
    comps = {-2: echelon(GM2), -1: echelon(GM1), 0: echelon(g0_basis)}
    d = 1
    while d <= maxdeg:
        prev = comps[d - 1]
        cand = component(d)
        if not cand:
            comps[d] = []
            break
        piv, sols = [], []
        for c in cand:
            img, src = 0, c
            for w in GM1:
                img = (img << DIMV) | reduce_vec(bracket(c, w), prev)
            for p, i0, s0 in piv:
                if img >> p & 1:
                    img ^= i0
                    src ^= s0
            if img:
                piv.append((img.bit_length() - 1, img, src))
                piv.sort(key=lambda t: -t[0])
            else:
                sols.append(src)
        comps[d] = echelon(sols)
        if not comps[d]:
            break
        d += 1
    return comps


def gdims(comps):
    return {d: len(comps[d]) for d in sorted(comps) if comps[d]}


def flatten(comps):
    return [v for d in sorted(comps) for _, v in comps[d]]


def ideal_generated(seed, elems):
    ideal = echelon([seed])
    changed = True
    while changed:
        changed = False
        for _, v in list(ideal):
            for g in elems:
                b = bracket(g, v)
                if b and not in_span(b, ideal):
                    ideal = echelon([u for _, u in ideal] + [b])
                    changed = True
    return ideal


def minimal_ideal(elems):
    """The smallest nonzero ideal, if the ideals generated by single basis
    vectors have a smallest one; returns (basis, is_unique_minimal)."""
    best = None
    dims = []
    for e in elems:
        idl = ideal_generated(e, elems)
        dims.append(len(idl))
        if best is None or len(idl) < len(best):
            best = idl
    # is it contained in every ideal generated by a single element?
    uniq = all(all(in_span(v, ideal_generated(e, elems)) for _, v in best)
               for e in elems)
    return best, uniq, dims


def is_simple(elems):
    n = len(echelon(elems))
    for e in elems:
        if len(ideal_generated(e, elems)) != n:
            return False
    return True


# ---------------------------------------------------------------- (3) Weisfeiler

def burnside_irreducible(g0, module):
    n = len(module)
    rec = []
    for j, u in enumerate(module):
        v, cm = u, 1 << j
        for p, b, c in rec:
            if v >> p & 1:
                v ^= b
                cm ^= c
        if v:
            rec.append((v.bit_length() - 1, v, cm))
            rec.sort(key=lambda t: -t[0])

    def coords(v):
        cm = 0
        for p, b, c in rec:
            if v >> p & 1:
                v ^= b
                cm ^= c
        return None if v else cm

    mats = []
    for g in g0:
        m = tuple(coords(bracket(g, u)) for u in module)
        if any(x is None for x in m):
            return False, 'module not stable'
        mats.append(m)

    def mul(a, b):
        out = []
        for j in range(n):
            r = 0
            for k in bits(b[j]):
                r ^= a[k]
            out.append(r)
        return tuple(out)

    ident = tuple(1 << j for j in range(n))
    flat = lambda m: sum(m[j] << (j * n) for j in range(n))     # noqa: E731
    alg = echelon([flat(m) for m in [ident] + mats])
    frontier = [ident] + mats
    while frontier:
        newf = []
        for a in frontier:
            for b in mats:
                c = mul(a, b)
                if not in_span(flat(c), alg):
                    alg = echelon([v for _, v in alg] + [flat(c)])
                    newf.append(c)
        frontier = newf
    return len(alg) == n * n, 'the generated associative algebra has dim %d, ' \
        'End has dim %d' % (len(alg), n * n)


# ------------------------------------------------------------- (5) superizations

def parity_of(v, p):
    """parity of a homogeneous vector field, or None if inhomogeneous."""
    par = None
    for i in bits(v):
        mask, j = divmod(i, NVAR)
        q = p[j]
        for b in bits(mask):
            q ^= p[b]
        if par is None:
            par = q
        elif par != q:
            return None
    return par


def split_by_parity(elems, p):
    """(even basis, odd basis) of the span of `elems`, or None if the span is
    not spanned by parity-homogeneous elements."""
    basis = echelon(elems)
    n = len(basis)
    ev = [v for _, v in basis if parity_of(v, p) == 0]
    od = [v for _, v in basis if parity_of(v, p) == 1]
    # a subspace is homogeneous iff its homogeneous vectors span it; the
    # echelon basis of a homogeneous subspace need not be homogeneous, so
    # project properly: intersect with the even and the odd part of vect
    if len(ev) + len(od) == n:
        return ev, od
    evs, ods = [], []
    for _, v in basis:
        pass
    # general case: solve for the homogeneous parts inside the span
    # write each basis vector as ev-part + od-part and intersect
    def part(v, which):
        out = 0
        for i in bits(v):
            mask, j = divmod(i, NVAR)
            q = p[j]
            for b in bits(mask):
                q ^= p[b]
            if q == which:
                out ^= 1 << i
        return out
    # the even part of the span is {v in span : part(v,1) = 0}
    # solve by elimination on (v, part(v,1))
    piv, sols = [], []
    for _, v in basis:
        img, src = part(v, 1), v
        for pp, i0, s0 in piv:
            if img >> pp & 1:
                img ^= i0
                src ^= s0
        if img:
            piv.append((img.bit_length() - 1, img, src))
            piv.sort(key=lambda t: -t[0])
        else:
            sols.append(src)
    evs = echelon(sols)
    piv, sols = [], []
    for _, v in basis:
        img, src = part(v, 0), v
        for pp, i0, s0 in piv:
            if img >> pp & 1:
                img ^= i0
                src ^= s0
        if img:
            piv.append((img.bit_length() - 1, img, src))
            piv.sort(key=lambda t: -t[0])
        else:
            sols.append(src)
    ods = echelon(sols)
    if len(evs) + len(ods) != n:
        return None
    return [v for _, v in evs], [v for _, v in ods]


def superizations(ir_elems, comps_ir):
    out = []
    basis = echelon(ir_elems)
    for p in itertools.product((0, 1), repeat=NVAR):
        sp = split_by_parity(ir_elems, p)
        if sp is None:
            continue
        ev, od = sp
        # the squaring must land inside the even part (p = 2 Lie superalgebra)
        evb = echelon(ev)
        if not all(in_span(compose_square(x), evb) for x in od):
            out.append((p, len(ev), len(od), False))
            continue
        out.append((p, len(ev), len(od), True))
    return out


# ---------------------------------------------------------------- (6) sandwiches

def sandwich_test(s, elems):
    """(san) and (san2) for s in the Lie algebra spanned by elems."""
    img = []
    for g in elems:
        b = bracket(s, g)
        if bracket(s, b):
            return False
        img.append(b)
    for i in range(len(img)):
        for j in range(i, len(img)):
            if bracket(img[i], img[j]):
                return False
    return True


def sandwiches_in(sub, elems, limit=1 << 20):
    n = len(sub)
    if n == 0 or (1 << n) > limit:
        return None
    found = []
    for c in range(1, 1 << n):
        s = 0
        for k in bits(c):
            s ^= sub[k]
        if sandwich_test(s, elems):
            found.append(s)
    return found


def full_sandwich_scan(elems):
    """All sandwiches of the whole algebra, by exhaustive search over F_2 with
    the cheap pre-test s o s = 0 (equivalent to (san) since ir is restricted
    and centreless)."""
    n = len(elems)
    sq = [compose_square(e) for e in elems]
    br = [[bracket(elems[i], elems[j]) for j in range(n)] for i in range(n)]
    found = []
    cur = 0                                  # running s o s
    subset = []
    total = 1 << n
    print('  exhaustive scan over %d elements ...' % (total - 1))
    # Gray-code walk
    prev = 0
    for g in range(1, total):
        gray = g ^ (g >> 1)
        diff = gray ^ prev
        j = diff.bit_length() - 1
        # toggling j: (s + e_j) o (s + e_j) = s o s + e_j o e_j + [s, e_j]
        upd = sq[j]
        for i in subset:
            upd ^= br[i][j]
        cur ^= upd
        if j in subset:
            subset.remove(j)
        else:
            subset.append(j)
        prev = gray
        if cur == 0:
            s = 0
            for k in subset:
                s ^= elems[k]
            if s and sandwich_test(s, elems):
                found.append(s)
    return found


