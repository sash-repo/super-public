import itertools
import sys

NVAR = 9
DIMO = 1 << NVAR
VDEG = [2] + [1] * 8                       # deg x_1 = 2, deg x_i = 1 (i >= 2)


def mdeg(mask):
    return sum(VDEG[i] for i in range(NVAR) if mask >> i & 1)


MDEG = [mdeg(m) for m in range(DIMO)]
DIMV = DIMO * NVAR
FDEG = [MDEG[i // NVAR] - VDEG[i % NVAR] for i in range(DIMV)]


def IDX(mask, j):
    return mask * NVAR + j


def vf(*terms):
    v = 0
    for mask, j in terms:
        v ^= 1 << IDX(mask, j)
    return v


def mon(*vars_):
    m = 0
    for v in vars_:
        m |= 1 << (v - 1)
    return m


def bits(v):
    while v:
        b = v & -v
        yield b.bit_length() - 1
        v ^= b


def bracket(a, b):
    """[a, b] for vector fields over F_2 (char 2: no signs)."""
    out = 0
    tb = list(bits(b))
    ta = list(bits(a))
    for ia in ta:
        ma, ja = divmod(ia, NVAR)
        for ib in tb:
            mb, jb = divmod(ib, NVAR)
            if mb >> ja & 1:
                r = mb ^ (1 << ja)
                if not (ma & r):
                    out ^= 1 << IDX(ma | r, jb)
            if ma >> jb & 1:
                r = ma ^ (1 << jb)
                if not (mb & r):
                    out ^= 1 << IDX(mb | r, ja)
    return out


def compose_square(a):
    """X o X for a vector field X over F_2: a derivation again, char 2."""
    out = 0
    ts = list(bits(a))
    for i1 in ts:
        m1, j1 = divmod(i1, NVAR)
        for i2 in ts:
            m2, j2 = divmod(i2, NVAR)
            # (x^{m1} d_{j1}) applied to x^{m2}, times d_{j2}
            if m2 >> j1 & 1:
                r = m2 ^ (1 << j1)
                if not (m1 & r):
                    out ^= 1 << IDX(m1 | r, j2)
    return out


# ------------------------------------------------------------ linear algebra F_2

def reduce_vec(v, basis):
    for p, b in basis:
        if v >> p & 1:
            v ^= b
    return v


def echelon(vectors):
    basis = []
    for v in vectors:
        v = reduce_vec(v, basis)
        if v:
            basis.append((v.bit_length() - 1, v))
            basis.sort(key=lambda pb: -pb[0])
    return basis


def in_span(v, basis):
    return reduce_vec(v, basis) == 0


def span_dim(vectors):
    return len(echelon(vectors))


