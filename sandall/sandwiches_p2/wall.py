#!/usr/bin/env python3
"""ALL Weisfeiler gradings of the simple Lie algebras over F_2 of dimension 15
and 16 (the library of Cushing--Stagg--Stewart, arXiv:2207.01094), a la the
Distr text: for every maximal subalgebra L_0 of L we produce the Weisfeiler
filtration, the dimensions of the components of the associated graded algebra,
the growth vector of the distribution preserved, and the isomorphism type of
g_0.

Two searches, meeting in the middle:

  * TOP-DOWN, exhaustive.  A subalgebra M of codimension c is the intersection
    of the kernels of a c-dimensional subspace U of L^*, and for every nonzero
    f in U the isotropy bound of Lemma "Lbound" gives
        rank(B_f | ker f) <= 2(c-1),   B_f(x,y) = f([x,y]).
    So U lies inside the set Cand(c) of functionals with that property; we
    enumerate such U by backtracking on "compatible sets" (f is compatible with
    the partial U if f + u is a candidate for every u in U already spanned).
    This is exhaustive for every c for which Cand(c) is small enough.

  * BOTTOM-UP / randomized.  A random greedy walk that always ends in a maximal
    subalgebra: start with a line, and while some coset representative y of the
    current M has <M, y> proper, replace M by <M, y>.  Only 2^codim - 1 cosets
    have to be looked at, so a walk is cheap.  This covers the codimensions the
    top-down search cannot reach.

For each maximal M, the Weisfeiler filtration is
    L_0 = M,  L_{-1} = M + (a minimal M-submodule of L/M),
    L_{-i-1} = L_{-i} + [L_{-1}, L_{-i}],
    L_{i+1} = {x in L_i : [x, L_{-1}] subset L_i}.
Note that a maximal subalgebra can have SEVERAL minimal M-submodules in L/M,
and each of them gives a Weisfeiler filtration of its own; all of them are
listed.
"""

import os
import random
import sys
import time

from css import LieF2, rref, in_span, all_elements, reduce_vec
from maxsub import restrict_rank, kernel
from runall import build


# --------------------------------------------------------------- subalgebras
def closure(L, rows):
    """the subalgebra generated by the subspace `rows`"""
    rows = rref(rows)
    changed = True
    while changed:
        changed = False
        for a in list(rows):
            for b in list(rows):
                w = L.mul(a, b)
                if w and not in_span(w, rows):
                    rows = rref(rows + [w])
                    changed = True
    return rows


def coset_reps(L, M):
    """one representative of every nonzero coset of the subspace M"""
    K = kernel(M, L.n)                      # a complement, as functionals
    # the 2^c - 1 nonzero cosets are represented by the elements of a complement
    comp = []
    for u in range(1, 1 << L.n):
        if not in_span(u, M) and all(not in_span(u ^ v, M) for v in comp):
            comp.append(u)
            if len(comp) == (1 << (L.n - len(M))) - 1:
                break
    return comp


def complement_basis(L, M):
    """a basis of a vector-space complement of M in L"""
    out = []
    rows = list(M)
    for i in range(L.n):
        u = 1 << i
        if not in_span(u, rows):
            rows = rref(rows + [u])
            out.append(u)
    return out


def cosets(L, M):
    """representatives of all 2^c - 1 nonzero cosets of M"""
    B = complement_basis(L, M)
    out = []
    for mask in range(1, 1 << len(B)):
        u = 0
        for i, b in enumerate(B):
            if (mask >> i) & 1:
                u ^= b
        out.append(u)
    return out


def is_maximal(L, M):
    for y in cosets(L, M):
        if len(closure(L, M + [y])) != L.n:
            return False
    return True


# ------------------------------------------------------- exhaustive top-down
def candidates(L, ranks, c):
    return [f for f in range(1, 1 << L.n) if ranks[f] <= 2 * (c - 1)]


def subalgebras_of_codim(L, ranks, c, budget=None, candmax=None):
    """all subalgebras of codimension exactly c (exhaustive), as rref bases.

    Every subspace U is met exactly once: a new basis vector g is admitted only
    if it is the smallest element of its own coset g + span(U), which is the
    canonical choice (and then the basis is automatically increasing).  The
    compatible candidates are carried along as a bitmask over the candidate
    list, so that filtering is one big-integer AND per element of the span
    already built."""
    lst = sorted(candidates(L, ranks, c))
    N = len(lst)
    if candmax and N > candmax:
        raise TimeoutError("%d candidate functionals at c=%d" % (N, c))
    pos = {f: i for i, f in enumerate(lst)}
    S = set(lst)
    # allow[f] = the set of g in the list with g + f in the list and g < g + f
    allow = {}
    for f in lst:
        m = 0
        for i, g in enumerate(lst):
            h = g ^ f
            if h in S and g < h:
                m |= 1 << i
        allow[f] = m
    full = (1 << N) - 1
    out = {}
    nodes = [0]

    def bits(m):
        while m:
            b = m & -m
            yield b.bit_length() - 1
            m ^= b

    def rec(U, span, compat):
        nodes[0] += 1
        if budget and nodes[0] > budget:
            raise TimeoutError("budget exceeded at c=%d" % c)
        if len(U) == c:
            M = kernel(U, L.n)
            if len(M) == L.n - c and L.is_subalgebra(M):
                out[tuple(M)] = M
            return
        if len(U) + bin(compat).count("1") < c:
            return
        for i in list(bits(compat)):
            f = lst[i]
            new_span = span + [f ^ s for s in span]
            nc = compat & ~((1 << (i + 1)) - 1)
            for s in new_span:
                if s:
                    nc &= allow[s]
                    if not nc:
                        break
            rec(U + [f], new_span, nc)

    rec([], [0], full)
    return list(out.values())


# ------------------------------------------------------------ random bottom-up
def normaliser(L, A):
    """{z in L : [z, A] subset A}; a subalgebra whenever A is one"""
    A = rref(A)
    if not A:
        return [1 << i for i in range(L.n)]
    return normaliser_in(L, [1 << i for i in range(L.n)], A, target=A)


def grow_to_maximal(L, A, cap=9, memo=None):
    """A proper subalgebra A is enlarged, first by the normaliser chain (linear
    algebra, fast), then --- once the codimension is at most `cap` --- by the
    exhaustive coset step, until a maximal subalgebra is reached.  The last
    step is an exhaustive check over all the 2^codim - 1 cosets, so what is
    returned really is a maximal subalgebra."""
    A = rref(A)
    while True:
        N = normaliser(L, A)
        N = [v for v in N if v]
        if len(N) == L.n:
            break                        # the chain ran into L itself
        if len(N) == len(A):
            break
        A = rref(N)
    if len(A) >= L.n:
        return None
    if memo is not None:
        k = tuple(A)
        if k in memo:
            return memo[k]
    start = tuple(A)
    while True:
        if L.n - len(A) > cap:           # too many cosets to check them all
            if memo is not None:
                memo[start] = None
            return None
        grown = False
        for y in cosets(L, A):
            B = closure(L, A + [y])
            if len(B) != L.n:
                A, grown = B, True
                break
        if not grown:
            if memo is not None:
                memo[start] = A
            return A


def maximal_by_normaliser_chains(L, lines=None):
    """for every line <x> (or those given), the normaliser chain followed by
    greedy extension; returns the maximal subalgebras met"""
    out = {}
    memo = {}
    src = lines if lines is not None else range(1, 1 << L.n)
    for x in src:
        M = grow_to_maximal(L, [x], memo=memo)
        if M is not None:
            out[tuple(M)] = M
    return list(out.values())


def random_maximal(L, rng, tries=200):
    """a random greedy walk up the lattice of proper subalgebras; it always
    ends in a maximal one, the last step being an exhaustive check over the
    2^codim - 1 cosets."""
    M = rref([rng.randrange(1, 1 << L.n)])
    while True:
        grown = False
        for _ in range(tries):          # cheap: random elements
            y = rng.randrange(1, 1 << L.n)
            if in_span(y, M):
                continue
            N = closure(L, M + [y])
            if len(N) != L.n:
                M, grown = N, True
                break
        if grown:
            continue
        cs = cosets(L, M)               # exhaustive: is M maximal?
        rng.shuffle(cs)
        for y in cs:
            N = closure(L, M + [y])
            if len(N) != L.n:
                M, grown = N, True
                break
        if not grown:
            return M


# ------------------------------------------------------- Weisfeiler filtration
def minimal_submodules(L, M):
    """all minimal M-submodules of L/M, given as subspaces N with M < N <= L
    such that N/M is a minimal M-submodule"""
    out = []
    seen = set()
    for y in cosets(L, M):
        N = rref(M + [y])
        changed = True
        while changed:
            changed = False
            for a in list(N):
                for b in M:
                    w = L.mul(a, b)
                    if w and not in_span(w, N):
                        N = rref(N + [w])
                        changed = True
        key = tuple(N)
        if key not in seen:
            seen.add(key)
            out.append(N)
    # keep the minimal ones
    mins = []
    for N in out:
        if not any(len(P) < len(N) and all(in_span(v, N) for v in P)
                   for P in out):
            mins.append(N)
    return mins


def normaliser_in(L, cur, gens, target=None):
    """{x in span(cur) : [x, gens] subset target}, by linear algebra over F_2;
    `target` defaults to `cur` itself"""
    if not cur:
        return []
    tgt = cur if target is None else target
    rows = []
    for j, v in enumerate(cur):
        img = 0
        for k, u in enumerate(gens):
            img |= reduce_vec(L.mul(v, u), tgt) << (k * L.n)
        rows.append((img, 1 << j))
    piv = {}
    ker = []
    for img, tag in rows:
        while img:
            p = img.bit_length() - 1
            if p in piv:
                img ^= piv[p][0]
                tag ^= piv[p][1]
            else:
                piv[p] = (img, tag)
                break
        else:
            ker.append(tag)
    out = []
    for t in ker:
        x = 0
        for j, v in enumerate(cur):
            if (t >> j) & 1:
                x ^= v
        if x:
            out.append(x)
    return rref(out)


def filtration(L, M, Lm1):
    """the W-filtration for L_0 = M, L_{-1} = Lm1; returns (neg, pos) dims"""
    neg = [M, Lm1]
    while len(neg[-1]) < L.n:
        prev = neg[-1]
        new = rref(prev + [L.mul(a, b) for a in Lm1 for b in prev])
        if len(new) == len(prev):
            break                      # L_{-1} does not generate: not a W-filt
        neg.append(new)
    pos = [M]
    while True:
        cur = pos[-1]
        nxt = normaliser_in(L, cur, Lm1)
        if len(nxt) == len(cur) or not nxt:
            break
        pos.append(nxt)
    negdims = [len(neg[i + 1]) - len(neg[i]) for i in range(len(neg) - 1)]
    posdims = [len(pos[i]) - len(pos[i + 1]) for i in range(len(pos) - 1)]
    posdims.append(len(pos[-1]))
    if len(pos[-1]) == 0:
        posdims = posdims[:-1]
    return negdims, posdims, neg, pos


def growth_vector(negdims):
    v, s = [], 0
    for d in negdims:
        s += d
        v.append(s)
    return v


def g0_type(L, M, pos):
    """the isomorphism type of g_0 = L_0/L_1: dim, dim of the derived algebra,
    number of 2-nilpotent elements, solvable?"""
    L0, L1 = pos[0], (pos[1] if len(pos) > 1 else [])
    # a basis of a complement of L1 in L0, with the induced bracket
    comp = []
    rows = list(L1)
    for v in L0:
        if not in_span(v, rows):
            rows = rref(rows + [v])
            comp.append(v)
    k = len(comp)
    idx = {}
    red = rref(L1)

    def coords(u):
        """coordinates of u mod L1 in the basis `comp`"""
        v, out = u, 0
        for i in range(k - 1, -1, -1):
            pass
        # gaussian elimination against comp + L1
        basis = [(c, 1 << i) for i, c in enumerate(comp)] + [(r, 0) for r in red]
        piv = {}
        for w, tag in basis:
            x, t = w, tag
            for p in sorted(piv, reverse=True):
                if (x >> p) & 1:
                    x ^= piv[p][0]
                    t ^= piv[p][1]
            if x:
                piv[x.bit_length() - 1] = (x, t)
        x, t = v, 0
        for p in sorted(piv, reverse=True):
            if (x >> p) & 1:
                x ^= piv[p][0]
                t ^= piv[p][1]
        assert x == 0
        return t

    tab = [[coords(L.mul(a, b)) for b in comp] for a in comp]
    g0 = LieF2(tab, "g0")
    der = len(g0.derived()) if k else 0
    nil = 0
    for u in range(1, 1 << k):
        if all(g0.mul(u, g0.mul(u, 1 << j)) == 0 for j in range(k)):
            nil += 1
    return k, der, nil, g0


def solvable(g0):
    rows = [1 << i for i in range(g0.n)]
    while rows:
        new = rref([g0.mul(a, b) for a in rows for b in rows])
        if len(new) == len(rows):
            return False
        rows = new
    return True


# ------------------------------------------------------------------- reporting
def wgradings_of(L, M):
    """all W-gradings coming from the maximal subalgebra M"""
    out = []
    for N in minimal_submodules(L, M):
        negdims, posdims, neg, pos = filtration(L, M, N)
        if sum(negdims) != L.n - len(M):
            continue                    # L_{-1} does not generate L/L_0
        k, der, nil, g0 = g0_type(L, M, pos)
        out.append({
            "codim": L.n - len(M),
            "neg": negdims,
            "pos": posdims,
            "growth": growth_vector(negdims),
            "g0": (k, der, nil, solvable(g0)),
        })
    return out


def key_of(w):
    return (tuple(w["neg"]), tuple(w["pos"]), w["g0"])


def report(path, cmax=6, nrand=0, budget=None, candmax=None,
           out=sys.stdout):
    L = build(path)
    t0 = time.time()
    ranks = {f: restrict_rank(L, f) for f in range(1, 1 << L.n)}
    print("=" * 78, file=out)
    print("%s   dim %d   (ranks in %.0fs)" % (L.name, L.n, time.time() - t0),
          file=out, flush=True)
    found = {}          # key -> [count of maximal subalgebras, sample]
    nmax = {}           # codim -> number of maximal subalgebras
    smaller = []        # all subalgebras of codimension < c, exhaustively
    for c in range(1, cmax + 1):
        t = time.time()
        try:
            subs = subalgebras_of_codim(L, ranks, c, budget=budget,
                                        candmax=candmax)
        except TimeoutError as e:
            print("   codim %d: SEARCH ABANDONED (%s)" % (c, e), file=out,
                  flush=True)
            break
        # M is maximal iff it lies in no subalgebra of smaller codimension;
        # the list `smaller` is exhaustive, so this test is rigorous.
        mx = [M for M in subs
              if not any(all(in_span(v, P) for v in M) for P in smaller)]
        smaller += subs
        nmax[c] = len(mx)
        print("   codim %2d: %5d subalgebras, %5d maximal   [%.0fs]"
              % (c, len(subs), len(mx), time.time() - t), file=out, flush=True)
        for M in mx:
            for w in wgradings_of(L, M):
                k = key_of(w)
                found.setdefault(k, [0, w])
                found[k][0] += 1
    if nrand:
        t = time.time()
        rng = random.Random(20260806)
        lines = ([rng.randrange(1, 1 << L.n) for _ in range(nrand)]
                 if nrand < (1 << L.n) - 1 else range(1, 1 << L.n))
        mx = maximal_by_normaliser_chains(L, lines)
        extra = {}
        for M in mx:
            c = L.n - len(M)
            extra[c] = extra.get(c, 0) + 1
            if c > cmax:
                for w in wgradings_of(L, M):
                    k = key_of(w)
                    if k not in found:
                        found[k] = [0, w]
                    found[k][0] += 1
        print("   normaliser chains from %s lines: %d maximal subalgebras,"
              " codimensions %s   [%.0fs]"
              % (nrand, len(mx), dict(sorted(extra.items())),
                 time.time() - t), file=out, flush=True)
    print("   --- the W-gradings:", file=out)
    for k, (cnt, w) in sorted(found.items(), key=lambda kv: kv[1][1]["codim"]):
        dg, dd, dn, sol = w["g0"]
        print("   codim %d  g_- = %s  g_>=0 = %s  growth %s  g_0: dim %d,"
              " dim g_0' %d, 2-nilp %d, solvable %s   [x %d]"
              % (w["codim"], w["neg"], w["pos"], w["growth"], dg, dd, dn, sol,
                 cnt), file=out, flush=True)
    return L, found, nmax


if __name__ == "__main__":
    cmax = int(os.environ.get("CMAX", "5"))
    nrand = int(os.environ.get("NRAND", "0"))
    budget = int(os.environ.get("BUDGET", "3000000"))
    candmax = int(os.environ.get("CANDMAX", "4000"))
    for p in sys.argv[1:]:
        try:
            report(p, cmax=cmax, nrand=nrand, budget=budget,
                   candmax=candmax)
        except Exception as e:
            print("FAILED on", p, repr(e), flush=True)
