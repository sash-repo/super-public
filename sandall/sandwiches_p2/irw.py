#!/usr/bin/env python3
r"""
irw.py --- all the W-gradings of the exceptional simple Lie algebra

        ir(9; \One) subset k(9; \One)           (dim 26)

of [BGLLS], eqs. (72)--(73), by the method of [KLS], Subsec. 3.3: a W-grading
of a vectorial algebra is a regrading of the indeterminates, so one runs over
the degree vectors d = (d_1, ..., d_9) and tests the Weisfeiler conditions.

The realization is the one of ir.py, which this script imports: a vector field
is a bit vector of length 512*9, the slot (mask, j) standing for x^mask d_j.
For a degree vector d the regraded degree of that slot is

        deg(x^mask d_j) = sum_{i in mask} d_i - d_j,

which for a contact field K_f is deg f - d_1 once the contact relation holds.
The four hyperbolic pairs of the contact form
        alpha = dx_1 + x_2 dx_9 + x_3 dx_8 + x_4 dx_7 + x_5 dx_6
are (2,9), (3,8), (4,7), (5,6), so the degree equation of Lemma "LemDegEq" of
the text reads
        d_1 = d_2 + d_9 = d_3 + d_8 = d_4 + d_7 = d_5 + d_6.

What is computed, all of it exact and exhaustive over F_2:

  Step 0  ir(9; \One) itself: the partial prolong (g_{-1}, tilde g_0)_* and its
          unique minimal ideal, 26-dimensional (this is ir.py's own step (2),
          repeated here so that the script stands alone).
  Step 1  the degree equation: over a box of degree vectors, the contact
          relation is shown to be necessary and sufficient for ir to be a
          graded subspace of k(9).
  Step 2  the Weisfeiler conditions -- finite depth, g_- generated by g_{-1},
          transitivity in every non-negative degree, and ABSOLUTE
          irreducibility (Burnside) of the g_0-module g_{-1} -- for every
          solution of the degree equation in a box.
  Step 3  the answers, deduplicated as gradings (two degree vectors giving the
          same decomposition of ir count once), with the growth vector of the
          distribution preserved.

Usage:  python3 irw.py [--box N] [--full]
"""

import os as _os_runs; _os_runs.makedirs('runs', exist_ok=True)  # logs go to ./runs
import itertools
import sys
from math import gcd

import ir
from ir import (NVAR, DIMV, bits, bracket, echelon, in_span, reduce_vec,
                burnside_irreducible, prolong, flatten, minimal_ideal,
                G0T, GM1, W, PAIRS)

LOG = None


def say(*a):
    s = ' '.join(str(x) for x in a)
    print(s)
    if LOG:
        LOG.write(s + '\n')
        LOG.flush()


def report(msg, ok):
    say(('  OK   ' if ok else '  FAIL ') + msg)
    if not ok:
        report.bad += 1


report.bad = 0

# --------------------------------------------------------------- the algebra


def build_ir():
    """the 26 basis vectors of ir(9; \\One), as in ir.py"""
    part = prolong(G0T)
    idl, uniq, _ = minimal_ideal(flatten(part))
    assert uniq and len(idl) == 26, (uniq, len(idl))
    return [v for _, v in idl]


def terms(v):
    """[(mask, j), ...] of a vector field"""
    return [divmod(i, NVAR) for i in bits(v)]


# ------------------------------------------------------------ the regrading

def slot_deg(mask, j, d):
    return sum(d[i] for i in range(NVAR) if mask >> i & 1) - d[j]


def graded_pieces(basis, tms, d):
    """split each basis vector of ir by d-degree; None if ir is not d-graded"""
    allparts = []
    for v, tv in zip(basis, tms):
        parts = {}
        for (mask, j) in tv:
            c = slot_deg(mask, j, d)
            parts[c] = parts.get(c, 0) ^ (1 << (mask * NVAR + j))
        if len(parts) == 1:
            allparts.append(v)
        else:
            allparts.extend(parts.values())
    sp = echelon(allparts)
    if len(sp) != len(basis):
        return None
    out = {}
    for _, v in sp:
        mask, j = divmod(v.bit_length() - 1, NVAR)
        out.setdefault(slot_deg(mask, j, d), []).append(v)
    return out


def normalize(pieces):
    """divide every degree by the gcd of the degrees that occur"""
    degs = [c for c in pieces if c]
    g = 0
    for c in degs:
        g = gcd(g, abs(c))
    if g in (0, 1):
        return pieces
    return {c // g: b for c, b in pieces.items()}


# ------------------------------------------------- the Weisfeiler conditions

def span_br(A, B):
    return [v for _, v in echelon([bracket(a, b) for a in A for b in B])]


def w_test(pieces):
    degs = sorted(pieces)
    if degs[0] >= 0:
        return False, 'no negative part'
    gm1 = pieces.get(-1)
    if not gm1:
        return False, 'g_{-1} = 0'
    # (a) g_- is generated by g_{-1}
    cur = gm1
    for c in range(-2, degs[0] - 1, -1):
        cur = span_br(cur, gm1)
        want = pieces.get(c, [])
        if len(cur) != len(want):
            return False, 'g_{%d} not generated by g_{-1}' % c
        pv = echelon(cur)
        if not all(in_span(v, pv) for v in want):
            return False, 'g_{%d} not generated by g_{-1}' % c
    # (b) transitivity in every non-negative degree
    for c in degs:
        if c < 0:
            continue
        for v in pieces[c]:
            if all(bracket(v, w) == 0 for w in gm1):
                return False, 'not transitive in degree %d' % c
    # (c) g_0 acts absolutely irreducibly on g_{-1}  (Burnside)
    g0 = pieces.get(0)
    if not g0:
        return False, 'g_0 = 0'
    pv = echelon(gm1)
    for a in g0:
        for v in gm1:
            if not in_span(bracket(a, v), pv):
                return False, 'g_0 does not preserve g_{-1}'
    irr, msg = burnside_irreducible(g0, gm1)
    if not irr:
        return False, 'g_{-1} not absolutely irreducible (%s)' % msg
    return True, 'W'


def growth(pieces):
    tot, gv = 0, []
    for c in sorted((c for c in pieces if c < 0), reverse=True):
        tot += len(pieces[c])
        gv.append(tot)
    return tuple(gv)


def is_contact(pieces):
    """depth 2, dim g_{-2} = 1, and the pairing g_{-1} x g_{-1} -> g_{-2}
    non-degenerate"""
    if sorted(c for c in pieces if c < 0) != [-2, -1]:
        return False
    if len(pieces[-2]) != 1:
        return False
    gm1 = pieces[-1]
    z = pieces[-2][0]
    # the Gram matrix of the pairing, over F_2
    rows = []
    for a in gm1:
        r = 0
        for k, b in enumerate(gm1):
            if bracket(a, b) == z:
                r |= 1 << k
        rows.append(r)
    return len(echelon(rows)) == len(gm1)


def signature(pieces):
    """a canonical fingerprint of the decomposition, for deduplication"""
    out = []
    for c in sorted(pieces):
        out.append((c, tuple(sorted(v for _, v in echelon(pieces[c])))))
    return tuple(out)


# ------------------------------------------------------------------ the runs

PAIRIDX = [(1, 8), (2, 7), (3, 6), (4, 5)]      # 0-based: (2,9)(3,8)(4,7)(5,6)


def contact_vectors(d1range, arange):
    """all degree vectors satisfying the degree equation d_1 = d_i + d_{11-i}"""
    for d1 in d1range:
        for a in itertools.product(arange, repeat=4):
            d = [0] * NVAR
            d[0] = d1
            for k, (i, j) in enumerate(PAIRIDX):
                d[i] = a[k]
                d[j] = d1 - a[k]
            yield tuple(d)


def main():
    global LOG
    box = 3
    for k, arg in enumerate(sys.argv):
        if arg == '--box':
            box = int(sys.argv[k + 1])
    LOG = open('runs/irw.log', 'w')

    say('=== Step 0: ir(9; \\One) ===')
    basis = build_ir()
    tms = [terms(v) for v in basis]
    say('  dim ir(9; \\One) = %d' % len(basis))
    std = tuple([2] + [1] * 8)
    p0 = graded_pieces(basis, tms, std)
    report('the standard contact grading (2;1,...,1) grades ir: %s'
           % {c: len(b) for c, b in sorted(p0.items())}, p0 is not None)
    ok, msg = w_test(p0)
    report('it is a W-grading, growth vector %s%s'
           % (growth(p0), 'C' if is_contact(p0) else ''), ok)
    report('it is the contact grading v = (8, 9)C of Statement "StIr" 6)',
           growth(p0) == (8, 9) and is_contact(p0))

    say('')
    say('=== Step 1: the degree equation ===')
    lo, hi = -1, 2
    viol, extra = [], []
    nn = 0
    for d1 in (1, 2, 3):
        for rest in itertools.product(range(lo, hi + 1), repeat=8):
            d = (d1,) + rest
            nn += 1
            contact = all(d[0] == d[i] + d[j] for i, j in PAIRIDX)
            gr = graded_pieces(basis, tms, d)
            if contact and gr is None:
                viol.append(d)
            elif (not contact) and gr is not None:
                extra.append(d)
    say('  tested %d degree vectors: d_1 in {1,2,3}, d_2..d_9 in [%d, %d]'
        % (nn, lo, hi))
    report('every degree vector that grades ir satisfies the contact relation'
           ' d_1 = d_i + d_{11-i}%s'
           % ('' if not extra else ' -- %d exceptions, e.g. %s'
              % (len(extra), extra[:3])), not extra)
    say('  the contact relation alone is NOT sufficient: %d of the %d contact'
        % (len(viol), sum(1 for _ in contact_vectors((1, 2, 3), range(lo, hi + 1)))))
    say('  vectors in the box do not grade ir, e.g. %s -- see Step 3.' % (viol[0],))

    say('')
    say('=== Step 2: the W-gradings among the solutions ===')
    d1range = range(-box - 1, box + 3)
    arange = range(-box - 2, box + 3)
    found, seen, tested, subs = {}, set(), 0, {}
    for d in contact_vectors(d1range, arange):
        tested += 1
        gr = graded_pieces(basis, tms, d)
        if gr is None:
            continue
        gr = normalize(gr)
        ok, msg = w_test(gr)
        if not ok:
            continue
        sig = signature(gr)
        dims = tuple((c, len(b)) for c, b in sorted(gr.items()))
        gv = growth(gr)
        cc = is_contact(gr)
        key = (dims, gv, cc)
        sub = tuple(sorted(v for _, v in
                           echelon([w for c in gr if c >= 0 for w in gr[c]])))
        subs.setdefault(key, set()).add(sub)
        if sig not in seen:
            seen.add(sig)
            found.setdefault(key, []).append(d)
    say('  ran over %d degree vectors with d_1 in %s and d_i in %s'
        % (tested, list(d1range), list(arange)))
    say('  %d distinct W-gradings, in %d classes:' % (len(seen), len(found)))
    say('')
    say('  %-34s %-12s %-7s %s' % ('dims of the components', 'growth', 'depth',
                                   'a degree vector'))
    for key in sorted(found, key=lambda k: (len(k[1]), k[1], k[0])):
        dims, gv, cc = key
        ds = ' '.join('%d:%d' % (c, m) for c, m in dims)
        say('  %-34s %-12s %-7s %s   (%d gradings, %d distinct subalgebras '
            'g_{>=0})'
            % (ds, str(gv) + ('C' if cc else ''), -dims[0][0],
               found[key][0], len(found[key]), len(subs[key])))
    say('')
    say('  what g_0 is, in each class:')
    for key in sorted(found, key=lambda k: (len(k[1]), k[1], k[0])):
        gr = normalize(graded_pieces(basis, tms, found[key][0]))
        g0 = gr[0]
        der = [v for _, v in echelon([bracket(a, b) for a in g0 for b in g0])]
        cen = [v for v in g0 if all(bracket(v, w) == 0 for w in g0)]
        nilp = sum(1 for m in range(1, 1 << len(g0))
                   if sq_is_zero(g0, m)) if len(g0) <= 16 else None
        say('     growth %-9s dim g_0 = %-3d dim [g_0,g_0] = %-3d '
            'dim z(g_0) = %-2d  #{x in g_0 : (ad_x)^2 = 0 on ir} = %s'
            % (str(key[1]) + ('C' if key[2] else ''), len(g0), len(der),
               len(cen), nilp))

    say('')
    say('=== Step 3: the extra equation, and the parity functions ===')
    # the candidate: d_1 + d_2 = d_3 + d_4 + d_5, found by irdiag.py
    viol2, extra2 = [], []
    for d in contact_vectors(range(1, 4), range(-2, 4)):
        want = (d[0] + d[1] == d[2] + d[3] + d[4])
        got = graded_pieces(basis, tms, d) is not None
        if want and not got:
            viol2.append(d)
        if got and not want:
            extra2.append(d)
    report('among the solutions of the contact equation, ir is graded if and '
           'only if  d_1 + d_2 = d_3 + d_4 + d_5', not viol2 and not extra2)
    say('      (equivalently d_1 + d_9 = d_6 + d_7 + d_8, by the contact '
        'relation)')
    # it comes from the lowest weight vector v = X_2^+ of g_1
    part = prolong(G0T)
    v = [w for _, w in part[1]]
    say('  the degree-1 module is of dim %d; the two "del_1-terms" of its'
        % len(v))
    say('  lowest weight vector v = X_2^+ are x_1x_2 del_1 and x_3x_4x_5 del_1,')
    say('  of degrees d_2 and d_3 + d_4 + d_5 - d_1 -- whence the equation.')
    from ir import V1
    dv = sorted({slot_deg(m, j, (1, -1, 0, 0, 0, 1, 1, 1, 2)) for m, j in terms(V1)})
    say('  check: on the degree vector (1,-1,0,0,0,1,1,1,2) the vector v is '
        'homogeneous: degrees %s' % dv)

    say('')
    say('  mod 2 the two equations read')
    say('     p(x_i) + p(x_{11-i}) = p(x_1),   p(x_2)+p(x_3)+p(x_4)+p(x_5) '
        '= p(x_1),')
    say('  which is exactly eq. (irparity) of Theorem "ThIrParity".')
    npar = 0
    for p in itertools.product((0, 1), repeat=NVAR):
        if all(p[i] + p[j] == p[0] or (p[i] + p[j]) % 2 == p[0] % 2
               for i, j in PAIRIDX):
            pass
    adm = [p for p in itertools.product((0, 1), repeat=NVAR)
           if all((p[i] + p[j]) % 2 == p[0] for i, j in PAIRIDX)
           and (p[1] + p[2] + p[3] + p[4]) % 2 == p[0]]
    report('the mod 2 reduction has exactly 16 solutions, as '
           'Theorem "ThIrParity" says', len(adm) == 16)

    say('')
    say('=== Step 4: maximality of g_{>=0}, by a complete sweep ===')
    for key in sorted(found, key=lambda k: (len(k[1]), k[1], k[0])):
        d = found[key][0]
        gr = normalize(graded_pieces(basis, tms, d))
        nonneg = [w for c in gr if c >= 0 for w in gr[c]]
        pv = echelon(nonneg)
        cod = len(basis) - len(pv)
        cosets = [w for _, w in echelon(basis)]
        # every x outside must generate everything together with g_{>=0}
        bad = 0
        allsp = echelon(basis)
        for mask in range(1, 1 << len(basis)):
            pass
        # cheaper: run over coset representatives = a complement basis
        comp = []
        cur = [w for _, w in pv]
        for w in basis:
            if not in_span(w, echelon(cur)):
                comp.append(w)
                cur = cur + [w]
        reps = []
        for m in range(1, 1 << len(comp)):
            x = 0
            for k in range(len(comp)):
                if m >> k & 1:
                    x ^= comp[k]
            reps.append(x)
        for x in reps:
            gen = [w for _, w in pv] + [x]
            cl = echelon(gen)
            changed = True
            while changed:
                changed = False
                cur = [w for _, w in cl]
                for a in cur:
                    for b in cur:
                        t = bracket(a, b)
                        if t and not in_span(t, cl):
                            cl = echelon(cur + [t])
                            changed = True
                            break
                    if changed:
                        break
            if len(cl) != len(basis):
                bad += 1
        report('the grading %s: g_{>=0} is of codimension %d and is a MAXIMAL '
               'subalgebra (all %d cosets sweep to the whole of ir)'
               % (str(key[1]) + ('C' if key[2] else ''), cod, len(reps)),
               bad == 0)

    say('')
    say('=== Step 5: the superizations ===')
    say('  by Theorem "ThS" the W-gradings of s(ir, gr(p)) are exactly those')
    say('  induced by the gr(p)-compatible W-gradings of ir.  All the 15')
    say('  W-gradings of ir are tested against each of the 16 parity functions.')
    fam = {}
    for p in adm:
        odd = tuple(i + 1 for i in range(NVAR) if p[i])
        res = []
        for key in found:
            for d in found[key]:
                gr = normalize(graded_pieces(basis, tms, d))
                ok, sdims = supersplit(gr, p)
                if ok:
                    res.append((key[2], tuple(sdims)))
        fam[odd] = sorted(set(res))
    for odd in sorted(fam, key=lambda o: (len(o), o)):
        say('')
        say('  odd indeterminates %s:' % (str(odd) if odd else '(none)'))
        for cc, sdims in fam[odd]:
            gv = ', '.join('%d|%d' % t for t in cumul(sdims))
            say('     %-46s v = (%s)%s'
                % (' '.join('%d:(%d|%d)' % t for t in sdims), gv,
                   'C' if cc else ''))
    say('')
    say('  bad checks: %d' % report.bad)
    return found


def sq_is_zero(g0, m):
    x = 0
    for k in range(len(g0)):
        if m >> k & 1:
            x ^= g0[k]
    from ir import compose_square
    return compose_square(x) == 0


def supersplit(gr, p):
    """is the grading gr compatible with the parity p?  if so, the sdims"""
    sdims = []
    for c in sorted(gr):
        ev = od = 0
        for w in gr[c]:
            we, wo = 0, 0
            for (mask, j) in terms(w):
                par = (sum(p[i] for i in range(NVAR) if mask >> i & 1)
                       + p[j]) % 2
                if par:
                    wo ^= 1 << (mask * NVAR + j)
                else:
                    we ^= 1 << (mask * NVAR + j)
            if we and wo:
                return False, None
            if wo:
                od += 1
            else:
                ev += 1
        sdims.append((c, ev, od))
    return True, sdims


def cumul(sdims):
    tot = [0, 0]
    out = []
    for c, a, b in sorted((t for t in sdims if t[0] < 0), reverse=True):
        tot[0] += a
        tot[1] += b
        out.append(tuple(tot))
    return out


