#!/usr/bin/env python3
r"""
kapK.py --- the sandwich variety of the Kaplansky algebras over the
algebraically closed K = \bar F_2, and the parity of the sandwiches in the
superizations of Subsec. 5.3 of arXiv:1301.2781.

Over F_2 the scan in kap.py is exhaustive, but that settles nothing over K:
conditions (san) and (san2) are systems of homogeneous quadratic equations, and
a Zariski-closed cone can acquire points over an extension.  We reuse the
certificate of sandK.py: each coordinate chart of the projectivized variety
that must be empty is shown to be so by exhibiting the constant 1 in the ideal
generated by the dehomogenized equations (weak Nullstellensatz), by exact
linear algebra over F_2 on the Macaulay matrix.

Output: runs/kapK.log.

Usage:  python3 kapK.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from css import rref, in_span                                       # noqa: E402
from sandK import analyse                                           # noqa: E402
from kap import (kap2, kapB, kap4, Closure, Q_arf, superization,    # noqa: E402
                 fast_sandwiches, bitcount)

LOG = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'runs', 'kapK.log')


def main():
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    log = open(LOG, 'w', buffering=1)

    class Tee:
        def write(self, s):
            sys.__stdout__.write(s)
            log.write(s)

        def flush(self):
            sys.__stdout__.flush()
            log.flush()

    sys.stdout = Tee()

    print('=' * 78)
    print('The sandwich variety of the Kaplansky algebras over K = bar F_2')
    print('=' * 78)

    algs = [kap4(2, 0), kap4(2, 1), kap2(2), kapB(2),
            Closure(kap4(2, 0), 4, 'Kap_{4,0}(4)+V^*'),
            Closure(kap4(2, 1), 4, 'Kap_{4,1}(4)+V^*')]
    for L in algs:
        analyse(L)
        print()

    # the 19-dimensional 2-closure: the F_2-scan is the Gray-code one of kap.py
    cl = Closure(kap2(2), 4, 'Kap_2(4)+V^*')
    S = fast_sandwiches(cl)
    cl.sandwiches = lambda S=S: S
    print('Kap_2(4)+V^*: the %d F_2-sandwich(es) come from the Gray-code scan'
          % len(S))
    analyse(cl)
    print()

    # ---------------------------------------------------- which element is it?
    print('=' * 78)
    print('The sandwiches themselves, and their parity in the superizations')
    print('=' * 78)
    K2 = kap2(2)
    s2 = K2.sandwiches()
    for x in s2:
        supp = [K2.gamma[i] for i in range(K2.n) if (x >> i) & 1]
        print('Kap_2(4): the sandwich is the sum of e_u over u in %s'
              % ['%04d' % int(bin(u)[2:]) for u in supp])
        print('   (%d summands; the u are the non-zero vectors of a subspace: %s)'
              % (len(supp), is_subspace(supp)))
    KB = kapB(2)
    for x in KB.sandwiches():
        supp = [KB.gamma[i] for i in range(KB.n) if (x >> i) & 1]
        print('Kap_{4,B}(4): a sandwich over the u in %s'
              % ['%04d' % int(bin(u)[2:]) for u in supp])

    print()
    for x in S:
        supp = [cl.J.gamma[i] for i in range(cl.nJ) if (x >> i) & 1]
        star = [i - cl.nJ for i in range(cl.nJ, cl.n) if (x >> i) & 1]
        print('Kap_2(4)+V^*: the sandwich has %d summands e_u and V^*-part %s'
              % (len(supp), star))
        for name, par in [('KapLS_2(4)', lambda u: K2.B(1, u)),
                          ('KapS_{2,0}(4)', lambda u: (Q_arf(2, 0)(u) + 1) & 1),
                          ('KapS_{2,1}(4)', lambda u: (Q_arf(2, 1)(u) + 1) & 1)]:
            par_of_summands = {par(u) for u in supp}
            print('   in %-14s the sandwich is %s'
                  % (name, 'even' if par_of_summands == {0} else
                     ('ODD' if par_of_summands == {1} else
                      'inhomogeneous (parities %s)' % sorted(par_of_summands))))
    sys.stdout = sys.__stdout__
    log.close()


def is_subspace(vs):
    S = set(vs) | {0}
    return all((u ^ v) in S for u in S for v in S)


if __name__ == '__main__':
    main()
