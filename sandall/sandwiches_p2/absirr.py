#!/usr/bin/env python3
r"""absirr.py --- absolute irreducibility of a module over F_2, cheaply.

A module is given by matrices `mats` acting on F_2^n, each matrix stored by
COLUMNS: m[j] = the image of the j-th basis vector, as a bit mask.

  Norton's irreducibility test: if theta in the generated associative algebra
  has a ONE-dimensional kernel spanned by v, and w spans the kernel of
  theta^T, then M is irreducible if and only if v generates M and w generates
  M^* (under the transposed matrices).
  Absolute irreducibility: for irreducible M with cyclic vector v, an
  endomorphism X commuting with the action is fixed by u = X(v); the
  conditions are linear in u, and M is absolutely irreducible if and only if
  the solution space is 1-dimensional (End_A M = F_2).
If no theta of nullity 1 is found, the caller falls back to Burnside.
"""
import random


def apply(m, x):
    y = 0
    j = 0
    while x:
        if x & 1:
            y ^= m[j]
        x >>= 1
        j += 1
    return y


def mul(a, b):            # (a b)[j] = a(b[j])
    return [apply(a, c) for c in b]


def add(a, b):
    return [x ^ y for x, y in zip(a, b)]


def transpose(m, n):
    return [sum(((m[j] >> i) & 1) << j for j in range(n)) for i in range(n)]


def kernel(m, n):
    """basis of {x : m x = 0}"""
    rec = []      # (pivot, image, combination)
    ker = []
    for j in range(n):
        v, c = m[j], 1 << j
        for p, b, cc in rec:
            if v >> p & 1:
                v ^= b
                c ^= cc
        if v:
            rec.append((v.bit_length() - 1, v, c))
            rec.sort(key=lambda t: -t[0])
        else:
            ker.append(c)
    return ker


def spin(mats, v, n):
    """basis of the submodule generated by v, with the words (as matrices)"""
    basis = [(v.bit_length() - 1, v)]
    words = [None]                     # None = identity
    seq = [(v, None)]
    i = 0
    while i < len(seq):
        x, w = seq[i]
        i += 1
        for k, a in enumerate(mats):
            y = apply(a, x)
            r = y
            for p, b in basis:
                if r >> p & 1:
                    r ^= b
            if r:
                basis.append((r.bit_length() - 1, r))
                basis.sort(key=lambda t: -t[0])
                seq.append((y, (k, i - 1)))
        if len(basis) == n:
            break
    return seq, len(basis)


def abs_irreducible(mats, n, tries=400, rng=None):
    """True / False, or None if undecided (no theta of nullity 1 found)"""
    rng = rng or random.Random(1)
    if n == 1:
        return True
    ident = [1 << j for j in range(n)]
    for _ in range(tries):
        th = [0] * n
        for _k in range(rng.randint(1, 4)):
            w = mats[rng.randrange(len(mats))]
            for _l in range(rng.randint(0, 3)):
                w = mul(mats[rng.randrange(len(mats))], w)
            th = add(th, w)
        if rng.random() < 0.5:
            th = add(th, [1 << j for j in range(n)])
        K = kernel(th, n)
        if len(K) != 1:
            continue
        v = K[0]
        seq, d = spin(mats, v, n)
        if d < n:
            return False
        tmats = [transpose(m, n) for m in mats]
        w = kernel(transpose(th, n), n)[0]
        _, d2 = spin(tmats, w, n)
        if d2 < n:
            return False
        # irreducible; now End_A(M).  Basis b_i = seq[i][0] (first n independent
        # ones); X(b_i) = W_i u where W_i is the word matrix of b_i.
        # Build the word matrices along seq.
        ident = [1 << j for j in range(n)]
        W = []
        indep = []
        ech = []
        for (x, how) in seq:
            Wm = ident if how is None else mul(mats[how[0]], W[how[1]])
            W.append(Wm)
            r = x
            for p, b, c in ech:
                if r >> p & 1:
                    r ^= b
            if r:
                ech.append((r.bit_length() - 1, r, None))
                ech.sort(key=lambda t: -t[0])
                indep.append(len(W) - 1)
        assert len(indep) == n
        B = [seq[i][0] for i in indep]
        WB = [W[i] for i in indep]
        # coordinates in basis B
        rec = []
        for j, u in enumerate(B):
            vv, c = u, 1 << j
            for p, b, cc in rec:
                if vv >> p & 1:
                    vv ^= b
                    c ^= cc
            rec.append((vv.bit_length() - 1, vv, c))
            rec.sort(key=lambda t: -t[0])

        def coords(x):
            c = 0
            for p, b, cc in rec:
                if x >> p & 1:
                    x ^= b
                    c ^= cc
            assert x == 0
            return c
        # equations: for each a, i:  sum_j c_ij WB_j u  -  a WB_i u = 0,
        # where a b_i = sum_j c_ij b_j.  Each is an n x n matrix acting on u.
        rows = []      # each row: a bit mask over u-coordinates
        for a in mats:
            for i in range(n):
                cij = coords(apply(a, B[i]))
                M = mul(a, WB[i])
                j = 0
                while cij:
                    if cij & 1:
                        M = add(M, WB[j])
                    cij >>= 1
                    j += 1
                # M u = 0: rows of M (M stored by columns)
                for r in transpose(M, n):
                    if r:
                        rows.append(r)
        ech2 = []
        for r in rows:
            for p, b in ech2:
                if r >> p & 1:
                    r ^= b
            if r:
                ech2.append((r.bit_length() - 1, r))
                ech2.sort(key=lambda t: -t[0])
                if len(ech2) == n - 1:
                    break
        return n - len(ech2) == 1
    return None
