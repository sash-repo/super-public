#!/usr/bin/env python3
r"""fvlesand.py --- a lower bound for the sandwich subalgebra of F vle = vle(7;1)'.

If L = sum_{m<=k<=M} L_k is Z-graded, every x in L_k with 2k+2m > M is a
sandwich over every field: (ad x)^2 L_j lies in degree 2k+j >= 2k+m > M, and
[[L,x],[L,x]] in degree >= 2k+2m > M.  The algebra is graded by every vector of
its rank-4 grading lattice, so s(L) contains the subalgebra generated by all
such components, over a box of the lattice.  Then its normalizer is computed.
Usage: python3 fvlesand.py B"""
import itertools
import sys
from math import gcd

import fvle
from fvle import graded_pieces, irw, echelon, bracket, in_span

L4 = [(1, 1, 0, 1, 0, 0, 0), (1, 0, 1, 0, 1, 0, 0), (0, 1, 1, 0, 0, 1, 0), (-1, -1, -1, 0, 0, 0, 1)]


def closure(gens):
    E = echelon(gens)
    vecs = [v for _, v in E]
    i = 0
    while i < len(vecs):
        for j in range(i):
            w = bracket(vecs[i], vecs[j])
            if w and not in_span(w, E):
                E = echelon(vecs + [w]); vecs.append(w)
        i += 1
    return E


def main():
    B = int(sys.argv[1])
    basis = fvle.build()
    tms = [irw.terms(v) for v in basis]
    gens = []
    for lam in itertools.product(range(-B, B + 1), repeat=4):
        d = tuple(sum(l * v[i] for l, v in zip(lam, L4)) for i in range(7))
        if not any(d):
            continue
        p = graded_pieces(basis, tms, d)
        m, M = min(p), max(p)
        for k, vs in p.items():
            if 2 * k + 2 * m > M:
                gens.extend(vs)
    S = closure(gens)
    fvle.say('sandwich lower bound, box', B, ': dim of the generated subalgebra', len(S), 'of', len(basis))
    if len(S) < len(basis):
        Sv = [v for _, v in S]
        # normalizer: x with [x, S] in S -- solve over F_2 on the basis of L
        N = []
        # linear map x -> ([x,s] mod S)_s ; kernel by elimination
        def img(x):
            out = 0
            for i, s in enumerate(Sv):
                r = bracket(x, s)
                for pp, b in S:
                    if r >> pp & 1:
                        r ^= b
                out = (out << (len(basis) * 7 * 128)) | r if False else out
            return None
        rec = []
        ker = []
        for j, x in enumerate(basis):
            v = tuple(fvle.ir.reduce_vec(bracket(x, s), S) for s in Sv)
            key = 0
            for r in v:
                key = (key << 896) | r
            c = 1 << j
            for p, b, cc in rec:
                if key >> p & 1:
                    key ^= b; c ^= cc
            if key:
                rec.append((key.bit_length() - 1, key, c)); rec.sort(key=lambda t: -t[0])
            else:
                ker.append(c)
        fvle.say('normalizer of it: dim', len(ker))


if __name__ == '__main__':
    main()
