#!/usr/bin/env python3
r"""
kas2.py --- exact arithmetic over F_2 for the desuperized exceptional Lie algebra

        F(kas(1;N|6)) = kas(7; \tilde N) \subset k(7; \tilde N),

and the complete determination of its W-gradings by the method of [KLS], Subsec. 3.3
(the Theta-form / degree-equation method), for p = 2.

Conventions, all taken from [BGLLS2] = Bouarroudj-Grozman-Lebedev-Leites-Shchepochkina,
"Simple vectorial Lie algebras in characteristic 2 and their superizations",
SIGMA 16 (2020) 089:

  * indeterminates  t, xi_1, xi_2, xi_3, eta_1, eta_2, eta_3  (all EVEN after F),
    the six former odd ones of height 1 (i.e. z^2 = 0), t of height N_t;
  * O(7; N) is the divided power algebra; for p = 2 it is the exterior algebra on the
    "binary digits" z_i^{(2^j)}, so a monomial is a subset of digit slots;
  * contact bracket, [BGLLS2] (2.13) = (17.1),

        {f,g} = d_t(f) (1+E')(g) + (1+E')(f) d_t(g)
                + sum_i ( d_{xi_i}(f) d_{eta_i}(g) + d_{eta_i}(f) d_{xi_i}(g) ),
        E' = sum_i xi_i d_{xi_i};

  * squaring, [BGLLS2] (2.14):  (K_f)^2 = K_h with h = sum_i d_{xi_i}(f) d_{eta_i}(f);
  * standard grading  deg t = 2, deg xi_i = deg eta_i = 1,  deg K_f = deg f - deg t;
  * F(kas) is the prolong of k(7)_{<=0} and the degree-one module

        U = Y + (V + P),   [BGLLS2] (17.4),
        Y = <x_1 x_2 x_3 | x_i in {xi_i, eta_i}>            (8 monomials)
        Phi = xi_1 eta_1 + xi_2 eta_2 + xi_3 eta_3
        V = <xi_i Phi, eta_i Phi>
        P = <t xi_j ; eta_i (t + xi_j eta_j), i != j>.

A W-regrading is given by a degree vector  d = (d_t; a_1,a_2,a_3; b_1,b_2,b_3),
a_i = deg xi_i,  b_i = deg eta_i.  The script
  (1) builds kas exactly and checks it is a subalgebra closed under squaring;
  (2) verifies that d makes kas a graded subalgebra iff the contact relation
      d_t = a_i + b_i holds for every i (the only linear equation the method yields);
  (3) for every such d in a box, tests the Weisfeiler conditions exactly --
      finite depth, g_- generated by g_{-1}, transitivity, and ABSOLUTE
      irreducibility of the g_0-module g_{-1} (Burnside: the associative algebra
      generated by the action is all of End(g_{-1}));
  (4) prints the growth vector of the resulting distribution.
"""

import itertools
import os
import sys
from functools import lru_cache

# ---------------------------------------------------------------- the algebra O

NT = int(os.environ.get('KAS_NT', '3'))   # height of t: exponents 0 .. 2^NT - 1
NVAR = 7                    # t, xi_1..3, eta_1..3
HEIGHT = [NT, 1, 1, 1, 1, 1, 1]
T, XI, ETA = 0, (1, 2, 3), (4, 5, 6)

# a monomial is the tuple of exponents (e_0, ..., e_6), e_i < 2^HEIGHT[i]
MONS = [m for m in itertools.product(*[range(2 ** h) for h in HEIGHT])]
IDX = {m: i for i, m in enumerate(MONS)}
DIMO = len(MONS)

# a polynomial is a Python int used as a bit vector over MONS
def mono(m):
    return 1 << IDX[m]

def bits(v):
    while v:
        b = v & -v
        yield b.bit_length() - 1
        v ^= b

def stddeg_mon(m):
    """standard grading: deg t = 2, deg xi = deg eta = 1"""
    return 2 * m[T] + sum(m[i] for i in XI + ETA)

def deg_mon(m, d):
    """d-degree of a monomial; d = (d_t, a_1,a_2,a_3, b_1,b_2,b_3)"""
    return sum(m[i] * d[i] for i in range(NVAR))

# multiplication: u^(r) u^(s) = prod C(r_i+s_i, r_i) u^(r+s); mod 2 the coefficient
# is 1 iff r_i & s_i == 0 for every i (Kummer), and then r+s = r|s
def mul_mon(m1, m2):
    out = []
    for i in range(NVAR):
        if m1[i] & m2[i]:
            return None
        out.append(m1[i] | m2[i])
    return tuple(out)

MUL = [[0] * DIMO for _ in range(DIMO)]
for i, m1 in enumerate(MONS):
    for j, m2 in enumerate(MONS):
        r = mul_mon(m1, m2)
        if r is not None:
            MUL[i][j] = 1 << IDX[r]

def mul(f, g):
    r = 0
    for i in bits(f):
        row = MUL[i]
        for j in bits(g):
            r ^= row[j]
    return r

# derivative: d_i u^(r) = u^(r - e_i)
DER = [[0] * DIMO for _ in range(NVAR)]
for i in range(NVAR):
    for k, m in enumerate(MONS):
        if m[i] > 0:
            mm = list(m)
            mm[i] -= 1
            DER[i][k] = 1 << IDX[tuple(mm)]

def der(i, f):
    r = 0
    tab = DER[i]
    for k in bits(f):
        r ^= tab[k]
    return r

# E' = sum_{i in XI} xi_i d_{xi_i};  on a monomial it is multiplication by
# (e_{xi_1}+e_{xi_2}+e_{xi_3}) mod 2
EPRIME_ODD = 0              # bit mask of monomials on which E' acts as 1
for k, m in enumerate(MONS):
    if sum(m[i] for i in XI) % 2:
        EPRIME_ODD |= 1 << k

def one_plus_E(f):
    return f ^ (f & EPRIME_ODD)          # (1+E')f: kills the E'-odd part

# ------------------------------------------------------------ contact bracket

def kb(f, g):
    """{f,g} of [BGLLS2] (2.13); p = 2, so all signs are +"""
    r = mul(der(T, f), one_plus_E(g)) ^ mul(one_plus_E(f), der(T, g))
    for i in range(3):
        r ^= mul(der(XI[i], f), der(ETA[i], g))
        r ^= mul(der(ETA[i], f), der(XI[i], g))
    return r

def sq(f):
    """the generating function of (K_f)^2, see [BGLLS2] (2.14)"""
    r = 0
    for i in range(3):
        r ^= mul(der(XI[i], f), der(ETA[i], f))
    return r

# ------------------------------------------------------- F_2 linear algebra

def echelon(vecs):
    """row echelon basis (list of ints) of the span"""
    basis = []
    piv = {}
    for v in vecs:
        while v:
            p = v.bit_length() - 1
            if p in piv:
                v ^= piv[p]
            else:
                piv[p] = v
                basis.append(v)
                break
    return sorted(basis, key=lambda x: -x.bit_length())

def reduce_by(v, piv):
    """canonical form of v modulo the span; piv must be a REDUCED (rref) pivot dict,
    otherwise this is not a linear map"""
    for p in sorted(piv, reverse=True):
        if (v >> p) & 1:
            v ^= piv[p]
    return v

def pivots(basis):
    """reduced row echelon pivot dict of the span of `basis`"""
    piv = {}
    for v in basis:
        v = reduce_by(v, piv)
        if v:
            p = v.bit_length() - 1
            for q in list(piv):
                if (piv[q] >> p) & 1:
                    piv[q] ^= v
            piv[p] = v
    return piv

def in_span(v, piv):
    return reduce_by(v, piv) == 0

# ----------------------------------------------------------- building kas

def std_component(j):
    """the monomials f with deg K_f = j, i.e. stddeg(f) = j + 2"""
    return [1 << k for k, m in enumerate(MONS) if stddeg_mon(m) == j + 2]

MAXDEG = max(stddeg_mon(m) for m in MONS) - 2      # top Lie degree

def build_kas():
    """F(kas) as the prolong of k(7)_{<=0} and U of (17.4)"""
    comp = {}
    for j in range(-2, 1):
        comp[j] = echelon(std_component(j))

    # the degree-one module U = Y + V + P
    def M(**kw):
        e = [0] * NVAR
        for k, v in kw.items():
            e[{'t': T, 'x1': 1, 'x2': 2, 'x3': 3,
               'e1': 4, 'e2': 5, 'e3': 6}[k]] = v
        return mono(tuple(e))

    xi = [M(x1=1), M(x2=1), M(x3=1)]
    eta = [M(e1=1), M(e2=1), M(e3=1)]
    tt = M(t=1)
    Phi = mul(xi[0], eta[0]) ^ mul(xi[1], eta[1]) ^ mul(xi[2], eta[2])

    U = []
    for choice in itertools.product(*[(xi[i], eta[i]) for i in range(3)]):
        U.append(mul(mul(choice[0], choice[1]), choice[2]))          # Y
    for i in range(3):
        U.append(mul(xi[i], Phi))
        U.append(mul(eta[i], Phi))                                    # V
    for j in range(3):
        U.append(mul(tt, xi[j]))                                      # P
    for i in range(3):
        for j in range(3):
            if i != j:
                U.append(mul(eta[i], tt ^ mul(xi[j], eta[j])))        # P
    comp[1] = echelon(U)

    gm1 = comp[-1]
    for j in range(2, MAXDEG + 1):
        prev = pivots(comp[j - 1])
        cand = std_component(j)
        # solve: which combinations f of cand have {f, g_{-1}} inside comp[j-1]?
        rows = []
        for f in cand:
            img = []
            for g in gm1:
                img.append(reduce_by(kb(f, g), prev))
            rows.append((f, img))
        comp[j] = echelon(_kernel(rows))
    return comp

def _kernel(rows):
    """rows = [(vector, [images])]; return a basis of {combinations with all images 0}"""
    n = len(rows)
    if n == 0:
        return []
    nimg = len(rows[0][1])
    # gaussian elimination on the concatenated image, carrying the source vector
    work = [(rows[i][0], list(rows[i][1])) for i in range(n)]
    piv = {}
    ker = []
    for src, img in work:
        s, im = src, list(img)
        while True:
            lead = None
            for k in range(nimg):
                if im[k]:
                    lead = (k, im[k].bit_length() - 1)
                    break
            if lead is None:
                ker.append(s)
                break
            if lead in piv:
                s2, im2 = piv[lead]
                s ^= s2
                im = [a ^ b for a, b in zip(im, im2)]
            else:
                piv[lead] = (s, im)
                break
    return ker

# ------------------------------------------------------- Weisfeiler conditions

def graded_pieces(kas_basis, d):
    """split the subspace kas by d-degree; returns None if it is not d-graded"""
    dt = d[T]
    by = {}
    for v in kas_basis:
        for k in bits(v):
            c = deg_mon(MONS[k], d) - dt
            by.setdefault(c, 0)
            by[c] ^= 1 << k
    pieces = {c: echelon([w]) for c, w in by.items()}
    # collect all homogeneous components of all basis vectors
    allcomp = []
    for v in kas_basis:
        parts = {}
        for k in bits(v):
            c = deg_mon(MONS[k], d) - dt
            parts[c] = parts.get(c, 0) ^ (1 << k)
        allcomp.extend(parts.values())
    sp = echelon(allcomp)
    if len(sp) != len(kas_basis):
        return None                     # components leave kas: not a graded subspace
    out = {}
    for v in sp:
        c = deg_mon(MONS[v.bit_length() - 1], d) - dt
        out.setdefault(c, []).append(v)
    return {c: echelon(b) for c, b in out.items()}

def brack_span(A, B):
    return echelon([kb(a, b) for a in A for b in B])

def w_test(pieces):
    """returns (ok, info) -- the Weisfeiler conditions"""
    degs = sorted(pieces)
    dmin = degs[0]
    if dmin >= 0:
        return False, 'no negative part'
    gm1 = pieces.get(-1, [])
    if not gm1:
        return False, 'g_{-1} = 0'
    # (a) g_- is generated by g_{-1}
    cur = gm1
    gen = {-1: echelon(gm1)}
    for c in range(-2, dmin - 1, -1):
        cur = brack_span(cur, gm1)
        gen[c] = cur
        want = pieces.get(c, [])
        if len(cur) != len(want):
            return False, f'g_{{{c}}} not generated by g_{{-1}} ({len(cur)} of {len(want)})'
        if not all(in_span(v, pivots(cur)) for v in want):
            return False, f'g_{{{c}}} not generated by g_{{-1}}'
    # (b) transitivity in non-negative degrees
    for c in degs:
        if c < 0:
            continue
        pv = pivots(gm1)
        rows = [(v, [kb(v, g) for g in gm1]) for v in pieces[c]]
        if _kernel(rows):
            return False, f'not transitive in degree {c}'
    # (c) g_0 acts absolutely irreducibly on g_{-1}  (Burnside)
    g0 = pieces.get(0, [])
    if not g0:
        return False, 'g_0 = 0'
    pv = pivots(gm1)                     # reduced: coordinates are the pivot bits
    ppos = sorted(pv)
    n = len(ppos)
    def vec_of(x):
        """coordinates of x in the rref basis of g_{-1}; None if x is not in it"""
        if reduce_by(x, pv):
            return None
        return sum(1 << i for i, p in enumerate(ppos) if (x >> p) & 1)
    basis_m1 = [pv[p] for p in ppos]
    mats = []
    for a in g0:
        cols = []
        for v in basis_m1:
            w = vec_of(kb(a, v))
            if w is None:
                return False, 'g_0 does not preserve g_{-1}'
            cols.append(w)
        mats.append(tuple(cols))
    # generate the associative algebra with 1
    ident = tuple(1 << i for i in range(n))
    def mat_mul(A, B):
        # (AB) applied to e_j = A(B e_j)
        out = []
        for j in range(n):
            v = B[j]
            r = 0
            for i in bits(v):
                r ^= A[i]
            out.append(r)
        return tuple(out)
    def flat(A):
        r = 0
        for j in range(n):
            r |= A[j] << (j * n)
        return r
    span = echelon([flat(ident)] + [flat(A) for A in mats])
    elts = [ident] + list(mats)
    changed = True
    while changed and len(span) < n * n:
        changed = False
        new = []
        for A in elts:
            for B in mats:
                C = mat_mul(A, B)
                if not in_span(flat(C), pivots(span)):
                    new.append(C)
        if new:
            elts.extend(new)
            span = echelon(span + [flat(C) for C in new])
            changed = True
    if len(span) != n * n:
        return False, f'g_{{-1}} not absolutely irreducible (envelope {len(span)} of {n*n})'
    return True, 'W'

def growth_vector(pieces):
    degs = sorted(c for c in pieces if c < 0)
    tot = 0
    gv = []
    for c in sorted(degs, reverse=True):
        tot += len(pieces[c])
        gv.append(tot)
    return tuple(gv)

# ----------------------------------------------------------------- main

def main():
    print('building F(kas) = kas(7; N) over F_2, N_t = %d ...' % NT)
    comp = build_kas()
    kas = echelon([v for j in sorted(comp) for v in comp[j]])
    print('  dim O(7;N) = %d,  dim kas = %d' % (DIMO, len(kas)))
    for j in sorted(comp):
        if comp[j]:
            print('    kas_%-3d dim %4d   (dim k_%d = %d)'
                  % (j, len(comp[j]), j, len(std_component(j))))

    # --- self-checks
    pv = pivots(kas)
    bad = 0
    for a in kas:
        for b in kas:
            if not in_span(kb(a, b), pv):
                bad += 1
    print('  closed under the bracket: %s' % ('YES' if bad == 0 else 'NO (%d)' % bad))
    bad2 = sum(0 if in_span(sq(a), pv) else 1 for a in kas)
    print('  closed under the squaring: %s' % ('YES' if bad2 == 0 else 'NO (%d)' % bad2))
    # Jacobi for the ambient contact bracket, on random elements
    import random
    random.seed(1)
    jbad = 0
    for _ in range(300):
        f, g, h = (random.getrandbits(DIMO) for _ in range(3))
        if kb(f, kb(g, h)) ^ kb(g, kb(f, h)) ^ kb(kb(f, g), h):
            jbad += 1
    print('  Jacobi identity for {,} on 300 random triples: %s'
          % ('OK' if jbad == 0 else 'FAILED %d' % jbad))

    # --- the degree equation: contact relation is necessary and sufficient
    print('\nStep 1: which degree vectors make kas a graded subalgebra of k(7)?')
    viol = []
    ok_noncontact = []
    for dt in range(1, 4):
        for a in itertools.product(range(-2, 4), repeat=3):
            for b in itertools.product(range(-2, 4), repeat=3):
                d = (dt,) + a + b
                contact = all(dt == a[i] + b[i] for i in range(3))
                gr = graded_pieces(kas, d)
                if contact and gr is None:
                    viol.append(d)
                if (not contact) and gr is not None:
                    ok_noncontact.append(d)
    print('  contact relation d_t = a_i + b_i holds  ==> graded : %s'
          % ('always' if not viol else 'FAILS for %s' % viol[:3]))
    print('  contact relation fails ==> not graded : %s'
          % ('always' if not ok_noncontact
             else '%d exceptions, e.g. %s' % (len(ok_noncontact), ok_noncontact[:3])))

    # --- Step 2: the W-gradings
    print('\nStep 2: the W-gradings among the solutions of the degree equation')
    found = {}
    for dt in range(1, 5):
        for a in itertools.product(range(-3, 5), repeat=3):
            b = tuple(dt - x for x in a)
            d = (dt,) + a + b
            gr = graded_pieces(kas, d)
            if gr is None:
                continue
            ok, info = w_test(gr)
            if not ok:
                continue
            gv = growth_vector(gr)
            key = tuple(sorted(zip(a, b)))          # up to the S_3 of the indices
            found.setdefault((dt, key), (d, gv, {c: len(v) for c, v in sorted(gr.items())}))
    print('  %d W-gradings up to the S_3 permuting the indices:' % len(found))
    for (dt, key), (d, gv, dims) in sorted(found.items()):
        print('    deg t = %d, deg xi = %s, deg eta = %s   growth vector %s'
              % (d[0], d[1:4], d[4:7], gv))
        print('         components %s' % dims)

    # --- Step 3: the verdict on every solution of the degree equation in a box
    print('\nStep 3: verdict on every solution of the degree equation, d_t <= 3,'
          ' deg xi in [-1,4], up to S_3')
    seen = set()
    for dt in range(1, 4):
        for a in itertools.product(range(-1, 5), repeat=3):
            b = tuple(dt - x for x in a)
            key = (dt, tuple(sorted(zip(a, b))))
            if key in seen:
                continue
            seen.add(key)
            d = (dt,) + a + b
            gr = graded_pieces(kas, d)
            if gr is None:
                verdict = 'not graded'
            else:
                ok, info = w_test(gr)
                verdict = ('W-grading, growth vector %s' % (growth_vector(gr),)) if ok else info
            print('    t=%d xi=%-10s eta=%-10s  %s'
                  % (dt, str(a), str(b), verdict))

if __name__ == '__main__':
    main()
