#!/usr/bin/env python3
"""
Independent re-verification of sandK.py, by a second and different route, plus
the falsification control the first route cannot give.

sandK.py works in the affine chart l = 1 and certifies "1 is in the ideal".
Here we stay homogeneous: for a linear form l we look for the certificate

        l^d  lies in the degree-d part of the ideal I generated by the
             quadrics (san), (san2),

which is exactly the homogenisation of the chart certificate and which implies
l(x) = 0 for every K-point x of the sandwich cone.  No substitution of
variables is involved, so a bug in `substitute` cannot survive both routes.

Two controls are run as well:

 (1) POSITIVE: for the algebras that DO have F_2-sandwiches, take a linear form
     l with l(s) = 1 for a known sandwich s.  Then l does NOT vanish on the
     cone, so NO certificate may exist -- if the machinery produced one, it
     would be wrong.  We check that l^d is NOT in I for all d <= 4.
 (2) The special shape of the answer for Eick_{16,4} = Ei(16:6): there every
     SQUARE a_i^2 is already an F_2-linear combination of the quadrics, i.e.
     l^2 in I for every l at once.  Since x -> x^2 is injective on K, this
     alone forces x = 0: no sandwiches over any field.
"""

import glob
import itertools
import os
import sys

from css import LieF2, rref, in_span
from sandK import build, quadrics, reduce_generators, annihilator_basis
from sandK import _mulmon, _mulpoly


# ---------------------------------------------------------------- F_2 linear algebra

def add_row(piv, v):
    for p in sorted(piv, reverse=True):
        if (v >> p) & 1:
            v ^= piv[p]
    if v:
        piv[v.bit_length() - 1] = v
    return v


def reduce_vec(piv, v):
    for p in sorted(piv, reverse=True):
        if (v >> p) & 1:
            v ^= piv[p]
    return v


# ---------------------------------------------------------------- the test

def power_of_form(ell, n, d):
    """the polynomial l^d for l = sum_{i in ell} a_i, in char 2"""
    lin = frozenset((i,) for i in range(n) if (ell >> i) & 1)
    p = frozenset([()])
    for _ in range(d):
        p = _mulpoly(p, lin)
    return p


def in_ideal_degree(polys, n, d, target):
    """is `target` (homogeneous of degree d) in the span of {mu * f}, deg mu = d-2?"""
    mons = list(itertools.combinations_with_replacement(range(n), d))
    index = {mu: i for i, mu in enumerate(mons)}

    def vec(poly):
        v = 0
        for mon in poly:
            v |= 1 << index[mon]
        return v

    tv = vec(target)
    piv = {}
    for mu in itertools.combinations_with_replacement(range(n), d - 2):
        for f in polys:
            add_row(piv, vec(frozenset(_mulmon(mu, mon) for mon in f)))
        if reduce_vec(piv, tv) == 0:
            return True
    return reduce_vec(piv, tv) == 0


def certify(polys, n, ell, maxdeg=4):
    for d in (2, 3, maxdeg):
        if in_ideal_degree(polys, n, d, power_of_form(ell, n, d)):
            return d
    return None


def run(path, maxdeg=4):
    L = build(path)
    n = L.n
    polys = reduce_generators(quadrics(L))
    brute = L.sandwiches()
    S = rref(list(brute)) if brute else []
    print("%-24s dim %2d | quadrics %3d | F_2-span of the sandwiches: dim %d"
          % (L.name, n, len(polys), len(S)), flush=True)

    # ---- (2) the all-squares shortcut
    squares = all(in_ideal_degree(polys, n, 2, frozenset([(i, i)]))
                  for i in range(n))
    if squares:
        print("      every square a_i^2 is a combination of the quadrics "
              "==> the only K-sandwich is 0.", flush=True)

    # ---- the certificates
    degs = []
    for ell in annihilator_basis(S, n):
        d = certify(polys, n, ell, maxdeg)
        degs.append(d)
        if d is None:
            names = "+".join("a%d" % i for i in range(n) if (ell >> i) & 1)
            print("      NO certificate for %s up to degree %d" % (names, maxdeg),
                  flush=True)
    okall = all(d is not None for d in degs)
    print("      %d/%d annihilator forms certified (l^d in I, d = %s)"
          % (sum(1 for d in degs if d), len(degs),
             sorted({d for d in degs if d})), flush=True)

    # ---- (1) the falsification control
    ctrl = "n/a (no F_2-sandwiches)"
    if brute:
        s = brute[0]
        j = s.bit_length() - 1                    # a coordinate with l(s) = 1
        ell = 1 << j
        d = certify(polys, n, ell, maxdeg)
        ctrl = ("FAILED: certified a form that does not vanish on a sandwich!"
                if d is not None else "passed (no false certificate)")
    print("      control: %s" % ctrl, flush=True)
    print("      VERDICT: %s" % ("K-sandwiches lie in the F_2-span"
                                 if okall else "inconclusive"), flush=True)
    return okall


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args:
        args = (sorted(glob.glob("css-bases/thin15/*.txt"))
                + sorted(glob.glob("css-bases/dim16/*.txt")))
    for p in args:
        run(p)
        print(flush=True)
