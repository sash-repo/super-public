#!/usr/bin/env python3
r"""Self-tests of skry3.py: the cube map, against cases known by hand."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np                                                    # noqa: E402
from gvect import P, Vect                                             # noqa: E402
from skry3 import act, cube, power, is_derivation, Model              # noqa: E402

OK = [0]
BAD = [0]


def check(name, cond):
    if cond:
        OK[0] += 1
    else:
        BAD[0] += 1
        print("  FAIL: %s" % name)


def main():
    # ---------------------------------------------------- W(1; 1), p = 3
    V = Vect([1], [(1,)], ["u"])
    Z, U, U2 = (0,), (1,), (2,)
    d0 = {(Z, 0): 1}                     # d
    E = {(U, 0): 1}                      # u d  (Euler)
    top = {(U2, 0): 1}                   # u^(2) d
    check("d^3 = 0", cube(V, d0) == {})
    check("(u d)^3 = u d", cube(V, E) == E)
    check("(u^(2) d)^3 = 0", cube(V, top) == {})
    check("every cube is a derivation",
          all(is_derivation(V, cube(V, D)) for D in (d0, E, top)))

    # ad_{D^3} = (ad_D)^3 on W(1;1)
    m = Model(V, [d0, E, top], [-1, 0, 1], [(-1,), (0,), (1,)], "W(1;1)")
    for D in (d0, E, top, {(Z, 0): 1, (U2, 0): 2}):
        A = m.admat(D)
        C = cube(V, D)
        A3 = (A @ A @ A) % P
        B = m.admat(C) if C else np.zeros((3, 3), dtype=np.int64)
        check("ad^3 = ad_cube on W(1;1)", np.array_equal(A3 % P, B % P))

    # ---------------------------------------------------- W(2; 1)
    V2 = Vect([1, 1], [(1, 0), (0, 1)], ["x", "y"])
    x, y = (1, 0), (0, 1)
    Z2 = (0, 0)
    fields = {
        "d_x": {(Z2, 0): 1},
        "x d_x": {(x, 0): 1},
        "y d_x": {(y, 0): 1},
        "x y d_y": {((1, 1), 1): 1},
        "x^(2) d_y": {((2, 0), 1): 1},
    }
    check("(d_x)^3 = 0", cube(V2, fields["d_x"]) == {})
    check("(x d_x)^3 = x d_x", cube(V2, fields["x d_x"]) == fields["x d_x"])
    check("(y d_x)^3 = 0", cube(V2, fields["y d_x"]) == {})
    check("(x^(2) d_y)^3 = 0", cube(V2, fields["x^(2) d_y"]) == {})
    # x y d_y = x.(y d_y): the Euler field in y times the nilpotent x, so
    # D^3(y) = 2 x^{(2)} x y = 0 because x^{(3)} does not exist in O(2; \One).
    c = cube(V2, fields["x y d_y"])
    check("(x y d_y)^3 = 0", c == {})

    # the whole of W(2;1) : cube is always inside, and ad^3 = ad_cube
    basis, deg, wt = [], [], []
    for m_ in V2.mons:
        for i in range(2):
            basis.append({(m_, i): 1})
            deg.append(V2.deg((m_, i)))
            wt.append(V2.wt((m_, i)))
    W2 = Model(V2, basis, deg, wt, "W(2;1)")
    allin, adok = True, True
    for D in W2.basis:
        C = cube(V2, D)
        co = W2.coords(C) if C else np.zeros(W2.n, dtype=np.int64)
        if co is None:
            allin = False
            continue
        A = W2.admat(D)
        B = W2.admat(C) if C else np.zeros((W2.n, W2.n), dtype=np.int64)
        if not np.array_equal((A @ A @ A) % P, B % P):
            adok = False
    check("W(2;1) closed under cubes", allin)
    check("W(2;1): ad^3 = ad_cube throughout", adok)

    # ---------------------------------------------------- additivity of the cube
    # Jacobson: on a restricted algebra the p-map is p-semilinear and
    # (x+y)^[p] - x^[p] - y^[p] lies in the subalgebra generated by x, y.
    rng = np.random.default_rng(7)
    good = True
    for _ in range(30):
        D1 = {k: int(c) for k, c in
              zip(W2.keys, rng.integers(0, P, len(W2.keys))) if c}
        D2 = {k: int(c) for k, c in
              zip(W2.keys, rng.integers(0, P, len(W2.keys))) if c}
        if not D1 or not D2:
            continue
        S = dict(D1)
        for k, c in D2.items():
            S[k] = (S.get(k, 0) + c) % P
        S = {k: c for k, c in S.items() if c}
        A1, A2 = W2.admat(D1), W2.admat(D2)
        AS = (A1 + A2) % P
        cS = cube(V2, S)
        B = W2.admat(cS) if cS else np.zeros((W2.n, W2.n), dtype=np.int64)
        if not np.array_equal((AS @ AS @ AS) % P, B % P):
            good = False
    check("ad^3 = ad_cube on 30 random (inhomogeneous) fields", good)

    # scalar: (aD)^3 = a^3 D^3 = a D^3 over F_3
    good = True
    for D in W2.basis[:20]:
        for a in (1, 2):
            D2 = {k: (a * c) % P for k, c in D.items()}
            c1 = cube(V2, D2)
            c0 = {k: (a * c) % P for k, c in cube(V2, D).items()}
            if c1 != c0:
                good = False
    check("(aD)^3 = a^3 D^3 = a D^3 over F_3", good)

    print("%d checks, %d failures" % (OK[0] + BAD[0], BAD[0]))
    return 1 if BAD[0] else 0


if __name__ == "__main__":
    sys.exit(main())
