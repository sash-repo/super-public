#!/usr/bin/env python3
r"""
runbj4.py --- the two consequences of the scan of runbj3.py:

 1) a counterexample to Theorem \ref{zk} as corrected by eq. (impC): in
    Bj(3; \One|2) the subspace of EVEN sandwiches is non-zero (it is
    8-dimensional), and yet a set of two odd sandwiches already generates
    a~non-nilpotent Lie superalgebra;
 2) the shape of n_L(s) for s generated by the even sandwiches alone, in each
    of the two W-gradings.

Output: runs/bj4.log
"""

import os
import sys
import itertools
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bj import (P, N, MONS, mvec, kbracket, parity, rref, inside,            # noqa
                std_component, deg_std, deg_A, deg_B, V_BASIS, prolong)
from runbj import show, submodule, lie_closure, lower_central, normaliser     # noqa
from runbj3 import build, points                                             # noqa

LOG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "runs", "bj4.log")


def main():
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    log = open(LOG, "w", buffering=1)

    def say(m):
        print(m)
        log.write(m + "\n")

    R, piv = build()

    def ad2_zero(v):
        pv = parity(v)
        return not any(kbracket(v, kbracket(v, b, pf=pv), pf=pv).any() for b in R)

    # all homogeneous sandwiches, in the three gradings
    sand = []
    for dg in (deg_std, deg_A, deg_B):
        comp = {}
        for r in R:
            k0 = [k for k, c in enumerate(r) if c % P][0]
            comp.setdefault((dg(MONS[k0]), parity(r)), []).append(r)
        for key, bs in comp.items():
            for co in points(len(bs)):
                v = np.zeros(N, dtype=np.int64)
                for c, b in zip(co, bs):
                    v = (v + c * b) % P
                if v.any() and ad2_zero(v):
                    sand.append(v)
    odd = [v for v in sand if parity(v) == 1]
    even = [v for v in sand if parity(v) == 0]
    say("homogeneous sandwiches: %d odd, %d even; spans %d and %d"
        % (len(odd), len(even), len(rref(odd)[0]), len(rref(even)[0])))

    # 1) two odd sandwiches generating a non-nilpotent algebra
    say("")
    say("1) pairs of odd sandwiches and the algebra they generate")
    # one representative per line, and only the first LIM of them
    seen, uniq = set(), []
    for v in odd:
        key = tuple(int(c) for c in v)
        k2 = tuple(int(2 * c % P) for c in v)
        if key in seen or k2 in seen:
            continue
        seen.add(key)
        uniq.append(v)
    say("    %d distinct odd sandwich lines" % len(uniq))
    LIM = 14
    best = None
    tried = 0
    for i in range(min(LIM, len(uniq))):
        for j in range(i + 1, min(LIM, len(uniq))):
            tried += 1
            rows, pv = lie_closure([uniq[i], uniq[j]])
            lcs = lower_central(rows, pv)
            if lcs[-1] != 0:
                best = (uniq[i], uniq[j], rows, lcs)
                break
        if best:
            break
    say("    %d pairs tried" % tried)
    if best:
        x, y, rows, lcs = best
        ev = sum(1 for r in rows if parity(r) == 0)
        say("    x = %s" % show(x))
        say("    y = %s" % show(y))
        say("    both are sandwiches: %s, %s" % (ad2_zero(x), ad2_zero(y)))
        say("    they generate a subalgebra of sdim (%d|%d), dim %d of %d"
            % (ev, len(rows) - ev, len(rows), len(R)))
        say("    lower central series %s -- NOT nilpotent" % lcs)
        say("    (the even sandwiches of Bj span a space of dim %d, so the"
            % len(rref(even)[0]))
        say("     hypothesis of eq. (impC) does hold here)")
    else:
        say("    every pair generates a nilpotent algebra")

    # 2) n_L(s) for the even sandwiches
    say("")
    say("2) s = the subalgebra generated by the even sandwiches")
    s_rows, s_piv = lie_closure(even)
    say("    dim %d, abelian: %s" % (len(s_rows), lower_central(s_rows, s_piv)[1] == 0))
    for tag, dg in (("A", deg_A), ("B", deg_B), ("std", deg_std)):
        ds = sorted({dg(MONS[[k for k, c in enumerate(r) if c][0]]) for r in s_rows})
        say("    its degrees in grading %-3s: %s" % (tag, ds))
    nn, nnp = normaliser(R, piv, s_rows, s_piv)
    ev = sum(1 for r in nn if parity(r) == 0)
    say("    n_L(s): sdim (%d|%d), dim %d, codim %d"
        % (ev, len(nn) - ev, len(nn), len(R) - len(nn)))
    for tag, dg in (("A", deg_A), ("B", deg_B)):
        comp = {}
        for r in nn:
            comp.setdefault(dg(MONS[[k for k, c in enumerate(r) if c][0]]), []).append(r)
        say("    its components in grading %s: %s"
            % (tag, {d: len(comp[d]) for d in sorted(comp)}))
        L0 = rref([r for r in R
                   if dg(MONS[[k for k, c in enumerate(r) if c][0]]) >= 0])
        say("        contains L_0^%s: %s" % (tag, all(inside(nn, nnp, r) for r in L0[0])))
    # is it a subalgebra, is it self-normalising
    closed = all(inside(nn, nnp, kbracket(a, b, pf=parity(a))) for a in nn for b in nn)
    say("    a subalgebra: %s" % closed)
    nn2, _ = normaliser(R, piv, nn, nnp)
    say("    self-normalising: %s" % (len(nn2) == len(nn)))

    log.close()


if __name__ == "__main__":
    main()
