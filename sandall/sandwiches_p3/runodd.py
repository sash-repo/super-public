#!/usr/bin/env python3
r"""
runodd.py --- the census behind the replacement of the Correction (impC).

For every algebra in the list: Jacobi (all triples), the identity (I), the
factor identity (II), and then the exhaustive census of the lines of g_odd and
of g_even --- how many s have (ad_s)^2 = 0, how many of those satisfy the
sandwich identity (7) = (8), what the strong ones span, and whether they
generate a nilpotent subalgebra.

Output: runs/oddsand.log
"""
import itertools
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from oddsand import SAlg, census, gl, q, vect0, rref_p, lines          # noqa

HERE = os.path.dirname(os.path.abspath(__file__))
LOG = os.path.join(HERE, "runs", "oddsand.log")


def jacobi_ok(alg):
    p, n = alg.p, alg.n
    for i, j, k in itertools.product(range(n), repeat=3):
        a, b, c = alg.unit(i), alg.unit(j), alg.unit(k)
        pi, pj, pk = int(alg.par[i]), int(alg.par[j]), int(alg.par[k])
        lhs = alg.br(a, alg.br(b, c))
        r1 = alg.br(alg.br(a, b), c)
        r2 = ((-1) ** (pi * pj)) * alg.br(b, alg.br(a, c))
        if ((lhs - r1 - r2) % p).any():
            return False, (i, j, k)
    return True, None


def report(say, alg, do_even=True):
    say("")
    say("=== %s over F_%d, sdim (%d|%d)"
        % (alg.name, alg.p, int((alg.par == 0).sum()), int((alg.par == 1).sum())))
    ok, w = jacobi_ok(alg)
    say("    super Jacobi on all %d triples: %s" % (alg.n ** 3, "OK" if ok else "FAILED at %s" % (w,)))
    assert ok

    allstrong = []
    for parity in ((0, 1) if do_even else (1,)):
        n2, nstrong, span, weak = census(alg, parity)
        tag = "even" if parity == 0 else "odd "
        say("    %s: lines with (ad_s)^2=0: %4d;  of them satisfying (7)=(8): %4d;"
            "  their span: dim %d" % (tag, n2, nstrong, len(span)))
        # the identity (I) and (II), and c7 <=> c8, on everything the census saw
        seen = weak + [np.array(v) for v in span]
        bad = [v for v in seen if not alg.identity(v)]
        say("        identity (I) on all %d elements with (ad_s)^2=0: %s"
            % (n2, "OK" if not bad else "FAILED"))
        assert not bad
        bad = [v for v in seen if alg.c7(v) != alg.c8(v)]
        say("        (7) <=> (8) on the same %d: %s" % (n2, "OK" if not bad else "FAILED"))
        assert not bad
        if parity == 0 and alg.p != 2:
            bad = [v for v in seen if not alg.c7(v)]
            say("        s even, p != 2: (7) automatic: %s"
                % ("OK, all %d" % n2 if not bad else "FAILED on %d" % len(bad)))
            assert not bad
        if parity == 1 and weak:
            v = weak[0]
            say("        an odd s with (ad_s)^2=0 but NOT (7): %s" % vec(alg, v))
        allstrong += [np.array(v) for v in span]

    if allstrong:
        B = alg.closure(allstrong)
        lcs = alg.lower_central(B)
        say("    the subalgebra generated by ALL the sandwiches (new definition):"
            " dim %d of %d, lower central series %s%s"
            % (len(B), alg.n, lcs, "  -- NILPOTENT" if lcs[-1] == 0 else "  -- NOT nilpotent"))
    else:
        say("    no sandwich at all under the new definition")


def vec(alg, v):
    return " + ".join("%d*e%d" % (c, i) for i, c in enumerate(v) if c) or "0"


def main():
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    log = open(LOG, "w", buffering=1)

    def say(m):
        print(m)
        log.write(m + "\n")

    say("oddsand: the sandwich identity for odd elements")
    say("(I)  ad_s ad_x ad_s (y) = [[s,x],[s,y]]   whenever (ad_s)^2 = 0")
    say("(II) (1 + (-1)^p(s)) ad_s ad_x ad_s = 0   -- vacuous for s odd, and at p = 2")

    for alg in (gl(1, 1, 3), gl(1, 2, 3), gl(2, 1, 3), gl(2, 2, 3),
                gl(1, 2, 3, traceless=True), gl(2, 2, 5, traceless=True),
                q(2, 3), q(3, 3), q(2, 5), vect0(2, 3), vect0(2, 5)):
        report(say, alg)

    say("")
    say("done.")
    log.close()


if __name__ == "__main__":
    main()
