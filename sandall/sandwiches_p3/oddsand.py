#!/usr/bin/env python3
r"""
oddsand.py --- the sandwich identity for ODD elements.

The question this answers: what is the condition "the subspace of even
sandwiches is non-zero" (the Correction of the text) to be replaced with?

The claim to be checked here.  Let s be an element of a Lie superalgebra g with
(ad_s)^2 = 0.  Then, for all x, y in g,

    (I)     ad_s ad_x ad_s (y) = [[s, x], [s, y]],

so that the sandwich identity

    (7)     ad_s ad_x ad_s = 0   for all x

and the condition [ZK] adds at p = 2,

    (8)     [[g, s], [g, s]] = 0,

are one and the same condition; and

    (II)    (1 + (-1)^{p(s)}) ad_s ad_x ad_s = 0,

so that (7) is a CONSEQUENCE of (ad_s)^2 = 0 exactly when the factor
1 + (-1)^{p(s)} is invertible, i.e., for s even and p != 2 --- and for no other
(parity, characteristic).  The degeneration at p = 2 that [ZK] repairs by hand
and the degeneration for odd s are literally the same one.

Everything below is exact over F_p.  The engine builds a Lie superalgebra from
a basis of homogeneous matrices (super-commutator) or from a structure-constant
table, and tests, for a given s:

    ad2   : (ad_s)^2 = 0
    c7    : ad_s ad_x ad_s = 0 for every basis x
    c8    : [[s, e_i], [s, e_j]] = 0 for all i, j
    ident : the identity (I), entry by entry, for all basis x, y

`census` runs over every line of a homogeneous component, exhaustively.
"""

import itertools
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "lib"))
from exactlin import solve                                           # noqa: E402


# ----------------------------------------------------------------- the algebra
class SAlg:
    """A Lie superalgebra over F_p by its structure constants.

    C[i, j, k] = the k-th coordinate of [e_i, e_j];  par[i] = parity of e_i.
    """

    def __init__(self, name, p, par, C):
        self.name, self.p = name, p
        self.par = np.array(par, dtype=np.int64)
        self.C = np.array(C, dtype=np.int64) % p
        self.n = len(self.par)
        # ad of every basis element, as a matrix acting on coordinate columns
        self.AD = [self.ad(self.unit(i)) for i in range(self.n)]

    def unit(self, i):
        v = np.zeros(self.n, dtype=np.int64)
        v[i] = 1
        return v

    def br(self, u, v):
        return np.einsum("i,j,ijk->k", u, v, self.C) % self.p

    def ad(self, u):
        """matrix A with A[:, j] = [u, e_j]."""
        return np.einsum("i,ijk->kj", u, self.C) % self.p

    # ------------------------------------------------------------- the tests
    def ad2_zero(self, s):
        A = self.ad(s)
        return not (A.dot(A) % self.p).any()

    def c7(self, s):
        A = self.ad(s)
        return all(not (A.dot(X).dot(A) % self.p).any() for X in self.AD)

    def c8(self, s):
        A = self.ad(s)                      # columns span [g, s]
        B = rref_p(A.T.tolist(), self.p)    # a basis of [g, s]
        for u, v in itertools.combinations_with_replacement(B, 2):
            if self.br(np.array(u), np.array(v)).any():
                return False
        return True

    def identity(self, s):
        """(I) entry by entry: ad_s ad_x ad_s (y) == [[s, x], [s, y]]."""
        A = self.ad(s)
        for i in range(self.n):
            lhs = A.dot(self.AD[i]).dot(A) % self.p
            si = self.br(s, self.unit(i))
            for j in range(self.n):
                rhs = self.br(si, self.br(s, self.unit(j)))
                if ((lhs[:, j] - rhs) % self.p).any():
                    return False
        return True

    def factor_identity(self, s):
        """(II): (1 + (-1)^{p(s)}) ad_s ad_x ad_s = 0 for every basis x."""
        f = (1 + (-1) ** int(self.par_of(s))) % self.p
        A = self.ad(s)
        return all(not ((f * A.dot(X).dot(A)) % self.p).any() for X in self.AD)

    def par_of(self, v):
        ps = {int(self.par[i]) for i, c in enumerate(v) if c % self.p}
        if len(ps) > 1:
            raise ValueError("not homogeneous")
        return ps.pop() if ps else 0

    # ------------------------------------------------------- subalgebras etc.
    def closure(self, gens):
        """the Lie subalgebra generated by `gens`; returns a row basis."""
        B = rref_p([list(g) for g in gens], self.p)
        while True:
            new = list(B)
            for u, v in itertools.combinations_with_replacement(B, 2):
                new.append(list(self.br(np.array(u), np.array(v))))
            B2 = rref_p(new, self.p)
            if len(B2) == len(B):
                return B
            B = B2

    def lower_central(self, B):
        """dimensions of B, [B, B], [B, [B, B]], ... until it stabilises."""
        cur, out = list(B), [len(B)]
        while True:
            new = []
            for u in B:
                for v in cur:
                    new.append(list(self.br(np.array(u), np.array(v))))
            nxt = rref_p(new, self.p)
            out.append(len(nxt))
            if len(nxt) in (0, len(cur)):
                return out
            cur = nxt


def rref_p(rows, p):
    """row-reduce over F_p; returns the non-zero rows as lists of int."""
    rows = [[int(c) % p for c in r] for r in rows]
    rows = [r for r in rows if any(r)]
    if not rows:
        return []
    R, _ = _rref(rows, p)
    return [r for r in R if any(r)]


def _rref(rows, p):
    from exactlin import rref as _r
    return _r(rows, p)


# ------------------------------------------------------- matrix superalgebras
def from_matrices(name, p, mats, pars):
    """structure constants of the span of `mats` (homogeneous, closed)."""
    n = len(mats)
    flat = np.array([m.flatten() for m in mats], dtype=np.int64) % p
    M = flat.T.tolist()                      # columns = the basis elements
    C = np.zeros((n, n, n), dtype=np.int64)
    for i in range(n):
        for j in range(n):
            sgn = -1 if (pars[i] and pars[j]) else 1
            b = (mats[i].dot(mats[j]) - sgn * mats[j].dot(mats[i])) % p
            x = solve(M, [int(c) for c in b.flatten()], p)
            if x is None:
                raise ValueError("%s: not closed under the bracket" % name)
            C[i, j] = [int(c) % p for c in x]
    return SAlg(name, p, pars, C)


def gl(m, n, p, traceless=False, name=None):
    mats, pars = [], []
    d = m + n
    par = [0] * m + [1] * n
    for i in range(d):
        for j in range(d):
            if traceless and i == j:
                continue
            E = np.zeros((d, d), dtype=np.int64)
            E[i, j] = 1
            mats.append(E)
            pars.append((par[i] + par[j]) % 2)
    if traceless:                            # the supertraceless diagonal
        for i in range(d - 1):
            E = np.zeros((d, d), dtype=np.int64)
            E[i, i] = 1
            s = 1 if par[i] == 0 else -1
            t = 1 if par[i + 1] == 0 else -1
            E[i + 1, i + 1] = (-s * pow(t, -1, p)) % p
            mats.append(E)
            pars.append(0)
    nm = name or ("sl(%d|%d)" % (m, n) if traceless else "gl(%d|%d)" % (m, n))
    return from_matrices(nm, p, mats, pars)


def q(n, p):
    """q(n) = {(A, B)} inside gl(n|n), realised by honest matrices."""
    mats, pars = [], []
    for i in range(n):
        for j in range(n):
            A = np.zeros((2 * n, 2 * n), dtype=np.int64)
            A[i, j] = A[n + i, n + j] = 1
            mats.append(A)
            pars.append(0)
    for i in range(n):
        for j in range(n):
            B = np.zeros((2 * n, 2 * n), dtype=np.int64)
            B[i, n + j] = B[n + i, j] = 1
            mats.append(B)
            pars.append(1)
    return from_matrices("q(%d)" % n, p, mats, pars)


def vect0(n, p):
    """vect(0|n) = der Lambda(n): non-symmetric, no Cartan matrix."""
    mons = [m for k in range(n + 1) for m in itertools.combinations(range(n), k)]
    idx = {m: i for i, m in enumerate(mons)}
    N = len(mons)

    def mul(m1, m2):
        if set(m1) & set(m2):
            return None, 0
        merged = list(m1) + list(m2)
        sgn, arr = 1, list(merged)
        for a in range(len(arr)):
            for b in range(len(arr) - 1, a, -1):
                if arr[b - 1] > arr[b]:
                    arr[b - 1], arr[b] = arr[b], arr[b - 1]
                    sgn = -sgn
        return tuple(arr), sgn

    # basis: f * d_i, f a monomial
    basis = [(m, i) for m in mons for i in range(n)]
    B = len(basis)
    bidx = {b: k for k, b in enumerate(basis)}
    pars = [(len(m) + 1) % 2 for m, i in basis]

    def act(vf, m):
        """(f d_i)(m) as a vector over the monomials."""
        f, i = vf
        out = np.zeros(N, dtype=np.int64)
        if i not in m:
            return out
        pos = m.index(i)
        rest = tuple(x for x in m if x != i)
        sgn = (-1) ** pos
        prod, s2 = mul(f, rest)
        if prod is None:
            return out
        out[idx[prod]] += sgn * s2
        return out

    C = np.zeros((B, B, B), dtype=np.int64)
    for a, (f, i) in enumerate(basis):
        for b, (g, j) in enumerate(basis):
            # [f d_i, g d_j] = f d_i(g) d_j - (-1)^{pq} g d_j(f) d_i
            v = np.zeros(B, dtype=np.int64)
            dg = act((f, i), g)
            for k in range(N):
                if dg[k] % p:
                    v[bidx[(mons[k], j)]] += dg[k]
            df = act((g, j), f)
            sgn = (-1) ** (pars[a] * pars[b])
            for k in range(N):
                if df[k] % p:
                    v[bidx[(mons[k], i)]] -= sgn * df[k]
            C[a, b] = v % p
    return SAlg("vect(0|%d)" % n, p, pars, C)


# -------------------------------------------------------------------- census
def lines(dim, p):
    """one representative per line of F_p^dim."""
    for lead in range(dim):
        for tail in itertools.product(range(p), repeat=dim - lead - 1):
            yield [0] * lead + [1] + list(tail)


def census(alg, parity, verbose=None):
    """exhaustive over the lines of the part of the given parity.

    Returns (n_ad2, n_c8, basis_of_the_span_of_the_strong_sandwiches, examples).
    """
    idxs = [i for i in range(alg.n) if alg.par[i] == parity]
    n_ad2, strong, weak_only = 0, [], []
    for co in lines(len(idxs), alg.p):
        v = np.zeros(alg.n, dtype=np.int64)
        for c, i in zip(co, idxs):
            v[i] = c
        if not alg.ad2_zero(v):
            continue
        n_ad2 += 1
        if alg.c8(v):
            strong.append(v)
        else:
            weak_only.append(v)
    span = rref_p([list(v) for v in strong], alg.p) if strong else []
    return n_ad2, len(strong), span, weak_only
