#!/usr/bin/env python3
r"""
zass.py --- the sandwich subalgebra of the Zassenhaus algebra vect(1; m) over
F_p, i.e. the case n = 1 of Subsec. "The case of p=3" of the text.

Basis e_i = x^{(i+1)} d,  i = -1, ..., p^m - 2;  the bracket is
    [x^{(a)}d, x^{(b)}d] = ( C(a+b-1, a-1) - C(a+b-1, b-1) ) x^{(a+b-1)} d,
truncated at x^{(p^m)} = 0.

Checked:
 1. every e_i with i >= (p^m+1)/2 is a sandwich -- the degree bound of the Lemma
    of that Subsection, with p in place of 3, is SUFFICIENT;
 2. it is not necessary: the homogeneous sandwiches below it are listed;
 3. s(g), the subalgebra GENERATED by the sandwiches, is the span of a cone and
    NOT the span of the homogeneous sandwiches alone: a non-homogeneous sandwich
    contributes its components, e.g. e_5 + e_11 + e_17 for p=3, m=3.  Supports of
    size <= 3 are searched;
 4. for p=3, m=2 the search is EXHAUSTIVE (all 3^9 elements): the cone is exactly
    the 26 nonzero elements of Span(e_5,e_6,e_7), so s(g) = g_{>=5} and
    n_g(s(g)) = g_{>=0}, of codimension 1 -- the Lemma is exact there;
 5. and there Corollary 2.2 of the text, which predicts L_{[alpha-1]} in C(L)
    whenever the p-adic digits of alpha sum to more than (p+1)/2, over-predicts:
    for alpha = 5 it gives L_{[4]}, and x^{(5)}d is not a sandwich, nor is any
    sandwich with a nonzero L_{[4]}-component.  [Kir, Chs. 2, 3] assume p > 3.
"""
import sys
from itertools import product as iproduct

LOG = open("runs/zass.log", "w")


def say(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    LOG.write(s + "\n")
    LOG.flush()


FAILS = []


def check(name, ok, extra=""):
    say(("  PASS  " if ok else "  FAIL  ") + name + (("   " + extra) if extra else ""))
    if not ok:
        FAILS.append(name)


def binom_mod(n, k, p):
    if k < 0 or k > n or n < 0:
        return 0
    r = 1
    for i in range(k):
        r = r * (n - i) // (i + 1)
    return r % p


class Zass:
    """vect(1; m) over F_p in the basis e_{-1}, ..., e_{p^m-2}."""

    def __init__(self, p, m):
        self.p, self.m = p, m
        self.top = p ** m                       # x^{(top)} = 0
        self.deg = list(range(-1, self.top - 1))
        self.n = len(self.deg)
        self.idx = {d: i for i, d in enumerate(self.deg)}
        # structure constants
        self.C = [[None] * self.n for _ in range(self.n)]
        for i, a in enumerate(self.deg):
            for j, b in enumerate(self.deg):
                A, B = a + 1, b + 1             # x^{(A)}d, x^{(B)}d
                s = A + B - 1
                if s >= self.top or s < 0:
                    self.C[i][j] = None
                    continue
                c = (binom_mod(s, A, p) - binom_mod(s, B, p)) % p
                self.C[i][j] = (self.idx[s - 1], c) if c else None

    def br(self, u, v):
        p, n = self.p, self.n
        w = [0] * n
        for i in range(n):
            if not u[i]:
                continue
            for j in range(n):
                if not v[j] or self.C[i][j] is None:
                    continue
                k, c = self.C[i][j]
                w[k] = (w[k] + u[i] * v[j] * c) % p
        return w

    def is_sandwich(self, u):
        """(ad_u)^2 = 0 on the whole algebra."""
        for j in range(self.n):
            e = [0] * self.n
            e[j] = 1
            if any(self.br(u, self.br(u, e))):
                return False
        return True

    def basis_vec(self, d):
        e = [0] * self.n
        e[self.idx[d]] = 1
        return e


def span_of_cone(g, maxsupport=3):
    """The degrees occurring in the span of the sandwich cone, as far as supports
    of size <= maxsupport see it.  The cone is not a subspace, so a NON-homogeneous
    sandwich contributes degrees that carry no homogeneous sandwich."""
    from itertools import combinations
    degs = g.deg
    S = set(d for d in degs if g.is_sandwich(g.basis_vec(d)))
    p = g.p
    for size in range(2, maxsupport + 1):
        for supp in combinations(degs, size):
            if all(d in S for d in supp):
                continue
            for co in iproduct(range(1, p), repeat=size):
                v = [0] * g.n
                for d, c in zip(supp, co):
                    v[g.idx[d]] = c
                if g.is_sandwich(v):
                    S.update(supp)
                    break
    return sorted(S)


def normalizer(g, S):
    return [d for d in g.deg
            if all(all(g.br(g.basis_vec(d), g.basis_vec(a))[g.idx[c]] == 0
                       for c in g.deg if c not in S) for a in S)]


def digits(a, p):
    d = []
    while a:
        d.append(a % p)
        a //= p
    return d


def cor22(d, p):
    """Corollary 2.2 of the text: L_{[alpha-1]} in C(L) iff the p-adic digits of
    alpha sum to more than (p+1)/2, or alpha_0 = 0 and the rest sum to (p+1)/2."""
    dg = digits(d + 1, p)
    return sum(dg) > (p + 1) // 2 or (dg and dg[0] == 0
                                      and sum(dg[1:]) == (p + 1) // 2)


def run(p, m, maxsupport=3):
    g = Zass(p, m)
    bound = (g.top + 1) // 2                     # (p^m+1)/2
    say(f"\n  vect(1; {m}) over F_{p}:  dim = {g.n}, degrees {g.deg[0]}..{g.deg[-1]},"
        f"  bound (p^m+1)/2 = {bound}")
    high = [d for d in g.deg if d >= bound]
    check(f"p={p}, m={m}: every e_i with i >= (p^m+1)/2 is a sandwich",
          all(g.is_sandwich(g.basis_vec(d)) for d in high))
    hom = [d for d in g.deg if g.is_sandwich(g.basis_vec(d))]
    say(f"    homogeneous sandwiches: degrees {hom}")
    below = [d for d in hom if d < bound]
    if below:
        say(f"    *** BELOW the bound: {below}  ---  the bound is not necessary")
    S = span_of_cone(g, maxsupport)
    more = [d for d in S if d not in hom]
    say(f"    degrees in the span of the cone (supports <= {maxsupport}): {S}")
    if more:
        say(f"    *** of which {more} carry NO homogeneous sandwich: they come"
            f" from non-homogeneous ones")
    norm = normalizer(g, S)
    say(f"    normalizer of that span: codimension {g.n - len(norm)}"
        + ("  = L_0" if norm == [d for d in g.deg if d >= 0] else
           f", missing the degrees {[d for d in g.deg if d >= 0 and d not in norm]}"))
    cor = [d for d in g.deg if d >= 0 and cor22(d, p)]
    say(f"    Corollary 2.2 predicts: {cor}")
    say(f"    not reached by any sandwich of support <= {maxsupport}: "
        f"{[d for d in cor if d not in S] or '---'}")


def exhaustive(p, m):
    """The one size at which the whole algebra can be searched."""
    g = Zass(p, m)
    say(f"\n  EXHAUSTIVE search, vect(1; {m}) over F_{p}: all {p}^{g.n} elements")
    sand = [v for v in iproduct(range(p), repeat=g.n)
            if any(v) and g.is_sandwich(list(v))]
    degs = sorted({d for v in sand for d in g.deg if v[g.idx[d]]})
    say(f"    {len(sand)} non-zero sandwiches; the degrees they occupy: {degs}")
    span = [v for v in iproduct(range(p), repeat=g.n)
            if any(v) and all(v[g.idx[d]] == 0 for d in g.deg if d not in degs)]
    check(f"p={p}, m={m}: the cone is exactly the {len(span)} non-zero elements"
          f" of the span of those degrees",
          len(span) == len(sand) and all(g.is_sandwich(list(v)) for v in span))
    norm = normalizer(g, degs)
    check(f"p={p}, m={m}: n_g(s(g)) = L_0, of codimension 1",
          norm == [d for d in g.deg if d >= 0],
          f"s(g) = degrees {degs}")
    cor = [d for d in g.deg if d >= 0 and cor22(d, p)]
    bad = [d for d in cor if d not in degs]
    check(f"p={p}, m={m}: Corollary 2.2 over-predicts", bool(bad),
          f"it gives {cor}, the truth is {degs}; the degrees {bad} carry no"
          f" sandwich component whatsoever")


def main():
    say("=" * 78)
    say("zass.py --- sandwiches in the Zassenhaus algebra vect(1; m)")
    say("=" * 78)
    exhaustive(3, 2)
    run(3, 2)
    run(3, 3)
    run(5, 1)
    run(5, 2)
    run(7, 1)
    say("\n" + "=" * 78)
    say(f"{len(FAILS)} FAILURES: " + "; ".join(FAILS) if FAILS else "all checks passed")
    say("=" * 78)


if __name__ == "__main__":
    main()
