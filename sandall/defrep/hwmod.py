#!/usr/bin/env python3
"""
hwmod.py --- exact computation of the irreducible highest-weight module
L^lambda over a Lie (super)algebra g(A) given by a Cartan matrix A,
over a field K of characteristic p (p = 0 means Q).

Method (no bilinear form, no sign guessing beyond the defining relation).

g(A) = ~g(A)/r, where ~g(A) is generated by e_i, f_i, h_i with
    [e_i, f_j] = delta_{ij} h_i,   [h_i, e_j] = a_{ij} e_j,
    [h_i, f_j] = -a_{ij} f_j,      p(e_i) = p(f_i) = par_i,
and r is the maximal ideal meeting the Cartan subalgebra trivially.  For a
highest weight lambda the irreducible module L^lambda is the quotient of the
Verma module over ~g(A) by the radical N of the contravariant form, and

    N_d = { x : e_k x  in  N_{d-e_k}  for every k },

because iterated e's bring any degree down to 0, where N_0 = 0.  Hence, if
M_d denotes the already-constructed L^lambda_d = Verma_d / N_d, then

    C_d := \\oplus_j  f_j (X) M_{d-e_j}   ->>  M_d,
    M_d  = C_d / { c : E_k(c) = 0 in M_{d-e_k} for all k },

where the operator E_k on C_d is computed from e_k f_j = delta_{kj} h_k +
(-1)^{p_k p_j} f_j e_k, i.e.

    E_k( f_j (X) u ) = delta_{kj} * mu_k(d-e_k) * u
                       + (-1)^{p_k p_j} * F_j( E_k u ).

Everything on the right is known at lower degrees, so the module is built
degree by degree with exact linear algebra only.  Nothing is guessed and the
Serre-type relations never have to be written down: they sit in the radical
automatically.

Degrees d are multidegrees in Z_{>=0}^n counting how many times each f_i was
used; the h_i-eigenvalue on M_d is  lambda_i - sum_j d_j a_{ij}  and the
parity of M_d is  sum_j d_j par_j  mod 2.

Usage:  see selftest() at the bottom, and defrep_check.py for the paper's data.
"""

from fractions import Fraction
from itertools import product


# ---------------------------------------------------------------- fields

class Fp:
    """The prime field F_p (p > 0) or Q (p == 0)."""

    def __init__(self, p):
        self.p = p

    def norm(self, x):
        if self.p:
            return x % self.p
        return x if isinstance(x, Fraction) else Fraction(x)

    def is_zero(self, x):
        if self.p:
            return x % self.p == 0
        return x == 0

    def inv(self, x):
        if self.p:
            return pow(int(x) % self.p, self.p - 2, self.p)
        return 1 / Fraction(x)

    zero = property(lambda self: 0 if self.p else Fraction(0))
    one = property(lambda self: 1 if self.p else Fraction(1))


# ------------------------------------------------------- linear algebra
# Matrices are lists of rows; a row is a list of field elements.

def mat_zero(K, r, c):
    return [[K.zero] * c for _ in range(r)]


def mat_mul(K, A, B):
    if not A or not B:
        return mat_zero(K, len(A), len(B[0]) if B else 0)
    n, m, q = len(A), len(B), len(B[0])
    out = []
    for i in range(n):
        Ai = A[i]
        row = [K.zero] * q
        for k in range(m):
            a = Ai[k]
            if K.is_zero(a):
                continue
            Bk = B[k]
            for j in range(q):
                if not K.is_zero(Bk[j]):
                    row[j] = K.norm(row[j] + a * Bk[j])
        out.append(row)
    return out


def rref(K, A):
    """Reduced row echelon form.  Returns (R, pivots) with R a fresh matrix."""
    R = [row[:] for row in A]
    rows = len(R)
    cols = len(R[0]) if rows else 0
    pivots = []
    r = 0
    for c in range(cols):
        piv = None
        for i in range(r, rows):
            if not K.is_zero(R[i][c]):
                piv = i
                break
        if piv is None:
            continue
        R[r], R[piv] = R[piv], R[r]
        iv = K.inv(R[r][c])
        R[r] = [K.norm(x * iv) for x in R[r]]
        for i in range(rows):
            if i != r and not K.is_zero(R[i][c]):
                f = R[i][c]
                R[i] = [K.norm(R[i][j] - f * R[r][j]) for j in range(cols)]
        pivots.append(c)
        r += 1
        if r == rows:
            break
    return R, pivots


def kernel_basis(K, A, ncols):
    """Basis of the right kernel of A (as a list of column vectors)."""
    if not A:
        return [[K.one if i == j else K.zero for i in range(ncols)]
                for j in range(ncols)]
    R, pivots = rref(K, A)
    free = [c for c in range(ncols) if c not in pivots]
    basis = []
    for fc in free:
        v = [K.zero] * ncols
        v[fc] = K.one
        for r, pc in enumerate(pivots):
            v[pc] = K.norm(-R[r][fc])
        basis.append(v)
    return basis


# ------------------------------------------------------------- the module

class HWModule:
    """The irreducible g(A)-module of highest weight lambda."""

    def __init__(self, A, par, p, lam, maxdim=None, maxheight=None,
                 verbose=False, field=None):
        # `field` overrides the prime field: any object with norm/is_zero/inv/
        # zero/one will do, e.g. ratf.F2alpha for the p = 2 tables with
        # a~parameter.  Then the entries of A and lam may be its elements.
        self.n = len(A)
        self.K = field if field is not None else Fp(p)
        K = self.K
        self.A = [[K.norm(x) for x in row] for row in A]
        self.par = list(par)
        self.lam = [K.norm(x) for x in lam]
        self.maxdim = maxdim
        self.maxheight = maxheight
        self.verbose = verbose
        # dim[d], F[(d, j)] : M_{d-e_j} -> M_d, E[(d, k)] : M_d -> M_{d-e_k}
        self.dim = {}
        self.F = {}
        self.E = {}
        self._build()

    def mu(self, d, i):
        """The h_i-eigenvalue on M_d."""
        K = self.K
        s = self.lam[i]
        for j in range(self.n):
            if d[j]:
                s = K.norm(s - d[j] * self.A[i][j])
        return K.norm(s)

    def _build(self):
        K = self.K
        n = self.n
        zero = tuple([0] * n)
        self.dim[zero] = 1
        height = 0
        total = 1
        while True:
            height += 1
            level = [d for d in self._degrees(height)]
            alive = False
            for d in level:
                m = self._degree(d)
                if m:
                    alive = True
                    total += m
                    if self.maxdim and total > self.maxdim:
                        raise MemoryError("dimension exceeds maxdim=%d" % self.maxdim)
            if self.verbose:
                print("   height %2d: running total %d" % (height, total))
            if not alive:
                break
            if self.maxheight and height >= self.maxheight:
                raise OverflowError(
                    "still alive at height %d (running total %d): the module "
                    "looks infinite-dimensional" % (height, total))
        self.total = total

    def _degrees(self, height):
        """Multidegrees of the given height with all predecessors known."""
        out = set()
        for d, m in self.dim.items():
            if m and sum(d) == height - 1:
                for j in range(self.n):
                    e = list(d)
                    e[j] += 1
                    out.add(tuple(e))
        return sorted(out)

    def _degree(self, d):
        """Construct M_d; returns its dimension."""
        K = self.K
        n = self.n
        blocks = []          # (j, offset, dim of M_{d-e_j})
        off = 0
        for j in range(n):
            dj = self._sub(d, j)
            m = self.dim.get(dj, 0) if dj is not None else 0
            if m:
                blocks.append((j, off, m))
                off += m
        c = off
        if c == 0:
            self.dim[d] = 0
            return 0

        # rows of the stacked operator  E = (E_k)_k  on C_d
        rows = []
        for k in range(n):
            dk = self._sub(d, k)
            if dk is None:
                continue
            mk = self.dim.get(dk, 0)
            if mk == 0:
                continue
            blk = mat_zero(K, mk, c)
            for (j, offj, mj) in blocks:
                dj = self._sub(d, j)
                if j == k:
                    s = self.mu(dk, k)
                    if not K.is_zero(s):
                        for a in range(mj):
                            blk[a][offj + a] = K.norm(blk[a][offj + a] + s)
                # (-1)^{p_k p_j} F_j E_k  on the j-th block
                Ek = self.E.get((dj, k))
                if Ek is not None:
                    djk = self._sub(dj, k)
                    Fj = self.F.get((dk, j))
                    if Fj is not None:
                        comp = mat_mul(K, Fj, Ek)   # M_{d-e_j} -> M_{d-e_k}
                        sgn = -1 if (self.par[k] and self.par[j]) else 1
                        for a in range(mk):
                            for b in range(mj):
                                if not K.is_zero(comp[a][b]):
                                    blk[a][offj + b] = K.norm(
                                        blk[a][offj + b] + sgn * comp[a][b])
            rows.extend(blk)

        ker = kernel_basis(K, rows, c) if rows else \
            [[K.one if i == t else K.zero for i in range(c)] for t in range(c)]
        m = c - len(ker)
        self.dim[d] = m
        if m == 0:
            return 0

        # projection P : C_d ->> M_d with kernel span(ker), and a section S
        P, S = self._projection(ker, c, m)
        for (j, offj, mj) in blocks:
            dj = self._sub(d, j)
            self.F[(d, j)] = [[P[a][offj + b] for b in range(mj)] for a in range(m)]
        for k in range(n):
            dk = self._sub(d, k)
            if dk is None or self.dim.get(dk, 0) == 0:
                continue
            Ek_on_C = None
            # rebuild the k-block of E on C_d, then E_k = (block) . S
            mk = self.dim[dk]
            blk = mat_zero(K, mk, c)
            for (j, offj, mj) in blocks:
                dj = self._sub(d, j)
                if j == k:
                    s = self.mu(dk, k)
                    if not K.is_zero(s):
                        for a in range(mj):
                            blk[a][offj + a] = K.norm(blk[a][offj + a] + s)
                Ek = self.E.get((dj, k))
                if Ek is not None:
                    Fj = self.F.get((dk, j))
                    if Fj is not None:
                        comp = mat_mul(K, Fj, Ek)
                        sgn = -1 if (self.par[k] and self.par[j]) else 1
                        for a in range(mk):
                            for b in range(mj):
                                if not K.is_zero(comp[a][b]):
                                    blk[a][offj + b] = K.norm(
                                        blk[a][offj + b] + sgn * comp[a][b])
            self.E[(d, k)] = mat_mul(K, blk, S)
        return m

    def _projection(self, ker, c, m):
        """P : K^c ->> K^m with kernel span(ker); S a section (P.S = 1)."""
        K = self.K
        # complete ker to a basis of K^c by adding standard vectors
        R, pivots = rref(K, ker) if ker else ([], [])
        free = [j for j in range(c) if j not in pivots]
        assert len(free) == m
        # coordinates on the free positions give the quotient map after
        # eliminating the pivot coordinates
        P = mat_zero(K, m, c)
        for a, fc in enumerate(free):
            P[a][fc] = K.one
        for r, pc in enumerate(pivots):
            for a, fc in enumerate(free):
                # x_pc = -sum R[r][fc] x_fc  on ker; so the induced map on the
                # quotient sends e_pc to  -R[r][.] read on free coordinates
                P[a][pc] = K.norm(-R[r][fc])
        S = mat_zero(K, c, m)
        for a, fc in enumerate(free):
            S[fc][a] = K.one
        # sanity: P.S = 1
        PS = mat_mul(K, P, S)
        for a in range(m):
            for b in range(m):
                want = K.one if a == b else K.zero
                assert K.norm(PS[a][b] - want) == K.zero or K.is_zero(PS[a][b] - want)
        return P, S

    def _sub(self, d, j):
        if d[j] == 0:
            return None
        e = list(d)
        e[j] -= 1
        return tuple(e)

    # ------------------------------------------------------------ results

    def sdim(self):
        ev = od = 0
        for d, m in self.dim.items():
            if not m:
                continue
            par = sum(d[j] * self.par[j] for j in range(self.n)) % 2
            if par:
                od += m
            else:
                ev += m
        return ev, od

    def dimension(self):
        return sum(self.dim.values())

    def is_super(self):
        return any(self.par)

    def describe(self):
        if self.is_super():
            ev, od = self.sdim()
            return "%d|%d" % (ev, od)
        return str(self.dimension())


def irrep(A, par, p, lam, **kw):
    return HWModule(A, par, p, lam, **kw)


# ---------------------------------------------------------------- selftest

def selftest():
    ok = True

    def check(name, got, want):
        nonlocal ok
        good = (got == want)
        ok = ok and good
        print("  %-46s %-12s %s" % (name, got, "OK" if good else "WRONG, want %s" % want))

    print("sl(3) over Q")
    sl3 = [[2, -1], [-1, 2]]
    check("L(1,0)", irrep(sl3, [0, 0], 0, [1, 0]).describe(), "3")
    check("L(0,1)", irrep(sl3, [0, 0], 0, [0, 1]).describe(), "3")
    check("L(1,1) = ad", irrep(sl3, [0, 0], 0, [1, 1]).describe(), "8")
    check("L(2,0)", irrep(sl3, [0, 0], 0, [2, 0]).describe(), "6")
    check("L(2,2)", irrep(sl3, [0, 0], 0, [2, 2]).describe(), "27")

    print("sl(3) over F_3")
    check("L(1,1)", irrep(sl3, [0, 0], 3, [1, 1]).describe(), "7")
    check("L(0,1)", irrep(sl3, [0, 0], 3, [0, 1]).describe(), "3")
    check("L(0,2)", irrep(sl3, [0, 0], 3, [0, 2]).describe(), "6")
    check("L(1,2)", irrep(sl3, [0, 0], 3, [1, 2]).describe(), "15")
    check("L(2,2)", irrep(sl3, [0, 0], 3, [2, 2]).describe(), "27")

    print("o(5) = sp(4) over Q,  A = [[2,-1],[-2,2]]")
    o5 = [[2, -1], [-2, 2]]
    check("L(1,0)", irrep(o5, [0, 0], 0, [1, 0]).describe(), "5")
    check("L(0,1)", irrep(o5, [0, 0], 0, [0, 1]).describe(), "4")
    check("L(1,1)", irrep(o5, [0, 0], 0, [1, 1]).describe(), "16")

    print("g(2) over Q,  A = [[2,-1],[-3,2]]")
    g2 = [[2, -1], [-3, 2]]
    check("L(1,0)", irrep(g2, [0, 0], 0, [1, 0]).describe(), "14")
    check("L(0,1)", irrep(g2, [0, 0], 0, [0, 1]).describe(), "7")
    check("L(0,2)", irrep(g2, [0, 0], 0, [0, 2]).describe(), "27")
    check("L(1,1)", irrep(g2, [0, 0], 0, [1, 1]).describe(), "64")

    print("osp(1|2) over Q, odd generator")
    # A = [[1]]: alpha(h) = 1, so the adjoint has highest weight 2 (= 2 alpha)
    check("A=[[1]], L(2) = ad", irrep([[1]], [1], 0, [2]).describe(), "3|2")
    check("A=[[1]], L(4)", irrep([[1]], [1], 0, [4]).describe(), "5|4")
    # A = [[2]]: alpha(h) = 2, so the adjoint has highest weight 4
    check("A=[[2]], L(4) = ad", irrep([[2]], [1], 0, [4]).describe(), "3|2")

    print("sl(1|2) over Q,  A = [[0,-1],[-1,2]], first root odd")
    sl12 = [[0, -1], [-1, 2]]
    check("L(1,0) = tautological", irrep(sl12, [1, 0], 0, [1, 0]).describe(), "1|2")

    print("\n%s" % ("ALL OK" if ok else "FAILURES ABOVE"))
    return ok


if __name__ == "__main__":
    import sys
    selftest()
