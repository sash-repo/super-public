#!/usr/bin/env python3
"""Two more numbers quoted in the text.

(1) dim H^1 of the divided power de Rham complex of O(m;1) at p = 2, and the
    dimension of h(omega) for the standard shape
        omega_Pi = dx_1^{(2)} + dx_2dx_3 + dx_4dx_5 + ...   (m odd)
        omega_Pi = dx_1^{(2)} + dx_1dx_{1+m/2} + ...        (m even)
    against 2^m - 1 + m.

(2) the ideal structure of the two m = 3 representatives: the smallest proper
    ideal of the last term of the derived series, over F_2.
"""
from nalt2 import *
from hamcheck import de_rham_h1
from run1 import show_form


def std_form(alg):
    m = alg.m
    om = {('b', 0): alg.one}
    if m % 2:
        for i in range((m - 1) // 2):
            om[('a', 1 + 2 * i, 2 + 2 * i)] = alg.one
    else:
        h = m // 2
        for i in range(h):
            om[('a', i, i + h)] = alg.one
    return om


def ideal_dims(alg, basis):
    """dimensions of the ideals generated by single elements."""
    n = len(basis)
    out = set()
    for bits in range(1, 1 << n):
        v = [0] * alg.m
        for i in range(n):
            if (bits >> i) & 1:
                for k in range(alg.m):
                    v[k] ^= basis[i][k]
        ideal = [v]
        grew = True
        while grew:
            grew = False
            new = reduce_basis(alg, ideal +
                               [bracket(alg, b, w) for b in basis for w in ideal])
            if len(new) > len(ideal):
                ideal, grew = new, True
        out.add(len(ideal))
    return sorted(out)


def last_term(alg, h):
    cur = h
    for _ in range(5):
        nxt = reduce_basis(alg, derived(alg, cur))
        if len(nxt) == len(cur):
            return cur
        cur = nxt
    return cur


print("(1) m | dim O | dim H^1 | dim h(omega_Pi) | 2^m - 1 + m")
for m in range(1, 6):
    alg = Alg(m, (1,) * m)
    om = std_form(alg)
    assert not d2(alg, om) and nondeg(alg, om), "standard shape check"
    h = preserving_algebra(alg, om)
    print("    %d | %5d | %7d | %15d | %d"
          % (m, alg.dim, de_rham_h1(alg), len(h), 2 ** m - 1 + m))

print()
print("(2) the two m = 3 representatives")
alg = Alg(3, (1, 1, 1))
for name, om in [("standard  dx_1^{(2)} + dx_2dx_3",
                  {('b', 0): alg.one, ('a', 1, 2): alg.one}),
                 ("second    dx_1^{(2)} + x_1 dx_1dx_2 + dx_2dx_3",
                  {('b', 0): alg.one, ('a', 0, 1): alg.gen(0),
                   ('a', 1, 2): alg.one})]:
    h = preserving_algebra(alg, om)
    lt = last_term(alg, h)
    print("  %s" % name)
    print("     derived series %s ; last term dim %d ; dims of the ideals "
          "generated by single elements: %s"
          % (derived_series(alg, h), len(lt), ideal_dims(alg, lt)))
