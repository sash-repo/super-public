#!/usr/bin/env python3
"""p = 2:  the residual splitting of the census classes, and the normal shapes.

The census (shomog.py) counts the classes of homogeneous closed non-degenerate
2-forms over O(m|n;1) and separates them by three invariants: the pair of types
of the two diagonal blocks of the constant Gram matrix, the class of omega in
H^2, and the shearing vector.  Those three leave groups of classes unseparated
-- 6 and 4 over O(2|1;1), 3 and 2 over O(1|2;1) -- and the census reported the
splitting without naming it.

This engine names it.  Two things are computed for every class:

  1) the SHORTEST representative in the orbit, i.e. the normal shape one can
     print, instead of the arbitrary orbit representative the census returned;

  2) the isomorphism invariants of the Lie superalgebra h(omega) AS A p = 2
     SUPERALGEBRA, i.e. with the squaring x |-> x^2 on the odd part, which is
     part of the structure at p = 2 and is invisible both to the ungraded
     problem and to the three invariants above:

        sdim h,  sdim [h,h],  sdim of the derived series,
        dim Span{x^2 | x odd},     -- the image of the squaring,
        N2(h) = #{x odd | x^2 = 0} -- the p = 2 analog of the count N(g) that
                                      separates the two periplectic algebras
                                      in characteristic 3,
        sdim of the center.

Everything is exact over F_2.  Output: ssplit.log.
"""
import sys, os, time, itertools
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sform as S
from scensus import (build, elementary_autos, all_autos, gen_matrix,
                     apply_map, show, name, invertible_table)
from shomog import homogeneous_nondeg, block_types, h2_classes

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = []


# --------------------------------------------------------------- vector fields
def act(A, D, f):
    """D(f) for a function f (p = 2, so no signs to get wrong)."""
    return A.lie(D)(f)


def brk(A, D, E):
    """[D,E] as a vector field; p = 2."""
    fs = tuple(A.add(act(A, D, E[0][i]), act(A, E, D[0][i]))
               for i in range(A.m))
    gs = tuple(A.add(act(A, D, E[1][j]), act(A, E, D[1][j]))
               for j in range(A.n))
    return (fs, gs, (D[2] + E[2]) % 2)


def square(A, D):
    """D^2 = D o D for odd D; p = 2.  This is the squaring of the superalgebra."""
    assert D[2] == 1
    fs = tuple(act(A, D, D[0][i]) for i in range(A.m))
    gs = tuple(act(A, D, D[1][j]) for j in range(A.n))
    return (fs, gs, 0)


def addf(A, D, E):
    fs = tuple(A.add(D[0][i], E[0][i]) for i in range(A.m))
    gs = tuple(A.add(D[1][j], E[1][j]) for j in range(A.n))
    return (fs, gs, D[2])


def vecof(A, D, idx):
    return S.vf_vec(A, D, idx)


def span_dim(rows):
    ech = []
    for v in rows:
        w = list(v)
        for b in ech:
            hb = b[0]
            if w[hb]:
                for t in range(len(w)):
                    w[t] ^= b[1][t]
        nz = [t for t in range(len(w)) if w[t]]
        if nz:
            ech.append((nz[0], w))
    return len(ech)


def echelon(rows):
    ech = []
    for v in rows:
        w = list(v)
        for hb, b in ech:
            if w[hb]:
                for t in range(len(w)):
                    w[t] ^= b[t]
        nz = [t for t in range(len(w)) if w[t]]
        if nz:
            ech.append((nz[0], w))
            ech.sort(key=lambda t: t[0])
    return ech


def in_span(ech, v):
    w = list(v)
    for hb, b in ech:
        if w[hb]:
            for t in range(len(w)):
                w[t] ^= b[t]
    return not any(w)


# ------------------------------------------------------------------ invariants
def superalg_invariants(A, om, idx):
    """the isomorphism invariants of h(omega) as a p = 2 Lie superalgebra."""
    ev, od, bas = S.preserving(A, om)
    even = [D for D in bas if D[2] == 0]
    odd = [D for D in bas if D[2] == 1]
    assert len(even) == ev and len(odd) == od

    def sd(fields):
        e = span_dim([vecof(A, D, idx) for D in fields if D[2] == 0])
        o = span_dim([vecof(A, D, idx) for D in fields if D[2] == 1])
        return (e, o)

    # the derived series, in the two conventions
    def derived(fields, with_squares):
        out = []
        for a in range(len(fields)):
            for b in range(a, len(fields)):
                out.append(brk(A, fields[a], fields[b]))
        if with_squares:
            oddf = [D for D in fields if D[2] == 1]
            # the squaring is not linear: s(x+y) = s(x)+s(y)+[x,y], so the span
            # of the image is generated by the squares of a basis together with
            # the brackets, which are already in the list
            for D in oddf:
                out.append(square(A, D))
        return out

    def series(fields, with_squares, steps=4):
        cur = list(fields)
        out = []
        for _ in range(steps):
            nxt = derived(cur, with_squares)
            # reduce to a basis to keep the lists short
            rows = [(vecof(A, D, idx), D) for D in nxt]
            eve = [r for r in rows if r[1][2] == 0]
            odr = [r for r in rows if r[1][2] == 1]
            keep = []
            for group in (eve, odr):
                ech = []
                for v, D in group:
                    w = list(v)
                    for hb, b in ech:
                        if w[hb]:
                            for t in range(len(w)):
                                w[t] ^= b[t]
                    nz = [t for t in range(len(w)) if w[t]]
                    if nz:
                        ech.append((nz[0], w))
                        ech.sort(key=lambda t: t[0])
                        keep.append(D)
            out.append(sd(keep))
            if sd(keep) == sd(cur):
                break
            cur = keep
        return out

    ser_br = series(even + odd, False)
    ser_sq = series(even + odd, True)

    # the squaring map on the odd part: image and zero set
    sqrows = [vecof(A, square(A, D), idx) for D in odd]
    # the span of ALL squares, not only of those of a basis
    allsq = []
    Ncone = 0
    for bits in range(1 << len(odd)):
        x = None
        for k in range(len(odd)):
            if (bits >> k) & 1:
                x = odd[k] if x is None else addf(A, x, odd[k])
        if x is None:
            Ncone += 1                     # 0^2 = 0
            continue
        s = square(A, x)
        v = vecof(A, s, idx)
        allsq.append(v)
        if not any(v):
            Ncone += 1
    dimsq = span_dim(allsq)

    # the center
    cent = []
    for pr, fields in ((0, even), (1, odd)):
        if not fields:
            cent.append(0)
            continue
        rows = []
        for D in fields:
            row = []
            for E in even + odd:
                row.extend(vecof(A, brk(A, D, E), idx))
            rows.append(row)
        if not rows[0]:
            cent.append(len(fields))
            continue
        T = [[rows[k][i] for k in range(len(rows))] for i in range(len(rows[0]))]
        ns = S.nullspace_p(T, 2)
        cent.append(len(ns))

    # the derivations of h(omega): of the bracket alone, and of the bracket
    # together with the squaring, which is the right notion at p = 2
    der = derivations(A, even, odd, idx, with_squaring=False)
    ders = derivations(A, even, odd, idx, with_squaring=True)

    # the fibers of the squaring: N2 above is the fiber over 0 alone
    fib = {}
    for bits in range(1 << len(odd)):
        x = None
        for k in range(len(odd)):
            if (bits >> k) & 1:
                x = odd[k] if x is None else addf(A, x, odd[k])
        v = tuple(vecof(A, square(A, x), idx)) if x is not None else \
            tuple([0] * ((A.m + A.n) * len(idx)))
        fib[v] = fib.get(v, 0) + 1
    fibprof = tuple(sorted(fib.values(), reverse=True))

    # the centralizer profile: dim of the centralizer of each element
    def cprof(fields, over):
        prof = {}
        for bits in range(1 << len(fields)):
            x = None
            for k in range(len(fields)):
                if (bits >> k) & 1:
                    x = fields[k] if x is None else addf(A, x, fields[k])
            if x is None:
                continue
            rows = [vecof(A, brk(A, x, E), idx) for E in over]
            T = [[rows[k][i] for k in range(len(rows))]
                 for i in range(len(rows[0]))]
            ns = S.nullspace_p(T, 2) if rows and rows[0] else []
            prof[len(ns)] = prof.get(len(ns), 0) + 1
        return tuple(sorted(prof.items()))

    allf = even + odd
    prof_od = cprof(odd, allf) if odd else ()
    prof_ev = cprof(even, allf) if even else ()

    return dict(sdim=(ev, od), ser_br=ser_br, ser_sq=ser_sq,
                dimsq=dimsq, Ncone=Ncone, center=tuple(cent),
                der=der, ders=ders, fib=fibprof,
                prof_od=prof_od, prof_ev=prof_ev)


def conformal(A, om):
    """dim {D | L_D omega in K omega} - dim h(omega); at p = 2 the only scalar
    available is 1, so this is 1 exactly when some field scales omega."""
    ev, od, bas = S.preserving(A, om)
    deg2 = A.basis(2)
    i2 = {mm: i for i, mm in enumerate(deg2)}
    omv = S.vec(A, om, i2)
    out = 0
    for pr in (0, 1):
        B = S.vfield_basis(A, pr)
        rows = [S.vec(A, A.lie(D)(om), i2) for D in B]
        # is omega in the span of the L_D omega ?
        r0 = S.rank_p(rows, 2)
        if S.rank_p(rows + [omv], 2) == r0 and any(omv):
            out += 1
    return out


def derivations(A, even, odd, idx, with_squaring):
    """sdim Der h, over F_2.  A derivation is a parity-homogeneous linear map
    phi with phi([a,b]) = [phi a, b] + [a, phi b]; at p = 2 it must also respect
    the squaring: phi(x^2) = [x, phi x] for odd x."""
    bas = even + odd
    ne, no = len(even), len(odd)
    rows_all = [vecof(A, D, idx) for D in bas]
    ech = echelon(rows_all)

    def coords(D):
        """D in the basis `bas`, by echelon reduction with bookkeeping."""
        return solve_coords(rows_all, vecof(A, D, idx))

    # bracket table in coordinates
    br = [[coords(brk(A, bas[a], bas[b])) for b in range(len(bas))]
          for a in range(len(bas))]
    sq = [coords(square(A, D)) for D in odd]

    out = []
    for phipar in (0, 1):
        # unknowns: phi(bas[k]) = sum_l c[k][l] bas[l], with the parity of
        # bas[l] equal to p(bas[k]) + phipar
        cols = []
        for k in range(len(bas)):
            pk = bas[k][2]
            tgt = (pk + phipar) % 2
            for l in range(len(bas)):
                if bas[l][2] == tgt:
                    cols.append((k, l))
        ci = {kl: i for i, kl in enumerate(cols)}
        eqs = []
        for a in range(len(bas)):
            for b in range(a, len(bas)):
                target = br[a][b]
                for t in range(len(bas)):     # one equation per coordinate
                    row = [0] * len(cols)
                    # [phi a, b] : sum_l c[a][l] [bas_l, bas_b]
                    for l in range(len(bas)):
                        if (a, l) in ci and br[l][b][t]:
                            row[ci[(a, l)]] ^= 1
                    for l in range(len(bas)):
                        if (b, l) in ci and br[a][l][t]:
                            row[ci[(b, l)]] ^= 1
                    # phi([a,b]) : sum_k target[k] * c[k][t']
                    for k in range(len(bas)):
                        if target[k] and (k, t) in ci:
                            row[ci[(k, t)]] ^= 1
                    if any(row):
                        eqs.append(row)
        if with_squaring:
            for j in range(no):
                k = ne + j                     # index of odd[j] in bas
                for t in range(len(bas)):
                    row = [0] * len(cols)
                    # phi(s(x)) : sum_r sq[j][r] c[r][t]
                    for r in range(len(bas)):
                        if sq[j][r] and (r, t) in ci:
                            row[ci[(r, t)]] ^= 1
                    # [x, phi x] : sum_l c[k][l] [bas_k, bas_l]
                    for l in range(len(bas)):
                        if (k, l) in ci and br[k][l][t]:
                            row[ci[(k, l)]] ^= 1
                    if any(row):
                        eqs.append(row)
        if not eqs:
            out.append(len(cols))
            continue
        ns = S.nullspace_p(eqs, 2)      # {c | eqs . c = 0}, c indexed by cols
        assert len(ns) <= len(cols)
        out.append(len(ns))
    return tuple(out)


def solve_coords(rows, target):
    """write `target` in the basis `rows` over F_2; the rows are independent."""
    n = len(rows)
    L = len(target)
    # augmented echelon
    ech = []
    for k, r in enumerate(rows):
        w = list(r)
        c = [0] * n
        c[k] = 1
        for hb, b, cb in ech:
            if w[hb]:
                for t in range(L):
                    w[t] ^= b[t]
                for t in range(n):
                    c[t] ^= cb[t]
        nz = [t for t in range(L) if w[t]]
        assert nz, "the fields given are not independent"
        ech.append((nz[0], w, c))
        ech.sort(key=lambda t: t[0])
    w = list(target)
    c = [0] * n
    for hb, b, cb in ech:
        if w[hb]:
            for t in range(L):
                w[t] ^= b[t]
            for t in range(n):
                c[t] ^= cb[t]
    assert not any(w), "the element is not in the span of the algebra"
    return c


def h2_orbit(red, maps, v):
    """the orbit of [omega] in H^2 under the parity-preserving group, labeled by
    the smallest cocycle in it.  This is Skryabin's invariant refined: the census
    used only whether the class vanishes."""
    c = red(v)
    seen = {c}
    stack = [c]
    while stack:
        w = stack.pop()
        for imgs in maps:
            z = red(apply_map(imgs, w))
            if z not in seen:
                seen.add(z)
                stack.append(z)
    return (len(seen), min(seen))


def orbit_of(v, maps):
    seen = {v}
    stack = [v]
    while stack:
        w = stack.pop()
        for imgs in maps:
            z = apply_map(imgs, w)
            if z not in seen:
                seen.add(z)
                stack.append(z)
    return seen


def run(m, n, LOG):
    def say(*a):
        s = " ".join(str(x) for x in a)
        print(s)
        LOG.write(s + "\n")
        LOG.flush()

    A = S.Om(m, n, 2, (1,) * m, dh=2, dxh=2)
    B2, idx, zbas, gram_bits, G = build(A)
    gens = elementary_autos(A, graded=True)
    maps = [gen_matrix(A, phi, B2, idx) for phi in gens]
    red = h2_classes(A, B2, idx, None, maps)
    mons = A.fun_basis()
    fidx = {mm: i for i, mm in enumerate(mons)}

    say("")
    say("=" * 78)
    say(f"  O({m}|{n};1), p = 2")
    for par, pname in ((0, "EVEN"), (1, "ODD")):
        el, dz = homogeneous_nondeg(A, zbas, gram_bits, G, par)
        if not el:
            continue
        left = set(el)
        classes = []
        while left:
            s = next(iter(left))
            orb = orbit_of(s, maps)
            best = min(orb, key=lambda v: (bin(v).count("1"), v))
            classes.append((best, len(orb)))
            left -= orb
        say(f"    {pname} forms: {len(el)}, {len(classes)} class(es)")
        rows = []
        for rep, size in sorted(classes, key=lambda t: (bin(t[0]).count("1"),
                                                        t[0])):
            om = show(A, rep, B2)
            bt = block_types(A, om)
            nz = red(rep) != 0
            inv = superalg_invariants(A, om, fidx)
            inv["h2"] = h2_orbit(red, maps, rep)
            inv["conf"] = conformal(A, om)
            rows.append((rep, size, om, bt, nz, inv))
            TEX.append(((m, n), par, rep, size, om, A, inv))
        # group by the three census invariants
        groups = {}
        for r in rows:
            groups.setdefault((r[3], r[4]), []).append(r)
        for key in sorted(groups, key=lambda k: (k[0], k[1])):
            bt, nz = key
            say(f"      GROUP: x-block {'alt' if bt[0] else 'non-alt'}, "
                f"xi-block {'alt' if bt[1] else 'non-alt'}, "
                f"[omega] {'!= 0' if nz else '= 0'}   "
                f"({len(groups[key])} class(es))")
            seen, seenh2 = {}, {}
            for rep, size, om, _, _, inv in groups[key]:
                sig = (inv["sdim"], tuple(inv["ser_br"]), tuple(inv["ser_sq"]),
                       inv["dimsq"], inv["Ncone"], inv["center"],
                       inv["der"], inv["ders"], inv["fib"],
                       inv["prof_od"], inv["prof_ev"])
                seen.setdefault(sig, []).append((rep, size, om))
                seenh2.setdefault(sig + (inv["h2"], inv["conf"]), []).append(rep)
                say(f"        |orbit|={size:6d}  sdim h = {inv['sdim']}  "
                    f"[h,h]-series {inv['ser_br']}  sq-series {inv['ser_sq']}")
                say(f"           dim Span(squares) = {inv['dimsq']}  "
                    f"N2 = {inv['Ncone']}  sdim z(h) = {inv['center']}  "
                    f"sdim Der = {inv['der']}  Der_s = {inv['ders']}  "
                    f"conf = {inv['conf']}  H^2-orbit {inv['h2']}")
                say(f"           squaring fibers {inv['fib']}")
                say(f"           centralizers odd {inv['prof_od']} "
                    f"even {inv['prof_ev']}")
                say(f"           omega = {name(A, om)}")
            say(f"        --> {len(seen)} signature(s) among "
                f"{len(groups[key])} class(es) by the superalgebra alone: "
                f"{'SEPARATED' if len(seen)==len(groups[key]) else 'NOT separated'}"
                f";  with the H^2-orbit: {len(seenh2)} "
                f"{'SEPARATED' if len(seenh2)==len(groups[key]) else 'NOT separated'}")
            for sig, mem in seenh2.items():
                if len(mem) > 1:
                    say(f"            tied: {len(mem)} classes with "
                        f"sdim {sig[0]}, N2 = {sig[4]}, H^2-orbit {sig[-1]}")


def texname(A, om):
    """the form in TeX, in the notation of the text."""
    gn = ([f"x_{i+1}" for i in range(A.m)] + [f"\\xi_{j+1}" for j in range(A.n)])
    dn = ([f"dx_{i+1}" for i in range(A.m)] + [f"d\\xi_{j+1}" for j in range(A.n)])
    from scensus import gen_index, dgen_index
    gi, dgi = gen_index(A), dgen_index(A)
    terms = []
    for mon in sorted(om):
        fun = "".join(gn[a] for a, g in enumerate(gi) if mon[g])
        form = []
        for k, g in enumerate(dgi):
            if mon[g] == 2:
                form.append(f"\\left(d{gn[k]}\\right)^{{(2)}}")
            elif mon[g] == 1:
                form.append(dn[k])
        terms.append(fun + ("\\," if fun else "") + "".join(form))
    return "+".join(terms) if terms else "0"


def textable(rows, out):
    """the table of normal shapes, grouped by superdimension, in two blocks."""
    def block(sel, f):
        last = None
        for (m, n), par, rep, size, om, A, inv in rows:
            if not sel(m + n):
                continue
            head = f"$({m}|{n})$" if (m, n) != last else ""
            last = (m, n)
            ser = ",\\ ".join(f"{a}|{b}" for a, b in inv["ser_sq"])
            f.write(f"{head} & ${texname(A, om)}$ & ${size}$ & "
                    f"${inv['Ncone']}$ & ${inv['dimsq']}$ & ${ser}$ & "
                    f"${inv['h2'][0]}$"
                    + (" & odd" if par else " & ") + "\\\\\n")
    with open(os.path.join(HERE, "ssplit-table1.tex"), "w") as f:
        block(lambda M: M <= 2, f)
    with open(os.path.join(HERE, "ssplit-table2.tex"), "w") as f:
        block(lambda M: M == 3, f)


def controls(m, n, LOG):
    """the two controls the statement rests on:

    1) h(omega) is closed under the bracket AND under the squaring -- i.e. the
       structure whose invariants we compute really lives on h(omega);
    2) the invariants are constant on an orbit: applying an automorphism to
       omega must not change any of them.  This is the control that makes them
       invariants rather than functions of the representative.
    """
    def say(*a):
        s = " ".join(str(x) for x in a)
        print(s)
        LOG.write(s + "\n")
        LOG.flush()

    A = S.Om(m, n, 2, (1,) * m, dh=2, dxh=2)
    B2, idx, zbas, gram_bits, G = build(A)
    gens = elementary_autos(A, graded=True)
    maps = [gen_matrix(A, phi, B2, idx) for phi in gens]
    mons = A.fun_basis()
    fidx = {mm: i for i, mm in enumerate(mons)}
    deg2 = A.basis(2)
    i2 = {mm: i for i, mm in enumerate(deg2)}
    nclosed = nsame = ntested = 0
    for par in (0, 1):
        el, _ = homogeneous_nondeg(A, zbas, gram_bits, G, par)
        if not el:
            continue
        left = set(el)
        while left:
            s = next(iter(left))
            orb = orbit_of(s, maps)
            left -= orb
            rep = min(orb, key=lambda v: (bin(v).count("1"), v))
            om = show(A, rep, B2)
            ev, od, bas = S.preserving(A, om)
            odd = [D for D in bas if D[2] == 1]
            for a in range(len(bas)):
                for b in range(a, len(bas)):
                    assert not A.lie(brk(A, bas[a], bas[b]))(om)
                    nclosed += 1
            for D in odd:
                assert not A.lie(square(A, D))(om)
                nclosed += 1
            base = superalg_invariants(A, om, fidx)
            base.pop("der"), base.pop("ders")
            # the same invariants at three other points of the orbit
            others = sorted(orb)[:3]
            for v in others:
                om2 = show(A, v, B2)
                inv2 = superalg_invariants(A, om2, fidx)
                inv2.pop("der"), inv2.pop("ders")
                assert inv2 == base, f"invariant moved inside an orbit, {m}|{n}"
                nsame += 1
            ntested += 1
    say(f"  O({m}|{n};1): {ntested} classes; h(omega) closed under bracket and "
        f"squaring in {nclosed} tests; the invariants agree at {nsame} further "
        f"points of the orbits")


if __name__ == "__main__":
    LOG = open(os.path.join(HERE, "ssplit.log"), "w")
    LOG.write("The residual splitting of the census classes, p = 2, u = 1\n")
    t0 = time.time()
    for M in (1, 2, 3):
        for n in range(0, M + 1):
            run(M - n, n, LOG)
    LOG.write("\nCONTROLS\n")
    print("\nCONTROLS")
    for M in (1, 2, 3):
        for n in range(0, M + 1):
            controls(M - n, n, LOG)
    textable(TEX, None)
    LOG.write(f"\ntotal {time.time()-t0:.1f} s\n")
    LOG.close()
