"""Sec. 4.7.7 of [P]: the "additional lattices" that "do not give new r-groups".

Part 1 (this file): exact arithmetic in Q(zeta_24).
  * builds every group K of the Case-2 list of Sec. 4.7.6 of [P] from the
    vectors e_1,...,e_s of Table 2 of [P], checks its order,
  * computes mu_j, the b_jk, the c_jk, the ring Z[Tr K],
  * enumerates the chains Delta_1 <= Delta_2 <= ... admitted by the algorithm
    of Sec. 4.7.6 and counts the resulting lattices; compares with the number of
    rows of Table 2 -- this reproduces Popov's list of the four exceptional K,
  * checks that every enumerated lattice is a K-invariant root lattice
    (exactly, with a transcendental modulus tau),
  * exhibits, for each of the four exceptional K, an element Q of GL(V) with
    QKQ^{-1} = K which is not in C^* K, and computes its action on the lattices,
    thereby matching the additional lattices with the rows of Table 2.

Run: ./venv/bin/python check_477.py   (no dependencies beyond the stdlib)
"""
from fractions import Fraction as Fr
from itertools import product

from lat24 import (F, ZERO, ONE, I, OMEGA, SQ2, SQ3, ZP, fadd, fsub, fneg, fscal,
                   fmul, fdiv, finv, fconj, fis0, feq, fnum, fstr,
                   vadd, vsub, vscal, herm, mat_apply, mat_mul, mat_id, mat_eq,
                   mat_inv, mat_trace, refl, group_gen, DEG)

OUT = []
CHECKS = [0, 0]


def say(s=""):
    OUT.append(s)
    print(s)


def check(ok, what):
    CHECKS[0] += 1
    if ok:
        CHECKS[1] += 1
    say("   [%s] %s" % ("ok " if ok else "FAIL", what))
    return ok


# --------------------------------------------------------------- small tools
def E(n, k):
    return tuple(ONE if j == k else ZERO for j in range(n))


def lin(n, *pairs):
    v = [ZERO] * n
    for (a, k) in pairs:
        v[k] = fadd(v[k], a)
    return tuple(v)


HALF = Fr(1, 2)
INVSQ2 = fscal(HALF, SQ2)
MU2 = fneg(ONE)
MU3 = OMEGA
MU4 = I

# ------------------------------------------------------------ the group data
# Every entry: (name, n, [e_j], [mu_j], expected order, rows of Table 2)


def group_data():
    D = []

    def g_m1s(m, s):
        """K_2 of type G(m,1,s): e_1 = eps_1 (order m), e_j = (eps_{j-1}-eps_j)/sqrt2."""
        n = s
        es = [E(n, 0)]
        for j in range(1, s):
            es.append(lin(n, (INVSQ2, j - 1), (fneg(INVSQ2), j)))
        mus = [{2: MU2, 3: MU3, 4: MU4, 6: fneg(OMEGA)}[m]] + [MU2] * (s - 1)
        order = m ** s
        for k in range(1, s + 1):
            order *= k
        return ("G(%d,1,%d)" % (m, s), n, es, mus, order)

    D.append(g_m1s(2, 2) + (3,))
    D.append(g_m1s(2, 3) + (5,))
    D.append(g_m1s(3, 2) + (2,))
    D.append(g_m1s(4, 2) + (2,))

    # K_2 of type G(6,6,2): the dihedral group of order 12
    n = 2
    e1 = vscal(INVSQ2, lin(n, (fadd(ONE, OMEGA), 0), (fneg(ONE), 1)))
    e2 = lin(n, (INVSQ2, 0), (fneg(INVSQ2), 1))
    D.append(("G(6,6,2)", 2, [e1, e2], [MU2, MU2], 12, 4))

    # K_5: e_1 = eps_1, e_2 = ((1-omega)/3)(sqrt2 eps_1 + eps_2), both of order 3
    c = fscal(Fr(1, 3), fsub(ONE, OMEGA))
    e1 = E(2, 0)
    e2 = lin(2, (fmul(c, SQ2), 0), (c, 1))
    D.append(("K_5", 2, [e1, e2], [MU3, MU3], 72, 1))

    # K_26: e_1 = ((1-omega^2)/3)(eps_1+eps_2+eps_3), e_2 = eps_3,
    #       e_3 = (eps_2-eps_3)/sqrt2
    c = fscal(Fr(1, 3), fsub(ONE, fmul(OMEGA, OMEGA)))
    e1 = lin(3, (c, 0), (c, 1), (c, 2))
    e2 = E(3, 2)
    e3 = lin(3, (INVSQ2, 1), (fneg(INVSQ2), 2))
    D.append(("K_26", 3, [e1, e2, e3], [MU3, MU3, MU2], 1296, 2))

    # K_28 = W(F_4)
    n = 4
    e1 = lin(n, (INVSQ2, 1), (fneg(INVSQ2), 2))
    e2 = lin(n, (INVSQ2, 2), (fneg(INVSQ2), 3))
    e3 = E(n, 3)
    h = Fr(1, 2)
    e4 = lin(n, (fscal(h, ONE), 0), (fscal(-h, ONE), 1),
             (fscal(-h, ONE), 2), (fscal(-h, ONE), 3))
    D.append(("K_28 = F_4", 4, [e1, e2, e3, e4], [MU2] * 4, 1152, 3))
    return D


# ------------------------------------------------------------ the ring Z[TrK]
def ring_of_traces(K):
    """Return 'Z', 'Z[i]', 'Z[omega]' -- the ring generated by the traces."""
    trs = {mat_trace(g) for g in K}
    def in_span(x, theta):
        # x = a + b theta with a,b in Z ?
        for a in range(-12, 13):
            for b in range(-12, 13):
                if feq(x, fadd(fscal(a, ONE), fscal(b, theta))):
                    return True
        return False
    if all(in_span(t, ZERO) for t in trs):
        return "Z", ZERO
    if all(in_span(t, I) for t in trs):
        return "Z[i]", I
    if all(in_span(t, OMEGA) for t in trs):
        return "Z[omega]", OMEGA
    return "?", None


# ------------------------------------------- lattices in C with a modulus tau
# A rank-2 lattice Delta in C is stored as a 2x2 rational matrix B: its
# Z-basis is  B[0][0]*u + B[0][1]*v ,  B[1][0]*u + B[1][1]*v , where (u,v) is
# (1,tau) when Z[Tr K] = Z and (1,theta) when Z[Tr K] = Z[theta].

def hnf(B):
    """Hermite normal form of a rational 2x2 basis matrix (rows = generators)."""
    from math import gcd
    den = 1
    for row in B:
        for x in row:
            den = den * x.denominator // gcd(den, x.denominator)
    M = [[int(x * den) for x in row] for row in B]
    # integer HNF of a 2x2 matrix (row style, lower triangular)
    a, b = M[0]
    c, d = M[1]
    while c != 0:
        q = a // c if c else 0
        a, b, c, d = c, d, a - q * c, b - q * d
    if a < 0:
        a, b = -a, -b
    if d < 0:
        c, d = -c, -d
    if d != 0:
        b %= d
    if a == 0 and c == 0:
        raise ValueError("degenerate")
    return ((Fr(a, den), Fr(b, den)), (Fr(c, den), Fr(d, den)))


def lat_eq(A, B):
    return hnf(A) == hnf(B)


def lat_scale(q, B):
    return tuple(tuple(Fr(q) * x for x in row) for row in B)


def lat_index(A, B):
    """[B : A] for A <= B, as a rational number det(A)/det(B)."""
    dA = A[0][0] * A[1][1] - A[0][1] * A[1][0]
    dB = B[0][0] * B[1][1] - B[0][1] * B[1][0]
    return abs(dA / dB)


def sub_of(A, B):
    """is A contained in B ? (rows of A integral in the basis of B)"""
    d = B[0][0] * B[1][1] - B[0][1] * B[1][0]
    for row in A:
        x = (row[0] * B[1][1] - row[1] * B[1][0]) / d
        y = (-row[0] * B[0][1] + row[1] * B[0][0]) / d
        if x.denominator != 1 or y.denominator != 1:
            return False
    return True


def mult_matrix(c, u, v):
    """matrix of multiplication by the field element c on the Z-module Zu+Zv,
    for u,v field elements; returns rational 2x2 or None if not integral."""
    # solve c*u = a u + b v, c*v = e u + f v over Q
    rows = []
    for w in (u, v):
        cw = fmul(c, w)
        sol = _solve2(u, v, cw)
        if sol is None:
            return None
        rows.append(sol)
    return tuple(tuple(x for x in r) for r in rows)


def _solve2(u, v, w):
    """w = a u + b v with a,b rational?  (u,v,w in the field)"""
    from lat24 import _solve
    mat = [[u[k], v[k]] for k in range(DEG)]
    rhs = [w[k] for k in range(DEG)]
    return _solve(mat, rhs)


def submodules(Mc, theta_mat):
    """all lattices L with  Mc Z^2 <= L <= Z^2  stable under theta_mat."""
    det = abs(Mc[0][0] * Mc[1][1] - Mc[0][1] * Mc[1][0])
    det = int(det)
    out = []
    if det == 0:
        return out
    for a in range(1, det + 1):
        if det % a:
            continue
        for d in range(1, det + 1):
            if a * d > det or det % (a * d):
                continue
            for b in range(0, d):
                L = ((Fr(a), Fr(b)), (Fr(0), Fr(d)))
                # want Mc Z^2 <= L <= Z^2 ; L <= Z^2 automatic (integral)
                McL = ((Fr(Mc[0][0]), Fr(Mc[0][1])), (Fr(Mc[1][0]), Fr(Mc[1][1])))
                if not sub_of(McL, L):
                    continue
                if theta_mat is not None:
                    Lt = tuple(tuple(row[0] * theta_mat[0][k] + row[1] * theta_mat[1][k]
                                     for k in range(2)) for row in L)
                    if not sub_of(Lt, L):
                        continue
                out.append(hnf(L))
    # dedupe
    seen, res = set(), []
    for L in out:
        if L not in seen:
            seen.add(L)
            res.append(L)
    return res


# ------------------------------------------------ modules with a modulus tau
DT = 1          # elements are polynomials of degree <= DT in tau


def mk(coeffs, g, v=None):
    """the module element (coeffs[0] + coeffs[1]*v) * g;  v = None means that the
    second coordinate is the transcendental modulus tau."""
    if v is None:
        return tuple(tuple(fscal(coeffs[k], g[j]) if k < len(coeffs) else ZERO
                           for k in range(DT + 1)) for j in range(len(g)))
    c = fadd(fscal(coeffs[0], ONE), fscal(coeffs[1], v))
    return tuple(tuple(fmul(c, g[j]) if k == 0 else ZERO for k in range(DT + 1))
                 for j in range(len(g)))


def elem_apply(M, x):
    n = len(x)
    out = []
    for k in range(DT + 1):
        slice_k = tuple(x[j][k] for j in range(n))
        out.append(mat_apply(M, slice_k))
    return tuple(tuple(out[k][j] for k in range(DT + 1)) for j in range(n))


def elem_scal(c, x):
    return tuple(tuple(fmul(c, a) for a in comp) for comp in x)


def flat(x):
    return [q for comp in x for a in comp for q in a]


def in_module(gens, x):
    """is x an integral combination of gens?"""
    from lat24 import _solve
    cols = [flat(g) for g in gens]
    rows = len(cols[0])
    mat = [[cols[c][r] for c in range(len(cols))] for r in range(rows)]
    sol = _solve(mat, flat(x))
    if sol is None:
        return False
    return all(s.denominator == 1 for s in sol)


def module_gens(deltas, gs, v=None):
    """generators of Gamma = sum_j Delta_j g_j ; Delta_j a rational 2x2 matrix."""
    out = []
    for B, g in zip(deltas, gs):
        for row in B:
            out.append(mk((row[0], row[1]), g, v))
    return out


# ================================================================== the driver
def analyse(name, n, es, mus, order, rows):
    say("")
    say("=" * 78)
    say("%s   (n = %d, s = %d), Table 2 rows: %d" % (name, n, len(es), rows))
    say("=" * 78)
    Rs = [refl(e, mu, n) for e, mu in zip(es, mus)]
    K = group_gen(Rs)
    check(len(K) == order, "|K| = %d (expected %d)" % (len(K), order))
    ring, theta = ring_of_traces(K)
    say("   Z[Tr K] = %s" % ring)

    # the b's and c's along the chain
    cs = []
    for j in range(len(es) - 1):
        b1 = fmul(fsub(ONE, mus[j + 1]), herm(es[j], es[j + 1]))
        b2 = fmul(fsub(ONE, mus[j]), herm(es[j + 1], es[j]))
        cs.append(fmul(b1, b2))
    say("   c_{j,j+1} = " + ", ".join(fstr(c) for c in cs))
    # off-chain entries vanish
    ok = True
    for j in range(len(es)):
        for k in range(len(es)):
            if abs(j - k) > 1 and not fis0(herm(es[j], es[k])):
                ok = False
    check(ok, "the graph is a chain (all non-adjacent <e_j|e_k> vanish)")

    # palindromic?
    pal = (mus == mus[::-1]) and all(feq(cs[j], cs[len(cs) - 1 - j])
                                     for j in range(len(cs)))
    say("   chain palindromic: %s" % pal)

    # the normalized generators g_l of Lambda_l = Delta_l g_l
    gs = [es[0]]
    fac = ONE
    for l in range(1, len(es)):
        fac = fmul(fac, fmul(fsub(ONE, mus[l]), herm(es[l - 1], es[l])))
        gs.append(vscal(fac, es[l]))

    # coordinates: (1, v) with v = tau (formal) if ring = Z, else v = theta
    formal = (ring == "Z")
    if formal:
        Mtheta = None
    else:
        Mtheta = mult_matrix(theta, ONE, theta)

    # enumerate the chains of Delta's
    ID = ((Fr(1), Fr(0)), (Fr(0), Fr(1)))
    chains = [[ID]]
    for j, c in enumerate(cs):
        if formal:
            sol = _solve2(ONE, ONE, c)     # c rational?
            check(sol is not None and sol[1] == 0,
                  "c_%d%d is rational (%s)" % (j + 1, j + 2, fstr(c)))
            Mc = ((Fr(sol[0]), Fr(0)), (Fr(0), Fr(sol[0])))
        else:
            Mc = mult_matrix(c, ONE, theta)
        new = []
        for ch in chains:
            Bl = ch[-1]
            # multiplication by c in the basis of Delta_l
            Bli = inv2(Bl)
            Mrel = mat2(mat2(Bl, Mc), Bli)
            for S in submodules(Mrel, Mtheta):
                # Delta' = c^{-1} (S . Bl)
                Bnext = mat2(mat2(S, Bl), inv2(Mc))
                new.append(ch + [hnf(Bnext)])
        chains = new
    say("   admissible chains (Delta_1,...,Delta_n): %d   [Table 2 has %d rows]"
        % (len(chains), rows))
    check(len(chains) >= rows, "at least as many lattices as rows")
    extra = len(chains) - rows
    say("   ==> additional lattices: %d" % extra)
    check((extra > 0) == pal, "additional lattices <=> palindromic chain")

    # every enumerated lattice is K-invariant (exact, with tau transcendental)
    allinv = True
    vcoord = None if formal else theta
    for ch in chains:
        gens = module_gens(ch, gs, vcoord)
        for R in Rs:
            for x in gens:
                if not in_module(gens, elem_apply(R, x)):
                    allinv = False
    check(allinv, "all %d enumerated lattices are K-invariant" % len(chains))

    return dict(name=name, n=n, es=es, mus=mus, Rs=Rs, K=K, cs=cs, gs=gs,
                chains=chains, ring=ring, theta=theta, pal=pal, rows=rows,
                extra=extra, formal=formal)


def mat2(A, B):
    return tuple(tuple(sum(A[i][k] * B[k][j] for k in range(2)) for j in range(2))
                 for i in range(2))


def inv2(A):
    d = A[0][0] * A[1][1] - A[0][1] * A[1][0]
    return ((A[1][1] / d, -A[0][1] / d), (-A[1][0] / d, A[0][0] / d))


# --------------------------------------------- the reversal Q of a palindrome
def reversal(G):
    """Q with Q e_j = a_j e_{n+1-j}, unitary; check Q R_j Q^{-1} = R_{n+1-j}."""
    es, mus, n = G["es"], G["mus"], G["n"]
    s = len(es)
    if s != n:
        return None
    a = [None] * s
    a[0] = ONE
    for j in range(1, s):
        # <Q e_{j-1} | Q e_j> = a_{j-1} conj(a_j) <e_{s-j} | e_{s-1-j}> = <e_{j-1}|e_j>
        num = herm(es[j - 1], es[j])
        den = fmul(a[j - 1], herm(es[s - j], es[s - 1 - j]))
        a[j] = fconj(fdiv(num, den))
    # build Q from Q e_j = a_j e_{s-1-j}
    Ecols = [[es[j][i] for j in range(n)] for i in range(n)]
    Emat = tuple(tuple(row) for row in Ecols)
    Icols = [[fmul(a[j], es[s - 1 - j][i]) for j in range(n)] for i in range(n)]
    Imat = tuple(tuple(row) for row in Icols)
    Q = mat_mul(Imat, mat_inv(Emat))
    Qi = mat_inv(Q)
    ok = True
    for j in range(s):
        conj = mat_mul(mat_mul(Q, G["Rs"][j]), Qi)
        if not mat_eq(conj, G["Rs"][s - 1 - j]):
            ok = False
    check(ok, "Q R_j Q^{-1} = R_{n+1-j} for all j  (so Q K Q^{-1} = K)")
    # Q is unitary
    unit = all(feq(herm(mat_apply(Q, es[j]), mat_apply(Q, es[k])), herm(es[j], es[k]))
               for j in range(n) for k in range(n))
    check(unit, "Q is unitary")
    # Q is not a scalar times an element of K
    inCK = False
    for g in G["K"]:
        M = mat_mul(Q, mat_inv(g))
        if all(feq(M[i][j], ZERO) for i in range(n) for j in range(n) if i != j) \
                and all(feq(M[0][0], M[i][i]) for i in range(n)):
            inCK = True
    check(not inCK, "Q is not in C^* K")
    return Q


def action_on_data(G, Q):
    """Q g_j = kappa_j g_{n+1-j}; return the normalized ratios rho_j."""
    gs, n = G["gs"], G["n"]
    s = len(gs)
    kappas = []
    ok = True
    for j in range(s):
        img = mat_apply(Q, gs[j])
        tgt = gs[s - 1 - j]
        # kappa = img / tgt on a nonzero coordinate
        k = next(idx for idx in range(n) if not fis0(tgt[idx]))
        kap = fdiv(img[k], tgt[k])
        if not all(feq(img[m], fmul(kap, tgt[m])) for m in range(n)):
            ok = False
        kappas.append(kap)
    check(ok, "Q g_j = kappa_j g_{n+1-j} for all j")
    rho = [fdiv(k, kappas[-1]) for k in kappas]
    say("   kappa_j = " + ", ".join(fstr(k) for k in kappas))
    say("   rho_j = kappa_j/kappa_n = " + ", ".join(fstr(r) for r in rho))
    return rho


def main():
    data = group_data()
    Gs = []
    for (name, n, es, mus, order, rows) in data:
        Gs.append(analyse(name, n, es, mus, order, rows))

    say("")
    say("=" * 78)
    say("SUMMARY of the Case-2 list of Sec. 4.7.6 of [P]")
    say("=" * 78)
    say("%-14s %-10s %-22s %6s %6s %6s %s" %
        ("K", "Z[Tr K]", "c_{j,j+1}", "latt.", "rows", "extra", "palindromic"))
    for G in Gs:
        say("%-14s %-10s %-22s %6d %6d %6d %s" %
            (G["name"], G["ring"],
             ",".join("%.3f" % fnum(c).real if abs(fnum(c).imag) < 1e-9
                      else "%.2f%+.2fi" % (fnum(c).real, fnum(c).imag) for c in G["cs"]),
             len(G["chains"]), G["rows"], G["extra"], G["pal"]))

    say("")
    say("=" * 78)
    say("THE REVERSAL Q, AND THE ACTION ON THE LATTICE DATA")
    say("=" * 78)
    for G in Gs:
        if not G["pal"]:
            continue
        say("")
        say("--- %s" % G["name"])
        Q = reversal(G)
        rho = action_on_data(G, Q)
        # expect rho = (c^{-1},...,c^{-1},1,...,1): check against the chain
        c = G["cs"][(len(G["cs"]) - 1) // 2]      # the middle (non-unit) c
        s = len(G["gs"])
        exp = []
        for j in range(s):
            # rho_j should be the inverse of the product of the c's "crossed"
            exp.append(ONE)
        # explicit check: rho_1 = 1/c_mid  and rho_n = 1
        ok = feq(rho[-1], ONE) and feq(fmul(rho[0], c), ONE)
        check(ok, "rho_n = 1 and rho_1 = 1/c  (c = %s): the data map is "
                  "(Delta_1,..,Delta_n) -> (Delta_n,..,Delta_1) with the "
                  "outer ones divided by c" % fstr(c))

    say("")
    say("=" * 78)
    say("THE MISPRINT IN THE ROW [F_4]^beta_2 OF TABLE 2 OF [P]")
    say("=" * 78)
    G = [g for g in Gs if g["name"].startswith("K_28")][0]
    gs = G["gs"]
    one = ((Fr(1), Fr(0)), (Fr(0), Fr(1)))            # [1,tau]
    half = ((Fr(1), Fr(0)), (Fr(0), Fr(1, 2)))        # [1,tau/2]
    printed = [one, half, one, half]                  # as printed in [P]
    fixed = [one, one, half, half]                    # what the algorithm gives
    for tag, dl in (("as printed  [1,b]e1+[1,b/2]e2+[1,b]sqrt2 e3+[1,b/2]sqrt2 e4", printed),
                    ("corrected   [1,b]e1+[1,b]e2+[1,b/2]sqrt2 e3+[1,b/2]sqrt2 e4", fixed)):
        gens = module_gens(dl, gs)
        inv = all(in_module(gens, elem_apply(R, x)) for R in G["Rs"] for x in gens)
        say("   %s : K-invariant = %s" % (tag, inv))
        check(inv == (dl is fixed), "invariance as expected (%s)" % tag[:11])

    say("")
    say("=" * 78)
    say("checks passed: %d / %d" % (CHECKS[1], CHECKS[0]))
    with open("check_477.out", "w") as f:
        f.write("\n".join(OUT) + "\n")


if __name__ == "__main__":
    main()
