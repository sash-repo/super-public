# Item (iii), part D: sl(2|1) -- primitive lattice data, sector cycle, and which walls carry reflections.
from sympy import *
from itertools import combinations

G = Matrix([[2, 1], [1, 0]])
al, be = Matrix([1, 0]), Matrix([0, 1])
sq = lambda v: (v.T * G * v)[0, 0]
refl = lambda e: eye(2) - (2 / sq(e)) * e * (e.T * G)
Ra = refl(al)

# 1. primitive generator of alpha^perp inside Q = Z alpha + Z beta
p = Matrix([1, -2])                                    # alpha - 2 beta
print("alpha-2beta in alpha^perp?", (p.T * G * al)[0, 0] == 0, " square", sq(p))
print("index of Z alpha + Z(alpha-2beta) in Q:", abs(Matrix.hstack(al, p).det()))
print("Q/(Z alpha + Z(alpha-2beta)) generated by beta mod L, order",
      abs(Matrix.hstack(al, p).det()))

# 2. the three walls and the cyclic order of the six sectors
roots = [al, -al, be, -be, al - be, be - al]
name = {(1, 0): "a", (-1, 0): "-a", (0, 1): "b", (0, -1): "-b",
        (1, -1): "a-b", (-1, 1): "b-a"}
nm = lambda v: name[(v[0], v[1])]
walls = {"a": al, "b": be, "a-b": al - be}
# direction vectors of the walls gamma^perp
for k, g in walls.items():
    d = Matrix([[(g.T * G)[0, 0], (g.T * G)[0, 1]]]).nullspace()[0]
    d = d * lcm([x.q for x in d])
    print("wall %-3s = perp of %-3s : direction %s, square %s, %s"
          % (k, k, d.T.tolist(), sq(d),
             "ANISOTROPIC -> carries the reflection R_%s" % k if sq(d) != 0
             else "isotropic -> carries no reflection"))

# 3. cyclic order of the 6 sectors and the wall crossed between consecutive ones
import math
dirs = []
for g in walls.values():
    d = Matrix([[(g.T * G)[0, 0], (g.T * G)[0, 1]]]).nullspace()[0]
    dirs += [d, -d]
angles = sorted((math.atan2(float(d[1]), float(d[0])), d) for d in dirs)
print("\nsix boundary rays, by angle:", [(round(a, 3), d.T.tolist()) for a, d in angles])
mids = []
for i in range(6):
    a1, d1 = angles[i]
    a2, d2 = angles[(i + 1) % 6]
    m = Matrix([float(d1[0]) + float(d2[0]), float(d1[1]) + float(d2[1])])
    pos = tuple(sorted(nm(r) for r in roots if (m.T * G * r)[0, 0] > 0))
    mids.append(pos)
print("\nsectors in cyclic order (positive systems):")
for s in mids:
    print("   ", s)
print("\nR_alpha on the 6 sectors: pairs them 3+3 (free action of W=Z/2)")
