# Item (iii), part C: Problem H2 -- the generalized root system of sl(2|1).
# V = R^2, basis alpha (even), beta (odd); Gram [[2,1],[1,0]]; roots +-alpha, +-beta, +-(alpha-beta).
from sympy import *
from itertools import combinations

G = Matrix([[2, 1], [1, 0]])
al, be = Matrix([1, 0]), Matrix([0, 1])
roots = [al, -al, be, -be, al - be, be - al]
name = {(1, 0): "a", (-1, 0): "-a", (0, 1): "b", (0, -1): "-b",
        (1, -1): "a-b", (-1, 1): "b-a"}
nm = lambda v: name[(v[0], v[1])]
sq = lambda v: (v.T * G * v)[0, 0]
print("squares:", {nm(r): sq(r) for r in roots})

# 1. The only anisotropic root line is R alpha; alpha^perp is spanned by alpha-2beta, NOT a root.
perp = Matrix([[2, 1]]).nullspace()[0]        # <x alpha + y beta | alpha> = 2x + y
perp = perp * (-2)                             # the primitive vector alpha - 2 beta of Q
print("alpha^perp =", perp.T.tolist(), "= alpha-2beta, square", sq(perp),
      "; is it a root?", any(perp == r or perp == -r for r in roots))

refl = lambda e: eye(2) - (2 / sq(e)) * e * (e.T * G)
Ra = refl(al)
print("R_alpha =", Ra.tolist(), " R_alpha(beta) =", (Ra * be).T.tolist(),
      " -R_alpha = R_(alpha-2beta) ?", -Ra == refl(perp))

# 2. Tran of the reflection group generated by R_alpha on Q = Z alpha + Z beta.
M = Matrix.hstack(*[(eye(2) - Ra) * v for v in (al, be)])
print("(1-R_alpha)Q generated by columns", M.tolist(), "=> Z alpha")
L2 = Matrix.hstack(al, perp)
print("Z alpha + Z(alpha-2beta) has index", abs(L2.det()), "in Q")

# 3. The bases of the generalized root system, and the sectors of the arrangement.
bases = []
for u, v in combinations(roots, 2):
    B = Matrix.hstack(u, v)
    if B.det() == 0:
        continue
    coeffs = [B.solve(r) for r in roots]
    if all(all(c >= 0 for c in c_) or all(c <= 0 for c in c_) for c_ in coeffs):
        bases.append((u, v))
print("number of bases:", len(bases))
print("bases:", [(nm(u), nm(v)) for u, v in bases])

# each base <-> the open sector where its positive roots are positive functionals
def sector(u, v):
    pos = [r for r in roots if all(c >= 0 for c in Matrix.hstack(u, v).solve(r))]
    return tuple(sorted(nm(r) for r in pos))
print("positive systems:", [sector(u, v) for u, v in bases])

# the three walls gamma^perp, gamma in {alpha, beta, alpha-beta}, cut the plane into 6 sectors
walls = [al, be, al - be]
import itertools
signs = set()
for pt in itertools.product([Rational(k, 7) for k in range(-20, 21)], repeat=2):
    v = Matrix(list(pt))
    s = tuple(sign((v.T * G * w)[0, 0]) for w in walls)
    if 0 not in s:
        signs.add(s)
print("open sign-vectors realized by the 3 walls:", len(signs), "=> 6 sectors")

# 4. W = {1, R_alpha} acts freely on the 6 bases
act = lambda B: tuple(sorted(nm(Ra * u) for u in B))
print("R_alpha on bases:", [(tuple(sorted((nm(u), nm(v)))), act((u, v))) for u, v in bases])
