    cases = [(2, 0), (3, 0), (4, 0), (0, 1), (1, 1), (2, 1), (3, 1), (4, 1), (1, 2), (2, 2), (5, 1)]
    for m, n in cases:
        K = 5 if m + 2 * n <= 4 else 4
        r = harmonic_test(m, n, K)
        print(f"osp({m}|{2*n}): sdim={r['sdim_osp']} laplacians={r['laplacians']}")
