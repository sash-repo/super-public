"""checks for the material on harmonic superpolynomials.

1) Harmonic superpolynomials: for osp(m|2n) acting on S(V), sdim V=(m|2n), by
   linear vector fields, find the invariant second-order constant operator
   (the Laplacian) by SOLVING [D_X, Delta]=0, then test whether
   H_k = ker(Delta|S^k) is an irreducible supermodule: the associative
   algebra A generated by the D_X on H_k must be End(H_k) (type M) or have
   dimension d^2/2 (type Q).  Ranks mod p (a lower bound is all a YES needs:
   dim A = d^2 forces A = End).
2) Fock space halves: for o(m), the t-even and t-odd halves of Lambda(xi)
   (with theta quantized for m odd): irreducible? isomorphic? (42).

Monomials in supercommuting x_1..x_N, fixed order; odd exponents <= 1.
"""
import sys, itertools
sys.path.insert(0, __import__("os").path.join(__import__("os").path.dirname(__import__("os").path.abspath(__file__)), "..", "lib"))
from fractions import Fraction
from exactlin import nullspace, rank

P = 1000003


def monos(par, k):
    N = len(par)
    out = []
    def rec(i, left, cur):
        if i == N:
            if left == 0:
                out.append(tuple(cur))
            return
        mx = left if par[i] == 0 else min(1, left)
        for a in range(mx + 1):
            cur.append(a); rec(i + 1, left - a, cur); cur.pop()
    rec(0, k, [])
    return out


def deriv(par, j, m):
    """d/dx_j of monomial m -> (coef, monomial) or None. Left derivative."""
    if m[j] == 0:
        return None
    s = 1
    if par[j] == 1:
        s = (-1) ** sum(m[i] for i in range(j) if par[i] == 1)
    mm = list(m); c = m[j] * s; mm[j] -= 1
    return c, tuple(mm)


def mult(par, i, m):
    """x_i * monomial m."""
    if par[i] == 1 and m[i] == 1:
        return None
    s = 1
    if par[i] == 1:
        s = (-1) ** sum(m[l] for l in range(i) if par[l] == 1)
    mm = list(m); mm[i] += 1
    return s, tuple(mm)


def op_matrix(par, terms, k_in, k_out):
    """terms: list of (coef, word) word = list of ('d',j)/('x',i) applied right-to-left."""
    B_in = monos(par, k_in); B_out = monos(par, k_out)
    idx = {m: r for r, m in enumerate(B_out)}
    M = [[Fraction(0)] * len(B_in) for _ in B_out]
    for col, m in enumerate(B_in):
        for c, word in terms:
            vec = {m: Fraction(c)}
            for kind, a in reversed(word):
                nv = {}
                for mm, cc in vec.items():
                    r = deriv(par, a, mm) if kind == 'd' else mult(par, a, mm)
                    if r is None:
                        continue
                    nv[r[1]] = nv.get(r[1], 0) + cc * r[0]
                vec = nv
            for mm, cc in vec.items():
                if cc:
                    M[idx[mm]][col] += cc
    return M


def osp_matrices(m, n):
    """Even orthosymplectic form on C^{m|2n}: even vars first (m of them, symmetric
    form, hyperbolic pairs + maybe one), odd vars (2n, symplectic)."""
    N = m + 2 * n
    par = [0] * m + [1] * (2 * n)
    G = [[0] * N for _ in range(N)]
    for i in range(m // 2):
        G[2 * i][2 * i + 1] = G[2 * i + 1][2 * i] = 1
    if m % 2:
        G[m - 1][m - 1] = 1
    for i in range(n):
        a, b = m + 2 * i, m + 2 * i + 1
        G[a][b] = 1; G[b][a] = -1
    # X in gl, homogeneous: X^{st} G + G X = 0 in super sense; solve generally:
    # condition B(Xu,v) + (-1)^{p(X)p(u)} B(u,Xv) = 0 on basis vectors e_u,e_v.
    sols = []
    for pX in (0, 1):
        ents = [(i, j) for i in range(N) for j in range(N) if (par[i] + par[j]) % 2 == pX]
        rows = []
        for u in range(N):
            for v in range(N):
                row = [0] * len(ents)
                for t, (i, j) in enumerate(ents):
                    # X e_j = sum_i X_ij e_i
                    if j == u:
                        row[t] += G[i][v]
                    if j == v:
                        row[t] += (-1) ** (pX * par[u]) * G[u][i]
                rows.append(row)
        for vec in nullspace(rows):
            X = [[Fraction(0)] * N for _ in range(N)]
            for t, (i, j) in enumerate(ents):
                X[i][j] = vec[t]
            sols.append((pX, X))
    return par, sols


def DX_terms(X, N):
    # derivation sending x_j -> sum_i X_ij x_i :  sum_{i,j} X_ij x_i d_j
    return [(X[i][j], [('x', i), ('d', j)]) for i in range(N) for j in range(N) if X[i][j]]


def matmul(A, B):
    return [[sum(A[i][t] * B[t][j] for t in range(len(B))) for j in range(len(B[0]))] for i in range(len(A))]


def laplacian(par, sols, K=3):
    N = len(par)
    pairs = [(i, j) for i in range(N) for j in range(i, N) if not (i == j and par[i] == 1)]
    pairs = [pq for pq in pairs if (par[pq[0]] + par[pq[1]]) % 2 == 0]
    rows = []
    for k in range(2, K + 1):
        cand = [op_matrix(par, [(1, [('d', i), ('d', j)])], k, k - 2) for i, j in pairs]
        for pX, X in sols:
            Dk = op_matrix(par, DX_terms(X, N), k, k)
            Dk2 = op_matrix(par, DX_terms(X, N), k - 2, k - 2)
            comms = []
            for C in cand:
                A = matmul(Dk2, C); Bm = matmul(C, Dk)
                comms.append([A[r][c] - Bm[r][c] for r in range(len(A)) for c in range(len(A[0]))])
            for e in range(len(comms[0])):
                rows.append([comms[t][e] for t in range(len(pairs))])
    ns = nullspace(rows)
    return pairs, ns


def closure_dim(gens, d):
    """dim of the associative algebra (with 1) generated by gens (d x d, mod P)."""
    import numpy as np
    gens = [np.array([[int(x) % P for x in row] for row in g], dtype=np.int64) for g in gens]
    basis = [np.eye(d, dtype=np.int64)]
    def rk(mats):
        return rank([list(map(int, mm.flatten())) for mm in mats], P)
    cur = rk(basis)
    frontier = list(basis)
    allm = list(basis)
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                c = (g @ a) % P
                if rk(allm + [c]) > cur:
                    allm.append(c); cur += 1; new.append(c)
                    if cur == d * d:
                        return cur
        frontier = new
    return cur


def harmonic_test(m, n, K):
    par, sols = osp_matrices(m, n)
    N = len(par)
    pairs, ns = laplacian(par, sols, K=min(K, 4))
    res = {'sdim_osp': (sum(1 for p, _ in sols if p == 0), sum(1 for p, _ in sols if p == 1)),
           'laplacians': len(ns)}
    out = []
    for k in range(0, K + 1):
        Bk = monos(par, k)
        if len(ns) == 1 and k >= 2:
            L = [[Fraction(0)] * len(Bk) for _ in monos(par, k - 2)]
            for t, (i, j) in enumerate(pairs):
                if ns[0][t]:
                    C = op_matrix(par, [(1, [('d', i), ('d', j)])], k, k - 2)
                    for r in range(len(C)):
                        for c in range(len(Bk)):
                            L[r][c] += ns[0][t] * C[r][c]
            H = nullspace(L) if L else [[Fraction(int(a == b)) for a in range(len(Bk))] for b in range(len(Bk))]
        else:
            H = [[Fraction(int(a == b)) for a in range(len(Bk))] for b in range(len(Bk))]
        d = len(H)
        if d == 0:
            out.append((k, 0, None)); continue
        # restrict each D_X to H: solve H^T y = D x  (coordinates in basis H)
        Hm = [list(r) for r in H]  # rows = vectors
        gens = []
        for pX, X in sols:
            D = op_matrix(par, DX_terms(X, N), k, k)
            img = []
            for v in Hm:
                w = [sum(D[r][c] * v[c] for c in range(len(v))) for r in range(len(D))]
                img.append(w)
            # coordinates: solve sum_a y_a H_a = w
            from exactlin import solve
            T = [[Hm[a][r] for a in range(d)] for r in range(len(Bk))]
            cols = []
            for w in img:
                y = solve(T, w)
                assert y is not None, "H_k not invariant"
                cols.append(y)
            gens.append([[cols[c][r] for c in range(d)] for r in range(d)])
        A = closure_dim(gens, d)
        out.append((k, d, A))
    res['H'] = out
    return res


